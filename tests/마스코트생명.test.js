/* 마스코트 생명 회귀 — 별눈 게이트·혼잣말 규격 (`lib/마스코트생명.js`).
 *
 * ■ 무엇을 지키나
 *   ① **별눈 닫힌 목록** — 목록 밖 사건(특히 매일 일어날 수 있는 것 전부)에서 별눈이 안 뜬다.
 *      그림 정본 「별눈 발동 규격」의 ⛔ 줄을 그대로 픽스처로 쓴다 — 「하나라도 올리면
 *      그날로 별눈은 그냥 과한 표정이 된다」.
 *   ② **하루 1회 상한** — 첫 경험이 겹치는 첫날에도 한 번만.
 *   ③ **목록 글자째 못박기** — 늘리려면 이 diff 가 리뷰에 보여야 한다(꼬리 `종류들` 과 같은 축 ·
 *      조용한 확장 차단이 목적이지 개정 금지가 아니다).
 *   ④ **혼잣말 규격** — 전 문구가 꼬리와 **같은** 금지 패턴(tests/lib/금지패턴.js) 0히트 ·
 *      1~4어절(생명감 §3). 탐지력(가짜가 걸리는지)은 tests/꼬리.test.js 가 지는데,
 *      여기서도 한 번 문다 — 공유 모듈이 비거나 무뎌진 채 「재사용」만 남는 것이 새는 방향이다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { 표정컷, 별눈허용사건, 별눈판정, 혼잣말 } = require('../lib/마스코트생명.js');
const { 금지패턴 } = require('./lib/금지패턴.js');

test('별눈 허용 목록을 글자째 못박는다 — 늘리는 diff 는 리뷰에 보여야 한다', () => {
  assert.deepEqual(
    별눈허용사건,
    ['진화', '생애첫제출', '생애첫녹음', '생애첫무오류답장', '시즌완주'],
    '닫힌 목록이 바뀌었다 — 「한 학생에게 몇 번 일어날 수 있는가」로 세운 목록이다(README 별눈 발동 규격)',
  );
});

test('별눈 — 목록 밖 사건에서 절대 안 뜬다 (그림 정본 ⛔ 줄 그대로)', () => {
  const 매일사건들 = ['앱켬', '제출완료', '무오류답장첫열람', '재발화', '그자리재도전', '캐릭터탭', '복귀'];
  for (const 사건 of 매일사건들) {
    const 답 = 별눈판정(사건, '2026-08-13', null);
    assert.equal(답.허용, false, `매일 일어날 수 있는 사건 「${사건}」에 별눈이 떴다 — 그날로 별눈은 과한 표정이 된다`);
    assert.equal(답.사유, '목록밖');
  }
  assert.equal(별눈판정('', '2026-08-13', null).허용, false);
  assert.equal(별눈판정(undefined, '2026-08-13', null).허용, false);
});

test('별눈 — 허용 다섯 사건은 게이트를 지난다 (오늘 처음이면)', () => {
  for (const 사건 of 별눈허용사건) {
    assert.equal(별눈판정(사건, '2026-08-13', null).허용, true, `허용 사건 「${사건}」이 막혔다`);
    assert.equal(별눈판정(사건, '2026-08-13', '2026-08-12').허용, true, '어제 떴다고 오늘 막히면 상한이 아니라 봉인이다');
  }
});

test('별눈 — 하루 1회 상한: 첫 경험이 겹치는 첫날에도 한 번만', () => {
  const 답 = 별눈판정('생애첫녹음', '2026-08-13', '2026-08-13');
  assert.equal(답.허용, false, '같은 날 두 번째 별눈이 떴다 — 첫날(첫 제출=첫 녹음)에 두 번 뜨는 자리다');
  assert.equal(답.사유, '하루1회');
});

test('혼잣말 — 전 문구가 금지 패턴(꼬리와 같은 정규식) 0히트 · 1~4어절', () => {
  const 전부 = Object.values(혼잣말).flat();
  assert.ok(전부.length >= 8, `혼잣말 풀을 못 읽었다(분모 ${전부.length}) — 통과가 아니라 미실행이다`);
  for (const 글 of 전부) {
    for (const p of 금지패턴) {
      assert.ok(!p.정규식.test(글), `혼잣말에 ${p.이름} 이 들어갔다: ${글}`);
    }
    const 어절 = 글.trim().split(/\s+/).length;
    assert.ok(어절 >= 1 && 어절 <= 4, `혼잣말이 초급 길이(1~4어절)를 벗어났다(${어절}어절): ${글}`);
  }
});

test('혼잣말 — 오류 순간의 풀이 아예 없다 (기죽는 반응 금지 · 생명감 §1-3)', () => {
  /* 「오류남은답장」 사건은 몸짓(카드 쪽 기울임)뿐이다 — 풀 키가 생기는 순간 누군가 채운다. */
  assert.ok(!('오류남은답장' in 혼잣말), '오류 순간의 혼잣말 칸이 생겼다 — 실패음의 재발명이 시작되는 자리다');
});

test('탐지력 — 공유 금지패턴이 실제로 문다 (재사용만 남고 검사가 빈 것을 잡는다)', () => {
  const 가짜 = ['잘했어요! 최고야', '오늘 세 번 말했어요', '친구보다 잘해요', '점수가 올랐어요'];
  for (const 글 of 가짜) {
    assert.ok(금지패턴.some((p) => p.정규식.test(글)), `이 문구를 못 잡는다 — 공유 모듈이 무뎌졌다: ${글}`);
  }
});

test('표정컷 — 별눈이 표정 어휘에 있고(자산 준비) 기본·기쁨·깜빡임 프레임이 산다', () => {
  /* 컷 «파일» 검사는 tests/마스코트자산.test.js 몫 — 여기는 어휘와 게이트의 아귀만 문다. */
  assert.equal(표정컷.기본, '본체');
  assert.equal(표정컷.기쁨, '본채깜찍', '보상 표정이 바뀌었다 — 「본채」는 유호 원본 표기다(README)');
  assert.equal(표정컷.별눈, '본체별눈');
  assert.equal(표정컷.잔잔감음, '본체눈감음2', '깜빡임 프레임이 사라졌다 — 깜빡임은 이 컷 하나로 산다');
});
