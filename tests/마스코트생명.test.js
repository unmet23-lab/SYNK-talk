test('새 자리 넷 ① — 시각·월 게이트가 순수 함수다 (주입한 시계만 본다)', () => {
  const 때 = (시, 달 = 4) => new Date(2026, 달 - 1, 15, 시);
  /* 밤 = 22~06 (08-13 판 승계 — 졸림 판정과 같은 자여야 한다) */
  for (const h of [22, 23, 0, 3, 5]) assert.equal(밤인가(때(h)), true, `${h}시가 밤이 아니다`);
  for (const h of [6, 10, 14, 21]) assert.equal(밤인가(때(h)), false, `${h}시가 밤이다`);
  /* 아침 = 06~10 · 밤과 겹치지 않는다(겹치면 같은 시각에 자리가 둘이 된다) */
  for (const h of [6, 7, 9]) assert.equal(아침인가(때(h)), true, `${h}시가 아침이 아니다`);
  for (const h of [5, 10, 12, 22]) assert.equal(아침인가(때(h)), false, `${h}시가 아침이다`);
  for (let h = 0; h < 24; h++) {
    assert.ok(!(밤인가(때(h)) && 아침인가(때(h))), `${h}시가 밤이면서 아침이다`);
  }
  /* 계절 = 월(12~2 겨울 · 6~8 여름) · 겹치지 않는다 */
  for (const m of [12, 1, 2]) assert.equal(겨울인가(때(13, m)), true, `${m}월이 겨울이 아니다`);
  for (const m of [3, 6, 9, 11]) assert.equal(겨울인가(때(13, m)), false, `${m}월이 겨울이다`);
  for (const m of [6, 7, 8]) assert.equal(여름인가(때(13, m)), true, `${m}월이 여름이 아니다`);
  for (const m of [5, 9, 12, 2]) assert.equal(여름인가(때(13, m)), false, `${m}월이 여름이다`);
  for (let m = 1; m <= 12; m++) {
    assert.ok(!(겨울인가(때(13, m)) && 여름인가(때(13, m))), `${m}월이 겨울이면서 여름이다`);
  }
});

test('새 자리 넷 ② — 자리고르기: 시각이 계절을 이기고, 나머지 달은 idle 이다', () => {
  const 때 = (시, 달) => new Date(2026, 달 - 1, 15, 시);
  assert.equal(자리고르기(때(23, 1)), '밤', '겨울 밤인데 계절이 이겼다 — 창이 좁은 쪽이 더 «지금»이다');
  assert.equal(자리고르기(때(2, 7)), '밤');
  assert.equal(자리고르기(때(7, 1)), '아침', '겨울 아침인데 계절이 이겼다');
  assert.equal(자리고르기(때(8, 7)), '아침');
  assert.equal(자리고르기(때(14, 1)), '겨울');
  assert.equal(자리고르기(때(20, 12)), '겨울');
  assert.equal(자리고르기(때(14, 7)), '여름');
  assert.equal(자리고르기(때(14, 4)), 'idle', '봄 낮은 idle 이다 — 봄·가을 풀은 정본에 없다');
  assert.equal(자리고르기(때(15, 10)), 'idle');
  /* 어느 시각·달을 넣어도 «활성 자리 안»의 값만 나온다 — 못 고르는 자리를 뱉으면 그날 무언이 된다. */
  for (let m = 1; m <= 12; m++) {
    for (let h = 0; h < 24; h++) {
      const z = 자리고르기(때(h, m));
      assert.ok(혼잣말자리들.includes(z), `${m}월 ${h}시 → 「${z}」 는 활성 자리 밖이다`);
    }
  }
});

test('새 자리 넷 ③ — 평상혼잣말: 해당하면 그 자리 풀, 비었으면 idle 풀', () => {
  const 때 = (시, 달) => new Date(2026, 달 - 1, 15, 시);
  for (const c of 혼잣말캐릭터들) {
    const 겨울풀 = 평상혼잣말(c, 때(14, 1));
    assert.deepEqual(겨울풀, 혼잣말(c, '겨울'), `${c}: 겨울 낮에 겨울 풀이 안 나온다`);
    assert.deepEqual(평상혼잣말(c, 때(8, 4)), 혼잣말(c, '아침'), `${c}: 봄 아침에 아침 풀이 안 나온다`);
    assert.deepEqual(평상혼잣말(c, 때(14, 4)), 혼잣말(c, 'idle'), `${c}: 봄 낮에 idle 풀이 안 나온다`);
    assert.ok(겨울풀.length >= 1);
  }
  /* 폴백이 «실제로» 돈다 — 없는 캐릭터는 모든 풀이 비므로 idle(역시 빈 배열)로 떨어지고,
     화면은 빈 풀에 아무 말도 안 한다(말하기() 첫 줄이 `!풀.length` 로 접는다). */
  assert.deepEqual(평상혼잣말('없는가이드', 때(14, 1)), []);
});

