test('연출 대본 — 걸음 규격·문구 금지 패턴·보상/게이트 표정 금지 (유호 확정 08-23 「그 자리 연기」)', () => {
  const 몸짓어휘 = ['점프', '큰점프', '기울임', '끄덕', '다가옴', '물러남', '사라짐'];
  assert.ok(Object.keys(연출대본).length >= 2, '연출 대본을 못 읽었다 — 통과가 아니라 미실행이다');
  /* 세 캐릭터 «산출물 전부»를 돈다(D4-9) — 말 슬롯만 갈리고 골격은 공유라, 어느 캐릭터판도
     같은 규격(표정·몸짓 어휘·박자·금지 패턴·어절)을 지나야 한다. 몽글판 = 기존 연출대본 그대로. */
  for (const 캐릭터 of ['몽글', '까몽', '마린']) {
    for (const 이름 of Object.keys(연출대본)) {
      const 대본 = 연출대본가져오기(이름, 캐릭터);
      assert.ok(Array.isArray(대본) && 대본.length >= 2, `${캐릭터}판 대본 「${이름}」이 비었다 — 연기가 아니라 정지 화면이다`);
      for (const 걸음 of 대본) {
        assert.ok(Number.isFinite(걸음.지속) && 걸음.지속 > 0, `${캐릭터}판 「${이름}」에 지속 없는 걸음 — 시퀀서가 0ms 로 겹쳐 재생한다`);
        if (걸음.표정) {
          /* 대본 어휘의 자는 몽글 벌이다 — 연출은 어느 캐릭터로도 돌 수 있어야 하고,
             몽글이 최소 공통 어휘다(까몽 벌은 몽글의 상위집합 + 전용 컷). */
          assert.ok(걸음.표정 in 표정컷.몽글, `${캐릭터}판 「${이름}」의 표정 「${걸음.표정}」이 어휘 밖이다 — 조용히 기본 컷으로 내려간다`);
          /* 기쁨은 보상 순간 전용(README 상시 금지) — 보상 대본(완료축하)만 예외다. 목록이 아니라
           * 이름 하나로 못박는다: 「특별한 대본」이 슬쩍 늘면 기쁨이 그냥 과한 표정이 된다(별눈 규율). */
          assert.ok(!(걸음.표정 === '기쁨' && 이름 !== '완료축하'), `${캐릭터}판 「${이름}」에 기쁨 — 보상 순간 전용이다(보상 대본 완료축하에만 허용)`);
          assert.ok(걸음.표정 !== '별눈', `${캐릭터}판 「${이름}」에 별눈 — 생애급 게이트(별눈판정) 밖 통로다`);
        }
        if (걸음.몸짓) assert.ok(몸짓어휘.includes(걸음.몸짓), `${캐릭터}판 「${이름}」의 몸짓 「${걸음.몸짓}」이 어휘 밖이다 — 시퀀서가 조용히 무시한다`);
        if (걸음.말 && 걸음.말 !== '@질문') {
          for (const p of 금지패턴) {
            assert.ok(!p.정규식.test(걸음.말), `${캐릭터}판 「${이름}」의 말에 ${p.이름} 이 들어갔다: ${걸음.말}`);
          }
          const 어절 = 걸음.말.trim().split(/\s+/).length;
          assert.ok(어절 >= 1 && 어절 <= 6, `대본 말이 짧은 안내 길이(1~6어절)를 벗어났다(${어절}어절): ${걸음.말}`);
        }
      }
    }
  }
  /* 몽글(기본값)판은 기존 연출대본 «그 객체»다 — 소비자·회귀 무영향의 기계 봉인. */
  for (const 이름 of Object.keys(연출대본)) {
    assert.equal(연출대본가져오기(이름), 연출대본[이름], `몽글판 「${이름}」이 딴 객체다 — 기존 소비자가 갈린다`);
  }
  /* 슬롯이 사라지면 몽글이 «내 숙제의 그 질문»을 못 물어본다 — 이 대본의 존재 이유가 빈다. */
  assert.ok(연출대본.답하기질문.some((걸음) => 걸음.말 === '@질문'), '답하기질문 대본에서 @질문 슬롯이 사라졌다');
});

test('연출 대본 — 캐릭터 지문 교차: 「이 몸」은 까몽판에만 산다 (말 슬롯이 실제로 갈렸다 · D4-9)', () => {
  const 말모음 = (캐릭터) => 연출대본가져오기('말하기인트로', 캐릭터).map((걸음) => 걸음.말 || '').join(' ');
  assert.match(말모음('까몽'), /이 몸/, '까몽 인트로에 까몽 지문(「이 몸」)이 없다 — 말 슬롯 치환이 안 돌았다');
  assert.doesNotMatch(말모음('몽글'), /이 몸/, '몽글 인트로에 까몽 말이 샜다');
  assert.doesNotMatch(말모음('마린'), /이 몸/, '마린 인트로에 까몽 말이 샜다');
  /* 마린 결(브리핑 · 군더더기 0)의 지문 하나 — 말이 몽글판 그대로면 여기서 빨개진다. */
  assert.match(말모음('마린'), /청취 개시\./, '마린 인트로가 브리핑 결이 아니다 — 몽글 말이 그대로 나온다');
  /* 골격 공유의 봉인 — 캐릭터판이 몸짓·박자를 바꾸면 회귀 어휘가 캐릭터 수만큼 갈라진다. */
  const 몽글판 = 연출대본가져오기('말하기인트로', '몽글');
  for (const 캐릭터 of ['까몽', '마린']) {
    const 판 = 연출대본가져오기('말하기인트로', 캐릭터);
    assert.equal(판.length, 몽글판.length, `${캐릭터}판 걸음 수가 다르다 — 갈린 것은 말뿐이어야 한다`);
    판.forEach((걸음, i) => {
      assert.equal(걸음.몸짓, 몽글판[i].몸짓, `${캐릭터}판 ${i}걸음의 몸짓이 갈렸다`);
      assert.equal(걸음.지속, 몽글판[i].지속, `${캐릭터}판 ${i}걸음의 박자가 갈렸다`);
      assert.equal(걸음.표정, 몽글판[i].표정, `${캐릭터}판 ${i}걸음의 표정이 갈렸다`);
    });
  }
  /* 메모이즈 봉인 — 매 호출 새 배열이면 화면이 연출 prop 변경으로 읽어 연기가 처음부터 다시 돈다. */
  assert.equal(연출대본가져오기('말하기인트로', '까몽'), 연출대본가져오기('말하기인트로', '까몽'),
    '캐릭터판이 메모이즈되지 않는다 — 렌더마다 새 대본 객체가 선다');
});

test('표정컷 — 캐릭터마다 «제 정본 접두»의 컷이고 기본·깜빡임 프레임이 산다 · 옛 렌더 복귀 차단', () => {
  /* 컷 «파일» 검사는 tests/마스코트자산.test.js 몫 — 여기는 어휘와 게이트의 아귀만 문다.
   * 🔴 접두 검사가 이 시험의 존재 이유다(08-23): 옛 08-13 렌더(본체·본채깜찍·본체별눈…)가
   *   정본 확정 뒤에도 talk 에 8일을 살았다 — 「대개편이 형제 저장소를 안 봤다」의 기계 봉인.
   *   캐릭터가 늘어도 자는 같다: 몽글 = 재염색_(펠트코랄_0815) · 까몽 = 까몽_(친구공방_0825). */
  const 접두 = { 몽글: /^재염색_/, 까몽: /^까몽_/ };
  assert.deepEqual(Object.keys(표정컷), ['몽글', '까몽'],
    '컷 어휘의 캐릭터 칸이 바뀌었다 — 마린 칸은 그림 외주가 오기 전엔 없어야 한다(빈 칸을 비슷한 컷으로 안 메운다)');
  for (const [캐릭터, 벌] of Object.entries(표정컷)) {
    for (const [표정, 컷] of Object.entries(벌)) {
      assert.match(컷, 접두[캐릭터], `${캐릭터}·「${표정}」의 컷 「${컷}」이 그 캐릭터 정본 밖이다 — 옛 렌더 재반입의 무늬다`);
    }
    assert.ok(!('별눈' in 벌), `${캐릭터}: 별눈이 컷 어휘에 돌아왔다 — 펠트 별눈판·발동 신호가 둘 다 선 게 아니면 옛 렌더의 재반입이다`);
  }
  assert.equal(표정컷.몽글.기본, '재염색_본체');
  assert.equal(표정컷.몽글.잔잔감음, '재염색_눈감음', '깜빡임 프레임이 사라졌다 — 깜빡임은 이 컷 하나로 산다');
  assert.equal(표정컷.몽글.기쁨, '재염색_눈웃음', '기쁨의 임시 접힘(펠트 깜찍판 미존재)이 바뀌었다 — 깜찍판이 섰다면 이 단언을 그 컷으로 갱신하라');
  assert.equal(표정컷.까몽.기본, '까몽_본체');
  assert.equal(표정컷.까몽.잔잔감음, '까몽_눈감음', '까몽 깜빡임 프레임이 사라졌다');
  assert.equal(표정컷.까몽.기쁨, '까몽_눈웃음', '까몽 기쁨의 임시 접힘(깜찍판 미존재)이 바뀌었다 — 깜찍판이 섰다면 이 단언을 그 컷으로 갱신하라');
});
