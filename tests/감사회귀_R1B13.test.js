test('D4-6 — 탭반응고르기: 몽글 반반 현행 · 까몽/마린 연타 3 부터 민망 · 산출이 그 캐릭터 컷 어휘 안', () => {
  /* 몽글 — 09-05 저녁에 «열었다»(유호 「열어줘」). 표정이 5 → 9 로 서면서 08-25 판(반반
     기쁨·눈웃음)을 지키던 까닭이 사라졌다. 그 규율은 «까몽 반입이 주인공을 흔들지 마라»는
     뜻이었지 «영원히 얇게 두라»가 아니다. 이제 셋으로 갈리고 연타 3회부터 들킴이다.
     🔑 경계는 1/3·2/3 이다 — 0.3 은 여전히 기쁨이고, 0.7 이 눈웃음에서 윙크로 옮겨 갔다. */
  assert.deepEqual(탭반응고르기('몽글', 0.3, 1), { 첫: '놀람', 뒤: '기쁨' });
  assert.deepEqual(탭반응고르기('몽글', 0.5, 1), { 첫: '놀람', 뒤: '눈웃음' });
  assert.deepEqual(탭반응고르기('몽글', 0.9, 1), { 첫: '놀람', 뒤: '윙크' });
  assert.deepEqual(탭반응고르기('몽글', 0.3, 3), { 첫: '놀람', 뒤: '민망' });
  assert.deepEqual(탭반응고르기('몽글', 0.9, 7), { 첫: '놀람', 뒤: '민망' });
  /* 까몽 — 겁(놀람) 뒤 허세 수습(으쓱), 연타 3부터 들킴(민망). */
  assert.deepEqual(탭반응고르기('까몽', 0.1, 1), { 첫: '놀람', 뒤: '으쓱' });
  assert.deepEqual(탭반응고르기('까몽', 0.9, 2), { 첫: '놀람', 뒤: '으쓱' });
  assert.deepEqual(탭반응고르기('까몽', 0.1, 3), { 첫: '놀람', 뒤: '민망' });
  assert.deepEqual(탭반응고르기('까몽', 0.9, 7), { 첫: '놀람', 뒤: '민망' });
  /* 마린 — 09-05 에 제 표가 섰다(그림이 왔다 · 그전엔 몽글 표로 폴백했다).
     브리핑체라 놀란 뒤 «임무를 받는» 얼굴(집중 = 가늘어진 렌즈)로 돌아가고,
     연타 3부터 그 태세가 무너진다(민망 — 꽃·칭찬에 약하다는 설정). */
  assert.deepEqual(탭반응고르기('마린', 0.3, 1), { 첫: '놀람', 뒤: '집중' });
  assert.deepEqual(탭반응고르기('마린', 0.9, 2), { 첫: '놀람', 뒤: '집중' });
  assert.deepEqual(탭반응고르기('마린', 0.1, 3), { 첫: '놀람', 뒤: '민망' });
  assert.notDeepEqual(탭반응고르기('마린', 0.3, 1), 탭반응고르기('몽글', 0.3, 1),
    '마린이 다시 몽글 표로 폴백한다 — 제 표가 사라졌다');
  /* 어휘 정합 — 산출 표정이 그 캐릭터(폴백이면 몽글) 표정컷 어휘 안이다. 밖이면 화면이
     조용히 기본 컷으로 내려간다(옛 몽글 사고의 모양 — 멀쩡해 보이는 화면). */
  for (const 캐릭터 of 혼잣말캐릭터들) {
    const 벌 = 표정컷[캐릭터] || 표정컷.몽글;
    for (const 고르기 of [0, 0.49, 0.5, 0.99]) {
      for (const 연타수 of [1, 2, 3, 9]) {
        const { 첫, 뒤 } = 탭반응고르기(캐릭터, 고르기, 연타수);
        assert.ok(첫 in 벌, `${캐릭터}(연타 ${연타수}) 첫 박자 「${첫}」이 컷 어휘 밖이다`);
        assert.ok(뒤 in 벌, `${캐릭터}(연타 ${연타수}) 뒤 박자 「${뒤}」가 컷 어휘 밖이다`);
      }
    }
  }
  /* 배선 — 화면이 고정 표(놀람→반반)를 직접 짓지 않고 lib 판정을 쓴다. */
  const 코드 = 코드만(마스코트소스);
  assert.match(코드, /탭반응고르기\(캐릭터, Math\.random\(\), 연타\.current\.수\)/,
    '탭이 캐릭터 반응 판정(lib)을 안 지난다 — 전 캐릭터가 몽글처럼 놀란다');
});

test('D4-3 — 까몽 컷: 표정컷 까몽 벌 8컷 전부 까몽_ 접두 실WebP 다', () => {
  const 컷들 = [...new Set(Object.values(표정컷.까몽))];
  assert.equal(컷들.length, 8, `까몽 컷 분모가 8 이 아니다(${컷들.length}) — 반입이 어긋났다`);
  for (const 컷 of 컷들) {
    assert.match(컷, /^까몽_/, `까몽 벌에 다른 정본의 컷 「${컷}」이 섞였다`);
    const 버퍼 = fs.readFileSync(path.join(ROOT, 'assets', '마스코트', `${컷}.webp`));
    assert.ok(버퍼.toString('latin1', 0, 4) === 'RIFF' && 버퍼.toString('latin1', 8, 12) === 'WEBP',
      `${컷}.webp 가 WebP 가 아니다 — 개명·플레이스홀더가 반입됐다`);
    assert.ok(버퍼.length > 8 * 1024, `${컷}.webp 가 ${버퍼.length}바이트뿐이다 — 실컷(수십 KB)이 아니다`);
  }
});
