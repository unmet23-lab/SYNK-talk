/* 팩이 낸 글자는 전부 정본이다(지문 속 「4개월」·「6만 원」…) — 숫자 검사 전에 걷어 낸다.
 * 🔑 문장틀은 화면에서 `{빈칸}` 자리가 밑줄로 바뀌어 원문 그대로는 렌더에 없다 — 조각(앞·뒤)도
 *   함께 담아야 렌더에 남은 정본 숫자(「4개월」)가 걷힌다(하네스가 공백을 홑칸으로 접는 것도 승계). */
function 팩글자들(값, 모음 = []) {
  if (typeof 값 === 'string') {
    for (const 조각 of [값, ...값.split('{빈칸}')]) {
      const 다듬 = 조각.replace(/\s+/g, ' ').trim();
      if (다듬.length >= 2) 모음.push(다듬);
    }
    return 모음;
  }
  if (값 && typeof 값 === 'object') for (const 속 of Object.values(값)) 팩글자들(속, 모음);
  return 모음;
}

