'use strict';
/**
 * 테마 «면» 회귀 — 카드 면을 바꿀 때 조용히 죽는 글자 층을 잡는다.
 *
 * 발단(유호님 확정 2026-08-14 「면 2단 보강」 · 2026-08-20 「양모 밤」 조항 ⓚ 로 이관):
 * 이 트랙은 **같은 실패에 두 번 걸렸다.**
 *   ① 옛 무채·네이비 판: 바탕과 카드가 ΔL* **1.48** 뿐이라 카드가 사실상 안 떠 있었다.
 *   ② 양모 밤 첫 설계안: ΔL* **8.6**. 대비비로는 「1.21 통과」로 보였는데, 눈금을 ΔL* 로
 *      바꾸고서야 그것이 08-20 에 기각된 옛 카드 Graphite 2(**8.26**)와 같은 값임이 드러났다.
 *   확정 값은 Ink Deep → Ink = **12.77** 이다.
 *
 *   🔴 **더 띄우려고 Deep Wool `#575046`(양모 회색 4)로 올리면 두 색이 그 면에서 죽는다** —
 *      `잉크_보조`(Stone) 4.36 · `신호`(Coral) 2.71. 둘 다 본문 기준 4.5 미달인데,
 *      **화면은 멀쩡해 보인다.** 「카드를 더 띄우자」는 다음 사람이 집을 가장 자연스러운 수라,
 *      프로즈로만 적어 두면 안 막힌다.
 *
 * 그래서 검사 대상은 「어떤 hex 를 썼나」가 아니라 **「그 면 위에서 글자가 사나」**다.
 *
 * ■ 이 검사의 대가(틀릴 때의 모습):
 *   맞는 얼굴로 틀릴 자리는 «파싱»이다 — `테마.js` 가 색 정의 문법을 바꾸면(상수 참조·객체 전개)
 *   칸을 못 읽는다. 그래서 **못 읽으면 던진다**(빠진 칸 이름을 대고 죽는다) — 그 칸만 빼고
 *   초록을 내지 않는다. 그리고 탐지력은 아래 «픽스처» 절이 못박는다: 실제 값이 통과하는 것만
 *   검사하면 판정식이 망가져도 초록이라, **알려진 나쁜 면(Deep Wool)을 실제로 잡는지**를 함께 건다.
 * ■ 닫을 것: 없다 — 순수 계산이라 repo 밖 환경(시간대·홈·자격증명·네트워크)에 안 기댄다.
 *   ⚠ WCAG 대비 «수식»은 appsscript `tools/모드대비계측.js` 와 겹친다. 값(정본)이 아니라 공식이라
 *     갈라질 판정이 없고, 저장소가 둘이라 공유 통로가 없다(합치려면 패키지를 새로 내야 한다).
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { 코드만, 파일소스 } = require('./lib/소스검사.js');
const { 킷색 } = require('../tools/테마색.js');

/* ── 색 계산 (WCAG 2.x 상대휘도 · CIE L*) ── */
const srgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const 선형 = (c) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
const 광도 = (h) => { const v = srgb(h).map(선형); return 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]; };
const 대비 = (a, b) => {
  const x = 광도(a), y = 광도(b);
  return Math.round(((Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)) * 100) / 100;
};
const Lstar = (h) => { const y = 광도(h); return y > 0.008856 ? 116 * Math.cbrt(y) - 16 : 903.3 * y; };
const 합성 = (fg, bg, a) => {
  const F = srgb(fg), B = srgb(bg);
  return '#' + F.map((c, i) => Math.round((c * a + B[i] * (1 - a)) * 255).toString(16).padStart(2, '0'))
    .join('').toUpperCase();
};

/** rgba(…) / #RRGGBB → { hex, 알파 } */
function 색풀기(v) {
  const m = String(v).match(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)/);
  if (m) {
    const hex = '#' + [m[1], m[2], m[3]].map((n) => Number(n).toString(16).padStart(2, '0')).join('').toUpperCase();
    return { hex, 알파: m[4] === undefined ? 1 : Number(m[4]) };
  }
  return { hex: String(v).toUpperCase(), 알파: 1 };
}

/** 🔴 못 읽으면 «던진다» — 그 칸만 빼고 초록을 내지 않는다(머리말 「대가」). 파서 = tools/테마색.js 한 벌. */
function 테마읽기() {
  const 값 = 킷색();
  const 필수 = ['바탕', '바탕띄움', '잉크', '신호', '잉크_태그', '잉크_서브', '잉크_메타', '잉크_보조'];
  const 빠짐 = 필수.filter((k) => !값[k]);
  assert.equal(빠짐.length, 0, `테마.js 에서 못 읽은 칸: ${빠짐.join(', ')}`);
  return 값;
}

/**
 * 한 면 위에서 «글자가 사나» — 이 파일의 판정식 하나.
 * 알파 층은 그 면에 합성해서 잰다(rgba 로 적힌 글자의 실제 대비는 합성색으로만 나온다).
 * 🚫 `잉크_희미` 는 안 센다 — 테마가 「선·비활성 도형 전용(글자 금지)」로 못박은 칸이다.
 * 🚫 `눌림`(Coral 3)도 안 센다 — 테마가 「면 전용 · 글자 금지」로 못박은 칸이다.
 */
function 죽은층(면, 값, 기준 = 4.5) {
  const 잉크 = 색풀기(값.잉크).hex;
  const 검사 = [
    ['잉크', 잉크, 1],
    ['잉크_태그', 잉크, 색풀기(값.잉크_태그).알파],
    ['잉크_서브', 잉크, 색풀기(값.잉크_서브).알파],
    ['잉크_메타', 잉크, 색풀기(값.잉크_메타).알파],
    ['잉크_보조', 색풀기(값.잉크_보조).hex, 1],
    ['신호', 색풀기(값.신호).hex, 1],
  ];
  const 죽음 = [];
  for (const [이름, 색, a] of 검사) {
    const c = 대비(합성(색, 면, a), 면);
    if (c < 기준) 죽음.push(`${이름} ${c}`);
  }
  return 죽음;
}

test('카드 면 위에서 글자 층이 «전부» 산다 — 신호(Coral)와 3번째 층(Stone)까지', () => {
  const 값 = 테마읽기();
  const 카드 = 색풀기(값.바탕띄움).hex;
  const 죽음 = 죽은층(카드, 값);
  assert.deepEqual(죽음, [], `카드 면 ${카드} 위에서 죽는 층: ${죽음.join(' · ')}`);
});

test('바탕 면 위에서도 글자 층이 전부 산다', () => {
  const 값 = 테마읽기();
  const 바탕 = 색풀기(값.바탕).hex;
  const 죽음 = 죽은층(바탕, 값);
  assert.deepEqual(죽음, [], `바탕 면 ${바탕} 위에서 죽는 층: ${죽음.join(' · ')}`);
});

/**
 * 🔑 문턱이 3.0 이 아니라 **10.0** 인 이유 — 「양모 밤」이 08-20 에 실측으로 세운 기각선이 8.3 이다.
 *   옛 문턱 3.0 은 옛 실패(1.48)만 막았고, 이 트랙이 실제로 두 번째로 걸린 값(8.6)은 **통과시킨다.**
 *   문턱의 근거는 여전히 «실측 사이»다: 기각 8.26(Graphite 2) · 확정 12.77(Ink Deep → Ink).
 */
test('카드가 실제로 «떠 있다» — 유호님 확정 2026-08-20 「양모 밤」(조항 ⓚ)', () => {
  const 값 = 테마읽기();
  const 들림 = Math.abs(Lstar(색풀기(값.바탕띄움).hex) - Lstar(색풀기(값.바탕).hex));
  assert.ok(들림 >= 10.0, `카드가 안 떠 있다 — ΔL* ${들림.toFixed(2)} (문턱 10.0 · 기각선 8.26)`);
});

/* ── 픽스처 — «탐지력»을 못박는다 ────────────────────────────────────────────
 * 위 세 검사는 실제 값이 통과하는 것만 본다. 판정식이 망가져도 초록일 수 있어(예: 기준을 0 으로
 * 떨어뜨리면 전부 통과) **알려진 나쁜 면을 실제로 잡는지**를 함께 건다.
 * 🚫 실저장소가 나쁜 값을 갖고 있기를 요구하지 않는다 — 나쁜 면은 여기 상수로만 산다. */
test('픽스처: Deep Wool 카드는 «잡힌다» — Stone·Coral 이 그 면에서 죽는다', () => {
  const 값 = 테마읽기();
  const 죽음 = 죽은층('#575046', 값); // Deep Wool(양모 회색 4) — 더 띄우려 할 때 집기 쉬운 그 단
  assert.ok(죽음.some((d) => d.startsWith('잉크_보조')), `Stone 미달을 못 잡았다 (잡은 것: ${죽음.join(' · ')})`);
  assert.ok(죽음.some((d) => d.startsWith('신호')), `Coral 미달을 못 잡았다 (잡은 것: ${죽음.join(' · ')})`);
});

test('픽스처: 08-20 에 기각된 면 2단(Graphite 2 = 8.26)이 문턱에 걸린다', () => {
  const 들림 = Math.abs(Lstar('#1D1D1C') - Lstar('#08090C')); // 옛 무채 카드 — 「안 떠 있다」로 기각된 실측
  assert.ok(들림 < 10.0, `기각된 값이 문턱을 넘어 버렸다 — ΔL* ${들림.toFixed(2)}`);
});

/* ── D6-15 — OS 글자 확대 캡 ─────────────────────────────────────────────────
 * 상한 «값»은 테마가 한 곳에 쥐고(글자배율상한), 고정 치수 상자를 가진 화면이 자리별
 * maxFontSizeMultiplier prop 으로 쓴다 — RN 0.86+React 19 는 Text.defaultProps 를 소비하지
 * 않아 전역 한 줄이 불가(08-31 실측). 본문(자유 배율)은 일부러 안 캡한다. */
test('글자배율상한 — 값은 테마 한 곳, 고정 치수 네 화면이 자리별 prop 으로 쓴다', () => {
  const 테마 = 코드만(파일소스(path.join(__dirname, '..', 'src', '테마.js')));
  assert.match(테마, /export const 글자배율상한 = 1\.2;/, '테마.js 가 글자배율상한을 안 내보낸다');
  const 소스들 = [
    ['src/답장화면.js', 코드만(파일소스(path.join(__dirname, '..', 'src', '답장화면.js')))],
    ['src/인증화면.js', 코드만(파일소스(path.join(__dirname, '..', 'src', '인증화면.js')))],
    ['src/원장초기화.js', 코드만(파일소스(path.join(__dirname, '..', 'src', '원장초기화.js')))],
    ['src/어제의나.js', 코드만(파일소스(path.join(__dirname, '..', 'src', '어제의나.js')))],
  ];
  for (const [f, 소스] of 소스들) {
    assert.ok(/maxFontSizeMultiplier=\{글자배율상한\}/.test(소스),
      `${f} 에 maxFontSizeMultiplier={글자배율상한} 자리가 없다 — 고정 치수 상자 글자가 OS 확대에 넘친다`);
  }
});
