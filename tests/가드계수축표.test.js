'use strict';
/* 축표 회귀 — 「한 축에서 배운 «모양»을 옆 축에 옮겼는가」를 **기계가 묻게** 하는 자리 (F414 뿌리).
 *
 * 🔴 왜 이 파일이 있나. `tools/가드계수.js` 는 같은 병에 **네 번** 걸렸다 —
 *   1차 base64url · 2차 「식도 사본이다」 · 3차 「별표는 주석이 아니다」 ·
 *   4차 「함수 선언형 원문 생산자」(㉡에서 08-13 에 고쳐 놓고 ㉠엔 08-14 까지 안 옮겼다).
 *   앞의 처방은 매번 «그 축»만 고쳤다. CLAUDE.md 신뢰성 조항의 「3번째 = 원인을 쓸 수 없게
 *   만든다」를 이미 지난 자리인데, 남은 뿌리는 **옮겼는지를 사람이 기억하는 것**이었다.
 *   여기서 그 기억을 기계로 내린다.
 *
 * 🔑 이 파일이 지는 것은 셋이고, **넷째는 일부러 안 진다**:
 *   ① 표가 «총체»인가 — 어휘의 모든 모양에 대해 모든 축이 칸을 갖는가.
 *      → 어휘에 새 모양을 더하면 모든 축의 칸이 비어 **적색**이 된다. 그게 「기계가 묻는다」다.
 *   ② ✗ 는 **사유가 필수**인가 — 안 받는다는 판정은 설명이 있어야 판정이다.
 *   ③ 축이 어휘를 **안 거치고** 손으로 타입을 비교하지 않는가(옛 통로 차단).
 *   ④ ✓ 칸이 «실물»인가 — 픽스처로 잰다. 표만 있고 실물이 없으면 그건 다시 프로즈다.
 *   🚫 안 지는 것: 「그 축이 그 모양을 **옳게** 판정하는가」. 그건 탐지력 픽스처들의 몫이고,
 *      여기서 또 재면 판정이 두 곳에 살아 갈라진다(CLAUDE.md 신뢰성 ④).
 *
 * ⚠ 이 회귀 자신의 대가(맹점 ④ — 장치는 안 도는 쪽보다 이쪽으로 샌다):
 *   · ③의 바늘은 **AST 의 Literal** 이다. 주석에 적힌 같은 글자는 안 센다 — 그건 의도다
 *     (주석을 바늘로 삼은 가드가 「항상 통과」로 죽어 있던 실사고가 F417 이다).
 *   · 타입 이름을 상수에 담아 비교하면(`const T = 'FunctionDeclaration'`) ③이 못 본다.
 *     미탐을 택했다 — 막으려면 상수 전개가 필요한데 그 비용이 이 장치가 막는 병보다 크다.
 *   · ①은 «칸이 있는가»만 본다. `[true, '']` 로 아무 모양이나 ✓ 처리하면 통과한다 —
 *     그래서 ④가 필요하다(✓ 라고 적고 실제로는 안 보는 것이 F414 그 자체다). */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const 계수기 = require('../tools/가드계수.js');
const 도구경로 = path.join(__dirname, '..', 'tools', '가드계수.js');
const 픽스처뿌리 = path.join(__dirname, 'fixtures', '가드계수축표');

/** 어휘의 «칸이 되는» 모양들 — 파생(`함수값` = 화살표 ∪ 함수식)은 뺀다. 둘이 이미 칸이라
 *  파생까지 칸으로 세면 같은 판정을 두 번 묻게 되고, 표가 뜻을 잃는다. */
const 파생 = new Set(['함수값']);
const 어휘 = Object.keys(계수기.모양).filter((k) => !파생.has(k));

// ── ① 표가 총체인가 ────────────────────────────────────────────────────────────
test('🔑 축표는 «모든 축 × 모든 모양»을 채운다 — 어휘에 모양을 더하면 축마다 답해야 한다', () => {
  assert.ok(어휘.length >= 4, `어휘가 비었다(파생만 남았나): ${JSON.stringify(어휘)}`);
  const 축들 = Object.keys(계수기.축표);
  assert.ok(축들.length >= 3, `축이 사라졌다 — 표가 비면 이 회귀는 아무것도 안 막는다: ${축들}`);

  for (const 축 of 축들) {
    const 칸들 = Object.keys(계수기.축표[축]);
    for (const 모양이름 of 어휘) {
      assert.ok(
        Object.prototype.hasOwnProperty.call(계수기.축표[축], 모양이름),
        `축 「${축}」에 모양 「${모양이름}」 칸이 없다.\n`
        + '  → 어휘에 새 모양이 들어왔고 이 축은 아직 대답하지 않았다.\n'
        + '     받으면 [true, \'\'] · 안 받으면 [false, \'왜 안 받나\'] 를 적어라.\n'
        + '     (F414 = 이 대답을 «사람이 기억»하게 뒀다가 네 번 눈이 먼 자리다)',
      );
    }
    for (const 칸 of 칸들) {
      assert.ok(어휘.includes(칸), `축 「${축}」이 어휘에 없는 모양 「${칸}」을 적었다 — 표가 실물보다 넓다`);
    }
  }
});

// ── ② ✗ 는 사유가 필수 ─────────────────────────────────────────────────────────
test('🔑 «안 받는다»는 사유 없이 못 적는다 — 설명 없는 ✗ 는 판정이 아니라 누락이다', () => {
  for (const [축, 행] of Object.entries(계수기.축표)) {
    for (const [모양이름, 칸] of Object.entries(행)) {
      assert.ok(Array.isArray(칸) && 칸.length === 2, `「${축}·${모양이름}」 칸이 [받는가, 사유] 모양이 아니다: ${JSON.stringify(칸)}`);
      const [받는가, 사유] = 칸;
      /* ⚠ boolean 을 못박는다 — 문자열 'false' 는 truthy 라, 오타 하나가 ✗ 를 «조용히 ✓» 로
       *   뒤집는다. 새는 방향이 언제나 「통과」인 그 모양 그대로다. */
      assert.strictEqual(typeof 받는가, 'boolean', `「${축}·${모양이름}」의 받는가가 boolean 이 아니다(${typeof 받는가}) — truthy 오타가 ✗ 를 ✓ 로 뒤집는다`);
      assert.strictEqual(typeof 사유, 'string', `「${축}·${모양이름}」의 사유가 문자열이 아니다`);
      if (받는가 === false) {
        assert.ok(사유.trim().length > 0, `「${축}」은 모양 「${모양이름}」을 «안 받는다»고 적어 놓고 사유가 비었다 — 왜 안 받는지 적어라(안 적으면 다음 사람이 누락과 구분할 수 없다)`);
      }
    }
  }
});

// ── ③ 옛 통로 차단 — 축이 손으로 타입을 비교하지 않는다 ────────────────────────────
test('🔑 함수 모양 타입은 `모양` 어휘 «안»에서만 적힌다 — 손 비교가 남으면 그 자리는 표 밖이다', () => {
  const 소스 = fs.readFileSync(도구경로, 'utf8');
  const ast = acorn.parse(소스, { ecmaVersion: 'latest', sourceType: 'script', allowReturnOutsideFunction: true });

  /* `const 모양 = { … }` 의 범위를 찾는다 — 이 안에서만 타입 이름이 허용된다. */
  let 어휘범위 = null;
  const 훑기 = (노드, 방문) => {
    if (!노드 || typeof 노드.type !== 'string') return;
    방문(노드);
    for (const k of Object.keys(노드)) {
      const v = 노드[k];
      if (Array.isArray(v)) v.forEach((c) => 훑기(c, 방문));
      else if (v && typeof v === 'object' && typeof v.type === 'string') 훑기(v, 방문);
    }
  };
  훑기(ast, (n) => {
    if (n.type === 'VariableDeclarator' && n.id && n.id.name === '모양' && n.init) {
      어휘범위 = [n.init.start, n.init.end];
    }
  });
  assert.ok(어휘범위, '`const 모양 = {…}` 을 못 찾았다 — 어휘가 사라졌거나 이름이 바뀌었다');

  const 함수모양타입 = new Set(['FunctionDeclaration', 'ArrowFunctionExpression', 'FunctionExpression']);
  const 샌자리 = [];
  훑기(ast, (n) => {
    if (n.type !== 'Literal' || typeof n.value !== 'string' || !함수모양타입.has(n.value)) return;
    if (n.start >= 어휘범위[0] && n.end <= 어휘범위[1]) return;      // 어휘 안 — 정상
    샌자리.push(`${소스.slice(0, n.start).split('\n').length}행 '${n.value}'`);
  });
  assert.deepStrictEqual(
    샌자리, [],
    '함수 모양 타입을 어휘 «밖»에서 손으로 비교했다 — 그 자리는 축표에 안 서고 이 회귀도 못 본다.\n'
    + `  샌 자리: ${샌자리.join(' · ')}\n`
    + '  → `모양.함수선언(n)` · `모양.함수값(n)` · `모양.식(n)` 을 써라.\n'
    + '     새 모양이면 `모양` 에 더해라 — 그 순간 축표가 비어 ①이 축마다 대답을 요구한다.',
  );
});

// ── ④ ✓ 칸이 실물인가 — 픽스처로 잰다 ──────────────────────────────────────────
test('🔑 ㉡사본의 ✓ 네 칸이 «실물»이다 — 화살표·함수식·함수선언·식 넷 다 잡힌다', () => {
  const r = 계수기.재기(픽스처뿌리);
  const 이름들 = r.사본.map((x) => x.이름).sort();
  assert.deepStrictEqual(
    이름들, ['선언사본', '식사본', '함수식사본', '화살표사본'],
    `㉡사본이 네 모양을 다 못 봤다(또는 거짓양성이 붙었다): ${JSON.stringify(이름들)}\n`
    + '  표는 ㉡사본의 네 칸을 전부 ✓ 로 적고 있다 — 표와 실물이 갈렸다.',
  );
});

test('🔑 ㉠원문생산자의 «함수선언» ✓ 가 실물이다 — 08-14 4차가 난 바로 그 칸', () => {
  const r = 계수기.재기(픽스처뿌리);
  const 위험글 = JSON.stringify(r.위험);
  assert.ok(
    위험글.includes('원문조각'),
    '`function 원문조각(a,b){ return 소스.slice(a,b) }` 가 원문 생산자로 안 섰다 — 4차 사각이 되살아났다.\n'
    + `  위험: ${위험글.slice(0, 300)}`,
  );
});

test('표가 «✓ 라고만» 적고 넘어가지 못한다 — ✗ 인 칸은 실제로 그 축에 안 든다', () => {
  const r = 계수기.재기(픽스처뿌리);
  /* ㉠원문생산자·식 = ✗ 다. 픽스처의 `식사본` 은 사본(㉡)으로는 서지만 원문 «생산자»로는
   * 안 선다 — 그 이름이 원문 생산자로 서면 표의 ✗ 가 거짓이 된다. */
  assert.strictEqual(
    계수기.축표['㉠원문생산자'].식[0], false,
    '이 회귀는 「㉠·식 = ✗」를 전제로 짜였다 — 표를 바꿨으면 이 단언도 같이 바꿔라',
  );
  /* ⚠ 이 단언은 계수기 자신의 ❔모름 1건으로 잡힌다(`재기()` 가 파일을 읽으니 그 반환의 파생인
   *   이 문자열을 계수기가 못 가른다). **고치지 마라** — 결과 덤프를 정제 통로로 감싸라는 말은
   *   따를 수 없는 처방이고, 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
   *   모름은 「위험」이 아니라 「못 갈랐다」이고, 여기서는 그게 맞는 값이다. */
  const 위험이름 = JSON.stringify(r.위험);
  assert.ok(!위험이름.includes('식사본'), '`식사본` 이 원문 생산자로 섰다 — 표는 ㉠·식을 ✗ 로 적고 있다');
});
