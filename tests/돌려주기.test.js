/* ─────────────── ⑤ 문구 — 숫자 0 · 금칙어 0 · 남과 비교 0 ─────────────── */

/** 학생이 읽는 한 줄이 지켜야 할 것. **탐지력은 아래 가짜 문구가 진다.** */
function 문구위반(글) {
  const 사유 = [];
  if (/[0-9０-９]/.test(글)) 사유.push('숫자');
  if (/(패배|졌|실패|불운|하락|부족|늦었)/.test(글)) 사유.push('금칙어');
  if (/(친구|다른 학생|남들|평균|등수|1등|보다 잘|보다 못)/.test(글)) 사유.push('남과 비교');
  if (/(잘했|못했|훌륭|아쉽)/.test(글)) 사유.push('평가어');
  return 사유;
}

test('탐지력 — 가짜 문구는 실제로 걸린다(이 검사가 아무것도 안 재고 초록이 되는 것을 막는다)', () => {
  assert.deepEqual(문구위반('지난번보다 3번 덜 고쳤어요.'), ['숫자']);
  assert.deepEqual(문구위반('다른 친구보다 빠르게 썼어요.'), ['남과 비교']);
  assert.deepEqual(문구위반('이번엔 실패했어요.'), ['금칙어']);
  assert.deepEqual(문구위반('아주 잘했어요.'), ['평가어']);
});

test('실문구 넷은 거짓양성 0 — 그리고 종류 목록과 정확히 짝이 맞는다', () => {
  assert.deepEqual(Object.keys(문구).sort(), [...종류들].sort(), '문구 없는 종류·종류 없는 문구는 화면에서 빈 줄이 된다');
  for (const [종류, 글] of Object.entries(문구)) {
    assert.deepEqual(문구위반(글), [], `${종류}: ${글}`);
    assert.ok(글.endsWith('.') || 글.endsWith('요.'), `${종류}: 한 줄로 끝나야 한다`);
  }
});

