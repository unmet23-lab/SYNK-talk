/* ── `expo-*` 를 끌고 오는 세 화면 (2026-08-09 · 위 머리말의 「가장 큰 남은 구멍」) ──────────
 * 실측하니 셋이 **서로 다른 이유**로 죽었다: 말하기=`expo` 배럴이 TS 소스를 가리켜 node 의
 * 타입 스트립이 node_modules 안에서 거부 · 답장=`expo-secure-store` 네이티브 바인딩 없음 ·
 * 도착확인=`expo-updates` 같은 이유. 통로가 **빈 판** 다섯을 세워 셋 다 열렸다(값 지어내기 0).
 * 🔑 여기서 재는 것은 여전히 **첫 렌더**뿐이다 — `useEffect` 는 서버 렌더에서 안 돈다.
 *   그래서 「서버가 막았을 때」 같은 갈래는 이 층이 아니라 `말하기로직`·`앱모듈세우기` 가 진다. */

test('⑥ 말하기화면 첫 프레임 — 「아직 모른다」가 빈 화면도 고정 문장도 아니다 (F268 이 난 화면)', () => {
  const { 급수편지 } = require(path.join(ROOT, 'contents', '첫편지.js'));
  const 글 = 그리기('src/말하기화면.js', { 급수: 1, 토큰: null, 학생번호: 'SYNK-042' });

  assert.match(글, /가져오는 중/, '「아직 모른다」가 빈 화면으로 나왔다 — 학생은 고장으로 읽는다');
  /* 🔴 **폴백 편지가 첫 프레임에 뜨면 안 된다.** `과제` 초기값을 폴백으로 두는 것은 자연스러운
     유혹인데(코드가 짧아진다), 그러면 서버 과제가 있는 날에도 고정 문장이 번쩍 떴다가 바뀌고
     학생은 이미 그걸 읽기 시작한다. 정본 = `말하기화면.js:112` 「null = 아직 모른다」. */
  assert.ok(!글.includes(급수편지(1).본문.slice(0, 12)), '서버 답을 받기 전에 고정 편지가 떴다');
  /* 🔴 웹 판은 기기 저장이 없다 — 정본(`src/저장.js` 머리말)이 「지속되지 않음을 숨기지 않는다」고
     적은 그 경고가 실제로 서는지. 숨기면 학생은 사라질 기록을 남은 것으로 믿는다. */
  assert.match(글, /기록이 기기에 남지 않아요/, '지속 안 됨을 화면이 숨겼다');
});

