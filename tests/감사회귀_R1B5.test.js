'use strict';
/* 감사 R1B5 회귀 — 문구 감수 화면·API 의 시공 세 가지를 **소스에서** 잰다
 * (RN 을 node 로 못 여는 자리라 `tests/문구감수화면.test.js` 와 같은 방식이다).
 *
 * · D8-10 초벌 복귀 통로 — 번역을 고치다 초벌로 돌아갈 길
 * · D8-6  자동 이어받기 — 목록이 0이 된 순간 다음 쪽을 잇되, 실패 시 무한루프가 원리상 막힘
 * · D8-12 「남은 것」 총계 — 옛 서버 응답(total 없음)엔 null 로 접히는 하위호환
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

const { 코드만, 파일소스 } = require('./lib/소스검사.js');

const 소스 = (p) => 코드만(파일소스(path.join(__dirname, '..', ...p.split('/'))));
const 화면 = 소스('src/문구감수화면.js');
const api = 소스('src/문구감수API.js');

test('D8-10 초벌로 되돌리는 길이 있다 — set번역(초벌) 호출이 소스에 산다', () => {
  /* 칸이 controlled(value={번역})라 set번역(초벌) 한 줄로 칸·판정미리가 같이 되돌아온다.
     이 호출이 사라지면 번역을 고치다 초벌로 돌아갈 길이 다시 없어진다. */
  assert.match(화면, /set번역\(초벌\)/, '초벌 복귀 통로가 없다 — 되돌리기 버튼이 죽었다');
  /* 버튼이 서는 조건은 trim 기준이어야 한다 — 판정 계산과 같은 자. 공백만 달라도 버튼이
     서면 눌러도 판정이 안 변해 거짓 문이 된다. */
  assert.match(화면, /번역\.trim\(\)\s*!==\s*초벌\.trim\(\)/,
    '되돌리기 게이트가 trim 비교가 아니다 — 판정 계산(행154)과 자가 갈린다');
});

test('D8-6 자동 이어받기 조건식에 「!오류」 가드가 있다 — 실패 시 무한루프가 원리상 막힌다', () => {
  /* 오류가 서면 자동 재시도가 멈추고, 수동 「더 불러오기」(더받기가 오류를 비우고 시작)가
     폴백으로 남는다. 이 가드가 빠지면 서버 실패 한 번에 요청이 무한히 돈다. */
  assert.match(화면, /불러옴\s*&&\s*!도는중\s*&&\s*!오류\s*&&\s*!목록\.length\s*&&\s*커서/,
    '자동 이어받기 조건식이 바뀌었다 — !오류 가드가 빠지면 실패 시 무한루프다');
});

test('D8-12 큐받기가 total 없는 옛 서버 응답을 총대기 null 로 접는다 — 하위호환', () => {
  /* Number.isFinite(undefined) === false 라, 옛 서버(total 안 실음)에선 총대기가 null 로
     접히고 화면은 목록.length 로 폴백한다. 이 모양이 바뀌면 옛 서버 앞에서 NaN 이 선다. */
  assert.match(api, /총대기:\s*Number\.isFinite\(본문\.total\)\s*\?\s*본문\.total\s*:\s*null/,
    '총대기 하위호환 접기가 바뀌었다 — 옛 서버 응답에서 null 이 아니게 된다');
  /* 화면 폴백 — 서버총이 없으면 손에 든 쪽 수로 그린다. */
  assert.match(화면, /서버총\s*\?\?\s*목록\.length/, '「남은 것」의 폴백(서버총 ?? 목록.length)이 없다');
});
