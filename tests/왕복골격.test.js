/* 왕복골격 회귀 — **옛 통로 금지**: 골격이 지는 머리(관리 API·토큰 읽기·리허설 게이트·키 fetch·
 * 배포판 게이트)를 왕복도구가 다시 자기 안에 복사하면 적색이 된다.
 *
 * 왜 — 같은 머리가 5벌 복사돼 이미 3갈래로 갈라져 있었다(`--운영승인` 1곳뿐·즉사 1곳·시그니처
 * 3종). 3번째 규칙: 호출부마다 고치는 대신 잘못 쓸 수 없는 공용 통로를 만들고 **옛 통로를
 * 테스트로 금지한다**(CLAUDE.md 신뢰성 · `lib/자격증명.js` 머리말과 같은 사슬).
 *
 * 세 맹점:
 *   ① 사람이 실제로 쓰는 표기 — 금지 조각은 옮겨 내기 전 5벌 복제에서 그대로 딴 리터럴이다.
 *   ② 탐지력은 픽스처가 진다 — 실저장소에는 거짓양성 0건만 검사한다(버그 존재를 요구하지 않는다).
 *   ③ 목록이 낡으면 스스로 운다 — 같은 조각이 골격 안에는 **있어야** 통과한다(개명·오타 감지).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 코드만 } = require('./lib/소스검사.js');

const ROOT = path.resolve(__dirname, '..');

/* 왕복도구 안에서 다시 나타나면 골격 복제가 시작된 조각들 — 전부 골격(과 그 아래 공용 통로)의 몫이다.
 * ⚠ `rehearsal` 낱말이 아니라 정규식 리터럴을 잡는다 — 픽스처 비밀번호(`rehearsal-…`)는 무죄다. */
const 금지 = [
  'api.supabase.com',        // 관리 API 리터럴(API 상수 복제)
  'SUPABASE_ACCESS_TOKEN',   // 토큰 직접 읽기
  '/rehearsal/i',            // 리허설 게이트 재구현
  'database/query',          // sql 헬퍼 재구현
  'api-keys',                // 키 fetch 재구현
  '배포대조',                 // 배포판 게이트 직접 호출(발화점은 골격이 쥔다)
  '자격증명',                 // env 통로 직접 사용(골격이 감싼다)
];
/* 🔑 판정은 **코드만** 본다 — 주석은 실행되지 않으므로 복제가 아니다 (F533 · 2026-08-18).
 *
 * 왜 열었나: 첫 판은 소스 전문을 훑어 **주석 속 낱말도 위반으로 셌다.** 그래서 「이 도구는
 *   `자격증명` 을 직접 안 든다 — 골격이 감싼다」 같은 **설계 이유를 코드 옆에 적을 수가 없었다**
 *   (실사고: `라디오왕복시험.js` 가 그 문장 하나로 빨개졌고, 우회는 «낱말을 피해 쓰기»였다 —
 *   그러면 다음 사람이 그 사실을 못 찾는다). 금지의 과녁은 «복제된 실행 경로»지 낱말이 아니다.
 * 📏 실측 2026-08-18(바꾸기 전에 쟀다): 왕복시험 도구 **11개 전부 위반 0**(전문·코드만 동일)
 *   → 이 완화가 **가리는 진짜 위반은 0건**이다. 그리고 `tools/` 의 **7개 파일**이 이미 그
 *   낱말을 주석에만 쓰고 있다(`배포빚`·`원격SQL`·`동봉신호` 등) — 관습은 이미 이쪽이었고,
 *   계약만 그 관습을 자기 분모 안에서 금지하고 있었다.
 * ⚠ 대가(틀릴 때의 모습): `코드만` 이 어느 파일에서 짝을 놓치면 **진짜 코드 위반이 조용히
 *   지워진다** — 새는 방향이 「통과」다. 그래서 아래 픽스처가 금지 조각을 **날 표기·문자열 표기
 *   두 벌로** 넣어 렉서가 그것을 삼키면 그 자리에서 빨개지게 못박는다(맹점②: 탐지력은 픽스처가
 *   진다). `database/query` 처럼 `/` 가 든 조각이 정규식으로 오독되는 자리가 정확히 그 함정이다. */
const 위반 = (소스) => { const 코드 = 코드만(소스); return 금지.filter((p) => 코드.includes(p)); };
/** 금지 조각 중 골격 «코드»에 없는 것 — 「목록이 낡았나」의 판정 하나(아래 검사와 픽스처가 함께 쓴다). */
const 빠진것 = (골격소스) => { const 코드 = 코드만(골격소스); return 금지.filter((p) => !코드.includes(p)); };

test('탐지력 — 옛 골격 조각이 하나라도 돌아오면 잡힌다 (픽스처 · 코드 표기 두 벌)', () => {
  for (const p of 금지) {
    assert.deepEqual(위반(`const 옛통로 = 무엇('${p}');`), [p], `${p} — 문자열 표기`);
    assert.deepEqual(위반(`if (${p}) return;`), [p], `${p} — 날 표기(렉서가 삼키면 여기서 빨개진다)`);
  }
  // 새 통로는 무죄다 — 이 줄이 걸리면 가드가 자기 처방을 막는 것이다(F103).
  assert.deepEqual(위반("const { sql, 확인, 보고 } = await 골격.열기('왕복시험');"), []);
});

test('거짓양성 — 「직접 안 든다」고 주석에 적은 것은 위반이 아니다 (F533)', () => {
  for (const p of 금지) {
    assert.deepEqual(
      위반(`const { sql } = await 골격.열기('x');   // ${p} 를 직접 안 든다 — 골격이 감싼다`), [],
      `${p}: 설계 이유를 적었다고 빨개지면, 고치는 손은 그 문장을 지우는 쪽으로 간다(F384 와 같은 압력)`);
  }
});

test('실저장소 — 왕복도구 5종이 실재하고(분모) 옛 골격 조각이 0건이다', () => {
  const 도구뿌리 = path.join(ROOT, 'tools');
  const 도구들 = fs.readdirSync(도구뿌리).filter((n) => /왕복시험\.js$/.test(n));
  // 0건=미실행 — glob 이 비면 「전부 통과」가 아니라 여기서 빨개져야 한다(F207).
  assert.ok(도구들.length >= 5, `왕복시험 도구가 ${도구들.length}개뿐이다 — 이름 규칙이 바뀌었으면 이 회귀부터 고친다`);
  for (const n of 도구들) {
    const 소스 = fs.readFileSync(path.join(도구뿌리, n), 'utf8');
    assert.deepEqual(위반(소스), [], `${n} 안에 옛 골격 조각이 있다 — lib/왕복골격.js 의 손잡이를 쓴다`);
  }
});

test('목록이 낡지 않았다 — 같은 조각이 골격 안에 **코드로** 산다', () => {
  /* 🔑 여기도 `코드만` 을 지난다(F533 과 한 벌) — 안 그러면 골격이 그 조각을 실제로는 안 쓰고
   *   «주석에서 언급만» 해도 이 검사가 초록이다. 그 초록은 「목록이 살아 있다」는 얼굴로
   *   낡은 목록을 통과시킨다(안 도는 쪽이 아니라 맞는 얼굴로 틀린 값 · 맹점④).
   * 📏 실측 2026-08-18: 금지 7개 전부 `코드만` 통과분에도 산다 — 조이는 값이 0원이었다. */
  const 골격소스 = fs.readFileSync(path.join(ROOT, 'lib', '왕복골격.js'), 'utf8');
  assert.deepEqual(빠진것(골격소스), [], '골격 «코드»에 없는 조각이 있다 — 개명됐거나 주석에만 남았으면 금지 목록도 같이 고친다');
});

test('목록 검사도 코드만 본다 — 주석 속 언급을 「산다」로 세면 낡은 목록이 초록이 된다 (F533)', () => {
  /* 🔴 변이 ④ 가 뚫은 자리다: 위 검사에서 `코드만` 을 빼도 오늘은 8건이 전부 초록이었다
   *   (지금은 7개가 코드에도 다 살아서 두 판이 같은 답을 낸다). 그러면 그 조임은 «장식»이고,
   *   누군가 골격에서 그 조각을 지우고 주석에만 남기는 날 조용히 초록으로 통과한다. */
  const 주석뿐인골격 = 금지.map((p) => `// ${p} 는 여기서 언급만 한다`).join('\n');
  assert.deepEqual(빠진것(주석뿐인골격), 금지,
    '주석뿐인 골격을 「전부 산다」로 읽었다 — 그러면 목록이 낡아도 이 검사가 안 운다');
});

test('🔒 금지 목록은 줄어들지 않는다 — 한 줄만 지워도 가드가 조용히 약해진다', () => {
  /* 래칫 사본이다(판정을 두 곳에 적은 것이 아니라, «바뀌었다»를 잡으려고 일부러 둔 거울).
   * 🔴 변이 ③ 이 뚫은 자리: `'자격증명'` 한 줄을 지워도 8건이 전부 초록이었다 — 분모가 줄면
   *   실저장소 검사는 «덜 요구»하면서도 초록이라, 새는 방향이 정확히 「통과」다.
   * 늘릴 때는 이 줄을 같이 늘린다. 줄일 때는 왜 줄이는지를 여기 적고 줄인다. */
  assert.deepEqual(금지, [
    'api.supabase.com', 'SUPABASE_ACCESS_TOKEN', '/rehearsal/i',
    'database/query', 'api-keys', '배포대조', '자격증명',
  ], '금지 목록이 바뀌었다 — 의도한 변경이면 이 래칫도 같이 고친다');
});

/* 게이트 스코프(`열기` 의 `함수목록`) — 시험이 부르는 함수보다 좁은 스코프는 옛 판을 초록으로
 * 재므로(새는 방향은 통과), 스코프를 선언한 도구는 「소스가 부르는 함수 ⊆ 선언 목록」을 여기서
 * 잰다. 함수 사용은 사람이 실제로 쓰는 표기 셋에서 걷는다: URL 리터럴 · 조회 기본값 · `함수:` 옵션. */
/* 스코프를 선언한 도구가 둘 이상이라 **판정을 한 곳에서 파생**시킨다 — 도구마다 이 검사를
 * 베껴 적으면 갈라지고, 갈라진 쪽의 증상은 「그 도구만 조용히 안 재짐」이다(=통과 모양). */
const 스코프도구 = [
  { 파일: '배달왕복시험.js', 최소: 4 },   // deliver·tasks·corrections·progress
  { 파일: '생성왕복시험.js', 최소: 3 },   // deliver·deliver-one·tasks (§12 픽스처 대군)
  { 파일: '골든왕복시험.js', 최소: 1 },   // teach 하나(픽스처는 SQL · 성적표는 DB 직독)
  { 파일: 'eval-run.js', 최소: 1 },        // correct 하나(평가 통로는 DB 무접촉이라 다른 함수를 안 부른다)
  { 파일: '과제생성평가.js', 최소: 1 },    // deliver-one 하나(§8-B 평가 갈래 `?평가=1` — 운영 큐 무접촉 · 벤더만)
  /* teach 하나만 «부른다» — `correct` 는 선언에만 있고 호출하지 않는다(그 호출이 벤더 유료
   * 경로라 F452 로 걷어냈다). 부르지 않아도 과녁인 이유: 그 시험이 `correct` 의 소스에서
   * 술어 원문을 꺼내 DB 에 태우므로, 그 파일이 배포본과 어긋나면 결론이 딴 함수 이야기가 된다.
   * 선언이 사용보다 «넓은» 것은 게이트를 좁히는 게 아니라 넓히는 쪽이라 안전하다. */
  { 파일: '반피드백왕복시험.js', 최소: 1 },
];

for (const { 파일, 최소 } of 스코프도구) {
  test(`${파일} 게이트 스코프 — 시험이 부르는 함수를 전부 덮는다`, () => {
    const 소스 = fs.readFileSync(path.join(ROOT, 'tools', 파일), 'utf8');
    const 선언문 = 소스.match(/const 게이트함수들 = \[([^\]]*)\]/);
    assert.ok(선언문, `${파일} 에 게이트함수들 선언이 없다 — 스코프를 접었으면 이 회귀도 같이 접는다`);
    assert.ok(소스.includes('함수목록: 게이트함수들'),
      `${파일}: 게이트함수들이 열기에 안 실린다 — 선언만 있고 발동이 없으면 스코프는 장식이다`);
    const 선언 = new Set([...선언문[1].matchAll(/'([^']+)'/g)].map((m) => m[1]));
    const 사용 = new Set();
    for (const m of 소스.matchAll(/functions\/v1\/([a-z_-]+)/g)) 사용.add(m[1]);   // URL 리터럴(호출 = deliver·teach)
    for (const m of 소스.matchAll(/옵션\.함수 \?\? '([^']+)'/g)) 사용.add(m[1]);   // 조회 기본값(tasks)
    for (const m of 소스.matchAll(/함수: '([^']+)'/g)) 사용.add(m[1]);             // 조회 옵션
    assert.ok(사용.size >= 최소,
      `${파일}: 함수 사용을 ${사용.size}종밖에 못 걷었다(최소 ${최소}) — 표기가 바뀌었으면 걷는 정규식부터 고친다`);
    for (const f of 사용) {
      assert.ok(선언.has(f), `${파일}: 게이트 스코프에 「${f}」 가 없다 — 시험이 부르는데 그 함수의 낡음을 안 잰다`);
    }
  });
}
