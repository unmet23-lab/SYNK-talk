/* ⓔ-22 «구앱 간주»의 서버 반쪽 회귀 — 활성 뒤 구앱 응답 `data` 의 안내 항목
 *   (상태기반 설계 §3-1 v5.13 · C0 §4-3 ① 구앱 전환 규칙 「창의 수명」).
 *
 * ■ 무엇을 재나 — 서술이 아니라 **구앱이 실제로 지나는 길**로 잰다(§12 「서술로만 두면 초록」):
 *   ① 조립 → 서버 거름망(`학생판스냅샷`) → 구앱 소비(`화면과제`)를 한 줄로 잇고, 끝에서
 *      「안내가 그려진다 + 발화·열람은 안 나간다」를 단언한다. 중간 어느 층이 안내 키를 벗기면
 *      여기가 빨개진다(허용 목록이 이 항목을 몰랐다는 뜻이다).
 *   ② `task_ref: null` 안전판 — 제출재료가 null 이라 그날 발화가 사건이 되지 않는다.
 *   ③ 문구가 없으면 항목도 없다 — `있음`·`없음`(안 그림)과 빈 문구는 빈 카드가 아니라 «항목 0»이다.
 *
 * ■ 활성일 게이트(함수 부재 = 무동작)와 판 선언(<c12) 분기는 이 층이 못 잰다 — DB 가 필요한
 *   판정이라 왕복시험 몫이다(활성 조각 착지 뒤 · 상태기반 §12 도장 절이 자리를 쥔다). */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { 구앱안내항목, 화면과제, 학생판스냅샷 } = require('../lib/오늘과제.js');
const { 생성안내 } = require('../contents/문구_생성.js');

const 폴백 = { id: null, 본문: '고정 편지', 핵심문장: '고정 문장', 질문: '고정 질문' };

test('① 조립 → 학생판스냅샷 → 화면과제 — 안내가 그려지고, 서버 경로가 키를 안 벗긴다', () => {
  for (const 상태 of ['생성중', '오류']) {
    const 안내 = 생성안내(상태);
    const 항목 = 구앱안내항목('2026-08-22', 안내);
    assert.ok(항목, `${상태}: 항목이 서야 한다`);

    // 서버가 응답 전에 하는 그 거름(절단문서 ②-20)을 그대로 지나서도 그려져야 한다.
    const 나간항목 = { ...항목, task_snapshot: 학생판스냅샷(항목.task_snapshot) };
    const 화면 = 화면과제(나간항목, 폴백);

    assert.equal(화면.출처, '서버', `${상태}: 폴백으로 내려가면 안내가 아니라 고정 편지가 뜬다`);
    const 글 = [...안내.제목, ...안내.본문].join('\n');
    assert.equal(화면.편지.본문, 글, `${상태}: 학생이 읽는 본문이 카피 정본과 다르다`);
    assert.equal(화면.편지.핵심문장, 글);
    assert.equal(화면.편지.질문, 글, `${상태}: 흐름을 넘겨도 같은 안내가 서야 한다`);
    assert.equal(화면.편지.선택지, null, `${상태}: 안내에 보기가 뜨면 안 된다`);
    assert.equal(화면.degraded, true, `${상태}: 정상 과제가 아니라는 표식`);
  }
});

test('② task_ref null 안전판 — 발화도 열람도 사건이 되지 않는다', () => {
  const 항목 = 구앱안내항목('2026-08-22', 생성안내('생성중'));
  const 화면 = 화면과제({ ...항목, task_snapshot: 학생판스냅샷(항목.task_snapshot) }, 폴백);
  assert.equal(화면.제출재료, null, '제출재료가 서면 안내를 향해 말한 것이 사건이 된다');
  assert.equal(화면.task_id, null);
  assert.equal(화면.intervention_id, null, '가리킬 배달 사건이 없다 — 열람(c9)도 안 나간다');
  assert.equal(화면.intervention_event_id, null);
});

test('③ 문구가 없으면 항목도 없다 — 빈 카드를 싣지 않는다', () => {
  for (const 안내 of [생성안내('있음'), 생성안내('없음'), 생성안내(null), null]) {
    assert.equal(구앱안내항목('2026-08-22', 안내), null);
  }
  assert.equal(구앱안내항목('2026-08-22', { 제목: [], 본문: [] }), null, '둘 다 빈 배열이면 글이 없다');
});
