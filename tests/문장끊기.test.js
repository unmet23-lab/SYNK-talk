'use strict';
/**
 * ②따라 「문장 단위 끊기」 회귀 (유호 확정 2026-08-23 · 어댑터 착지 08-26).
 *
 * 급소 넷을 못박는다:
 *   ① **글자를 안 잃는다** — 학생이 따라 말할 글자는 서버가 낸 그 글자여야 한다.
 *      자르기가 한 글자라도 먹으면 「의도를 100% 아는 발화」(설계 §6 ②)의 정답 라벨이 거짓이 된다.
 *   ② **못 자르면 통으로 둔다** — 틀리게 자르느니 08-23 이전 그대로. 새 손해를 만들지 않는다.
 *   ③ **걸음 이름이 문지기를 지난다** — `따라2` 가 `제출로그.항목추가` 에 막히면 녹음이 로그에도
 *      못 들어가고, 화면은 「보내기」를 눌러도 **아무 일이 안 일어난다**(오류 한 줄 없이).
 *   ④ **봉투가 만들어진다** — 형식 표에 그 이름이 없으면 `제출사건` 이 `null` 을 내고, 증상은
 *      「녹음은 했는데 서버에 없다」다. ③과 ④는 **다른 문**이라 각각 잰다.
 */
const test = require('node:test');
const assert = require('node:assert');

const { 문장들, 상한 } = require('../lib/문장끊기.js');
const { 따라걸음, 따라차례, 녹음걸음인가 } = require('../lib/걸음.js');
const { 항목추가 } = require('../lib/제출로그.js');
const { 화면과제, 제출사건 } = require('../lib/오늘과제.js');

/* ─────────────── ① 자르기 ─────────────── */

test('두 문장을 둘로 가른다 — 생성 산출의 기본값이다(08-26 실측: 80행 중 2문장 71·3문장 9·1문장 0)', () => {
  const 글 = '저녁을 먹고 나서 할머니께 전화를 드렸어요. 할머니께서 요즘 무릎이 아프시다고 하셔서 걱정이 됐어요.';
  assert.deepEqual(문장들(글), [
    '저녁을 먹고 나서 할머니께 전화를 드렸어요.',
    '할머니께서 요즘 무릎이 아프시다고 하셔서 걱정이 됐어요.',
  ]);
});

test('🔴 자른 조각을 이어 붙이면 원문이다 — 한 글자도 안 먹는다', () => {
  const 표본 = [
    '어제 할머니 댁에 갔는데, 노래를 틀어 주셨어요. 저는 처음 듣는 노래였지만 계속 따라 불렀어요.',
    '정말요? 네! 좋아요.',
    '마침표가 없는 한 문장',
    '친구가 「같이 가자.」라고 했어요. 그래서 같이 갔어요.',
  ];
  for (const 글 of 표본) {
    const 붙임 = 문장들(글).join('').replace(/\s+/g, '');
    assert.equal(붙임, 글.replace(/\s+/g, ''), 글);
  }
});

test('따옴표 안의 마침표로는 안 자른다 — 인용이 두 동강 나면 화계가 사라진다', () => {
  assert.deepEqual(문장들('친구가 「같이 가자.」라고 했어요.'), ['친구가 「같이 가자.」라고 했어요.']);
});

test('숫자 사이 마침표는 소수점이지 문장 끝이 아니다', () => {
  assert.deepEqual(문장들('우유를 3.5리터 샀어요.'), ['우유를 3.5리터 샀어요.']);
});

test('② 짝이 안 맞는 여는 따옴표가 있으면 통으로 둔다 — 틀리게 자르느니 현행 그대로', () => {
  const 글 = '괄호가 (안 닫혔어요. 그래서 못 자릅니다.';
  assert.deepEqual(문장들(글), [글]);
});

test('빈 글은 빈 배열 — 없는 문장을 지어내지 않는다', () => {
  for (const v of ['', '   ', null, undefined]) assert.deepEqual(문장들(v), []);
});

test(`🔴 상한(${상한})을 넘겨도 버리지 않는다 — 남은 글이 통째로 마지막 조각에 담긴다`, () => {
  const 조각 = 문장들('하나. 둘. 셋. 넷. 다섯.');
  assert.equal(조각.length, 상한);
  assert.equal(조각[상한 - 1], '셋. 넷. 다섯.');
  assert.equal(조각.join('').replace(/\s+/g, ''), '하나.둘.셋.넷.다섯.');
});

/* ─────────────── ② 걸음 이름 ─────────────── */

test('문장이 하나면 걸음은 `따라` 그대로다 — 안 갈린 날은 08-23 이전과 한 글자도 안 다르다', () => {
  assert.equal(따라걸음(1, 1), '따라');
  assert.equal(따라차례('따라'), null, '「안 갈랐다」와 「첫 문장이다」는 다른 사실이다');
});

test('문장이 둘 이상이면 차례가 이름에 붙는다', () => {
  assert.equal(따라걸음(1, 2), '따라1');
  assert.equal(따라걸음(2, 2), '따라2');
  assert.equal(따라차례('따라2'), 2);
});

test('차례 0·앞자리 0 은 걸음이 아니다 — 같은 문장이 두 이름을 가지면 재시도가 갈린다', () => {
  for (const 나쁜것 of ['따라0', '따라01', '따라 1', '답하기2', '', null]) {
    assert.equal(따라차례(나쁜것), null, String(나쁜것));
    assert.equal(녹음걸음인가(나쁜것), false, String(나쁜것));
  }
});

/* ─────────────── ③ 문지기 — 로그에 들어가는 문 ─────────────── */

const 항목입력 = (step) => ({
  date: '2026-08-26', step, status: 'submitted', duration_ms: 1200, hesitation_ms: 0,
  spoke: true, threshold_db: -40, text: null, audio: null, prompt_id: 'p1',
  created_at: '2026-08-26T01:00:00.000Z', task_meta: null, capture_app: null,
  correlation_id: '11111111-1111-4111-8111-111111111111', replayed_at: null,
});

test('🔴 `따라N`·`라디오낭독` 이 제출 로그 문지기를 지난다 — 막히면 녹음이 로그에도 못 들어간다', () => {
  for (const step of ['따라', '따라1', '따라3', '답하기', '라디오낭독']) {
    const { 항목 } = 항목추가([], 항목입력(step));
    assert.equal(항목.step, step);
    assert.equal(항목.id, `2026-08-26-${step}-1`);
  }
});

test('모르는 걸음은 여전히 던진다 — 넓혔지 열어 둔 것이 아니다', () => {
  for (const step of ['없는걸음', '따라0', '답하기1', '']) {
    assert.throws(() => 항목추가([], 항목입력(step)), /녹음이 없는 호흡/, String(step));
  }
});

test('시도 번호는 **걸음마다** 센다 — 둘째 문장이 첫 문장의 재시도로 둔갑하지 않는다', () => {
  let 로그 = [];
  ({ 로그 } = 항목추가(로그, 항목입력('따라1')));
  ({ 로그 } = 항목추가(로그, { ...항목입력('따라1'), status: 'retried' }));
  ({ 로그 } = 항목추가(로그, 항목입력('따라2')));
  const 번호 = Object.fromEntries(로그.map((e) => [e.id, e.attempt]));
  assert.equal(번호['2026-08-26-따라1-1'], 1);
  assert.equal(번호['2026-08-26-따라1-2'], 2, '같은 문장을 다시 말한 것 = attempt 증가');
  assert.equal(번호['2026-08-26-따라2-1'], 1, '🔴 다음 문장은 새 걸음이라 attempt 가 1 이다');
});

/* ─────────────── ④ 봉투 — 서버로 나가는 문 ─────────────── */

const 폴백 = { id: 'intro', 본문: '안녕하세요.', 핵심문장: '안녕하세요.', 질문: '이름이 뭐예요?' };
const 스냅 = {
  ver: 1, 날짜: '2026-08-26',
  호흡: [
    { 차례: 1, 무엇: '듣기' },
    { 차례: 2, 무엇: '따라말하기', task_format: '낭독', 문장: '저는 학교에 가요. 버스를 타요.' },
    { 차례: 3, 무엇: '답하기', task_format: '자유발화', 프롬프트: '어떻게 가요?' },
  ],
};
const 서버항목 = () => ({
  task_id: 't1', task_ref: 'task-2026-08-26', task_snapshot: 스냅,
  level_snapshot: 'Lv3', goal_snapshot: '유학', intervention: null,
});

test(`형식 표가 따라1~따라${상한} 을 안다 — 없으면 그 발화는 오류 없이 서버에서 사라진다`, () => {
  const { 제출재료 } = 화면과제(서버항목(), 폴백);
  for (let i = 1; i <= 상한; i += 1) {
    assert.equal(제출재료.형식[따라걸음(i, 상한)], '낭독', `따라${i}`);
  }
  assert.equal(제출재료.형식.따라, '낭독', '안 갈린 날의 이름도 그대로 산다');
  assert.equal(제출재료.형식.답하기, '자유발화');
});

test('🔴 문장마다 봉투가 만들어진다 — 걸음마다 자기 형식(낭독)을 갖는다', () => {
  const { 제출재료 } = 화면과제(서버항목(), 폴백);
  for (const step of ['따라1', '따라2']) {
    /* 🔑 항목은 **문지기를 지나 만들어진 것**을 쓴다 — 손으로 지은 객체에는 `attempt`·멱등키가
     *   없어, 봉투가 비어도 시험은 초록이 된다(두 문을 한 번에 지나야 이 절이 뜻을 갖는다). */
    const { 항목 } = 항목추가([], { ...항목입력(step), task_meta: 제출재료 });
    const e = 제출사건(항목, 'voice/a/b.m4a');
    assert.ok(e, `${step}: 봉투가 없다 — 녹음은 했는데 서버엔 안 남는다`);
    assert.equal(e.event_type, 'submission.created');
    assert.equal(e.submission.task_format, '낭독');
    assert.equal(e.payload.attempt_no, 1);
  }
});

test(`상한 밖 걸음(따라${상한 + 1})은 봉투가 없다 — 형식을 지어내지 않는다`, () => {
  const { 제출재료 } = 화면과제(서버항목(), 폴백);
  const { 항목 } = 항목추가([], { ...항목입력(`따라${상한 + 1}`), task_meta: 제출재료 });
  assert.equal(제출사건(항목, null), null);
});
