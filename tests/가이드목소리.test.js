'use strict';
/** 가이드 목소리 배치 회귀 — 「많이 넣되 우겨넣지 않기」(유호 08-25)의 기계 자리.
 *
 * 화면 회귀(`마스코트배선`)는 «어느 자리가 어느 상황인가»를 보고, 이 파일은 «그 상황에서
 * 어떤 소리가 나는가»를 본다. 둘이 갈라지면 오답 옆에서 밝은 소리가 나거나, 같은 소리가
 * 연달아 나 「또 그 소리」가 된다 — 증상이 「어쩐지 단조롭다」라 눈으로는 못 잡는 자리다.
 *
 * 🔴 08-28 캐릭터 축(몽글·까몽·마린) 반입 뒤 이 파일이 «추가로» 지키는 것 둘:
 *   ① **몽글 줄 불변** — 개명·확장이 유호님 귀 확정(08-25)을 한 톨도 안 건드렸다.
 *   ② **빈 풀은 무음** — 까몽·마린은 6상황을 다 못 채운다. 「비슷하니까」로 메우는 순간
 *      오답 옆에서 겁먹은 소리가 난다(정지선 ③④). 못 채운 자리는 조용해야 «맞다».
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const {
  캐릭터들, 소리들, 배치, 상황들, 기본캐릭터, 흔들폭, 겹침막기ms, 목소리판정,
} = require('../lib/가이드목소리.js');
const { 목소리이름 } = require('../lib/소리게이트.js');

/** 몽글 줄의 «글자째» 사본 — 유호님이 귀로 확정한 08-25 배치. 늘리는 diff 는 리뷰에 보여야 한다. */
const 몽글배치_확정판 = {
  기본: ['무', '뿌우'],
  기쁨: ['먀앙', '미유'],
  물음: ['뽀오', '뽀옹'],
  안심: ['미이', '미유우'],
  잠결: ['우웅', '무우움'],
  완료축하: ['모오옹'],
};

test('어휘 — 21종(몽글 12·까몽 5·마린 4)이 게이트 화이트리스트와 1:1 이다(사본 금지)', () => {
  assert.deepEqual(캐릭터들, ['몽글', '까몽', '마린']);
  assert.equal(Object.keys(소리들.몽글).length, 12, '몽글 12종이 아니다 — 유호 확정 08-25 판');
  assert.equal(Object.keys(소리들.까몽).length, 5, '까몽 5종이 아니다 — 08-28 셋 + 09-01 유호 픽 둘');
  assert.equal(Object.keys(소리들.마린).length, 4, '마린 4종이 아니다 — 08-28 셋 + 09-01 유호 픽 하나');
  const 자산들 = 캐릭터들.flatMap((c) => Object.values(소리들[c]));
  assert.equal(자산들.length, 21);
  assert.equal(new Set(자산들).size, 21, '자산 키가 캐릭터끼리 겹친다 — 한 파일을 둘이 쓴다');
  assert.deepEqual([...자산들].sort(), [...목소리이름].sort(),
    '배치가 아는 소리와 게이트가 허용하는 소리가 갈렸다 — 한쪽에만 있는 소리는 영원히 무음이거나 영원히 막힌다');
});

test('🔴 몽글 줄 불변 — 캐릭터 축이 08-25 확정 배치를 한 톨도 안 건드린다', () => {
  assert.equal(기본캐릭터, '몽글', '기본 캐릭터가 바뀌었다 — 캐릭터를 안 넘기는 화면 전부가 조용히 다른 소리를 낸다');
  for (const [상황, 확정줄] of Object.entries(몽글배치_확정판)) {
    assert.deepEqual(배치.몽글[상황], 확정줄, `몽글 「${상황}」 줄이 바뀌었다`);
  }
  assert.deepEqual(Object.keys(배치.몽글), Object.keys(몽글배치_확정판));
});

test('배치 — 상황 어휘가 캐릭터마다 같고, 놓인 이름은 전부 실재한다', () => {
  assert.deepEqual(상황들, ['기본', '기쁨', '물음', '안심', '잠결', '완료축하']);
  for (const 캐릭터 of 캐릭터들) {
    assert.deepEqual(Object.keys(배치[캐릭터]), 상황들,
      `${캐릭터} 의 상황 어휘가 다르다 — 화면은 캐릭터를 모르고 «자리»만 말한다(어휘가 갈리면 그 자리는 무음)`);
    for (const 상황 of 상황들) {
      for (const 소리 of 배치[캐릭터][상황]) {
        assert.ok(소리들[캐릭터][소리], `${캐릭터}·${상황} 에 없는 소리(${소리})가 배치됐다 — 그 자리는 무음이 된다`);
      }
    }
    assert.ok(배치[캐릭터].기본.length >= 1, `${캐릭터} 의 기본 자리가 비었다 — 탭조차 조용하다`);
  }
});

test('🔴 오류 자리(안심)에는 내려앉는 소리만 — 밝은 소리도, 겁먹은 소리도 안 놓인다', () => {
  /* 기죽는 반응 금지 확정의 소리판. 밝은 자리의 소리가 이 줄에 끼면 오답 옆에서 밝게 들리고,
     까몽의 「히익」(겁먹음)이 끼면 그게 곧 기죽는 반응이다 — 그래서 까몽 안심은 «빈 채»가 맞다. */
  const 밝은것 = new Set([...배치.몽글.기쁨, ...배치.몽글.물음]);
  for (const 소리 of 배치.몽글.안심) {
    assert.ok(!밝은것.has(소리), `안심 자리에 밝은 소리(${소리})가 놓였다`);
  }
  assert.ok(배치.몽글.안심.length >= 2, '안심 후보가 하나뿐이면 오류가 반복될 때 같은 소리만 난다');
  /* 09-01 유호 픽으로 두 안심 자리가 «내려앉는 소리»를 얻었다 — 채워진 뒤에도 ③은 그대로 잰다. */
  assert.ok(배치.까몽.안심.length >= 1, '까몽 안심 자리가 도로 비었다 — 유호 픽(그르렁 b)이 사라졌다');
  assert.ok(!배치.까몽.안심.includes('히익'), '까몽 안심에 히익(겁먹음)이 끼었다 — 기죽는 반응 금지(③)');
  assert.ok(!배치.까몽.안심.includes('베에'), '까몽 안심에 베에(약 올리기)가 끼었다 — 오답 옆에서 약 올린다');
  assert.ok(배치.마린.안심.length >= 1, '마린 안심 자리가 도로 비었다 — 유호 픽(링 감쇠 b)이 사라졌다');
  assert.ok(!배치.마린.안심.includes('몰래기쁨'), '마린 안심에 몰래기쁨(오름형)이 끼었다 — 하강만(③)');
});

test('🚫 빈 풀은 «무음»이다 — 아는 상황인데 소리가 없으면 조용히 넘어간다(다른 소리로 안 메운다)', () => {
  const 지금 = 9_000_000;
  const 빈자리 = [
    ['까몽', '물음'], ['까몽', '잠결'],
    ['마린', '물음'], ['마린', '잠결'],
  ];
  for (const [캐릭터, 상황] of 빈자리) {
    assert.deepEqual(배치[캐릭터][상황], [], `픽스처가 낡았다 — ${캐릭터}·${상황} 이 이제 차 있다`);
    const 답 = 목소리판정({ 캐릭터, 상황, 지금, 마지막: 0 });
    assert.equal(답.낼까, false, `${캐릭터}·${상황}: 빈 풀인데 소리가 났다 — 기본 소리로 메웠다(정지선 ③④)`);
    assert.equal(답.소리, undefined);
    assert.match(답.사유, /빈 풀/);
  }
});

test('🚫 빈 풀 ≠ 오타 — 모르는 상황은 «기본»으로 떨어지고, 아는 빈 상황은 조용하다', () => {
  const 지금 = 9_100_000;
  for (const 캐릭터 of 캐릭터들) {
    const 오타 = 목소리판정({ 캐릭터, 상황: '없는상황', 지금, 마지막: 0 });
    assert.equal(오타.낼까, true, `${캐릭터}: 오타 때문에 입을 닫았다 — 침묵은 게이트만 정한다`);
    assert.ok(배치[캐릭터].기본.includes(오타.소리));
  }
  /* 이 둘이 같은 길로 흐르면(`줄[상황] || 줄.기본`) 까몽 물음에서 «베에»가 난다. */
  assert.equal(목소리판정({ 캐릭터: '까몽', 상황: '물음', 지금, 마지막: 0 }).낼까, false);
});

test('모르는 캐릭터는 «무음»이 아니라 «몽글»이다 (오타가 침묵을 정하지 않는다)', () => {
  const 답 = 목소리판정({ 캐릭터: '없는캐릭터', 상황: '기본', 지금: 9_200_000, 마지막: 0 });
  assert.equal(답.낼까, true);
  assert.ok(배치.몽글.기본.includes(답.소리));
  /* 캐릭터를 «안 넘기면» 반입 전과 100% 같은 동작이어야 한다 — 지금 화면들이 전부 그 길이다. */
  const 안넘김 = 목소리판정({ 상황: '안심', 지금: 9_200_000, 마지막: 0, 고르기: 0 });
  const 몽글명시 = 목소리판정({ 캐릭터: '몽글', 상황: '안심', 지금: 9_200_000, 마지막: 0, 고르기: 0 });
  assert.deepEqual(안넘김, 몽글명시, '캐릭터를 안 넘긴 판정이 몽글과 달라졌다 — 기존 화면의 소리가 바뀐다');
});

test('다양함 ② — 같은 상황에서 직전 소리를 피한다(연속 반복 차단)', () => {
  const 지금 = 1_000_000;
  for (const 캐릭터 of 캐릭터들) {
    for (const 상황 of 상황들) {
      if (배치[캐릭터][상황].length < 2) continue;      // 완료축하·까몽·마린은 후보가 하나라 반복이 없다
      for (const 직전 of 배치[캐릭터][상황]) {
        for (const 고르기 of [0, 0.49, 0.99]) {
          const 답 = 목소리판정({ 캐릭터, 상황, 지금, 마지막: 0, 직전소리: 직전, 고르기 });
          assert.notEqual(답.소리, 직전, `${캐릭터}·${상황}: 직전(${직전})과 같은 소리가 또 났다`);
        }
      }
    }
  }
});

test('다양함 ② — 난수를 흔들면 상황 안 후보가 «전부» 나온다(한쪽만 쏠리지 않는다)', () => {
  const 지금 = 2_000_000;
  for (const 캐릭터 of 캐릭터들) {
    for (const 상황 of 상황들) {
      if (!배치[캐릭터][상황].length) continue;   // 빈 풀은 위 시험이 «무음»으로 따로 문다
      const 나온것 = new Set();
      for (let i = 0; i < 40; i++) {
        나온것.add(목소리판정({ 캐릭터, 상황, 지금, 마지막: 0, 고르기: i / 40 }).소리);
      }
      assert.equal(나온것.size, 배치[캐릭터][상황].length,
        `${캐릭터}·${상황}: 후보 ${배치[캐릭터][상황].length}종 중 ${나온것.size}종만 난다 — 나머지는 죽은 자산이다`);
    }
  }
});

test('다양함 ③ — 미세 변주는 매번 다르고 폭은 ±3% 를 안 넘는다', () => {
  const 지금 = 3_000_000;
  const 속도 = (흔들) => 목소리판정({ 상황: '기본', 지금, 마지막: 0, 흔들 }).속도;
  assert.equal(속도(0.5), 1, '가운데 난수인데 속도가 1 이 아니다');
  assert.ok(Math.abs(속도(0) - (1 - 흔들폭)) < 1e-6);
  assert.ok(Math.abs(속도(1) - (1 + 흔들폭)) < 1e-6);
  assert.ok(흔들폭 <= 0.05, '변주 폭이 5% 를 넘는다 — 같은 소리로 안 들린다');
});

test('🚫 겹침막기 — 가장 긴 소리보다 길다(꼬리까지 안 포갠다)', () => {
  const 지금 = 4_000_000;
  assert.equal(목소리판정({ 상황: '기본', 지금, 마지막: 지금 - 100 }).낼까, false);
  assert.equal(목소리판정({ 상황: '기본', 지금, 마지막: 지금 - (겹침막기ms - 1) }).낼까, false);
  assert.equal(목소리판정({ 상황: '기본', 지금, 마지막: 지금 - 겹침막기ms }).낼까, true);
  /* 가장 긴 소리 = **마린 완수 680ms**(08-28 반입으로 몽글 모오옹 669ms 를 넘어섰다).
     이보다 짧으면 두 소리가 포개져 웅얼거린다 — 값의 정본은 as `docs/디자인_토큰.json` 「사운드」. */
  assert.ok(겹침막기ms > 680, `겹침막기(${겹침막기ms})가 가장 긴 소리(마린 완수 680ms)보다 짧다`);
  assert.equal(목소리판정({ 상황: '기쁨', 지금, 마지막: 지금 - 50 }).낼까, false,
    '상황만 바꿔 겹침을 우회했다');
  assert.equal(목소리판정({ 캐릭터: '마린', 상황: '기본', 지금, 마지막: 지금 - 50 }).낼까, false,
    '캐릭터만 바꿔 겹침을 우회했다 — 겹침은 «귀» 기준이라 누가 내든 하나다');
});

test('예비 소리는 어떤 배치에도 안 쓴다 — 쓰이면 그날 배치에 등재한다', () => {
  /* 예비 둘 = 몽글 「무우」(새 상황용) · 까몽 「히익」(놀람/겁 — 상황 어휘 여섯에 그 자리가 없다).
     둘 다 «자산은 있고 배치엔 없는» 상태다: 소리는 반입돼 있으니 상황이 서는 날 한 줄이면 열린다. */
  const 예비 = [['몽글', '무우'], ['까몽', '히익']];
  for (const [캐릭터, 이름] of 예비) {
    const 쓰인것 = new Set(Object.values(배치[캐릭터]).flat());
    assert.ok(!쓰인것.has(이름), `${캐릭터} 예비(${이름})가 조용히 배치에 들어갔다 — 어느 상황인지 적어야 한다`);
    assert.ok(소리들[캐릭터][이름], `${캐릭터} 예비 자산(${이름})이 사라졌다`);
  }
  /* 예비를 뺀 나머지는 전부 어딘가에 놓여 있어야 한다 — 안 놓인 소리는 «죽은 자산»이다. */
  const 예비키 = new Set(예비.map(([c, n]) => 소리들[c][n]));
  for (const 캐릭터 of 캐릭터들) {
    for (const [이름, 키] of Object.entries(소리들[캐릭터])) {
      if (예비키.has(키)) continue;
      const 쓰인것 = new Set(Object.values(배치[캐릭터]).flat());
      assert.ok(쓰인것.has(이름), `${캐릭터}·${이름} 이 어느 상황에도 안 놓였다 — 예비면 위 목록에 적고, 아니면 배치한다`);
    }
  }
});
