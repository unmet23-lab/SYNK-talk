/* NPC 연출 회귀 — 규격 3 의 판정층(lib/NPC연출.js).
 *
 * ■ 왜 자산·화면 없이 서 있나 (08-24)
 *   유호님이 배지 «형상»을 반려하셨고(「다 똑같이 생겼다」 · 트랙 §2-G), 재설계 전까지 자산도
 *   화면 배선도 안 든다. 그런데 규격 3 이 정한 **판정**(상태 3단이 언제 넘어가나 · 어느 자리에서만
 *   바뀌나 · 어휘가 무엇인가)은 형상과 **무관하다** — 몸을 다시 빚어도 그대로 산다.
 *   그래서 판정층만 먼저 세우고 여기서 문다. 형상이 서는 날 화면·자산이 이 위에 얹힌다.
 *
 * ■ 규격 정본 = SYNK-appsscript docs/미니게임_게임층_설계.md §4 규격 3
 *   · 상태 3단은 계열 공통: 평온 → 기울어짐 → 돌아섬(발주서 G3 §4-3 「팔짱 → 시계 보기 → 돌아섬」)
 *   · 실시간 전환은 G3 하나뿐 — 나머지는 «상태 전이 자리»에서만(검사 ① 동시 1개 장치)
 *   · 문턱은 판마다 고정 상수 · 상수 1곳 · 회차 간 변동 0
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { 역들, 상태들, 역게임, 압박문턱, 압박상태, 전이상태, 컷이름 } = require('../lib/NPC연출.js');

/** 그 판의 녹음 상한(ms) — 문턱이 «비율»이라 판정은 상한과 짝으로만 성립한다. */
const 상한 = 30 * 1000;

test('어휘 — 확정 4역 × 상태 4(압박 3단 + 결과 1)', () => {
  assert.deepEqual([...역들], ['prof', 'lead', 'boss', 'insp'], '역이 바뀌었다 — 게임층 설계 §4 확정 4역이다');
  assert.deepEqual([...상태들], ['calm', 'lean', 'back', 'win']);
  assert.deepEqual(역게임, { prof: 'G1', lead: 'G2', boss: 'G3', insp: 'G4' },
    '역↔게임 지도가 갈렸다 — 자산 반입 대장과 화면 배선이 이 표 하나를 본다');
});

test('압박 3단 — 지나간 «비율»에 따라 평온 → 기울어짐 → 돌아섬 (G3 전용 축)', () => {
  const 때 = (비율) => Math.round(상한 * 비율);
  assert.equal(압박상태(1, 상한), 'calm');
  assert.equal(압박상태(때(압박문턱.기울어짐) - 1, 상한), 'calm');
  assert.equal(압박상태(때(압박문턱.기울어짐), 상한), 'lean');
  assert.equal(압박상태(때(압박문턱.돌아섬) - 1, 상한), 'lean');
  assert.equal(압박상태(때(압박문턱.돌아섬), 상한), 'back');
  assert.equal(압박상태(상한 * 3, 상한), 'back', '끝까지 가도 돌아섬이 마지막 단이다');
});

test('🔑 문턱이 «비율»이라 상한이 무엇이든 3단이 전부 선다', () => {
  /* 초로 두면 상한이 바뀌는 날 한 단이 조용히 0회 노출이 된다 — 첫 판이 정확히 그랬다
     (상한 30초에 돌아섬 문턱 30초). 그래서 축을 비율로 잡았고, 여기서 그 성질을 못박는다. */
  for (const 초 of [12, 30, 60, 90]) {
    const 단들 = [0.1, 0.5, 0.9].map((r) => 압박상태(초 * 1000 * r, 초 * 1000));
    assert.deepEqual(단들, ['calm', 'lean', 'back'], `상한 ${초}초에서 3단이 다 안 선다`);
  }
});

test('압박 — 시계는 뒤로 안 가고, «못 잼»을 압박으로 번역하지 않는다', () => {
  assert.equal(압박상태(-5000, 상한), 'calm');
  assert.equal(압박상태(NaN, 상한), 'calm');
  assert.equal(압박상태(undefined, 상한), 'calm');
  assert.equal(압박상태(9999, 0), 'calm', '상한 0(못 잼)이 돌아섬으로 읽히면 안 된다');
  assert.equal(압박상태(9999, undefined), 'calm');
});

test('압박 문턱 — 오름차순 비율이고 1 미만이다 (규격 3 「상수 1곳」)', () => {
  assert.ok(압박문턱.기울어짐 > 0, '첫 단 문턱이 0 이하면 판이 시작하자마자 기울어진다');
  assert.ok(압박문턱.돌아섬 > 압박문턱.기울어짐, '문턱이 뒤집혔다 — 3단이 2단이 된다');
  assert.ok(압박문턱.돌아섬 < 1, '돌아섬이 상한 뒤면 그 단은 원리상 0회 노출이다');
});

test('전이 자리 — 시작은 평온 · 완료는 흡족 · 실패는 돌아섬', () => {
  assert.equal(전이상태('시작'), 'calm');
  assert.equal(전이상태('완료'), 'win');
  assert.equal(전이상태('실패'), 'back');
  assert.equal(전이상태('모르는자리'), 'calm', '모르는 자리는 «가장 조용한 값»으로 내려간다');
});

test('컷 이름 — 어휘 밖이면 조용히 기본으로 안 내려가고 던진다 (옛 몽글 사고의 규율)', () => {
  assert.equal(컷이름('boss', 'win'), 'boss-win');
  assert.throws(() => 컷이름('king', 'calm'), /정본에 없다/);
  assert.throws(() => 컷이름('boss', '화남'), /정본에 없다/);
  assert.throws(() => 컷이름(undefined, undefined), /정본에 없다/);
});
