/* 마스코트 강사판 발화 회귀 — 「표 밖 발화 금지」·상한·문구 규격의 기계 자리.
 *
 * ■ 무엇을 지키나 (lib/마스코트강사말 · 말할순간 v1.1 §2 ㉮ = T1~T5·T10)
 *   ① 닫힌 목록 — 순간 키는 여섯뿐이고, 목록 밖 키는 빈 풀(침묵)이다.
 *   ② 상한 판정 — 주 1회·하루 1회·카드당 1회·기기당 1회가 «키»로 선다(같은 키 재발화 0).
 *   ③ 문구 규격 — 남과의 비교·평가어·점수등급 0 (tests/lib/금지패턴.js 재사용).
 *      ⚠ 「숫자」 축은 **안 건다** — 강사판 ㉮의 정의가 숫자·상태 문장이다(배선 §2 ·
 *      표 예시 「이번 주 5건」). 학생판 꼬리 규칙을 그대로 걸면 이 층의 존재 이유가 죽는다.
 *   ④ 화면 사본 0 — 강사화면에 문구가 한 글자도 없다(문구 정본은 lib 하나).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 강사순간, 강사문구, 강사순간고르기, 세는말 } = require('../lib/마스코트강사말.js');
const { 금지패턴 } = require('./lib/금지패턴.js');
const { 코드만 } = require('./lib/소스검사.js');

const ROOT = path.join(__dirname, '..');
const 소스 = (상대) => fs.readFileSync(path.join(ROOT, ...상대.split('/')), 'utf8');

const 셈 = (덮기) => ({ 남음: 3, 판정됨: 2, 막힘: 0, 전체: 5, ...덮기 });
const 신호 = (덮기) => ({
  셈: 셈(), 주: '2026-W33', 요일: 2, 오늘: '2026-08-14', 막힌카드: [], ...덮기,
});

test('① 닫힌 목록 — 순간은 T1~T5·T10 여섯뿐, 밖의 키는 침묵(빈 풀)이다', () => {
  assert.deepEqual([...강사순간], ['T1', 'T2', 'T3', 'T4', 'T5', 'T10']);
  for (const 밖 of ['T6', 'T7', 'T18', 'S1', 'P1', '']) {
    assert.equal(강사문구(밖, 셈()).length, 0, `표 밖 키 ${밖 || '(빈)'} 가 문구를 낸다 — 표 밖 발화다`);
  }
});

test('① 여섯 순간 전부 문구가 서고, 전부 얼려져 있다', () => {
  for (const 순간 of 강사순간) {
    const 풀 = 강사문구(순간, 셈({ 막힘: 1 }));
    assert.ok(풀.length >= 1, `${순간} 의 풀이 비었다`);
    assert.ok(Object.isFrozen(풀), `${순간} 풀이 안 얼려졌다 — 화면이 문구를 밀어 넣을 수 있다`);
    for (const 글 of 풀) assert.equal(typeof 글, 'string');
  }
});

test('③ 문구 규격 — 비교·평가어·점수등급 0 (숫자 축은 ㉮ 정의라 제외)', () => {
  const 걸축 = 금지패턴.filter((p) => p.이름 !== '숫자');
  const 모든셈 = [셈(), 셈({ 남음: 1, 판정됨: 4 }), 셈({ 막힘: 1 }), 셈({ 막힘: 3 })];
  for (const 순간 of 강사순간) {
    for (const 한셈 of 모든셈) {
      for (const 글 of 강사문구(순간, 한셈)) {
        for (const { 이름, 정규식 } of 걸축) {
          assert.doesNotMatch(글, 정규식, `${순간} 「${글}」 에 ${이름} — 강사판도 사실성 규격을 승계한다`);
        }
      }
    }
  }
});

test('세는말 — 1~10 은 세는 말, 밖은 숫자 그대로(지어내지 않는다)', () => {
  assert.equal(세는말(5), '다섯');
  assert.equal(세는말(1), '한');
  assert.equal(세는말(11), '11');
  assert.equal(세는말(-1), '-1');
});

test('② T10 — 이 기기의 첫 방문이 모든 것에 앞서고, 기기당 1회다', () => {
  const 고른 = 강사순간고르기('열림', 신호(), {});
  assert.equal(고른.순간, 'T10');
  assert.equal(고른.키, 'T10');
  const 다음 = 강사순간고르기('열림', 신호({ 셈: 셈({ 판정됨: 0, 남음: 5 }) }), { T10: '2026-08-01' });
  assert.notEqual(다음 && 다음.순간, 'T10', 'T10 이 두 번 나온다 — 기기당 1회가 깨졌다');
});

test('② T1 — 이번 주 첫 만남(판정 0) · 주 1회 · 표본 0이면 침묵', () => {
  const 기록 = { T10: 'x' };
  const 고른 = 강사순간고르기('열림', 신호({ 셈: 셈({ 판정됨: 0, 남음: 5 }) }), 기록);
  assert.equal(고른.순간, 'T1');
  assert.equal(고른.키, 'T1:2026-W33');
  assert.equal(
    강사순간고르기('열림', 신호({ 셈: 셈({ 판정됨: 0, 남음: 5 }) }), { ...기록, 'T1:2026-W33': 'x' }),
    null, '같은 주에 T1 이 또 나온다',
  );
  assert.equal(
    강사순간고르기('열림', 신호({ 셈: 셈({ 전체: 0, 남음: 0, 판정됨: 0 }) }), 기록),
    null, '표본 0 인 주에 말을 건다 — 말할 사실이 없다(빈 카드가 말한다)',
  );
});

test('② T2 — 하다 만 재접속 · 하루 1회', () => {
  const 기록 = { T10: 'x' };
  const 고른 = 강사순간고르기('열림', 신호(), 기록);
  assert.equal(고른.순간, 'T2');
  assert.equal(고른.키, 'T2:2026-08-14');
  assert.equal(
    강사순간고르기('열림', 신호(), { ...기록, 'T2:2026-08-14': 'x' }),
    null, '같은 날 T2 가 또 나온다',
  );
});

test('② T4 — 주 후반(목요일부터)·판정 0·T1 이 이미 나간 주에만 · 무시하면 그 주 침묵', () => {
  const 기록 = { T10: 'x', 'T1:2026-W33': 'x' };
  const 판정0 = 셈({ 판정됨: 0, 남음: 5 });
  assert.equal(강사순간고르기('열림', 신호({ 셈: 판정0, 요일: 3 }), 기록), null, '수요일에 재촉한다');
  const 고른 = 강사순간고르기('열림', 신호({ 셈: 판정0, 요일: 4 }), 기록);
  assert.equal(고른.순간, 'T4');
  assert.equal(
    강사순간고르기('열림', 신호({ 셈: 판정0, 요일: 5 }), { ...기록, 'T4:2026-W33': 'x' }),
    null, 'T4 가 같은 주에 반복된다 — 재촉은 한 번뿐(무시=그 주 침묵)',
  );
});

test('② T5 — 막힌 카드당 1회 · 다른 줄이 조용할 때만', () => {
  const 기록 = { T10: 'x', 'T1:2026-W33': 'x', 'T2:2026-08-14': 'x' };
  const 막힘셈 = 셈({ 막힘: 1, 남음: 2 });
  const 고른 = 강사순간고르기('열림', 신호({ 셈: 막힘셈, 막힌카드: ['c9'] }), 기록);
  assert.equal(고른.순간, 'T5');
  assert.equal(고른.키, 'T5:c9');
  assert.equal(
    강사순간고르기('열림', 신호({ 셈: 막힘셈, 막힌카드: ['c9'] }), { ...기록, 'T5:c9': 'x' }),
    null, '같은 막힌 카드에 T5 가 또 나온다',
  );
});

test('② T3 — 「전부 완료한 순간」(계기=완료)에만 · 주 1회 · 열림 계기에서는 안 나온다', () => {
  const 기록 = { T10: 'x' };
  const 끝셈 = 셈({ 남음: 0, 판정됨: 5 });
  const 고른 = 강사순간고르기('완료', 신호({ 셈: 끝셈 }), 기록);
  assert.equal(고른.순간, 'T3');
  assert.equal(고른.키, 'T3:2026-W33');
  assert.equal(
    강사순간고르기('완료', 신호({ 셈: 끝셈 }), { ...기록, 'T3:2026-W33': 'x' }),
    null, 'T3 가 같은 주에 반복된다',
  );
  assert.equal(
    강사순간고르기('열림', 신호({ 셈: 끝셈 }), 기록),
    null, '다 끝난 주의 재방문에 말을 건다 — 「이번 주 끝」 카드가 이미 말하고 있다',
  );
});

test('④ 화면 사본 0 — 강사화면에는 문구가 없고, lib 판정만 부른다 (등록층)', () => {
  const 화면 = 코드만(소스('src/강사화면.js'));
  assert.match(화면, /강사순간고르기/, '강사화면이 lib 판정을 안 부른다 — 문구를 화면이 짓기 시작하는 자리다');
  const 모든풀 = 강사순간.flatMap((순간) => [...강사문구(순간, 셈({ 막힘: 1 }))]);
  for (const 글 of 모든풀) {
    const 앞토막 = 글.split('—')[0].trim().slice(0, 10);
    assert.ok(!화면.includes(앞토막), `강사화면에 문구 사본 「${앞토막}…」 — 정본은 lib 하나다`);
  }
  /* 로그아웃 귀속 — 발화 기록이 안 비워지면 다음 사람이 첫 안내(T10)를 영영 못 받는다. */
  const 저장 = 코드만(소스('src/저장.js'));
  assert.match(저장, /기기비우기[\s\S]{0,700}마스코트기록쓰기\(\{\}\)/, '기기비우기에서 마스코트 기록이 안 비워진다');
});
