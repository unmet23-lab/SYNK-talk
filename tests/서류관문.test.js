/* G4 채점기 회귀 — `lib/서류관문.js` (발주_게임모듈.md §G4 §6-2 ⓑ · §9-1 ⓐ).
 *
 * ■ 무엇을 지키나
 *   ① 정규화는 **정확히 넷만** — NFC·앞뒤 공백·연속 공백 1칸·끝부호. 조사·활용·띄어쓰기
 *      보존이 급소다: 하나라도 접히면 「에」와 「에서」가 같은 답이 되어 측정이 죽는다.
 *   ② 3갈래 — 맞음(오류없음)/축오답(재는축)/모름(태그 키 «부재»). 모름이 오답으로 접히면
 *      살아있는 이형태가 거짓 라벨로 굳는다(§9-1 — g4t04 b3 「하고」가 그 실물).
 *   ③ 결정성·동결·못 쓸 재료 null.
 *   ④ 전수 — 실팩 빈칸 15벌의 정답·오답 전 원소가 제 갈래로 떨어진다(분모 명시).
 *   ⚠ 부분일치 표기 금지는 `tests/멘탈게이지.test.js` 가 소스 전문으로 검사한다(목록에 등재).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { 채점기판본, 정규화, 채점 } = require('../lib/서류관문.js');
const 팩 = require('../contents/서류관문문항.js');

const 표본빈칸 = 팩.문항들[0].빈칸[0]; // g4t01 b1 — 정답 [에서] · 오답 [에, 로, 으로]

test('채점기판본 — 규칙이 바뀌는 커밋에서만 오른다(스냅샷 재현의 담보)', () => {
  assert.equal(채점기판본, 'g4채점.v1');
});

test('정규화 넷만 — NFC·trim·연속 공백 1칸·끝부호 제거', () => {
  assert.equal(정규화('에서'), '에서');
  assert.equal(정규화('  에서  '), '에서', 'trim');
  assert.equal(정규화('에서.'), '에서', '끝부호(마침표)');
  assert.equal(정규화('오겠습니다!'), '오겠습니다', '끝부호(느낌표)');
  assert.equal(정규화('주세요?'), '주세요', '끝부호(물음표) — 빈칸 답은 끝부호가 뜻을 안 가른다');
  assert.equal(정규화('에서 .'), '에서', '부호 앞 공백까지 접는다');
  assert.equal(정규화('있습니다…'), '있습니다');
  assert.equal(정규화('가'.normalize('NFD')), '가', 'NFC — 자모 분해형(모바일 IME)이 같은 글자다');
  assert.equal(정규화('확인  합니다'), '확인 합니다', '연속 공백은 1칸으로 — 없애지는 않는다');
  for (const 아닌것 of [null, undefined, 7, ['에서'], {}]) {
    assert.equal(정규화(아닌것), null, String(아닌것));
  }
});

test('🔴 정규화가 보존하는 것 — 조사·활용·띄어쓰기(이 모듈이 «재는» 축)', () => {
  assert.notEqual(정규화('에'), 정규화('에서'), '조사가 접히면 측정이 죽는다');
  assert.notEqual(정규화('올게요'), 정규화('오겠습니다'), '활용');
  assert.notEqual(정규화('확인 합니다'), 정규화('확인합니다'), '띄어쓰기 오류는 산 신호다');
  assert.equal(정규화('주 세요.'), '주 세요', '내부 공백은 남는다 — 지우면 띄어쓰기 축이 사라진다');
});

test('3갈래 — 맞음(오류없음)·축오답(재는축)·모름(태그 키 부재)', () => {
  assert.deepEqual(채점(표본빈칸, '에서'), { 판정: '맞음', 오류태그: '오류없음' });
  assert.deepEqual(채점(표본빈칸, ' 에서. '), { 판정: '맞음', 오류태그: '오류없음' },
    '정규화를 지나 판정한다 — 끝부호·공백이 정오를 못 가른다');
  assert.deepEqual(채점(표본빈칸, '에'), { 판정: '축오답', 오류태그: '조사:처소(에·에서)' },
    '태그는 그 빈칸의 재는축이다 — 같은 축의 알려진 오답만 담겨 정직하다');
  const 모름 = 채점(표본빈칸, '한테서');
  assert.equal(모름.판정, '모름');
  assert.equal('오류태그' in 모름, false,
    '🔴 태그 0 은 빈 문자열이 아니라 키 «부재»다(§6-8 규칙 1) — 감사 레인 몫');
});

test('🔴 g4t04 b3 「하고」 = 모름 — 격이 다른 살아있는 형태를 오답으로 적지 않는다(§9-1)', () => {
  const 빈칸 = 팩.문항들[3].빈칸[2];
  assert.equal(빈칸.빈칸id, 'b3', '표본이 그 자리다');
  assert.deepEqual(채점(빈칸, '하고'), { 판정: '모름' },
    '「여권하고 등록증」은 살아있는 말이다 — 「틀렸다」로 적으면 엔진이 거짓을 배운다');
});

test('빈 입력 = 모름 — 닫힌 두 집합 밖(「모르겠어요」 skipped 는 화면 몫의 별개 통로)', () => {
  assert.deepEqual(채점(표본빈칸, ''), { 판정: '모름' });
  assert.deepEqual(채점(표본빈칸, '   '), { 판정: '모름' });
});

test('결정성·동결 — 같은 재료 = 같은 판정 · 산출은 얼어 나간다', () => {
  const a = 채점(표본빈칸, '에');
  assert.deepEqual(채점(표본빈칸, '에'), a);
  assert.ok(Object.isFrozen(a));
  assert.throws(() => { a.판정 = '맞음'; }, TypeError);
});

test('못 쓸 재료는 null — 반쪽 판정을 지어내지 않는다', () => {
  assert.equal(채점(null, '에서'), null);
  assert.equal(채점([], '에서'), null);
  assert.equal(채점({ 재는축: '조사:기타' }, '에서'), null, '집합이 없다');
  assert.equal(채점({ ...표본빈칸, 정답집합: [] }, '에서'), null, '빈 정답집합');
  assert.equal(채점({ ...표본빈칸, 오답집합: '에' }, '에서'), null, '배열이 아니다');
  assert.equal(채점({ ...표본빈칸, 재는축: ' ' }, '에서'), null, '축이 비었다');
  assert.equal(채점(표본빈칸, null), null, '원문이 문자열이 아니다');
  assert.equal(채점(표본빈칸, 7), null);
});

test('전수 — 실팩 빈칸 15벌: 정답 전 원소 = 맞음 · 오답 전 원소 = 축오답 · 헛말 = 모름', () => {
  let 빈칸수 = 0;
  let 정답수 = 0;
  let 오답수 = 0;
  for (const 관문 of 팩.문항들) {
    for (const 빈칸 of 관문.빈칸) {
      const 길 = `${관문.관문id}.${빈칸.빈칸id}`;
      for (const 값 of 빈칸.정답집합) {
        assert.deepEqual(채점(빈칸, 값), { 판정: '맞음', 오류태그: '오류없음' }, `${길} 「${값}」`);
        정답수 += 1;
      }
      for (const 값 of 빈칸.오답집합) {
        assert.deepEqual(채점(빈칸, 값), { 판정: '축오답', 오류태그: 빈칸.재는축 }, `${길} 「${값}」`);
        오답수 += 1;
      }
      assert.equal(채점(빈칸, 'ㅁㄴㅇㄹ').판정, '모름', 길);
      빈칸수 += 1;
    }
  }
  assert.equal(빈칸수, 15, '분모 — 빈칸 전수');
  assert.ok(정답수 >= 15 && 오답수 >= 45, `집합 원소 전수(정답 ${정답수}·오답 ${오답수})`);
});
