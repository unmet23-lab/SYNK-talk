/* 라디오 시즌 달력층 회귀 — 달력·취약 축·폴백을 «값»으로 잰다(발전 트랙 ⑨ · 유호 확정 08-14). */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');

const { 표본하한 } = require('../lib/라디오편성.js');
const { 시즌판, 진입기본, 시즌판정, 집중축, 시즌라운드선정 } = require('../lib/라디오시즌.js');

test('시즌판정 — 오늘 형식 불량은 던진다(조용한 시즌 꺼짐이 최악의 증상이라 입구에서 막는다)', () => {
  assert.throws(() => 시즌판정({ 오늘: '2026-8-14', 시험일들: [] }), TypeError);
  assert.throws(() => 시즌판정({ 오늘: undefined, 시험일들: [] }), TypeError);
  assert.throws(() => 시즌판정({ 오늘: '2026-08-14', 시험일들: [], 진입일수: -1 }), TypeError);
});

test('시즌판정 — 못 읽는 시험일은 버리지 않고 «무시»로 센다(F207 — 오타는 로그로 드러나야 한다)', () => {
  const r = 시즌판정({ 오늘: '2026-08-14', 시험일들: ['2026.10.11', '2026-10-11', null] });
  assert.deepEqual(r.무시, ['2026.10.11', null]);
  assert.deepEqual(r.시즌, null); // D-58 — 진입 밖
});

test('시즌판정 — 경계: D-진입일수는 시즌, D-(진입일수+1)은 아직', () => {
  const 시험 = ['2026-08-28']; // 오늘 08-14 기준 D-14
  assert.equal(시즌판정({ 오늘: '2026-08-14', 시험일들: 시험 }).시즌.디데이, 진입기본);
  assert.equal(시즌판정({ 오늘: '2026-08-13', 시험일들: 시험 }).시즌, null); // D-15
  assert.equal(시즌판정({ 오늘: '2026-08-28', 시험일들: 시험 }).시즌.디데이, 0); // 시험 당일
});

test('시즌판정 — 지난 시험은 건너뛰고 다가오는 첫 시험만 본다', () => {
  const r = 시즌판정({ 오늘: '2026-08-14', 시험일들: ['2026-04-12', '2026-08-20', '2026-10-11'] });
  assert.deepEqual(r.시즌, { 시험일: '2026-08-20', 디데이: 6 });
});

test('집중축 — 표본하한 미만·오답 0 제외, 오답률 내림차순, 동률은 id 사전순, 상한 절단', () => {
  const 요약 = {
    d: { 응답: 표본하한, 오답: 2 },            // 0.4
    a: { 응답: 10, 오답: 6 },                  // 0.6
    c: { 응답: 10, 오답: 6 },                  // 0.6 — a 와 동률 → 사전순으로 a 먼저
    소표본: { 응답: 표본하한 - 1, 오답: 4 },    // 하한 미만 — 제외
    무오답: { 응답: 20, 오답: 0 },             // 기울일 이유 없음 — 제외
    불량: { 응답: 3, 오답: 9 },                // 오답 > 응답 — 제외
  };
  assert.deepEqual(집중축({ 승격요약: 요약 }), ['a', 'c', 'd']);
  assert.deepEqual(집중축({ 승격요약: 요약, 상한: 2 }), ['a', 'c']);
  assert.throws(() => 집중축({ 승격요약: 요약, 상한: 0 }), TypeError);
  assert.deepEqual(집중축({ 승격요약: {} }), []);
});

/* ── 시즌라운드선정 — 폴백·우선순위까지 값으로 ─────────────────────────── */
const 팩 = [
  { 문항id: 'q약점', skill_ids: ['s약'] },
  { 문항id: 'q평소1', skill_ids: ['s평'] },
  { 문항id: 'q평소2', skill_ids: ['s평'] },
];
/* s평 은 «무오답»이라 집중축에 안 든다 — 오답이 1이라도 있으면 상한 3 안에 같이 들어와
 * 한정이 안 좁혀진다(첫 실행이 그걸 잡았다: 축이 ['s약','s평'] 로 나와 폴백 검사가 헛돌았다). */
const 약점요약 = { s약: { 응답: 10, 오답: 8 }, s평: { 응답: 10, 오답: 0 } };
const 공통 = { 문항들: 팩, 노출수: {}, 승격요약: 약점요약, 씨앗: 'ch1:t1', 시험일들: ['2026-08-20'] };

test('시즌 중이면 취약 축으로 한정된다 — 씨앗이 무엇이든 약점 문항 하나뿐', () => {
  const r = 시즌라운드선정({ ...공통, 오늘: '2026-08-14' });
  assert.equal(r.사유, '시즌적용');
  assert.deepEqual(r.시즌축한정, ['s약']);
  assert.equal(r.문항id, 'q약점');
  assert.equal(r.시즌판, 시즌판);
  assert.deepEqual(r.시즌, { 시험일: '2026-08-20', 디데이: 6 });
});

test('시즌 밖이면 평소 편성 그대로 — 사유가 남는다', () => {
  const r = 시즌라운드선정({ ...공통, 오늘: '2026-06-01' });
  assert.equal(r.사유, '시즌아님');
  assert.equal(r.시즌축한정, null);
  assert.ok(r.문항id, '평소 편성이 결번이 됐다');
});

test('재도전 짝이 시즌보다 세다 — 부르는 쪽의 축한정을 시즌이 덮지 않는다', () => {
  const r = 시즌라운드선정({ ...공통, 오늘: '2026-08-14', 축한정: ['s평'], 제외: ['q평소1'] });
  assert.equal(r.사유, '재도전우선');
  assert.equal(r.시즌축한정, null);
  assert.equal(r.문항id, 'q평소2'); // 같은 skill(s평) 다른 문항 — 재도전 계약 그대로
});

test('시즌인데 표본이 마르면 한정하지 않는다 — 좁혀서 결번내는 쪽이 더 나쁘다', () => {
  const r = 시즌라운드선정({ ...공통, 오늘: '2026-08-14', 승격요약: { s약: { 응답: 표본하한 - 1, 오답: 3 } } });
  assert.equal(r.사유, '표본부족');
  assert.equal(r.시즌축한정, null);
  assert.ok(r.문항id);
});

test('시즌 축 문항이 팩(제외 반영)에 없으면 평소로 폴백 — 결번 대신 사유를 남긴다', () => {
  const r = 시즌라운드선정({ ...공통, 오늘: '2026-08-14', 제외: ['q약점'] });
  assert.equal(r.사유, '시즌팩없음→평소');
  assert.equal(r.시즌축한정, null);
  assert.ok(['q평소1', 'q평소2'].includes(r.문항id));
});

test('전부 말랐으면 결과 null — 없는 것을 지어내지 않는다', () => {
  const r = 시즌라운드선정({ ...공통, 오늘: '2026-08-14', 문항들: [] });
  assert.equal(r.결과, null);
  assert.equal(r.문항id, undefined);
});

test('결정성 — 같은 재료 두 번이면 같은 답', () => {
  const 재료 = { ...공통, 오늘: '2026-08-14' };
  assert.deepEqual(시즌라운드선정(재료), 시즌라운드선정(재료));
});
