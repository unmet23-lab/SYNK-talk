'use strict';
/**
 * 주석 제거는 **통로가 하나다** — 사본을 못 만들게 기계로 막는다 (F401 · 2026-08-13).
 *
 * ■ 왜 이 회귀가 있나
 *   F401 은 「같은 계열 2번째」였다. 첫 번째(2026-08-12)는 `for update` 를 코드에서 지웠는데
 *   바로 위 주석이 그 낱말을 설명하고 있어 검사가 **영원히 초록**이던 자리고, 두 번째는 반대로
 *   주석에 적은 `allowsRecording` 을 위반으로 읽어 **master 를 적색으로** 만든 자리다.
 *   두 번 다 「그 파일에 주석 제거를 하나 더 짓는다」로 수습됐고, 그래서 사본이 늘었다.
 *   CLAUDE.md 신뢰성: 3번째는 **원인을 쓸 수 없게** 만든다 — 공용 통로 하나 + 옛 통로 금지.
 *
 * ■ 무엇을 어디서 재나 (가드의 세 맹점 중 ①②)
 *   · **탐지력은 픽스처가 진다** — `tests/fixtures/가드계수/` 에 사본·위험·거짓양성 재료를
 *     일부러 심어 두고 그것을 값으로 못박는다. 버그가 «아직 있을 것»을 요구하지 않는다.
 *   · **실저장소에는 거짓양성만** 묻는다 — 「지역 사본이 0인가」 하나.
 *   · 판정은 `tools/가드계수.js` **한 곳**에서 온다. 여기 다시 적으면 갈라지고, 갈라진 쪽의
 *     증상은 언제나 「통과」다.
 *
 * ■ 못 재면 fail 이 아니라 skip 이다 (F296)
 *   계수기는 `acorn` 파서를 쓴다(정규식으로 세면 계수기가 세려는 병에 스스로 걸린다 —
 *   주석에 적힌 예시를 실물로 센다). 파서가 없는 환경에서 **빨개지면 남의 배포를 막는다.**
 *   그래서 못 재는 날은 skip 으로 «드러낸다» — 조용히 통과시키지 않는다.
 */

const test = require('node:test');
const assert = require('node:assert');
const path = require('node:path');

const { 코드만, 줄맞춰코드만, 구간, 코드만픽스처, 상위집합픽스처 } = require('./lib/소스검사.js');
const 계수기 = require('../tools/가드계수.js');

const ROOT = path.join(__dirname, '..');
const 픽스처뿌리 = path.join(__dirname, 'fixtures', '가드계수');

/* ── ① 공용 통로의 힘 — 값으로 못박는다 ─────────────────────────────────────── */

test('옛 픽스처가 그대로 통과한다 — 상위집합으로 갈아도 옛 보장은 안 잃는다', () => {
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대);
});

test('사본 7벌이 저마다 지키던 것을 «하나»가 전부 진다', () => {
  for (const c of 상위집합픽스처) {
    assert.equal(코드만(c.입력), c.기대, `흡수 실패: ${c.왜}`);
  }
  assert.ok(상위집합픽스처.length >= 6, '픽스처가 줄었다 — 흡수 근거가 사라진다');
});

test('앵커를 못 찾으면 «던진다» — 조용한 빈 문자열은 미실행을 초록으로 만든다', () => {
  assert.throws(() => 구간('const a = 1;', '없는앵커', null), /못 찾았다/);
});

/* ── ② 계수기의 탐지력 — 픽스처가 진다 ──────────────────────────────────────── */

test('계수기가 사본을 잡고, 사본이 «아닌 것»은 안 잡는다 (픽스처)', { skip: 계수기.잴수있나() ? false : 'acorn 없음 — 셀 수 없다(0건이 아니다)' }, () => {
  const r = 계수기.재기(픽스처뿌리);
  assert.equal(r.훑은파일, 2, '픽스처를 못 훑었다 — 아래 단언들이 통째로 미실행이다');
  /* 🔴 [2026-08-13 2차] 세 «모양»을 다 잡는지 — 첫 판은 화살표 모양만 봐서 「사본 0벌」을 냈고
   *   아래 ③ 이 **16벌이 산 채로 초록**이었다(F401 잔여 처분에서 실측). 새는 방향은 늘 통과다. */
  assert.deepEqual(r.사본.map((x) => x.이름).sort(), ['주석없이', '주석뺀소스', '주석제거'].sort(),
    '세 모양(화살표 · 함수선언 · «식») 중 하나라도 놓치면 그 모양의 사본이 조용히 산다.\n'
    + '   동시에 — base64url 인코더(`.replace(/\\//g,"_")`)·공백 납작(`\\s+`)을 사본으로 세면 F401 의 과대계상이 되살아난다.\n'
    + '   그리고 «별표는 주석이 아니다»(3차 · ⑪⑫): 마크다운 굵게(`/\\*\\*/`)·glob→정규식(`/\\*/`)이\n'
    + '   목록에 들면 판정이 `\\*` 로 되돌아간 것이다 — 블록 주석은 `\\/\\*` 라 슬래시가 있어야 한다.\n'
    + '   그 되돌림의 대가는 as 저장소에서 사본 20 → 44 (거짓양성 24벌)였다.');
  /* ⚠ 이 숫자가 «JSON 경계»도 함께 진다 — 경계를 빼면 `JSON.parse(readFileSync(…))` 가
   *   원문으로 서고 그 파생인 **생성된 SQL** 까지 번져 위험이 3 이 된다(픽스처 `깨끗함.js`). */
  assert.equal(r.위험.length, 2, '문자열 상수를 재는 단언·긍정 단언·JSON 구조는 이 축이 아니다');
  assert.equal(r.안전.length, 5, '정제 경유와 그 파생을 못 세면 ❔모름이 부풀어 숫자를 아무도 안 읽는다');
  /* ⑩ 축 — 한 이름이 두 뜻이면 «못 가른 것»이라 ❔모름이다. 이 둘이 위험으로 새면
   *   처방이 「상수를 공용 통로로 감싸라」가 되어 아무도 안 따른다(F103). */
  assert.equal(r.모름.length, 2, '같은 이름의 두 선언을 못 가른 자리는 ❔모름으로 «드러낸다»');
});

/* ── ②-b 불투명 import · 함수 «선언» 생산자 — 4차 조임의 탐지력 (2026-08-14) ────────
 *
 * 왜 픽스처 뿌리가 «따로»인가: 위 ② 는 ㉡(사본) 축의 census 를 값으로 못박고 있다.
 *   같은 뿌리에 재료를 더하면 그 숫자가 흔들려, 어느 축이 깨졌는지 안 보이게 된다.
 *
 * ⚠ 이 장치의 «대가»(v9.2 맹점④ — 틀릴 때의 모습):
 *   ① 상대경로 require 를 **한 겹만** 따라간다. 두 겹짜리 생산자가 생기면 그 자리는 조용히
 *      ❔모름으로 돌아간다 — 적색이 아니라 «모름 증가»가 증상이라 눈에 안 띈다.
 *   ② 못 읽거나 못 파싱한 모듈은 아무것도 안 더한다(F296 — repo 밖 환경에 안 기댄다).
 *   ③ 닫은 것: **없다.** 이건 새 가드가 아니라 이미 있던 계수기의 사각을 좁힌 것이고,
 *      안전 가드는 숫자를 맞추려고 억지로 닫지 않는다(v9.2 그 조항).
 */

test('계수기가 «들여온» 원문 생산자와 함수 선언형 생산자를 따라간다 (픽스처)', { skip: 계수기.잴수있나() ? false : 'acorn 없음 — 셀 수 없다(0건이 아니다)' }, () => {
  const r = 계수기.재기(path.join(__dirname, 'fixtures', '가드계수불투명'));
  assert.equal(r.훑은파일, 2, '픽스처를 못 훑었다 — 아래 단언들이 통째로 미실행이다(F207)');
  assert.deepEqual(r.못읽은파일, [], '못 읽은 파일을 「깨끗하다」로 접지 않는다');

  /* ①②③ — 원문이 «한 겹 건너» 와도 원문이다.
   *   ① `const 코드 = 엔진원문()`      ← 상대경로 require 한 겹(②-c)
   *   ② `구역(…)`                      ← 함수 «선언» 모양 생산자(③-b · 옛 판은 화살표만 봤다)
   *   ③ `const 조각 = 코드.slice(…)`   ← 그 파생
   * 셋 중 하나라도 빠지면 그 모양의 눈먼 가드가 ❔모름 뒤에 숨는다 — as 실측으로
   * ①계열 17자리·②계열 24자리가 그렇게 숨어 있었다. */
  assert.equal(r.위험.length, 3,
    '들여온 생산자(②-c)·함수 선언형 생산자(③-b)·그 파생 중 하나를 놓쳤다.\n'
    + '   놓치면 숫자가 «좋아지는» 쪽으로 틀린다 — 새는 방향은 언제나 「통과」다.');

  /* ④ — 읽고서 «정제해» 준 것은 정제다. 위험으로 세면 이미 감싼 것을 또 감싸라는
   *   처방이 되고, 따를 수 없는 처방은 우회를 정상 통로로 만든다(F103). */
  assert.equal(r.안전.length, 1,
    '들여온 생산자가 읽기를 «자기 안에» 감추면 정제 경유가 ❔모름으로 샌다 — 정제가 이겨야 한다');

  /* ⑤ — 🔴 4차 조임의 «첫 판»이 정확히 여기서 틀렸다. `세우기()` 는 파일을 읽지만 내주는 것은
   *   모듈 객체다. 원문으로 세면 그 팩에서 나온 데이터가 전부 원문 파생이 되어, talk 실저장소에
   *   오탐 3건(`팩.같은스킬다른문항(…)`·`JSON.stringify(학생판)`)이 났다.
   *   읽었다고 «글»을 내주는 것은 아니다 — 지역 판정의 `JSON구조인가` 와 같은 축이다. */
  assert.equal(r.모름.length, 1,
    '읽었으나 «구조»(모듈 객체)를 내주는 생산자를 원문으로 셌다 — 그 처방은 아무도 못 따른다(F103)');
  assert.ok(!r.위험.some((v) => /팩\./.test(v.글) || /팩\)/.test(v.글)),
    '모듈 객체를 재는 단언이 위험으로 섰다 — 주석이 사는 층이 아니라 이 축이 원리상 성립하지 않는다');

  /* 이 묶음의 공용 통로는 사본으로 «세어져야» 한다 — 픽스처가 자기 규칙에서 면제되면
   * 그 census 가 무엇을 재는지 흐려진다. */
  assert.deepEqual(r.사본.map((x) => x.이름), ['주석없이'], '픽스처의 통로 1벌이 census 에서 사라졌다');
});

/* ── ①-b 줄 맞춘 판 — 렉서는 하나, 공백 정책만 둘 ──────────────────────────── */

test('줄맞춰코드만 은 «줄 수»를 원문 그대로 둔다 — 행 번호로 짚는 소비자가 있다', () => {
  const 입력 = ['const a = 1;', '// 버리지 않고 눕힌다', '', 'const b = 2;'].join('\n');
  const 나온것 = 줄맞춰코드만(입력);
  assert.equal(나온것.split('\n').length, 4, '줄이 줄면 `스폰통로` 가 짚는 행 번호가 밀린다');
  assert.ok(!/버리지/.test(나온것), '주석이 안 눕혀졌다');
  /* 같은 재료로 `코드만` 은 그 줄을 «버린다» — 둘이 다른 것이 이 분리의 전부다. */
  assert.equal(코드만(입력).split('\n').length, 3);
});

test('두 판이 «같은 렉서»를 쓴다 — 문자열 속 `//` 는 어느 쪽도 안 먹는다', () => {
  const 입력 = "const u = 'https://x/평균';";
  assert.equal(줄맞춰코드만(입력), 입력);
  assert.equal(코드만(입력), 입력);
});

/* ── ③ 실저장소 — 거짓양성만 (버그가 남아 있기를 요구하지 않는다) ─────────────── */

test('🔴 주석 제거기 지역 사본이 0벌이다 — 통로는 tests/lib/소스검사.js 하나뿐', { skip: 계수기.잴수있나() ? false : 'acorn 없음 — 셀 수 없다(0건이 아니다)' }, () => {
  const r = 계수기.재기(ROOT);
  /* 🔑 분모를 먼저 못박는다 — 스폰 실패·빈 출력로 0건이 나면 「깨끗하다」와 같은 모양이다(F207). */
  assert.ok(r.훑은파일 > 100, `훑은 파일이 ${r.훑은파일}개다 — 미실행을 통과로 셀 뻔했다`);
  assert.deepEqual(r.못읽은파일, [], '못 읽은 파일을 「깨끗하다」로 접지 않는다');
  assert.deepEqual(
    r.사본.map((x) => `${x.파일}:${x.줄} ${x.이름}`), [],
    '주석 제거기를 또 지었다 — `const { 코드만 } = require("./lib/소스검사.js")` 로 바꾼다.\n'
    + '   사본이 늘면 갈라진 쪽이 조용히 눈이 먼다(F401: 인라인 `//`·JSX·문자열 속 `//` 를 저마다 다르게 봤다).');
});
