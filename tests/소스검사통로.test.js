/* ── ③ 실저장소 — 거짓양성만 (버그가 남아 있기를 요구하지 않는다) ─────────────── */

/** 실저장소 census 는 한 번만 센다 — 아래 ③④ 가 같은 판을 본다(199 파일을 두 번 파싱하지 않는다). */
