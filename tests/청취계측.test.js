'use strict';
/**
 * 청취 계측 회귀 (`lib/청취계측.js`) — **승인 게이트 ①에 들어갈 숫자**를 재는 자리.
 *
 * 왜 이 파일이 필요한가: 이 값이 부풀면 0초 승인이 3초로 적히고, 깎이면 정상 검수가
 * 확정을 못 한다. 둘 다 **증상이 화면에 안 뜬다** — 앞은 게이트가 조용히 열린 것이고
 * 뒤는 검수자가 「앱이 이상하다」고만 느낀다. 그래서 판정을 화면 밖으로 뺐고 여기서 잰다.
 */

const test = require('node:test');
const assert = require('node:assert/strict');
const { 새계측, 재기, 들은ms, 허용오차ms } = require('../lib/청취계측.js');

/** 1배속 재생 표본열 — 위치와 시각이 같은 만큼 흐른다. */
function 재생(계측, 시작위치, 시작시각, 걸음, 횟수) {
  let c = 계측;
  for (let i = 1; i <= 횟수; i += 1) {
    c = 재기(c, { 재생중: true, 위치ms: 시작위치 + 걸음 * i, 시각ms: 시작시각 + 걸음 * i });
  }
  return c;
}

test('빈 계측은 0이다', () => {
  assert.equal(들은ms(새계측()), 0);
});

test('1배속으로 흐른 만큼 센다', () => {
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 1000 });
  c = 재생(c, 0, 1000, 200, 10); // 2초
  assert.equal(들은ms(c), 2000);
});

test('멈추면 구간이 닫히고, 다시 이어 들으면 합쳐진다', () => {
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 200, 5); // 0~1000
  c = 재기(c, { 재생중: false, 위치ms: 1000, 시각ms: 1000 });
  /* 한참 뒤에 이어서 재생 — 시각은 크게 뛰었지만 위치는 이어진다. */
  c = 재기(c, { 재생중: true, 위치ms: 1000, 시각ms: 60000 });
  c = 재생(c, 1000, 60000, 200, 5); // 1000~2000
  assert.equal(들은ms(c), 2000);
});

test('🔴 같은 자리를 되들어도 두 번 안 센다 — 합집합이라 게이트를 반복으로 못 연다', () => {
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 200, 5); // 0~1000
  // 되감기(seek) — 위치가 뒤로 뛴다
  c = 재기(c, { 재생중: true, 위치ms: 0, 시각ms: 1200 });
  c = 재생(c, 0, 1200, 200, 5); // 다시 0~1000
  c = 재기(c, { 재생중: true, 위치ms: 0, 시각ms: 2400 });
  c = 재생(c, 0, 2400, 200, 5);
  assert.equal(들은ms(c), 1000, '세 번 들어도 들은 구간은 1초다');
});

test('🔴 앞으로 건너뛴 구간은 안 센다 — 시각이 안 흘렀다', () => {
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 200, 5); // 0~1000
  // 10초 앞으로 seek — 위치만 뛰고 시각은 그대로
  c = 재기(c, { 재생중: true, 위치ms: 11000, 시각ms: 1050 });
  c = 재생(c, 11000, 1050, 200, 5); // 11000~12000
  assert.equal(들은ms(c), 2000, '앞 1초 + 뒤 1초. 건너뛴 10초는 안 센다');
});

test('🔴 앱이 물러나 있던 시간은 안 센다 — 시각만 뛴 표본은 새 구간이다', () => {
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 200, 5); // 0~1000
  /* 재생 중이라고 보고되지만 30초 동안 위치가 안 움직였다(화면 밖) */
  c = 재기(c, { 재생중: true, 위치ms: 1000, 시각ms: 31000 });
  assert.equal(들은ms(c), 1000);
});

test('구간이 겹치면 합집합으로 접힌다 (품은 구간도)', () => {
  let c = 새계측();
  // 0~3000
  c = 재기(c, { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 500, 6);
  c = 재기(c, { 재생중: false, 위치ms: 3000, 시각ms: 3000 });
  // 안쪽 1000~2000 을 다시
  c = 재기(c, { 재생중: true, 위치ms: 1000, 시각ms: 4000 });
  c = 재생(c, 1000, 4000, 500, 2);
  assert.equal(들은ms(c), 3000, '품은 구간이 총량을 줄이면 안 된다');
});

test('붙어 있는 두 구간은 하나로 이어진다', () => {
  let c = 새계측();
  c = 재기(c, { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 500, 2); // 0~1000
  c = 재기(c, { 재생중: false, 위치ms: 1000, 시각ms: 1000 });
  c = 재기(c, { 재생중: true, 위치ms: 1000, 시각ms: 2000 });
  c = 재생(c, 1000, 2000, 500, 2); // 1000~2000
  assert.equal(들은ms(c), 2000);
});

test('허용오차 안의 흔들림은 같은 재생으로 본다', () => {
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  /* 위치가 시각보다 조금 앞서거나 뒤처지는 것은 표본 지터다 — 끊으면 정상 재생이 잘게 갈린다. */
  c = 재기(c, { 재생중: true, 위치ms: 1000, 시각ms: 1000 + (허용오차ms - 1) });
  assert.equal(들은ms(c), 1000);
});

test('🔴 허용오차 안의 **되감기**는 이어붙이지 않는다 — 끝을 뒤로 당기면 들은 것이 줄어든다', () => {
  /* 변이 ②가 여기서 나왔다: `위치델타 >= 0` 을 빼도 시각 대조가 큰 seek 은 잡아내서
     검사가 통과했다. 남는 구멍은 **허용오차보다 작은 뒤로 뜀**(디코더가 위치를 되물리거나
     0.4초짜리 되감기)이고, 그때 진행 구간의 끝이 당겨져 들은 양이 조용히 깎인다. */
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 200, 5); // 0~1000
  c = 재기(c, { 재생중: true, 위치ms: 600, 시각ms: 1100 }); // 400ms 뒤로(허용오차 안)
  assert.equal(들은ms(c), 1000, '되감기가 진행 구간의 끝을 당겼다');
});

test('🔴 망가진 표본이 재생을 끊지 않는다 — 끊기면 그 사이가 통째로 안 세인다', () => {
  /* 변이 ⑤가 여기서 나왔다: 「들은 양이 안 늘어난다」로만 재면 그 표본이 **구간을 끊는** 것을
     못 본다(끊긴 구간도 합집합에선 각자 세이므로 총량이 비슷해 보인다). 실제 손해는
     끊긴 자리의 **사이**다 — 여기서는 1000~1200 이 사라지는지 본다. */
  let c = 재기(새계측(), { 재생중: true, 위치ms: 0, 시각ms: 0 });
  c = 재생(c, 0, 0, 200, 5); // 0~1000
  c = 재기(c, { 재생중: true, 위치ms: NaN, 시각ms: 1050 });
  c = 재기(c, null);
  c = 재기(c, { 재생중: true, 시각ms: 1100 }); // 위치 없음
  c = 재생(c, 1000, 1000, 200, 5); // 재생은 끊긴 적 없다 — 1200~2000 으로 그대로 흐른다
  /* 🔑 1000~1200 **사이**가 급소다. 망가진 표본이 `마지막` 을 오염시키면 다음 정상 표본이
     이어붙질 못해 구간이 [0,1000]·[1200,2000] 으로 갈리고, 그 200ms 가 조용히 사라진다. */
  assert.equal(들은ms(c), 2000, '망가진 표본이 구간을 끊어 그 사이가 안 세였다');
});

test('재기는 원본을 안 고친다 — React 상태로 그대로 쓴다', () => {
  const 처음 = 새계측();
  const 다음 = 재기(처음, { 재생중: true, 위치ms: 0, 시각ms: 0 });
  assert.notEqual(처음, 다음);
  assert.equal(들은ms(처음), 0);
});
