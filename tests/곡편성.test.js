'use strict';
/* 곡편성 — Reed 의 심장. 「랜덤 재생」과 「방송」을 가르는 규칙 셋이 실제로 도는가.
 * 🔴 이 스위트의 급소: ①결 경계가 «계단»인가(툭 갈리면 방송이 아니다)
 *   ②최소 간격이 어떤 이유로도 안 뚫리는가 ③못 고를 때 «아무거나»로 접지 않는가
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const 편 = require('../lib/곡편성.js');

const 곡 = (id, 장르, BPM, 밝기, 길이초 = 400) => ({
  id, 제목: id, 장르, 결: '낮', DJ: '까몽', 판: 'v1', 재현: 'x', 길이초,
  상태: '채택', BPM, 밝기,
});
const 장부 = [
  곡('city-a', '시티팝', 114, 0.82), 곡('city-b', '시티팝', 100, 0.62),
  곡('elec-a', '전자', 108, 0.70), 곡('elec-b', '전자', 100, 0.55),
  곡('nat-a', '자연', 60, 0.15), 곡('nat-b', '자연', 54, 0.10),
  곡('후보-x', '시티팝', 114, 0.8), // 상태가 채택이 아니면 안 뽑힌다
].map((c, i) => (i === 6 ? { ...c, 상태: '후보' } : c));

test('결 다섯이 하루를 빈틈없이 덮는다 — 0~24 어디를 찍어도 결이 하나 나온다', () => {
  const 본것 = new Set();
  for (let h = 0; h < 24; h += 0.25) 본것.add(편.지금결(h).이름);
  assert.equal(본것.size, 5);
  assert.equal(편.지금결(0).이름, '새벽');
  assert.equal(편.지금결(23.9).이름, '밤');
});

test('시각이 24를 넘거나 음수여도 감긴다 — 미리보기가 자정을 넘어간다', () => {
  assert.equal(편.지금결(25).이름, 편.지금결(1).이름);
  assert.equal(편.지금결(-1).이름, 편.지금결(23).이름);
});

test('🔴 결 한가운데서는 과녁이 그 결 그대로다 — 계단은 경계 앞에서만 선다', () => {
  const g = 편.과녁(12);
  assert.equal(g.결, '낮');
  assert.equal(g.다음결, null);
  assert.equal(g.진행, 0);
});

test('🔴 경계 앞에서는 과녁이 «계단»으로 움직인다 — 툭 갈리면 방송이 아니라 재생목록이다', () => {
  const 멀리 = 편.과녁(16.0);      // 저녁까지 60분
  const 가까이 = 편.과녁(16.9);    // 저녁까지 6분
  assert.equal(멀리.다음결, null);
  assert.equal(가까이.다음결, '저녁');
  assert.ok(가까이.진행 > 0.7, `진행 ${가까이.진행}`);
  // 낮 BPM 108 → 저녁 98 이므로 과녁 BPM 이 «내려가는 중»이어야 한다
  assert.ok(가까이.BPM < 멀리.BPM, '과녁 BPM 이 다음 결 쪽으로 안 움직였다');
  assert.ok(가까이.BPM > 98, '아직 도착하면 안 된다 — 계단이지 점프가 아니다');
});

test('전환 구간에서는 두 결의 장르를 «함께» 받는다 — 경계에서 소리가 툭 갈리지 않게', () => {
  const g = 편.과녁(20.9);         // 밤(자연·전자) 직전의 저녁(시티팝)
  assert.ok(g.장르.includes('시티팝') && g.장르.includes('자연'));
});

test('🔴 DJ 교대는 결이 «넘어간 뒤» 한 번 — 전환 구간에서 미리 바뀌지 않는다', () => {
  assert.equal(편.과녁(20.9).DJ, '까몽', '아직 저녁이므로 까몽이다');
  assert.equal(편.과녁(21.1).DJ, '몽글', '밤으로 넘어갔으니 몽글이다');
  assert.equal(편.DJ교대인가(20.9, 21.1), true);
  assert.equal(편.DJ교대인가(20.0, 20.9), false, '같은 결 안에서는 안 바뀐다');
  assert.equal(편.DJ교대인가(8.9, 9.1), true, '아침(까몽)→낮(새친구)');
});

test('결에 맞는 장르만 고른다 — 새벽에 시티팝이 나오지 않는다', () => {
  const r = 편.다음곡(장부, 3);
  assert.ok(r.곡);
  assert.equal(r.곡.장르, '자연');
});

test('채택이 아닌 곡은 원리상 안 뽑힌다', () => {
  for (let h = 0; h < 24; h += 0.5) {
    const r = 편.다음곡(장부, h);
    if (r.곡) assert.notEqual(r.곡.id, '후보-x');
  }
});

test('🔴 최장 미노출 우선 — 방금 나간 곡보다 안 나간 곡이 먼저다', () => {
  const r = 편.다음곡(장부, 3, [{ id: 'nat-a', 언제분: 200 }]);
  assert.equal(r.곡.id, 'nat-b', '더 오래된 쪽이 아니라 안 나간 쪽이 먼저다');
});

test('🔴 최소 간격은 어떤 이유로도 안 뚫린다 — 과녁에 아무리 맞아도', () => {
  const 최근 = [{ id: 'nat-a', 언제분: 5 }, { id: 'nat-b', 언제분: 10 }];
  const r = 편.다음곡(장부, 3, 최근);
  assert.equal(r.곡, null);
  assert.match(r.왜, /90분/);
  assert.equal(r.후보수, 2, '풀 크기는 그대로 말한다 — 「곡이 없다」와 「곡이 쉬는 중」은 다르다');
});

test('🔴 못 고르면 «아무거나»로 접지 않는다 — 왜 못 골랐는지를 말한다', () => {
  const r = 편.다음곡([], 3);
  assert.equal(r.곡, null);
  assert.match(r.왜, /채택곡이 0/);
  assert.equal(r.후보수, 0);
});

test('같은 상태면 같은 답 — 난수가 0이라 「왜 이 곡인가」를 물을 수 있다', () => {
  const a = 편.다음곡(장부, 12, [{ id: 'elec-a', 언제분: 300 }]);
  const b = 편.다음곡(장부, 12, [{ id: 'elec-a', 언제분: 300 }]);
  assert.equal(a.곡.id, b.곡.id);
});

test('🔴 최소 간격이 «풀의 최소 크기»를 정한다 — 회귀가 잡아낸 파생 규칙', () => {
  assert.equal(편.풀최소크기(360), 16, '6분 곡이면 90분을 채우는 데 16곡');
  assert.equal(편.풀최소크기(60), 91, '1분 곡이면 91곡 — 짧을수록 곡이 폭발한다');
  // 위 장부는 자연이 2곡뿐이라 «정직하게 멈춘다» — 조용히 같은 곡을 다시 트는 것보다 낫다
  const 짧은풀 = 편.미리보기(장부, 2, 6);
  assert.ok(짧은풀.some((x) => !x.곡), '풀이 모자라면 멈춰야 한다');
  assert.match(짧은풀.find((x) => !x.곡).왜, /곡이 모자라다/);
});

test('미리보기 — 방송을 안 켜고도 하루를 돌려본다(학생 0명에도 잴 수 있는 유일한 층)', () => {
  const 넉넉한장부 = [...장부];
  for (let i = 0; i < 20; i++) 넉넉한장부.push(곡(`nat-${i}`, '자연', 54 + i, 0.1 + i * 0.005));
  const 줄 = 편.미리보기(넉넉한장부, 2, 6);
  assert.equal(줄.length, 6);
  assert.ok(줄.every((x) => x.곡), `못 고른 자리 ${줄.filter((x) => !x.곡).length}`);
  // 최소 간격이 미리보기 안에서도 지켜진다(같은 곡이 90분 안에 두 번 안 나온다)
  const 언제 = new Map();
  let 분 = 0;
  for (const x of 줄) {
    if (언제.has(x.곡.id)) assert.ok(분 - 언제.get(x.곡.id) >= 편.최소간격분, `${x.곡.id} 가 너무 빨리 다시 나왔다`);
    언제.set(x.곡.id, 분);
    분 += (x.곡.길이초 || 360) / 60;
  }
});

test('미리보기가 자정을 넘어도 결이 이어진다 — 새벽으로 감긴다', () => {
  const 넉넉한장부 = [...장부];
  for (let i = 0; i < 20; i++) 넉넉한장부.push(곡(`nat-${i}`, '자연', 54 + i, 0.1 + i * 0.005));
  const 줄 = 편.미리보기(넉넉한장부, 23.5, 4);
  assert.ok(줄.every((x) => x.곡), '자정 경계에서 편성이 끊기면 안 된다');
  assert.ok(줄.some((x) => x.과녁.결 === '새벽' || x.과녁.다음결 === '새벽'));
});
