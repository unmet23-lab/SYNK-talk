'use strict';
/**
 * 「저장된 기록 중 N줄을 읽지 못했어요」 회귀 — 문구가 **한 곳에만 살게** 못박는다.
 *
 * 🔴 왜 있나: 이 문장은 세 화면(말하기·교수멘탈·보고서교정)에 그대로 복제돼 있었고,
 *   셋 다 반말 「…읽지 못했다」였다. 앱 전체가 해요체인데 학생 오류칸에서만 말이 갈렸고,
 *   카피 전수감사(2026-08-13 · 유호 확정 「따뜻하되 직관적」)가 그제야 잡았다.
 *   호출부마다 고치면 네 번째 복제가 또 갈린다 — 그래서 문장을 `lib/제출로그.js`
 *   (`역직렬화` 가 깨진줄을 세는 자리)로 옮기고, 여기서 사본·미호출·반말을 막는다.
 *
 * 검사 넷: ①문구 자체 ②사본 금지(실저장소) ③실제 호출(import 만 남는 위장 차단)
 *          ④탐지력 픽스처 — 실저장소가 아니라 가짜 소스로 잰다(버그가 남아 있기를
 *          요구하는 회귀를 만들지 않는다).
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { 깨진기록안내, 역직렬화 } = require('../lib/제출로그.js');

const ROOT = path.join(__dirname, '..');
/* 감사(HEAD 좌표)는 셋만 셌다 — 이 회귀가 **네 번째**(서류관문화면)를 잡았다.
 * 감사 표를 쓰는 동안 G4 트랙이 새 화면을 만들며 같은 줄을 또 복제한 것이다.
 * 목록을 손으로 유지하지 않는다: 아래 「사본 금지」가 src 전체를 훑으므로 다섯 번째도 잡힌다. */
const 화면들 = ['말하기화면.js', '교수멘탈화면.js', '보고서교정화면.js', '서류관문화면.js'];

/** 주석 속 설명은 위반이 아니다 — 안 벗기면 이 파일을 설명한 주석이 곧 실패가 된다. */
const 주석제거 = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');

test('0줄이면 아무것도 띄우지 않는다 — 「0줄을 읽지 못했어요」가 뜨면 사고다', () => {
  assert.equal(깨진기록안내(0), null);
  assert.equal(깨진기록안내(undefined), null);
  assert.equal(깨진기록안내(null), null);
  assert.equal(깨진기록안내(-1), null, '음수는 계산이 깨진 것 — 문구로 덮지 않는다');
});

test('깨진 줄이 있으면 해요체로, 다음 걸음까지 말한다', () => {
  const 말 = 깨진기록안내(3);
  assert.equal(말, '저장된 기록 중 3줄을 읽지 못했어요 — 남은 기록으로 이어가요');
  assert.ok(/어요|에요/.test(말), '학생 화면은 해요체다 — 여기만 반말이면 앱이 갈린다');
  assert.equal(/못했다|못했음/.test(말), false, '구 반말 표기가 되살아났다');
});

test('숫자의 주인과 문구의 주인이 같다 — 역직렬화가 센 값을 그대로 받는다', () => {
  const { 깨진줄 } = 역직렬화('{"a":1}\n{망가진\n{"b":2}\n');
  assert.equal(깨진줄, 1);
  assert.equal(깨진기록안내(깨진줄), '저장된 기록 중 1줄을 읽지 못했어요 — 남은 기록으로 이어가요');
});

test('문장을 화면이 직접 적지 않는다 (사본 금지)', () => {
  const 걸린것 = fs.readdirSync(path.join(ROOT, 'src'))
    .filter((f) => f.endsWith('.js'))
    .filter((f) => 주석제거(fs.readFileSync(path.join(ROOT, 'src', f), 'utf8')).includes('줄을 읽지 못했'));
  assert.deepEqual(걸린것, [],
    `문구가 화면에 직접 적혀 있다: ${걸린것.join(', ')}\n`
    + '  「저장된 기록 중 N줄을 읽지 못했어요」는 lib/제출로그.js 의 `깨진기록안내` 하나에서만 나온다.');
});

/* 🔴 이름이 보이는 것과 부르는 것은 다르다 — import 만 남겨도 사본 금지는 통과한다.
 *   그 상태가 정확히 사고의 모양이다: 문장이 화면에서 사라졌는데 검사는 「쓰고 있다」고 말한다. */
test('세 화면 모두 그 함수를 **실제로 부른다**', () => {
  for (const f of 화면들) {
    const src = 주석제거(fs.readFileSync(path.join(ROOT, 'src', f), 'utf8'));
    assert.ok(/깨진기록안내\s*\(/.test(src),
      `${f} 가 깨진기록안내 를 안 부른다 — 이름만 import 에 남으면 사본 금지도 같이 눈이 먼다`);
  }
});

test('탐지력 픽스처 — 사본·주석 오탐이 되살아나면 잡는다', () => {
  assert.ok(주석제거('set오류(`저장된 기록 중 ${n}줄을 읽지 못했다`);').includes('줄을 읽지 못했'),
    '사본 탐지기가 죽으면 위 검사는 무엇이든 통과시킨다');
  assert.equal(주석제거('/* 「N줄을 읽지 못했어요」는 여기서만 만든다 */ 깨진기록안내(n)').includes('줄을 읽지 못했'), false,
    '주석 속 설명을 위반으로 읽으면 바른 코드가 막힌다');
});
