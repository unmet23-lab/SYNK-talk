'use strict';
/**
 * 소스 텍스트를 검사 대상으로 삼는 공용 통로 — **주석을 지우고** 구간을 자른다.
 *
 * ■ 왜 공용인가 (사본을 만들면 갈라진다)
 *   `tests/검수통로.test.js` 가 이 둘을 지역 함수로 갖고 있었고, 화면 쪽에도 같은 것이
 *   필요해졌다. 사본이 둘이 되면 **한쪽만 주석 제거를 놓치는** 날이 오고, 그 검사는 설명을
 *   코드로 읽어 **영원히 초록**이 된다 — 새는 방향이 언제나 「통과」인 형태다.
 *
 * ■ 🔴 이 파일이 존재하는 실측 근거
 *   `for update` 를 코드에서 지웠는데 검사가 초록이었다. 바로 위 주석이 「뷰에는
 *   `for update` 를 걸 수 없다」고 **설명**하고 있었고 검사가 그 문자열을 코드로 읽었다.
 *   가드는 자기 주석에 눈이 먼다 — **설명이 자세할수록 더 잘 먼다.**
 *   그래서 이 모듈을 쓰는 쪽은 반드시 탐지력 픽스처(`코드만픽스처`)를 한 번 돌린다.
 *
 * ⚠ 줄 단위라 코드 줄 끝의 인라인 `/* … *\/` 는 남는다 — 두 파일의 주석은 전부 블록이라 충분하다.
 *
 * ■ 🔴 [2026-08-12] **JSX 주석이 통째로 사각이었다** (같은 뿌리 두 번째)
 *   화면 파일의 주석은 `{/* … *\/}` 이고 **이어지는 줄이 `*` 로 안 시작한다**(저장소 관례 —
 *   `App.js`·`도착확인.js` 가 전부 그 표기다). 옛 판은 첫 줄의 `{` 때문에 시작도 못 잡고
 *   이어지는 줄은 본문으로 읽었다. 그래서 「화면에 «평균»이라는 낱말이 있나」 같은 검사가
 *   **금지를 설명하는 주석 자체를 위반으로 잡았다**(실측 — `반피드백화면` 이 그 자리다).
 *   증상이 거짓양성이라 눈에 띄었지만, 반대 방향(설명이 코드로 읽혀 영원히 초록)이 이 파일
 *   머리말의 실측 그대로라 **같은 구멍의 다른 얼굴**이다.
 *   👉 가드는 **사람이 실제로 쓰는 표기**로 검사해야 한다 — JSX 표기를 여기서 함께 진다.
 */

/**
 * 주석 줄을 뺀다(블록 `/*`·이어지는 `*`·줄 `//`·JSX `{/* … *\/}` **여러 줄 포함**).
 *
 * 🔑 JSX 블록만 «상태»가 필요하다 — 이어지는 줄에 아무 표식이 없어서 그 줄만 보면
 *   코드와 구별할 수 없다. 그래서 여는 줄부터 닫는 줄까지를 통째로 센다.
 */
function 코드만(본문) {
  let JSX주석 = false;
  return 본문.split('\n').filter((l) => {
    if (JSX주석) {
      // 닫는 줄도 버린다 — `*/}` 뒤에 코드를 이어 쓰는 표기는 이 저장소에 없다.
      if (l.includes('*/}') || /\*\/\s*\}/u.test(l)) JSX주석 = false;
      return false;
    }
    if (/^\s*\{\s*\/\*/u.test(l)) {
      // 한 줄로 닫히면 그 줄만 버린다.
      if (!/\*\/\s*\}/u.test(l)) JSX주석 = true;
      return false;
    }
    return !/^\s*(\*|\/\*|\/\/)/u.test(l);
  }).join('\n');
}

/**
 * 두 앵커 사이를 잘라 **주석을 지운 채** 돌려준다.
 * 🔑 앵커를 못 찾으면 **던진다** — 조용히 빈 문자열을 주면 그 검사는 「아무것도 안 든 문자열」을
 *   대상으로 통과한다(미실행이 초록과 같은 모양이 되는 자리).
 * @param {string} 소스 파일 전문
 * @param {string} 시작앵커
 * @param {string|null} 끝앵커 `null` 이면 끝까지
 */
function 구간(소스, 시작앵커, 끝앵커) {
  const i = 소스.indexOf(시작앵커);
  if (i === -1) throw new Error(`앵커 \`${시작앵커}\` 를 못 찾았다 — 이 검사가 통째로 미실행이다`);
  if (끝앵커 === null) return 코드만(소스.slice(i));
  const j = 소스.indexOf(끝앵커, i + 1);
  if (j <= i) throw new Error(`앵커 \`${끝앵커}\` 를 못 찾았다 — 구간을 못 자른다`);
  return 코드만(소스.slice(i, j));
}

/** 탐지력 픽스처 — **버그가 아직 있을 것을 요구하지 않고** 제거기의 힘만 못박는다.
 *  쓰는 쪽에서 `assert.equal(코드만(입력), 기대)` 로 한 번 돌린다. */
const 코드만픽스처 = Object.freeze({
  입력: [
    '  /* 뷰에는 `for update` 를 걸 수 없다.',
    '   * 그래서 잠금을 갈랐다. */',
    '  const x = 1;',
    '  // for update 라고 적어 둔다',
    /* JSX 표기 — **이어지는 줄에 표식이 없다.** 여기 「평균」을 일부러 심는다: 옛 판이
       금지를 설명하는 주석을 위반으로 잡던 그 모양 그대로다(머리말 🔴 2026-08-12). */
    '      {/* 🚫 평균·등수를 여기 두지 않는다',
    '          — 정렬 축이 곧 비교다. */}',
    '      <Text>{c.기다림}</Text>',
    '      {/* 한 줄짜리도 버린다 */}',
  ].join('\n'),
  기대: ['  const x = 1;', '      <Text>{c.기다림}</Text>'].join('\n'),
});

module.exports = { 코드만, 구간, 코드만픽스처 };
