const 낱말모양 = /^--[가-힣A-Za-z0-9_-]+$/;

/**
 * 코드가 **낱말 그 자체로** 인용한 `--…` 전량 (자식 인자도 여기 섞인다 — 가르는 것은 아래 몫).
 *
 * 🔴 **줄 단위로 훑는다 — 파일 전체에 전역으로 돌리면 «짝 밀림»이 낭떠러지다**(#Q112 ㉢).
 *   `local_31b3b9c3` 이 #Q111 끝에 재놓고 넘긴 실측: 파일 전체 토크나이저는 앞에서 짝이 **한 번만**
 *   어긋나도(정규식 리터럴 속 따옴표 하나면 된다) 그 뒤가 통째로 밀린다 — `tools/엔진뷰어.js` 에서
 *   조각 104개를 뽑고도 `--건수` 를 품은 조각이 **0개**였다. 후보 넷 중 «줄 단위»만 재현율 0 누락 ·
 *   정밀도 0 오탐(15/15)이었다.
 *   ⚠ 그 실측은 **원문**을 훑은 판이고, 여기는 `코드만` 을 지난 코드를 훑는다 — 짝을 깨던 것이
 *     대부분 «주석 속 산문»이었으므로 2026-08-18 실저장소에서는 두 판의 차이가 **0**이다(전수 실측).
 *     그래도 줄 단위로 둔다: 코드 안의 정규식 리터럴은 렉서가 (정당하게) 지키므로 낭떠러지가
 *     남아 있고, 줄 단위는 손해가 **그 한 줄로 갇힌다.** 값이 같을 때 갈아 두는 것이 값이다.
 *   ⚠ 백틱도 본다 — 옛 판은 아예 안 봤다(그래서 이미 «덜 요구»하고 있었다).
 */
function 낱말들(코드) {
  const 나온것 = new Set();
  for (const 줄 of String(코드).split('\n')) {
    for (const 조각 of 줄.match(/'[^']*'|"[^"]*"|`[^`]*`/g) || []) {
      const 속 = 조각.slice(1, -1);
      if (낱말모양.test(속)) 나온것.add(속);
    }
  }
  return [...나온것];
}

const 이름꼴 = '[A-Za-z_$가-힣][\\w$가-힣]*';
const 정규식escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * argv 를 담는 이름 전부 — 저장소가 실제로 쓰는 세 모양을 따라간다(2026-08-18 전수 실측).
 *   ① `const args = process.argv.slice(2)`        — 13개 도구
 *   ② `main(process.argv.slice(2))` + `function main(argv)` — **매개변수 꼴**. 옛 판이 이걸
 *      못 봐서 `eval-score.js`·`독립채점.js` 가 「자기 플래그 0」으로 나왔다(거짓 안심).
 *   ③ `process.argv` 직접 — `process.argv.includes('--현황')` (`문항검수.js`)
 */
function argv이름들(코드) {
  const 이름 = new Set(['process.argv']);
  let m;
  const 직접 = new RegExp(`(?:const|let|var)\\s+(${이름꼴})\\s*=\\s*process\\.argv`, 'g');
  while ((m = 직접.exec(코드))) 이름.add(m[1]);
  const 넘김 = new RegExp(`(${이름꼴})\\s*\\(\\s*process\\.argv[^)]*\\)`, 'g');
  while ((m = 넘김.exec(코드))) {
    const 함수 = 정규식escape(m[1]);
    const d = new RegExp(`function\\s+${함수}\\s*\\(\\s*(${이름꼴})`).exec(코드)
      || new RegExp(`(?:const|let|var)\\s+${함수}\\s*=\\s*(?:async\\s*)?\\(?\\s*(${이름꼴})`).exec(코드);
    if (d) 이름.add(d[1]);
  }
  return [...이름];
}

/** argv 를 첫 인자로 받는 «도우미»(`인자값(argv, '--조각')`)도 자기 플래그를 읽는 자리다.
 *  `독립채점.js`·`eval-score.js` 가 값 받는 낱말을 전부 이 꼴로만 읽는다. */
function 도우미이름들(코드, argv이름) {
  const 이름 = new Set();
  for (const v of argv이름) {
    const re = new RegExp(`(${이름꼴})\\s*\\(\\s*${정규식escape(v)}\\s*,`, 'g');
    let m;
    while ((m = re.exec(코드))) 이름.add(m[1]);
  }
  return [...이름];
}

/** 위치 인자만 받는 꼴인가 — 낱말이 0일 때만 물어야 하는 질문이다. */
function 위치인자꼴(코드, argv이름) {
  return argv이름.some((v) => {
    const esc = 정규식escape(v);
    return new RegExp(`\\[[^\\]]*\\]\\s*=\\s*${esc}`).test(코드)     // const [a, b] = argv
      || new RegExp(`${esc}\\s*\\[\\s*\\d+\\s*\\]`).test(코드);       // argv[2]
  });
}

/**
 * 도구 하나의 인자 층.
 * @param {string} 코드 `코드만` 을 지난 소스
 * @returns {{argv읽나:boolean, 낱말:string[], 모양:'플래그읽음'|'위치인자'|'모름', 자식후보:string[]}}
 *   `모양`
 *     · `플래그읽음` — 자기 낱말을 하나 이상 읽는다 → 선언은 그 낱말들
 *     · `위치인자`   — `--` 를 아예 안 읽는다 → 선언은 **빈 목록**(모든 `--낱말` 거절)
 *     · `모름`       — 낱말은 0인데 위치 꼴도 아니다 → **사람이 그 파일을 열어 정한다**
 *   ⚠ `모름` 은 「안전」이 아니다. `동봉신호.js` 가 그 자리인데, 그 도구는
 *      `.find((a) => !a.startsWith('--'))` 로 `--` 를 **일부러 버린다** — F435 그 모양이다.
 */
function 인자층(코드) {
  const argv읽나 = /process\.argv/.test(코드);
  if (!argv읽나) return { argv읽나: false, 낱말: [], 모양: '위치인자', 자식후보: [] };
  const argv이름 = argv이름들(코드);
  const 대상 = [...argv이름, ...도우미이름들(코드, argv이름)];
  const 결과 = new Set();
  for (const v of 대상) {
    const esc = 정규식escape(v);
    const 꼴들 = [
      /* argv.includes('--x') · argv.indexOf('--x') */
      new RegExp(`${esc}[^;\\n]{0,100}?\\.(?:includes|indexOf|lastIndexOf)\\(\\s*(['"])(--[^'"]+)\\1`, 'g'),
      /* 인자값(argv, '--조각') — 도우미에 낱말을 넘기는 꼴 */
      new RegExp(`${esc}\\s*\\([^)\\n]{0,60}?(['"])(--[^'"]+)\\1`, 'g'),
      /* argv[i] === '--x' 와 그 반대 순서 */
      new RegExp(`${esc}[^;\\n]{0,140}?===\\s*(['"])(--[^'"]+)\\1`, 'g'),
      new RegExp(`(['"])(--[^'"]+)\\1\\s*===[^;\\n]{0,140}?${esc}`, 'g'),
    ];
    for (const p of 꼴들) { let m; while ((m = p.exec(코드))) if (낱말모양.test(m[2])) 결과.add(m[2]); }
  }
  /* 이미 선언된 목록도 자기 낱말이다 — 게이트를 건 도구는 여기서 자기 축을 스스로 밝힌다. */
  const d = 코드.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
  if (d) for (const w of 낱말들(`[${d[1]}]`)) 결과.add(w);

  const 낱말 = [...결과].sort();
  const 모양 = 낱말.length ? '플래그읽음'
    : (위치인자꼴(코드, argv이름) || 낱말들(코드).length === 0) ? '위치인자' : '모름';
  return { argv읽나: true, 낱말, 모양, 자식후보: 낱말들(코드).filter((w) => !결과.has(w)).sort() };
}

/** 선언한 `아는플래그` — 없으면 `null`(선언 자체가 없다). */
function 선언목록(코드) {
  const m = 코드.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
  return m ? { 원본: m[0], 낱말: 낱말들(`[${m[1]}]`), 공용폄: /\.\.\.공용플래그/.test(m[1]) } : null;
}

const 읽기부름 = (코드) => /자격증명\s*\.\s*읽기\s*\(/.test(코드);
const 정의파일 = /자격증명\.js$/;

/**
 * **조준축** — 그 도구에서 `--운영` 이 «뜻»을 갖는가(= 과녁을 갈아타는가).
 * 이 판정이 부착 처방을 가른다: 있으면 선언에 `...공용플래그` 를 펴고, 없으면 넣지 않는다
 * (없는데 받아 주면 「받은 척」이 초록으로 나간다 · F592 · #Q111 의 `배포빚.js` 선례).
 *
 * ■ 🔴 왜 「직접」만으로는 안 되나 (2026-08-18 실측 · 이 파일의 첫 판이 틀렸다)
 *   옛 분모는 소스에 `자격증명.읽기(` 가 있는 도구 13개였다. 그런데 **`lib/왕복골격.js` 의
 *   `열기()` 가 그 함수를 부른다** — 그래서 `왕복시험`·`교정1건왕복`·`세그먼트재료`·
 *   `업로드왕복시험`·`eval-run` **다섯**이 조준축을 가지면서 그 분모 밖에 있었다.
 *   그중 `세그먼트재료`·`업로드왕복시험` 은 «위치 인자 전용» 이라, 첫 판의 명단이 그 둘에
 *   「선언 = 빈 목록」이라는 처방을 적어 두었다 — **따르면 `--운영` 이 죽는다**(F103 그 모양).
 *
 * ■ 🔴 그리고 한 겹 추적의 첫 판도 틀렸다 — ㉡ 이 이번엔 «문자열»에서 재발했다
 *   `lib/자격증명.js` 169행이 도움말로 `` `자격증명.읽기('<도구>', …)` `` 를 **문자열에** 담는다.
 *   `코드만` 은 문자열을 (정당하게) 지키므로, 그 파일을 「부여자」로 세면 그 파일을 들여온
 *   `앱밟기.js` 가 조준축으로 승격됐다 — 그 도구는 `파일읽기` 만 쓴다(실측 거짓양성).
 *   👉 **정의 파일은 조준축을 부여하지 않는다.** 그 파일을 들여온 도구는 자기가 `읽기(` 를
 *      불러야 조준축이다. ⚠ `\b` 로 못 가른다 — JS 의 `\b` 는 ASCII 경계라 한글에 안 붙고
 *      `파일읽기(` 가 `읽기(` 를 품는다. 그래서 한글 lookbehind 로 가른다.
 *
 * ⚠ **대가**: 상대경로 require 를 **한 겹만** 따라간다(`tools/가드계수.js` 의 불투명 import
 *   판정과 같은 선례·같은 대가). 두 겹짜리 감싸기가 생기면 그 도구는 조용히 「조준축 없음」이
 *   된다 — 적색이 아니라 «처방이 틀리는» 쪽으로 샌다. 실측 0건이고, 생기면 그때 층을 넓힌다.
 *
 * @param {string} 코드 도구 소스(`코드만` 통과분)
 * @param {(상대경로:string)=>string} lib코드 상대 require 경로를 코드로 바꿔 주는 읽기 —
 *   **주입한다.** 픽스처가 파일 없이 이 판정을 시험할 수 있어야 한다(그래야 위 두 오판이 못 돌아온다).
 * @returns {'직접'|'구조분해'|string|null} 한 겹이면 `'한겹:<경로>'` · 없으면 null
 */
function 조준축(코드, lib코드) {
  if (읽기부름(코드)) return '직접';
  const 들여온것 = [...코드.matchAll(/require\(\s*'(\.\.\/lib\/[^']+)'\s*\)/g)].map((m) => m[1]);
  if (들여온것.some((r) => 정의파일.test(r)) && /(?<![가-힣])읽기\s*\(/.test(코드)) return '구조분해';
  const 감염 = 들여온것.filter((r) => !정의파일.test(r) && 읽기부름(lib코드(r) || ''));
  return 감염.length ? `한겹:${감염.join(',')}` : null;
}

/**
 * **분모** — 그 디렉터리에서 `process.argv` 를 «코드로» 읽는 도구 전부.
 * 🔑 목록을 손으로 적지 않는다. 손 목록은 새 도구가 생기는 날 조용히 낡는다(F435 가 정확히 그것).
 * 🔑 그리고 «두 분모를 따로 만들지 않는다» — 자격증명 여부는 여기서 칸으로 내주고,
 *    쓰는 쪽이 거른다(같은 판정을 두 곳에 적으면 갈라진다 · CLAUDE.md 등록층 ④).
 */
function CLI도구들(디렉터리) {
  /* 형제 `lib/` 는 여러 도구가 같이 들여온다 — 한 판에 한 번만 읽는다. */
  const 캐시 = new Map();
  const lib코드 = (상대) => {
    const 절대 = path.resolve(디렉터리, 상대);
    if (!캐시.has(절대)) {
      try { 캐시.set(절대, 코드만(파일소스(절대))); } catch { 캐시.set(절대, ''); }
    }
    return 캐시.get(절대);
  };
  return fs.readdirSync(디렉터리)
    .filter((f) => f.endsWith('.js'))
    .map((f) => {
      const 코드 = 코드만(파일소스(path.join(디렉터리, f)));
      return {
        파일: f,
        코드,
        게이트: /인자게이트\s*\(/.test(코드),
        조준축: 조준축(코드, lib코드),
        선언: 선언목록(코드),
        ...인자층(코드),
      };
    })
    .filter((r) => r.argv읽나);
}

