/* ── ⑤ 통로 재료 — 화면에 안 뜨는 행은 노력 줄의 재료가 못 된다 (판정은 lib · 재료는 통로) ── */

test('통로의 재발화 재료 — 게이트 셋·전량·정렬·매핑이 소스에 실제로 있다', () => {
  /* 🔴 lib 은 화면도 SQL 도 모른다 — 플래그의 «뜻»은 통로가 지므로 여기서 소스로 잰다.
   *   각 항목이 막는 사고(적대 리뷰 2026-08-13 실측):
   *   · 낭독 술어 없음(B1) → ③자유발화·쓰기 제출에 「되말했다」가 붙는 거짓.
   *   · submission.created 없음(H4) → 배정·퀴즈 행의 retry 가 딴 뜻으로 읽힌다.
   *   · 보여줄행 없음 → 학생이 못 본 행이 연속 금지의 「직전」이 되어 다음 줄을 삼킨다.
   *   · 매핑 줄 없음(M13) → 별칭만 남고 값은 늘 undefined — 같은 실패를 오늘과제.test.js:927 이
   *     이미 겪었다(「별칭만 남고 응답 줄이 없으면 값은 늘 undefined」).
   *   · limit(M12) → 「처음이에요」가 창 안의 처음이 되는 거짓 — 조용한 상한은 통과 모양으로 온다.
   *   · asc 정렬(M11) → 굴리기 전체(처음·연속 금지)의 전제. */
  const fs = require('node:fs');
  const 소스 = fs.readFileSync(
    path.join(__dirname, '..', 'supabase', 'functions', 'corrections', 'index.ts'), 'utf8');

  const 사본 = 소스.match(/corrected_text is not null or array_length/g) || [];
  assert.equal(사본.length, 1, '표시 술어가 손사본으로 늘었다 — 갈라지는 날 안 뜬 행이 꼬리를 낸다');
  assert.ok(/and \$\{보여줄행\(\)\}/.test(소스), '목록 WHERE 가 표시 술어 한 벌에서 떨어져 나갔다');

  const 시작 = 소스.indexOf('const 이력행 = await sql`');
  assert.ok(시작 >= 0, '이력행 조회를 소스에서 못 찾았다 — 이 검사 전체가 미실행이다');
  const 조각 = 소스.slice(시작, 소스.indexOf('`', 시작 + 'const 이력행 = await sql`'.length));
  for (const 술어 of [
    '${보여줄행()}',
    "e.event_type = 'submission.created'",
    "s.task_format = '낭독'",
    'e.retry_of_event_id is not null',
    /* 그자리재도전(제2 노력 갈래 · 유호 확정 08-13) 게이트 — 각각이 막는 거짓:
     *   · 말하기 형식 in 술어 없음 → 타자 친 제출(게임·보고서·서류관문)·보기 고르기(`응답`)에
     *     「다시 «말해» 봤다」가 붙는다(B1 과 같은 축).
     *   · 숫자꼴 검사 없음 → payload 는 자유 JSON 이라 행 하나가 조회 전체를 500 으로 만들고,
     *     5xx 는 retryable 이라 앱이 무한 재시도한다(functions/progress 가 겪은 그 자리). */
    "s.task_format in ('낭독', '자유발화')",
    "(e.payload->>'attempt_no') ~ '^[0-9]+$'",
    '::int else 1 end) >= 2',
    'order by c.created_at asc, c.correction_id asc',
  ]) {
    assert.ok(조각.includes(술어), `이력행 조회에서 빠졌다: ${술어}`);
  }
  assert.equal((조각.match(/\$\{보여줄행\(\)\}/g) || []).length, 2,
    '표시 술어가 플래그 둘에 다 곱해져 있지 않다 — 빠진 쪽 플래그가 안 뜬 행에서 서서 다음 줄을 삼킨다');
  assert.ok(!/limit/i.test(조각), '이력행이 잘렸다 — 전량이 아니면 「처음이에요」가 거짓이 된다');

  assert.ok(/재발화:\s*r\.재발화 === true/.test(소스),
    '줄들 매핑에 재발화 줄이 없다 — SQL 별칭만 남으면 값은 늘 undefined 로 「통과」다');
  assert.ok(/그자리재도전:\s*r\.그자리재도전 === true/.test(소스),
    '줄들 매핑에 그자리재도전 줄이 없다 — 별칭만 남으면 제2 노력 갈래가 조용히 죽는다');
});

