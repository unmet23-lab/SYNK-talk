/* 꼬리 회귀 — AI 답장 맨 아래 «한 줄»(철학 Ⅱ-8 둘째 실물 · `lib/꼬리.js`).
 *
 * ■ 세 맹점(CLAUDE.md)
 *   ① **사람이 실제로 쓰는 표기** — 자리 이름 검사는 손 목록이 아니라 **계약 어휘 전량**
 *      (`계약/수집_교정_계약.json` 오류태그 24종)을 통과시킨다. 계약이 늘어도 이 검사가 따라간다.
 *   ② **버그가 아직 있을 것을 요구하지 않는다** — 문구 검사(숫자·비교·점수)의 탐지력은 가짜 문구
 *      픽스처가 지고, 실문구 표에는 **거짓양성 0** 만 본다.
 *   ③ **자기 처방** — 「견줄 어제가 없어서 null」인 이력에 앞선 교정을 붙이면 줄이 실제로 난다.
 *
 * 🔴 이 파일이 지키는 판정 넷(전부 조용히 깨진다 — 새는 방향은 언제나 「통과」다):
 *   · **문턱 0** — 「몇 번 이상 걸렸으면」이 코드에 들어오는 날 빨개진다(한 번짜리 이력으로 잰다).
 *   · **없는 성공을 말하지 않는다** — 오류가 남은 교정에는 꼬리가 안 난다.
 *   · **판정 안 함 ≠ 오류 0** — 빈 `error_tags` 는 분자에도 분모에도 안 들어간다.
 *   · **전량을 받는다** — 최근 N건으로 자르면 「처음이에요」가 거짓이 되는데, 자른 쪽이 더 조용하다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

const {
  무오류표식, 종류들, 문구,
  자리이름, 판정났나, 무오류인가, 잦던태그,
  성립하는것, 글짓기, 줄들, 꼬리한줄,
} = require('../lib/꼬리.js');

const 계약 = require(path.join('..', '계약', '수집_교정_계약.json'));

/** 교정 한 건 — 통로가 주는 모양 그대로(`functions/corrections` 의 select 두 칸). */
const 교정 = (id, ...tags) => ({ correction_id: String(id), error_tags: tags });
const 무오류 = (id) => 교정(id, 무오류표식);
const 미판정 = (id) => ({ correction_id: String(id), error_tags: [] });

/* ── ① 자리 이름 — 계약 어휘 전량 (분모 먼저) ─────────────────────────────── */

test('계약 오류태그 전량이 «학생이 볼 자리 이름»을 낸다 — 하나라도 빈 이름이면 그 태그는 꼬리에서 사라진다', () => {
  const 어휘 = 계약.오류태그;
  assert.ok(Array.isArray(어휘) && 어휘.length >= 20,
    `계약 어휘를 못 읽었다(분모 ${Array.isArray(어휘) ? 어휘.length : '없음'}) — 통과가 아니라 미실행이다`);

  const 빈것 = 어휘.filter((t) => t !== 무오류표식).filter((t) => !자리이름(t));
  assert.deepEqual(빈것, [], `자리 이름이 안 나오는 태그가 있다 — 그 태그가 최빈이면 꼬리가 통째로 안 뜬다`);
});

test('자리 이름은 학생이 «찾아야 하는 글자»를 먼저 쓴다 — 괄호 > 갈래 > 태그', () => {
  assert.equal(자리이름('조사:주격(이/가·은/는)'), '이/가·은/는');
  assert.equal(자리이름('어미:시제'), '시제');
  assert.equal(자리이름('어순'), '어순');
  assert.equal(자리이름(무오류표식), null, '무오류 표식은 「자리」가 아니다');
  assert.equal(자리이름(''), null);
  assert.equal(자리이름(null), null);
});

/* ── ② 문구 — 숫자 0 · 비교 0 · 점수 0 (탐지력은 가짜가 진다) ─────────────── */

/* 🔑 **고유어 수사를 빠뜨리면 이 가드는 정작 필요한 자리에서 샌다** — 철학 본문의 예시가
 *   하필 「지난주엔 **세 번** 틀렸는데」라, 한자어 수사만 세던 첫 판은 그 문장을 통과시켰다
 *   (2026-08-12 실측 · 이 파일의 탐지력 픽스처가 잡았다).
 * 🔑 붙여쓴 낱말은 안 센다 — `이번`·`한글` 이 수사로 읽히면 실문구가 통째로 빨개지고, 그렇게
 *   시끄러운 가드는 곧 꺼진다. 그래서 한글 수사는 **띄어쓰기를 요구**하고 아라비아 숫자만 붙여쓰기를 본다. */
const 한글수사 = '한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|스무|일|이|삼|사|오|육|칠|팔|구|십|백|천|만';
const 단위 = '번|개|회|점|등|군데|가지|자리|줄|문장';
const 금지패턴 = Object.freeze([
  { 이름: '숫자', 정규식: new RegExp(`[0-9]|(?:${한글수사})\\s+(?:${단위})`) },
  { 이름: '남과의 비교', 정규식: /친구|다른 (학생|아이|사람)|평균|등수|순위|반에서/ },
  { 이름: '점수·등급', 정규식: /점수|퍼센트|%|등급|레벨|랭킹/ },
]);

test('실문구 표에 숫자·남과의 비교·점수가 하나도 없다 (거짓양성 0)', () => {
  const 글들 = Object.values(문구);
  assert.equal(글들.length, 종류들.length, '문구 표와 종류 목록이 갈렸다 — 한쪽만 늘면 나머지 검사가 그 종류를 안 본다');
  for (const 글 of 글들) {
    for (const p of 금지패턴) {
      assert.ok(!p.정규식.test(글), `문구에 ${p.이름} 이 들어갔다: ${글}`);
    }
  }
});

test('탐지력 — 가짜 문구를 넣으면 위 검사가 실제로 잡는다', () => {
  const 가짜 = ['지난주엔 세 번 틀렸어요.', '친구들보다 잘했어요.', '오늘 점수는 90% 예요.'];
  for (const 글 of 가짜) {
    assert.ok(금지패턴.some((p) => p.정규식.test(글)), `이 문구를 못 잡는다 — 검사가 헐거워졌다: ${글}`);
  }
});

test('글짓기는 자리가 필요한 틀에 자리가 없으면 «빈 자리»를 남기지 않고 null 을 낸다', () => {
  assert.equal(글짓기('잦던자리', null), null);
  assert.ok(!/\{자리\}/.test(String(글짓기('잦던자리', '이/가'))), '치환이 안 된 채 학생에게 나갔다');
  assert.equal(글짓기('없는종류', '이/가'), null);
});

/* ── ③ 성립 조건 ────────────────────────────────────────────────────────── */

test('첫 교정에는 꼬리가 없다 — 견줄 «어제»가 없다', () => {
  assert.deepEqual(성립하는것(무오류('a'), []), []);
  assert.equal(꼬리한줄([무오류('a')], 'a'), null);
});

test('오류가 남은 교정에는 꼬리가 안 난다 — 없는 성공을 말하지 않는다', () => {
  const 이력 = [교정('a', '조사:주격(이/가·은/는)'), 교정('b', '어미:시제')];
  assert.deepEqual(성립하는것(이력[1], [이력[0]]), []);
  assert.equal(꼬리한줄(이력, 'b'), null);
});

test('판정 안 함(빈 태그)은 분자에도 분모에도 안 들어간다', () => {
  assert.equal(판정났나(미판정('x')), false);
  assert.equal(무오류인가(미판정('x')), false, '빈 배열을 「오류 0」으로 세면 못 잰 것이 성취로 둔갑한다');
  // 앞선 것이 미판정뿐이면 견줄 어제가 없다.
  assert.deepEqual(성립하는것(무오류('b'), [미판정('a')]), []);
});

test('문턱 0 — 앞선 이력에 «한 번» 걸린 자리도 「전에는 걸리던 자리」로 선다', () => {
  const 이력 = [교정('a', '어미:시제'), 무오류('b')];
  const 줄 = 꼬리한줄(이력, 'b');
  assert.ok(줄, '한 번짜리 이력에서 꼬리가 안 났다 — 「몇 번 이상」 문턱이 코드에 들어왔다');
  assert.ok(줄.글.includes('시제') || 줄.종류 === '첫무오류', `자리를 못 짚었다: ${JSON.stringify(줄)}`);
});

test('「처음이에요」는 이력 전체에서 «딱 한 번»만 나간다', () => {
  /* 🔴 이 검사는 **연속 금지에 가려진다** — 이력이 짧으면 두 번째 「처음」이 「직전과 같은
   *   종류」로 걸러져, 조건을 통째로 지워도 초록이 된다(2026-08-12 변이 ③ 실측 · 놓쳤다).
   *   그래서 무오류를 셋 이어 붙여 «가림막이 안 걸리는 자리»를 만들고, 종류를 하나씩 보는 대신
   *   **전체에서 몇 번 나갔나**를 센다. 학생에게 「처음」이 두 번 가는 것이 이 파일이 막는 거짓이다. */
  const 이력 = [교정('a', '어미:시제'), 무오류('b'), 무오류('c'), 무오류('d')];
  const 종류열 = [...줄들(이력).values()].map((v) => v.종류);
  assert.ok(종류열.length >= 3, `줄이 ${종류열.length} 개뿐이다 — 통과가 아니라 미실행이다`);
  assert.equal(종류열.filter((k) => k === '첫무오류').length, 1,
    `「처음이에요」가 ${종류열.filter((k) => k === '첫무오류').length} 번 나갔다: ${종류열.join(' → ')}`);
  assert.equal(종류열[0], '첫무오류', '첫 무오류가 「처음」을 못 받았다 — 그 말은 한 번뿐이라 놓치면 영영 못 준다');
});

test('이력을 «자르면» 거짓이 나간다 — 전량을 받는지 긴 이력으로 잰다', () => {
  /* 🔴 조용한 상한은 통과와 같은 모양으로 온다(2026-08-12 변이 ⑤ 실측 · 짧은 픽스처가 놓쳤다).
   *   먼 옛날에 이미 무오류가 있었던 학생이 오늘 또 무오류를 받는 자리 — 최근 몇 건만 보면
   *   「처음이에요」가 되고 그건 학생에게 거짓말이다. */
  const 이력 = [
    교정('a', '어미:시제'), 무오류('b'),
    교정('c', '어순'), 교정('d', '맞춤법:받침'), 교정('e', '어순'), 교정('f', '어미:종결'),
    무오류('g'),
  ];
  const 줄 = 꼬리한줄(이력, 'g');
  assert.ok(줄, '긴 이력에서 꼬리가 아예 안 났다 — 통과가 아니라 미실행이다');
  assert.notEqual(줄.종류, '첫무오류',
    '먼 옛날 무오류를 못 보고 「처음이에요」를 냈다 — 이력이 잘렸다(자르기의 처방은 자르기가 아니라 집계다)');
});

test('잦던 자리 = 최빈 · 동률이면 더 최근 것 (결정론)', () => {
  const 잦음 = [교정('a', '어미:시제'), 교정('b', '어미:시제'), 교정('c', '어순')];
  assert.equal(잦던태그(잦음), '어미:시제');
  const 동률 = [교정('a', '어미:시제'), 교정('b', '어순')];
  assert.equal(잦던태그(동률), '어순', '동률에서 최근을 안 고르면 같은 이력이 부를 때마다 다른 줄을 낸다');
  assert.equal(잦던태그([]), null);
  assert.equal(잦던태그([무오류('a')]), null, '무오류 표식이 「자리」로 세어졌다');
});

/* ── ④ 굴리기 — 같은 줄 연속 금지 · 결정론 ──────────────────────────────── */

test('같은 줄을 연속으로 내지 않는다 — 이어지는 무오류가 매번 같은 말을 받지 않는다', () => {
  const 이력 = [교정('a', '어미:시제'), 무오류('b'), 무오류('c'), 무오류('d')];
  const 표 = 줄들(이력);
  const 낸것 = ['b', 'c', 'd'].map((k) => (표.get(k) || {}).종류).filter(Boolean);
  assert.ok(낸것.length >= 2, `줄이 거의 안 났다(${낸것.length}) — 통과가 아니라 미실행이다`);
  for (let i = 1; i < 낸것.length; i++) {
    assert.notEqual(낸것[i], 낸것[i - 1], `같은 종류가 연속으로 나갔다: ${낸것.join(' → ')}`);
  }
});

test('결정론 — 같은 이력이면 언제 불러도 같은 줄이다(화면 리렌더에 말이 안 바뀐다)', () => {
  const 이력 = [교정('a', '어미:시제'), 교정('b', '어순'), 무오류('c'), 무오류('d')];
  const 첫판 = JSON.stringify([...줄들(이력)]);
  const 두판 = JSON.stringify([...줄들(이력)]);
  assert.equal(첫판, 두판);
});

test('자기 처방 — 앞선 교정을 붙이면 null 이던 자리에서 실제로 줄이 난다', () => {
  assert.equal(꼬리한줄([무오류('a')], 'a'), null);
  const 줄 = 꼬리한줄([교정('z', '맞춤법:받침'), 무오류('a')], 'a');
  assert.ok(줄 && 줄.글, '처방을 따랐는데도 줄이 안 났다 — 따를 수 없는 처방이다');
});

test('남과의 비교는 «입력에 들어오지도 않는다» — 재료의 성질로 지켜진다', () => {
  const 인자수 = 꼬리한줄.length;
  assert.equal(인자수, 2, `꼬리한줄 이 인자 ${인자수} 개를 받는다 — 남의 이력이 들어올 문이 생겼다`);
});

test('없는 교정을 물으면 null — 빈 자리를 남기지 않는다', () => {
  const 이력 = [교정('a', '어미:시제'), 무오류('b')];
  assert.equal(꼬리한줄(이력, '없는id'), null);
  assert.equal(꼬리한줄(이력, null), null);
  assert.equal(꼬리한줄(null, 'b'), null);
});
