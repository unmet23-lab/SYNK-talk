/* 감사 회귀 R3B1 — 이 조 시공 앵커.
 *   G3-2 ko/mn 줄배열 병기(join 소멸 · i===0 킷폰트) · D1-2 마이크 거절의 다음 걸음(설정 열기)
 *   D5-3 판 종료 도장햅틱(게임 3종 · 알바변명 0 유지) · D4-8 오랜만 복귀 인트로 · D4-9 캐릭터 대본.
 * ⚠ D7-2(교정 큐 배출구)는 tests/교정로그.test.js · G2-2(녹음 복구)는 tests/녹음복구.test.js ·
 *   D7-4(복귀행동 ⓒ)는 tests/말하기로직.test.js 가 진다 — 층이 그쪽 정본이라 여기 겹쳐 적지 않는다. */

const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { 코드만, 파일소스, 코드만픽스처 } = require('./lib/소스검사.js');

const ROOT = path.join(__dirname, '..');
const 소스 = (p) => 코드만(파일소스(path.join(ROOT, ...p.split('/'))));

test('주석 제거기가 산다 — 아래 소스 검사들이 설명을 코드로 읽지 않는다', () => {
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대, '주석 제거기가 죽었다 — 이 파일 전체가 거짓 초록이 된다');
});

/* ── G3-2 — ko/mn 줄배열을 한 덩이로 뭉개던 join(' ') 무늬 소멸 · i===0 킷폰트 병기 ── */

test('G3-2 반응안내·목표반응 호출 뒤 join(당 한 줄 뭉개기) 무늬가 src 에 0건이다', () => {
  const fs = require('node:fs');
  const 걸린것 = [];
  for (const f of fs.readdirSync(path.join(ROOT, 'src')).filter((x) => x.endsWith('.js'))) {
    const 코드 = 소스(`src/${f}`);
    if (/(반응안내|목표반응)\([^)]*\)[^\n]*\.join\(/.test(코드)) 걸린것.push(f);
  }
  assert.deepEqual(걸린것, [],
    `ko/mn 줄배열이 join 으로 한 덩이가 됐다(뒤 줄 몽골어가 킷 한글 폰트를 타 두부가 된다): ${걸린것.join(' · ')}`);
  /* 탐지력 픽스처 — 이 정규식이 옛 무늬를 실제로 문다. */
  assert.ok(/(반응안내|목표반응)\([^)]*\)[^\n]*\.join\(/.test("{(반응안내(확인답) || []).join(' ')}"),
    '정규식이 옛 무늬를 못 잡는다 — 위 0건이 아무것도 안 잰 것이다');
});

test('G3-2 네 자리 전부 i===0 킷폰트 무늬로 선다(막힘카드 병기 눈금)', () => {
  const 교수 = 소스('src/교수멘탈화면.js');
  assert.match(교수, /\(반응안내\(확인답\) \|\| \[\]\)\.map\(\(줄, i\) =>/, '교수멘탈 반응안내가 줄별 렌더가 아니다');
  assert.match(교수, /i === 0 \? s\.관찰 : s\.관찰_병기/, '교수멘탈 병기 갈래가 없다');
  assert.match(교수, /관찰_병기: \{ fontFamily: 몽골어폰트\.캡션/, '교수멘탈 병기 줄이 몽골어폰트를 안 탄다 — 키릴이 두부가 된다');

  const 목표 = 소스('src/목표카드.js');
  assert.match(목표, /\(목표반응\(답\) \|\| \[\]\)\.map\(\(줄, i\) =>/, '목표카드 반응글이 줄별 렌더가 아니다');
  assert.match(목표, /i === 0 \? s\.반응글 : s\.반응글_병기/, '목표카드 반응 병기 갈래가 없다');
  assert.match(목표, /i === 0 \? s\.본문 : s\.본문_병기/, '목표카드 문장 병기 갈래가 없다');
  assert.match(목표, /반응글_병기: \{ fontFamily: 몽골어폰트\.캡션/, '반응 병기 줄이 몽골어폰트를 안 탄다');
  assert.match(목표, /본문_병기: \{ fontFamily: 몽골어폰트\.본문/, '문장 병기 줄이 몽골어폰트를 안 탄다');

  const 말하기 = 소스('src/말하기화면.js');
  assert.match(말하기, /i === 0 \? s\.녹음안내 : s\.녹음안내_병기/, 'AI한줄 병기 갈래가 없다');
  assert.match(말하기, /녹음안내_병기: \{ fontFamily: 몽골어폰트\.캡션/, 'AI한줄 병기 줄이 몽골어폰트를 안 탄다');
});

/* ── D1-2 — 영구 거절의 다음 걸음: 재요청가능이 화면까지 온다 ── */

test('D1-2 마이크준비 — 다시 물을 수 있는 거절은 재요청가능=true 다(설정 문이 함부로 안 선다)', async () => {
  const { 마이크준비, 거절_메시지 } = require('../lib/마이크권한.js');
  const r = await 마이크준비({
    권한요청: async () => ({ granted: false, canAskAgain: true }),
    오디오모드: async () => {},
  });
  assert.equal(r.ok, false);
  assert.equal(r.재요청가능, true, '다시 물을 수 있는 거절인데 영구 거절로 읽었다 — 설정 보내기는 마지막 문이다');
  /* 문장의 정본이 오류 문구 표로 옮겨 앉았다 — 리터럴 사본이 되살아나면 번역이 길을 잃는다. */
  const { 말 } = require('../contents/문구_오류.js');
  assert.equal(거절_메시지, 말('err.mic_denied'), '거절_메시지가 문구 표 파생이 아니다');
  assert.ok(!/거절_메시지 = '/.test(소스('lib/마이크권한.js')), '거절 문구 리터럴이 lib 에 되살아났다');
});

test('D1-2 대기 카드 — 영구 거절(재요청가능=false)에만 「설정 열기」 문이 서고, 문은 설정으로 간다', () => {
  const 말하기 = 소스('src/말하기화면.js');
  assert.match(말하기, /set설정필요\(준비\.재요청가능 === false\)/,
    '마이크준비의 재요청가능을 화면이 버린다 — 영구 거절 학생의 다음 걸음이 없다');
  assert.match(말하기, /\{막힘 && 설정필요 && \(/, '설정 문이 막힘·영구 거절 겹침에만 서지 않는다');
  assert.match(말하기, /Linking\.openSettings\(\)/, '설정 열기가 설정으로 안 간다');
  assert.match(말하기, /set막힘\(null\);\s*set설정필요\(false\);/, '재시도 때 설정필요가 안 걷힌다 — 낡은 문이 남는다');
});

/* ── D5-3 — 판 종료 도장햅틱: 게임 3종 achieve 곁 정확히 1회 · 알바변명 0 유지 ── */

test('D5-3 게임 3종 — achieve 곁에 도장햅틱이 정확히 1회씩 선다(판 종료 문장부호 전용)', () => {
  for (const f of ['src/교수멘탈화면.js', 'src/보고서교정화면.js', 'src/서류관문화면.js']) {
    const 코드 = 소스(f);
    const 햅틱 = [...코드.matchAll(/도장햅틱\(\)/g)];
    assert.equal(햅틱.length, 1, `${f}: 도장햅틱 호출이 ${햅틱.length}회다 — 판 종료 한 자리뿐이어야 한다`);
    /* ⚠ 코드만 이 `catch { /* … *​/ }` 를 통째로 걷는다(JSX 주석 무늬) — catch 뒤 몸을 열어 잰다. */
    assert.match(코드, /try \{ 효과음\('achieve'\); \} catch(?:\s*\{[^}]*\})?\s*try \{ 도장햅틱\(\); \} catch/,
      `${f}: 도장햅틱이 achieve 바로 곁이 아니다 — 소리와 몸이 다른 순간을 찍으면 문장부호가 둘이 된다`);
  }
});

test('D5-3 알바변명화면 소스엔 여전히 0건 — G3 의 판 종료는 말하기화면 완주때 콜백이 진다', () => {
  const 알바 = 소스('src/알바변명화면.js');
  assert.equal([...알바.matchAll(/도장햅틱\(/g)].length, 0,
    '알바변명화면이 햅틱을 직접 낸다 — 소리·햅틱 직접 금지(그 화면 시험 ⑪)와 정면 충돌이다');
  /* G3 몫은 완주때 콜백에 이미 실려 있다(R2B1 D5-6) — 여기서는 존재만 다시 문다(이중 방어). */
  assert.match(소스('src/말하기화면.js'), /완주때=\{\(\) => \{ try \{ 효과음\('achieve'\); 도장햅틱\(\); \}/,
    'G3 완주 콜백에서 도장햅틱이 빠졌다');
});

/* ── D4-8 — 오랜만 복귀 인트로: 순수 판정 + 대본 + 배선 ── */

test('D4-8 오랜만복귀인가 — 로그 0줄 false(첫편지는 복귀가 아니다) · 2일차 false · 3일차 true', () => {
  const { 오랜만복귀인가 } = require('../lib/마스코트생명.js');
  assert.equal(오랜만복귀인가([], '2026-08-31'), false, '생애 첫 만남이 「오랜만」이 됐다');
  assert.equal(오랜만복귀인가([{ date: '2026-08-29' }], '2026-08-31'), false, '2일 비움이 문턱(3일)을 넘었다');
  assert.equal(오랜만복귀인가([{ date: '2026-08-28' }], '2026-08-31'), true, '3일 비움인데 복귀 인트로가 안 선다');
  // 최신 날짜가 정본이다 — 항목 순서와 무관하게 max(date)로 잰다.
  assert.equal(오랜만복귀인가([{ date: '2026-08-01' }, { date: '2026-08-30' }], '2026-08-31'), false);
  assert.equal(오랜만복귀인가([{ date: null }, {}], '2026-08-31'), false, '깨진 항목만 있으면 판정하지 않는다');
});

test('D4-8 대본·배선 — 복귀판 첫 두 걸음만 갈리고, 화면·시퀀서가 그 판을 실제로 문다', () => {
  const { 연출대본 } = require('../lib/마스코트생명.js');
  const 복귀 = 연출대본.말하기인트로복귀;
  assert.ok(Array.isArray(복귀) && 복귀.length === 연출대본.말하기인트로.length, '복귀판 걸음 수가 원판과 다르다');
  assert.deepEqual({ 표정: 복귀[0].표정, 몸짓: 복귀[0].몸짓 }, { 표정: '놀람', 몸짓: '큰점프' }, '첫 걸음이 큰점프 반김이 아니다');
  assert.equal(복귀[1].말, '다시 만나서 반가워요!', '반김 말이 갈렸다(⚠초안 — 바꿨다면 이 단언도 유호님 확정과 함께)');
  for (let i = 2; i < 복귀.length; i++) {
    assert.equal(복귀[i], 연출대본.말하기인트로[i], `뒤 걸음 ${i}가 원판과 딴 객체다 — 두 벌로 적으면 한쪽만 고쳐진다`);
  }
  assert.match(소스('src/말하기화면.js'), /오랜만복귀인가\(로그, date\)\s*\? 연출대본가져오기\('말하기인트로복귀'\)\s*: 연출대본가져오기\('말하기인트로'\)/,
    '인트로 자리가 복귀 판정을 안 탄다');
  assert.match(소스('src/마스코트.js'), /else if \(걸음\.몸짓 === '큰점프'\) 점프\(16\);/,
    '시퀀서가 큰점프를 모른다 — 복귀 첫 걸음이 조용히 무시된다');
});
