/* 감사 회귀 R1B2 — 말하기화면 아홉 자리 시공(D1-3·D1-4·D1-15·D2-1·D2-2·D2-4·D2-8·D2-12·D7-11).
 *
 * 재는 층이 둘이다:
 *   · 첫 렌더로 닿는 것(듣기카드 듣기 전 프레임)은 **실제로 그린다** — 통로는 `tests/lib/화면세우기.js`.
 *   · effect·핸들러 «뒤»라 첫 렌더가 원리상 못 닿는 자리(폴백 사유 조립·복귀 분기·onError 상태)는
 *     **소스로 못박는다**(`tests/화면렌더.test.js` ②-b 와 같은 규율 — 못 재는 검사를 초록으로 두지 않는다).
 * 🔑 이미 다른 파일이 진 판정은 여기서 다시 재지 않는다(한 판정 한 자) — 열람이 onDone 에만 붙는
 *   것은 `tests/오늘과제.test.js` 열람배선이, 복귀행동 줄의 불변은 `tests/말하기로직.test.js` 가 진다. */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { ROOT } = require('./lib/화면세우기.js');
const { 코드만, 파일소스 } = require('./lib/소스검사.js');

const React = require('react');
const { renderToString } = require('react-dom/server');

const 코드 = 코드만(파일소스(path.join(ROOT, 'src', '말하기화면.js')));
const { 듣기카드 } = require(path.join(ROOT, 'src', '말하기화면.js'));

// ── D1-4 — 듣기카드 위계: 듣기가 주버튼, 건너뛰기는 글자층 ─────────────────────

test('D1-4 듣기 전 프레임 — 「♪ 들어보기」와 「듣지 않고 넘어가기」가 함께 선다', () => {
  const 글 = renderToString(React.createElement(듣기카드, { 편지: { 본문: '오늘도 만나서 반가워요' }, 다음() {} }));
  assert.ok(글.includes('♪ 들어보기'), '재생 문이 첫 프레임에 없다 — 듣기 카드의 본동작이 사라졌다');
  assert.ok(글.includes('듣지 않고 넘어가기'), '건너뛰는 문이 없다 — 소리가 안 나오는 기기의 학생이 갇힌다');
  // 전진 주버튼 라벨은 들었다(또는 읽기실패) 뒤에만 — 첫 프레임에 서면 위계가 안 뒤집힌 것이다.
  assert.ok(!글.includes('다 들었어요'), '듣기 전인데 「다 들었어요」가 섰다');
  assert.ok(!글.includes('읽었어요'), '실패한 적 없는데 「읽었어요」가 섰다');
});

test('D1-4 testID 는 «지금 전진시키는 컨트롤»에 얹힌다 — Maestro 두 흐름이 이 id 로 전진한다', () => {
  // 듣기 전 = 건너뛰기 글자층, 들었다/읽기실패 = 전진 주버튼. 게이트가 갈라 동시 렌더는 없다.
  assert.equal((코드.match(/testID="말하기-다들었어요"/g) || []).length, 2,
    '전진 컨트롤 두 갈래(주버튼·건너뛰기 글자층)가 id 를 나눠 들지 않는다');
  assert.match(코드, /<Pressable testID="말하기-다들었어요" onPress=\{다음\} hitSlop=\{10\}>/,
    '건너뛰기 글자층이 id 를 안 들었다 — 듣기 전 프레임에서 Maestro 가 전진할 손잡이가 없다');
});

test('D1-4 킷 밖 색 리터럴이 소각됐다 — 주버튼_대기(rgba)의 소비처가 0이라 함께 사라진다', () => {
  assert.doesNotMatch(코드, /주버튼_대기/, '주버튼_대기가 되살아났다 — 위계 뒤집기 전의 잔재다');
  assert.doesNotMatch(코드, /rgba\(246,\s*241,\s*232/, 'src 유일 킷 밖 색값이 되살아났다(테마 토큰만 · 킷 규율)');
});

// ── D1-15 — 재생 실패를 「들었다」로 접지 않는다 ───────────────────────────────

test('D1-15 onError 는 읽기실패를 세우고 「들었다」는 세우지 않는다 (소스층 — 핸들러는 첫 렌더 밖)', () => {
  assert.match(코드, /onError: \(\) => \{\s*set읽는중\(false\);\s*set읽기실패\(true\);\s*\},/,
    'onError 가 들었다를 세운다 — 못 들은 학생에게 들은 것처럼 말한다(관측 뜻 갈아타기)');
  // 실패 뒤의 전진 라벨 — 「읽었어요」(글로 읽은 사실 그대로). 들었다면 「다 들었어요」.
  assert.match(코드, /들었다 \? '다 들었어요' : '읽었어요'/, '실패 갈래의 전진 라벨이 없다 — 실패가 「다 들었어요」로 선다');
  assert.match(코드, /\{읽기실패 && !들었다 && \(\s*<Text style=\{s\.녹음안내\}>소리 대신 글로 읽어 볼까요\?/,
    '실패 안내 줄이 없다 — 학생은 왜 소리가 안 나는지 모른 채 버튼만 본다');
  // 재시도 성공이 안내를 걷는다 — onDone 에 리셋 한 줄.
  assert.match(코드, /set들었다\(true\);\s*set읽기실패\(false\);/, '재시도가 끝까지 가도 실패 안내가 안 걷힌다');
});

// ── D1-3 · D7-11 — 폴백 사유: 학생 문장과 기계 원인을 가른다 ──────────────────

test('D1-3 폴백 사유 조립 — raw 오류문이 학생 문장의 괄호에서 빠지고, 원인·첫만남이 제 칸에 선다', () => {
  assert.match(코드, /결과\.사유 = '오늘 과제를 다시 받아 볼게요!';/, '학생 문장이 바뀌었거나 원인이 도로 괄호에 박혔다');
  assert.doesNotMatch(코드, /다시 받아 볼게요! \(/, 'raw 영어 오류문이 학생 문장 괄호로 되살아났다');
  assert.match(코드, /결과\.사유원인 = 토큰 \? String\(e\.message \|\| e\) : null;/,
    '원인 칸이 없다 — 명랑은 말투지 정보 삭제가 아니다(원인은 남는다)');
  assert.match(코드, /결과\.첫만남 = 기록\.length === 0;/,
    '첫만남 판정이 없다 — 이 기기 전 생애 로그 0줄이 그 눈금이다(catch 스코프의 기록)');
});

test('D1-3 첫 만남의 폴백엔 「연습 문장」 메모가 안 선다 — 관측은 degraded 행이 진다 (소스층 — effect 뒤)', () => {
  assert.match(코드, /\{!과제\.첫만남 && <Text style=\{s\.메모\}>오늘은 연습 문장으로 말해요 — \{과제\.사유\}<\/Text>\}/,
    '메모가 첫만남 게이트 없이 선다 — 처음 온 학생이 「연습 문장으로 말해요」라는 비교문을 듣는다');
});

test('D7-11 조판 — 학생의 다음 걸음이 앞, 기계 원인은 모노 아래 줄(메모 본문에 안 섞인다)', () => {
  assert.match(코드, /\{과제\.사유원인 \? <Text style=\{s\.사유원인\}>\{과제\.사유원인\}<\/Text> : null\}/,
    '원인 줄이 제 스타일로 안 선다 — 학생 문장과 기계 원인이 한 줄에 섞인다');
  assert.doesNotMatch(코드, /s\.메모\}>[^<]*\{과제\.사유원인\}/, '사유원인이 s.메모 본문에 섞였다');
  assert.match(코드, /사유원인: \{ fontFamily: 폰트\.모노, fontSize: 11, letterSpacing: 모노트래킹\.라벨, color: 색\.잉크_보조 \}/,
    '원인 줄 스타일이 막힘카드 「모르는 코드 메모」 무늬(모노 11·라벨 트래킹·잉크_보조)가 아니다');
});

// ── D2-1 — 「생성중」이 손 안 대도 스스로 갱신된다 ────────────────────────────

test('D2-1 생성중 폴링 효과와 복귀 즉시 재조회 분기가 산다', () => {
  assert.match(코드, /if \(서버생성상태 !== '생성중'\) return undefined;/, '폴링 효과의 게이트가 없다');
  assert.match(코드, /setInterval\(\(\) => set세대\(\(n\) => n \+ 1\), 25000\)/,
    '주기 재조회가 없다 — 생성중 화면의 학생은 앱을 껐다 켜야 과제를 만난다');
  assert.match(코드, /return \(\) => clearInterval\(t\);/, '폴링 타이머를 안 걷는다 — 화면이 사라져도 세대가 돈다');
  assert.match(코드, /if \(생성상태참조\.current === '생성중'\) \{ set세대\(\(n\) => n \+ 1\); return; \}/,
    '복귀 즉시 1회 분기가 없다 — 배경에서 돌아온 학생이 다음 폴링까지 옛 화면을 본다');
  // ref 는 두 갈래(성공·실패)에서 다 적힌다 — 리스너는 낡은 state 를 본다(막힘참조와 같은 이유).
  assert.ok((코드.match(/생성상태참조\.current = /g) || []).length >= 2,
    '생성 상태 ref 를 한 갈래만 적는다 — 서버를 못 받은 날 복귀 분기가 옛 값을 본다');
});

// ── D2-2 — 못 보낸 목소리를 그 자리에서 다시 밀어 볼 문 ───────────────────────

