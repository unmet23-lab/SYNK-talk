'use strict';
/* 곡장부 — Reed 첫 기둥의 회귀.
 * 🔴 이 스위트가 지키는 것 셋: ①재현 칸이 「모른다」를 통과시키지 않는 것
 *   ②«못 잰 것»이 «통과»로 접히지 않는 것(새는 방향은 언제나 「통과」다)
 *   ③채택 문턱이 상태 전이의 «문»에 실제로 걸려 있는 것(프로즈로만 있으면 안 지켜진다)
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const 장 = require('../lib/곡장부.js');

const 성한곡 = (덧 = {}) => ({
  id: 'r001', 제목: '여름날', 장르: '시티팝', 결: '아침', DJ: '까몽',
  판: 'v1', 재현: 'node tools/… --씨 101', 길이초: 400, 상태: '후보',
  BPM: 114, 밝기: 0.8,
  측정: { 라우드니스LUFS: -14.0, 피크dBTP: -1.4, 이음새: 0.02, 곡내최대점프: 0.07 },
  ...덧,
});

test('성한 곡은 흠 0', () => {
  assert.deepEqual(장.곡검증(성한곡()), []);
});

test('흠은 «첫 하나»가 아니라 전부 낸다 — 100곡을 한 흠씩 고치면 100번을 100번 돈다', () => {
  const 흠 = 장.곡검증({ id: 'x' });
  assert.ok(흠.length >= 5, `빠진 칸이 여럿인데 흠이 ${흠.length}개다`);
});

test('🔴 재현 칸 — 「모른다」류는 안 받는다. «없음» 이라고 명시해야 통과한다', () => {
  assert.deepEqual(장.곡검증(성한곡({ 재현: '없음' })), []);
  assert.ok(장.곡검증(성한곡({ 재현: '??' })).some((x) => x.includes('재현')));
  assert.ok(장.곡검증(성한곡({ 재현: '' })).some((x) => x.includes('재현')));
});

test('🔴 «없음» 인 곡은 고칠 수 없다 — 그 사실이 값으로 남아야 센다', () => {
  assert.equal(장.고칠수있나(성한곡()), true);
  assert.equal(장.고칠수있나(성한곡({ 재현: '없음' })), false);
  assert.equal(장.요약([성한곡(), 성한곡({ id: 'r2', 재현: '없음' })]).못고침, 1);
});

test('목록 밖 값은 거절한다 — 장르·결·상태', () => {
  assert.ok(장.곡검증(성한곡({ 장르: '록' })).some((x) => x.includes('장르')));
  assert.ok(장.곡검증(성한곡({ 결: '한낮' })).some((x) => x.includes('결')));
  assert.ok(장.곡검증(성한곡({ 상태: '보류' })).some((x) => x.includes('상태')));
});

test('🔴 길이 문턱 — 6분(360초) 미만은 방송 판이 아니다(§3-B 산수)', () => {
  const r = 장.채택판정(성한곡({ 길이초: 200 }));
  assert.equal(r.선다, false);
  assert.ok(r.흠.some((x) => x.includes('360초')));
  assert.equal(장.채택판정(성한곡({ 길이초: 360 })).선다, true, '정확히 문턱이면 선다');
});

test('🔴 «못 잰 것»은 «통과»가 아니다 — 새는 방향이 언제나 「통과」다', () => {
  const r = 장.채택판정(성한곡({ 측정: { 피크dBTP: -1.4, 이음새: 0.02, 곡내최대점프: 0.07 } }));
  assert.equal(r.선다, false);
  assert.deepEqual(r.흠, [], '못 잰 것은 «흠»이 아니라 «못 잰 것»이다 — 두 갈래를 뭉치지 않는다');
  assert.deepEqual(r.못잰것, ['라우드니스']);
});

test('라우드니스는 목표 ±허용 안에만 — 크든 작든 갈린다', () => {
  assert.equal(장.채택판정(성한곡({ 측정: { ...성한곡().측정, 라우드니스LUFS: -14.9 } })).선다, true);
  assert.equal(장.채택판정(성한곡({ 측정: { ...성한곡().측정, 라우드니스LUFS: -16 } })).선다, false);
  assert.equal(장.채택판정(성한곡({ 측정: { ...성한곡().측정, 라우드니스LUFS: -12 } })).선다, false);
});

test('🔴 루프 이음새는 «그 곡 자신»과 견준다 — 절대 문턱이면 조용한 곡과 빽빽한 곡이 갈린다', () => {
  const 빽빽 = 성한곡({ 측정: { ...성한곡().측정, 이음새: 0.03, 곡내최대점프: 0.05 } });
  const 조용 = 성한곡({ 측정: { ...성한곡().측정, 이음새: 0.03, 곡내최대점프: 0.01 } });
  assert.equal(장.채택판정(빽빽).선다, true, '같은 0.03 인데 빽빽한 곡에서는 안 들린다');
  assert.equal(장.채택판정(조용).선다, false, '같은 0.03 이 조용한 곡에서는 턱이 된다');
});

test('🔴 채택 문턱이 «상태 전이의 문»에 실제로 걸려 있다 — 프로즈로만 있으면 안 지켜진다', () => {
  const 짧은곡 = 성한곡({ 길이초: 100 });
  const r = 장.상태바꾸기(짧은곡, '채택');
  assert.equal(r.됐나, false);
  assert.match(r.사유, /규격 문턱/);
  assert.equal(r.곡.상태, '후보', '실패하면 원래 곡을 그대로 돌려준다(반쯤 바뀐 곡을 만들지 않는다)');
});

test('은퇴는 문턱 없이 간다 — 빼는 방향은 언제나 안전하다', () => {
  const r = 장.상태바꾸기(성한곡({ 길이초: 100 }), '은퇴');
  assert.equal(r.됐나, true);
  assert.equal(r.곡.상태, '은퇴');
});

test('은퇴한 곡을 다시 채택할 수 있다 — 실제로 생기는 일이라 되돌릴 수 있게 둔다', () => {
  const r = 장.상태바꾸기(성한곡({ 상태: '은퇴' }), '채택');
  assert.equal(r.됐나, true);
});

test('없는 길은 사유를 내고 «던지지 않는다» — 100곡 들일 때 한 건이 전체를 죽이면 안 된다', () => {
  const r = 장.상태바꾸기(성한곡({ 상태: '채택' }), '후보');
  assert.equal(r.됐나, false);
  assert.match(r.사유, /없는 길/);
});

test('요약은 «합계 = 갈래 + 갈래»로 낸다 — 좋은 0과 「안 재봤다」를 가른다', () => {
  const 장부 = [성한곡(), 성한곡({ id: 'b', 상태: '채택' }), 성한곡({ id: 'c', 상태: '은퇴' }), { id: 'd' }];
  const s = 장.요약(장부);
  assert.equal(s.전체, s.후보 + s.채택 + s.은퇴 + s.모름);
  assert.equal(s.모름, 1, '상태를 모르는 행이 조용히 사라지지 않는다');
  assert.deepEqual(s.장르별, { 시티팝: 1 }, '장르별은 «채택된 것»만 센다(풀의 실제 크기)');
});
