'use strict';
/** 몽글 목소리 배치 회귀 — 「많이 넣되 우겨넣지 않기」(유호 08-25)의 기계 자리.
 *
 * 화면 회귀(`마스코트배선`)는 «어느 자리가 어느 상황인가»를 보고, 이 파일은 «그 상황에서
 * 어떤 소리가 나는가»를 본다. 둘이 갈라지면 오답 옆에서 밝은 소리가 나거나, 같은 소리가
 * 연달아 나 「또 그 소리」가 된다 — 증상이 「어쩐지 단조롭다」라 눈으로는 못 잡는 자리다. */

const test = require('node:test');
const assert = require('node:assert/strict');
const { 소리들, 배치, 상황들, 흔들폭, 겹침막기ms, 목소리판정 } = require('../lib/몽글목소리.js');
const { 목소리이름 } = require('../lib/소리게이트.js');

test('어휘 — 12종이 게이트 화이트리스트와 1:1 이다(사본 금지)', () => {
  const 자산들 = Object.values(소리들);
  assert.equal(자산들.length, 12);
  assert.deepEqual([...자산들].sort(), [...목소리이름].sort(),
    '배치가 아는 소리와 게이트가 허용하는 소리가 갈렸다 — 한쪽에만 있는 소리는 영원히 무음이거나 영원히 막힌다');
});

test('배치 — 상황마다 소리가 있고, 이름은 전부 실재한다', () => {
  assert.deepEqual(상황들, ['기본', '기쁨', '물음', '안심', '잠결', '완료축하']);
  for (const 상황 of 상황들) {
    assert.ok(배치[상황].length >= 1, `${상황} 자리가 비었다`);
    for (const 소리 of 배치[상황]) {
      assert.ok(소리들[소리], `${상황} 에 없는 소리(${소리})가 배치됐다 — 그 자리는 무음이 된다`);
    }
  }
});

test('🔴 오류 자리(안심)에는 내려앉는 소리만 — 기쁨·물음 소리가 섞이지 않는다', () => {
  /* 기죽는 반응 금지 확정의 소리판. 밝은 자리의 소리가 이 줄에 끼면 오답 옆에서 밝게 들린다. */
  const 밝은것 = new Set([...배치.기쁨, ...배치.물음]);
  for (const 소리 of 배치.안심) {
    assert.ok(!밝은것.has(소리), `안심 자리에 밝은 소리(${소리})가 놓였다`);
  }
  assert.ok(배치.안심.length >= 2, '안심 후보가 하나뿐이면 오류가 반복될 때 같은 소리만 난다');
});

test('다양함 ② — 같은 상황에서 직전 소리를 피한다(연속 반복 차단)', () => {
  const 지금 = 1_000_000;
  for (const 상황 of 상황들) {
    if (배치[상황].length < 2) continue;      // 완료축하는 하루 한 번이라 반복이 없다
    for (const 직전 of 배치[상황]) {
      for (const 고르기 of [0, 0.49, 0.99]) {
        const 답 = 목소리판정({ 상황, 지금, 마지막: 0, 직전소리: 직전, 고르기 });
        assert.notEqual(답.소리, 직전, `${상황}: 직전(${직전})과 같은 소리가 또 났다`);
      }
    }
  }
});

test('다양함 ② — 난수를 흔들면 상황 안 후보가 «전부» 나온다(한쪽만 쏠리지 않는다)', () => {
  const 지금 = 2_000_000;
  for (const 상황 of 상황들) {
    const 나온것 = new Set();
    for (let i = 0; i < 40; i++) {
      나온것.add(목소리판정({ 상황, 지금, 마지막: 0, 고르기: i / 40 }).소리);
    }
    assert.equal(나온것.size, 배치[상황].length,
      `${상황}: 후보 ${배치[상황].length}종 중 ${나온것.size}종만 난다 — 나머지는 죽은 자산이다`);
  }
});

test('다양함 ③ — 미세 변주는 매번 다르고 폭은 ±3% 를 안 넘는다', () => {
  const 지금 = 3_000_000;
  const 속도 = (흔들) => 목소리판정({ 상황: '기본', 지금, 마지막: 0, 흔들 }).속도;
  assert.equal(속도(0.5), 1, '가운데 난수인데 속도가 1 이 아니다');
  assert.ok(Math.abs(속도(0) - (1 - 흔들폭)) < 1e-6);
  assert.ok(Math.abs(속도(1) - (1 + 흔들폭)) < 1e-6);
  assert.ok(흔들폭 <= 0.05, '변주 폭이 5% 를 넘는다 — 같은 소리로 안 들린다');
});

test('🚫 겹침막기 — 가장 긴 소리보다 길다(꼬리까지 안 포갠다)', () => {
  const 지금 = 4_000_000;
  assert.equal(목소리판정({ 상황: '기본', 지금, 마지막: 지금 - 100 }).낼까, false);
  assert.equal(목소리판정({ 상황: '기본', 지금, 마지막: 지금 - (겹침막기ms - 1) }).낼까, false);
  assert.equal(목소리판정({ 상황: '기본', 지금, 마지막: 지금 - 겹침막기ms }).낼까, true);
  /* 가장 긴 소리 = 모오옹 669ms. 이보다 짧으면 두 소리가 포개져 웅얼거린다. */
  assert.ok(겹침막기ms > 669, `겹침막기(${겹침막기ms})가 가장 긴 소리보다 짧다`);
  assert.equal(목소리판정({ 상황: '기쁨', 지금, 마지막: 지금 - 50 }).낼까, false,
    '상황만 바꿔 겹침을 우회했다');
});

test('모르는 상황은 «무음»이 아니라 «기본»이다 (오타가 침묵을 정하지 않는다)', () => {
  const 답 = 목소리판정({ 상황: '없는상황', 지금: 5_000_000, 마지막: 0 });
  assert.equal(답.낼까, true, '오타 때문에 몽글이 입을 닫았다 — 침묵은 게이트만 정한다');
  assert.ok(배치.기본.includes(답.소리));
});

test('예비 소리(무우)는 어떤 배치에도 안 쓴다 — 쓰이면 그날 배치에 등재한다', () => {
  const 쓰인것 = new Set(Object.values(배치).flat());
  assert.ok(!쓰인것.has('무우'), '예비가 조용히 배치에 들어갔다 — 어느 상황인지 적어야 한다');
  assert.ok(소리들.무우, '예비 자산이 사라졌다');
});
