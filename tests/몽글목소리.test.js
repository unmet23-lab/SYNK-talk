'use strict';
/** 몽글 목소리 판정 회귀 — 「많이 넣되 우겨넣지 않기」(유호 08-25)의 기계 자리.
 *
 * 화면 회귀(`마스코트배선`)는 «어느 자리에 어느 표정»을 보고, 이 파일은 «그 표정이 실제로
 * 어떤 속도가 되는가»와 «겹침을 막는가»를 본다. 둘이 갈라지면 소리가 겹쳐 웅얼거리거나
 * 표정이 사라진다 — 증상이 「어쩐지 기계 같다」라 눈으로는 못 잡는 자리다. */

const test = require('node:test');
const assert = require('node:assert/strict');
const { 표정속도, 표정들, 흔들폭, 겹침막기ms, 목소리판정 } = require('../lib/몽글목소리.js');

test('표정 다섯 — 어휘와 순서(밝음→어두움)가 정본대로다', () => {
  assert.deepEqual(표정들, ['기쁨', '물음', '기본', '안심', '잠결']);
  /* 🔑 순서가 곧 뜻이다 — 기쁨이 가장 빠르고(높고) 잠결이 가장 느리다(낮다).
     이 단조성이 깨지면 「오류 자리가 기쁨보다 밝다」 같은 일이 소리에서 벌어진다. */
  const 속도들 = 표정들.map((t) => 표정속도[t]);
  for (let i = 1; i < 속도들.length; i++) {
    assert.ok(속도들[i] < 속도들[i - 1], `${표정들[i]} 가 ${표정들[i - 1]} 보다 느리지 않다 — 표정 사다리가 무너졌다`);
  }
  assert.equal(표정속도.기본, 1.0, '기본이 1.0 이 아니다 — 원음이 곧 기본이라는 약속이 깨졌다');
});

test('🔴 오류 자리의 «안심»은 기본보다 반드시 느리다 (기죽는 반응 금지의 소리판)', () => {
  assert.ok(표정속도.안심 < 표정속도.기본, '안심이 기본보다 빠르다 — 오답 옆에서 밝게 들린다');
  assert.ok(표정속도.기쁨 > 표정속도.기본, '기쁨이 기본보다 느리다 — 좋은 순간이 안 밝다');
});

test('겹침막기 — 같은 소리가 연달아 나지 않는다(웅얼거림 방지)', () => {
  const 지금 = 1_000_000;
  assert.equal(목소리판정({ 표정: '기본', 지금, 마지막: 지금 - 100 }).낼까, false, '100ms 만에 두 번째가 지나갔다');
  assert.equal(목소리판정({ 표정: '기본', 지금, 마지막: 지금 - (겹침막기ms - 1) }).낼까, false, '문턱 직전이 지나갔다');
  assert.equal(목소리판정({ 표정: '기본', 지금, 마지막: 지금 - 겹침막기ms }).낼까, true, '문턱을 넘었는데 막혔다');
  assert.equal(목소리판정({ 표정: '기본', 지금, 마지막: 0 }).낼까, true, '첫 소리가 막혔다');
  /* 소리 자체가 297ms 다 — 문턱은 그보다 길어야 꼬리까지 안 겹친다. */
  assert.ok(겹침막기ms > 297, '겹침막기가 소리 길이보다 짧다 — 꼬리가 다음 소리와 포갠다');
});

test('미세 변주 — 매번 같은 속도가 아니고, 폭은 ±3% 를 안 넘는다', () => {
  const 지금 = 2_000_000;
  const 재기 = (흔들) => 목소리판정({ 표정: '기본', 지금, 마지막: 0, 흔들 }).속도;
  assert.equal(재기(0.5), 1.0, '흔들 0.5(가운데)인데 속도가 바탕값이 아니다');
  const 최저 = 재기(0), 최고 = 재기(1);
  assert.ok(최저 < 1 && 최고 > 1, '난수 양끝에서 속도가 안 흔들렸다 — 표정 안에서 기계가 된다');
  assert.ok(Math.abs(최저 - (1 - 흔들폭)) < 1e-6, `아래쪽 폭이 ${흔들폭} 가 아니다: ${최저}`);
  assert.ok(Math.abs(최고 - (1 + 흔들폭)) < 1e-6, `위쪽 폭이 ${흔들폭} 가 아니다: ${최고}`);
  /* 🔑 폭이 너무 크면 «다른 소리»로 들린다 — 목소리의 동일성이 깨진다. */
  assert.ok(흔들폭 <= 0.05, '미세 변주 폭이 5% 를 넘는다 — 같은 캐릭터로 안 들린다');
});

test('모르는 표정은 «무음»이 아니라 «기본»이다 (오타가 침묵을 정하지 않는다)', () => {
  const 답 = 목소리판정({ 표정: '없는표정', 지금: 3_000_000, 마지막: 0 });
  assert.equal(답.낼까, true, '오타 때문에 몽글이 입을 닫았다 — 침묵은 게이트만 정한다');
  assert.equal(답.속도, 표정속도.기본);
});

test('표정이 달라도 겹침막기는 똑같이 적용된다 (표정을 바꿔 우회할 수 없다)', () => {
  const 지금 = 4_000_000;
  assert.equal(목소리판정({ 표정: '기쁨', 지금, 마지막: 지금 - 50 }).낼까, false,
    '표정만 바꿔 겹침을 우회했다 — 두 소리가 포개져 웅얼거린다');
});
