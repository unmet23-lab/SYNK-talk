/* 보고서교정화면 회귀 — G2 화면을 **실제로 그려 본다**(`tests/lib/화면세우기.js` · F268 계열).
 *
 * 재는 것: ① 세 상태가 그리다 죽지 않고 정본 값을 글자로 낸다 ② 🔴 **정답이 화면에 0**
 * (기준 교정문·오류태그·자리) ③ 앉음 «안» 피드백 0(맞다·틀리다라는 글자가 없다) ④ 숨은 시계
 * (시간·숫자·퍼센트 0) ⑤ controlled TextInput 금지(소스층 — 핸들러는 첫 렌더가 못 돈다)
 * ⑥ 화면이 편성·스냅샷을 **직접 조립하지 않는다**(소스층 — 조립이 두 곳이면 행과 화면이 갈린다)
 * ⑦ 학생 접점 금칙어 0 ⑧ 말하기화면 G2 갈래의 실재(소스층 — 갈래는 effect 뒤라 첫 렌더 밖이다).
 * 탐지력(깨진 화면을 정말 잡는가)은 `화면렌더.test.js` ⑤ 픽스처가 이미 못박았다 — 같은 통로다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { 그리기, ROOT } = require('./lib/화면세우기.js');
const { 코드만 } = require('./lib/소스검사.js');

const 소스 = fs.readFileSync(path.join(ROOT, 'src', '보고서교정화면.js'), 'utf8');

/* 픽스처는 **실팩 + 실조립기**로 짓는다 — 화면이 읽는 모양을 여기 또 적으면 두 벌이다.
 * 게이트(`검수확정=false`)만 비켜 간다: `앉음재료` 는 실팩에서 늘 null 이라(그 fail-closed 는
 * `보고서교정제출.test.js` ⑦ 이 따로 못박는다) 확정된 날의 산출을 같은 조립기로 여기서 편다. */
const 팩 = require(path.join(ROOT, 'contents', '보고서교정문항.js'));
const { G2스냅샷 } = require(path.join(ROOT, 'lib', '게임스냅샷.js'));

const 앵커 = 팩.문항목록().find((id) => !팩.대조문항인가(id));
assert.ok(앵커, '팩에 오류 문항이 없다 — 픽스처 전제가 깨졌다');
const 편성 = 팩.앉음편성(앵커);
assert.ok(편성 && 편성.length === 3, '앉음편성이 3턴을 못 냈다');

const 벌 = 편성.map((문항id) => {
  const 스냅샷 = G2스냅샷(문항id);
  assert.ok(스냅샷, `${문항id}: 스냅샷을 못 폈다`);
  return {
    문항id,
    스냅샷,
    보기: 스냅샷.보기,
    task_ref: 'task-2026-08-12',
    level_snapshot: 'Lv2',
    goal_snapshot: null,
    retry_of_event_id: null,
  };
});

const 그때 = (덧 = {}) => 그리기('src/보고서교정화면.js', {
  벌, 토큰: 'x', 학생번호: 'SYNK-042', ...덧,
});

/* synk-brand 바닥 검사 — 활용형까지 어간으로(교수멘탈화면.test.js 와 같은 자) */
const 금칙꼴 = [/패배/, /졌다/, /실패/, /불운/, /하락/, /부족/, /안\s?됨/, /늦/];

test('① 짚기 — 상황 한 줄·어절 전부·「고칠 곳 없음」이 선다(발주 G2 §4-1~3)', () => {
  const 글 = 그때();
  assert.ok(글.includes(벌[0].스냅샷.지시문), '상황문이 없다 — 팩 정본이 그리는 재료다');
  for (const o of 벌[0].보기) {
    assert.ok(글.includes(o.label), `어절이 빠졌다: ${o.label} — 이 목록이 곧 「짚을 수 있었던 자리」의 분모다`);
  }
  assert.match(글, /고칠 곳 없음/, '「고칠 곳 없음」이 없다 — 과잉 교정 성향의 유일한 계기판이 사라진다');
  assert.match(글, /한 군데만/, '한 자리만 짚는다는 규칙이 화면에 없다');
});

test('① 고침 — 짚은 어절 자리에 입력칸·제출·되짚기 길이 선다', () => {
  const 자리 = 벌[0].보기[0].option_id;
  const 글 = 그때({ 시작단계: '고침', 시작짚은것: 자리 });
  assert.match(글, /짚은 자리만 고쳐 써요/, '고침 카드가 안 선다');
  assert.match(글, /제출/, '주행동이 없다');
  assert.match(글, /다른 데를 짚을래요/, '되짚는 길이 없으면 잘못 짚은 학생이 갇힌다');
  assert.match(글, /비우면 그 어절을 지우는 것/, '빈 입력의 뜻을 안 알려 준다(지우는 교정이 정상 입력이다)');
});

test('① 대기 — 「선생님이 보고 알려줄게」 · 즉답처럼 보이지 않는다', () => {
  const 글 = 그때({ 시작단계: '대기' });
  assert.match(글, /선생님이 보고 알려줄게/, '설계 문구(§4 피드백)가 화면에 없다');
  assert.match(글, /답장/, '어디서 보게 되는지를 안 알려 준다');
});

test('🔴 ② 정답이 화면에 0 — 기준 교정문·오류태그·자리가 어느 상태에도 안 뜬다', () => {
  /* 정답이 기기 «화면»에 뜨면 이 게임이 재는 것은 탐지 능력이 아니라 「정답을 봤나」가 된다.
   * 스냅샷 층은 `게임스냅샷.test.js` ⑤(학생공개키)가 지고, 여기는 **그려진 글자**를 잰다. */
  const 상태들 = [그때(), 그때({ 시작단계: '고침', 시작짚은것: 벌[0].보기[0].option_id }), 그때({ 시작단계: '대기' })];
  for (const 하나 of 벌) {
    const 펴진 = 팩.펴기(하나.문항id);
    if (!펴진.교정문) continue; // 대조 문항엔 정답 자체가 없다
    for (const 글 of 상태들) {
      assert.ok(!글.includes(펴진.교정문), `기준 교정문이 화면에 떴다: ${하나.문항id}`);
      assert.ok(!글.includes(펴진.오류태그), `오류태그가 화면에 떴다: ${펴진.오류태그}`);
    }
  }
});

test('🔴 ③ 앉음 «안» 피드백 0 — 맞다·틀리다라는 글자가 어느 상태에도 없다', () => {
  /* 1턴에 판정을 주면 2·3턴의 지목·지연이 탐지 능력이 아니라 방금 받은 힌트의 반응이 된다.
   * 게다가 이 기기엔 정답이 없어 판정할 재료 자체가 없다 — 있는 척하는 글자를 막는다. */
  const 판정꼴 = [/맞았/, /맞아요/, /틀렸/, /틀려/, /정답/, /오답/, /점수/];
  for (const 글 of [그때(), 그때({ 시작단계: '고침', 시작짚은것: 벌[0].보기[0].option_id }), 그때({ 시작단계: '대기' })]) {
    for (const 꼴 of 판정꼴) assert.ok(!꼴.test(글), `판정 글자 「${꼴}」 — 앉음 안 피드백은 0이다`);
  }
});

test('④ 숨은 시계 — 시간·숫자·퍼센트가 화면에 0 이다(유호 확정 · 발주 §6)', () => {
  /* 몇 번째 문장인지도 숫자로 안 낸다 — 칸으로만 낸다(진행 표시는 점수가 아니다). */
  for (const 글 of [그때(), 그때({ 시작단계: '고침', 시작짚은것: 벌[0].보기[0].option_id }), 그때({ 시작단계: '대기' })]) {
    const 학생글 = 글.replace(/SYNK-\d+/g, ''); // 학생번호는 화면 장식이 아니라 신원이다
    assert.ok(!/\d/.test(학생글), `화면에 숫자가 있다: ${학생글.match(/.{0,20}\d.{0,20}/)}`);
    assert.ok(!/[%초분]\b/.test(학생글), '시간·퍼센트 표기가 있다');
  }
});

test('⑤ controlled TextInput 금지 — 값은 ref 로만(한글 조합이 깨지면 우리 버그가 라벨이 된다)', () => {
  const 코드 = 코드만(소스);
  assert.equal([...코드.matchAll(/<TextInput/g)].length, 1, '입력 칸은 짚은 자리 하나다');
  assert.match(코드, /defaultValue=/, 'defaultValue 가 없다 — controlled 로 돌아갔다');
  assert.ok(!/<TextInput[^>]*\svalue=/.test(코드), 'TextInput 에 value= 가 붙었다 — 매 글자 되돌려 넣으면 조합이 깨진다');
  assert.match(코드, /입력참조\.current = t/, '입력 최신본을 ref 가 안 쥔다');
});

test('⑥ 조립은 한 곳이다 — 화면이 편성·스냅샷·정답을 직접 안 만진다(소스층)', () => {
  const 코드 = 코드만(소스);
  assert.ok(!/앉음편성|G2스냅샷|보기만들기/.test(코드),
    '화면이 재료를 스스로 조립한다 — 갈라지는 날 행에 적힌 문항과 화면에 뜬 문항이 다르고 증상이 없다');
  assert.ok(!/\.정답/.test(코드), '화면이 정답 칸을 읽는다 — 그 칸은 학생 기기에 오지도 않는다');
  assert.match(코드, /교정문만들기\(/, 'body_original 조립이 lib 을 안 지난다');
  assert.match(코드, /다음시도번호\([^)]*문항id\)/, 'attempt 를 문항 단위로 안 센다 — 다른 문항이 재시도로 적힌다');
});

