test('⑩ 말하기화면 G2 갈래 — 게이트 있는 판정 하나로 가르고, 막힘 검사 뒤에 선다(소스층)', () => {
  const 말하기 = 코드만(fs.readFileSync(path.join(ROOT, 'src', '말하기화면.js'), 'utf8'));
  assert.match(말하기, /setG2벌\(앉음재료\(G2게임재료\(항목\)\)\)/,
    'G2 라우팅이 게이트 있는 판정(게임재료)을 안 지난다 — 미검수 판이 학생에게 열린다');
  assert.match(말하기, /<보고서교정화면/, 'G2 갈래가 화면을 안 그린다 — 판정만 있고 배선이 없다');
  const 막힘자리 = 말하기.indexOf('if (서버막힘)');
  const G2자리 = 말하기.indexOf('if (G2벌)');
  assert.ok(막힘자리 > -1 && G2자리 > 막힘자리, 'G2 갈래가 막힘 검사보다 앞이다 — 막힌 학생에게 게임이 열려 업로드만 죽는다');
  /* 두 갈래는 **나란히**다 — G1 이 없는 날에도 G2 가 서야 한다(중첩이면 영영 안 뜬다). */
  assert.ok(말하기.indexOf('if (게임재료값)') < G2자리, 'G1·G2 갈래 순서가 뒤집혔다');
  /* 못 받은 날 두 값이 **둘 다** 비워져야 어제 게임이 오늘 화면에 안 남는다. */
  assert.match(말하기, /setG2벌\(null\)/, '못 받은 날 G2 재료를 안 비운다 — 어제 앉음이 오늘 뜬다');
});
