/* 멘탈게이지 회귀 — G1 5칸 판정(`lib/멘탈게이지.js` · 발주_게임모듈.md G1 §4-5).
 *
 * 세 맹점을 의식하고 짰다(CLAUDE.md):
 *   ① 사람이 실제로 쓰는 표기 — 판정에 먹이는 글은 문형 조각이 아니라 학생이 낼 법한
 *      **메일 전문**이고, 오탐 검사는 이유 어미와 글자만 같은 실제 이웃(에서·께서·-면서·
 *      여기서·보고서)으로 한다.
 *   ② 버그가 아직 있을 것을 요구하지 않는다 — 탐지력은 「칸 하나를 뺀 메일」 픽스처가 지고,
 *      실팩 결속에는 거짓양성만 본다.
 *   ③ 자기 처방 — 판정이 「빠졌다」고 한 칸을 그 문형대로 채우면 채워진 것으로 잡혀야 한다
 *      (한칸빠짐 픽스처가 양방향으로 그것을 증명한다).
 *
 * 🔑 5칸 목록의 정본은 팩이다 — 판정기 키 ↔ `펴기().요구문형` 키의 1:1 결속이 여기서 잡힌다.
 *    팩이 6번째 칸을 얻는 날 이 회귀가 빨개진다(조용한 반쪽 판정 금지).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 코드만, 코드만픽스처 } = require('./lib/소스검사.js');
const { 세우기 } = require('./lib/앱모듈세우기.js');
const { 판정기, 판정, 같은판정 } = require('../lib/멘탈게이지.js');

const 뿌리 = path.resolve(__dirname, '..');
const fetch금지 = () => { throw new Error('멘탈게이지는 fetch 를 부르지 않는다'); };
const 팩 = 세우기(path.join(뿌리, 'contents', '교수멘탈문항.js'), fetch금지);
const 요구문형 = 팩.펴기('g1t01.s0d0').요구문형;

/* 학생이 낼 법한 메일 — 칸별 문장 조각(각 조각은 자기 칸만 채운다 · 픽스처의 전제) */
const 조각 = {
  인사: '교수님, 안녕하십니까. 3학년 바트체첵입니다.',
  사과: '과제를 기한 안에 내지 못해 정말 죄송합니다.',
  이유: '갑자기 몸이 아파서 과제를 끝내지 못했습니다.',
  요청: '3일만 더 주시면 감사하겠습니다.',
  맺음: '감사합니다. 바트체첵 올림',
};

function 메일(빼는칸) {
  return Object.keys(조각).filter((k) => k !== 빼는칸).map((k) => 조각[k]).join(' ');
}

test('판정기 ↔ 팩 요구문형 — 칸 이름 1:1 결속(사본 금지의 기계 강제)', () => {
  assert.deepEqual(Object.keys(판정기).sort(), Object.keys(요구문형).sort(),
    '팩이 칸을 얻거나 잃으면 판정기가 같은 커밋에서 따라와야 한다');
});

test('완성 메일 = 5/5 — 빠진칸 0', () => {
  const 결과 = 판정(메일(null), 요구문형);
  assert.deepEqual(결과.빠진칸, []);
  assert.equal(결과.채움수, 5);
  assert.equal(결과.전체수, 5);
});

test('탐지력 — 칸 하나를 뺀 메일은 정확히 그 칸만 빠진다(픽스처 5벌)', () => {
  for (const 칸 of Object.keys(조각)) {
    const 결과 = 판정(메일(칸), 요구문형);
    assert.deepEqual(결과.빠진칸, [칸], `「${칸}」 조각을 뺐다`);
    assert.equal(결과.채움수, 4, 칸);
  }
});

test('이유 오탐 이웃 — 글자만 같은 「○서」는 이유가 아니다', () => {
  const 이웃들 = [
    '도서관에서 공부했습니다.',      // 자리 에서
    '교수님께서 말씀하셨습니다.',    // 주어 께서
    '음악을 들으면서 공부합니다.',   // 동시 -면서
    '여기서 기다리겠습니다.',        // 지시 여기서
    '보고서 제출을 준비합니다.',     // 명사 끝 글자
  ];
  for (const 글 of 이웃들) {
    assert.equal(판정(글, 요구문형).칸별.이유, false, `오탐: 「${글}」`);
  }
  // 처방대로 채우면 잡힌다(맹점 ③) — 진짜 이유 연결어미들
  for (const 글 of ['제출이 늦어서 연락드립니다.', '컴퓨터가 고장 나서 못 냈습니다.',
    '준비하느라 시간이 걸렸습니다.', '일정이 겹치기 때문에 어렵습니다.']) {
    assert.equal(판정(글, 요구문형).칸별.이유, true, `미탐: 「${글}」`);
  }
});

test('맺음은 끝자리만 — 본문 중간의 감사는 맺음이 아니고, 요청의 「감사하겠습니다」도 아니다', () => {
  assert.equal(판정('항상 지도해 주셔서 감사합니다. 이번 과제 사정을 말씀드리고 싶습니다.',
    요구문형).칸별.맺음, false, '본문 중간 감사');
  assert.equal(판정('사흘만 더 주시면 감사하겠습니다.', 요구문형).칸별.맺음, false,
    '요청 문형으로 끝난 글');
  assert.equal(판정('말씀드릴 것이 있습니다. 감사합니다.', 요구문형).칸별.맺음, true);
  assert.equal(판정('부탁드립니다. 바트체첵 올림', 요구문형).칸별.맺음, true);
});

test('반쪽 판정 금지 — 재료가 아니거나 판정기 없는 칸이 있으면 전체가 null', () => {
  assert.equal(판정(123, 요구문형), null, '글이 문자열이 아니다');
  assert.equal(판정('글', null), null);
  assert.equal(판정('글', []), null);
  assert.equal(판정('글', {}), null, '칸이 0개');
  assert.equal(판정('글', { ...요구문형, 서명: '아직 없는 칸' }), null,
    '판정기 없는 칸 — 일부만 재서 「채워졌다」로 읽히면 안 된다');
});

test('산출은 얼어 나가고, 같은판정이 리렌더 판단을 진다', () => {
  const a = 판정(메일(null), 요구문형);
  assert.ok(Object.isFrozen(a) && Object.isFrozen(a.칸별) && Object.isFrozen(a.빠진칸));
  assert.ok(같은판정(a, 판정(메일(null), 요구문형)), '같은 글 = 같은 판정(리렌더 0)');
  assert.ok(!같은판정(a, 판정(메일('맺음'), 요구문형)), '칸이 달라지면 리렌더 1회');
  assert.ok(같은판정(null, null));
  assert.ok(!같은판정(a, null));
});

test('부분일치 채점 금지 — 소스에 .includes( 0(보드 인계 규약의 기계 강제)', () => {
  /* 🔴 주석을 지우고 잰다 — 이 금지야말로 자기 주석에 걸리는 전형이다. 세 파일 어디든
   *   「부분일치(`.includes(`)를 쓰지 않는다」는 **설명 한 줄**이 그대로 위반으로 잡혔다.
   *   F401 이 그 사고였다: `tests/마이크권한.test.js` 가 주석의 `allowsRecording` 을 원문
   *   `includes` 로 재서, 코드는 한 줄도 안 어긴 커밋이 master 를 적색으로 만들었다. */
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대, '주석 제거기가 죽었다');
  for (const 파일 of ['멘탈게이지.js', '게임스냅샷.js', '서류관문.js']) {
    const 코드 = 코드만(fs.readFileSync(path.join(뿌리, 'lib', 파일), 'utf8'));
    assert.ok(!/\.includes\(/.test(코드), `${파일}: .includes( 발견`);
  }
});
