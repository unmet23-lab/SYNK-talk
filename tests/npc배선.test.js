/* NPC 배선 회귀 — 판정층(lib/NPC연출)과 화면층의 아귀 · 규격 3 의 기계 자리.
 *
 * ■ 왜 소스 층까지 보나 — 규격이 «화면에 무엇을 안 그리는가»로 적혀 있어서다.
 *   「상태에 숫자·퍼센트 병기 금지」는 값으로 못 잰다: 그리는 순간이 위반이고, 그 위반은
 *   테스트가 아니라 눈에만 보인다. 등록층에서 문자로 막는 것이 유일한 기계 자리다.
 *
 * ■ 규격 정본 = SYNK-appsscript docs/미니게임_게임층_설계.md §4 규격 3
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 코드만 } = require('./lib/소스검사.js');
const { 역들, 상태들, 압박문턱, 압박상태, 전이상태, 컷이름 } = require('../lib/NPC연출.js');

const ROOT = path.resolve(__dirname, '..');
const 소스 = (상대) => fs.readFileSync(path.join(ROOT, ...상대.split('/')), 'utf8');

/** 그 판의 녹음 상한(ms) — 문턱이 «비율»이라 판정은 상한과 짝으로만 성립한다. */
const 상한 = 30 * 1000;

test('압박 3단 — 지나간 «비율»에 따라 평온 → 기울어짐 → 돌아섬 (규격 3 · G3 전용 축)', () => {
  const 때 = (비율) => Math.round(상한 * 비율);
  assert.equal(압박상태(1, 상한), 'calm');
  assert.equal(압박상태(때(압박문턱.기울어짐) - 1, 상한), 'calm');
  assert.equal(압박상태(때(압박문턱.기울어짐), 상한), 'lean');
  assert.equal(압박상태(때(압박문턱.돌아섬) - 1, 상한), 'lean');
  assert.equal(압박상태(때(압박문턱.돌아섬), 상한), 'back');
  assert.equal(압박상태(상한 * 3, 상한), 'back', '끝까지 가도 돌아섬이 마지막 단이다');
  /* 🔑 상한이 무엇이든 세 단이 «전부» 선다 — 그게 문턱을 초가 아니라 비율로 둔 이유다. */
  for (const 초 of [12, 30, 60, 90]) {
    const 단들 = [0.1, 0.5, 0.9].map((r) => 압박상태(초 * 1000 * r, 초 * 1000));
    assert.deepEqual(단들, ['calm', 'lean', 'back'], `상한 ${초}초에서 3단이 다 안 선다`);
  }
  /* 시계는 뒤로 안 가고, «못 잼»을 압박으로 번역하지 않는다. */
  assert.equal(압박상태(-5000, 상한), 'calm');
  assert.equal(압박상태(NaN, 상한), 'calm');
  assert.equal(압박상태(undefined, 상한), 'calm');
  assert.equal(압박상태(9999, 0), 'calm', '상한 0(못 잼)이 돌아섬으로 읽히면 안 된다');
  assert.equal(압박상태(9999, undefined), 'calm');
});

test('압박 문턱 — 오름차순 비율이고 상수는 이 파일 하나뿐이다 (규격 3 「상수 1곳」)', () => {
  assert.ok(압박문턱.기울어짐 > 0 && 압박문턱.돌아섬 > 압박문턱.기울어짐 && 압박문턱.돌아섬 < 1,
    '문턱이 뒤집혔거나 1 이상이다 — 돌아섬이 상한 뒤면 그 단은 원리상 0회 노출이다');
});

test('🔴 판정은 lib 하나가 진다 — 화면이 «상태 문자열»을 직접 짓지 않는다', () => {
  /* 🔑 문턱을 «숫자»로 찾는 검사는 원리상 못 쓴다 — 첫 판이 `opacity: 0.75`(스타일 값)를
     돌아섬 문턱으로 읽어 거짓양성을 냈다. 숫자는 우연히 같을 수 있다.
     진짜 위험은 값이 아니라 **화면이 자기 판정을 만드는 것**이다: `경과 > 12000 ? 'lean' : …`
     처럼 상태를 직접 지으면 그날로 문턱이 두 곳이 된다. 그래서 «상태 어휘가 화면에 있는가»를
     본다 — 어휘가 없으면 판정도 못 짓는다. */
  for (const 상대 of ['src/알바변명화면.js', 'src/교수멘탈화면.js',
    'src/보고서교정화면.js', 'src/서류관문화면.js']) {
    const 화면 = 코드만(소스(상대));
    for (const 상태 of 상태들) {
      assert.ok(!new RegExp(`['"\`]${상태}['"\`]`).test(화면),
        `${상대} 가 상태 「${상태}」를 직접 지었다 — 값은 lib/NPC연출(압박상태·전이상태)만 낸다`);
    }
  }
});

test('전이 자리 — 시작은 평온 · 완료는 흡족 · 실패는 돌아섬', () => {
  assert.equal(전이상태('시작'), 'calm');
  assert.equal(전이상태('완료'), 'win');
  assert.equal(전이상태('실패'), 'back');
  assert.equal(전이상태('모르는자리'), 'calm', '모르는 자리는 «가장 조용한 값»으로 내려간다');
});

test('컷 이름 — 어휘 밖이면 조용히 기본으로 안 내려가고 던진다 (옛 몽글 사고의 규율)', () => {
  assert.equal(컷이름('boss', 'win'), 'boss-win');
  assert.throws(() => 컷이름('king', 'calm'), /정본에 없다/);
  assert.throws(() => 컷이름('boss', '화남'), /정본에 없다/);
});

test('컷 지도 — 화면의 정적 require 가 역 x 상태 16종과 1:1 이다', () => {
  const 화면 = 소스('src/NPC.js');
  for (const 역 of 역들) {
    for (const 상태 of 상태들) {
      const 이름 = 컷이름(역, 상태);
      assert.ok(화면.includes(`require('../assets/npc/${이름}.webp')`),
        `컷 지도에 ${이름} 이 없다 — 그 조합은 화면에서 조용히 사라진다`);
    }
  }
});

test('🔴 규격 3 — NPC 층이 숫자·퍼센트·상태 이름을 «그리지» 않는다 (모호함이 설계다)', () => {
  const 화면 = 코드만(소스('src/NPC.js'));
  assert.ok(!/%|퍼센트/.test(화면), 'NPC 가 퍼센트를 그린다 — 읽히는 시계가 되어 회피 지연 축이 오염된다');
  assert.ok(!/<Text/.test(화면), 'NPC 가 글자를 그린다 — 상태 이름·숫자가 붙는 통로가 열린 것이다');
  /* 접근성 라벨은 «역»까지만 — 상태를 읽어 주면 스크린리더 사용 학생만 조건이 갈린다. */
  assert.match(화면, /accessibilityLabel=\{직함\[역\]/, '라벨이 역 이름에서 벗어났다(상태 노출 위험)');
});

test('🔴 규격 3 — 실시간 전환은 G3 하나뿐이다 (G1·G2·G4 는 전이 자리에서만)', () => {
  /* 압박상태() 는 «경과 → 단» 함수라 입력 중 계속 불린다. G3 밖 화면이 이걸 부르면
     그 화면에 입력 중 움직이는 장치가 하나 더 생겨 검사 ①(동시 1개)이 깨진다. */
  for (const 상대 of ['src/교수멘탈화면.js', 'src/보고서교정화면.js', 'src/서류관문화면.js']) {
    const 화면 = 코드만(소스(상대));
    assert.ok(!/압박상태/.test(화면),
      `${상대} 가 압박상태() 를 부른다 — 실시간 전환이 허용된 자리는 G3(알바변명) 하나다`);
  }
  assert.match(코드만(소스('src/알바변명화면.js')), /압박상태/,
    'G3 에서 압박 3단이 사라졌다 — 사장님 연출이 이 게임의 압박 게이지를 겸한다(발주서 §4-3)');
});
