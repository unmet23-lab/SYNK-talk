/* 라디오 라운드 «제안↔노출» 두 문 회귀 — `radio-round` Fn 의 판정층 (설계 §2-J·§4-5 · P3).
 *
 * 이 회귀가 지는 것 셋:
 *   ㉠ **정답이 화면으로 새지 않는다** — 방송은 소급 수정이 없다. 전광판판정의 `라운드금칙` 은
 *      마지막 그물이고, 여기서 애초에 안 싣는 것을 못박는다.
 *   ㉡ **검수 안 된 문항이 원장에 못 앉는다** — 팩 상수(`검수확정`)가 아니라 문항별 장부가
 *      정본이고, 지문이 낡으면(문항이 그새 바뀌면) 막힌다.
 *   ㉢ **ack 로 원장에 앉을 스냅샷이 소비자 계약을 만족한다** — 소비자는 `라디오승격` 이고
 *      그 모양 판정은 `이벤트검증.보기id들` 이다. 그 «진짜» 함수를 태운다(사본으로 재면
 *      갈라진 날 둘 다 초록이다).
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');

const R = require('../lib/라디오라운드.js');
const { 확정얹기, 반려얹기, 범주초안 } = require('../lib/토픽퀴즈검수.js');
const { 보기id들 } = require('../lib/이벤트검증.js');
const 팩 = require('../contents/토픽퀴즈문항.js');

const 판 = { 문항판: 팩.문항판, 스킬판: 팩.스킬판 };
const 지금 = Date.parse('2026-08-15T09:00:00Z');
const 어제 = '2026-08-14T09:00:00Z';

/** 앞 n 문항만 검수확정한 장부 — 정본 통로(`확정얹기`)로 만든다(손으로 칸을 짜면 지문이 갈린다). */
function 장부만들기(n) {
  let 장부 = {};
  for (const q of 팩.문항들.slice(0, n)) {
    장부 = 확정얹기({ 장부, 문항: q, 범주: 범주초안(q.skill_ids) ?? '형태', 지금: 어제 });
  }
  return 장부;
}

const 제안하기 = (덧 = {}) => R.제안조립({
  문항들: 팩.문항들, 판, 장부: 장부만들기(6), 노출수: {}, 승격요약: {},
  씨앗: 'ch1:2026-08-15T09:00Z', 지금, ...덧,
});

/* ── ㉠ 유출 ────────────────────────────────────────────────────────────── */

test('화면 payload 에 정답·해설 칸이 없다 — 방송은 되돌릴 수 없다', () => {
  const { 제안 } = 제안하기();
  assert.ok(제안, '제안이 나와야 이 검사가 산다');
  /* 중첩까지 본다 — 전광판판정의 `금지칸찾기` 와 같은 수법(얕게 보면 한 겹 감싸서 샌다). */
  const 금지 = ['정답', 'answer', 'correct_option', '해설'];
  (function 키훑기(값, 깊이) {
    if (깊이 > 6 || !값 || typeof 값 !== 'object') return;
    for (const k of Object.keys(값)) {
      assert.equal(금지.includes(k), false, `화면에 «${k}» 칸이 실렸다`);
      키훑기(값[k], 깊이 + 1);
    }
  }(제안.화면, 0));
  /* 🔑 **값으로는 못 잰다** — 정답 `option_id`(예 'o4')는 보기 4개가 전부 들고 있어야
   *   정상이고(그게 없으면 `!답 2` 해석이 죽는다), 유출은 «어느 것이 정답인지 구별되는가»다.
   *   그래서 재는 것은 **보기 칸의 균질성**이다: 어느 보기도 남과 다른 칸을 달고 있지 않다.
   *   (첫 판은 여기서 정답 문자열 부재를 단정했다가 회귀가 잡았다 — 정상을 위반으로 셌다.) */
  const 칸모양 = [...new Set(제안.화면.보기들.map((o) => Object.keys(o).sort().join(',')))];
  assert.deepEqual(칸모양, ['label,option_id'], '보기마다 칸이 다르면 그 차이가 곧 정답 표식이다');
  /* 스냅샷 «쪽»에는 있어야 한다 — 원장까지는 간다(정답 공개·재도전의 재료). */
  assert.ok(제안.스냅샷.정답, '스냅샷에서까지 정답이 빠지면 정답 공개를 못 한다');
});

