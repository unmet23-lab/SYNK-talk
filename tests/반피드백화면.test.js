'use strict';
/**
 * 강사 반 단위 피드백 **화면**(§8-4) 회귀 — 정본 `docs/강사_반단위_피드백_설계.md` v2 §5·§6.
 *
 * ■ 이 파일이 지는 것 셋
 *   ① **순수 판정** — 기다린 나이·갈래(`origin`) 판정. 화면을 안 세우고 잰다.
 *   ② **어휘 사본 0** — 갈래·처분·본문 상한을 화면이 손으로 안 적었나(`lib/반피드백.js` 가 정본).
 *   ③ **철학 ㉢** — 정렬·비교 축이 화면에 안 들어왔나(등수표가 되는 자리).
 *   ⚠ 목록·큐 카드 자체는 이 층이 못 잰다 — 조회가 `useEffect` 라 서버 렌더에서 안 돈다
 *     (검수 콘솔과 같은 경계). 첫 프레임은 `tests/화면렌더.test.js` 가 진다.
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { 코드만, 코드만픽스처 } = require('./lib/소스검사.js');

const 뿌리 = path.resolve(__dirname, '..');
const 화면경로 = path.join(뿌리, 'src', '반피드백화면.js');
const API경로 = path.join(뿌리, 'src', '반피드백API.js');
const 화면소스 = 코드만(fs.readFileSync(화면경로, 'utf8'));
const API소스 = 코드만(fs.readFileSync(API경로, 'utf8'));

/* 순수 함수만 떼어 잰다 — `react-native` 를 안 끌고 오려고 소스에서 그 세 함수만 평가한다.
 * 🔑 **사본이 아니다**: 파일에서 «그 자리»를 잘라 그대로 돌린다. 손으로 옮겨 적으면 화면이
 *   바뀐 날 이 회귀만 옛 규칙을 초록으로 지킨다. */
function 순수함수들() {
  const 조각 = [];
  for (const 이름 of ['기다린날', '나이글', '갈래판정']) {
    const i = 화면소스.indexOf(`export function ${이름}(`);
    assert.ok(i > 0, `${이름} 을 못 찾았다 — 이 회귀가 미실행이다`);
    const 끝 = 화면소스.indexOf('\n}\n', i);
    assert.ok(끝 > i, `${이름} 의 끝을 못 찾았다 — 이 회귀가 미실행이다`);
    조각.push(화면소스.slice(i, 끝 + 2).replace('export function', 'function'));
  }
  // eslint-disable-next-line no-new-func
  return new Function(`${조각.join('\n')}\nreturn { 기다린날, 나이글, 갈래판정 };`)();
}
const { 기다린날, 나이글, 갈래판정 } = 순수함수들();

const 지금 = Date.parse('2026-08-12T09:00:00Z');

/* ── ① 기다린 나이 = 내 일감의 나이 ────────────────────────────────── */

test('① 밤에 낸 것이 자정을 넘겼다고 「1일」이 되지 않는다 — 24시간 단위로 센다', () => {
  /* 🔴 자정 경계로 세면 밤 11시 제출이 한 시간 뒤 「1일 기다림」이 되고, 강사는 안 밀린 것을
     밀린 것으로 읽는다. 큐 정렬 축이 이 숫자라 그 오독이 곧 일하는 순서를 바꾼다.
     ⚠ [2026-08-12 변이 실측] 처음 픽스처는 **같은 날 오전**을 썼다 — 자정 경계 구현으로 바꿔도
        그 값은 안 변해서 검사가 초록이었다. 경계를 재려면 **전날**이면서 24시간 안인 시각이라야
        한다(어제 23시 ↔ 오늘 09시 = 10시간). 픽스처가 경계를 안 밟으면 탐지력이 0이다. */
  const 어제밤 = '2026-08-11T23:00:00Z'; // 10시간 전 · 달력으로는 «어제»
  assert.equal(기다린날(어제밤, 지금), 0);
  assert.equal(나이글(어제밤, 지금), '오늘');
});

test('① 이틀 지난 것은 2일이다', () => {
  const t = new Date(지금 - 2 * 86400000 - 3600000).toISOString();
  assert.equal(기다린날(t, 지금), 2);
  assert.equal(나이글(t, 지금), '2일');
});

test('① 시각이 없거나 모양이 아니면 «지어내지 않는다» — null 이고 글자는 빈 문자열', () => {
  /* 🔑 0 으로 접으면 「오늘 냈다」로 보인다 — 모르는 것과 오늘이 같은 모양이면 안 된다. */
  assert.equal(기다린날(null, 지금), null);
  assert.equal(기다린날('어제', 지금), null);
  assert.equal(나이글(null, 지금), '');
});

test('① 시계가 뒤로 밀려도 음수가 안 나온다', () => {
  const 미래 = new Date(지금 + 3600000).toISOString();
  assert.equal(기다린날(미래, 지금), 0);
});

/* ── ② 갈래(`origin`)는 «동작»에서 나온다 ──────────────────────────── */

test('② 안 가져왔으면 written — 빈 칸에 쓴 것이 기본이다', () => {
  assert.equal(갈래판정({ 가져옴: false, 글: '잘했어요', AI교정: '잘했어요' }), 'written');
});

test('② 가져와서 글자 그대로면 as_is', () => {
  assert.equal(갈래판정({ 가져옴: true, 글: '학교에 갔습니다', AI교정: '학교에 갔습니다' }), 'as_is');
});

test('② 가져와서 한 글자라도 고쳤으면 edited', () => {
  assert.equal(갈래판정({ 가져옴: true, 글: '학교에 갔습니다!', AI교정: '학교에 갔습니다' }), 'edited');
});

test('② 앞뒤 공백만 다른 것은 «고친 것»이 아니다 — 서버도 trim 뒤로 잰다', () => {
  /* 🔑 서버(`lib/반피드백.한마디검사`)가 `body` 를 trim 해 저장한다. 여기서 공백을 편집으로
     세면 저장된 글자는 AI 그대로인데 갈래만 `edited` 로 남고, 그 행은 영원히 거짓이다. */
  assert.equal(갈래판정({ 가져옴: true, 글: '  학교에 갔습니다  ', AI교정: '학교에 갔습니다' }), 'as_is');
});

test('② AI 교정이 없는데 가져옴이 서면 as_is 로 굳지 않는다', () => {
  /* 빈 문자열끼리 같다고 `as_is` 를 내면 「AI 문장 그대로」라는 뜻이 근거 없이 붙는다. */
  assert.equal(갈래판정({ 가져옴: true, 글: '직접 쓴 말', AI교정: null }), 'edited');
  assert.equal(갈래판정({ 가져옴: true, 글: '', AI교정: null }), 'edited');
});

test('② 화면이 내는 갈래가 lib 값목록 안에 있다 — 나머지 하나도 도달 가능하다', () => {
  const { 갈래 } = require(path.join(뿌리, 'lib', '반피드백.js'));
  const 낸것 = new Set([
    갈래판정({ 가져옴: false, 글: 'a', AI교정: 'b' }),
    갈래판정({ 가져옴: true, 글: 'b', AI교정: 'b' }),
    갈래판정({ 가져옴: true, 글: 'c', AI교정: 'b' }),
  ]);
  assert.deepEqual([...낸것].sort(), [...갈래].sort(),
    '화면이 도달 못 하는 갈래가 있다 — 못 도달하는 값은 DB 에 영원히 안 쌓인다');
});

/* ── ③ 어휘 사본 0 ──────────────────────────────────────────────────── */

test('③ 화면이 갈래·처분·상한을 lib 에서 끌어온다(손 상수 0)', () => {
  assert.match(화면소스, /from '\.\.\/lib\/반피드백\.js'/, 'lib 을 안 부른다');
  for (const 낱말 of ['본문상한', '카드요약']) {
    assert.ok(화면소스.includes(낱말), `${낱말} 을 lib 에서 안 쓴다`);
  }
  /* 🔴 상한 숫자를 손으로 적었나 — 적으면 lib 이 바뀌는 날 화면만 옛 숫자를 말하고, 그 거짓말은
     「저장이 안 된다」로만 보인다(어디까지 줄여야 하는지 강사는 알 길이 없다). */
  assert.ok(!/\b600\b/.test(화면소스), '본문 상한 600 이 화면에 손으로 박혔다');
});

test('③ API 층에도 어휘 사본이 0이다 — 갈래·처분 값을 안 적었다', () => {
  for (const 값 of ['as_is', 'edited', 'written', 'confirmed', 'retry']) {
    assert.ok(!API소스.includes(`'${값}'`), `API 가 ${값} 를 손으로 적는다 — 세 번째 정본이다`);
  }
});

test('③ 처분 «말»은 lib 의 코드에서 찾아 쓴다 — 목록을 손으로 안 편다', () => {
  const { 처분 } = require(path.join(뿌리, 'lib', '반피드백.js'));
  /* 화면은 `처분값.map` 으로 그리고 말만 붙인다 — 배열 리터럴로 다시 적으면 lib 에 값이 느는
     날 화면만 옛 둘을 그리고, 그 누락은 아무 데도 안 빨개진다. */
  assert.match(화면소스, /처분값\.map\(/, '처분 버튼을 lib 값에서 안 편다');
  for (const 코드 of 처분) {
    assert.ok(화면소스.includes(`${코드}:`), `처분말에 ${코드} 의 말이 없다 — 화면에 코드값이 그대로 뜬다`);
  }
});

/* ── ④ 철학 ㉢ — 정렬 축이 곧 비교다 ────────────────────────────────── */

test('④ 화면이 큐를 다시 정렬하지 않는다 — 서버의 「오래 기다린 순」 하나다', () => {
  /* 🔴 `sort` 한 줄이면 이 화면은 등수표가 된다. 서버가 `order by occurred_at` 로 이미 정했고,
     화면이 다시 정하는 순간 정렬 축의 정본이 둘이 된다. */
  assert.ok(!/\.sort\(/.test(화면소스), '화면이 목록을 정렬한다 — 정렬 축이 둘이 됐다');
});

test('④ 비교 어휘가 화면 어디에도 없다 — 평균·등수·상위·정답률', () => {
  for (const 낱말 of ['평균', '등수', '순위', '상위', '정답률', '랭킹']) {
    assert.ok(!화면소스.includes(낱말), `화면에 「${낱말}」이 있다 — 철학 ㉢ 을 정면으로 깬다`);
  }
});

test('④ 카드가 싣는 수는 둘뿐이다 — 반 인원과 내 일감의 수', () => {
  const i = 화면소스.indexOf('const s = StyleSheet.create');
  const 본문 = 화면소스.slice(0, i > 0 ? i : undefined);
  const 셈 = [...본문.matchAll(/c\.(\w+)/g)].map((m) => m[1]);
  for (const 칸 of 셈) {
    assert.ok(['id', '열쇠', '이름', '학생수', '기다림', '모양'].includes(칸),
      `카드가 ${칸} 을 읽는다 — 카드에 실을 수 있는 수는 인원과 일감뿐이다`);
  }
});

/* ── ⑤ 셈을 두 번 판정하지 않는다 ──────────────────────────────────── */

test('⑤ 한 마디 뒤 카드 모양을 `카드요약` 으로 다시 낸다 — 손으로 `기다림 > 0` 을 안 적는다', () => {
  const i = 화면소스.indexOf('const 보내기');
  const 끝 = 화면소스.indexOf('const 조용한이반');
  assert.ok(i > 0 && 끝 > i, '보내기 구간을 못 찾았다 — 이 검사가 미실행이다');
  const 구간 = 화면소스.slice(i, 끝);
  assert.match(구간, /카드요약\(/, '카드 모양을 화면이 스스로 판정한다 — 두 번째 정본이다');
  assert.ok(!/기다림\s*>\s*0/.test(구간), '`기다림 > 0` 을 손으로 적었다 — lib 과 갈리는 날 조용하다');
});

test('⑤ 고쳐 쓴 것은 큐에서 안 뺀다 — 애초에 큐에 없던 항목이다', () => {
  /* 🔴 서버 술어 ②는 「강사 한 마디가 아직 없다」다. 고쳐 쓰기(`updated_at` 이 온 경우)는 이미
     한 마디가 있던 자리라 큐에 없었고, 그걸 또 빼면 카드 셈이 한 칸 어긋난다 — 그 어긋남이
     정확히 설계 §4 가 막으려던 「● 4 인데 들어가면 3건」이다. */
  assert.match(화면소스, /if \(!r\.고친시각\)/, '고쳐 쓰기와 처음 쓰기를 안 가른다');
});

/* ── ⑥ 재조회 0 ────────────────────────────────────────────────────── */

test('⑥ 뒤로 갈 때 다시 조회하지 않는다 — 조회 1회 = 감사 1행이고 그게 분모다', () => {
  const i = 화면소스.indexOf('set반(null)');
  assert.ok(i > 0, '내 반으로 돌아가는 자리를 못 찾았다 — 이 검사가 미실행이다');
  const 뒤 = 화면소스.slice(i, i + 160);
  assert.ok(!/반목록\(|첫조회\(/.test(뒤), '뒤로 갈 때 다시 조회한다 — 감사 분모가 조용히 달라진다');
});

test('⑥ 첫 조회는 딱 한 자리다 — `useEffect` 하나', () => {
  assert.equal((화면소스.match(/useEffect\(/g) || []).length, 1,
    'useEffect 가 둘 이상이다 — 조회가 겹치면 감사 행이 겹쳐 쌓인다');
});

/* ── ⑦ 탐지력은 픽스처가 진다 ──────────────────────────────────────── */

test('⑦ 주석 제거기가 **JSX 표기까지** 지운다 — 안 지우면 위 검사가 설명을 코드로 읽는다', () => {
  /* 🔴 실측(2026-08-12): 이 파일의 ④ 가 처음 돌 때 **금지를 설명하는 JSX 주석 자체**를
     위반으로 잡았다 — 화면 주석은 `{/* … *\/}` 이고 이어지는 줄에 표식이 없어 옛 제거기가
     통째로 놓쳤다. 거짓양성이라 눈에 띄었지만 반대 방향(설명이 코드로 읽혀 영원히 초록)이
     `소스검사.js` 머리말의 실측 그대로다 — 같은 구멍의 다른 얼굴이라 픽스처로 못박는다. */
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대, '주석 제거기가 죽었다');
});
