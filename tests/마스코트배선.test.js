/* 마스코트 배선 회귀 — 배치 판정·게이트 우회·컷 지도의 등록층.
 *
 * ■ 왜 소스 층인가 — 가드는 로직보다 등록층에서 새고, 새는 방향은 언제나 「통과」다.
 *   · 배치 = 보는 화면(답장)뿐, 말하기(녹음) 화면 금지 — 08-12 판정(v3 코랄 몸 × 녹음 버튼
 *     신호 충돌 실측)이 프로즈로만 남으면 다음 커밋이 조용히 올린다.
 *   · 별눈은 게이트(`lib/마스코트생명.별눈판정`) 없이 화면이 못 세운다 — 화면 코드에 그 컷
 *     이름이 등장하는 순간이 우회의 시작이다(지금은 다섯 사건 모두 앱에 신호가 없다).
 *   · Metro 의 정적 require 탓에 컷 지도는 손으로 산다 — `표정컷`과 갈라지면 그 표정은
 *     조용히 기본 컷으로 내려간다(모양이 「통과」다).
 *
 * ■ 렌더는 `그리기`(공용 통로) — 답장화면이 마스코트를 얹고도 첫 렌더에서 안 죽는지는
 *   tests/화면렌더.test.js ⑦이 이미 문다. 여기서는 무오류 모양까지 한 번 더 세운다.
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { 그리기, ROOT } = require('./lib/화면세우기.js');
const { 코드만 } = require('./lib/소스검사.js');
const { 표정컷 } = require('../lib/마스코트생명.js');

const 소스 = (상대) => fs.readFileSync(path.join(ROOT, ...상대.split('/')), 'utf8');

test('배치 — 답장·강사화면에는 마스코트가 살고, 말하기 화면에는 «연기»로만 한시 등장한다 (08-12 실측 → 08-23 유호 확정으로 갱신)', () => {
  const 답장 = 코드만(소스('src/답장화면.js'));
  assert.match(답장, /<마스코트/, '답장화면에서 마스코트가 사라졌다 — 학생판에서 캐릭터가 사는 화면이다(생명감 §5)');
  /* 말하기 화면 — 08-12 실측(코랄 몸 × 녹음 버튼 신호 충돌)의 «상주 금지»는 그대로다.
     08-23 유호 확정(숙제 인트로 = 그 자리 연기)이 연 것은 **연출 한시 등장**뿐이다:
     모든 등장은 연출 배선 + 잡담 잠금 + 끝나면(내려가는 길)을 갖춰야 한다 — 연출 없는
     <마스코트 하나가 곧 상주의 시작이고, 그 순간 08-12 충돌이 되돌아온다. */
  const 말하기 = 코드만(소스('src/말하기화면.js'));
  const 등장들 = 말하기.match(/<마스코트[\s\S]*?\/>/g) || [];
  assert.ok(등장들.length >= 1, '말하기 화면에서 몽글 인트로 연기가 사라졌다 — 유호 확정 08-23(숙제 인트로 연기)의 실물이다');
  for (const 등장 of 등장들) {
    assert.match(등장, /연출=/, '말하기 화면에 연출 없는 마스코트가 올라갔다 — 상주는 녹음 버튼 신호와 충돌한다(08-12 실측·상주 금지)');
    assert.match(등장, /잡담=\{false\}/, '말하기 화면 마스코트의 잡담이 열렸다 — 이 화면의 말은 대본(연출)뿐이다');
    assert.match(등장, /끝나면/, '연출에 끝나면(내려가는 길)이 없다 — 연기가 끝나도 몸이 안 내려가면 그게 상주다');
  }
  /* 강사판(배선 §7 1단계 · 유호 확정 08-14) — 비서가 산다. 단 잡담(학생판 idle 혼잣말)은
     잠근 채여야 한다: 강사판 말할순간 표에 idle 줄이 없다(표 밖 발화 금지 §1-1). */
  const 강사 = 코드만(소스('src/강사화면.js'));
  assert.match(강사, /<마스코트/, '강사화면에서 마스코트가 사라졌다 — 1단계 강사판(배선 §7)의 실물이다');
  assert.match(강사, /잡담=\{false\}/, '강사화면 마스코트의 잡담이 열렸다 — 강사판 표에 idle 혼잣말 줄이 없다(표 밖 발화 금지)');
});

test('별눈 우회 차단 — 화면 층(src/마스코트.js)에 별눈 컷이 등장하지 않는다', () => {
  const 화면 = 코드만(소스('src/마스코트.js'));
  assert.ok(!/별눈/.test(화면), '화면 코드에 별눈이 생겼다 — 생애급 게이트(lib/마스코트생명.별눈판정)를 지나지 않는 별눈은 우회다');
});

test('컷 지도 — 화면의 정적 require 가 표정 어휘(별눈 제외)와 1:1 이다', () => {
  const 화면 = 소스('src/마스코트.js');
  for (const [표정, 컷] of Object.entries(표정컷)) {
    if (표정 === '별눈') continue; // 배선 없음 — 자산만 준비(위 검사가 등장 자체를 막는다)
    assert.ok(
      화면.includes(`require('../assets/마스코트/${컷}.webp')`),
      `컷 지도에 ${표정}(${컷})가 없다 — 그 표정은 조용히 기본 컷으로 내려간다`,
    );
  }
});

test('마스코트는 로컬 존재다 — 서버·소리를 직접 잡지 않는다 (반응은 전부 로컬 · 생명감 §5)', () => {
  const 화면 = 코드만(소스('src/마스코트.js'));
  assert.ok(!/fetch\s*\(/.test(화면), '마스코트가 서버를 부른다 — 반응은 전부 로컬(서버 왕복 0)이다');
  assert.ok(!/효과음\s*\(/.test(화면), '마스코트가 소리를 낸다 — 소리는 화면·소리킷 몫이다(킷 3종 밖 통로 금지)');
  assert.ok(!/expo-audio|expo-haptics/.test(화면), '마스코트가 expo 소리 모듈을 직접 잡았다 — 어댑터(src/소리.js) 규칙 위반');
  assert.match(화면, /지금녹음중/, '녹음 경계 확인이 사라졌다 — 「녹음 중 전부 정지」가 프로즈로 돌아간다(§1-3)');
});

test('렌더 — 연출(대본 연기)을 받은 마스코트가 첫 렌더에 선다 (말하기화면의 몽글은 과제 도착 뒤에만 떠서 화면렌더 통로가 못 잡는다)', () => {
  const { 연출대본 } = require(path.join(ROOT, 'lib', '마스코트생명.js'));
  /* 시퀀서(useEffect)는 서버 렌더에서 안 돈다 — 여기서 재는 것은 「연출 prop 을 받고도
     그리다 죽지 않는가」까지다. 시간 흐름(연기 재생)은 실기기·웹 눈검수 몫(하네스 머리말 🚫). */
  for (const 이름 of Object.keys(연출대본)) {
    그리기('src/마스코트.js', {
      잡담: false,
      연출: { 대본: 연출대본[이름], 채움: { 질문: '주말에 뭘 할 거예요?' }, 끝나면() {} },
    });
  }
});

test('렌더 — 무오류 답장 모양에서도 마스코트를 얹은 화면이 첫 렌더에 선다', () => {
  const { 무오류표식 } = require(path.join(ROOT, 'lib', '꼬리.js'));
  const 글 = 그리기('src/답장화면.js', {
    토큰: 'x', 막힘: null, 학생번호: 'SYNK-042', 돌아가기() {},
    교정: {
      correction_id: 'c1', corrected_text: '어제 학교에 갔어요.', error_tags: [무오류표식],
      actor_kind: 'ai', growth_note: { text: '오늘은 고칠 데가 없었어요.', lang: 'ko' },
    },
  });
  assert.match(글, /어제 학교에 갔어요/, '교정 카드가 안 섰다 — 마스코트를 얹다 화면을 깨뜨렸다');
  assert.doesNotMatch(글, new RegExp(무오류표식), '무오류 표식이 태그로 떴다 — 성취의 날이 경고의 옷을 입었다(케어 방향 회귀)');
});
