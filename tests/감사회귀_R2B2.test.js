'use strict';
/* 감사 회귀 R2B2 — 직원·게임 화면 여섯 자리 시공(D7-9·D8-13·G2-8·D5-4).
 *
 * 전부 **소스로 못박는다** — 재는 자리가 effect·핸들러 «뒤»라 첫 렌더가 원리상 못 닿는다
 * (`tests/감사회귀_R1B2.test.js` 와 같은 규율 — 못 재는 검사를 초록으로 두지 않는다).
 * 🔑 이미 다른 파일이 진 판정은 다시 재지 않는다(한 판정 한 자) — G3(알바변명)의 BGM 금지는
 *   `tests/알바변명화면.test.js` 가 진다. 여기서는 «켠 세 판»만 잰다. */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { ROOT } = require('./lib/화면세우기.js');
const { 코드만, 파일소스 } = require('./lib/소스검사.js');

const 소스 = (이름) => 코드만(파일소스(path.join(ROOT, 'src', 이름)));

const 강사 = 소스('강사화면.js');
const 반피드백 = 소스('반피드백화면.js');
const 검수 = 소스('검수화면.js');
const 저장 = 소스('저장.js');

// ── D7-9 — 첫 조회 실패에 재시도 손잡이가 선다 ────────────────────────────────

test('D7-9 강사화면 — 「다시 불러오기」가 재조회를 올리고, 첫 조회 효과가 그 값을 듣는다', () => {
  assert.match(강사, /set오류\(''\); set불러오는중\(true\); set재조회\(\(n\) => n \+ 1\);/,
    '재시도 손잡이가 없다 — 조회가 죽은 강사의 다음 걸음이 「앱 재시작」뿐이다');
  assert.match(강사, /<Text style=\{s\.backText\}>다시 불러오기<\/Text>/,
    '「다시 불러오기」 문구가 없다 — 손잡이가 있어도 강사가 못 찾는다');
  assert.match(강사, /\}, \[토큰, 재조회\]\);/,
    '첫 조회 효과가 재조회를 안 듣는다 — 버튼을 눌러도 아무 일도 안 일어난다');
});

test('D7-9 강사화면 — 조회가 죽은 날 「판정할 것이 없어요」 빈 카드가 서지 않는다', () => {
  assert.match(강사, /\{!불러오는중 && !오류 && 셈\.전체 === 0 &&/,
    '빈 표본 카드에 !오류 가드가 없다 — 조회 실패가 「이번 주는 판정할 것이 없어요」로 선다');
});

test('D7-9 반피드백화면 — 반 목록 층의 「다시 불러오기」가 첫조회를 그대로 다시 부른다', () => {
  assert.match(반피드백, /\{오류 && !목록 \? \(\s*<Pressable onPress=\{첫조회\}/,
    '재시도 손잡이가 없거나 첫조회 밖의 새 통로를 팠다 — 통로는 useCallback 첫조회 하나다');
  assert.match(반피드백, /<Text style=\{s\.줄버튼글\}>다시 불러오기<\/Text>/,
    '「다시 불러오기」 문구가 없다 — 기존 줄버튼 스타일 재사용이 규격이다');
});

// ── D8-13 — 기준 접힘이 기기에 남는다 (각자 제 키로) ──────────────────────────

test('D8-13 저장.js — 화면설정 한 쌍이 있고 기기비우기가 그것도 비운다', () => {
  assert.match(저장, /export async function 화면설정읽기\(\)/, '화면설정읽기가 없다');
  assert.match(저장, /export async function 화면설정쓰기\(설정\)/, '화면설정쓰기가 없다');
  assert.match(저장, /'ui_prefs\.json'/, '설정 파일 이름이 갈렸다 — 읽기와 쓰기가 다른 파일을 보면 취향이 영영 안 남는다');
  assert.match(저장, /await 화면설정쓰기\(\{\}\);/,
    '기기비우기가 화면설정을 안 비운다 — 기기를 같이 쓰는 다음 사람이 앞사람 취향을 물려받는다');
});

test('D8-13 검수화면 — 검수기준접힘 키로 읽고 쓴다', () => {
  assert.match(검수, /화면설정읽기\(\)\.then\(\(p\) => \{ if \(살아있음 && p && p\.검수기준접힘\) set기준펼침\(false\); \}\)/,
    '마운트 때 접힘 취향을 안 읽는다 — 세션마다 펼친 채 열린다');
  assert.match(검수, /화면설정쓰기\(\{ \.\.\.\(p \|\| \{\}\), 검수기준접힘: !다음 \}\)/,
    '토글이 취향을 안 남기거나 남의 키를 덮어쓴다(펼친 채 …(p||{}) 없이 쓰면 강사 키가 지워진다)');
});

test('D8-13 강사화면 — 강사기준접힘 키로 읽고 쓴다 (검수와 키가 달라야 한다)', () => {
  assert.match(강사, /화면설정읽기\(\)\.then\(\(p\) => \{ if \(살아있음 && p && p\.강사기준접힘\) set기준펼침\(false\); \}\)/,
    '마운트 때 접힘 취향을 안 읽는다');
  assert.match(강사, /화면설정쓰기\(\{ \.\.\.\(p \|\| \{\}\), 강사기준접힘: !다음 \}\)/,
    '토글이 취향을 안 남긴다');
  assert.doesNotMatch(강사, /검수기준접힘/, '강사화면이 검수 키를 쓴다 — 두 화면의 접힘이 한 손잡이로 묶인다');
});

// ── G2-8 — 게임큐 담기 실패가 더는 무관측이 아니다 ────────────────────────────

const 게임화면들 = [
  ['교수멘탈화면.js', 'G1', 3],
  ['보고서교정화면.js', 'G2', 1],
  ['서류관문화면.js', 'G4', 1],
];

for (const [파일, 게임, 자리수] of 게임화면들) {
  test(`G2-8 ${파일} — 게임사건담기의 침묵 catch ${자리수}곳이 관측보고를 부른다 (game: ${게임})`, () => {
    const 코드 = 소스(파일);
    assert.match(코드, /import \{ 관측보고 \} from '\.\/관측';/, '관측보고를 안 들여온다');
    const 무늬 = new RegExp(
      `관측보고\\(e, \\{ spot: 'game_enqueue', game: '${게임}' \\}\\)`, 'g');
    assert.equal((코드.match(무늬) || []).length, 자리수,
      `침묵 자리 ${자리수}곳이 전부 관측보고로 안 잡혔다 — 담기 실패는 «학생 발화가 기기에 안 남은» 사건이다`);
    assert.doesNotMatch(코드, /게임사건담기\(사건\)\.catch\(\(\) =>/,
      '게임사건담기의 빈 .catch 가 되살아났다 — 무관측으로 되돌아간 자리다');
  });
}

// ── D5-4 — 게임 세 판에 BGM 이 깔린다 (마운트 재생 · 언마운트 정지 한 벌) ─────

for (const [파일] of 게임화면들) {
  test(`D5-4 ${파일} — bgm재생 마운트 + bgm정지 언마운트가 한 벌로 선다 (인자 없이 = 유호 선정 트랙)`, () => {
    const 코드 = 소스(파일);
    assert.match(코드, /import \{ 효과음, bgm재생, bgm정지 \} from '\.\/소리\.js';/,
      'bgm 손잡이를 안 들여온다');
    assert.match(코드, /useEffect\(\(\) => \{ bgm재생\(\); return \(\) => bgm정지\(\); \}, \[\]\);/,
      'BGM 마운트·언마운트 한 벌이 없다 — 켜기만 하면 판을 나가도 소리가 따라온다');
    assert.doesNotMatch(코드, /bgm재생\([^)]/,
      'bgm재생에 인자를 실었다 — 다른 트랙을 끼우는 날은 새 시청 확정이 먼저다(소리.js 머리말 계약)');
  });
}

test('D5-4 검수문 — ⑨ BGM 귀검수 칸이 있고 문을 나가면 반드시 끈다', () => {
  const 코드 = 소스('검수문.js');
  assert.match(코드, /BGM 켜고 듣기/, 'BGM 귀검수 토글이 없다 — 깔지 말지의 판정 자리는 유호님 귀다');
  assert.match(코드, /useEffect\(\(\) => \(\) => bgm정지\(\), \[\]\);/,
    '언마운트 정리가 없다 — 검수문을 나가도 BGM 이 계속 돈다');
});
