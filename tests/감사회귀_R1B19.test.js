'use strict';
/* 감사회귀 R1B19 — D4-11: 사건 자리(무오류첫열람·재도전)의 짧 갈래가 캐릭터당 4벌 이상인가.
 *
 * ■ 감사 당시 실측(2026-08-31): 무오류첫열람·짧 = 몽글 1·까몽 1·마린 2, 재도전·짧 = 몽글 1·까몽 1·마린 2
 *   (idle 짧 43~53 대비). 풀이 1벌이면 그 사건은 매번 같은 말이 나와 «반복 대사»가 된다.
 * ■ 여기는 «풀의 넓이»만 잰다 — 문구의 규격(어절·금지 패턴)은 tests/마스코트생명.test.js 가,
 *   사본-정본 일치는 tests/혼잣말.test.js 가 잰다. 축이 다르다.
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const 사본 = require('../contents/혼잣말.json');

test('D4-11 — 사건 자리 짧 풀이 캐릭터당 4벌 이상이다(규격 4~6 · 정본 증편분)', () => {
  for (const 자리 of ['무오류첫열람', '재도전']) {
    for (const 캐릭터 of ['몽글', '까몽', '마린']) {
      const n = 사본.문구.filter((r) => r.캐릭터 === 캐릭터 && r.자리 === 자리 && r.갈래 === '짧').length;
      assert.ok(n >= 4, `${캐릭터}·${자리}: 짧 ${n}벌 — 4벌 밑이면 사건이 반복 대사가 된다(감사 D4-11 재발)`);
    }
  }
});
