'use strict';
/* 곡반응 — Reed 넷째 기둥의 회귀. 이 층이 있어야 Reed 가 도구가 아니라 «엔진»이 된다.
 * 🔴 급소 셋: ①0명 구간을 「이탈 0%」로 안 읽는다 ②결의 바닥과 견준다(절대값 줄 세우기 금지)
 *   ③«표본 부족»과 «성적 나쁨»을 절대 안 섞는다
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const 반 = require('../lib/곡반응.js');

const 관 = (곡id, 결, 시작인원, 끝인원) => ({ 곡id, 결, 시작인원, 끝인원 });
const 여러개 = (n, ...a) => Array.from({ length: n }, () => 관(...a));

test('이탈률 — 20명에서 15명이면 25%', () => {
  assert.equal(반.이탈률(관('a', '밤', 20, 15)), 0.25);
});

test('🔴 0명에서 시작한 구간은 null — 「0에서 0으로 갔으니 이탈 0%」로 읽으면 아무도 없는 새벽이 최고가 된다', () => {
  assert.equal(반.이탈률(관('a', '새벽', 0, 0)), null);
  assert.equal(반.이탈률(관('a', '새벽', 0, 3)), null);
});

test('못 읽는 값은 null — 지어내지 않는다', () => {
  assert.equal(반.이탈률({ 곡id: 'a', 결: '밤' }), null);
  assert.equal(반.이탈률(null), null);
});

test('사람이 늘어도 음수로 안 간다 — 0~1 안에 가둔다', () => {
  assert.equal(반.이탈률(관('a', '밤', 10, 14)), 0);
});

test('🔴 결의 «바닥»과 견준다 — 새벽에 사람이 빠지는 건 곡 탓이 아니라 자는 것이다', () => {
  const 관측 = [
    ...여러개(15, '새벽곡', '새벽', 10, 4),    // 60% 이탈 — 새벽의 바닥
    ...여러개(15, '밤곡', '밤', 10, 9),        // 10% 이탈 — 밤의 바닥
  ];
  const 새벽 = 반.곡성적(관측, '새벽곡');
  const 밤 = 반.곡성적(관측, '밤곡');
  // 절대값으로는 새벽곡이 6배 나쁘지만…
  assert.ok(새벽.절대 > 밤.절대);
  // …그 시간대 치고는 둘 다 «보통»이다(상대 ≈ 0)
  assert.ok(Math.abs(새벽.상대) < 0.02, `새벽 상대 ${새벽.상대}`);
  assert.ok(Math.abs(밤.상대) < 0.02, `밤 상대 ${밤.상대}`);
});

test('상대값이 음수면 «그 시간대 치고 잘 붙잡은 것»이다', () => {
  const 관측 = [
    ...여러개(15, '보통', '밤', 10, 7),   // 30%
    ...여러개(15, '좋은', '밤', 10, 9),   // 10%
  ];
  const s = 반.곡성적(관측, '좋은');
  assert.ok(s.상대 < 0, `상대 ${s.상대}`);
  assert.match(s.말, /덜 빠졌다/);
});

test('🔴 표본이 모자라면 «나쁘다»가 아니라 «안 재봤다»다 — 새 곡은 언제나 표본이 0이다', () => {
  const s = 반.곡성적([관('새곡', '밤', 10, 1)], '새곡');
  assert.equal(s.표본, 1);
  assert.equal(s.믿을만한가, false);
  assert.match(s.말, /돼야 믿는다/);
  assert.ok(!s.말.includes('덜 빠졌다') && !s.말.includes('더 빠졌다'), '못 믿는 숫자를 판정문으로 내지 않는다');
});

test('관측 0 — 「나쁘다」가 아니라 「아직 안 재봤다」', () => {
  const s = 반.곡성적([], '없는곡');
  assert.equal(s.표본, 0);
  assert.equal(s.절대, null);
  assert.match(s.말, /안 재봤다/);
});

test('🔴 줄 세우기에서 «못 잰 것»은 아래가 아니라 «밖»이다 — 섞으면 새 곡이 꼴찌로 굳는다', () => {
  const 관측 = [
    ...여러개(15, '오래된곡', '밤', 10, 9),
    관('새곡', '밤', 10, 2),                     // 관측 1건
  ];
  const r = 반.결순위(관측, '밤');
  assert.deepEqual(r.순위.map((s) => s.곡id), ['오래된곡']);
  assert.deepEqual(r.못잰것.map((s) => s.곡id), ['새곡']);
});

test('순위는 «그 시간대 치고 잘 붙잡은 순»이다', () => {
  const 관측 = [
    ...여러개(15, '좋은', '밤', 10, 9),
    ...여러개(15, '나쁜', '밤', 10, 5),
  ];
  const r = 반.결순위(관측, '밤');
  assert.deepEqual(r.순위.map((s) => s.곡id), ['좋은', '나쁜']);
  assert.ok(r.바닥 && r.바닥.표본 === 30);
});

test('다음곡힌트 — 표본이 없으면 «감이 낫다»고 말한다(지어낸 눈금을 주지 않는다)', () => {
  const h = 반.다음곡힌트([], [], '밤');
  assert.equal(h.쓸만한가, false);
  assert.equal(h.BPM, null);
  assert.match(h.말, /감이 낫다/);
});

test('다음곡힌트 — 잘 붙잡은 곡들의 눈금을 낸다(무엇을 만들지는 사람이 정한다)', () => {
  const 장부 = [
    { id: '좋은', BPM: 62, 밝기: 0.2 }, { id: '좋은2', BPM: 64, 밝기: 0.22 },
    { id: '나쁜', BPM: 120, 밝기: 0.9 },
  ];
  const 관측 = [
    ...여러개(15, '좋은', '밤', 10, 9), ...여러개(15, '좋은2', '밤', 10, 9),
    ...여러개(15, '나쁜', '밤', 10, 4),
  ];
  const h = 반.다음곡힌트(관측, 장부, '밤');
  assert.equal(h.쓸만한가, true);
  assert.ok(h.BPM < 80, `잘 붙잡은 쪽 눈금이어야 한다 — BPM ${h.BPM}`);
});

test('🔴 축상태 — «합계 = 쓸 것 + 버린 것»으로 낸다(좋은 0과 「안 재봤다」를 가른다)', () => {
  const s = 반.축상태([관('a', '밤', 10, 8), 관('b', '새벽', 0, 0)]);
  assert.equal(s.관측, s.쓸수있는것 + s.버린것);
  assert.equal(s.버린것, 1, '0명 구간은 조용히 사라지지 않고 «버린 것»으로 센다');
});

test('방송 전에는 0이고, 그것을 «정상»이라고 말한다', () => {
  const s = 반.축상태([]);
  assert.equal(s.관측, 0);
  assert.match(s.말, /정상이다/);
});
