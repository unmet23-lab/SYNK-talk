/* 확인 카드 «하루 두 장» (2026-09-06 · 철학 Ⅱ-8 v1.22 「맞아? 카드 하루 두 장」 · 4회차 심문 A1)
 *
 * ■ 지키는 셋
 *   ① 오늘 답 0 → 카드 · 오늘 답 1(다른 카드) → 둘째 카드는 «다른» 키 · 오늘 답 2 → 없음
 *   ② 옛 호출(`오늘답함: true`)은 상한 도달로 읽는다 — 옛 호출자가 조용히 두 장을 내지 않게
 *   ③ 상한 값의 정본은 lib 하나다(`하루상한`) — 서버·회귀가 같은 수를 읽는다
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { 확인카드, 하루상한 } = require('../lib/성향확인.js');

/* 재료는 성향확인.test.js 의 꼴 그대로(리듬 = 여유제출 후보 · 작성과정 = 고쳐쓰기 후보) — 둘째 장이 «다른 축»에서 서게 둘을 준다. */
const 리듬 = (덧 = {}) => ({ 제출률: 1, 마감여유분_중앙: 180, 지각: 0, n: 5, 여유n: 5, ...덧 });
const 축들 = () => ({ 리듬: 리듬(), 작성과정: { 되돌림_중앙: 2, n: 4 }, 집중띠: null });

test('③ 상한은 둘이고 lib 이 낸다', () => {
  assert.equal(하루상한, 2);
});

test('① 하루 두 장 — 첫 장 뒤 둘째 장은 다른 카드 · 둘 뒤엔 없음', () => {
  const 첫 = 확인카드(축들(), { 오늘답수: 0, 오늘답한키들: [], 부정키들: [] }, 't', 'v');
  assert.ok(첫, '오늘 답 0 인데 카드가 없다');
  const 둘째 = 확인카드(축들(), { 오늘답수: 1, 오늘답한키들: [`${첫.trait_axis}:${첫.shown_key}`], 부정키들: [] }, 't', 'v');
  assert.ok(둘째, '오늘 답 1 인데 둘째 장이 없다 — 하루 두 장이 안 열렸다');
  assert.notEqual(둘째.shown_key, 첫.shown_key, '둘째 장이 첫 장과 같은 카드다 — 같은 카드의 둘째 답은 색인이 duplicate 로 접는다');
  assert.equal(확인카드(축들(), { 오늘답수: 2, 오늘답한키들: [], 부정키들: [] }, 't', 'v'), null, '오늘 둘 답했는데 셋째가 나왔다');
});

test('② 옛 호출 `오늘답함: true` 는 상한 도달이다', () => {
  assert.equal(확인카드(축들(), { 오늘답함: true, 부정키들: [] }, 't', 'v'), null);
  assert.ok(확인카드(축들(), { 오늘답함: false, 부정키들: [] }, 't', 'v'), '옛 호출의 「안 답함」이 막혔다');
});
