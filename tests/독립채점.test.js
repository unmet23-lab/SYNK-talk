/* 독립 채점 통로 — 새는 방향은 «정답 누출»이고, 새면 증상이 없다(채점자는 답을 몰랐다고
 * 말해 주지 않는다). 그래서 탐지력은 픽스처가 지고, 실저장소(evals/)는 거짓양성만 본다.
 *
 * 픽스처의 답 값들은 모델 출력과 «절대 겹치지 않게» 지어냈다 — 실데이터에서는 모델이
 * 맞힌 항목의 고친문장이 기대교정과 같은 글자라, 값 대조로는 누출과 정답을 못 가른다.
 * 여기서만큼은 값이 겹치지 않아야 「패킷에 이 글자가 있으면 누출이다」가 참이 된다. */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const {
  패킷만들기, 지시문조립, 조각내기, 수거하기, 대조하기, 축분류,
} = require('../tools/독립채점.js');
const { 채점하기 } = require('../tools/eval-score.js');

const 미니픽스처 = {
  항목: [
    { id: 'C01', 종류: '정상', 입력: '하늘이 파랗습니다.', 기대태그: ['오류없음'], 불변: true, 함정: '몰래심은함정글' },
    {
      id: 'E01', 종류: '오류', 입력: '밥을 먹었다가 학교에 갔어요.',
      기대태그: ['어미:연결어미'], 기대교정: '몰래심은답A', 포함: ['몰래심은포함'], 불포함: ['먹었다가'],
      대안태그: [['어미:시제']], 비고: '몰래심은비고',
    },
    { id: 'M01', 종류: '오류', 입력: '어제 도서관에 공부해요.', 기대태그: ['조사:처소(에·에서)'], 기대교정: '몰래심은답B', 포함: [], 불포함: [], 복합: true },
  ],
};
const 미니출력 = {
  항목: [
    { id: 'C01', 고친문장: '하늘이 파랗습니다.', 오류태그: ['오류없음'] },
    { id: 'E01', 고친문장: '밥을 먹고 학교에 갔어요.', 오류태그: ['어미:연결어미'] },
    { id: 'M01', 검증사유: '형식밖' }, // 고친문장 자체가 없다 → 채점할 답이 없다
  ],
};

test('패킷 — 픽스처의 답이 한 글자도 안 실린다 (키도 값도 · 탐지력 픽스처)', () => {
  const { 패킷항목, 매핑, 제외 } = 패킷만들기(미니픽스처, 미니출력);
  const 글 = JSON.stringify(패킷항목);
  // 값 누출 — 픽스처에만 있는 값들이 패킷에 있으면 누출이다.
  for (const 심은것 of ['몰래심은답A', '몰래심은답B', '몰래심은포함', '몰래심은비고', '몰래심은함정글']) {
    assert.ok(!글.includes(심은것), `답 값이 샜다: ${심은것}`);
  }
  // 키 누출 — 허용목록 밖 픽스처 칸이 키로 실리면, 값이 우연히 겹치는 날 그대로 샌다.
  for (const 키 of ['종류', '기대태그', '기대교정', '포함', '불포함', '대안태그', '불변', '함정', '비고', '복합']) {
    assert.ok(!글.includes(`"${키}"`), `픽스처 칸이 키로 샜다: ${키}`);
  }
  // id 누출 — E/C/M 접두가 「오류가 있는가」의 답이다.
  assert.ok(!/"[CEM]\d/.test(글), 'id 접두가 샜다');
  for (const p of 패킷항목) assert.match(p.id, /^B\d{3}$/);
  // 채점할 답이 없는 행은 조용히 사라지지 않고 제외 목록에 «보인다» (F207).
  assert.strictEqual(패킷항목.length, 2);
  assert.strictEqual(제외.length, 1);
  assert.strictEqual(제외[0].id, 'M01');
  assert.match(제외[0].사유, /형식밖/);
  assert.strictEqual(매핑.length, 2);
});

test('패킷 — 결정적이다: 두 번 만들어도 같은 순서·같은 블라인드 id (F281)', () => {
  const 한번 = 패킷만들기(미니픽스처, 미니출력);
  const 두번 = 패킷만들기(미니픽스처, 미니출력);
  assert.deepStrictEqual(한번.패킷항목, 두번.패킷항목);
  assert.deepStrictEqual(한번.매핑, 두번.매핑);
});

test('지시문 — 재료(문장·태그 어휘)는 실리고 답은 안 실린다', () => {
  const { 패킷항목 } = 패킷만들기(미니픽스처, 미니출력);
  const 글 = 지시문조립(패킷항목, ['조사:기타', '오류없음'], 1, 1);
  assert.ok(글.includes('밥을 먹었다가 학교에 갔어요.'), '학생 문장이 실려야 한다');
  assert.ok(글.includes('조사:기타'), '태그 어휘가 실려야 한다');
  assert.ok(!글.includes('몰래심은답A'), '지시문으로 답이 샜다');
  assert.ok(글.includes('다르다»는 실패 근거가 아니다'), '「다름≠실패」 문구가 지시문의 급소다');
});

test('조각내기 — 전부 담기고 겹치지 않는다', () => {
  const 조각 = 조각내기([1, 2, 3, 4, 5], 2);
  assert.deepStrictEqual(조각.flat(), [1, 2, 3, 4, 5]);
});

test('수거 — 빠짐·중복·모르는 id·규격 밖 값은 조용히 못 지나간다', () => {
  const 매핑 = [{ 블라인드id: 'B001', id: 'E01' }, { 블라인드id: 'B002', id: 'C01' }];
  const 좋은표 = { id: 'B001', 원문오류: '있다', 교정: '통과', 태그: '통과', 사유: 'ㅇ' };
  const 다른표 = { id: 'B002', 원문오류: '없다', 교정: '통과', 태그: '통과', 사유: 'ㅇ' };
  // 빠짐 — 완결은 «합집합»으로 잰다: 아무도 B002 를 안 내면 목록으로 던진다.
  assert.throws(() => 수거하기(매핑, [{ 채점자: 'a', 판정들: [좋은표] }]), /채점 안 됐다.*B002/);
  // 조각 분담 — 채점자마다 전량을 요구하면 정상 수거가 전부 죽는다(첫 실행 실측).
  const 분담 = 수거하기(매핑, [
    { 채점자: 'a', 판정들: [좋은표] },
    { 채점자: 'b', 판정들: [다른표] },
  ]);
  assert.strictEqual(분담.length, 2);
  // 중복 — 같은 채점자가 같은 id 를 두 번.
  assert.throws(() => 수거하기(매핑, [{ 채점자: 'a', 판정들: [좋은표, 좋은표] }]), /중복/);
  // 채점자 «간» 같은 id 는 오류가 아니라 표다(복수 표결).
  const 두표 = 수거하기(매핑, [
    { 채점자: 'a', 판정들: [좋은표, 다른표] },
    { 채점자: 'b', 판정들: [{ ...좋은표, 교정: '실패' }] },
  ]);
  assert.strictEqual(두표.filter((r) => r.id === 'E01').length, 2);
  // 모르는 id — 딴 판의 매핑으로 수거하면 그 자리에서 선다.
  assert.throws(() => 수거하기(매핑, [{ 채점자: 'a', 판정들: [{ ...좋은표, id: 'B999' }, 다른표] }]), /모르는 블라인드 id/);
  // 규격 밖 값.
  assert.throws(() => 수거하기(매핑, [{ 채점자: 'a', 판정들: [{ ...좋은표, 교정: '보통' }, 다른표] }]), /규격 밖/);
  // 정상 — 블라인드가 풀려 실제 id 로 돌아온다.
  const 행들 = 수거하기(매핑, [{ 채점자: 'a', 판정들: [좋은표, 다른표] }]);
  assert.deepStrictEqual(행들.map((r) => r.id).sort(), ['C01', 'E01']);
  assert.strictEqual(행들[0].채점자, 'a');
});

test('대조 — 갈림의 네 칸이 갈린다 (탐지력 픽스처 · 픽스처 축은 eval-score 실통로)', () => {
  const 픽스처rows = 채점하기(미니픽스처, 미니출력);
  // C01: 픽스처 통과(불변·오류없음) · E01: 픽스처 교정 ✖(포함 미충족)·태그 ✔ · M01: 무응답.
  const 독립행들 = [
    { id: 'C01', 블라인드id: 'B?', 채점자: 'a', 원문오류: '없다', 교정: '실패', 태그: '통과', 사유: '고쳤어야' },
    { id: 'E01', 블라인드id: 'B?', 채점자: 'a', 원문오류: '있다', 교정: '통과', 태그: '통과', 사유: '그 자체로 옳다' },
  ];
  const { 요약, 갈림, 분모 } = 대조하기(픽스처rows, 독립행들);
  assert.strictEqual(분모.픽스처, 3);
  assert.strictEqual(분모.독립채점, 2);
  assert.deepStrictEqual(요약.채점안됨, ['M01']); // 무응답 행은 채점 대상이 아니었음이 «보인다»
  // C01 교정: 픽스처 ✔ vs 독립 ✖ → 픽스처만통과 (픽스처가 못 보는 실패 후보)
  assert.strictEqual(요약.교정.픽스처만통과, 1);
  // E01 교정: 픽스처 ✖ vs 독립 ✔ → 독립만통과 (하나로 못박은 자리 후보)
  assert.strictEqual(요약.교정.독립만통과, 1);
  // 태그 축은 둘 다 통과.
  assert.strictEqual(요약.태그.둘다통과, 2);
  const 축들 = 갈림.map((g) => `${g.id}:${g.축}:${g.칸}`).sort();
  assert.deepStrictEqual(축들, ['C01:교정:픽스처만통과', 'E01:교정:독립만통과']);
});

test('대조 — 표결이 갈리면 다수결로 접지 않고 «표결갈림»으로 남는다', () => {
  const 픽스처rows = 채점하기(미니픽스처, 미니출력);
  const 독립행들 = [
    { id: 'C01', 채점자: 'a', 원문오류: '없다', 교정: '통과', 태그: '통과', 사유: 'ㅇ' },
    { id: 'C01', 채점자: 'b', 원문오류: '없다', 교정: '실패', 태그: '통과', 사유: 'ㄴ' },
    { id: 'E01', 채점자: 'a', 원문오류: '있다', 교정: '통과', 태그: '통과', 사유: 'ㅇ' },
    { id: 'E01', 채점자: 'b', 원문오류: '있다', 교정: '통과', 태그: '통과', 사유: 'ㅇ' },
  ];
  const { 요약 } = 대조하기(픽스처rows, 독립행들);
  assert.strictEqual(요약.교정.표결갈림, 1);      // C01 — 채점자끼리 갈렸다
  assert.strictEqual(요약.교정.독립만통과, 1);    // E01 — 만장일치는 값이다
});

test('축분류 — 픽스처가 못 잰 축(무응답·판정불가)은 「픽스처못잼」으로 따로 선다', () => {
  assert.strictEqual(축분류(null, '통과'), '픽스처못잼');
  assert.strictEqual(축분류(true, '판단불가'), '독립못잼');
  assert.strictEqual(축분류(true, '통과'), '둘다통과');
  assert.strictEqual(축분류(false, '실패'), '둘다실패');
  assert.strictEqual(축분류(true, '실패'), '픽스처만통과');
  assert.strictEqual(축분류(false, '통과'), '독립만통과');
});

/* 실저장소 — 거짓양성만 본다(탐지력은 위 픽스처가 이미 졌다). 값 대조는 여기서 못 쓴다:
 * 모델이 맞힌 항목은 고친문장이 기대교정과 같은 글자라 「기대교정 값이 보인다」가 정상이다.
 * 그래서 구조(키·id·개수)만 잰다. */
test('실저장소 — 패킷이 픽스처 칸을 키로 싣지 않고, 분모가 맞는다', (t) => {
  const 픽스처경로 = path.join(__dirname, '..', 'evals', '픽스처.json');
  const 출력경로 = path.join(__dirname, '..', 'evals', '출력_v7.json');
  if (!fs.existsSync(픽스처경로) || !fs.existsSync(출력경로)) {
    t.skip('evals 실파일이 없다');
    return;
  }
  const fixture = JSON.parse(fs.readFileSync(픽스처경로, 'utf8'));
  const outputs = JSON.parse(fs.readFileSync(출력경로, 'utf8'));
  const { 패킷항목, 매핑, 제외 } = 패킷만들기(fixture, outputs);
  const 글 = JSON.stringify(패킷항목);
  for (const 키 of ['종류', '기대태그', '기대교정', '포함', '불포함', '대안태그', '불변', '함정', '비고', '복합']) {
    assert.ok(!글.includes(`"${키}"`), `실패킷에 픽스처 칸이 샜다: ${키}`);
  }
  assert.ok(!/"id":"[CEM]\d/.test(글), '실패킷에 원 id 가 샜다');
  assert.strictEqual(패킷항목.length + 제외.length, fixture.항목.length, '분모가 안 맞는다');
  assert.strictEqual(new Set(매핑.map((m) => m.블라인드id)).size, 매핑.length, '블라인드 id 가 겹친다');
});
