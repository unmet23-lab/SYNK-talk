/* 성과 계기판(`tools/성과계기판.js`) — **판정**을 못박는다.
 *
 * 이 도구의 실패는 예외가 아니라 «그럴듯하게 낮은 숫자»로 온다. 아직 안 온 창을 분모에 넣으면
 * 개원 첫 달은 구조적으로 낮게 찍히고, 그 화면을 본 사람은 「개입이 효과 없다」고 읽는다.
 * 그래서 여기서 재는 것은 「도구가 돈다」가 아니라 **분모가 무엇인가**다.
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const { 계수내기, 질의, HTML만들기, 빈칸, 담기 } = require('../tools/성과계기판.js');
const { 쓰는사건, 회수창, 닻사건 } = require('../lib/성과회수.js');

const 기점 = Date.UTC(2026, 7, 1);
const t = (일) => new Date(기점 + 일 * 86400000).toISOString();

const 개입 = (learner_id, 일, 덧 = {}) => ({
  event_id: `iv-${learner_id}-${일}`, learner_id, event_type: 닻사건,
  occurred_at: t(일), intervention_id: `IV-${learner_id}`, ...덧,
});

/* 축이 값을 내려면 배정↔제출 쌍이 필요하다(리듬축은 배정이 0이면 null 이라 표본0 이 된다). */
const 배정제출 = (learner_id, 일) => ([
  { event_id: `a-${learner_id}-${일}`, learner_id, event_type: 'task.assigned', occurred_at: t(일), due_at: t(일 + 1) },
  { event_id: `s-${learner_id}-${일}`, learner_id, event_type: 'submission.created', occurred_at: t(일 + 0.5) },
]);

const 창값 = (계수, 일수) => 계수.전체.창[`${일수}일`];

test('🔴 연결률의 분모에 «미도래» 는 안 들어간다 — 이 파일의 존재 이유', () => {
  /* 개입 둘: L1 은 7일 창이 이미 닫혔고(t10+7 ≤ t22), L2 는 아직 안 왔다(t20+7 > t22).
   * 분모를 「개입 수」로 잡으면 0.5 가 나오고, 그 값은 「절반은 효과가 없었다」로 읽힌다.
   * 실제로 잴 수 있었던 것은 하나뿐이고 그 하나는 측정됐다 — 정답은 1.0 이다. */
  const 행들 = [
    개입('L1', 10), ...배정제출('L1', 8), ...배정제출('L1', 11),
    개입('L2', 20), ...배정제출('L2', 18), ...배정제출('L2', 21),
  ];
  const c = 창값(계수내기(행들, { 기준시각: t(22) }), 7);

  assert.equal(c.미도래, 1, '아직 안 온 창을 미도래로 안 셌다');
  assert.equal(c.잴수있던것, 1, '미도래가 분모에 들어갔다 — 개원 첫 달이 구조적으로 낮게 찍힌다');
  assert.equal(c.연결률, 1, `연결률이 ${c.연결률} 이다 — 분모를 개입 수로 잡았다`);
});

test('🔴 «표본0» 은 분모에 들어간다 — 잴 수 있었는데 활동이 없었던 것은 결과다', () => {
  /* 미도래(재료가 아직 없다)와 표본0(재료를 잴 수 있었는데 활동이 0이었다)은 다른 사실이다.
   * 표본0 까지 분모에서 빼면 연결률은 「측정된 것 중 측정된 비율」이 되어 늘 1.0 이다. */
  const 행들 = [
    개입('L1', 10), ...배정제출('L1', 8), ...배정제출('L1', 10.2),   // 개입 뒤 활동 O
    개입('L3', 10), ...배정제출('L3', 8),                             // 개입 뒤 활동 X
  ];
  const c = 창값(계수내기(행들, { 기준시각: t(40) }), 1);

  assert.equal(c.측정, 1);
  assert.equal(c.표본0, 1, '개입 뒤 활동이 0인 창을 표본0 으로 안 셌다');
  assert.equal(c.잴수있던것, 2, '표본0 이 분모에서 빠졌다 — 그러면 연결률은 영원히 1.0 이다');
  assert.equal(c.연결률, 0.5);
});

test('🔴 남의 활동이 남의 개입 성과로 안 적힌다 — 학습자별로 묶는다', () => {
  /* 사건 배열을 통째로 넘기면 성과회수는 그것을 «그 학생의» 신호로 믿는다. 묶기를 빠뜨리면
   * 활발한 학생 한 명이 전원의 개입을 「효과 있음」으로 만든다 — 값만 보고는 절대 못 잡는다. */
  const 행들 = [
    개입('L1', 10), ...배정제출('L1', 8),          // L1: 개입 뒤 활동 0
    ...배정제출('L9', 10.2), ...배정제출('L9', 10.5), // L9: 같은 시각에 활발(개입은 없다)
  ];
  const 계수 = 계수내기(행들, { 기준시각: t(40) });

  assert.equal(계수.전체.개입, 1, '개입이 아닌 학생의 행을 개입으로 셌다');
  assert.equal(창값(계수, 1).표본0, 1, 'L9 의 활동이 L1 의 개입 성과로 섞여 들어갔다');
  assert.equal(창값(계수, 1).측정, 0);
});

test('선택 규칙(policy_ver)별로 가른다 — 합치면 「무엇이 통했나」가 사라진다', () => {
  const 행들 = [
    개입('L1', 10, { policy_ver: '오늘과제.v1' }), ...배정제출('L1', 8), ...배정제출('L1', 10.2),
    개입('L2', 10, { policy_ver: '오늘과제.v2' }), ...배정제출('L2', 8),
    개입('L3', 10), ...배정제출('L3', 8),                              // 규칙 이전에 배달된 행
  ];
  const 계수 = 계수내기(행들, { 기준시각: t(40) });

  assert.deepEqual(Object.keys(계수.규칙별).sort(), ['(규칙 미기록)', '오늘과제.v1', '오늘과제.v2']);
  assert.equal(계수.규칙별['오늘과제.v1'].개입, 1);
  assert.equal(계수.규칙별['오늘과제.v1'].창['1일'].측정, 1);
  assert.equal(계수.규칙별['오늘과제.v2'].창['1일'].표본0, 1);
  assert.equal(계수.전체.개입, 3, '전체가 규칙별 합과 갈렸다');
});

test('🔴 기준선이 잘린 개입은 세지 않고 «뺐다»고 적는다', () => {
  /* 질의 창 시작 부근의 개입은 직전 30일이 통째로 비어 「활동이 없던 학생」과 구별이 안 된다.
   * 조용히 세면 그 구분 불가가 낮은 값으로만 나타난다. */
  const 행들 = [개입('L1', 2), 개입('L2', 40), ...배정제출('L2', 39)];
  const 계수 = 계수내기(행들, { 기준시각: t(60), 개입최소시각: t(35) });

  assert.equal(계수.전체.개입, 1, '기준선이 잘린 개입을 셌다');
  assert.equal(계수.제외.기준선부족, 1, '뺀 건수를 안 적었다 — 조용한 절단은 「전부 봤다」로 읽힌다');
});

test('관측 짝은 `parent_event_id` 로 이어져야 닿음으로 센다', () => {
  const 행들 = [
    개입('L1', 10),
    { event_id: 'v1', learner_id: 'L1', event_type: 'content.viewed', occurred_at: t(10.5), parent_event_id: 'iv-L1-10' },
    개입('L2', 10),
    { event_id: 'v2', learner_id: 'L2', event_type: 'content.viewed', occurred_at: t(10.5), intervention_id: 'IV-L2' },
  ];
  const 계수 = 계수내기(행들, { 기준시각: t(40) });

  assert.equal(계수.전체.닿음, 1, '`intervention_id` 만 든 관측 행을 짝으로 셌다(계약 c9 는 parent_event_id 다)');
  assert.equal(계수.전체.관측률, 0.5);
  assert.equal(계수.전체.지연분_중앙, 720, '배달→열람 지연이 안 잡혔다');
});

test('🔴 못 센 것은 삼키지 않는다 — 실패·학습자 없음을 건수로 낸다', () => {
  /* 미실행이 통과와 같은 모양이면 계기판은 낙관을 그린다(F207 — 초록은 분모와 함께 읽는다). */
  const 행들 = [
    { ...개입('L1', 10), occurred_at: '언제인지모름' },
    { ...개입('L2', 10), learner_id: null },
    개입('L3', 10), ...배정제출('L3', 8),
  ];
  const 계수 = 계수내기(행들, { 기준시각: t(40) });

  assert.equal(계수.전체.개입, 1);
  assert.equal(계수.제외.계산실패, 1, '시각을 못 읽은 개입을 조용히 버렸다');
  assert.equal(계수.제외.학습자없음, 1, '묶을 수 없는 개입을 조용히 버렸다');
  assert.equal(계수.실패사유.length, 1, '왜 못 셌는지가 안 남았다 — 건수만으로는 고칠 자리를 못 찾는다');
  assert.match(계수.실패사유[0], /occurred_at/);
});

