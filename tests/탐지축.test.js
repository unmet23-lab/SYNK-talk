test('탐지축이 쓴 행이 evidence_refs 에 남는다 — 재계산 대조의 재료', () => {
  const e = 짚음(오류들[0], 1);
  const r = 상태([e]);
  const 사건들 = r.evidence_refs && (r.evidence_refs.사건 || r.evidence_refs.events || r.evidence_refs);
  assert.ok(JSON.stringify(사건들).includes(e.event_id),
    `탐지축이 센 행의 주소가 근거에 없다: ${JSON.stringify(r.evidence_refs)}`);
});
