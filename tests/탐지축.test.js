test('자기인식 v12(Ⅲ⑦) — 짚음 제출이 축 분모·표기에 들되 estimator_confidence 표본은 안 늘린다', () => {
  const r = 상태([짚음(오류들[0], 1, { 확신도: 'low' }), 짚음(오류들[1], 1)]);
  assert.ok(r.축.자기인식, '짚음 제출만으로 자기인식축이 안 섰다 — v12 확장이 죽었다');
  assert.equal(r.축.자기인식.n, 2, '짚음 두 건이 분모에 안 들었다');
  assert.equal(r.축.자기인식.저확신, 1, '짚음의 low 표기가 안 세어졌다');
  assert.equal(r.축.자기인식.표본n, 0, '퀴즈 0건인데 표본 몫이 있다 — 짚음 행은 끈기축이 이미 센다');
  /* 신뢰도 등식 — 짚음 두 건의 표본 기여는 끈기 쪽 «한 번»뿐이어야 한다(회귀 ⑩의 그 규율).
   * 자기인식이 표본에 또 얹으면 이 등식이 깨진다. */
  const 끈기만 = r.축.끈기 ? r.축.끈기.n : 0;
  const 표본추정 = Object.entries(r.축).reduce(
    (s, [이름, a]) => s + (['작성과정', '집중띠', '탐지', '강제산출'].includes(이름) || !a ? 0 : (a.표본n ?? a.n)), 0);
  assert.ok(표본추정 <= 끈기만 + 2, `표본이 ${표본추정} — 같은 짚음이 두 축에서 표본으로 세어진다`);
});

