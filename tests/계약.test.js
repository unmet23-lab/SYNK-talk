  const 답 = (태그) => ({ 고친문장: '제 동생은 키가 커요.', 오류태그: 태그 });

  // ① 대안 세트가 맞으면 태그 축 통과 — 그리고 «대안으로» 통과했음이 표시된다
  const 대안 = scoreOne(대안있음, 답(['어휘:연어(자연스러운 짝)']));
