  // ② 기대 태그 그대로 맞은 것은 «대안 통과가 아니다»(둘이 섞이면 엄격 숫자가 틀린다)
  const 정면 = scoreOne(대안있음, 답(['어휘:유의어혼동']));
  assert.ok(정면.판정.태그 && !정면.대안통과, '기대 태그로 통과한 것이 대안으로 세어졌다');

  /* ③ ⚠ 반대 방향 — 대안에도 없는 태그는 «여전히» 실패한다. 이 축이 새는 순간
   *   태그 채점은 아무것도 안 재는 칸이 된다. */
  assert.equal(scoreOne(대안있음, 답(['어순'])).판정.태그, false, '대안 밖 태그까지 통과시킨다');

