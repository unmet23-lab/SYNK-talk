'use strict';
/* 감사 회귀 W2C3 — App.js·테마 군단 시공 앵커.
 *   여기 담는 것은 D7-6 하나다: 도착확인 미전송 카드의 주 행동 버튼이 실제로 «말하기로 가는
 *   길»(돌아가기)을 부르는가. 나머지 항목(D6-8·G3-3·G3-7·D1-11)은 hitSlop·접근성 속성·칸 순서라
 *   렌더 무해 — 기존 시험(화면렌더·화면구문·각 화면 시험)이 덮고 새 회귀 불요(조스펙 그대로).
 *
 * ■ 재는 법 — 소스 검사(코드만): 재전송 통로는 말하기 화면 마운트 하나뿐이라(나가기게이트 B1 ·
 *   둘째 통로 금지), 이 버튼이 지는 몫은 「돌아가기를 부른다」가 전부다. 그 배선을 코드만으로 잰다.
 */
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const { ROOT } = require('./lib/화면세우기.js');
const { 코드만, 코드만픽스처 } = require('./lib/소스검사.js');

test('D7-6 — 미전송 카드의 「말하기 열어서 지금 보내기」가 돌아가기를 부르고, 「알겠어요」보다 위에 선다', () => {
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대, '주석 제거기가 죽었다 — 아래 검사가 거짓 초록이 된다');
  const 소스 = 코드만(fs.readFileSync(path.join(ROOT, 'src', '도착확인.js'), 'utf8'));

  const 자리 = 소스.indexOf('말하기 열어서 지금 보내기');
  assert.ok(자리 > -1, '주 행동 버튼이 없다 — 미전송 카드가 다시 「알겠어요」(막다른 안내)뿐이 된다');

  /* 그 라벨을 감싼 Pressable 이 돌아가기를 부르는가 — 재전송을 여기서 새로 하면 둘째 통로다(B1). */
  const 버튼 = 소스.slice(소스.lastIndexOf('<Pressable', 자리), 자리);
  assert.match(버튼, /onPress=\{돌아가기\}/,
    '버튼이 돌아가기를 안 부른다 — 말하기 화면 마운트가 곧 재전송이라, 이 길이 끊기면 탭이 처방이 아니다');
  assert.ok(!/밀린것|게임큐밀기|보낼것/.test(버튼),
    '버튼이 재전송을 직접 한다 — 밀린 것을 올리는 자리는 말하기 화면 하나다(둘째 통로 금지)');

  /* 주 행동이 위, 닫기(알겠어요)가 아래 — 순서가 뒤집히면 처방보다 막다른 문이 먼저 읽힌다. */
  const 닫기자리 = 소스.indexOf('알겠어요');
  assert.ok(닫기자리 > -1, '픽스처가 낡았다 — 미전송 카드의 닫기 버튼(알겠어요)이 사라졌다');
  assert.ok(자리 < 닫기자리, '주 행동 버튼이 「알겠어요」 아래에 있다 — 위가 주 행동 자리다');
});
