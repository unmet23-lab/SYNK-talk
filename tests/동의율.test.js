/* 본인 동의율 회귀(세층합류 §6 · 09-01) — 판별 분리·마지막 답 접기·분모 규율을 행동으로 못박는다. */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const { 동의율표 } = require('../lib/동의율.js');

const 행 = (학생, 판, 축, 키, 답, 때, id = `${학생}-${때}`) => ({
  event_type: 'estimate.responded',
  learner_id: 학생,
  event_id: id,
  occurred_at: `2026-09-0${때}T10:00:00Z`,
  payload: { trait_axis: 축, shown_key: 키, response: 답, estimator_version: 판, ver: 1 },
});

test('동의율표 — (판·축·키)별 집계 · n = 맞다 + 아니다 (합계 = 갈래 + 갈래)', () => {
  const r = 동의율표([
    행('a', 'v15+성향확인.v2', '리듬', '여유제출', '맞다', 1),
    행('b', 'v15+성향확인.v2', '리듬', '여유제출', '아니다', 1),
    행('a', 'v15+성향확인.v2', '작성과정', '고쳐쓰기', '맞다', 2),
  ]);
  const 판 = r.판들['v15+성향확인.v2'];
  assert.equal(판.n, 3);
  assert.equal(판.맞다, 2);
  assert.equal(판.아니다, 1);
  assert.equal(판.n, 판.맞다 + 판.아니다, '합계가 갈래의 합이 아니다');
  assert.equal(판.학생수, 2);
  assert.deepEqual(판.축별.리듬.키별.여유제출, { 맞다: 1, 아니다: 1 });
  assert.deepEqual(판.축별.작성과정.키별.고쳐쓰기, { 맞다: 1, 아니다: 0 });
});

test('마지막 답 접기(v14 상속) — 같은 (학생·축·키)의 여러 답은 마지막 하나 · 접힘·뒤집힘을 센다', () => {
  const r = 동의율표([
    행('a', 'v', '리듬', '여유제출', '맞다', 1),
    행('a', 'v', '리듬', '여유제출', '아니다', 3),   // 뒤집힘 — 마지막 답이 이긴다
    행('a', 'v', '리듬', '여유제출', '아니다', 2),   // 순서 섞여 들어와도 시각순으로 접는다
  ]);
  const 판 = r.판들.v;
  assert.equal(판.n, 1, '원행 셋이 쌍 하나로 안 접혔다 — 모순 쌍이 자에 잡음으로 남는다');
  assert.equal(판.아니다, 1, '마지막 답(아니다)이 아니라 다른 것을 골랐다');
  assert.equal(판.접힘수, 2);
  assert.equal(판.뒤집힘수, 1, '맞다→아니다 한 번(시각순) — 아니다→아니다는 뒤집힘이 아니다');
});

test('판 분리 — 다른 판의 답은 다른 질문에 대한 답이라 합산하지 않는다', () => {
  const r = 동의율표([
    행('a', 'v13+성향확인.v1', '리듬', '여유제출', '아니다', 1),
    행('a', 'v15+성향확인.v2', '리듬', '여유제출', '맞다', 2),
  ]);
  assert.equal(Object.keys(r.판들).length, 2, '두 판이 한 칸에 섞였다');
  assert.equal(r.판들['v13+성향확인.v1'].아니다, 1);
  assert.equal(r.판들['v15+성향확인.v2'].맞다, 1);
  assert.equal(r.판들['v15+성향확인.v2'].접힘수, 0, '판이 다른 답을 같은 쌍으로 접었다');
});

test('학생 분리 — 다른 학생의 같은 (축·키)는 각자 쌍이다(남의 답으로 안 접는다)', () => {
  const r = 동의율표([
    행('a', 'v', '리듬', '여유제출', '맞다', 1),
    행('b', 'v', '리듬', '여유제출', '맞다', 1, 'b-1b'),
  ]);
  assert.equal(r.판들.v.n, 2);
  assert.equal(r.판들.v.접힘수, 0);
  assert.equal(r.판들.v.학생수, 2);
});

test('거르기 — 다른 사건·모르는 답은 안 센다(지어내지 않는다) · 빈 입력은 빈 표', () => {
  const r = 동의율표([
    { event_type: 'submission.created', learner_id: 'a', payload: {} },
    행('a', 'v', '리듬', '여유제출', '글쎄', 1),      // 값록 밖 — c13 은 맞다|아니다 둘뿐
    행('a', 'v', '리듬', '여유제출', '맞다', 2),
  ]);
  assert.equal(r.총행수, 1, '값록 밖 답이 라벨로 세어졌다');
  assert.equal(r.판들.v.n, 1);
  const 빈 = 동의율표([]);
  assert.deepEqual(빈, { 판들: {}, 총행수: 0, 총학생수: 0 });
  assert.deepEqual(동의율표(null), { 판들: {}, 총행수: 0, 총학생수: 0 });
});

test('계기판 배선 — 계수내기가 동의율을 싣고, HTML 이 각주(동의율 ≠ 정확도)를 든다', () => {
  const { 계수내기, HTML만들기 } = require('../tools/성과계기판.js');
  const 계수 = 계수내기([
    행('a', 'v15+성향확인.v2', '리듬', '여유제출', '맞다', 1),
  ], { 기준시각: '2026-09-05T00:00:00Z' });
  assert.equal(계수.동의율.판들['v15+성향확인.v2'].맞다, 1, '계수에 동의율이 안 실렸다');
  계수.승격 = { 의사: 0, 사건: 0, 격차: 0 };
  계수.스탬프 = { 전체: 0, 완비: 0, 미비: 0 };
  const html = HTML만들기({ 계수, ref: 'test', 잘림: false });
  assert.ok(html.includes('본인 동의율'), '계기판 화면에 동의율 절이 없다');
  assert.ok(html.includes('정확도가 아니라 본인 확인의 비율'), '각주(동의율 ≠ 정확도)가 없다 — ⑤ 자기설명');
  assert.ok(/맞다 1 \+ 아니다 0/.test(html), '「n = 맞다 + 아니다」 꼴 분모가 화면에 없다');
});
