/* eval 실행기(tools/eval-run.js) — 원격 묶음 크기의 **증명 가능한 상계**.
 *
 * 같은 절차에서 두 번째 죽음이었다(08-12 하루): 25건(평균 6초 가정)도, 12건(「절반 여유」)도
 * Edge Fn IDLE_TIMEOUT 150초에 504. 평균으로 고른 손튜닝 숫자는 분산에 진다 — 항목 하나가
 * 왕복제한까지 걸리는 것이 합법이라 최악은 「묶음크기 × 왕복제한」이다. 그래서 묶음크기를
 * 한계에서 파생시켰고, 이 회귀는 그 파생이 다시 손 숫자로 돌아가는 것을 막는다.
 * 스크립트는 require 하면 main() 이 돌므로(벤더 비용) 소스 텍스트로 잰다 — 이 저장소의
 * Deno 함수 회귀와 같은 방식(tests/교정배치.test.js).
 */
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const 본체 = fs.readFileSync(path.join(ROOT, 'tools', 'eval-run.js'), 'utf8');
const { 왕복제한밀리 } = require('../lib/교정엔진.js');

const 숫자 = (m, 이름) => {
  assert.ok(m, `${이름}을 소스에서 못 찾았다 — 이 회귀가 재는 자리가 사라졌다`);
  return Number(m[1].replace(/_/g, ''));
};

test('🔴 못 읽은 응답은 원문을 남긴다 — 안 남기면 「형식밖」의 원인을 아무도 못 말한다', () => {
  /* 08-12 첫 API 기준선이 그 상태였다: 형식밖 6건인데 파일에는 사유 한 낱말뿐이라, 잘린 JSON
   * (토큰 고갈 → 예산 재산정)과 울타리·군말(형식 이탈 → 프롬프트 문구)이 **같은 모양**이었다.
   * 처방이 정반대인 둘을 가르는 재료가 원문이고, 그건 그 순간에만 손에 있다. */
  assert.match(본체, /항목\.원문\s*=/, '원문을 남기는 자리가 사라졌다 — 형식밖이 다시 진단 불가가 된다');

  /* 🔑 조건이 **채점기의 「무응답」 술어와 같아야** 한다: 채점에서 빠지는 항목이 곧 원문이
   *   남는 항목이다. 갈리면 「채점엔 안 들어가는데 원문도 없는」 항목이 생기고, 그 항목은
   *   어느 쪽에서도 안 보인다. 두 파일이 같은 술어(`고친문장 === undefined`)를 쓰는지 문다. */
  assert.match(본체, /항목\.고친문장 === undefined/, '실행기의 원문 보존 술어가 갈렸다');
  const 채점기 = fs.readFileSync(path.join(ROOT, 'tools', 'eval-score.js'), 'utf8');
  assert.match(채점기, /out\.고친문장 === undefined/, '채점기의 무응답 술어가 갈렸다 — 두 파일이 다른 것을 센다');

  /* 조건과 대입이 **한 자리**여야 한다 — 조건이 떨어져 나가면 파싱된 답에까지 원문이 겹쳐
   * 적히고, 그때 원형과 원문 중 어느 쪽이 정본인지가 흐려진다(채점기는 원형을 본다). */
  assert.match(본체, /if \(항목\.고친문장 === undefined\)\s*항목\.원문\s*=/,
    '원문 대입이 조건에서 떨어졌다 — 조건 없이 적히면 원형과 원문이 겹친다');
});

test('🔴 원격 묶음크기는 유휴한계에서 파생된다 — 손 숫자로 되돌리면 504 가 재발한다', () => {
  const 한계 = 숫자(/const 엣지유휴한계밀리 = ([\d_]+)/.exec(본체), '엣지유휴한계밀리');
  const 여유 = 숫자(/const 묶음크기 = Math\.max\(1, Math\.floor\(\(엣지유휴한계밀리 - ([\d_]+)\) \/ 왕복제한밀리\)\)/.exec(본체),
    '묶음크기 파생식');
  /* 최악 증명: 묶음 전체가 왕복제한까지 걸려도 유휴한계 안이다. 왕복제한을 늘리면
   * 묶음이 저절로 줄어 이 부등식이 유지된다 — 그게 파생의 이유다. */
  const 묶음크기 = Math.max(1, Math.floor((한계 - 여유) / 왕복제한밀리));
  assert.ok(묶음크기 * 왕복제한밀리 <= 한계 - 여유,
    `묶음 최악 ${묶음크기 * 왕복제한밀리}ms 가 유휴한계-여유 ${한계 - 여유}ms 를 넘는다`);
  /* 파생으로도 못 지키는 자리: 항목 «하나»가 유휴한계를 넘으면 묶음 1도 죽는다.
   * 왕복제한을 유휴한계 근처로 올리는 편집은 여기서 막는다. */
  assert.ok(왕복제한밀리 + 여유 <= 한계,
    `왕복제한 ${왕복제한밀리}ms 가 유휴한계 ${한계}ms 에 닿는다 — 묶음 1건도 504 가 된다`);
});

