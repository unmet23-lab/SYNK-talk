/* 플래그 게이트 회귀 — 「모르는 `--` 낱말은 조용히 무시되지 않는다」를 **등록층까지** 못박는다.
 *
 * 🔴 왜 있나 (실사건 넷 · 전부 「새는 방향이 통과」):
 *   F400(배포대조·읽기) → F435(원격SQL·읽기) → F436(원격SQL·쓰기) → 그리고 2026-08-14 실측:
 *   `--운영` 을 받을 수 있는 도구 **11 중 die 하는 것은 1**뿐이었다. 조준(`--운영` 이 과녁을
 *   갈아타는 것)은 F436 이 `lib/자격증명.js` 로 공용화했고, 이 파일이 나머지 절반을 진다.
 *
 * 세 맹점(CLAUDE.md 신뢰성):
 *   ① 사람이 실제로 쓰는 표기 — 픽스처의 낱말은 한글 플래그다(이 저장소가 실제로 그렇다).
 *   ② 버그가 아직 있을 것을 요구하지 않는다 — 탐지력은 **픽스처**가 지고(순수 함수),
 *      실저장소에는 **거짓양성만** 검사한다(선언이 소스를 덮는가).
 *   ③ 자기 처방 — 차단문이 「아는 것은 …뿐」이라 말하는 그 낱말들이 실제로 통과하는지 본다.
 *      따를 수 없는 처방은 우회를 정상 통로로 만든다(F103).
 *
 * ⚠ 이 장치가 틀릴 때의 모습 = **거짓양성**이다(선언에서 낱말 하나를 빠뜨리면 되던 명령이 죽는다).
 *   그래서 ④가 소스에 실제로 쓰이는 `--낱말` 전량을 선언이 덮는지 기계로 센다 — 사람이 목록을
 *   손으로 맞추는 자리를 안 남긴다(CLAUDE.md 맹점 ④ · 맞는 얼굴로 틀린 값).
 */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { 공용플래그, 모름, 인자게이트 } = require('../lib/플래그.js');

const TOOLS = path.join(__dirname, '..', 'tools');

/** 게이트를 져야 하는 도구 = **`--운영` 을 받을 수 있는 도구** = 자격증명 공용 통로를 쓰는 도구.
 *  목록을 손으로 적지 않는다 — 손 목록은 새 도구가 생기는 날 조용히 낡는다(F435 가 정확히 그것). */
function 자격증명도구들() {
  return fs.readdirSync(TOOLS)
    .filter((f) => f.endsWith('.js'))
    .filter((f) => /자격증명\s*\.\s*읽기\s*\(/.test(fs.readFileSync(path.join(TOOLS, f), 'utf8')));
}

/** 소스가 **낱말 그 자체로** 인용한 `--…` 전량.
 *  ⚠ 「`--` 로 시작하는 문자열」로 세면 안 된다 — 오류 문구가 낱말로 시작하는 자리가 실제로 여럿이고
 *    (`'--교정문 이 필요하다 …'`), 자식 프로세스 인자(`'--format=%cI'`)도 섞인다. 2026-08-14 실측으로
 *    그 판이 거짓양성 7건을 냈다. 도구가 실제로 비교하는 모양(`args.includes('--적용')`)은 **정확 일치**라,
 *    따옴표 안이 낱말 하나인 것만 센다. */
const 낱말모양 = /^--[가-힣A-Za-z0-9_-]+$/;
function 소스낱말(소스) {
  const 전부 = (소스.match(/'[^']*'|"[^"]*"/g) || []).map((s) => s.slice(1, -1));
  return [...new Set(전부.filter((s) => 낱말모양.test(s)))];
}

/* ── ① 탐지력 — 픽스처가 진다 (실저장소·자격증명·네트워크 0) ─────────────── */

test('① 탐지력 — 모르는 낱말은 걸러진다 (조용히 무시하면 그게 F400·F435 다)', () => {
  assert.deepEqual(모름(['--운영모드'], ['--운영']), ['--운영모드'], '오타가 통과하면 딴 과녁을 재고 초록이 된다');
  assert.deepEqual(모름(['--진단'], ['--적용']), ['--진단'], '남의 도구 낱말이 통과하면 F435 그대로다');
  assert.deepEqual(모름(['--가', '--나'], []), ['--가', '--나'], '여러 개면 여러 개를 다 보여준다');
});

test('① 탐지력 — 게이트가 사람이 따라갈 수 있는 한 줄을 낸다 (도구 이름 + 아는 낱말)', () => {
  const 줄 = 인자게이트('원격SQL', ['--진단'], ['--운영', '--적용']);
  assert.ok(줄, '모르는 낱말인데 null 이면 게이트가 죽은 것이다');
  assert.match(줄, /--진단/, '무엇이 틀렸는지를 안 보여주면 고칠 수가 없다');
  assert.match(줄, /원격SQL/, '어느 도구가 거절했는지 없으면 여러 도구를 엮어 쓸 때 못 가른다');
  assert.match(줄, /--운영 --적용/, '아는 낱말을 안 보여주면 처방이 없는 차단이다(F103)');
});

/* ── ② 거짓양성 — 멀쩡한 것을 죽이지 않는다 ──────────────────────────── */

test('② 거짓양성 — 아는 낱말·값·위치 인자는 그대로 통과한다', () => {
  assert.deepEqual(모름(['--적용'], ['--적용']), []);
  assert.deepEqual(모름(['--학생', '홍길동'], ['--학생']), [], '값은 `--` 로 안 시작하니 애초에 안 걸린다');
  assert.deepEqual(모름(['supabase/x.sql', '--적용'], ['--적용']), [], '파일 경로를 낱말로 세면 도구가 통째로 죽는다');
  assert.deepEqual(모름([], ['--적용']), [], '인자 없음이 오류가 되면 기본 실행이 막힌다');
  assert.equal(인자게이트('아무개', ['--적용'], ['--적용']), null, '통과는 null 이다(오류 문자열이 아니다)');
});

test('② 자기 처방 — 차단문이 「아는 것」이라 부른 낱말은 실제로 통과한다 (F103)', () => {
  const 아는것 = ['--운영', '--적용', '--회전'];
  const 줄 = 인자게이트('라디오시크릿', ['--없는낱말'], 아는것);
  const 인용된것 = (줄.match(/--[가-힣a-zA-Z]+/g) || []).filter((f) => f !== '--없는낱말');
  for (const f of 인용된것) {
    assert.deepEqual(모름([f], 아는것), [], `차단문이 시킨 ${f} 가 그 가드에 막힌다 — 따를 수 없는 처방이다`);
  }
});

/* ── ③ 등록층 — 가드는 로직보다 여기서 샌다 (CLAUDE.md) ────────────────── */

test('③ 등록층 — `--운영` 을 받을 수 있는 도구는 **전부** 게이트를 지난다', () => {
  const 도구들 = 자격증명도구들();
  assert.ok(도구들.length >= 10, `스캔 대상이 ${도구들.length}개다 — 대상 소실은 통과가 아니다(F207)`);
  const 안건것 = 도구들.filter((f) => {
    const 소스 = fs.readFileSync(path.join(TOOLS, f), 'utf8');
    return !/인자게이트\s*\(/.test(소스);
  });
  assert.deepEqual(안건것, [],
    `게이트를 안 건 도구: ${안건것.join(', ')}\n`
    + '  이 도구들은 모르는 낱말을 **조용히 무시**한다 — 사람은 자기가 부탁한 일이 된 줄 안다(F435).\n'
    + "  붙이는 법: const 아는플래그 = [...공용플래그, '--…']; 뒤에 인자게이트(도구, args, 아는플래그).");
});

/** 게이트를 «부른» 자리가 그 답을 실제로 쓰는가. 셋 중 하나여야 한다:
 *  ⓐ `if (인자게이트(…))`  ⓑ `return 인자게이트(…)`  ⓒ `const X = 인자게이트(…)` + 뒤에서 X 를 씀.
 *  @returns {string|null} 위반 사유 · 정상이면 null */
function 답을쓰나(소스) {
  const i = 소스.search(/인자게이트\s*\(/);
  if (i === -1) return '부르지 않는다';
  const 앞 = 소스.slice(Math.max(0, i - 60), i);
  if (/if\s*\(\s*$/.test(앞) || /return\s+$/.test(앞)) return null;
  const m = 앞.match(/(?:const|let|var)\s+([^\s=]+)\s*=\s*$/);
  if (!m) return '답을 안 받는다(맨 호출문)';
  /* ⚠ `\b` 를 안 쓴다 — JS 의 `\b` 는 ASCII 낱말 경계라 한글 변수명(`플래그오류`)엔 **원리상 안 붙는다.**
   *   실측: `\b플래그오류\b` 로 세면 멀쩡한 도구 12개가 전부 「안 쓴다」로 나온다(거짓양성 100%). */
  return 소스.slice(i).includes(m[1]) ? null : `답(${m[1]})을 받고도 안 쓴다`;
}

test('🔑 ③-2 등록층 — 게이트의 «답»을 실제로 쓴다 (부르기만 하면 부르지 않은 것과 같다)', () => {
  /* 🔴 2026-08-15 실측: `회차장부.js` 가 `인자게이트(...)` 를 부르고 **반환을 버렸다.**
   *   위 ③은 「불렀나」만 봐서 초록이었다 — 가드가 자기 등록층에 눈이 먼 자리다(CLAUDE.md 맹점 ④).
   *   같은 계열 다섯 번째라(F400·F435·F436·08-14 11중1·이번) 문구가 아니라 기계로 못박는다. */
  const 위반 = [];
  for (const f of 자격증명도구들()) {
    const 사유 = 답을쓰나(fs.readFileSync(path.join(TOOLS, f), 'utf8'));
    if (사유 && 사유 !== '부르지 않는다') 위반.push(`${f}: ${사유}`);   // 안 부른 것은 ③의 몫이다
  }
  assert.deepEqual(위반, [],
    `${위반.join(' · ')}\n`
    + '  게이트는 던지지 않고 **문장을 돌려준다** — 안 받으면 모르는 낱말이 조용히 무시된다.\n'
    + '  고치는 법: const 플래그오류 = 인자게이트(도구, args, 아는플래그); if (플래그오류) die(플래그오류);');
});

test('③-2 탐지력 픽스처 — 세 모양을 갈라 본다 (판정기가 죽으면 위 검사는 장식이다)', () => {
  assert.equal(답을쓰나('const 플래그오류 = 인자게이트("t", a, b);\nif (플래그오류) die(플래그오류);'), null);
  assert.equal(답을쓰나('if (인자게이트("t", a, b)) die("x");'), null);
  assert.equal(답을쓰나('  return 인자게이트("t", a, b);'), null);
  assert.match(답을쓰나('인자게이트("t", a, b);\nconst 자세히 = 1;'), /맨 호출문/);
  assert.match(답을쓰나('const 오류 = 인자게이트("t", a, b);\nconst 자세히 = 1;'), /안 쓴다/);
});

test('③ 등록층 — 게이트를 건 도구는 `공용플래그`(--운영)를 **자기 목록에 편다**', () => {
  const 빠진것 = [];
  for (const f of 자격증명도구들()) {
    const 소스 = fs.readFileSync(path.join(TOOLS, f), 'utf8');
    const m = 소스.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
    if (!m) { 빠진것.push(`${f}(선언 없음)`); continue; }
    if (!/\.\.\.공용플래그/.test(m[1])) 빠진것.push(`${f}(공용플래그 안 폄)`);
  }
  assert.deepEqual(빠진것, [],
    `${빠진것.join(', ')}\n`
    + '  `--운영` 은 `lib/자격증명.js 읽기()` 가 **도구를 안 가리고** 조준에 쓴다(F436).\n'
    + '  자기 목록에 안 펴면 그 가드가 **자기 처방을 막는다** — 시스템이 시키는 낱말을 거절한다(F103).');
});

/* ── ④ 거짓양성 예방 — 선언이 소스 전량을 덮는가 (이 장치의 대가를 기계가 진다) ── */

test('④ 선언한 `아는플래그` 가 그 도구 소스에 쓰이는 `--낱말` 전량을 덮는다', () => {
  const 빠진것 = [];
  for (const f of 자격증명도구들()) {
    const 소스 = fs.readFileSync(path.join(TOOLS, f), 'utf8');
    const m = 소스.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
    if (!m) continue;                                   // ③이 이미 잡는다
    const 선언 = new Set([...공용플래그, ...소스낱말(`[${m[1]}]`)]);
    /* 선언 줄 자신은 빼고 센다 — 안 그러면 자기 자신을 덮는 것으로 늘 참이 된다
     * (가드는 자기 전처리에도 눈이 먼다 · CLAUDE.md 등록층 ④). */
    const 본문 = 소스.replace(m[0], '');
    for (const 낱말 of 소스낱말(본문)) {
      if (!선언.has(낱말)) 빠진것.push(`${f}: ${낱말}`);
    }
  }
  assert.deepEqual(빠진것, [],
    `선언에 없는데 소스가 쓰는 낱말: ${빠진것.join(' · ')}\n`
    + '  이대로 두면 **되던 명령이 죽는다** — 이 장치가 틀릴 때의 모습이 정확히 이것이다(F103).\n'
    + '  낱말이 진짜 인자가 아니면(주석·문서용) 선언에 넣지 말고 그 문자열을 소스에서 고쳐라.');
});

test('④ 탐지력 픽스처 — 선언이 낱말을 빠뜨리면 잡는다 (추출기가 죽으면 ④는 무엇이든 통과시킨다)', () => {
  const 가짜 = "const 아는플래그 = [...공용플래그, '--적용'];\n if (args.includes('--회전')) {}";
  const m = 가짜.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
  assert.ok(m, '선언 추출기가 죽었다 — 그러면 ④는 아무것도 안 센다');
  const 선언 = new Set([...공용플래그, ...소스낱말(`[${m[1]}]`)]);
  const 남은것 = 소스낱말(가짜.replace(m[0], '')).filter((w) => !선언.has(w));
  assert.deepEqual(남은것, ['--회전'], '빠진 낱말을 못 잡으면 이 검사는 장식이다');
});

test('④ 거짓양성 픽스처 — 선언이 다 덮으면 아무것도 안 잡는다', () => {
  const 가짜 = "const 아는플래그 = [...공용플래그, '--적용', '--회전'];\n args.includes('--회전'); args.includes('--운영');";
  const m = 가짜.match(/const\s+아는플래그\s*=\s*\[([^\]]*)\]/);
  const 선언 = new Set([...공용플래그, ...소스낱말(`[${m[1]}]`)]);
  const 남은것 = 소스낱말(가짜.replace(m[0], '')).filter((w) => !선언.has(w));
  assert.deepEqual(남은것, [], '멀쩡한 선언을 위반으로 잡으면 그 검사가 다음 마찰이 된다');
});
