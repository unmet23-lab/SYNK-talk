/* 생성 종단 — §12-29 「생성분이 ③답하기 통로를 탄다」 (v5.6 신설 · v5.7 F3 ④효과음 · v5.9 머리)
 *
 * ■ 이 시험이 재는 것 = «배선»뿐이다(§12-29 머리 · v5.8) — 생성 질문이 ③답하기 행에 앉고,
 *   꼬리·효과음이 폴백 배정과 같은 판정을 탄다. 문장이 학생에게 쓸 만한가(재미·도움·신선)는
 *   §8-A·§8-B 몫이라 여기 초록은 철학 ① 게이트의 초록이 아니다(F207).
 * ■ 벤더 0 — 생성 산출물은 픽스처 문자열이다(비결정에 안 기댄다).
 * ■ ③④의 「같은 판정」 증명 = **분기의 부재**: 꼬리·효과음·화면 층은 스냅샷의 `출처` 도
 *   `generation_outcome` 도 받지 않는다(코드에 그 비교 자체가 0). 갈릴 자리가 없는 것이
 *   「같은 결과」의 가장 강한 형태다 — 그 부재를 기계로 잰다.
 * ■ 캐릭터 반응(⑤)은 안 잰다(⏸ §12-29) — 마스코트 동반자층 코드 착지 전이라 지금 재면
 *   「없는 것」을 재는 픽스처다. 마스코트 트랙 착지 후 더한다. */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const { 스냅샷, 오늘과제, 답하기프롬프트, 따라말하기문장 } = require('../lib/오늘과제.js');
const 소리게이트 = require('../lib/소리게이트.js');

const 생성질문 = '주말에 보통 뭐 하면서 쉬어요?';
const 생성문장 = '주말에는 집에서 쉬면서 요리를 해요.';

test('§12-29 ①② — 생성 스냅샷에 ③답하기(차례 3) 행이 서고 그 프롬프트가 생성된 질문이다', () => {
  const snap = 스냅샷('2026-08-22', 생성문장, '생성', 생성질문);
  const 셋째 = (snap.호흡 || []).find((h) => h.차례 === 3);
  assert.ok(셋째, '③답하기 행이 없다 — 생성 질문이 앉을 자리가 없다');
  assert.equal(셋째.프롬프트, 생성질문, '③행의 프롬프트가 생성된 질문이 아니다');
  assert.equal(답하기프롬프트(snap), 생성질문, '조립기 쪽 판별(차례===3)이 같은 값을 되꺼낸다');
  assert.equal(따라말하기문장(snap), 생성문장, '②따라말하기 행의 문장이 생성 문장이다');
});

test('§12-29 ③ 앞단 — 생성 스냅샷과 폴백 스냅샷은 «같은 모양»이라 같은 통로를 탄다', () => {
  const 생성snap = 스냅샷('2026-08-22', 생성문장, '생성', 생성질문);
  const 폴백 = 오늘과제({ 날짜: '2026-08-22', 첫날: true });
  const 모양 = (snap) => ({
    차례들: (snap.호흡 || []).map((h) => h.차례),
    무엇들: (snap.호흡 || []).map((h) => h.무엇),
    형식2: (snap.호흡 || []).find((h) => h.차례 === 2)?.task_format,
  });
  assert.deepEqual(모양(생성snap), 모양(폴백.task_snapshot),
    '생성분의 호흡 구조가 폴백과 다르다 — 조립기가 두 통로로 갈린다(§8-A 「별도 배선 0」이 거짓이 된다)');
  /* 다른 것은 내용(문장·프롬프트·출처)뿐이어야 한다 — 출처 칸이 실제로 갈림을 확인(칸은 있되 분기는 없다). */
  assert.equal((생성snap.호흡 || []).find((h) => h.차례 === 2)?.출처, '생성');
  assert.notEqual((폴백.task_snapshot.호흡 || []).find((h) => h.차례 === 2)?.출처, '생성');
});

test('§12-29 ③④ — 꼬리·효과음·화면 층에 «생성 분기»가 0이다(같은 판정의 기계 증명)', () => {
  /* 꼬리(재발화·그자리재도전)는 교정 이력만 받고, achieve 게이트는 무오류 판정 하나만 받는다 —
   * 어느 층도 출처·generation_outcome 을 입력으로 안 받으므로 생성분이 다른 판정을 탈 자리가 없다.
   * 소스에 그 비교가 «생기면» 이 시험이 먼저 빨개진다. */
  const 분기꼴 = /출처\s*[=!]==?\s*['"]생성['"]|['"]생성['"]\s*[=!]==?\s*[^=]|generation_outcome/;
  for (const 상대 of ['lib/꼬리.js', 'lib/소리게이트.js', 'src/답장화면.js', 'src/말하기화면.js', 'src/과제API.js']) {
    const 글 = fs.readFileSync(path.join(ROOT, 상대), 'utf8');
    assert.ok(!분기꼴.test(글), `${상대} 에 생성 출처 분기가 생겼다 — §12-29 의 「같은 판정」이 깨질 자리`);
  }
});

test('§12-29 ④ — achieve 효과음 게이트의 판정 입력은 녹음 상태·이름뿐(스냅샷 무관)', () => {
  const 게이트 = 소리게이트.만들기();
  assert.deepEqual(게이트.판정('sfx', 'achieve'), { 허용: true },
    'achieve 가 킷 화이트리스트에 있고 비녹음 중 허용된다 — 생성분·폴백분 구분 입력 자체가 없다');
  게이트.녹음시작();
  assert.equal(게이트.판정('sfx', 'achieve').허용, false, '녹음 중엔 어느 배정이든 같은 거부다');
});
