test('④ 재시도 상한 — 판정은 재시도남았나 하나: 무제한(기본)·상한 2 에서 3번째 「다시」가 없다', () => {
  const 항목 = (attempt) => ({ date: '2026-08-13', step: '답하기', attempt });
  // 기본값(상한 없음) = 현행 — 몇 번을 남겼어도 참이다.
  assert.equal(재시도남았나([항목(1), 항목(2), 항목(3)], '2026-08-13', '답하기', null), true);
  assert.equal(재시도남았나([항목(1), 항목(2), 항목(3)], '2026-08-13', '답하기', undefined), true);
  // 상한 2 = 총 3 attempt(발주 G3 §4-3 ⑤): 남긴 시도 0·1개 → 남았다, 2개 → 끝.
  assert.equal(재시도남았나([], '2026-08-13', '답하기', 2), true);
  assert.equal(재시도남았나([항목(1)], '2026-08-13', '답하기', 2), true);
  assert.equal(재시도남았나([항목(1), 항목(2)], '2026-08-13', '답하기', 2), false);
  // 다른 날·다른 호흡은 안 센다 — 어제의 재시도가 오늘 상한을 깎으면 안 된다.
  assert.equal(재시도남았나([{ date: '2026-08-12', step: '답하기', attempt: 2 }], '2026-08-13', '답하기', 2), true);
  assert.equal(재시도남았나([{ date: '2026-08-13', step: '따라', attempt: 2 }], '2026-08-13', '답하기', 2), true);
});

