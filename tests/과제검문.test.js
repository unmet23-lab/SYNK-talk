/* 과제검문 회귀 — §8 표의 판정식·경계값(±1)·라벨 순서·중복 판정식 하나를 못박는다.
 * 경계값 «정확히 그 값은 통과»(§8) — 회귀가 ±1 을 함께 잰다. */
'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');

const { 검문, 정규화, 중복정규화, 문장길이, 질문길이 } = require('../lib/과제검문.js');

const 정상 = () => ({ 문장: '주말에 친구하고 등산을 갔어요.', 질문: '주말에 무엇을 했어요?' });

test('정상 산출은 통과하고, 반환 문장·질문은 정규화 «후» 값이다 (§7 「검문이 본 것과 같은 바이트」)', () => {
  const r = 검문({ 문장: '  주말에  친구하고 등산을 갔어요.‍'.normalize('NFD').replace('‍', ''), 질문: ' 주말에 무엇을  했어요? ' });
  assert.equal(r.ok, true, r.사유들.join('/'));
  assert.equal(r.문장, '주말에 친구하고 등산을 갔어요.');
  assert.equal(r.질문, '주말에 무엇을 했어요?');
  assert.equal(r.사유, null);
});

test('경계값 — 하한·상한 «정확히 그 값»은 통과, ±1 은 탈락 (§8)', () => {
  const 한글 = (n) => '가'.repeat(n);
  assert.equal(검문({ 문장: 한글(문장길이.하한), 질문: `${한글(질문길이.하한 - 1)}?` }).ok, true);
  assert.equal(검문({ 문장: 한글(문장길이.상한), 질문: `${한글(질문길이.상한 - 1)}?` }).ok, true);
  assert.equal(검문({ 문장: 한글(문장길이.하한 - 1), 질문: '주말에 무엇을 했어요?' }).사유, '길이');
  assert.equal(검문({ 문장: 한글(문장길이.상한 + 1), 질문: '주말에 무엇을 했어요?' }).사유, '길이');
  assert.equal(검문({ 문장: 한글(10), 질문: `${한글(질문길이.상한)}?` }).사유, '길이');
});

test('빈 출력이 첫 라벨이다 — 여러 항목이 걸려도 사유는 §8 행 순서의 첫 것 하나', () => {
  const r = 검문({ 문장: '', 질문: '' });
  assert.equal(r.사유, '빈출력');
  assert.equal(r.ok, false);
});

test('한국어 비율 — «각각» 잰다: 짧은 질문의 영문이 긴 문장에 희석되지 않는다 (§8 I8)', () => {
  const r = 검문({ 문장: '주말에 친구하고 등산을 갔어요 정말 즐거웠어요.', 질문: 'What did you do?' });
  assert.equal(r.사유, '한국어비율');
  assert.equal(검문({ 문장: '주말에 abc 등산을 갔어요.', 질문: '주말에 무엇을 했어요?' }).ok, true,
    '한글이 6할 이상인데 탈락했다');
});

test('금칙 서식 — 따옴표 시작·끝 · 번호 매기기 · 접두 라벨 (§8 표)', () => {
  assert.equal(검문({ ...정상(), 문장: '"주말에 등산을 갔어요."' }).사유, '금칙서식');
  assert.equal(검문({ ...정상(), 문장: '1. 주말에 등산을 갔어요.' }).사유, '금칙서식');
  assert.equal(검문({ ...정상(), 질문: '질문: 주말에 무엇을 했어요?' }).사유, '금칙서식');
});

test('질문 형태 — 질문«만» ? 로 끝나야 한다 (문장에는 안 건다)', () => {
  assert.equal(검문({ ...정상(), 질문: '주말에 무엇을 했는지 말해요.' }).사유, '질문형태');
  assert.equal(검문(정상()).ok, true, '문장이 ? 없이 통과해야 한다');
});

test('식별자 역유입 — 문장·질문 «각각» · 빈 식별자는 안 잰다 (§10)', () => {
  assert.equal(검문({ ...정상(), 식별자들: ['S2026-001'] }).ok, true);
  /* 라틴 식별자는 한국어 비율도 끌어내리므로 첫 라벨이 아니라 «걸렸다» 자체를 잰다 —
   * 라벨 순서는 위 「빈 출력이 첫 라벨」 케이스가 이미 못박았다. */
  assert.ok(검문({ 문장: '주말에 S2026-001 학생이 등산을 갔어요.', 질문: '주말에 무엇을 했어요?', 식별자들: ['S2026-001'] })
    .사유들.includes('식별자역유입'));
  assert.equal(검문({ ...정상(), 식별자들: ['', '  '] }).ok, true, '빈 식별자가 전건 탈락을 만든다');
});

test('중복 — 판정식 «하나»: 문장↔이력문장·질문↔이력질문 각각 완전 일치, 어느 하나면 중복 (§8 C2)', () => {
  const 이력 = { 최근문장들: ['주말에 친구하고 등산을 갔어요.'], 최근질문들: ['어제 뭐 했어요?'] };
  assert.equal(검문({ ...정상(), ...이력 }).사유, '중복', '문장만 일치해도 중복이다(F4 — 절반이 샌다)');
  assert.equal(검문({ 문장: '오늘 시장에서 과일을 샀어요.', 질문: '어제 뭐 했어요?', ...이력 }).사유, '중복',
    '질문만 일치해도 중복이다');
  assert.equal(검문({ 문장: '오늘 시장에서 과일을 샀어요.', 질문: '주말에 무엇을 했어요?', ...이력 }).ok, true);
});

test('중복 정규화 — 문장부호·따옴표 무시 · 조사는 안 건드린다 (§8 C2 정규화 규격)', () => {
  assert.equal(중복정규화('주말에 등산을 갔어요.'), 중복정규화('「주말에 등산을 갔어요…」'));
  assert.notEqual(중복정규화('주말에 등산을 갔어요'), 중복정규화('주말에 등산은 갔어요'),
    '조사가 정규화됐다 — 한국어에서 조사 정규화는 뜻을 바꾼다');
  assert.equal(검문({ ...정상(), 최근문장들: ['주말에 친구하고 등산을 갔어요'] }).사유, '중복',
    '마침표 차이가 중복을 피하게 했다');
});

test('복수 실패 — 사유들이 전부 남는다(순서 그대로) · 라벨은 첫 것 (§8 · attempts.gate_failed_reasons)', () => {
  const r = 검문({ 문장: '"Hi"', 질문: 'ok' });
  assert.equal(r.사유, '길이');
  assert.ok(r.사유들.includes('한국어비율') && r.사유들.includes('금칙서식') && r.사유들.includes('질문형태'),
    r.사유들.join('/'));
  assert.deepEqual([...r.사유들].sort(), [...new Set(r.사유들)].sort(), '사유가 중복 기재됐다');
});

test('정규화 — NFC 고정: NFD 로 온 같은 글자가 같은 바이트가 된다', () => {
  assert.equal(정규화('가나다'.normalize('NFD')), '가나다');
});

/* 유호 확정 08-23 «완화»의 회귀 — 2~3문장·후속 질문. 완화가 «어디까지»인지를 경계로 못박는다. */
test('완화 08-23 — 세 문장 120자 통과 · 물음표 2 통과 · 3부터 질문형태 탈락', () => {
  const 긴문장 = '밥을 급하게 먹었더니 배가 아파요. 아마 체한 것 같아요. 그래서 약을 먹고 조금 쉬려고 해요.';
  assert.ok(검문({ 문장: 긴문장, 질문: '몸이 안 좋을 때는 보통 어떻게 해요?', 식별자들: [], 최근문장들: [], 최근질문들: [] }).ok,
    '유호 교정 실물 모양(3문장)이 길이에 걸렸다 — 완화가 안 실렸다');
  const 후속 = '바쁜 날 딱 한 사람한테만 연락한 적 있어요? 왜 바빴는지 기억나요?';
  assert.ok(검문({ 문장: '주말에는 시간이 없어서 언니한테밖에 연락을 못 했어요', 질문: 후속, 식별자들: [], 최근문장들: [], 최근질문들: [] }).ok,
    '후속 질문(물음표 2)이 탈락했다');
  const r = 검문({ 문장: '오늘은 날씨가 좋아서 산책을 했어요', 질문: '어디 갔어요? 누구랑요? 뭐 했어요?', 식별자들: [], 최근문장들: [], 최근질문들: [] });
  assert.ok(!r.ok && r.사유들.includes('질문형태'), '물음표 3개(설문)가 통과했다 — 물음표상한이 죽었다');
});
