/* 유호 확정 08-23 «완화»의 회귀 — 2~3문장·후속 질문. 완화가 «어디까지»인지를 경계로 못박는다. */
test('완화 08-23 — 세 문장 120자 통과 · 물음표 2 통과 · 3부터 질문형태 탈락', () => {
  const 긴문장 = '밥을 급하게 먹었더니 배가 아파요. 아마 체한 것 같아요. 그래서 약을 먹고 조금 쉬려고 해요.';
  assert.ok(검문({ 문장: 긴문장, 질문: '몸이 안 좋을 때는 보통 어떻게 해요?', 식별자들: [], 최근문장들: [], 최근질문들: [] }).ok,
    '유호 교정 실물 모양(3문장)이 길이에 걸렸다 — 완화가 안 실렸다');
  const 후속 = '바쁜 날 딱 한 사람한테만 연락한 적 있어요? 왜 바빴는지 기억나요?';
  assert.ok(검문({ 문장: '주말에는 시간이 없어서 언니한테밖에 연락을 못 했어요', 질문: 후속, 식별자들: [], 최근문장들: [], 최근질문들: [] }).ok,
    '후속 질문(물음표 2)이 탈락했다');
  const r = 검문({ 문장: '오늘은 날씨가 좋아서 산책을 했어요', 질문: '어디 갔어요? 누구랑요? 뭐 했어요?', 식별자들: [], 최근문장들: [], 최근질문들: [] });
  assert.ok(!r.ok && r.사유들.includes('질문형태'), '물음표 3개(설문)가 통과했다 — 물음표상한이 죽었다');
});

/* ── 「1~3문장」을 기계가 잰다 (08-26 신설 · 그전엔 프롬프트 지시로만 살았다) ────────────────
 * 🔴 이 절의 셋째 검사가 급소다 — 세는 자를 «자르는 자»로 바꾸면 이 검문은 원리상 아무것도
 *   못 막으면서 초록이다. 그 되돌림을 여기서 잡는다(「검사가 제 주장을 원리상 못 본다」 무늬). */
const { 문장들, 문장개수, 상한: 문장수상한 } = require('../lib/문장끊기.js');
const 넷문장 = '밥을 급하게 먹었어요. 배가 아파요. 체한 것 같아요. 약을 먹으려고요.';
const 문장재료 = (문장) => ({ 문장, 질문: '몸이 안 좋을 때는 보통 어떻게 해요?', 식별자들: [], 최근문장들: [], 최근질문들: [] });

test('문장 수 — 3문장은 통과 · 4문장부터 「길이」로 탈락', () => {
  const 셋 = '밥을 급하게 먹었더니 배가 아파요. 아마 체한 것 같아요. 그래서 약을 먹으려고요.';
  assert.equal(문장개수(셋), 3);
  assert.ok(검문(문장재료(셋)).ok, '3문장은 계약 안이다(유호 확정 08-23 「1~3문장」)');

  assert.equal(문장개수(넷문장), 4);
  const r = 검문(문장재료(넷문장));
  assert.ok(!r.ok, '4문장이 통과했다 — 문장 수 검문이 죽었다');
  assert.ok(r.사유들.includes('길이'), `사유가 「길이」여야 한다: ${r.사유들.join('/')}`);
  assert.deepEqual([...r.사유들], [...new Set(r.사유들)], '「길이」가 두 번 실렸다(글자수 조건과 겹쳐 밀어 넣은 자리)');
});

test('사유 라벨은 DB CHECK 의 일곱 값을 안 넘는다 — 여덟째를 만들면 운영 jobs_finalize 가 던진다', () => {
  const 캐논 = new Set(['빈출력', '길이', '한국어비율', '금칙서식', '질문형태', '식별자역유입', '중복']);
  for (const s of 검문(문장재료(넷문장)).사유들) {
    assert.ok(캐논.has(s), `사유 「${s}」는 attempts_gate_values_c13 캐논 밖이다`);
  }
});

test('🔴 세는 자와 자르는 자는 다른 자다 — 「문장들().length」로 재면 4문장이 조용히 통과한다', () => {
  /* 자르는 자는 상한에서 «자르기를 멈추므로» 반환 길이가 절대 상한을 안 넘는다. */
  assert.equal(문장들(넷문장).length, 문장수상한, '문장들() 이 상한을 넘겼다 — 받침 규약이 바뀌었다');
  assert.equal(문장들(넷문장).length > 문장수상한, false,
    '이 식이 참이 될 수 있다면 위 회귀가 우연히 통과한 것이다 — 검문이 이 식을 쓰면 원리상 아무것도 못 막는다');
  assert.ok(문장개수(넷문장) > 문장수상한, '문장개수() 가 상한을 못 넘는다면 검문이 막는 척만 한다');
});

test('세는 자는 자르는 자와 «같은 규칙»으로 센다 — 따옴표 안·소수점은 한 문장', () => {
  const 인용 = '친구가 「같이 가자. 늦지 마.」라고 했어요.';
  assert.equal(문장개수(인용), 1, '따옴표 안의 종결자를 문장 끝으로 셌다 — 자르는 자와 갈렸다');
  assert.equal(문장개수('오늘 기온이 3.5도까지 내려갔어요.'), 1, '소수점을 문장 끝으로 셌다');
  /* 갈리면 「검문은 4문장이라는데 화면은 3조각」이 된다 — 상한 아래에선 두 자가 같은 수를 내야 한다. */
  for (const s of ['한 문장이에요.', '두 문장이에요. 그렇죠?', 인용]) {
    assert.equal(문장들(s).length, 문장개수(s), `상한 아래에서 두 자가 갈렸다: 「${s}」`);
  }
});
