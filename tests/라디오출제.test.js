/* 라디오 출제 리듬 회귀 — 「언제 여는가·무엇을 칠 차례인가」.
 *
 * 이 층이 틀리면 드러나는 자리가 **송출 첫날 새벽**뿐이고, 그때의 모양은
 * 「문항 재고가 하루 만에 말랐다」 또는 「쿼터를 넘겨 수집이 조용히 0」이다 — 둘 다 소급이 안 된다.
 * 그래서 값으로 못박는다(주석이 아니라).
 */
'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');

const 출제 = require('../lib/라디오출제.js');
const 수집 = require('../lib/라디오수집.js');

const 기본 = { 동시시청: 5, 오늘연수: 0, 마지막출제ms: null, 지금ms: 1_700_000_000_000, 쿼터상한: 18 };

test('열림 — 조건 넷을 다 지나면 열고, 남은 칸을 함께 낸다', () => {
  const r = 출제.열까(기본);
  assert.equal(r.열다, true);
  assert.equal(r.사유, '열림');
  assert.equal(r.남은칸, 6, '하루상한 6 과 쿼터 18 중 작은 쪽이 상한이다');
});

test('🔴 「모름」은 「0명」이 아니다 — 시청자 수를 못 읽은 회차엔 안 연다', () => {
  const r = 출제.열까({ ...기본, 동시시청: null });
  assert.equal(r.열다, false);
  assert.equal(r.사유, '시청자수모름');
  assert.equal(r.남은칸, null, '못 잰 것을 숫자로 접지 않는다');
});

test('시청자 0 이면 안 연다 — 아무도 없는데 태우면 재고가 소진되고 허수 분모가 남는다', () => {
  assert.equal(출제.열까({ ...기본, 동시시청: 0 }).사유, '시청자0');
});

test('🔴 쿼터 상한이 하루 상한보다 작으면 «쿼터»가 이긴다 — 출제부터 줄인다', () => {
  const r = 출제.열까({ ...기본, 쿼터상한: 2 });
  assert.equal(r.남은칸, 2, '하루상한 6 이어도 쿼터가 2 면 2 다');
  const 찬 = 출제.열까({ ...기본, 오늘연수: 2, 쿼터상한: 2 });
  assert.equal(찬.열다, false);
  assert.equal(찬.사유, '하루상한');
});

test('쿼터를 못 재면 안 연다 — 「모름」을 통과로 읽으면 넘긴 날 수집이 조용히 죽는다', () => {
  assert.equal(출제.열까({ ...기본, 쿼터상한: null }).사유, '쿼터상한모름');
});

test('🔑 정각마다 열지 않는다 — 간격이 모자라면 접는다(유호 확정 08-25 ①의 실체)', () => {
  const 방금 = 기본.지금ms - 10 * 60 * 1000;
  assert.equal(출제.열까({ ...기본, 마지막출제ms: 방금 }).사유, '간격부족');
  const 한참 = 기본.지금ms - 출제.라운드간최소밀리;
  assert.equal(출제.열까({ ...기본, 마지막출제ms: 한참 }).열다, true, '최소 간격을 채우면 열린다');
});

test('실측 — 60초 폴링의 쿼터 상한(18)이 하루 상한(6)을 안 막는다', () => {
  const 쿼터 = 수집.라운드상한(수집.폴링하한밀리);
  assert.equal(쿼터, 18);
  assert.equal(출제.열까({ ...기본, 쿼터상한: 쿼터 }).남은칸, 출제.하루상한기본);
  assert.equal(수집.쿼터안전전체(수집.폴링하한밀리, 출제.하루상한기본 * 2), true,
    '하루 6회 + 재도전 6회 = 12 라운드도 쿼터 안이다');
});

/* ── 상태 기계 ─────────────────────────────────────────────────────── */

const T0 = 1_700_000_000_000;
const 진행기본 = { 출제ms: T0, 마감초: 60, 지금ms: T0 };

test('출제 직후는 대기 — 남은초가 마감까지의 시간이다', () => {
  const r = 출제.다음동작(진행기본);
  assert.equal(r.동작, '대기');
  assert.equal(r.남은초, 60);
});

test('마감초가 지나면 마감을 친다', () => {
  const r = 출제.다음동작({ ...진행기본, 지금ms: T0 + 60_000 });
  assert.equal(r.동작, '마감');
  assert.equal(r.남은초, 0);
});

test('마감 뒤 곧바로 정답이 아니다 — 학생이 마감줄을 읽을 틈을 둔다', () => {
  const 마감뒤 = { ...진행기본, 마감침: true, 지금ms: T0 + 60_000 };
  assert.equal(출제.다음동작(마감뒤).동작, '대기', '공개지연 전에는 안 친다');
  assert.equal(출제.다음동작({ ...마감뒤, 지금ms: T0 + 60_000 + 출제.공개지연초 * 1000 }).동작, '정답');
});

test('정답 뒤 60초에 재도전 — 이게 retry_of 쌍을 만드는 자리다', () => {
  const 정답뒤 = { ...진행기본, 마감침: true, 정답침: true };
  const 정답때 = T0 + 60_000 + 출제.공개지연초 * 1000;
  assert.equal(출제.다음동작({ ...정답뒤, 지금ms: 정답때 + 1000 }).동작, '대기');
  assert.equal(출제.다음동작({ ...정답뒤, 지금ms: 정답때 + 출제.재도전지연초 * 1000 }).동작, '재도전');
});

test('🔴 재도전은 한 번뿐 — 사슬이 길어지면 그날 재고가 마른다', () => {
  const 늦게 = T0 + 10 * 60 * 1000;
  const 끝난 = { ...진행기본, 마감침: true, 정답침: true, 지금ms: 늦게 };
  assert.equal(출제.다음동작({ ...끝난, 깊이: 1 }).동작, '끝', '재도전 라운드의 자식은 없다');
  assert.equal(출제.다음동작({ ...끝난, 재도전냄: true }).동작, '끝', '이미 냈으면 끝이다');
});

test('시각을 안에서 읽지 않는다 — 안 주면 던진다(회귀가 돌린 날에 따라 갈리면 안 된다)', () => {
  assert.throws(() => 출제.열까({ ...기본, 지금ms: undefined }), TypeError);
  assert.throws(() => 출제.다음동작({ 출제ms: T0 }), TypeError);
});

test('탐지력 — 상수를 0 으로 바꾸면 위 판정이 실제로 무너진다', () => {
  assert.ok(출제.라운드간최소밀리 > 0, '0 이면 정각마다 여는 것과 같아진다');
  assert.ok(출제.재도전지연초 > 0 && 출제.공개지연초 > 0);
  assert.equal(출제.재도전깊이상한, 1);
});
