'use strict';
/**
 * `tools/왕복시험.js --새학생` 의 두 규율 — 실 DB 가 필요한 시험이라 CI 는 이 층밖에 못 본다.
 *
 * 왜 소스 구조를 보나: 이 모드의 값은 「무엇을 재느냐」가 아니라 **무엇을 안 심느냐**에 있다.
 * 관문마다 픽스처를 심으면 그 사이 이음매는 영원히 안 재진다(F176 — 리허설 학생 64명 중
 * 동의가 있는 40명 안에서만 돌던 시험을 갓 등록한 학생으로 태우자 두 칸이 연달아 막혔다).
 * 그래서 「동의를 SQL 로 심지 않는다」와 「운영 명부에 학생을 만들지 않는다」 둘 다 되돌아오면
 * 모드가 이름만 남는다 — 되돌아온 것이 **초록으로 보인다**는 게 이 검사가 있는 이유다.
 */
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const 소스 = fs.readFileSync(path.join(__dirname, '..', 'tools', '왕복시험.js'), 'utf8');

/** 주석·문자열이 아니라 실제로 도는 줄만 본다 — 설명문의 낱말이 검사를 통과시키면 안 된다. */
const 실행줄 = 소스.split('\n').filter((줄) => {
  const t = 줄.trim();
  return t && !t.startsWith('*') && !t.startsWith('//') && !t.startsWith('/*');
}).join('\n');

test('--새학생 은 --운영승인 으로도 안 뚫린다(운영 명부에 사람을 만들지 않는다)', () => {
  // 리허설 판정을 `새학생` 과 함께 보는 줄이 있어야 한다. `--운영승인` 예외가 여기 끼면 무효다.
  const 게이트 = 실행줄.split('\n').find((줄) => /새학생\s*&&/.test(줄) && /rehearsal/.test(줄));
  assert.ok(게이트, '--새학생 전용 리허설 게이트가 없다 — 운영 명부에 시험 학생이 생긴다');
  assert.ok(!/운영승인/.test(게이트), '그 게이트에 --운영승인 예외가 붙으면 뚫린다');
});

test('--새학생 은 동의를 SQL 로 심지 않고 운영자 도구를 실제로 부른다', () => {
  /* 🔴 「이름이 어딘가 적혀 있다」로 재면 안 된다 — 첫 판이 그렇게 썼다가 변이가 살아남았다:
   *   호출을 SQL 로 되돌려도 `console.log('… tools/동의발급.js')` 한 줄이 검사를 통과시켰다.
   *   부르는 것은 문자열이 아니라 **프로세스 실행**이라, 그 결합을 본다. */
  assert.ok(/execFileSync[\s\S]{0,300}?동의발급\.js/.test(실행줄),
    'tools/동의발급.js 를 실제로 실행하지 않는다 — 동의 관문이 다시 픽스처가 됐다(F176 그대로)');

  // 심는 쪽 통로는 남아 있어도 된다(인자로 학생을 받는 판이 쓴다). 다만 **else 절 안**이어야 한다.
  const 심는곳 = 실행줄.indexOf('insert into engine.consents');
  if (심는곳 !== -1) {
    assert.ok(/\}\s*else\s*\{/.test(실행줄.slice(Math.max(0, 심는곳 - 300), 심는곳)),
      '동의 SQL 심기가 새학생 분기 안에 있다 — --새학생 이 다시 픽스처를 심는다');
  }
});

test('첫 등록이 막히면 거기서 멈춘다(뒤 관문의 초록이 앞 관문의 실패를 덮지 않는다)', () => {
  // first-login 이 200 이 아닌데 계속 돌면, 그 뒤 55건은 **다른 학생 상태**를 재는 것이 된다.
  assert.ok(/first-login/.test(실행줄), '첫 등록 통로를 안 탄다');
  assert.ok(/fr\.status !== 200[\s\S]{0,200}?die\(/.test(실행줄),
    '첫 등록 실패에 die 가 없다 — 개원 첫날 막히는 자리가 초록으로 지나간다');
});

/* ── 업로드왕복 ⑪ — 「앱이 조립한 봉투」를 재려면 **앱의 가드까지** 재현해야 한다.
 *
 * 2026-08-07 실측: 이 갈래가 `항목추가` 에 `correlation_id` 를 안 넘겨 `제출사건` 이 `null` 을
 * 냈고, 시험은 그 `null` 을 그대로 보내 **평문 500** 을 받았다. 증상은 「서버가 이상하다」인데
 * 원인은 봉투 조립이었다. 게다가 그 실패가 `if (한건?.event_id)` 를 닫아 **뒤따르는 검사 6건이
 * 통째로 실행되지 않았고**, 총계는 「20/21」로 나왔다 — 미실행이 한 건의 실패로 접혀 보였다.
 * `제출사건` 이 요구하는 칸은 계약이 늘 때마다 는다(①-10 이 `correlation_id` 를 공통 필수로
 * 올린 것이 이 사고의 시작이다). 그래서 「그 칸 이름」이 아니라 **가드의 존재**를 못박는다. */
const 업로드소스 = fs.readFileSync(path.join(__dirname, '..', 'tools', '업로드왕복시험.js'), 'utf8');
const 업로드실행줄 = 업로드소스.split('\n').filter((줄) => {
  const t = 줄.trim();
  return t && !t.startsWith('*') && !t.startsWith('//') && !t.startsWith('/*');
}).join('\n');

test('업로드왕복은 앱처럼 한 앉음을 들려 보내고, 봉투가 안 서면 거기서 멈춘다', () => {
  /* ① 앱이 넘기는 값(`src/말하기화면.js` 흐름잡기)을 시험도 넘긴다. `항목추가` 는 이 칸을
   *   짓지 않고 받기만 하므로(`lib/제출로그.js`), 안 넘기면 조용히 `null` 봉투가 된다. */
  assert.ok(/항목추가\([\s\S]{0,900}?correlation_id\s*:/.test(업로드실행줄),
    '업로드왕복이 항목추가에 correlation_id 를 안 넘긴다 — 제출사건이 null 을 내고 500 이 된다');

  /* ② 그리고 **앱의 가드**(`src/제출API.js` `if (!사건) return`)가 있어야 한다. ①만 있으면
   *   다음에 필수 칸이 하나 더 늘 때 같은 사고가 같은 모양(평문 500)으로 돌아온다. */
  assert.ok(/제출사건\([\s\S]{0,400}?if\s*\(!\s*사건\s*\)[\s\S]{0,120}?die\(/.test(업로드실행줄),
    '봉투가 null 인데 그대로 보낸다 — 조립 실패가 「서버 장애」로 읽힌다(앱은 여기서 멈춘다)');
});
