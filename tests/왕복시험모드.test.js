'use strict';
/**
 * `tools/왕복시험.js --새학생` 의 두 규율 — 실 DB 가 필요한 시험이라 CI 는 이 층밖에 못 본다.
 *
 * 왜 소스 구조를 보나: 이 모드의 값은 「무엇을 재느냐」가 아니라 **무엇을 안 심느냐**에 있다.
 * 관문마다 픽스처를 심으면 그 사이 이음매는 영원히 안 재진다(F176 — 리허설 학생 64명 중
 * 동의가 있는 40명 안에서만 돌던 시험을 갓 등록한 학생으로 태우자 두 칸이 연달아 막혔다).
 * 그래서 「동의를 SQL 로 심지 않는다」와 「운영 명부에 학생을 만들지 않는다」 둘 다 되돌아오면
 * 모드가 이름만 남는다 — 되돌아온 것이 **초록으로 보인다**는 게 이 검사가 있는 이유다.
 */
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const 소스 = fs.readFileSync(path.join(__dirname, '..', 'tools', '왕복시험.js'), 'utf8');

/** 주석·문자열이 아니라 실제로 도는 줄만 본다 — 설명문의 낱말이 검사를 통과시키면 안 된다. */
const 실행줄 = 소스.split('\n').filter((줄) => {
  const t = 줄.trim();
  return t && !t.startsWith('*') && !t.startsWith('//') && !t.startsWith('/*');
}).join('\n');

/* ── 시험 학생 채번 — 「대역이 찼다」가 **틀린 사유로** 나오면 처방도 통째로 헛일이 된다.
 *
 * 2026-08-09 실측: 손으로 만든 `SYNK-999`("유호 관통시험") 한 줄이 `max(...)+1` 을 1000 으로
 * 밀어, 실제로는 13/98 만 쓴 대역에서 `--새학생` 이 die 했다. 차단문은 "대역을 넓히거나 리허설
 * DB 를 새로 깔아라"였고 **둘 다 필요 없는 일**이었다(F103 — 따를 수 없는 처방).
 * 그래서 「가장 낮은 빈 번호」를 못박는다. 고갈 판정은 진짜 98칸이 다 찼을 때만 나와야 한다. */
const { 빈번호, 대역시작, 대역끝, 밀린시각들 } = require('../tools/왕복시험.js');

test('채번은 max+1 이 아니라 가장 낮은 빈 번호다 — 높은 번호 한 줄이 대역을 죽이지 않는다', () => {
  assert.equal(빈번호([]), `SYNK-${대역시작}`);

  // 실측 그대로: 902~913 연속 + 손으로 만든 999. max+1 판은 여기서 죽었다.
  const 실측 = [...Array(12).keys()].map((i) => `SYNK-${902 + i}`).concat('SYNK-999');
  assert.equal(빈번호(실측), 'SYNK-914');

  // 가운데가 비면 그 자리를 다시 쓴다(정리 뒤에도 대역이 되살아난다).
  assert.equal(빈번호(실측.filter((c) => c !== 'SYNK-905')), 'SYNK-905');

  // 901 은 인증왕복시험 몫이라 절대 나오면 안 된다 — 겹치면 그쪽이 「이미 등록됨」을 만난다.
  assert.ok(대역시작 > 901);
});

test('진짜로 다 찼을 때만 고갈이다', () => {
  const 전부 = [];
  for (let n = 대역시작; n <= 대역끝; n += 1) 전부.push(`SYNK-${n}`);
  assert.equal(빈번호(전부), null);
  assert.equal(빈번호(전부.slice(1)), `SYNK-${대역시작}`);   // 한 칸만 비어도 고갈이 아니다
});

/* ── 오프라인 5건의 시각 (C0 §7 왕복 6-④ · 왕복시험 ⑯) ────────────────────
 *
 * 이 함수가 지는 것은 **그 칸이 무엇을 재는지**다. 다섯이 서로 다른 시각이라야 「보존됐다」와
 * 「수신 시각으로 덮였다」가 갈리는데, 창이 좁으면(방금 동의한 새학생) 정수 나눗셈이 간격을
 * 0 으로 접어 다섯이 **보낼 때부터** 한 점이 된다 — 그러면 ⑯ 은 덮여도 초록이다.
 * 실 DB 왕복은 CI 가 못 돌리니 그 함정만 여기서 못박는다. */
test('밀린 다섯은 서로 다른 시각이다 — 창이 좁아도 간격이 0 으로 안 접힌다', () => {
  const 동의 = Date.parse('2026-08-09T00:00:00.000Z');

  // ① 넓은 창 — 하루 전에 동의한 학생(인자로 학생을 받는 판)
  const 넓게 = 밀린시각들(동의, 동의 + 24 * 3600 * 1000);
  assert.equal(넓게.length, 5);
  assert.equal(new Set(넓게).size, 5);
  const ms = 넓게.map(Date.parse);
  assert.ok(ms.every((t, i) => i === 0 || t > ms[i - 1]), '오름차순이 아니다 — 큐 순서가 뒤집힌다');
  assert.ok(ms[0] > 동의, '첫 건이 동의보다 앞선다 — CONSENT_MISSING 을 재게 된다');
  assert.ok(ms[4] < 동의 + 24 * 3600 * 1000, '마지막이 미래다 — 「밀려 있던 것」이 아니다');

  // ② 좁은 창 — 방금 동의한 새학생(⓪→⑯ 사이가 12초). 간격이 접히면 여기서 죽는다.
  const 좁게 = 밀린시각들(동의, 동의 + 12_000).map(Date.parse);
  assert.equal(new Set(좁게).size, 5, '창이 좁다고 다섯이 한 점이 되면 ⑯ 은 덮여도 초록이다');
  assert.ok(좁게.every((t, i) => i === 0 || t - 좁게[i - 1] >= 1000), '간격이 1초 미만이다');

  // ③ 기기 시계가 서버보다 뒤 — 창이 음수여도 다섯은 갈라져 있고 전부 동의 뒤다
  const 역전 = 밀린시각들(동의, 동의 - 60_000).map(Date.parse);
  assert.equal(new Set(역전).size, 5);
  assert.ok(역전.every((t) => t > 동의), '시계가 역전되면 동의보다 앞선 시각을 만든다');
});

test('--새학생 은 --운영승인 으로도 안 뚫린다(운영 명부에 사람을 만들지 않는다)', () => {
  /* 리허설 판정을 `새학생` 과 함께 보는 줄이 있어야 한다. `--운영승인` 예외가 여기 끼면 무효다.
   * 판정은 골격이 돌려준 `리허설이다` 다(2026-08-09 골격 합치기 — 정규식 직접 검사는
   * tests/왕복골격.test.js 가 금지한다). **부정(`!`)까지** 본다 — 뒤집힌 게이트는 항상 통과다. */
  const 게이트 = 실행줄.split('\n').find((줄) => /새학생\s*&&\s*!리허설이다/.test(줄));
  assert.ok(게이트, '--새학생 전용 리허설 게이트(새학생 && !리허설이다)가 없다 — 운영 명부에 시험 학생이 생긴다');
  assert.ok(!/운영승인/.test(게이트), '그 게이트에 --운영승인 예외가 붙으면 뚫린다');
});

test('--새학생 은 동의를 SQL 로 심지 않고 운영자 도구를 실제로 부른다', () => {
  /* 🔴 「이름이 어딘가 적혀 있다」로 재면 안 된다 — 첫 판이 그렇게 썼다가 변이가 살아남았다:
   *   호출을 SQL 로 되돌려도 `console.log('… tools/동의발급.js')` 한 줄이 검사를 통과시켰다.
   *   부르는 것은 문자열이 아니라 **프로세스 실행**이라, 그 결합을 본다. */
  assert.ok(/execFileSync[\s\S]{0,300}?동의발급\.js/.test(실행줄),
    'tools/동의발급.js 를 실제로 실행하지 않는다 — 동의 관문이 다시 픽스처가 됐다(F176 그대로)');

  // 심는 쪽 통로는 남아 있어도 된다(인자로 학생을 받는 판이 쓴다). 다만 **else 절 안**이어야 한다.
  const 심는곳 = 실행줄.indexOf('insert into engine.consents');
  if (심는곳 !== -1) {
    assert.ok(/\}\s*else\s*\{/.test(실행줄.slice(Math.max(0, 심는곳 - 300), 심는곳)),
      '동의 SQL 심기가 새학생 분기 안에 있다 — --새학생 이 다시 픽스처를 심는다');
  }
});

test('첫 등록이 막히면 거기서 멈춘다(뒤 관문의 초록이 앞 관문의 실패를 덮지 않는다)', () => {
  // first-login 이 200 이 아닌데 계속 돌면, 그 뒤 55건은 **다른 학생 상태**를 재는 것이 된다.
  assert.ok(/first-login/.test(실행줄), '첫 등록 통로를 안 탄다');
  assert.ok(/fr\.status !== 200[\s\S]{0,200}?die\(/.test(실행줄),
    '첫 등록 실패에 die 가 없다 — 개원 첫날 막히는 자리가 초록으로 지나간다');
});

/* ── 업로드왕복 ⑪ — 「앱이 조립한 봉투」를 재려면 **앱의 가드까지** 재현해야 한다.
 *
 * 2026-08-07 실측: 이 갈래가 `항목추가` 에 `correlation_id` 를 안 넘겨 `제출사건` 이 `null` 을
 * 냈고, 시험은 그 `null` 을 그대로 보내 **평문 500** 을 받았다. 증상은 「서버가 이상하다」인데
 * 원인은 봉투 조립이었다. 게다가 그 실패가 `if (한건?.event_id)` 를 닫아 **뒤따르는 검사 6건이
 * 통째로 실행되지 않았고**, 총계는 「20/21」로 나왔다 — 미실행이 한 건의 실패로 접혀 보였다.
 * `제출사건` 이 요구하는 칸은 계약이 늘 때마다 는다(①-10 이 `correlation_id` 를 공통 필수로
 * 올린 것이 이 사고의 시작이다). 그래서 「그 칸 이름」이 아니라 **가드의 존재**를 못박는다. */
const 업로드소스 = fs.readFileSync(path.join(__dirname, '..', 'tools', '업로드왕복시험.js'), 'utf8');
const 업로드실행줄 = 업로드소스.split('\n').filter((줄) => {
  const t = 줄.trim();
  return t && !t.startsWith('*') && !t.startsWith('//') && !t.startsWith('/*');
}).join('\n');

/* 🔴 총계가 **분모의 이동**을 감추면 안 된다(F207 · 2026-08-09 실측).
 *   ⑪ 이 빨개진 실행이 `18/20` 으로 나왔다 — 「20건 중 2건 실패」로 읽히지만 실제는
 *   「2건 실패 + 앱 체인 7건 미실행」이었고, 고친 뒤 같은 실행이 `27/27` 이 됐다.
 *   미실행은 실패보다 조용해서, 세지 않으면 총계만 보는 사람에게 영원히 안 보인다. */
test('건너뛴 묶음은 세어져서 총계 줄에 함께 나온다 — 미실행이 통과 옆에 숨지 않는다', () => {
  const 건너뛴자리 = 업로드실행줄.match(/건너뛴다\(/g) || [];
  assert.ok(건너뛴자리.length >= 2,
    `건너뛰는 자리가 ${건너뛴자리.length}곳뿐이다 — 배정 없음·봉투 재료 없음 둘 다 세어야 한다`);

  assert.ok(/\[업로드왕복\] \$\{[\s\S]{0,200}?건너뜀\.length/.test(업로드실행줄),
    '총계가 건너뜀을 안 읽는다 — 7건이 안 돌아도 초록으로 보인다');
});

test('업로드왕복은 앱처럼 한 앉음을 들려 보내고, 봉투가 안 서면 거기서 멈춘다', () => {
  /* ① 앱이 넘기는 값(`src/말하기화면.js` 흐름잡기)을 시험도 넘긴다. `항목추가` 는 이 칸을
   *   짓지 않고 받기만 하므로(`lib/제출로그.js`), 안 넘기면 조용히 `null` 봉투가 된다. */
  assert.ok(/항목추가\([\s\S]{0,900}?correlation_id\s*:/.test(업로드실행줄),
    '업로드왕복이 항목추가에 correlation_id 를 안 넘긴다 — 제출사건이 null 을 내고 500 이 된다');

  /* ② 그리고 **앱의 가드**(`src/제출API.js` `if (!사건) return`)가 있어야 한다. ①만 있으면
   *   다음에 필수 칸이 하나 더 늘 때 같은 사고가 같은 모양(평문 500)으로 돌아온다. */
  assert.ok(/제출사건\([\s\S]{0,400}?if\s*\(!\s*사건\s*\)[\s\S]{0,120}?die\(/.test(업로드실행줄),
    '봉투가 null 인데 그대로 보낸다 — 조립 실패가 「서버 장애」로 읽힌다(앱은 여기서 멈춘다)');
});
