  /* 바늘이 정의를 집었는지는 **그 줄을 보면** 안다 — 인덱스 크기 비교로는 못 가른다
   *   (정의 안의 `검증(행들)` 은 `function` 보다 몇 글자 뒤라 「호출이 정의보다 뒤」가 참이 된다). */
  const 줄찾기 = (i) => 주석뺀소스.slice(주석뺀소스.lastIndexOf('\n', i) + 1, 주석뺀소스.indexOf('\n', i));
