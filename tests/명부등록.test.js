/* ── F269 — 계정을 만드는 두 번째 통로가 되살아나는 자리 ────────────────────
 * 옛 판은 GoTrue 관리자 API 로 계정을 직접 만들었다. 그 주소는 8자 코드에서 나오고
 * 앱·서버가 쓰는 주소는 `student_code` 에서 나와, 만든 계정이 **영원히 안 열렸다**.
 * 규칙을 맞추는 것으로는 안 낫는다 — 계정이 서는 자리는 첫 등록 하나여야 한다(§4-1). */
