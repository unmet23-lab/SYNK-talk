/* ── 신뢰 경계 — 사람이 친 값이 SQL 이 되지 않는가 ──────────────────────────
 * 🔴 「어느 한 곳이라도 안전하면 통과」로 쓰면 안 된다 — 이 파일엔 SQL 이 셋이고 하나만
 *   보면 다른 둘이 뚫려도 초록이다(2026-08-07 변이 시험이 정확히 그 구멍으로 살아남았다).
 *   그래서 **모든** 보간을 하나씩 센다. */
function 보간들(s) {
  const out = [];
  const re = /\$\{/g;
  let m;
  while ((m = re.exec(s))) {
    let 깊이 = 1;
    let i = m.index + 2;
    const 시작 = i;
    while (i < s.length && 깊이 > 0) {
      if (s[i] === '{') 깊이 += 1;
      else if (s[i] === '}') 깊이 -= 1;
      i += 1;
    }
    out.push(s.slice(시작, i - 1));
  }
  return out;
}
const 안전한보간 = (내용) => 내용.includes('따옴표(') || 내용.trim() === '접기';

test('SQL 보간은 **전부** 따옴표를 지난다 (신뢰 경계)', () => {
  const 질의들 = [...주석뺀소스.matchAll(/await sql\(\s*e,([\s\S]*?)\);/g)].map((m) => m[1]);
  /* 🔴 분모를 먼저 밝힌다(F207) — 「0건 검사」도 초록과 같은 모양으로 온다. `sql(e,` 등장 수에서
   *   선언 하나를 뺀 것이 호출 수다. 안 맞으면 await 없이 부른 자리가 있다는 뜻이고, 그 자리는
   *   이 검사가 통째로 못 본다. */
  const 등장 = (주석뺀소스.match(/sql\(\s*e,/g) || []).length;
  assert.equal(질의들.length, 등장 - 1,
    `sql(e, …) 가 ${등장}번 나오는데(선언 1 포함) 잡은 호출은 ${질의들.length}개다 — 못 본 자리가 있다`);
  assert.ok(질의들.length >= 3, `sql() 호출을 ${질의들.length}개밖에 못 찾았다 — 추출이 낡으면 이 검사가 빈다`);
  for (const q of 질의들) {
    const 보간 = 보간들(q);
    const 샌것 = 보간.filter((v) => !안전한보간(v));
    assert.deepEqual(샌것, [], `따옴표를 안 지나는 보간이 있다: ${샌것.join(' · ')}`);
  }
  assert.equal(따옴표("SYNK-001'; drop table engine.learners; --"),
    "'SYNK-001''; drop table engine.learners; --'");
});

test('탐지력 픽스처 — 보간 추출기가 죽으면 위 검사는 무엇이든 통과시킨다', () => {
  assert.deepEqual(보간들('`where a = ${번호} and b = ${따옴표(전화)}`'), ['번호', '따옴표(전화)']);
  assert.equal(안전한보간('번호'), false, '맨 변수를 안전하다고 하면 검사가 죽은 것이다');
  assert.equal(안전한보간('이름 ? 따옴표(이름) : \'null\''), true, '삼항 안의 따옴표도 읽어야 한다');
  assert.deepEqual(보간들('`${따옴표(a)}`'), ['따옴표(a)'], '중첩 괄호에서 잘리면 안 된다');
});

