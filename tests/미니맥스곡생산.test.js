'use strict';
/* 미니맥스곡생산 — «곡이 제 발로 끝나는가»의 회귀.
 *
 * 🔴 이 스위트가 지키는 것은 2026-09-08 유호 지시 한 줄이다:
 *   「곡이 자연스럽게 끝맺음만 나면 돼. 노래 나오다가 중간에 막 끊기는거 말고」
 *
 * 그날 실측 8건이 예외 없이 하나로 갈렸다(자 = 마지막 1초 평균이 곡 전체 평균보다 얼마나 낮은가):
 *   | 주문 | 실제 | 낱말 | 구역 | 끝맺음 | |
 *   |---|---|---|---|---|---|
 *   | 240 | 222 | 288 |  8 | 39.4 | ✅ 제 발로 끝난다 |
 *   | 240 | 178 |  —  | —  | 36.2 | ✅ (모델이 노랫말을 지은 판) |
 *   | 240 | 240 | 373 | 12 |  0.4 | 🔴 끊긴다 |
 *   | 240 | 240 | 399 | 11 |  6.7 | 🔴 |
 *   | 240 | 240 | 334 | 11 |  6.2 | 🔴 |
 *   | 120 | 120 | 149 | 10 |  1.3 | 🔴 |
 *   | 120 | 120 | 184 | 10 | −0.6 | 🔴 |
 *   | 120 | 120 |  —  | —  |  1.5 | 🔴 |
 *
 * 🔑 **구역 수가 가른다** — 여덟이면 끝맺고, 열 이상이면 시간이 모자라 잘린다.
 *    앞 판은 구역에 «하한»만 두어(여덟 이상) 12구역짜리를 통과시켰고, 그 곡이 끊겼다.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const 곡 = require('../tools/미니맥스곡생산.js');

/** 실측을 흉내낸 노랫말을 짓는다 — 구역 수와 낱말 수만 자에 걸리므로 그 둘을 정확히 맞춘다. */
function 노랫말짓기(구역들, 낱말수) {
  const 몸 = Array.from({ length: 낱말수 }, (_, i) => `w${i}`).join(' ');
  const 덩이 = Math.ceil(낱말수 / 구역들.length);
  const 쪼갠 = 몸.split(' ');
  return 구역들.map((이름, i) => `[${이름}]\n${쪼갠.slice(i * 덩이, (i + 1) * 덩이).join(' ')}`).join('\n');
}

const 여덟구역 = ['intro', 'verse', 'pre-chorus', 'chorus', 'verse', 'bridge', 'chorus', 'outro'];
const 열구역 = ['intro', 'verse', 'pre-chorus', 'chorus', 'verse', 'pre-chorus', 'chorus', 'bridge', 'chorus', 'outro'];
const 열두구역 = [...열구역, 'verse', 'chorus'];

test('🔴 실측 — 240초에 여덟 구역·288낱말은 쓸만하다(그 곡이 제 발로 끝났다 · 39.4)', () => {
  const 판정 = 곡.노랫말재기(노랫말짓기(여덟구역, 288), 240);
  assert.equal(판정.구역.length, 8);
  assert.equal(판정.낱말, 288);
  assert.ok(판정.마무리있나, 'outro 가 있는데 못 찾았다');
  assert.ok(판정.구성섰나, '여덟 구역이 구성 조건에서 떨어지면 안 된다');
  assert.ok(판정.쓸만한가, '09-08 에 유일하게 제 발로 끝난 노랫말이 탈락하면 자가 뒤집힌 것이다');
});

test('🔴 실측 — 열 구역 이상은 «탈락»한다(그 곡들이 전부 노래 도중에 끊겼다)', () => {
  /* 앞 판은 구역에 하한만 두어 이 넷을 전부 통과시켰다. 그것이 결함이었다. */
  for (const [구역들, 낱말, 길이] of [
    [열두구역, 373, 240],
    [열구역, 399, 240],
    [열구역, 334, 240],
    [열구역, 149, 120],
    [열구역, 184, 120],
  ]) {
    const 판정 = 곡.노랫말재기(노랫말짓기(구역들, 낱말), 길이);
    assert.ok(!판정.쓸만한가,
      `구역 ${구역들.length}·낱말 ${낱말}·주문 ${길이}초 는 실측에서 끊긴 판인데 통과했다`);
  }
});

test('🔴 낱말이 «넘치는» 쪽은 통과하지 못한다 — 시간이 모자라 노래가 끊기기 때문이다', () => {
  /* 240초 상한은 300낱말(240×1.25). 334 는 그것을 넘으므로 구역이 여덟이어도 떨어진다. */
  const 판정 = 곡.노랫말재기(노랫말짓기(여덟구역, 334), 240);
  assert.ok(!판정.분량맞나, '334낱말이 240초 곡의 분량 조건을 통과하면 안 된다');
  assert.ok(!판정.쓸만한가);
});

test('🔴 «가장 나은 것»을 고를 때 넘치는 판이 알맞은 판을 제치지 못한다', () => {
  /* 09-08 실사고: 다섯 번 지어 다 떨어졌을 때 12구역·373낱말짜리가 뽑혔고, 그 곡이 끊겼다.
   * 넘침에 벌점이 없으면 「마무리 있다」 1000점만으로 둘이 동점이 되어 순서가 곡을 정한다. */
  const 넘친판 = 곡.노랫말재기(노랫말짓기(열두구역, 373), 240);
  const 모자란판 = 곡.노랫말재기(노랫말짓기(여덟구역, 201), 240);
  assert.ok(곡.노랫말점수(모자란판) > 곡.노랫말점수(넘친판),
    '모자란 판은 곡이 짧아질 뿐이지만 넘친 판은 노래가 끊긴다 — 값이 다르므로 점수도 달라야 한다');
});

test('마무리 절이 없으면 어떤 구성이어도 통과하지 못한다', () => {
  const 마무리없는여덟 = ['intro', 'verse', 'pre-chorus', 'chorus', 'verse', 'bridge', 'chorus', 'verse'];
  const 판정 = 곡.노랫말재기(노랫말짓기(마무리없는여덟, 288), 240);
  assert.ok(!판정.마무리있나);
  assert.ok(!판정.쓸만한가);
});

test('🔴 못 잰 것을 «끝맺었다»로 적지 않는다 — 없는 파일은 null 을 낸다', () => {
  /* 거짓 초록 방지. 09-08 기억 `zero-is-a-success-face-taxonomy` 의 그 자리다. */
  const r = 곡.끝맺음재기('없는파일_______.wav', 240);
  assert.equal(r.실제, null);
  assert.equal(r.차이, null);
  assert.equal(r.끝맺었나, null, '못 쟀는데 true/false 를 내면 그 판정이 장부에 도장으로 남는다');
});

test('끝맺음 판정의 문턱은 실측 두 무리 사이에 있다(20 · 사이가 30 넘게 비었다)', () => {
  /* 자를 코드에서 직접 못 읽으므로 «두 무리»가 갈리는지를 값으로 재현한다.
   * 제 발로 끝난 둘 = 36.2 · 39.4 · 끊긴 여섯 = −0.6 ~ 6.7. */
  const 끝맺은값 = [36.2, 39.4];
  const 끊긴값 = [-0.6, 0.4, 1.3, 1.5, 6.2, 6.7];
  const 문턱 = 20;
  for (const v of 끝맺은값) assert.ok(v >= 문턱, `${v} 는 끝맺은 쪽인데 문턱 아래다`);
  for (const v of 끊긴값) assert.ok(v < 문턱, `${v} 는 끊긴 쪽인데 문턱 위다`);
  assert.ok(Math.min(...끝맺은값) - Math.max(...끊긴값) > 25,
    '두 무리 사이가 좁아지면 문턱 하나로 못 가른다 — 그때는 자를 다시 세워야 한다');
});
