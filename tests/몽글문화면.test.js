'use strict';
/* G1-5 회귀 — 몽글에게 묻는 문(`companion/ask`)의 앱 입구(src/몽글문화면.js).
 *
 * ■ 왜 소스 층인가 — 어기는 방향이 전부 «조용해서»다.
 *   · 상한을 화면이 제 숫자로 적으면 서버 상한이 바뀌는 날 화면만 옛 숫자를 말한다(빨간 데 0).
 *   · «넘김»이 오류색을 입으면 강사가 「고장났다」로 읽고 다시 물어 장부 분모가 조용히 부푼다.
 *   · 자동 재시도·답 캐시는 몽글API 머리말 🚫 그대로 — 새면 질문 하나가 여러 행이 된다.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');
const { 코드만, 파일소스, 구간, 코드만픽스처 } = require('./lib/소스검사.js');
const { 그리기 } = require('./lib/화면세우기.js');

const 원문 = 파일소스(path.join(__dirname, '..', 'src', '몽글문화면.js'));
const 화면 = 코드만(원문);

test('주석 제거기가 산다 — 아래 소스 검사들이 설명을 코드로 읽지 않는다', () => {
  assert.equal(코드만(코드만픽스처.입력), 코드만픽스처.기대, '주석 제거기가 죽었다 — 이 파일 전체가 거짓 초록이 된다');
});

test('판정은 lib/몽글물음.질문판정 하나다 — 상한 숫자를 화면이 직접 적지 않는다', () => {
  assert.match(화면, /import \{ 질문판정 \} from '\.\.\/lib\/몽글물음\.js';/, '질문판정을 lib 에서 안 빌린다');
  assert.match(화면, /질문판정\(질문\)/, '입력을 질문판정에 안 태운다 — 보내기 게이트가 화면 감이 된다');
  assert.ok(!/2000/.test(화면), '상한 숫자가 화면에 박혔다 — 서버 상한이 바뀌는 날 화면만 옛 숫자를 말한다');
});

test('몽글API 는 별칭(몽글묻기)으로 든다 — 도착확인의 동명 로컬 물어보기와 갈라 둔다', () => {
  assert.match(화면, /import \{ 물어보기 as 몽글묻기 \} from '\.\/몽글API\.js';/, '별칭 import 가 아니다');
  assert.match(화면, /몽글묻기\(토큰, \{ 질문, 화면: '몽글문' \}\)/, '질문을 화면 맥락과 함께 안 보낸다');
});

test('넘김 갈래는 실패색이 아니다 — 색.신호 0 · 잉크_보조 안내 (인계는 설계된 정상 결과)', () => {
  const 넘김 = 구간(원문, "갈래 === '넘김'", "갈래 === '못받음'");
  assert.ok(!/색\.신호/.test(넘김), '넘김(인계)이 오류색을 입었다 — 강사가 「고장났다」로 읽고 다시 묻는다');
  assert.match(넘김, /s\.넘김글/, '넘김 안내가 전용 글자층을 안 탄다');
  assert.match(화면, /넘김글: \{[^}]*color: 색\.잉크_보조/, '넘김글 색이 잉크_보조(Stone)가 아니다');
  assert.match(넘김, /원장님께 넘겼어요/, '넘김 폴백 문구가 사라졌다 — 사유 없는 인계가 빈 카드가 된다');
});

test('자동 재시도·답 캐시 0 — 몽글API 머리말 🚫 그대로', () => {
  assert.ok(!/setInterval|setTimeout/.test(화면), '화면에 타이머가 생겼다 — 자동 재시도의 시작이 이 모양이다');
  assert.ok(!/재시도/.test(화면), '재시도 손잡이가 생겼다 — 다시 묻는 것은 사람 손뿐이다');
  assert.ok(!/from '\.\/저장/.test(화면), '화면이 저장층을 들었다 — 답을 기기에 남기면 문서 갱신 뒤에도 옛 답이 산다');
});

test('렌더 — 첫 렌더(질문 전 · 답 없음)에 선다', () => {
  const 글 = 그리기('src/몽글문화면.js', { 토큰: 'x', 돌아가기() {} });
  assert.match(글, /몽글에게 묻기/, '제목이 안 섰다');
  assert.match(글, /물어보기/, '보내기 버튼이 안 섰다');
});
