/* 라디오 라운드 생성기 회귀 — 결정적 추첨이라 분포가 아니라 «값»으로 잰다(설계 §4-5 · P3). */
'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');

const { 생성판, 눈금, 라운드선정 } = require('../lib/라디오라운드.js');

const 팩 = [
  { 문항id: 'q1', skill_ids: ['a'] },
  { 문항id: 'q2', skill_ids: ['a'] },
  { 문항id: 'q3', skill_ids: ['b'] },
];

test('눈금 — 같은 씨앗은 같은 값, 다른 씨앗은 다른 값, 범위는 [0,1)', () => {
  assert.equal(눈금('r-1'), 눈금('r-1'));
  assert.notEqual(눈금('r-1'), 눈금('r-2'));
  for (const s of ['r-1', 'r-2', 'r-3', 42]) {
    const v = 눈금(s);
    assert.ok(v >= 0 && v < 1, `눈금이 범위를 벗어났다: ${v}`);
  }
});

test('씨앗이 없으면 던진다 — 없는 채로 통과하면 매 라운드가 같은 문항을 뽑는다', () => {
  assert.throws(() => 라운드선정({ 문항들: 팩, 씨앗: undefined }), TypeError);
  assert.throws(() => 라운드선정({ 문항들: 팩, 씨앗: '' }), TypeError);
  /* 팩이 마른 날에만 조용히 통과하는 인자를 안 만든다 — 후보 0 이어도 씨앗은 검사한다.
   * 이걸 빼면 부르는 쪽의 누락이 팩이 찰 때까지 안 드러난다. */
  assert.throws(() => 라운드선정({ 문항들: [{ 문항id: 'q1' }], 제외: ['q1'], 씨앗: undefined }), TypeError);
});

test('같은 씨앗·같은 재고면 같은 문항 — 결정적이라 회귀가 값으로 잰다', () => {
  const 재료 = { 문항들: 팩, 노출수: {}, 승격요약: { a: { 응답: 10, 오답: 10 } }, 씨앗: 'ch1:2026-08-13T09:00Z' };
  const 첫 = 라운드선정(재료);
  assert.deepEqual(라운드선정(재료), 첫);
  assert.equal(첫.생성판, 생성판);
  assert.equal(첫.후보수, 3);
  // a(오답률 1.0)=2 씩 두 문항 + b(요약에 없음 → 중립 1) 한 문항 = 5
  assert.equal(첫.총가중, 5, '가중이 안 실렸다 — 약점 축이 중립으로 접혔나');
});

test('입력 순서가 결과를 안 바꾼다 — DB 행 순서는 보증이 없다', () => {
  /* 씨앗 하나로는 못 잡는다 — 순서를 뒤집어도 «우연히» 같은 문항이 걸리는 씨앗이 있다.
   * 여러 씨앗 전량이 일치해야 「정렬이 산다」는 말이 된다(변이 시험에서 1개 씨앗판이
   * 정렬 제거를 못 물었다). */
  const 공통 = { 노출수: {}, 승격요약: { a: { 응답: 10, 오답: 10 } } };
  const 뒤집힌 = [...팩].reverse();
  for (let i = 0; i < 12; i += 1) {
    const 씨앗 = `ch1:라운드${i}`;
    const 정 = 라운드선정({ ...공통, 문항들: 팩, 씨앗 });
    const 역 = 라운드선정({ ...공통, 문항들: 뒤집힌, 씨앗 });
    assert.equal(역.문항id, 정.문항id, `정렬 없이 누적했다(씨앗 ${씨앗}) — 같은 씨앗이 날마다 다른 문항을 뽑는다`);
  }
});

test('미노출 우선이 가중보다 앞선다 — 노출된 문항은 약점 축이어도 안 뽑힌다', () => {
  const 뽑힌 = new Set();
  for (let i = 0; i < 20; i += 1) {
    const r = 라운드선정({
      문항들: 팩,
      노출수: { q1: 5, q2: 5 },                       // q3 만 미노출
      승격요약: { a: { 응답: 10, 오답: 10 }, b: { 응답: 10, 오답: 0 } },
      씨앗: `ch1:${i}`,
    });
    뽑힌.add(r.문항id);
  }
  assert.deepEqual([...뽑힌], ['q3'], '노출된 문항이 재고 축을 제쳤다');
});

test('제외·축한정 — 재도전 짝은 «같은 skill 다른 문항»이다', () => {
  const r = 라운드선정({
    문항들: 팩,
    노출수: {},
    승격요약: {},
    씨앗: 'retry-1',
    제외: ['q1'],       // 방금 낸 문항
    축한정: ['a'],      // 그 문항의 축
  });
  assert.equal(r.문항id, 'q2', '같은 축의 다른 문항이 아니라 딴 축이 뽑혔다');
});

test('고를 것이 없으면 null — 없는 문항을 지어내지 않는다', () => {
  assert.equal(라운드선정({ 문항들: [], 씨앗: 's' }), null);
  assert.equal(라운드선정({ 문항들: 팩, 제외: ['q1', 'q2', 'q3'], 씨앗: 's' }), null);
  assert.equal(라운드선정({ 문항들: 팩, 축한정: ['없는축'], 씨앗: 's' }), null);
  assert.equal(라운드선정({ 씨앗: 's' }), null);
});

test('가중이 실제로 추첨을 기울인다 — 약점 축이 더 자주 뽑힌다', () => {
  /* 분포로 «판정»하지 않는다(플레이크). 씨앗을 고정한 100회를 값으로 세고, 방향만 잰다:
   * a(오답률 1.0 · w=2) 문항 하나 vs b(오답률 0 · w=1) 문항 하나면 기대는 2:1 이다. */
  const 셈 = { qa: 0, qb: 0 };
  for (let i = 0; i < 100; i += 1) {
    const r = 라운드선정({
      문항들: [{ 문항id: 'qa', skill_ids: ['a'] }, { 문항id: 'qb', skill_ids: ['b'] }],
      노출수: {},
      승격요약: { a: { 응답: 10, 오답: 10 }, b: { 응답: 10, 오답: 0 } },
      씨앗: `fixed:${i}`,
    });
    셈[r.문항id] += 1;
  }
  assert.equal(셈.qa + 셈.qb, 100);
  assert.ok(셈.qa > 셈.qb, `약점 축이 안 기울었다 — qa ${셈.qa} vs qb ${셈.qb}`);
});
