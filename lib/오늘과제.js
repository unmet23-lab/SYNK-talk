/* 날짜는 **몽골 달력**으로 끊는다(C0 §4-3 ① · §10-A-4).
 * UTC 로 끊으면 몽골 오전 8시(=00:00Z)까지가 「어제」라, 아침에 앱을 연 학생이
 * 어제 것을 오늘 것으로 받는다. 오프셋을 상수로 적지 않는 이유는 그게 규칙의 사본이기
 * 때문이다 — 규칙은 tzdata 가 지고, 여기는 이름만 든다. */
const 시간대 = 'Asia/Ulaanbaatar';
const 날짜형식 = new Intl.DateTimeFormat('en-CA', {
  timeZone: 시간대, year: 'numeric', month: '2-digit', day: '2-digit',
});

/** @param {Date|string|number} [때] @returns {string} `YYYY-MM-DD` (몽골 기준) */
function 몽골날짜(때) {
  const d = 때 == null ? new Date() : 때 instanceof Date ? 때 : new Date(때);
  if (Number.isNaN(d.getTime())) throw new TypeError('몽골날짜: 날짜가 아니다');
  return 날짜형식.format(d);
}

/* 앱이 **배경에서 돌아올 때** 무엇을 다시 할지 — 순수 판정.
 *
 * ■ 왜 이 판정이 있어야 하나 (실측 2026-08-09 · `AppState` 가 저장소 전체에 0줄이었다)
 *   `src/말하기화면.js` 는 오늘 날짜·오늘 과제·「이미 냈나」를 **마운트 때 한 번** 세운다.
 *   그런데 안드로이드에서 백그라운드 앱은 며칠 산다 — 그래서 앱을 켠 채 자정을 넘긴 학생의
 *   화면은 **어제의 완료 카드**에 갇혀, 앱을 완전히 죽이지 않으면 오늘 제출을 할 수 없었다.
 *   곁들여 밀린 오프라인 큐도 그 한 자리에서만 나가므로, 지하철에서 나와 회선이 붙어도
 *   화면을 새로 열지 않으면 안 올라갔다(`도착확인` 화면의 안내문이 그래서 반쯤 거짓이었다).
 *
 * 🔴 **돌아왔다고 늘 다시 세우면 안 된다.** 사전을 찾으러 나갔다 온 학생의 호흡이 ③답하기에서
 *   ①듣기로 되돌아가고, 그 일은 자정 넘김보다 훨씬 자주 일어난다. 그래서 갈래가 둘이다:
 *   ⓐ 날짜가 바뀌었다 = **새 날**이라 되세우는 것이 옳다(흐름이 리셋되는 것이 정확하다).
 *   ⓑ 같은 날이면 **큐만** 민다 — 화면 상태에는 손대지 않는다.
 *
 * 🔑 지금 날짜를 **인자로 받는다** — 안에서 시계를 읽으면 회귀가 자정을 못 만든다.
 *
 * @param {string|null} 이전날짜  화면이 쥐고 있던 날짜(`YYYY-MM-DD`)
 * @param {string} 지금날짜       복귀 시점의 `몽골날짜()`
 * @param {number} 밀린수         아직 서버에 못 닿은 항목 수
 * @returns {'재초기화'|'밀린것'|null} `null` = 할 일 없음(대부분의 복귀가 이것이다)
 */
function 복귀행동(이전날짜, 지금날짜, 밀린수) {
  if (이전날짜 && 지금날짜 && 지금날짜 !== 이전날짜) return '재초기화';
  return 밀린수 > 0 ? '밀린것' : null;
}

