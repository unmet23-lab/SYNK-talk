/* 급수 1~2(미정 0 포함)인가 — 설계 §6.
 *
 * 🔑 **모르면 초급으로 본다.** `level_current` 는 `text` 라 값 규약이 문서에 없고(실측 08-09),
 *   「미정」·빈 값·못 읽는 표기가 실제로 들어온다. 이때 둘 중 어느 쪽으로 접느냐가 비대칭이다:
 *     · 선택지를 받은 상급자 → 무시하고 자유롭게 말한다(선택지는 힌트지 강제가 아니다). 손해 0.
 *     · 자유발화를 받은 초급자 → **아무것도 못 낸다.** 그날 발화가 통째로 사라지고 소급 불가다.
 *   그래서 「초급이 아님을 숫자로 증명할 수 있을 때만」 자유발화를 낸다. `급수편지()` 의
 *   0=미정→초급 규칙과 같은 축이다(`contents/첫편지.js`).
 *
 * 🔑 **표기에서 숫자를 뽑는다** — 실측 값이 `'Lv3'` 이다(`tests/오늘과제.test.js` 픽스처 ·
 *   `level_current` 는 `text` 라 스키마가 형식을 안 잡는다). `Number('Lv3')` 는 `NaN` 이라
 *   그대로 재면 **3급 학생이 초급으로 접힌다** — 첫 판이 실제로 그랬고 회귀가 잡았다.
 * ⚠ 남는 한계: `'중급'` 처럼 숫자가 없는 표기는 초급으로 접힌다. 위 비대칭(모르면 초급) 상
 *   안전한 방향이지만 정확하지는 않다 — 값 규약이 L0 에 서면 그때 이 함수만 좁힌다. */
const 초급인가 = (급수) => {
  const m = /\d+/.exec(String(급수 ?? ''));
  if (!m) return true;
  const n = Number(m[0]);
  return !Number.isFinite(n) || n <= 2;
};

/** 호흡 2개짜리 스냅샷 — 「그날 학생이 본 것 그대로」(C0 §4-3 ①).
 *
 * 🔑 ③의 `task_format` 은 **선택지 유무에서 파생**한다 — 급수를 여기서 다시 재지 않는다.
 *   형식과 선택지를 각자 정하면 「`자유발화` 인데 보기가 있다」가 성립하고, 그 행은 나중에
 *   낭독/자유발화를 가르려던 c5 의 축(`왜_task_format이_따로인가`)을 조용히 오염시킨다.
 *   한 값에서 나오면 갈라질 수 없다(가드 맹점 ④: 같은 판정을 두 곳에 적으면 목록이 갈린다). */
function 스냅샷(날짜, 문장, 출처, 프롬프트, 선택지 = null) {
  const 고름 = Array.isArray(선택지) && 선택지.length > 0;
  return {
    ver: 1,
    날짜,
    호흡: [
      { 차례: 2, 무엇: '따라 말하기', task_format: '낭독', 문장, 출처 },
      {
        차례: 3,
        무엇: '답하기',
        task_format: 고름 ? '응답' : '자유발화',
        프롬프트,
        /* 자유발화 날엔 키 자체를 두지 않는다 — `null` 을 실으면 「보기가 없는 응답」과
         * 「애초에 자유발화」가 행에서 같은 모양이 된다. */
        ...(고름 ? { 선택지: [...선택지] } : {}),
      },
    ],
  };
}

/* ■ 학생에게 내보내도 되는 스냅샷 키 — **허용 목록** (절단문서 ②-20)
 *
 *   `GET /v1/tasks` 는 배정 행의 `task_snapshot` 을 **통째로** 돌려준다. 그런데 계약은 그 안에
 *   **정답**을 두기로 했고(C0 §4-1 예시 `{지시문·문항·보기·정답}` · L0 §3-3 「질문·보기·정답·지시문」
 *   필수 4 · 발주_게임모듈 §342 `정답` = 기준 교정문 + 심은 오류의 자리 + 오류태그), 채점은
 *   `body_original` + `task_snapshot.정답` 으로 나중에 계산하는 **파생**이다(C0 「is_correct 를
 *   만들지 않는다」). 즉 **앱은 정답이 필요 없는데** 응답에는 그걸 실을 자리가 이미 나 있다.
 *   오늘 새는 양이 0 인 것은 생산자가 따라말하기뿐이기 때문이지 통로가 막혀서가 아니다.
 *
 *   🔑 **차단 목록이 아니라 허용 목록으로 잡는다.** 앞으로 생길 키 이름을 미리 알 수 없어서다 —
 *      차단 목록은 못 적은 이름이 그대로 새고 증상이 「통과」라 아무도 모른다. 허용 목록이면 새 키의
 *      기본값이 「안 나감」이고 증상은 **화면이 비는 것**이라 그날 사람이 온다. 그 자리에서
 *      「이걸 학생이 봐도 되나」를 정하게 되는 것이 이 목록의 값이다.
 *
 *   🔴 앱은 받은 판을 제출에 **되싣는다**(아래 `제출사건`) — 여기서 벗긴 키는 제출 행에도 없다.
 *      그래도 소급 손실이 아니다: 정답 원본은 **배정 행**(`task.assigned` 의
 *      `submissions.task_snapshot` · `functions/deliver` 가 적는다)에 그대로 남고, 제출은
 *      `task_ref` 로 그 행에 붙는다(절단문서 ①-11). 채점 재계산은 그 원본으로 한다.
 *   ⛔ 그러니 이 목록을 넓혀 정답을 다시 내보내는 것으로 「제출 스냅샷이 비었다」를 고치지 않는다.
 *   🚫 반대로 서버가 제출 행의 스냅샷을 배정 행에서 베껴 채우지도 않는다 — 관측 칸에 추정을 넣는
 *      것이고 `lib/이벤트검증.js` 가 이미 금지한 자리다(절단문서 ①-7 과 같은 오염). */
const 학생공개키 = Object.freeze({
  최상위: Object.freeze(['ver', '날짜', '호흡']),
  /* `선택지` — 급수 1~2 의 보기(설계 §6). 정답이 아니라 **학생이 소리 내어 고를 것**이라
   * 안 내보내면 그 학생의 화면이 그냥 자유발화가 된다(=이 갈래를 만든 뜻이 사라진다). */
  호흡: Object.freeze(['차례', '무엇', 'task_format', '문장', '출처', '프롬프트', '선택지']),
});

/** 스냅샷에서 학생에게 줄 판만 남긴다 — 목록 밖 키는 전부 지운다(②-20). 원본은 안 건드린다. */
function 학생판스냅샷(snap) {
  if (!snap || typeof snap !== 'object' || Array.isArray(snap)) return snap;
  const 골라내기 = (o, 허용) => Object.fromEntries(Object.entries(o).filter(([k]) => 허용.includes(k)));
  const 판 = 골라내기(snap, 학생공개키.최상위);
  if (Array.isArray(snap.호흡)) {
    판.호흡 = snap.호흡.map((h) => (h && typeof h === 'object' && !Array.isArray(h) ? 골라내기(h, 학생공개키.호흡) : h));
  }
  return 판;
}

/**
 * 오늘 이 학생에게 낼 것을 고른다.
 *
 * @param {object} 재료
 * @param {string} 재료.날짜          몽골 기준 `YYYY-MM-DD`
 * @param {boolean} [재료.첫날]       이 학생에게 배정 이력이 없다
 * @param {string|null} [재료.교정문]  지난 배정 뒤에 새로 확정된 교정문(있으면 ②슬롯 · §6-3)
 * @param {string|null} [재료.전날문장] 마지막 배정의 ②문장(강등 1단계 · §6-4)
 * @returns {{task_snapshot: object, task_ref: string, degraded: boolean, 출처: string}}
 */
function 오늘과제(재료) {
  const { 날짜, 첫날 = false, 교정문 = null, 전날문장 = null, 급수 = null } = 재료 || {};
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(날짜))) throw new TypeError('오늘과제: 날짜는 YYYY-MM-DD 여야 한다');

  /* 순서가 곧 우선순위다(§6-1 의 세 갈래 + §6-4 의 두 단계).
   * `첫날` 이 교정문보다 앞이다 — 배정 이력이 없는데 교정이 있는 상태는 데이터가 어긋난
   * 것이고, 그때 「어제 교정문」을 내면 그 학생의 **첫 발화 기준선**(§4-5 · 소급 불가)을 잃는다. */
  const [문장, 출처, degraded] =
    첫날 ? [도입.따라말하기, '도입', false]
    : 교정문 ? [String(교정문), '교정문', false]
    : 전날문장 ? [String(전날문장), '전날', true]
    : [도입.따라말하기, '도입', true];

  return {
    /* 🔑 첫날 기준선의 식별자는 `task_ref` 가 아니다 — 그건 `task-${날짜}` 라 날짜마다 달라서
     *   6개월 뒤 해봉 행과 안 이어진다. 첫날 = **`출처='도입'` + `degraded=false`** 조합이고
     *   (강등 마지막 단계가 같은 도입 문장을 쓰므로 `degraded` 가 유일한 구분축이다),
     *   둘 다 이미 행에 남는다. 새 필드를 만들지 않는 이유가 이것이다(N23 · 전수분석 §12-B). */
    /* ③은 급수로 갈린다(설계 §6) — 1~2·미정에는 보기 2개를 함께 낸다. 질문과 보기를 같은
     * 삼항에서 고르는 이유: 따로 고르면 「첫날 질문 + 평일 보기」 같은 짝이 조용히 성립한다. */
    task_snapshot: 스냅샷(
      날짜, 문장, 출처,
      첫날 ? 도입.첫날답하기 : 도입.답하기,
      초급인가(급수) ? (첫날 ? 도입.첫날답하기선택지 : 도입.답하기선택지) : null,
    ),
    task_ref: `task-${날짜}`,
    degraded,
    출처,
  };
}

/** 스냅샷의 한 호흡. 셋이 같은 자리를 읽으므로 찾는 규칙도 한 곳이다. */
const 호흡찾기 = (snap, 차례) =>
  (snap && Array.isArray(snap.호흡) ? snap.호흡.find((x) => x && x.차례 === 차례) : null) || null;

/** 스냅샷에서 ②문장만 되꺼낸다 — 다음 날 강등의 「전날 문장」이 여기서 나온다. */
const 따라말하기문장 = (snap) => {
  const h = 호흡찾기(snap, 2);
  return h && h.문장 ? String(h.문장) : null;
};

/** 스냅샷에서 ③프롬프트를 되꺼낸다. */
const 답하기프롬프트 = (snap) => {
  const h = 호흡찾기(snap, 3);
  return h && h.프롬프트 ? String(h.프롬프트) : null;
};

/** 스냅샷에서 ③선택지를 되꺼낸다(급수 1~2 · 없으면 `null`).
 *  배열이 아니거나 비었으면 `null` 로 접는다 — 화면이 「보기 0개짜리 고르기」를 그리지 않게. */
const 답하기선택지 = (snap) => {
  const h = 호흡찾기(snap, 3);
  const c = h && Array.isArray(h.선택지) ? h.선택지.filter((x) => typeof x === 'string' && x.trim()) : [];
  return c.length ? c : null;
};

/** 호흡의 형식(`낭독`·`자유발화`·`응답`). 제출 행은 **자기 호흡의 형식**을 갖는다(P0 §2-1). */
const 호흡형식 = (snap, 차례) => {
  const h = 호흡찾기(snap, 차례);
  return h && h.task_format ? String(h.task_format) : null;
};

/** 화면의 호흡 이름 → 스냅샷의 차례. 두 어휘가 만나는 자리는 여기 하나다. */
const 호흡차례 = { 따라: 2, 답하기: 3 };

/**
 * `GET /v1/tasks` 의 `data[0]` → 화면이 쓰는 「편지」 모양 (C0 §4-3 ①).
 *
 * ■ 왜 **여기**에 있나 — 스냅샷을 만드는 곳과 읽는 곳이 같은 파일이어야 안 갈린다.
 *   호흡 배열의 모양(`차례`·`문장`·`프롬프트`)을 아는 곳이 둘이 되면, 배치가 키 이름을
 *   바꾸는 날 조회는 **오류 없이 빈 화면**을 낸다 — 그 증상엔 원인이 안 적혀 있다.
 *
 * ■ 못 읽으면 **폴백으로 내려가되 그 사실을 낸다**(P0 §6-4 · C0 §4-3 「빈 상태는 오류가 아니다」).
 *   🔴 폴백을 조용히 쓰면 화면은 늘 멀쩡해 보이고, **배치가 몇 날 안 돌아도 아무도 모른다.**
 *   그건 P0 §4-1 이 경계한 「막힌 것이 통과한 것처럼 보이는 상태」다. 그래서 `사유` 를 함께 낸다.
 *
 * @param {object|null} 항목  `data[0]`(없으면 null)
 * @param {object} 폴백       `contents/첫편지.js` 의 급수편지(급수) — 첫날·배치 실패 때 쓰는 고정 과제
 */
function 화면과제(항목, 폴백) {
  const 내려감 = (사유) => ({
    편지: 폴백, 출처: '고정', 사유, degraded: true, task_id: null, intervention_id: null,
    // 폴백 날엔 가리킬 배달 사건이 없다 — 열람도 안 보낸다(`열람사건` 이 null 을 낸다).
    intervention_event_id: null,
    // 🔴 폴백 날의 발화는 **서버로 못 보낸다** — 어느 과제에 대한 것인지(`task_ref`)도, 그때
    //   급수(`level_snapshot`)도 앱이 알 길이 없다. 지어내면 큐와 안 이어진 행이 조용히 쌓인다.
    //   보낼 수 없다는 사실은 로그 항목에 사유로 남는다(`src/말하기화면.js`).
    제출재료: null,
  });
  if (!폴백) throw new TypeError('화면과제: 폴백이 필요하다 — 빈 화면을 내지 않는다');
  if (!항목) return 내려감('오늘 받은 과제가 아직 없어요');

  const snap = 항목.task_snapshot;
  const 핵심문장 = 따라말하기문장(snap);
  const 질문 = 답하기프롬프트(snap);
  // 둘 중 하나만 있어도 화면은 반쪽이다 — ②③은 쌍이라서 값이 있다(P0 §2-1).
  if (!핵심문장 || !질문) return 내려감('오늘 과제를 읽지 못했어요');

  const 개입 = 항목.intervention || null;
  return {
    편지: {
      id: 항목.task_id || null,
      // ①듣기 = AI 가 실제로 한 말. 없으면 ②문장이 곧 그날 나간 말이다(강등 경로 · §6-4).
      본문: (개입 && 개입.output_text) || 핵심문장,
      핵심문장,
      질문,
      /* 급수 1~2 의 보기(설계 §6). **서버가 낸 것만 쓴다** — 앱이 지어내면 그날 학생이 본
       * 보기와 배정 행의 보기가 갈리고, 「무엇을 보고 골랐나」를 나중에 복원할 수 없다. */
      선택지: 답하기선택지(snap),
    },
    출처: '서버',
    사유: null,
    degraded: Boolean(항목.degraded),
    task_id: 항목.task_id || null,
    intervention_id: (개입 && 개입.intervention_id) || null,
    /* 🔑 **그 배달 사건의 id** — `content.viewed` 가 `parent_event_id` 로 가리킬 유일한 값
     *   (c9 · C0 §4-3 ①). 위 `intervention_id` 는 업무 키라 배달·성과가 같은 값을 나눠 들고,
     *   그걸로 가리키면 같은 개입을 두 번 내보낸 날 두 열람이 한 행으로 접힌다. 서버가 이 칸을
     *   안 싣던 동안 c9 는 이름·물리·검증기가 다 선 채로 **생산자가 0**이었다. */
    intervention_event_id: (개입 && 개입.event_id) || null,
    /* 제출 사건에 **되돌려 실을** 값들(C0 §4-3 ①). 앱이 만드는 것은 하나도 없다 —
     * 셋 다 배정 행이 낸 것이고, 여기 없으면 `제출사건` 이 사건을 못 만든다(=안 보낸다). */
    제출재료: 항목.task_ref
      ? {
          task_ref: String(항목.task_ref),
          /* 🔴 그날 **이 화면이 실제로 그린 판**. 위 `핵심문장`·`질문` 이 전부 여기서 나왔으므로
           *   이 값이 곧 학생이 본 것이다 — 나중에 배정 행에서 베껴 오면 「앱이 배정대로 그렸다」는
           *   추정이 관측 칸에 들어간다(절단문서 ①-3·①-7). 오프라인 큐가 며칠 들고 있어도
           *   항목이 자기 것을 들고 가므로 그 사이 문항이 개정돼도 안 흔들린다. */
          task_snapshot: snap,
          level_snapshot: 항목.level_snapshot || null,
          goal_snapshot: 항목.goal_snapshot || null,
          /* 🔴 오늘 것이 교정문이면 **그 교정의 원 제출 사건**(서버 배정 행이 낸 값 · C0 §4-3 ①).
           *   제출 사건에 되돌려 실으면 그게 `retry_of_event_id` — 설계 전체의 **유일한 결과
           *   변수**다(L0 §9-2). 🔑 앱이 지어내지 않는다: 목록의 교정문과 오늘 문장을 글자로
           *   대조하는 길도 있지만 그건 추정이고, 같은 문장이 두 번 교정된 날 조용히 갈린다.
           * 🔑 항목이 들고 간다 — `task_meta` 의 나머지와 같은 이유다(오프라인으로 사흘 밀린
           *   발화도 그날의 고리를 그대로 들고 올라간다). */
          retry_of_event_id: 항목.retry_of_event_id || null,
          형식: { 따라: 호흡형식(snap, 2), 답하기: 호흡형식(snap, 3) },
        }
      : null,
  };
}

/**
 * 「그날 앞에 놓인 것에 눈·귀가 실제로 닿았다」 → `content.viewed` 하나 (c9). **순수 함수다.**
 *
 * ■ 이 함수가 닫는 것 — c9 생산자 0
 *   `content.viewed` 는 이름(c9)·물리(CHECK)·검증기(`lib/이벤트검증.js`)·서버 INSERT 까지 전부
 *   서 있는데 **내는 코드가 0줄**이었다. 이유는 화면이 게을러서가 아니라 `parent_event_id` 로
 *   가리킬 값을 **손에 못 들었기 때문**이다 — `/v1/tasks` 가 업무 키(`intervention_id`)만 싣고
 *   배달 사건의 `event_id` 를 안 실었다. 그 칸이 서면서(C0 §4-3 ①) 이 함수가 가능해졌다.
 *   🔴 손실 시계는 **개원**이다. 「그날 열었는가」는 그날에만 알 수 있고, 나중에 이 코드를 넣어도
 *   그 전 기간은 영원히 빈칸이다 — `intervention.delivered` 는 배치의 **추정**이라(`lib/사건출처.js`
 *   가 `inferred` 로 박아 둔 자리) 관측 짝이 없으면 네트워크 실패가 「전달 완료」로 학습된다.
 *
 * ■ 무엇을 「닿았다」로 치나 — **재생이 끝난 것만**
 *   화면에 글자가 떠 있는 것은 관측이 아니다(안 보고 넘긴 학생과 같은 모양이다). 낭독이 끝까지
 *   간 것만 센다. 🚫 재생 **오류**는 열람이 아니다 — 흐름은 안 막지만(본문이 화면에 있다) 귀에
 *   닿은 것은 없다. 거기서 사건을 내면 「들었다」가 「띄웠다」로 조용히 뜻을 갈아탄다.
 *
 * ■ 멱등키는 **호출자가 들고 온다** — 여기서 짓지 않는다
 *   `제출사건` 과 같은 규약이다(C0 §4-1 · 절단문서 ①-5). 화면이 한 번 지어 사건 객체를 쥐고,
 *   재전송은 그 객체를 그대로 다시 보낸다 — 그래야 회선이 끊길 때마다 같은 열람이 여러 벌
 *   쌓이지 않는다(서버가 `duplicate` 로 접는다).
 *   ⚠ 천장: 이 사건은 아직 **디스크에 안 남는다** — 앱이 전송 전에 죽으면 그 한 건은 사라진다
 *     (`src/교정API.js` 가 이미 진 것과 같은 천장 · 윗길은 제출 로그 같은 지속 큐로 큐를
 *     일반화하는 별건이다).
 *
 * @param {object} 재료 `{ parent_event_id, idempotency_key, correlation_id, level_snapshot, occurred_at }`
 * @returns {object|null} 보낼 사건. 재료가 없으면 `null`(=만들지 않는다)
 */
function 열람사건({ parent_event_id, idempotency_key, correlation_id, level_snapshot, occurred_at } = {}) {
  /* 셋 중 하나라도 없으면 **안 만든다.** 지어내면 ①-10(가짜 앉음)·①-5(좌표 멱등키)로 되돌아가고,
   * `parent_event_id` 없는 열람은 계약이 이미 거부한다(대상 없는 관측은 학생 단위 집계로만 남는다). */
  if (!parent_event_id || !idempotency_key || !correlation_id) return null;
  return {
    idempotency_key,
    event_type: 'content.viewed',
    occurred_at: occurred_at || new Date().toISOString(),
    correlation_id,
    /* 널허용 칸 — 「모른다」와 「앱이 빠뜨렸다」를 가른다(C0 §4-3 ① ⓑ). 급수 없는 학생(개원 첫 주)의
     * 화면은 급수를 모르고, 그때 `null` 이 유일하게 정확한 값이다. `undefined` 는 키 누락이라 막힌다. */
    level_snapshot: level_snapshot === undefined ? null : level_snapshot,
    parent_event_id,
    payload: { ver: 1 },
  };
}

/**
 * 「자기 목소리를 되들었다」 → c9 `content.viewed` — **①-2 의 마지막 값**(절단문서). 순수 함수다.
 *
 * ■ 왜 부모가 `열람사건` 과 다른가
 *   ①듣기의 열람은 **배달물**을 가리킨다(`intervention.delivered` 의 관측 짝 · ①-12). 되듣기의
 *   대상은 배달물이 아니라 **학생 자기 녹음**이라, 같은 배달을 부모로 재사용하면 두 관측이 한 행으로
 *   섞여 「배달 오디오가 귀에 닿았다」가 부풀고 뜻이 조용히 갈아탄다. 그래서 부모는 그 제출 사건이다
 *   (`lib/이벤트검증.js` 생산자 장부가 적어 둔 판정 · 새 `event_type` 을 짓는 길은 c10 이고 c9 가
 *   이미 이 이름을 냈다).
 *
 * ■ 🔴 **착지한 뒤에만 만들어진다** — 그게 이 함수의 존재 이유다
 *   `event_id` 가 없으면 `열람사건` 이 `null` 을 내므로 **부모 없는 되듣기는 만들어질 수가 없다.**
 *   서버는 없는 부모를 `retryable:false` 로 접고(`functions/events` 고리풀기) 앱은 그것을
 *   `send_final` 로 적는다 — 즉 「먼저 보내기」의 결과는 재시도가 아니라 **영구 소멸**이다.
 *   녹음 화면에서 바로 보내면 WAV 업로드보다 이 작은 POST 가 먼저 닿아 거의 매번 그렇게 죽는다.
 *
 * ■ 멱등키는 항목 키에서 판다
 *   항목 키 자체가 v4 uuid 라 ①-5 가 금지한 **좌표 조립**(`날짜:호흡:시도`)이 아니다. 같은 항목이
 *   두 번 착지해도(`duplicate` 로 같은 `event_id` 가 돌아온다) 키가 같아 되듣기가 두 벌 안 쌓인다.
 *
 * @param {object} 항목 `lib/제출로그.js` 의 제출 로그 항목 — `replayed_at` 이 없으면 되듣기가 없던 것이다
 * @param {string} event_id 그 항목의 **착지한** 제출 사건 id
 * @returns {object|null} 보낼 사건. 되듣기가 없거나 재료가 모자라면 `null`
 */
function 되듣기사건(항목, event_id) {
  if (!항목 || !항목.replayed_at) return null;
  return 열람사건({
    parent_event_id: event_id,
    idempotency_key: 항목.idempotency_key ? `${항목.idempotency_key}:replay` : null,
    correlation_id: 항목.correlation_id,
    // 그때 화면이 알던 급수를 **항목이 들고 있다** — 사흘 밀려 올라가도 그날 값이다(task_meta 와 같은 자리).
    level_snapshot: 항목.task_meta ? 항목.task_meta.level_snapshot : null,
    occurred_at: 항목.replayed_at,
  });
}

/**
 * 로그 항목 하나 → `POST /v1/events` 의 사건 하나 (C0 §4-1). **순수 함수다.**
 *
 * ■ 왜 여기인가
 *   스냅샷의 호흡 형식을 읽는 곳이 이미 여기다. 조립을 화면에 두면 **같은 어휘를 아는 곳이 둘**이
 *   되고, 갈라지는 날 증상은 「제출이 400 으로 거절된다」가 아니라 **엉뚱한 형식으로 저장되는 것**
 *   이다 — 낭독 데이터가 자유발화로 섞여 들어가면 P0 §2-1 이 경계한 그 사고가 조용히 성립한다.
 *
 * ■ 멱등키는 **항목이 들고 온다** — 여기서 짓지 않는다
 *   `lib/제출로그.js` 가 항목을 만들 때 v4 uuid 로 한 번 짓는다(C0 §4-1). 서버는
 *   `(learner_id, idempotency_key)` 로 접으므로 재전송은 여전히 중복 행을 안 만든다 —
 *   같은 항목을 몇 번 조립해도 같은 값이 실리기 때문이다.
 *   🔴 여기서 `submission:{날짜}:{호흡}:{시도}` 로 조립하면 안 된다: `attempt` 는 로컬 로그에서
 *   세는 값이라 재설치·로그 초기화·다른 기기에서 1 로 되돌아가고, 그때 **새 녹음이 옛 행에
 *   `duplicate` 로 접혀 성공과 같은 모양으로 사라진다**(절단문서 ①-5).
 *
 * ■ 무발화는 `session.abandoned` 다
 *   내용물이 없어 `submission.created` 로는 검증을 못 지나고(택1 필수), 지난다 해도
 *   `submission_count` 가 「말 안 한 날」에 올라 「어제의 나」가 거짓말을 한다(C0 §4-3 ③).
 *   「막혔다」는 그 자체가 신호라 문턱이 없다(`lib/이벤트검증.js` 이벤트별필수 참조).
 *
 * ⚠ **머뭇거림·발화길이는 payload 로는 안 나간다 — 그리고 나갈 필요가 없다.** 이름이 계약
 *   목록에 없는 것은 맞지만(`C0 §4-1`), 새 이름은 이미 기각돼 있다: `발주_게임모듈.md` §646 이
 *   「`stt_segments` 첫 세그먼트의 `start` 가 곧 `hesitation_ms` 다(WAV 0초 = 녹음 시작)」로
 *   `wpm`·`pause_duration_sec` 와 같은 계열의 **파생**이라 못박았다. 즉 이 둘의 원천은 payload
 *   칸이 아니라 **WAV 파일 자체**고, 파일이 서버에 있으면 c9 없이도 산다.
 *   👉 그래서 남는 소급불가는 하나다 — **파일이 안 붙는 행.** 아래 `session.abandoned` 참조.
 *   🚫 `capture_meta` 로 우회하지 않는다(「요청한 설정」과 「관측」을 섞지 말라는 c6 판정).
 *
 * @param {object} 항목      `lib/제출로그.js` 의 항목 — **재료도 그 안에 있다**(`task_meta`)
 * @param {string|null} [audio_ref]  업로드가 끝났으면 그 참조
 * @returns {object|null} 보낼 사건. 재료가 없거나 형식을 모르면 `null`(=보내지 않는다)
 */
function 제출사건(항목, audio_ref) {
  if (!항목) return null;
  const 재료 = 항목.task_meta;
  const capture_app = 항목.capture_app || null;
  if (!재료 || !재료.task_ref) return null;
  /* 한 앉음을 묶는 키가 없으면 **보내지 않는다.** 계약이 이제 공통 필수로 걸므로 보내 봐야
   * 400 이고, 그 항목은 큐에서 영영 재시도한다. 없는 값을 지어내지도 않는다 — 지어낸 키는
   * 흩어진 것을 「한 앉음」이라고 거짓말하고, 그 거짓은 나중에 못 가려낸다(절단문서 ①-10). */
  if (!항목.correlation_id) return null;
  /* 멱등키도 같다 — **항목이 들고 온 것만 쓴다.** 없다고 여기서 지어내면 그 순간 좌표 조립으로
   * 되돌아가고(=①-5 가 다시 성립), 그 손실은 `duplicate` 라 성공과 같은 모양이다. 옛 판 큐 항목은
   * `correlation_id` 가 없어 어차피 이미 안 나간다 — 여기서 갈래를 하나 더 만들지 않는다. */
  if (!항목.idempotency_key) return null;
  const 차례 = 호흡차례[항목.step];
  if (!차례) return null;

  const 공통 = {
    idempotency_key: 항목.idempotency_key,
    occurred_at: 항목.created_at,
    /* 한 앉음을 묶는 키(P0 §3-1 ④). ②낭독과 ③자유발화가 **같은 값**을 들어야 「한 번에 낸 쌍」이
     * 선다. 🔴 `task_ref` 로 대신하지 않는다 — 그건 그날 배정이라 아침에 ②, 저녁에 ③ 을 낸 날도
     * 같은 값이고, 무발화로 접힌 앉음까지 한 덩어리가 된다. `occurred_at` 정렬로도 못 대신한다
     * (C0 §4-1 이 「기기 시계는 못 믿는다」를 이미 못박았다).
     * 🔴 c9 부터 **공통 필수**라 없으면 위에서 이미 사건을 안 만든다(옛 판 큐 항목은 안 나간다). */
    correlation_id: 항목.correlation_id,
    level_snapshot: 재료.level_snapshot,
    goal_snapshot: 재료.goal_snapshot,
    // 재시도는 새 event_type 이 아니라 attempt 증가로 남는다(P0 S1-7 · C0 §4-3 ③ `retry_count`).
    payload: { ver: 1, attempt_no: 항목.attempt },
  };

  /* 형식은 **무발화에도 필요하다** — 어디서 막혔는지가 그 사건이 가진 전부이기 때문이다.
   * 지어내지 않는다: 모르면 안 보낸다(스냅샷 생성기가 `낭독`·`자유발화` 를 늘 박으므로
   * null 은 남의 판·옛 큐 항목뿐이다). */
  const task_format = 재료.형식 ? 재료.형식[항목.step] : null;
  if (!task_format) return null;   // 형식을 모르면 지어내지 않는다 — 안 보내는 편이 옳다

  /* 「막혔다」가 **어디서** 막혔는지를 들고 간다(절단문서 ①-6). 낭독 시작 전 이탈과 자유발화 중
   * 포기는 끈기·난이도 모델에서 정반대 신호인데, 형식이 없으면 둘이 같은 행이 되어 사후에 못
   * 가른다 — 그건 소급 불가다.
   * 🔑 `task_ref` 를 함께 싣는 이유 = 없으면 그 무발화가 **어느 날 배정에 대한 것인지**가
   *   사라져 「받고 안 냈다」의 분모를 못 만든다.
   *
   * 🔴 **무발화는 두 가지다 — 그 둘이 여기서 접히면 사후에 못 가른다**(①-6 의 한 층 아래).
   *   ⓐ 조각이 하나도 안 왔다 = 입을 안 뗐다 → WAV 가 아예 없다.
   *   ⓑ 소리는 났는데 문턱 미달 = **말을 걸었지만 작았다** → `src/말하기화면.js` 가 그 WAV 를
   *      만들어 로그에 넣고, `src/제출API.js` 가 **이미 업로드까지 한다**(`항목.audio` 갈래).
   *   그런데 여기서 `audio_ref` 를 안 실으면 ⓑ 의 행은 ⓐ 와 **바이트 단위로 같아지고**, 올라간
   *   파일은 아무도 안 가리키는 고아로 버킷에 남는다. 겁먹은 학생과 포기한 학생이 같은 행이 되는
   *   것이라 이탈 예측(P0 S1-6)의 원신호가 그 자리에서 죽는다.
   *   🔑 새 이름을 안 지었다 = **c9 불요**: `audio_ref` 는 계약이 이미 낸 이름이고
   *      `lib/이벤트검증.js` 의 `선택필드` 에 사유와 함께 등재돼 있다(내용물 문턱이 없는 이 사건에
   *      「있으면 싣는다」는 그 장부가 허용하는 정확한 형태다).
   *   🔑 이 참조 하나가 `hesitation_ms`·`duration_ms` 도 되살린다 — 그 둘은 파생이라 새 열을
   *      안 만들기로 이미 기각됐고(`발주_게임모듈.md` §646), 파생의 원천이 바로 이 파일이다.
   *      곁들여 서버가 `capture_meta.server` 에 헤더 실측을 얹는다(`functions/events` 헤더측정).
   *   ⚠ 그래도 **제출은 아니다** — `event_type` 은 그대로 `session.abandoned` 고 하류 5곳은
   *      전부 `event_type` 으로 세므로 제출 수는 안 흔들린다(①-6 이 실측해 둔 자리).
   *   🚫 `body_original` 은 여전히 안 싣는다. 낸 답이 없다는 것이 이 사건의 뜻이다. */
  if (항목.status === 'abandoned') {
    return {
      ...공통,
      event_type: 'session.abandoned',
      task_type: '발화녹음',
      submission: {
        task_ref: 재료.task_ref,
        task_format,
        ...(audio_ref ? { audio_ref } : {}),
      },
    };
  }
  // 판(스냅샷)을 못 들고 온 옛 큐 항목도 같다. 「막혔다」(abandoned)는 위에서 이미 나갔다.
  if (!재료.task_snapshot) return null;
  return {
    ...공통,
    /* 🔴 **결과 변수**(L0 §9-2 · C0 §4-1) — 오늘 것이 교정문이었으면 이 발화는 「교정을 받고
     *   다시 낸 것」이고, 그 고리가 없으면 엔진은 상관만 배우고 처방을 못 배운다.
     * 🔑 `...(x ? {} : {})` 로 **있을 때만** 싣는다: 첫 제출에 `null` 을 박아 보내도 저장은
     *   되지만, 그러면 「재시도가 아니다」와 「모른다」가 같은 모양이 된다.
     * ⚠ `session.abandoned` 에는 안 싣는다 — 안 낸 것은 재제출이 아니다(받고 안 한 날은
     *   그 사건이 이미 분모로 남는다). */
    ...(재료.retry_of_event_id ? { retry_of_event_id: 재료.retry_of_event_id } : {}),
    event_type: 'submission.created',
    task_type: '발화녹음',
    submission: {
      task_ref: 재료.task_ref,
      task_format,
      // 그때 이 화면이 그린 판 — 항목이 들고 온 것을 그대로 되싣는다(위 `화면과제` 주석).
      task_snapshot: 재료.task_snapshot,
      body_original: 항목.text || null,
      audio_ref: audio_ref || null,
      /* `app` = 앱이 **요청한** 설정. 서버는 파일 헤더에서 **잰** 값을 `.server` 에 따로 얹는다
       * (C0 §4-2). 지금 앱은 AGC 를 끄라고 요청조차 하지 않으므로 그 사실이 그대로 적혀야 한다 —
       * 안 적으면 「요청」 칸이 영원히 비고, 나중에 규격 밖 행을 봐도 **앱 설정 탓인지 기기 탓인지**
       * 가를 근거가 없다. 🚫 여기에 헤더에서 잰 값을 적지 않는다(그건 관측이지 요청이 아니다). */
      ...(capture_app ? { capture_meta: { app: capture_app } } : {}),
    },
  };
}

/**
 * 배정 0인 날을 **지금 구제할 것인가** — C0 심문 B3 (소급 불가 · 순수 함수).
 *
 * ■ 왜 이 판정이 따로 사는가
 *   `/tasks` 안에 조건 셋을 인라인으로 적으면 그 판정은 **소스 글자로만** 검사할 수 있고,
 *   글자 검사는 조건 하나를 통째로 죽여도(`if (true)`) 초록이 된다(F287 · 같은 날 실측).
 *   순수 함수로 빼면 값을 먹여 **행동으로** 잴 수 있다. 부르는 곳은 하나여야 한다.
 *
 * ■ 조건 셋을 전부 본다 — 하나라도 빠지면 새는 방향은 「부른다」이고, 그 대가가 각자 다르다
 *   ①`배정수 === 0` : 있으면 구제할 게 없다.
 *   ②`막힘` 이 없다 : 동의 없는 학생은 `deliver` 가 `skipped`(consent_missing)로 건너뛴다.
 *      불러도 결과가 같으므로, 안 가르면 그 학생의 **매 요청이 배치를 한 번씩 때린다.**
 *      그 자리는 구제가 아니라 `CONSENT_MISSING` 게이트 몫이다.
 *   ③`날짜 === 오늘` : `deliver` 는 자기 몽골날짜로 **오늘에만** 쓴다. 어제를 조회하면서 부르면
 *      **오늘 배정이 서고 응답은 그대로 빈** 채가 된다 — 고친 것 없이 남의 날짜에 행을 만든다.
 *
 * ⚠ 「몇 번 부를까」는 여기서 안 정한다. 이 함수는 **한 번의 판정**이고, 한 번만 부르는 것은
 *   부르는 쪽의 구조(루프 없음)가 진다 — 여기에 횟수를 넣으면 상태를 들게 되고, 그 순간
 *   같은 판정이 두 곳(여기·호출부)에 살게 된다.
 *
 * @param {{배정수:number, 막힘:unknown, 날짜:string, 오늘:string}} 상황
 * @returns {boolean}
 */
function 구제할까(상황) {
  const { 배정수, 막힘, 날짜, 오늘 } = 상황 || {};
  if (Number(배정수) !== 0) return false;
  if (막힘) return false;
  return Boolean(날짜) && 날짜 === 오늘;
}

module.exports = {
  몽골날짜, 복귀행동, 멱등키, 오늘과제, 따라말하기문장, 답하기프롬프트, 호흡형식, 호흡차례,
  화면과제, 제출사건, 열람사건, 되듣기사건, 도입, 시간대, 학생판스냅샷, 학생공개키, 구제할까,
};
