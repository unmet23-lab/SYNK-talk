/**
 * 게임스냅샷 — G1 `task_snapshot` 의 **조립기** (발주_게임모듈.md §6-8 정본 표). 순수 함수만.
 *
 * ⚠ 이름은 `de44763a` 가 보드에 선언한 것을 따랐다(`lib/{작성과정,멘탈게이지,게임스냅샷}.js`).
 *
 * ■ 자리 — §6-8 규칙 3 「키 이름은 이 표 밖에서 만들지 않는다」의 실행층
 *   팩(`contents/교수멘탈문항.js`)이 값 «재료»(지시문·질문·문항판)와 모듈 상수를 대고,
 *   여기가 §6-8 공통층 4키 + 조건층 2키(G1 몫)를 **한 벌로** 조립한다. 값 사본 0 —
 *   `모듈상수`·`펴기` 를 그대로 쓴다(베끼면 팩 개정이 스냅샷에 안 닿는다).
 *
 * ■ G1 스냅샷의 키는 정확히 6이다
 *   공통층: `지시문`(학생에게 보인 지시 전문 — 핵심어휘 3개도 이 안이다) · `질문`(상황문) ·
 *   `문항판`(문항 «자체»의 판 — 스냅샷 «모양»의 판은 `task_schema_ver` 로 L0 몫) ·
 *   `challenge_id`. 조건층: `addressee_level`(합쇼체) · `prompt_seed`(문항 단위 식별).
 *   🔴 `보기`·`정답` 은 **만들지 않는다** — 열린 쓰기에는 지시대상이 없고, 빈 값으로 채우면
 *   「모른다」와 「없다」가 같은 모양이 된다(G1 §6 · §9-③). `mn` 은 G4 번역 행만의 키다.
 *   `요구문형` 도 안 싣는다 — 화면 비노출 내부 재료라 「그날 학생에게 보인 것」이 아니다.
 *
 * ■ 🔴 반쪽 스냅샷을 내지 않는다 (§6-8 규칙 1 · `작성과정.계측payload` 와 같은 축)
 *   여섯 값 중 하나라도 비면 키를 빼는 게 아니라 **스냅샷 자체를 안 만든다**(`null`) —
 *   G1 의 여섯은 전부 필수라, 빠진 채 나가면 「그날 안 보였다」로 읽힌다.
 *
 * ■ 🔑 배정 쪽도 이 함수다 (§6-8 규칙 4)
 *   `task.assigned` 의 스냅샷과 `submission.created` 의 스냅샷이 같은 조립을 지나야
 *   `challenge_id`·`prompt_seed` 가 배정↔제출에서 같은 모양이 된다(§6-7 ⑥ 소급 불가 조건).
 *
 * ■ ⚠ `검수확정` 게이트는 여기가 아니다
 *   미검수 판을 학생에게 **배정하지 않는 것**은 배정 통로의 게이트다(발주_게임콘텐츠팩.md §3 —
 *   배정 배선 커밋의 인수 조건). 조립기는 보인 것을 그대로 스냅샷한다 — 여기서 막으면
 *   이미 보여 준 화면의 제출이 기록을 못 남긴다.
 *
 * ⚠ 이 파일은 **아직 생산자가 아니다** — 사건을 내는 것은 G1 화면·배정 배치고 둘 다 아직
 *   없다(`작성과정`·`선택로그` 가 밟은 순서 그대로: 조립기·회귀가 1단계, 화면·소비자·엔진
 *   도달이 2단계 한 커밋).
 *
 * ■ 🔴 이 파일은 CJS 다 (배정 배선 ①단계 · 2026-08-11)
 *   배정 배치(deliver)가 이 조립기를 동봉으로 실어야 하는데(§6-8 규칙 4 — 배정·제출이 같은
 *   조립), 동봉 기전은 CJS 전용이다(팩 머리말 · 적대 반박 C2). `tests/동봉CJS.test.js` 가 잡는다.
 */
'use strict';

const { 모듈상수, 펴기 } = require('../contents/교수멘탈문항.js');

/** §6-8 표가 G1 에 준 키 전부 — 회귀가 이 목록으로 「표 밖 키 0 · 빈 값 0」을 검사한다. */
const 스냅샷키들 = Object.freeze([
  '지시문', '질문', '문항판', 'challenge_id', 'addressee_level', 'prompt_seed',
]);

/* G1 제출 통로 — 발주 §6 표 고정값. 앱 조립(`lib/게임제출.js`)과 서버 배정(`functions/deliver`)이
 * 같은 행 규격을 말해야 하는데 저쪽은 ESM·이쪽만 동봉되므로, CJS 정본은 여기 한 곳이다
 * (두 파일이 각자 '숙제제출' 을 적으면 §6-8 규칙 3 이 막는 그 갈림이 값에서 난다). */
const 과제유형 = '숙제제출';

/** 이 스냅샷이 G1 것인가 — 라우팅·조회가 같은 축(`challenge_id` · §6-7 ⑥)으로 가른다. */
function 게임스냅샷인가(snap) {
  return !!snap && typeof snap === 'object' && !Array.isArray(snap)
    && snap.challenge_id === 모듈상수.challenge_id;
}

/* ■ 학생에게 내보내도 되는 G1 스냅샷 키 — **허용 목록** (절단문서 ②-20 · 배정 배선 ④ C1)
 *
 *   `GET /v1/tasks` 의 거름망(`lib/오늘과제.학생판스냅샷`)은 말하기 판(`ver·날짜·호흡`)만 알아서
 *   G1 6키를 전부 벗겼다 — 앱은 게임을 원리상 못 보고 증상은 「오늘 과제를 읽지 못했어요」뿐이었다.
 *   G1 은 여섯 키 전부 공개다: 열린 쓰기라 스냅샷에 `보기`·`정답` 이 애초에 없다(§6-8 규칙 1).
 *
 * 🔴 `스냅샷키들` 에서 파생하지 않고 **따로 적는다** — 저 목록은 「행에 남는 키」고 이 목록은
 *   「학생에게 새도 되는 키」라 축이 다르다. 파생시키면 나중에 비공개 재료 키가 스냅샷에 서는 날
 *   그대로 새고 증상이 「통과」다(새는 방향은 언제나 통과). 새 키의 기본값은 「안 나감」이고,
 *   그날 화면이 비어 사람이 온다 — 그 자리에서 「학생이 봐도 되나」를 정한다. */
const 학생공개키 = Object.freeze([
  '지시문', '질문', '문항판', 'challenge_id', 'addressee_level', 'prompt_seed',
]);
/* 멤버십은 Set 으로 본다 — 이 파일은 부분일치 채점 금지(`tests/멘탈게이지.test.js`)가 부분일치
 * 표기를 소스 전문에서 통째로 막는 파일이라, 배열 멤버십도 그 표기를 안 쓴다(주석도 소스다). */
const 학생공개세트 = new Set(학생공개키);

/** G1 스냅샷에서 학생에게 줄 판만 남긴다 — 목록 밖 키는 전부 지운다. 원본은 안 건드린다. */
function 학생판게임스냅샷(snap) {
  if (!게임스냅샷인가(snap)) return snap;
  return Object.fromEntries(Object.entries(snap).filter(([k]) => 학생공개세트.has(k)));
}

/**
 * 스냅샷 **모양**의 판 (`submission.task_schema_ver` · L0 §3-3) — 정의는 여기 하나다.
 * 문항 자체의 판은 스냅샷 안의 `문항판` 이다 — 둘은 다른 축이다(발주 G1 §6).
 * 🔴 `스냅샷키들`(6키)이 바뀌는 날 이 판이 함께 오른다 — 회귀가 키 목록을 못박아 두어,
 *   키를 바꾸고 판을 안 올리면 그 테스트부터 빨개진다.
 * 🔑 `게임제출`(앱)이 아니라 여기 사는 이유: 배정 행(`task.assigned`)도 같은 판을 적어야
 *   하는데, 서버 동봉은 이 파일까지만 싣는다 — 앱 제출 사슬(게임제출)을 서버에 끌고 오지
 *   않고도 배정·제출이 같은 정의 하나를 본다(배정 배선 ①단계 이사 · 2026-08-11).
 */
const 스냅샷모양판 = 'g1스냅샷.v1';

/**
 * G1 `task_snapshot` 을 조립한다 — 화면(제출)과 배정 배치가 같이 쓰는 유일한 입구.
 *
 * @param {string} prompt_seed `g1t01.s0d1` 꼴(팩 `시드만들기` 산출)
 * @returns {Readonly<object>|null} §6-8 6키 스냅샷. 못 펴는 시드·빈 재료는 `null` —
 *          지어내지 않는다(팩 `펴기` 와 같은 판정).
 */
function G1스냅샷(prompt_seed) {
  const 시드 = String(prompt_seed || '');
  const 문항 = 펴기(시드);
  if (!문항) return null;
  const 스냅샷 = {
    지시문: 문항.지시문,
    질문: 문항.질문,
    문항판: 문항.문항판,
    challenge_id: 모듈상수.challenge_id,
    addressee_level: 모듈상수.addressee_level,
    prompt_seed: 시드,
  };
  for (const 키 of 스냅샷키들) {
    const 값 = 스냅샷[키];
    if (typeof 값 !== 'string' || 값.trim() === '') return null;
  }
  return Object.freeze(스냅샷);
}

module.exports = {
  스냅샷키들, 스냅샷모양판, G1스냅샷, 과제유형, 게임스냅샷인가, 학생공개키, 학생판게임스냅샷,
};
