/* 과제검문 — 생성 산출(문장·질문)을 «막는 것만» 거르는 순수 검문
 *   (정본 = appsscript docs/상태기반_과제선택_설계.md §8 · 판정식·숫자를 이 파일이 낸다 · 2026-08-21).
 *
 * ■ 이 파일이 `quality_ver` 재료이고 `policy_ver` 재료 2 다(§5-1·§5-1-a — 파일 해시).
 *   문턱 숫자만이 아니라 정규화·오류 «순서»까지 판의 재료라 파일 전체를 해시한다(V6-16).
 * ■ 숫자의 근거를 정직하게 적는다(§8): 첫 판의 8·60·6·0.6 은 측정값이 아닌 **안전선**이었고,
 *   🔴 08-23 유호 채점 1회전(79건)이 첫 실측이 됐다 — 「한 문장 60자」가 자연스러움과 정면 충돌
 *   (유호 교정 다수가 2~3문장·최장 ≈70자 · 확정 「2~3문장 허용·후속 질문 허용」). ⇒ 문장 8~120
 *   (1~3문장) · 질문 6~90(물음표 1~2·후속 하나) — 바꾸면 판이 오른다(quality_ver·policy_ver 재료).
 *   ✅ 08-26: 「1~3문장」의 **문장 «수»도 이제 기계가 잰다**(그전엔 글자수만 걸고 문장 수는
 *   프롬프트 지시로만 살았다). 세는 자 = `lib/문장끊기.문장개수` · 라벨은 `길이` 를 그대로 쓴다
 *   (사유 일곱은 DB CHECK `attempts_gate_values_c13` 에 못박혀 있다 — 여덟째를 만들면 운영이 던진다).
 * ■ 「각각」= 문장·질문에 «따로» 걸고 하나라도 걸리면 탈락(§8 I8 — 합쳐 재면 짧은 질문의 낮은
 *   한국어 비율이 긴 문장에 희석돼 통과한다).
 * ■ 실패 «라벨»은 §8 행 순서의 첫 항목 하나(`generation_gate_failed` 7값) — 나머지 전부는
 *   `사유들` 배열이 든다(attempts.gate_failed_reasons 로 가는 값 · 복수 실패를 안 잃는다).
 * ■ ❌ 못 재는 것 — 문장이 그 학생에게 «좋은가». 런타임 품질 문턱을 넣지 않는다(그게 곧 ㉠ ·
 *   불변식 5). 재미·도움은 §8-B(오프라인 사람 채점)와 첫 학생 뒤 층이 잰다(§8-A 게이트 지도).
 * ■ 반환의 `문장`·`질문` 은 **정규화 «후» 값**이다 — §7 매핑 표의 「검문이 본 것과 같은
 *   바이트」가 스냅샷에 실리는 그 값이라, 부르는 쪽이 다시 정규화하면 안 된다. */
'use strict';
const { 문장개수, 상한: 문장수상한 } = require('./문장끊기.js');

/* ── 판정 상수(§8 표 그대로 — 경계값 «정확히 그 값»은 통과) ── */
const 문장길이 = Object.freeze({ 하한: 8, 상한: 120 });   // 1~3문장(유호 확정 08-23 — 자연스러움 우선)
const 질문길이 = Object.freeze({ 하한: 6, 상한: 90 });    // 주 질문 + 후속 하나까지
const 물음표상한 = 2;   // 후속 질문 «하나»의 기계 축 — 3개부터는 설문이다
const 한국어비율하한 = 0.6;
const 중복창_일 = 14;   // §8 중복 검사의 창 — 신선함의 기계 축(효과 회수 창과 별개 · §6-0 F5)

/** 비교 전 정규화(§8 첫 행) — NFC 고정 · 앞뒤 공백 제거 · 연속 공백 1칸. */
const 정규화 = (s) => String(s ?? '').normalize('NFC').trim().replace(/\s+/g, ' ');

/* 중복 비교용 정규화(§8 중복 행) — 위 정규화 뒤 문장부호·따옴표 제거.
 * ⚠ 대소문자·조사는 안 건드린다 — 한국어에서 조사 정규화는 뜻을 바꾼다. */
const 중복정규화 = (s) => 정규화(s).replace(/[.?!,…"'「」]/g, '');

const 코드포인트수 = (s) => Array.from(s).length;

/* 한글 코드포인트 — 완성형(가-힣) + 호환 자모(ㄱ-ㅎ·ㅏ-ㅣ). §8 은 「한글 코드포인트」라고만
 * 적었고 숫자·판정식은 이 파일이 못박는 자리다 — 자모 단독 표기(「ㅋㅋ」류)도 한국어 산출의
 * 일부라 센다. 분모는 공백 «제외» 전체 코드포인트(§8 표). */
const 한글인가 = (cp) => /[가-힣ㄱ-ㅎㅏ-ㅣ]/.test(cp);
const 한국어비율 = (s) => {
  const 전체 = Array.from(s).filter((c) => !/\s/.test(c));
  if (!전체.length) return 0;
  return 전체.filter(한글인가).length / 전체.length;
};

/* 금칙 서식(§8 표) — 따옴표로 시작·끝 · 번호 매기기 · 접두 라벨 포함. */
const 금칙서식인가 = (s) =>
  /^["']|["']$/.test(s) || /^\s*\d+[.)]/.test(s) || /예시:|답:|문장:|질문:/.test(s);

/**
 * @param {object} 재료
 * @param {string} 재료.문장  벤더 응답 sentence
 * @param {string} 재료.질문  벤더 응답 question
 * @param {string[]} [재료.식별자들]  그 학생의 식별자 문자열들(§10 — 역유입 검사 대상)
 * @param {string[]} [재료.최근문장들]  중복창(14일) 안 «성공» 생성물의 문장들(공급 = ②' 조인)
 * @param {string[]} [재료.최근질문들]  〃 질문들
 * @returns {{ok: boolean, 사유: string|null, 사유들: string[], 문장: string, 질문: string}}
 *   `사유` = 첫 실패 라벨(§4-1 `generation_gate_failed` 7값) · `사유들` = 걸린 전부(순서 그대로)
 */
function 검문(재료) {
  const { 식별자들 = [], 최근문장들 = [], 최근질문들 = [] } = 재료 || {};
  const 문장 = 정규화(재료 && 재료.문장);
  const 질문 = 정규화(재료 && 재료.질문);
  const 사유들 = [];

  /* §8 행 순서 그대로 — 라벨은 첫 항목이 든다. */
  if (코드포인트수(문장) === 0 || 코드포인트수(질문) === 0) 사유들.push('빈출력');
  const 문장수 = 코드포인트수(문장), 질문수 = 코드포인트수(질문);
  /* 🔴 08-26 신설 — 「1~3문장」의 «문장 수»를 기계가 잰다(여태 프롬프트 지시로만 살았다).
   *   ⓐ 라벨은 **`길이` 를 그대로 쓴다**: `attempts.gate_failed_reasons` 는 DB CHECK
   *      (`attempts_gate_values_c13`)로 일곱 값에 못박혀 있어 여덟째를 만들면 운영이 던진다.
   *      문장 «수»도 길이의 한 갈래라 뜻도 어긋나지 않는다.
   *   ⓑ 세는 자는 `문장개수` 다 — `문장들().length` 로 재면 그 함수가 상한에서 자르기를 멈춰
   *      **원리상 언제나 3 이하**라, 막는 척만 하는 검문이 된다(문장끊기 머리말에 못박았다).
   *   ⓒ 하한은 안 건다 — 0문장은 위 `빈출력` 이 이미 문다. */
  const 문장조각수 = 문장수 > 0 ? 문장개수(문장) : 0;
  if ((문장수 > 0 && (문장수 < 문장길이.하한 || 문장수 > 문장길이.상한))
    || (질문수 > 0 && (질문수 < 질문길이.하한 || 질문수 > 질문길이.상한))
    || 문장조각수 > 문장수상한) 사유들.push('길이');
  if ((문장수 > 0 && 한국어비율(문장) < 한국어비율하한)
    || (질문수 > 0 && 한국어비율(질문) < 한국어비율하한)) 사유들.push('한국어비율');
  if (금칙서식인가(문장) || 금칙서식인가(질문)) 사유들.push('금칙서식');
  /* 질문 형태 — 끝은 ? · ? 는 최대 2개(주 + 후속 하나 · 유호 확정 08-23). 세 개부터는 설문이다. */
  if (질문수 > 0 && (!질문.endsWith('?') || (질문.match(/\?/g) || []).length > 물음표상한)) 사유들.push('질문형태');
  {
    const 실린 = 식별자들.map((x) => String(x ?? '').trim()).filter((x) => x.length > 0);
    if (실린.some((id) => 문장.includes(id) || 질문.includes(id))) 사유들.push('식별자역유입');
  }
  {
    /* 중복(§8 C2 — 판정식 하나): 문장은 이력의 문장들과, 질문은 이력의 질문들과 «각각»
     * 중복정규화 후 완전 일치 — 어느 하나라도 일치하면 중복. 쌍 튜플도 축별 OR 도 아니다.
     * 품질 판정이 아니라 반복 검사다 — 문턱도 점수도 없다(§8-A). */
    const 문 = 중복정규화(문장), 질 = 중복정규화(질문);
    if ((문 && 최근문장들.some((s) => 중복정규화(s) === 문))
      || (질 && 최근질문들.some((s) => 중복정규화(s) === 질))) 사유들.push('중복');
  }

  return { ok: 사유들.length === 0, 사유: 사유들[0] ?? null, 사유들, 문장, 질문 };
}

module.exports = { 검문, 정규화, 중복정규화, 한국어비율, 문장길이, 질문길이, 물음표상한, 한국어비율하한, 중복창_일 };
