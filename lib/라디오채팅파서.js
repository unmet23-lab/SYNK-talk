/* 라디오24 채팅 파서 — 명령 어휘의 **정본**과 그 판(`parser_ver`)이 사는 곳.
 *
 * ■ 왜 이 파일이 따로 있나 (라디오24_설계 §4-1 · 원칙 5)
 *   원장 `radio.chat_message` 의 `command_kind`·`command_arg` 는 **파서 산출물(파생)**이다 —
 *   DDL 에 CHECK 를 안 건 이유가 「계약 밖 값목록을 DDL 에 만들지 않는다」이고, 그 값목록이
 *   사는 자리가 여기다. 수집봇과 승격기(Edge Fn)가 **같은 표**를 읽어야 갈라지지 않는다
 *   (`lib/사건출처.js` 가 `source_kind` 에 한 것과 같은 형태). 파서를 고치면 `파서판` 을
 *   올린다 — 원장의 `raw`·`body` 가 남아 있어 옛 행은 언제든 새 판으로 재파싱된다.
 *
 * ■ 인자 정책 = 유호님 판정 ㉠㉡ 의 기계 실체 (설계 §7-2 · 2026-08-08 확정)
 *   ㉡ 원칙 2(「누르면 끝」 금지)는 **①축(엔진 학습) 명령에만** 인자를 강제한다:
 *     `출석`·`목표`·`질문`·`답` = '필수'. 인자가 없으면 접수하지 않고 오버레이가 재시도를
 *     안내한다(그 판정 재료가 `인자정책` — 오늘의 소비자는 승격기의 「인자없음」 제외이고,
 *     재시도 안내는 P3 오버레이 몫이다. **봇은 못 문다** — 파생 두 칸이 Fn 독점이라
 *     `tests/라디오수집.test.js` 가 봇의 파서 참조 0 을 강제한다. 원장에는 인자 없이도 남는다).
 *   ㉠ ②축 전용(`빗소리`·`asmr`)은 '선택' — 인자가 있으면 `selection_reason` 이 되고
 *     없으면 선택만 승격한다(마찰 0 · 말한 사람의 이유는 건진다).
 *   `연동` 은 '무시' — **인자를 받는 순간 식별자가 새는 자리**다(§10 기각 2 · 코드 사칭·명단
 *     스캔·잠금 DoS). 학생이 실수로 코드를 쳐도 `command_arg` 에 싣지 않는다(원문은 `body`·
 *     `raw` 에 남으니 소실이 아니다 — 파생에 안 실을 뿐이다).
 *
 * ■ `답해석` 은 파서와 다른 층이다
 *   `!답 2?` 의 「2」와 「?」 해석(전각·「2번」 변형·확신도)은 승격 시점에 필요한 **해석**이고,
 *   원장에는 인자 원문이 그대로 남는다. 해석 규칙이 바뀌어도(새 파서판) 원장 재파싱으로
 *   전량 복원된다 — 해석 결과를 원장에 굳히지 않는 이유다.
 *   확신도 표기(설계 §2-J): `?`=애매('low') · `??`=찍음('guess') · 없음=null(안 물었다 —
 *   계약 `confidence` 는 「화면이 물었을 때만 있다」이고 없는 것을 지어내지 않는다).
 */
'use strict';

/* 파서 판 — 원장 행마다 이 값이 박힌다. 규칙(어휘·인자 정책·해석)을 바꾸면 판을 올린다. */
const 파서판 = 'radio-parse.v1';

/* 명령 어휘와 인자 정책 — 정본. 값: '필수'(①축 · ㉡) · '선택'(②축 · ㉠) · '없음' · '무시'(연동).
 * 🔴 새 명령은 설계 §2 의 게이트(수집→엔진 3단)를 지나야 여기 는다 — 어휘만 늘리고 승격
 *   규격이 없으면 그 명령은 「원장에만 남는 기능」이라 상시 지시(수집=엔진 도달까지)에 걸린다. */
const 명령표 = {
  '출석': { 인자: '필수' },   // ⓓ submission.created / 자습체크인 — 오늘의 한 문장
  '목표': { 인자: '필수' },   // ⓒ submission.created / 목표선언
  '질문': { 인자: '필수' },   // I-1 질문 원장 → 야간 군집 다이제스트
  '답':   { 인자: '필수' },   // J  quiz.answered (승격은 라운드·링크 게이트 뒤)
  '빗소리': { 인자: '선택' }, // ⓐ preference.stated / study_environment
  'asmr': { 인자: '선택' },   // ⓑ preference.stated / asmr_track
  '슬럼프': { 인자: '선택' }, // ⓔ affect.reported — 문턱 없음(막혔다는 신호 자체)
  '말하기': { 인자: '없음' }, // I-3 앱 딥링크 깔때기(수집 0 — correlation_id 만 실어 보낸다)
  '연동': { 인자: '무시' },   // §3 승인 대기 노크 — 인자를 파생에 싣지 않는다
  '문의': { 인자: '선택' },   // G 리드 사건(비학생 포함)
  '상담': { 인자: '선택' },
  '공지': { 인자: '선택' },   // F 운영 보조 통로(정본 입력은 시트 운영층 1행)
  '축하': { 인자: '선택' },
};

/* 채팅 한 줄 → { command_kind, command_arg } (원장 두 칸 그대로).
 * 명령이 아니면 둘 다 null — 자발 발화는 명령이 아니라도 원장에 남는다(c10 ⑤ 후보 재료). */
function 파싱(body) {
  const 원문 = String(body ?? '');
  const m = /^!\s*(\S+)([\s\S]*)$/.exec(원문.trim());
  if (!m) return { command_kind: null, command_arg: null };
  const 이름 = m[1].toLowerCase();
  const 명령 = 명령표[이름];
  if (!명령) return { command_kind: null, command_arg: null };  // 화이트리스트 밖 — 명령 아님
  if (명령.인자 === '무시') return { command_kind: 이름, command_arg: null };
  const 인자 = m[2].trim();
  return { command_kind: 이름, command_arg: 인자 === '' ? null : 인자 };
}

/* `!답` 인자 해석 — 승격 시점용. { 선택, 확신도 } | null(해석 불가 = 승격하지 않는다).
 *   받는 변형(§9 픽스처): '2' · '２'(전각) · '2번' · '2?' · '2 ?' · '2??' · '２번？？'
 *   확신도: '?'=`low`(애매) · '??'=`guess`(찍음) — 계약 `confidence` 값은 승격기가 매핑한다. */
function 답해석(command_arg) {
  if (command_arg == null) return null;
  let s = String(command_arg).trim()
    .replace(/[０-９]/g, (d) => String.fromCharCode(d.charCodeAt(0) - 0xFEE0))  // 전각 숫자
    .replace(/？/g, '?');                                                        // 전각 물음표
  const m = /^(\d{1,2})\s*(?:번)?\s*(\?{0,2})$/.exec(s);
  if (!m) return null;                       // 「2 아니면 3」 같은 것 — 지어내서 고르지 않는다
  return { 선택: m[1], 확신도: m[2] === '' ? null : (m[2] === '?' ? 'low' : 'guess') };
}

/* 인자 정책 조회 — 접수 판정의 한 곳. 오늘은 승격기(`인자없음` 제외)가 읽고, 그날이 오면
 * P3 오버레이(재시도 안내)가 읽는다 — 봇은 못 문다(파생 두 칸 Fn 독점). */
const 인자정책 = (command_kind) => 명령표[command_kind]?.인자 ?? null;

module.exports = { 파서판, 명령표, 파싱, 답해석, 인자정책 };
