'use strict';
/**
 * 브라우저에서 오는 요청을 받는 자리 — **CORS**.
 *
 * ■ 🔴 이게 없어서 «웹에서는 앱이 데이터를 하나도 못 받았다** (08-27 실측)
 *   화면은 뜨는데 `tasks`·`corrections`·`progress`·`deliver`·`l10n/queue` 가 전부 막혔다.
 *   ⚠ **기기(RN)에서는 CORS 가 없어 안 드러난다** — 웹에서만 죽는 종류라 더 늦게 발견된다
 *   (`src/사건통로.js` 머리말이 조회 함수의 OPTIONS 자리 없음을 이미 적어 뒀던 그 자리다).
 *
 * ■ 🔑 진짜 원인은 「OPTIONS 자리가 없다」가 아니라 **순서**였다
 *   preflight(OPTIONS)는 **커스텀 헤더를 안 싣는다** — 그걸 실어도 되는지 «물으러» 오는 요청이라
 *   그렇다. 그런데 우리 함수들은 첫 줄에서 `X-Contract-Ver` 를 검사하고 없으면 400 을 냈다.
 *   즉 preflight 가 우리 계약 검문에 걸려 죽었다(실측: 400 응답에 `x-deno-execution-id` 가 있다 —
 *   게이트웨이가 아니라 **우리 코드**가 낸 것이다).
 *   👉 그래서 `예비응답()` 은 **어떤 검사보다도 앞**에 서야 한다. 뒤에 두면 고쳐도 안 고쳐진다.
 *
 * ■ 🔴 `Access-Control-Allow-Origin: *` 인 까닭 — 그리고 **조이지 말라**는 부탁
 *   조이면 안전해 보이지만 여기서는 **아무것도 안 지키고 고장만 낸다.**
 *   · 우리 인증은 **Bearer 토큰**이다 — 쿠키가 아니다. 브라우저가 «알아서 붙여 보내는» 자격이
 *     하나도 없으므로, 남의 페이지가 우리 API 를 불러도 **실을 토큰이 없다**(우리 앱 저장소는
 *     그 페이지가 못 읽는다). 즉 CORS 는 여기서 인증 경계가 아니다 — 경계는 JWT 다.
 *   · 토큰을 훔친 공격자는 애초에 브라우저가 필요 없다(서버에서 부르면 CORS 가 없다).
 *   · 반대로 허용 목록을 두면 **새 주소가 뜨는 날마다 조용히 안 된다.** 이 저장소가 가장 많이
 *     데인 무늬가 그것이다(「증상 없이 안 되는 것」).
 *   🚫 그러므로 **여기를 허용 목록으로 바꾸지 않는다.** 바꿔야 할 진짜 조건은 하나뿐이다:
 *     쿠키·세션 같은 «브라우저가 자동으로 붙이는 자격»을 쓰기 시작하는 날. 그날은
 *     `Allow-Credentials` 가 필요해지고, 그때는 `*` 가 **규격상 못 쓰이므로** 저절로 드러난다.
 *
 * ■ 🔑 허용 헤더는 **되받아 적는다**(echo)
 *   목록을 손으로 적으면 새 헤더 하나가 느는 날 그것만 조용히 막힌다 — 그리고 그 증상은
 *   「네트워크가 이상하다」로 보인다. 브라우저가 «이 헤더들 써도 되냐»고 물어 온 그대로 돌려주면
 *   그 자리가 원리상 안 생긴다. 어차피 origin 이 `*` 라 이보다 좁힐 실익도 없다.
 *
 * ■ 🔑 `Max-Age` 하루 — 몽골 모바일 회선에서 preflight 는 **왕복 한 벌이 통째로 더 드는 것**이다.
 *   하루 캐시하면 학생 한 명당 그 왕복이 하루 한 번으로 준다.
 */

/** 되받아 적을 것이 없을 때 쓰는 바닥값 — 우리 앱이 실제로 싣는 것들. */
const 기본허용헤더 = 'authorization, apikey, content-type, x-contract-ver, x-client-info';

/**
 * **진짜 응답**에 얹을 머리 — 딱 한 줄이다.
 *
 * 🔑 `Allow-Headers`·`Allow-Methods`·`Max-Age` 는 **preflight 전용**이다. 진짜 응답에 얹어도
 *   브라우저가 안 본다 — 얹으면 「뭔가 하고 있다」는 착각만 준다.
 * 🔑 그래서 **`req` 를 안 받는다.** 이게 중요하다: 함수들의 `봉투()` 는 `req` 를 인자로 안 들고
 *   있어서, 요청을 요구하는 모양으로 두면 그 자리에서 안 잡히는 스코프 오류가 난다
 *   (08-27 에 실제로 그렇게 짰다가 되돌렸다 — 기계로 붙이는 수리는 이런 자리에서 샌다).
 * ⚠ `Access-Control-Expose-Headers` 는 안 넣는다 — 우리 앱은 응답 헤더를 안 읽고 본문만 읽는다.
 *   읽어야 할 헤더가 생기는 날 여기 더한다.
 */
function 머리() {
  return { 'Access-Control-Allow-Origin': '*' };
}

/**
 * preflight 면 **바로** 204 를 돌려준다. 아니면 `null` — 부르는 쪽이 하던 일을 계속한다.
 *
 * 🔴 **핸들러 첫 줄에 둔다.** 계약판·인증·경로 검사보다 앞이다(위 머리말 §순서).
 *   쓰는 법: `const 예비 = 예비응답(req); if (예비) return 예비;`
 * 🔑 본문 없이 204 다 — preflight 는 «허락»만 묻는다. 본문을 실으면 그것도 규격 밖은 아니지만,
 *   실어 봐야 브라우저가 안 읽는다.
 */
function 예비응답(req, 메서드) {
  if (!req || req.method !== 'OPTIONS') return null;
  const 물어온헤더 = req.headers && req.headers.get('Access-Control-Request-Headers');
  return new Response(null, {
    status: 204,
    headers: {
      ...머리(),
      'Access-Control-Allow-Headers': 물어온헤더 || 기본허용헤더,
      'Access-Control-Allow-Methods': 메서드 || 'GET, POST, OPTIONS',
      'Access-Control-Max-Age': '86400',
    },
  });
}

module.exports = { 머리, 예비응답, 기본허용헤더 };
