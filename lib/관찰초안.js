'use strict';
/* 관찰 초안 — 강사가 적은 자유 한 줄에서 **구조만** 뽑는다.
 * (정본 = appsscript `docs/관찰태그_자동화_설계.md` v1.1 §2 ㉮·§3 · 계약 c14 `observation.noted`)
 *
 * ■ 이 파일이 정본인 것 넷
 *   ① **어휘 2층** — 영역 9종은 늘 뽑고, 오류태그는 «실릴 수 있는 관찰에만» 얹는다(§3).
 *   ② **프롬프트** — 🚫 앱 축 데이터가 한 칸도 안 들어간다(§2 ㉯ 기각의 프롬프트 적용:
 *      앱의 의심을 먼저 보여주면 그 뒤 관찰은 앱 사전확률의 확증 표본이 된다).
 *   ③ **초안 지문** — `draft_modified` 를 **서버가** 정하는 자(§2 ㉡). 앱이 불리언을 보내면
 *      `서버칸` 규약이 막으려던 자기신고가 이름만 바꿔 돌아온다.
 *   ④ **분모 규칙** — 빈 초안 확정은 「무수정」이 아니라 **분모 밖**(`null`)이다(§2).
 *
 * ■ 값록은 사본이다 — 기계가 문다
 *   이 파일은 teach 함수에 `.mjs` 로 동봉되는데(`supabase/functions/teach/동봉.json`) 계약
 *   JSON 은 동봉 목록에 없어 서버에서 require 할 수 없다. 없앨 수 없는 사본은 기계에 문다 —
 *   `tests/관찰통로.test.js` 가 계약과 **글자로** 대조한다(`lib/반피드백.js` 와 같은 규율).
 *   갈리면 증상이 조용하다: JS 는 통과시키고 검증기가 거절하며, 화면엔 「저장이 안 된다」로만 보인다.
 *
 * ■ 🚫 여기 없는 것
 *   벤더 왕복(`fetch`) — index.ts 가 진다(`functions/correct` 와 같은 갈래: 순수부는 lib 에서
 *   회귀가 재고, 부수효과는 함수에서 진다) · 학생 식별자 · 확신도 문턱(지금 0 — **먼저 세고**
 *   실측이 쌓이면 게이트를 판정한다 · §2).
 */

/** 이 판정판 — 초안의 「어느 판이 뽑았나」. 프롬프트·값록·파싱이 바뀌면 올린다. */
const 판정판 = '관찰초안.v1';

/** 관찰 영역 9종 — 계약 「관찰영역」의 사본(라이브 폼 `TEACHER_MEMO_TYPES` 와 같은 눈금). */
const 영역들 = Object.freeze([
  '문법', '어휘', '발음', '말하기', '듣기', '읽기', '쓰기', '태도', '기타',
]);

/** 오류태그 — 계약 최상위 `오류태그`의 사본(24 = 23종 + `오류없음`). */
const 태그들 = Object.freeze([
  '조사:주격(이/가·은/는)', '조사:목적격(을/를)', '조사:처소(에·에서)', '조사:여격(에게·한테)',
  '조사:도구·방향(로/으로)', '조사:접속(와/과·하고)', '조사:기타',
  '어미:시제', '어미:연결어미', '어미:불규칙활용', '어미:종결',
  '높임:주체', '높임:상대(존댓말 등급)',
  '어휘:유의어혼동', '어휘:연어(자연스러운 짝)', '어휘:없는말',
  '맞춤법:받침', '맞춤법:띄어쓰기', '맞춤법:기타',
  '어순', '누락:필수성분', '중복:불필요', '화용:공손성', '오류없음',
]);

/* 🔑 오류태그가 **원리상 실릴 수 있는** 영역 넷. 나머지 다섯(발음·말하기·듣기·태도·기타)에서
 *   태그를 받으면 버린다 — 23종은 **텍스트 교정 축**이라 발음·태도 관찰이 여기 실리면 그 관찰이
 *   「기타」로 뭉개진다(§3). 「태그 없는 관찰」은 결함이 아니라 축이 다른 관찰이다.
 * ⚠ 이 넷은 게이트가 아니라 **정직한 범위**의 물리다 — 발음 관찰의 값은 태그가 아니라 확정
 *   라벨의 권위 + 영역·메모 축적이고, 「발음:*」 태그 신설은 개원 후 실측이 답한다(§3). */
const 태그실리는영역 = Object.freeze(['문법', '어휘', '쓰기', '읽기']);

/** 강사 원문 상한 — 한 줄 관찰이다. 넘으면 잘라 보내지 않고 **거절**한다(잘린 원문은 그 문장이 아니다). */
const 원문상한 = 500;

/** 태그 상한 — 0~2(§4 흐름). 셋을 받으면 「구조화」가 아니라 분류의 산탄이 된다. */
const 태그상한 = 2;

/** 모델이 낼 최대 토큰 — 세 칸짜리 JSON 한 줄이다(교정문 1024 와 다른 축이라 여기서 정한다).
 *  넘치면 잘린 JSON 이 오고 `초안읽기` 가 빈 초안으로 접는다 — 반쯤 적는 것보다 낫다. */
const 최대토큰 = 200;

/** 빈 초안 — AI 를 못 불렀거나 못 뽑았을 때. **정상 경로**다(비운 채 확정이 규격 · §3). */
function 빈초안(사유) {
  return { area: null, tags: [], confidence: null, draft_ver: 판정판, 사유: 사유 || null };
}

/** 초안이 비었나 — `draft_modified` 분모 밖인지 가르는 자(§2 분모 규칙). */
const 비었나 = (초안) => !초안 || (!초안.area && (!Array.isArray(초안.tags) || 초안.tags.length === 0));

/**
 * 벤더에 보낼 지시문 — 🚫 앱 축 데이터·학생 식별자가 한 칸도 없다.
 * 🔑 「구조화만」이 이 지시문의 전부다: 모델이 관찰을 **덧붙이면** 그 행의 `teacher` 등급이
 *   거짓이 된다(새 정보는 교실에서만 나온다 · §2 ㉮).
 */
function 지시문() {
  return [
    '너는 한국어 학원 강사가 교실에서 적은 관찰 메모 한 줄을 **구조화**하는 도구다.',
    '관찰을 새로 만들지 마라 — 메모에 없는 것은 뽑지 않는다. 판단·조언·평가도 쓰지 않는다.',
    '',
    `영역(area) 하나를 반드시 고른다: ${영역들.join(' · ')}`,
    `오류태그(tags)는 0~${태그상한}개다. 메모가 ${태그실리는영역.join('·')} 계열이고 어떤 오류인지 분명할 때만 고른다.`,
    '분명하지 않으면 **비운다** — 태그 없는 관찰은 결함이 아니라 축이 다른 관찰이다.',
    `태그는 다음 목록에서 글자 그대로만 고른다: ${태그들.join(' | ')}`,
    '',
    '메모에 학생 이름이 적혀 있으면 무시한다(이름은 구조가 아니다).',
    'confidence 는 0~1 실수 — 이 구조화가 메모를 옳게 읽었다고 보는 정도다.',
    '',
    '출력은 JSON 한 줄만: {"area":"…","tags":["…"],"confidence":0.0}',
  ].join('\n');
}

/** 벤더에 보낼 사용자 글 — 원문 하나뿐이다. */
const 사용자글 = (원문) => `관찰 메모: ${String(원문 == null ? '' : 원문).trim()}`;

/** 강사 원문 검사 — 빈 줄·상한 초과를 가른다. 통과하면 다듬은 문자열. */
function 원문검사(값) {
  if (typeof 값 !== 'string') return { 거절: '원문이 문자열이 아닙니다' };
  const 다듬 = 값.trim();
  if (!다듬) return { 거절: '관찰 한 줄을 적어 주세요' };
  if (다듬.length > 원문상한) return { 거절: `관찰은 ${원문상한}자까지입니다 (지금 ${다듬.length}자)` };
  return { 값: 다듬 };
}

/**
 * 모델 응답 글 → 초안. 못 읽으면 `빈초안`이다 — **던지지 않는다**(초안 실패로 확정을 막지
 * 않는 것이 §3 의 규격: 강사는 언제나 비운 채 확정할 수 있다).
 * 🔑 값록 밖은 조용히 버린다 — 지어낸 태그가 통과하면 그 축이 사라진다(값목록_규칙).
 */
function 초안읽기(글) {
  const 원 = typeof 글 === 'string' ? 글 : '';
  /* 코드펜스·앞뒤 산문을 견딘다 — 첫 `{` 부터 마지막 `}` 까지. */
  const i = 원.indexOf('{');
  const j = 원.lastIndexOf('}');
  if (i < 0 || j <= i) return 빈초안('응답형식밖');
  let 몸;
  try { 몸 = JSON.parse(원.slice(i, j + 1)); } catch { return 빈초안('응답형식밖'); }
  if (!몸 || typeof 몸 !== 'object') return 빈초안('응답형식밖');

  const area = 영역들.includes(몸.area) ? 몸.area : null;

  /* 태그: ①값록 안 ②중복 제거 ③상한 ④태그가 실릴 수 있는 영역일 때만. 순서가 뜻이다 —
   * 영역이 «먼저» 정해져야 태그를 버릴지 알 수 있다. */
  let tags = [];
  if (area && 태그실리는영역.includes(area) && Array.isArray(몸.tags)) {
    for (const t of 몸.tags) {
      if (태그들.includes(t) && !tags.includes(t)) tags.push(t);
      if (tags.length >= 태그상한) break;
    }
  }

  const c = Number(몸.confidence);
  const confidence = Number.isFinite(c) ? Math.min(1, Math.max(0, c)) : null;

  return { area, tags, confidence, draft_ver: 판정판, 사유: null };
}

/**
 * 초안 지문 — **대조의 자**다. 태그는 정렬해 담는다(순서는 뜻이 아니라 모델의 버릇이라,
 * 순서만 다른 것을 「고쳤다」로 세면 무수정 통과율이 조용히 부풀려진다).
 */
function 초안지문(초안) {
  const a = (초안 && 초안.area) || '';
  const t = (초안 && Array.isArray(초안.tags) ? 초안.tags.slice() : []).sort();
  return `${a}|${t.join(',')}`;
}

/**
 * `draft_modified` — 서버가 정한다(§2 ㉡).
 * @returns {true|false|null} `null` = 분모 밖(초안이 비어 있었다 · §2 분모 규칙)
 */
function 고쳤나(초안, 확정) {
  if (비었나(초안)) return null;
  return 초안지문(초안) !== 초안지문(확정);
}

/** 확정값 검사 — 강사가 무엇으로 확정하든 계약 값록 안이어야 한다. */
function 확정검사(area, tags) {
  if (!영역들.includes(area)) return { 거절: '영역을 골라 주세요', 칸: 'area' };
  const 목 = Array.isArray(tags) ? tags : [];
  if (목.length > 태그상한) return { 거절: `태그는 ${태그상한}개까지입니다`, 칸: 'tags' };
  const 본 = [];
  for (const t of 목) {
    if (!태그들.includes(t)) return { 거절: `모르는 오류태그: ${String(t).slice(0, 40)}`, 칸: 'tags' };
    if (!본.includes(t)) 본.push(t);
  }
  /* 🔑 강사가 태그를 **지우는** 것은 언제나 되고, 태그가 안 실리는 영역에 «다는» 것은 막는다 —
   *   막지 않으면 발음·태도 관찰이 텍스트 교정 축에 섞여 그 축의 집계가 못 쓰게 된다(§3). */
  if (본.length && !태그실리는영역.includes(area)) {
    return { 거절: `${area} 관찰에는 오류태그가 안 실립니다 — 비운 채 확정해 주세요`, 칸: 'tags' };
  }
  return { area, tags: 본 };
}

module.exports = {
  판정판, 영역들, 태그들, 태그실리는영역, 원문상한, 태그상한, 최대토큰,
  빈초안, 비었나, 지시문, 사용자글, 원문검사, 초안읽기, 초안지문, 고쳤나, 확정검사,
};
