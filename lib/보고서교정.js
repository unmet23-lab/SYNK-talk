/**
 * 보고서교정 — G2 「보고서 교정」의 순수 로직. **저장 0 · 서버 호출 0 · AI 호출 0.**
 *
 * ■ 무엇인가 (발주_게임모듈.md G2 §4 화면 흐름 · §6-2 보기 · §6-4 채점 판정)
 *   ① 문장을 **어절 단위 보기**로 가른다(학생이 탭할 수 있었던 자리 전부 = `options_shown`).
 *   ② 오류문↔기준 교정문에서 **심은 오류의 자리**(option_id)를 낸다.
 *   ③ 학생 제출을 **3갈래**로 즉시 판정한다(맞음 · 검수대기 · 자리틀림).
 *
 * ■ 🔴 저장하는 판정은 없다 — `is_correct` 를 만들지 않는다 (G2 §8 · C0 §4-1)
 *   자리 일치·교정문 일치는 `task_snapshot.정답` 과 `body_original` 이 있으면 **언제든 재계산되는
 *   파생**이다. 채점 규칙이 바뀌는 날 과거가 거짓말하지 않게, 이 파일의 산출은 화면 피드백까지고
 *   이벤트·payload 에 실리지 않는다(`lib/멘탈게이지` 와 같은 규약).
 *
 * ■ 🔴 「그 외 전부」는 «틀림»이 아니라 «검수대기»다 (§6-4 ③)
 *   `includes` 같은 부분일치로 느슨하게 통과시키면 **안 고친 답도 통과**하고, 완전일치로 오답
 *   처리하면 **정답과 다른 맞는 교정**(이 게임 최고급 데이터 · §5 A행)이 오답 통계에 묻힌다.
 *   두 극단 사이는 자동 판정이 아니라 사람이다. 그래서 이 파일은 부분일치 채점을 **소스 층에서**
 *   금지한다 — 그 문자열 호출은 0 이고 회귀가 전문에서 센다(`lib/멘탈게이지.js` 선례).
 *   멤버십·자리 비교는 전부 완전일치(`===`)나 배열 색인으로 한다.
 *
 * ■ 🔴 정답은 인자로 «받는다» — 이 파일이 팩을 열지 않는다
 *   `학생판게임스냅샷`(§6-8 · `lib/게임스냅샷.js`)이 G2 스냅샷에서 `정답` 을 벗기므로 **학생
 *   기기에는 정답이 없다.** 정답이 기기에 실리면 이 게임이 탐지 능력이 아니라 「정답을 봤나」를
 *   재게 된다(§9-③ 의 빠른 판). 그래서 `판정()` 은 `(선택자리, 교정문, 정답)` 을 인자로 받는
 *   모양이고 — 정답이 서버에서 오든, 배정 행에서 재계산되든, 뒷날 검수 결과로 오든 **이 함수는
 *   그대로 선다.** 어느 통로로 줄지는 2단계(화면) 커밋의 판정이고 여기서 풀지 않는다.
 *
 * ■ 문장부호 처리 규칙 (보기 조립)
 *   어절에 붙은 문장부호는 **그 어절의 일부로 둔다**(`있습니다.`·`교수님,`). 떼어내면 화면이
 *   보여 준 글자와 `options_shown[].label` 이 갈리고, 그 순간 「그날 학생에게 보인 것」의 기록이
 *   거짓이 된다(스냅샷은 불변이라 되짚을 길이 없다). 자르는 자리는 **공백뿐**이다.
 *
 * ■ 🔴 이 파일은 CJS 다 — 동봉 기전이 CJS 전용이다(`tests/동봉CJS.test.js`).
 */

/**
 * 문장을 어절로 가른다 — 자르는 자리는 공백뿐(문장부호는 어절에 붙어 남는다).
 * @returns {string[]|null} 재료가 아니거나 어절이 0이면 null.
 */
function 어절나누기(문장) {
  if (typeof 문장 !== 'string') return null;
  const 다듬은 = 문장.trim();
  if (다듬은 === '') return null;
  return 다듬은.split(/\s+/);
}

/**
 * 보기(`options_shown`)를 만든다 — 학생이 탭할 수 있었던 자리 **전부**.
 *
 * 🔑 `option_id` 는 자리 표기(`w1`,`w2`,…)라 **같은 문장은 언제나 같은 보기**다(결정적) —
 *   배정 행과 제출 행이 같은 조립을 지나야 `selected_option` 이 같은 것을 가리킨다(§6-8 규칙 4).
 * 🔴 이 목록이 빠지면 「이 자리를 짚었다」의 **분모가 사라진다**(§6-2 · L0 못박음) — 그래서
 *   조립기는 보기가 비면 스냅샷 자체를 안 만든다.
 *
 * @param {string} 오류문 화면에 뜬 문장(대조 문항의 멀쩡한 문장도 같다)
 * @returns {readonly {option_id:string,label:string}[]|null} 못 가르면 null.
 */
function 보기만들기(오류문) {
  const 어절들 = 어절나누기(오류문);
  if (!어절들) return null;
  return Object.freeze(어절들.map((label, i) => Object.freeze({
    option_id: `w${i + 1}`,
    label,
  })));
}

/**
 * 심은 오류의 자리를 낸다 — 오류문과 기준 교정문에서 **다른 그 한 어절**의 option_id.
 *
 * 판정 규칙(오류문 쪽이 기준이다): 앞뒤로 같은 어절을 벗기고 남은 것이 **오류문 쪽 정확히 1
 * 어절**이어야 한다. 교정문 쪽 남은 것은 1개(보통) · 2개 이상(띄어쓰기 교정) · 0개(불필요한
 * 어절 삭제) 어느 쪽이어도 된다 — 화면이 여는 입력칸이 «탭한 그 어절 하나»라, 학생이 그 칸에
 * 무엇을 쓰든(공백 포함·빈 값 포함) 바뀌는 것은 그 한 자리뿐이기 때문이다(G2 §4-4).
 *
 * 🔴 **아니면 `null` 이다 — 반쪽을 내지 않는다.** 어절이 옮겨 다니거나(어순) 없던 어절이
 *   끼어들면(누락) 「학생이 탭할 자리」가 없고, 그 문항은 이 게임이 표현할 수 없는 문항이다.
 *   팩 회귀가 이 함수로 전 문항을 기계 검사한다 — 못 잡으면 그 문항은 화면에서 **정답 자리가
 *   없는 채로** 배정되고, 증상은 「아무 데를 짚어도 자리틀림」뿐이다.
 *
 * @param {string} 오류문
 * @param {string} 교정문 기준 교정문
 * @param {readonly {option_id:string}[]} 보기 그 오류문의 `보기만들기` 산출
 * @returns {string|null} option_id.
 */
function 오류자리찾기(오류문, 교정문, 보기) {
  const 오류어절 = 어절나누기(오류문);
  const 교정어절 = 어절나누기(교정문);
  if (!오류어절 || !교정어절) return null;
  if (!Array.isArray(보기) || 보기.length !== 오류어절.length) return null;

  const 짧은쪽 = Math.min(오류어절.length, 교정어절.length);
  let 앞 = 0;
  while (앞 < 짧은쪽 && 오류어절[앞] === 교정어절[앞]) 앞 += 1;
  let 뒤 = 0;
  while (뒤 < 짧은쪽 - 앞
    && 오류어절[오류어절.length - 1 - 뒤] === 교정어절[교정어절.length - 1 - 뒤]) 뒤 += 1;

  if (오류어절.length - 앞 - 뒤 !== 1) return null;
  const 자리 = 보기[앞];
  if (!자리 || typeof 자리.option_id !== 'string' || 자리.option_id === '') return null;
  return 자리.option_id;
}

/**
 * 학생이 낸 **문장 전문**을 만든다 — 짚은 어절 한 자리만 학생 글로 갈고 나머지는 그대로.
 *
 * 🔴 왜 화면이 아니라 여기인가 — `body_original` 은 **그 어절만 바꾼 문장 전문**이고(§5 A행),
 *   그 조립을 화면이 손으로 하면 「행에 적힌 문장」과 「학생이 본 문장」을 잇는 규칙이 화면마다
 *   다시 지켜져야 한다. 재료도 여기 것이다 — 보기(`보기만들기`)가 곧 어절 목록이라, 화면이
 *   원문을 다시 자르면 자르는 규칙이 두 벌이 된다(공백 하나가 갈리는 날 자리가 밀린다).
 * 🔑 빈 입력·여러 어절 입력을 **막지 않는다**(`오류자리찾기` 머리말과 한 쌍): 지우는 교정
 *   (`중복:불필요`)과 띄어쓰기 교정이 그 모양이고, 그때 남는 이중 공백은 아래 `정규화` 가 접는다.
 * 🚫 여기서 정규화하지 않는다 — `body_original` 은 **학생이 낸 그대로**여야 한다(정규화는 대조
 *   시점의 판정이지 저장 시점의 가공이 아니다 · 「원문은 절대 갱신하지 않는다」).
 *
 * @param {readonly {option_id:string,label:string}[]} 보기 그 문항의 `보기만들기` 산출
 * @param {string} 고른것 짚은 자리의 option_id
 * @param {string} 입력 학생이 그 칸에 쓴 글
 * @returns {string|null} 목록 밖 자리·못 쓸 재료면 null(= 제출을 안 만든다).
 */
function 교정문만들기(보기, 고른것, 입력) {
  if (!Array.isArray(보기) || 보기.length === 0) return null;
  if (typeof 고른것 !== 'string' || 고른것 === '') return null;
  if (typeof 입력 !== 'string') return null;
  let 찾음 = false;
  const 어절들 = [];
  for (const 칸 of 보기) {
    if (!칸 || typeof 칸.option_id !== 'string' || typeof 칸.label !== 'string') return null;
    if (칸.option_id === 고른것) { 찾음 = true; 어절들.push(입력); } else 어절들.push(칸.label);
  }
  if (!찾음) return null; // 보기 밖 자리 — 지어내지 않는다(`선택로그` 가 접는 그 자리와 한 축)
  return 어절들.join(' ');
}

/**
 * 정규화 — **정확히 셋만** 한다 (§6-4 ②: 앞뒤 공백 제거 · 연속 공백 1칸 · 종결 마침표 유무 무시).
 *
 * 🔴 그 이상 하지 않는다. 더 느슨하면(조사 무시·문장부호 전부 제거 따위) **안 고친 답도 통과**해
 *   이 게임이 재려던 것이 안 재진다. 반대로 이 셋조차 안 하면 「고친 내용은 같은데 공백 하나가
 *   다른」 답이 검수 큐로 밀려 사람 손이 늘어난다 — 규칙 ③(99% 자동화)의 실측 비용이다.
 * 🔑 「연속 공백 1칸」은 장식이 아니다 — 불필요한 어절을 지우는 교정(`중복:불필요`)에서 입력칸을
 *   비우면 그 자리에 공백 둘이 남는다. 그 정상 동작을 여기서 흡수한다.
 * ⚠ `?`·`!` 는 건드리지 않는다 — 종결 «마침표»만이 규칙이고, 물음표는 뜻을 바꾸는 글자다.
 *
 * @returns {string|null} 재료가 아니면 null.
 */
function 정규화(문장) {
  if (typeof 문장 !== 'string') return null;
  return 문장.trim().replace(/\s+/g, ' ').replace(/\.$/, '').trim();
}

/**
 * 학생 제출을 판정한다 — **화면 피드백 전용**(저장 0 · §6-4).
 *
 * @param {object} 재료
 * @param {string|null} 재료.선택자리 학생이 짚은 option_id. **없으면 「고칠 곳 없음」**
 *        (= payload `rejected_all: true` 의 같은 사실 · 화면 상태 하나에서 둘 다 파생한다).
 * @param {string} [재료.교정문] 학생이 낸 **문장 전문**(`body_original` — span 만 아니다).
 * @param {{교정문:string, 오류자리:string}} [재료.정답] 심은 오류의 기준.
 *        **대조 문항에는 이 키가 없다**(§6-8 규칙 1 — `null` 을 넣지 않는다).
 * @returns {'맞음'|'검수대기'|'자리틀림'|null} 재료가 못 쓸 모양이면 null(반쪽 판정 금지).
 *
 * 갈래:
 *   ⓐ 대조 문항(`정답` 없음) — 「고칠 곳 없음」이면 **맞음**, 짚었으면 **자리틀림**(멀쩡한 문장을
 *      건드렸다 = 과잉 교정). 이 한 칸이 §9-③ 의 유일한 조기 경보 재료다.
 *   ⓑ 자리가 다르거나 안 짚었다 → **자리틀림**. 자리 비교는 option_id **문자열 완전일치**다
 *      (라벨 문자열로 비교하지 않는 이유가 이것이다 — 부분일치가 낄 여지 자체가 없다).
 *   ⓒ 자리는 맞고 교정문이 정규화 후 완전일치 → **맞음**.
 *   ⓓ 자리는 맞았는데 글이 다르다 → **검수대기**. 🔴 「틀림」이 아니다. 여기 떨어지는 것이
 *      **정답과 다른 맞는 교정**이고, 즉석에서 오답 처리하면 그 데이터를 죽인다(§4 피드백 문면
 *      「선생님이 보고 알려줄게」). 안 고치고 낸 답도 여기 떨어진다 — 가르는 것은 사람이다.
 */
function 판정(재료) {
  if (!재료 || typeof 재료 !== 'object' || Array.isArray(재료)) return null;
  const { 선택자리, 교정문, 정답 } = 재료;

  const 안짚음 = 선택자리 === undefined || 선택자리 === null;
  const 짚었나 = typeof 선택자리 === 'string' && 선택자리 !== '';
  if (!안짚음 && !짚었나) return null; // 자리가 문자열도 「없음」도 아니다 — 못 읽는 재료다

  /* ⓐ 대조 문항 — `정답` 키 자체가 없다(있는데 null 인 모양은 팩·조립기가 만들지 않는다). */
  if (정답 === undefined) return 짚었나 ? '자리틀림' : '맞음';
  if (!정답 || typeof 정답 !== 'object' || Array.isArray(정답)) return null;

  const { 오류자리, 교정문: 기준교정문 } = 정답;
  if (typeof 오류자리 !== 'string' || 오류자리 === '') return null;
  if (typeof 기준교정문 !== 'string' || 기준교정문.trim() === '') return null;

  if (!짚었나 || 선택자리 !== 오류자리) return '자리틀림'; // ⓑ
  if (typeof 교정문 !== 'string') return null; // 짚었는데 낸 글이 없다 — 화면이 못 만드는 모양
  return 정규화(교정문) === 정규화(기준교정문) ? '맞음' : '검수대기'; // ⓒ / ⓓ
}

/* ── SQL 그림자 — 「맞음」을 «AI 교정 앞단»에서 거른다 (강사_반단위_피드백_설계 §7) ──────
 *
 * ■ 무엇을 막나. 정답대로 고친 문장을 AI 에게 「고쳐 달라」고 보내면 벤더는 **무언가를 만들어
 *   낸다**. 그 행이 골든 풀에 들고(`lib/골든표본.풀술어` 는 `actor_kind='ai'` + 빈 카드 아님,
 *   그뿐이다), 뽑히면 강사가 「①원문이 이미 맞다 = 과교정」을 누른다. 그래서 M2 §5 가
 *   **「21/21≠100%」 실패모드를 상시 감시하려고** 세운 과교정률이 **G2 정답 문장 때문에**
 *   나빠진 것처럼 보인다. 덤으로 벤더 호출이 그만큼 돈다.
 *
 * ■ 왜 «앞단»인가. 큐 조회 시점에 내리면 이미 둘이 벌어져 있다(AI 행이 생겼고 풀에 들었다).
 *   앞단에 서면 새 표 0 · 새 열 0 · 새 상태값 0 이다 — 검수 큐의 AI 조인이 inner 라
 *   (`review_queue`) **AI 행이 안 생기면 큐가 알아서 뺀다.**
 *   🚫 `pipeline_jobs.status` 를 새 값으로 옮기지 않는다 · 🚫 `discarded` 재사용(폐기 통계 오염).
 *
 * ■ 🔴 왜 술어가 «여기» 사는가 — 판정이 두 벌이 되는 자리다.
 *   판정 정본은 위 `판정()` 인데 `correct` 의 `대기조건()` 은 SQL 조각이다. SQL 에 손으로 다시
 *   적으면 그게 두 번째 정본이고, 갈리는 날 증상은 「어떤 맞음은 걸러지고 어떤 맞음은 안
 *   걸러진다」라 **아무 데도 안 남는다.** 그래서 술어 «텍스트»를 이 파일이 내보내고 소비자가 그
 *   하나를 끼운다 — `lib/동의게이트.지금유효술어`·`lib/골든표본.풀술어` 와 같은 선례이고,
 *   `tests/보고서교정.test.js` 가 소비자 소스에 이 텍스트가 실제로 담겼는지 기계로 대조한다.
 *   🚫 `sql.unsafe` 로 태그 질의에 끼워 넣지 않는다 — 런타임에서 깨지면 수집이 멈춘다.
 */

/**
 * `정규화()` 의 SQL 판 — **같은 셋을 같은 순서로** 한다(§6-4 ②).
 *
 * 🔑 순서가 규칙이다: 앞뒤 공백 → 연속 공백 1칸 → 종결 마침표 → **다시 앞뒤 공백**. 마지막
 *   `btrim` 이 빠지면 `"안녕 ."` 이 `"안녕 "` 으로 남아 `"안녕"` 과 안 같아진다(JS 쪽 끝의
 *   `.trim()` 이 바로 그 자리다).
 *
 * 🔴 **백슬래시를 한 개도 쓰지 않는다 — `\s` 가 아니라 `[[:space:]]`, `\.` 가 아니라 `[.]`.**
 *   이 텍스트는 층을 셋 지난다: 이 파일의 JS 문자열 → 소비자의 **TS 템플릿 리터럴** → SQL
 *   문자열 리터럴. 가운데 층이 급소다 — 템플릿 리터럴에서 `\s` 는 «정의되지 않은 이스케이프»라
 *   조용히 `s` 로 접히고, 그러면 SQL 에 `'s+'` 가 박혀 **「공백 정규화」가 「s 정규화」가 된다.**
 *   증상은 문법 오류가 아니라 「어떤 맞음은 안 걸러진다」뿐이라 아무 데도 안 남는다. POSIX
 *   문자 클래스는 백슬래시가 없어 세 층 어디서도 뜻이 안 바뀌고, PostgreSQL 에서 `\s`·`\.` 와
 *   각각 같은 것을 가리킨다. 회귀가 이 파일과 소비자 양쪽에서 백슬래시 0 을 센다.
 *
 * ⚠ **`[[:space:]]` 의 뜻이 JS 의 `\s` 와 정확히 같지는 않다.** JS 는 유니코드 공백을 널리 담고
 *   (U+00A0·U+3000·U+FEFF …), PostgreSQL 쪽은 로케일이 정하는 좁은 집합이다. 즉 **SQL 쪽이
 *   좁거나 같다.** 갈리는 날 SQL 은 「다르다」로 읽어 그 행을 AI 로 보낸다 — §7 이 정한 안전
 *   방향(모르면 AI 로 보낸다)과 같은 쪽이라 새도 사고가 아니라 낭비다. 반대 방향(SQL 이 더
 *   넓게 봐서 «안 고친 답»까지 맞음으로 걸러 버리는 것)은 이 포함 관계상 생기지 않는다.
 *   🔴 이것은 **문자 집합의 포함 관계로 세운 정적 근거이고 DB 실측이 아니다** — 실왕복은
 *   설계 §8-5 몫이고, 그 전에는 「쟀다」고 쓰지 않는다.
 *
 * ⚠ 넷째 정규화를 얻는 날 이 함수도 같이 오른다 — 결속 회귀가 그걸 진다.
 *
 * @param {string} 열식 정규화할 SQL 식(열 이름·`->>` 추출식)이 그대로 박힌다.
 */
function 정규화식(열식) {
  return `btrim(regexp_replace(regexp_replace(btrim(${열식}), '[[:space:]]+', ' ', 'g'), '[.]$', ''))`;
}

/**
 * 「맞음」 술어 — 이 조건이 참인 `submissions` 행은 **AI 교정을 건너뛴다**.
 *
 * ⚠ 별칭 둘을 전제한다 — `s` = `engine.submissions` · `e` = `engine.learning_events`.
 *   자리는 payload 에, 글과 정답은 submission 에 있어 술어가 표 하나에 살 수 없다.
 *   `대기조건()`(`functions/correct`)이 이미 그 두 이름으로 조인한다.
 *
 * 세 마디가 각각 무엇을 지는가 — 위 `판정()` 의 갈래와 1:1 이다:
 *   ① **`정답` 키가 있는 행만 대상**이다. 대조 문항은 키 자체가 없고(§6-8 규칙 1), 발화 녹음·
 *      G1·번역 따위는 애초에 이 모양이 아니다. 없으면 술어가 거짓 → 그 행은 **그대로 AI 로
 *      간다**(빠지는 쪽이 아니라 남는 쪽이 기본값이다).
 *   ② **자리** = `판정()` ⓑ. `selected_option` 은 짚음 갈래 payload 에 «항상» 있다
 *      (`보고서교정제출.선택로그` 가 자리 없는 지목은 조립 자체를 접는다).
 *   ③ **글** = `판정()` ⓒ. `body_original` «만» 본다 — `transcript` 를 안 보므로 발화 녹음
 *      제출은 이 술어에 걸릴 길이 없다(대기조건의 `coalesce` 와 일부러 다르다).
 *
 * 🔴 `판정()` 의 ⓐ(대조 문항 「고칠 곳 없음」)는 여기 없다 — 그 갈래는 `quiz.answered` 라
 *   이 술어가 붙는 질의(correct `대기조건`)가 `event_type='submission.created'` 조인으로
 *   애초에 그 행을 안 집는다. ⚠08-24 실측 정정: `submissions` **행 자체는 생긴다** —
 *   `무산출사건` 이 submission 칸을 싣고 events Fn 이 행을 만든다. 「안 생긴다」로 적으면
 *   그 행을 세는 다음 소비자(복습 파생층 등)가 「없어야 정상」으로 오독한다. 술어에 ⓐ를
 *   적으면 **영영 거짓인 마디**가 하나 늘고, 읽는 사람은 그것이 무언가를 막는다고 믿는다.
 *
 * 🚫 느슨하게 열지 않는다 — 느슨하면 **안 고친 답까지 AI 를 건너뛰어** 진짜 오류가 아무에게도
 *   안 간다. 새는 방향이 「통과」인 자리라 좁게 연다.
 */
const 맞음술어 = `s.task_snapshot -> '정답' ->> '교정문' is not null
       and e.payload ->> 'selected_option' = s.task_snapshot -> '정답' ->> '오류자리'
       and ${정규화식('s.body_original')}
         = ${정규화식("s.task_snapshot -> '정답' ->> '교정문'")}`;

module.exports = { 어절나누기, 보기만들기, 오류자리찾기, 교정문만들기, 정규화, 판정, 정규화식, 맞음술어 };
