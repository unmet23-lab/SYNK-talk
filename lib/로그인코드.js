'use strict';
/**
 * 로그인 코드 — 표기형 ↔ 정규형 변환의 **유일한 자리** (L0 §4-1·§4-2)
 *
 * 왜 lib 인가 — §4-2 가 못박은 그대로다: **앱과 발급 도구가 같은 함수 하나를 공유한다.**
 *   두 곳에 적으면 갈라지고, 갈라졌을 때 증상은 「로그인이 안 된다」뿐이라 원인이 안 보인다.
 *   실전에서 깨지는 자리가 정확히 두 줄이다 — **이메일은 소문자 · 비밀번호는 대문자.**
 *
 * ⛔ 여기에 코드 **생성**은 없다. 생성은 `tools/로그인코드발급.js` 만 한다:
 *   ① 앱은 코드를 만들 일이 없다(학원이 발급한다) ② 난수 API 가 런타임마다 달라
 *   여기 두면 앱 번들이 깨진다. 이 파일은 순수 문자열 함수뿐이라 RN·Node 양쪽에서 돈다.
 *
 * 🔴 평문 코드는 우리 표에 적지 않는다(§4-1) — 사는 곳은 `auth.users` 뿐이다.
 */

/** `I·O·0·1` 제외 32자 — 학생이 손으로 옮겨 적는다(§4-1). */
const 집합 = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
const 길이 = 8;
/** RFC 2606 예약 TLD — 어떤 메일도 실제로 배달될 수 없다. 2026-08-06 Supabase 수용 실측 완료. */
const 도메인 = '@synk.invalid';

/**
 * 표기형·오타 섞인 입력 → **정규형**(하이픈·공백 제거 + 대문자).
 * 인증에 실제로 쓰는 유일한 형태다. 앱은 입력받는 즉시 이걸 통과시킨다.
 */
function 정규형(입력) {
  return String(입력 == null ? '' : 입력).replace(/[\s\-–—]/g, '').toUpperCase();
}

/** 정규형 → **표기형**(4자마다 하이픈). 학생에게 보여주고 인쇄하는 형태. */
function 표기형(코드) {
  const n = 정규형(코드);
  return n.length === 길이 ? `${n.slice(0, 4)}-${n.slice(4)}` : n;
}

/** 규격에 맞나 — 길이 8 · 허용 문자만. **애매하면 false**(막히는 방향이 안전하다). */
function 형식맞나(입력) {
  const n = 정규형(입력);
  return n.length === 길이 && Array.prototype.every.call(n, (c) => 집합.indexOf(c) !== -1);
}

/** 정규형 → 합성 이메일. **소문자**다 — Supabase 가 이메일을 소문자로 저장한다. */
function 이메일(코드) {
  return 정규형(코드).toLowerCase() + 도메인;
}

/** 정규형 → 비밀번호. **대문자 그대로**다 — 비밀번호는 대소문자를 구분한다. */
function 비밀번호(코드) {
  return 정규형(코드);
}

module.exports = { 집합, 길이, 도메인, 정규형, 표기형, 형식맞나, 이메일, 비밀번호 };
