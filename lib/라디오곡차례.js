/* 라디오 «곡»의 차례 — 어떤 결을 어떤 순서로 트나. (유호 확정 2026-09-02)
 *
 *   「한 장르 쭉 하고 한 장르 쭉 하고 이렇게 해야할것같아. 장르마다 마스코트를 변경하면 될것같고」
 *
 * ⚠ **`lib/라디오편성.js` 와 다른 파일이다 — 합치지 말 것.**
 *   그쪽(편성 «가중»)은 **퀴즈 문항**을 어떻게 추첨하나(§4-5 집단 되돌림)이고,
 *   이쪽은 **음악 트랙**을 어떤 차례로 트나다. 이름이 닮아서 09-02 에 실제로
 *   덮어쓰는 사고가 났다(회귀가 `추첨가중 is not a function` 으로 잡았다).
 *
 * ■ 왜 lib 으로 뺐나 — 순서를 «파일 이름»이 쥐고 있었다.
 *   재생목록이 `.sort()` 로 이름순만 냈다. 그래서 곡을 더하면(09·10) 그 곡이 제 블록 뒤가
 *   아니라 **목록 맨 끝**에 붙어 시티팝 블록이 둘로 쪼개진다 — 방송에서는 마스코트가
 *   한 곡만 잠깐 바뀌었다 되돌아오는 모양이 된다. 블록을 지키려면 팩 전체를 다시 번호
 *   매겨야 했고, 그러면 .ts·크레딧 장부·목록이 전부 딸려 온다.
 *   ⇒ 순서의 주인을 이름에서 여기로 옮긴다. 번호는 «언제 만들었나»만 뜻하고,
 *     «언제 나가나»는 이 파일이 정한다. 곡을 더할 때 아무것도 다시 이름 짓지 않는다.
 *
 * ■ 그리고 «한 값을 두 곳» 하나를 함께 없앴다 — `결ascii`·`결차례` 가
 *   `tools/라디오곡생산.js` 안에만 살았고, 배경을 고르는 `bots/송출/인코딩.sh` 와
 *   재생목록은 그것을 모른 채 각자 이름 규칙을 짐작하고 있었다.
 *
 * ■ 결↔마스코트는 여기서 안 정한다 — 그림은 형제 저장소(`SYNK-appsscript`
 *   `tools/라디오배경굽기.js` 의 `장르들`)가 쥔다. 여기는 «소리의 차례»만 안다.
 */

/** 결 이름(한글) → 파일에 박히는 ascii. 🔑 파일 이름은 ASCII 만 — 셸·ffmpeg 를 건너간다. */
/* 🆕 2026-09-05 — 셋에서 일곱으로. 형제 저장소가 무대 일곱 장을 4K 로 굽고 배경까지 합성했는데
 *   (`SYNK-appsscript` `tools/라디오배경굽기.js` 의 `장르들`) 이 목록이 셋이라 그 넷이 방송에
 *   닿지 못하고 있었다. 유호 지시 09-05 「무대 넷도 배경으로 이어줘」 → 「방송 쪽 셋도 이어줘」.
 *   ⚠ 이름(한글)은 그림 쪽 `장르들[키].이름` 과 «글자까지 같게» 맞춘다 — 갈리면 로그에서
 *     같은 결이 두 이름으로 보인다. 그림이 정본이고 여기는 그것을 따른다. */
const 결ascii = {
  시티팝: 'citypop', 차분: 'calm', 전자: 'house',
  도시: 'city', 드림하늘: 'dream_sky', 드림물: 'dream_water', 드림들판: 'dream_field',
};
const ascii결 = Object.fromEntries(Object.entries(결ascii).map(([k, v]) => [v, k]));

/** 방송에서 블록이 도는 차례. 앞의 결을 다 틀고 다음 결로 넘어간다(그때 마스코트가 바뀐다).
 *  🔑 차례는 «하루의 빛»을 따라간다 — 노을(citypop) → 저녁 도시(city) → 밤 호수(calm) →
 *    꿈 셋(하늘·물·들판) → 새벽 네온 항구(house). 블록이 넘어갈 때 화면이 저절로 바뀌므로
 *    이 순서가 곧 «밤새 밝기가 흐르는 모양»이다.
 *  🔑 곡이 없는 결은 `차례세우기` 가 블록에서 뺀다 — 그래서 여기 미리 적어 두어도 화면이 안 깨진다. */
const 블록차례 = ['citypop', 'city', 'calm', 'dream_sky', 'dream_water', 'dream_field', 'house'];

/** 생산할 때 결을 뽑는 차례 — 한 번 실행에서 블록이 이 모양으로 나온다.
 *  🔴 **여기는 09-05 에 «일부러» 안 늘렸다.** 이 배열을 늘리면 다음 생산에서 그 결의 곡이
 *    실제로 만들어지고 돈이 나간다. 목록을 넓히는 일(위 둘)과 곡을 사는 일은 다른 결정이라,
 *    새 넷은 유호님이 「그 장르 곡도 만들자」고 부르실 때 여기 더한다. */
const 결차례 = ['시티팝', '시티팝', '시티팝', '차분', '차분', '차분', '전자', '전자'];

/** `synk-radio-07-house-air.ts` → `{ 번호: 7, 결: 'house', 이름: '전자' }` · 못 읽으면 null.
 *  🔴 밑줄을 읽는다(09-05). 그 전 `[a-z]+` 는 `dream_sky` 를 통째로 못 잡아 드림코어 셋이
 *    «모르는 결»로 밀려났다 — 조용히 버리진 않지만(맨 뒤로 간다) 제 블록에는 영영 못 든다.
 *    같은 병이 `bots/송출/인코딩.sh` 의 배경 고르기에도 있었고 그날 같이 고쳤다. */
function 트랙읽기(파일) {
  const m = /^synk-radio-(\d+)-([a-z][a-z0-9_]*)-air\.[a-z0-9]+$/i.exec(파일);
  if (!m) return null;
  return { 번호: parseInt(m[1], 10), 결: m[2], 이름: ascii결[m[2]] || m[2] };
}

/**
 * 파일 목록을 «방송 차례»로 세운다 — 블록차례 순, 블록 안에서는 번호 순.
 * 🔑 못 읽는 이름·모르는 결도 **버리지 않는다**(맨 뒤로 이름순). 조용히 빠지면
 *   「목록이 짧아진 것」을 아무도 못 본다 — 자막 없는 누락은 0건을 성공 얼굴로 만든다.
 * @returns {{차례: string[], 블록: {결:string, 이름:string, 트랙:string[]}[], 모름: string[]}}
 */
function 차례세우기(파일들) {
  const 읽힌 = [];
  const 모름 = [];
  for (const f of 파일들) {
    const t = 트랙읽기(f);
    if (t && 블록차례.includes(t.결)) 읽힌.push({ ...t, 파일: f });
    else 모름.push(f);
  }
  모름.sort();

  const 블록 = [];
  for (const 결 of 블록차례) {
    const 트랙 = 읽힌.filter((t) => t.결 === 결).sort((a, b) => a.번호 - b.번호).map((t) => t.파일);
    if (트랙.length) 블록.push({ 결, 이름: ascii결[결] || 결, 트랙 });
  }
  const 차례 = [...블록.flatMap((b) => b.트랙), ...모름];
  return { 차례, 블록, 모름 };
}

module.exports = { 결ascii, ascii결, 블록차례, 결차례, 트랙읽기, 차례세우기 };
