/* 라디오 시즌 편성 — TOPIK 디데이가 편성을 «자동으로» 기울이는 달력층 (발전 트랙 ⑨ · 유호 확정 08-14)
 *
 * ■ 무엇을 하나
 *   시험 D-N 진입을 달력이 판정하고, 그 기간엔 링크 집단의 취약 skill 로 라운드 후보를
 *   한정한다(«시험 2주 전 집중 편성»). 새 부품 최소 — 가중은 `라디오편성`, 추첨은
 *   `라디오라운드`를 그대로 재사용하고, 이 파일은 «언제·어느 축»만 정한다.
 *
 * ■ 경계
 *   · DB·시계를 안 읽는다 — 오늘·시험일 전부 인자다(안에서 현재 시각을 읽으면 회귀가
 *     돌린 날에 따라 갈린다 — `라디오편성` 머리말과 같은 규약).
 *   · 시험일 데이터는 운영 설정의 몫이다(여기 상수로 박지 않는다 — 몽골 TOPIK 일정은
 *     해마다 바뀌는 외부사실이라 코드에 박는 순간 낡는다). 배선은 라운드 생성기 Fn 과
 *     한 벌(P3 · ⛔채널 게이트 뒤) — 그 전까지 이 층의 게이트 ④는 「닿았나 ✗」다.
 *   · 개인 단위 입력 칸이 없다 — 재료는 집단 합산 요약뿐(§3 철칙 · §8).
 *   · **재도전 짝이 시즌보다 세다** — 부르는 쪽이 이미 `축한정`(같은 skill 재도전)을 줬으면
 *     시즌은 손대지 않는다. 계약 축(retry_of_round_id)을 연출 축이 밀어내면 안 된다.
 *
 * ■ 틀릴 때의 모습 · 대가 (새 장치 조항)
 *   시험일 오타는 시즌을 «조용히» 안 서게 만든다 — 그래서 못 읽은 시험일을 버리지 않고
 *   `무시`로 세어 돌려준다(부르는 쪽이 로그로 드러낸다 · F207 분모 규약).
 *   닫는 것: 없음 — 신설 층(기존 편성엔 달력 축 자체가 없었다).
 */
'use strict';

const { 표본하한 } = require('./라디오편성.js');
const { 라운드선정 } = require('./라디오라운드.js');

const 시즌판 = 'radio-season.v1';

/** D-이 값 이하부터 시즌 — P6 첫 2주 실측 뒤 재조정 자리. */
const 진입기본 = 14;

/** 집중축 상한 — 축을 너무 좁히면 팩이 마른다(후보 0 → 폴백만 돈다). */
const 집중상한기본 = 3;

const 날짜꼴 = /^\d{4}-\d{2}-\d{2}$/;
const 하루 = 86400000;

/* 'YYYY-MM-DD' → UTC 자정 ms. 시각·시간대를 안 섞는 이유: 날짜 문자열끼리의 차이만 쓰면
 * 서버 시간대가 어디든 디데이가 같다(부르는 쪽이 «울란바토르 기준 오늘»을 만들어 준다). */
function 날짜ms(s) {
  if (typeof s !== 'string' || !날짜꼴.test(s)) return null;
  const t = Date.parse(s + 'T00:00:00Z');
  return Number.isFinite(t) ? t : null;
}

/**
 * 시즌 판정. 재료 = { 오늘: 'YYYY-MM-DD', 시험일들: ['YYYY-MM-DD'], 진입일수? }
 * 반환 = { 시즌: { 시험일, 디데이 } | null, 무시: [원소] }
 *   — 지난 시험은 건너뛰고 «다가오는 첫 시험»만 본다. 못 읽은 원소는 `무시`에 담는다.
 */
function 시즌판정(재료) {
  const { 오늘, 시험일들 = [], 진입일수 = 진입기본 } = 재료 || {};
  const 기준 = 날짜ms(오늘);
  if (기준 == null) throw new TypeError("시즌판정: 오늘은 'YYYY-MM-DD' 여야 한다");
  if (!Number.isFinite(Number(진입일수)) || Number(진입일수) < 0) {
    throw new TypeError('시즌판정: 진입일수는 0 이상 숫자여야 한다');
  }

  const 무시 = [];
  let 다음 = null;
  for (const 원소 of Array.isArray(시험일들) ? 시험일들 : []) {
    const t = 날짜ms(원소);
    if (t == null) { 무시.push(원소); continue; }
    const 디데이 = Math.round((t - 기준) / 하루);
    if (디데이 < 0) continue; // 지난 시험
    if (!다음 || 디데이 < 다음.디데이) 다음 = { 시험일: 원소, 디데이 };
  }

  const 시즌 = 다음 && 다음.디데이 <= Number(진입일수) ? 다음 : null;
  return { 시즌, 무시 };
}

/**
 * 집단 취약 축 — `라디오편성.승격요약(...).요약` 에서 오답률 상위 skill 을 뽑는다.
 * 표본하한 미만·오답 0 은 뺀다(하한은 `라디오편성` 것 하나를 그대로 쓴다 — 두 곳에 적으면
 * 갈라진다). 동률은 skill id 사전순 — 입력 순서에 기대면 같은 재료가 날마다 다른 축을 낸다.
 */
function 집중축(재료) {
  const { 승격요약 = {}, 상한 = 집중상한기본 } = 재료 || {};
  const n = Number(상한);
  if (!Number.isFinite(n) || n < 1) throw new TypeError('집중축: 상한은 1 이상 숫자여야 한다');
  return Object.entries(승격요약 || {})
    .map(([skill, 셈]) => {
      const 응답 = Number(셈 && 셈.응답);
      const 오답 = Number(셈 && 셈.오답);
      if (!Number.isFinite(응답) || !Number.isFinite(오답) || 응답 < 표본하한 || 오답 <= 0 || 오답 > 응답) return null;
      return { skill, 오답률: 오답 / 응답 };
    })
    .filter(Boolean)
    .sort((a, b) => (b.오답률 - a.오답률) || a.skill.localeCompare(b.skill))
    .slice(0, n)
    .map((x) => x.skill);
}

/**
 * 시즌을 아는 라운드 선정 — 라운드 생성기가 부를 «하나뿐인 문».
 *
 * 재료 = 라운드선정 재료 + { 오늘, 시험일들, 진입일수?, 집중상한? }
 * 반환 = { ...라운드선정 반환(또는 결과: null), 시즌판, 시즌, 시즌축한정, 사유, 무시 }
 *   사유: '재도전우선' | '시즌아님' | '표본부족' | '시즌적용' | '시즌팩없음→평소' — 분모 규약(F207):
 *   시즌이 «안» 기운 라운드에도 왜 안 기울었는지가 남는다.
 */
function 시즌라운드선정(재료) {
  const { 오늘, 시험일들, 진입일수, 집중상한, 승격요약 = {}, ...나머지 } = 재료 || {};
  const { 시즌, 무시 } = 시즌판정({ 오늘, 시험일들, 진입일수 });

  const 재도전중 = Array.isArray(나머지.축한정) && 나머지.축한정.length > 0;
  let 시즌축 = null;
  let 사유;
  if (재도전중) 사유 = '재도전우선';
  else if (!시즌) 사유 = '시즌아님';
  else {
    const 축 = 집중축({ 승격요약, 상한: 집중상한 ?? 집중상한기본 });
    if (!축.length) 사유 = '표본부족';
    else { 시즌축 = 축; 사유 = '시즌적용'; }
  }

  let 결과 = 라운드선정({ ...나머지, 승격요약, 축한정: 재도전중 ? 나머지.축한정 : 시즌축 });
  if (!결과 && 시즌축) {
    /* 팩에 취약 축 문항이 (제외까지 빼고) 없다 — 라운드를 결번내는 것보다 평소 편성이 낫다.
     * 폴백을 여기 두는 이유: 부르는 쪽마다 폴백을 짜게 하면 하나는 빠뜨리고, 그 증상은
     * 시험 2주 전에만 나는 결번이라 아무도 원인을 못 찾는다. */
    결과 = 라운드선정({ ...나머지, 승격요약, 축한정: null });
    사유 = '시즌팩없음→평소';
    시즌축 = null;
  }

  return { ...(결과 || { 결과: null }), 시즌판, 시즌, 시즌축한정: 시즌축, 사유, 무시 };
}

module.exports = { 시즌판, 진입기본, 집중상한기본, 시즌판정, 집중축, 시즌라운드선정 };
