/**
 * 모르는 `--` 플래그를 거절하는 **공용 판정** — 도구마다 목록은 다르고, 판정은 하나다.
 *
 * 🔴 왜 공용이어야 하나 (실사건 넷 · 전부 「새는 방향이 통과」):
 *   F400(배포대조·읽기) → F435(원격SQL·읽기) → F436(원격SQL·쓰기) → 그리고 2026-08-14 실측:
 *   `--운영` 을 받을 수 있는 도구 **11개 중 die 하는 것은 1개**뿐이었다(배포대조). 나머지 열은
 *   모르는 낱말을 조용히 흘린다 — `--진단` 을 원격SQL 에 치면 오류 없이 무시되고, 사람은
 *   자기가 부탁한 일이 된 줄 안다. **조준**(`--운영` 이 과녁을 갈아타는 것)은 F436 이
 *   `lib/자격증명.js 읽기()` 로 이미 공용화했다. 이 파일은 **나머지 절반**을 진다.
 *
 * 🔑 왜 「목록」이 아니라 「판정」만 공용인가: 도구마다 아는 낱말이 다르다. 목록을 여기서 세면
 *   멀쩡한 인자가 죽는다(`lib/자격증명.js` 가 F400 처방 ①을 자기 파일에 못 올린 바로 그 이유).
 *   그래서 공용으로 두는 것은 ⓐ판정 ⓑ**어느 도구에서든 뜻을 갖는 낱말 목록**(`공용플래그`) 둘뿐이고,
 *   도구는 자기 낱말에 그것을 펴 넣는다: `const 아는플래그 = [...공용플래그, '--적용'];`
 *
 * ⚠ 이 장치가 틀릴 때의 모습 = **거짓양성**이다(맞는 얼굴로 틀린 값 · CLAUDE.md 맹점 ④).
 *   선언 목록에서 낱말 하나를 빠뜨리면 되던 명령이 죽고, 그건 따를 수 없는 처방이 된다(F103).
 *   그래서 `tests/플래그게이트.test.js` 가 **소스에 실제로 쓰이는 `--낱말` 전량을 선언이 덮는지**
 *   기계로 센다 — 사람이 목록을 손으로 맞추는 자리를 안 남긴다.
 *
 * ⚠ 값을 받는 낱말(`--학생 홍길동`)의 **값** 쪽은 여기서 안 본다 — `--` 로 시작하지 않으므로
 *   애초에 이 검사에 안 걸린다. `--키=값` 꼴은 이 저장소가 안 쓴다(2026-08-14 전수 실측).
 */
'use strict';

/** 어느 도구에서든 뜻을 갖는 낱말 — `lib/자격증명.js 읽기()` 가 **도구를 안 가리고** 조준에 쓴다(F436).
 *  도구가 자기 목록에 안 적어도 뜻이 살아 있으므로, 여기 없으면 가드가 **자기 처방을 막는다** —
 *  차단문이 시키는 낱말을 그 가드가 거절하는 형태(CLAUDE.md 가드 맹점 ③ · F103). */
const 공용플래그 = ['--운영'];

/** 모르는 `--` 인자만 골라낸다. **순수 함수** — 자격증명·네트워크 없이 회귀가 여기를 문다(F296). */
function 모름(args, 아는것) {
  const 준것 = args || [];
  const 아는 = 아는것 || [];
  return 준것.filter((a) => typeof a === 'string' && a.startsWith('--') && !아는.includes(a));
}

/**
 * 도구가 부르는 통로 — 모르는 낱말이 있으면 **사람이 따라갈 수 있는** 한 줄을 돌려준다(없으면 null).
 * 막는 것은 도구 몫이다(`die` 의 모양이 도구마다 다르다).
 */
function 인자게이트(도구, args, 아는것) {
  const 모른것 = 모름(args, 아는것);
  if (!모른것.length) return null;
  return `모르는 플래그 ${모른것.join(' ')} — ${도구} 가 아는 것은 ${(아는것 || []).join(' ')} 뿐이다.`
    + ' 조용히 무시하면 「딴 과녁을 재고 초록」이 된다(F400·F435).';
}

module.exports = { 공용플래그, 모름, 인자게이트 };
