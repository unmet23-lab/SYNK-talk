'use strict';
/**
 * 녹음 복구 — «담겼는데 보내기 전에 죽은» 발화의 순수 판정 (G2-2).
 *
 * ■ 무엇을 닫나
 *   녹음 중 이탈 뒤 프로세스가 죽으면 조각·조립 바이트·'확인' 단계가 전부 메모리라 사라졌다.
 *   이제 `끝()` 이 WAV 를 디스크에 앉힌 직후 메타 한 장(`src/저장.js` 임시녹음메타쓰기)을
 *   남기고, 다음 마운트가 **이 판정**으로 「들어보고 보낼까요?」 카드를 세울지 정한다.
 *
 * ■ 왜 lib 인가 — 회귀가 화면 없이 판정만 물 수 있어야 한다(`lib/오늘과제.복귀행동` 과 같은 자리).
 *   파일을 읽고 쓰는 것은 저장 어댑터의 일이고, 여기는 「그 메타가 아직 뜻이 있는가」만 진다.
 */
const { 학습출석 } = require('./제출로그.js');

/**
 * 이 메타를 학생에게 되보여 줄 것인가.
 * 🔑 넷이 전부 참일 때만 true:
 *   · 메타가 있다(uri 포함) — 없으면 보여 줄 것이 없다.
 *   · 그날 것이다(date === 오늘) — 어제 발화를 오늘 과제에 실으면 남의 날 행이 된다.
 *   · 발화가 있다(spoke) — 무발화 판은 되살릴 값이 없다(그 신호는 로그가 이미 안다).
 *   · 오늘 아직 안 냈다(!학습출석) — 낸 날의 되살림은 이중 제출의 문이다.
 * @param {{date?:string, uri?:string, spoke?:boolean}|null} 메타 임시녹음메타읽기 의 결과
 * @param {string} 오늘 'YYYY-MM-DD'
 * @param {object[]} 로그 제출 로그
 * @returns {boolean}
 */
function 복구후보(메타, 오늘, 로그) {
  if (!메타 || !메타.uri || !오늘) return false;
  if (메타.date !== 오늘) return false;
  if (!메타.spoke) return false;
  return !학습출석(로그 || [], 오늘);
}

module.exports = { 복구후보 };
