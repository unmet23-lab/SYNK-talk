'use strict';
/**
 * 곡반응 — SYNK **Reed** 넷째 기둥. 「어느 곡이 어느 시간대에 얼마나 붙잡았나」.
 * 이 층이 있어야 Reed 가 «도구»가 아니라 **엔진**이 된다(쌓이는 것이 있어야 엔진이다).
 * (설계 정본 = appsscript `docs/Reed_설계_v0.1.md` §5·§5-B)
 *
 * ■ 🔴 지표는 «좋아요»가 아니라 «체류»다
 *   배경음악은 성공 조건이 다르다 — **눈에 안 띄는 것이 성공**이다. 그래서 묻는 것은
 *   「좋아했나」가 아니라 **「곡이 바뀐 뒤 몇 % 빠졌나」**다. 1:다 방송이라 개인 성향은
 *   원리상 못 재고, 그게 라디오에는 맞는 단위이기도 하다.
 *
 * ■ 🔴 이 파일의 급소 = **결의 «바닥»과 견준다(절대 이탈률로 줄 세우지 않는다)**
 *   새벽 3시에 사람이 빠지는 것은 곡 탓이 아니라 **자는 것**이다. 절대값으로 줄을 세우면
 *   새벽 곡이 통째로 「나쁜 곡」이 되고, 그 판정으로 새벽 편성을 고치면 방송이 망가진다.
 *   ⇒ 곡의 성적은 언제나 **그 결의 평균 대비**다. 「이 곡은 그 시간대 치고 잘/못 붙잡았나」.
 *
 * ■ 🔴 «표본 부족»과 «성적 나쁨»을 절대 안 섞는다
 *   학생 0명·방송 0일 동안 이 축은 0이고 그게 정상이다(그릇은 첫날부터 있어야 나중에 안 빈다).
 *   표본이 모자란 곡을 「나쁘다」로 읽으면 만들자마자 은퇴시키는 일이 난다 — 새 곡은 언제나
 *   표본이 0이다. 그래서 판정에 `믿을만한가` 를 **따로** 낸다.
 *
 * ■ 🚫 여기 두지 않는 것
 *   · 사람 식별 — 관측은 «몇 명이 있었나»뿐이다. 누가 들었는지는 안 받고 안 센다.
 *   · 저장·조회 — 순수 판정만(수집 통로는 라디오24 설계도·앱 몫)
 */

/** 이 수보다 관측이 적으면 «못 잰 것»이다. 100곡 × 하루 2~3바퀴면 한 달에 곡당 60~90 관측. */
const 최소표본 = 12;

const 수인가 = (v) => Number.isFinite(Number(v));

/**
 * 관측 하나 → 이탈률. **곡이 시작할 때와 끝날 때의 동시 청취자**로 잰다.
 * 🔑 0명에서 시작한 구간은 `null` 이다 — 0에서 0으로 갔다고 「이탈 0%」로 읽으면
 *   아무도 없는 새벽이 «가장 잘 붙잡은 시간»이 된다.
 * @param {{시작인원: number, 끝인원: number}} 관 @returns {number|null} 0~1
 */
function 이탈률(관) {
  const o = 관 && typeof 관 === 'object' ? 관 : {};
  if (!수인가(o.시작인원) || !수인가(o.끝인원)) return null;
  const 시 = Number(o.시작인원), 끝 = Number(o.끝인원);
  if (시 <= 0) return null;
  return Math.min(1, Math.max(0, (시 - 끝) / 시));
}

/** 관측들 → 결별 «바닥»(그 시간대의 평균 이탈률). 견줄 자가 이것이다. */
function 결바닥(관측들) {
  const 모음 = {};
  for (const 관 of Array.isArray(관측들) ? 관측들 : []) {
    const r = 이탈률(관);
    if (r === null || !관.결) continue;
    (모음[관.결] = 모음[관.결] || []).push(r);
  }
  const 바닥 = {};
  for (const [결, 값들] of Object.entries(모음)) {
    바닥[결] = { 평균: 값들.reduce((a, b) => a + b, 0) / 값들.length, 표본: 값들.length };
  }
  return 바닥;
}

/**
 * 곡 하나의 성적 — **그 결의 바닥 대비**.
 * `상대` 가 음수면 그 시간대 치고 «덜» 빠진 것 = 잘 붙잡은 것이다.
 * @returns {{곡id, 표본, 절대: number|null, 상대: number|null, 믿을만한가: boolean, 말: string}}
 */
function 곡성적(관측들, 곡id, 바닥 = null) {
  const 전부 = (Array.isArray(관측들) ? 관측들 : []).filter((o) => o && o.곡id === 곡id);
  const b = 바닥 || 결바닥(관측들);
  const 쓸것 = [];
  for (const 관 of 전부) {
    const r = 이탈률(관);
    if (r === null) continue;
    const 바 = b[관.결];
    쓸것.push({ r, 상대: 바 ? r - 바.평균 : null });
  }
  const n = 쓸것.length;
  if (!n) {
    return { 곡id, 표본: 0, 절대: null, 상대: null, 믿을만한가: false, 말: '아직 안 재봤다(관측 0)' };
  }
  const 절대 = 쓸것.reduce((a, x) => a + x.r, 0) / n;
  const 상대값 = 쓸것.filter((x) => x.상대 !== null).map((x) => x.상대);
  const 상대 = 상대값.length ? 상대값.reduce((a, b2) => a + b2, 0) / 상대값.length : null;
  const 믿을만한가 = n >= 최소표본;
  /* 🔴 말에 «표본»을 반드시 싣는다 — 숫자만 보면 관측 2건짜리 곡이 관측 90건짜리 곡과
   *   같은 무게로 읽힌다(유호 확정 08-14 「합계 = 갈래 + 갈래」와 같은 축). */
  const 말 = 믿을만한가
    ? `${(절대 * 100).toFixed(0)}% 이탈 · 그 시간대 치고 ${상대 === null ? '?' : (상대 <= 0 ? `${Math.abs(상대 * 100).toFixed(0)}%p 덜 빠졌다` : `${(상대 * 100).toFixed(0)}%p 더 빠졌다`)} (관측 ${n})`
    : `관측 ${n}건 — ${최소표본}건은 돼야 믿는다(지금 숫자는 참고만)`;
  return { 곡id, 표본: n, 절대, 상대, 믿을만한가, 말 };
}

/**
 * 결 하나의 줄 세우기 — **믿을 만한 것만** 세운다. 못 잰 것은 «아래»가 아니라 **밖**이다.
 * @returns {{결: string, 순위: object[], 못잰것: object[], 바닥: object|null}}
 */
function 결순위(관측들, 결) {
  const b = 결바닥(관측들);
  const ids = [...new Set((Array.isArray(관측들) ? 관측들 : [])
    .filter((o) => o && o.결 === 결 && o.곡id).map((o) => o.곡id))];
  const 성적들 = ids.map((id) => 곡성적((관측들 || []).filter((o) => o.결 === 결), id, b));
  const 순위 = 성적들.filter((s) => s.믿을만한가).sort((x, y) => (x.상대 ?? 9) - (y.상대 ?? 9));
  const 못잰것 = 성적들.filter((s) => !s.믿을만한가);
  return { 결, 순위, 못잰것, 바닥: b[결] || null };
}

/**
 * 다음 곡을 «무엇으로» 만들까 — 이 엔진이 감을 대신하는 자리.
 * 잘 붙잡은 곡들의 공통점(BPM·밝기 중앙값)을 결별로 낸다.
 * 🔑 «평균 취향 맞히기»가 아니다(설계 §5-B ③) — 잘 되는 자리의 «눈금»을 읽어 주는 것뿐이고,
 *   무엇을 만들지는 사람이 정한다.
 */
function 다음곡힌트(관측들, 장부, 결) {
  const { 순위, 바닥 } = 결순위(관측들, 결);
  const 좋은것 = 순위.slice(0, Math.max(1, Math.ceil(순위.length / 3)));
  const 곡찾기 = (id) => (Array.isArray(장부) ? 장부 : []).find((c) => c && c.id === id);
  const 값 = (칸) => 좋은것.map((s) => Number((곡찾기(s.곡id) || {})[칸])).filter(Number.isFinite).sort((a, b) => a - b);
  const 중앙 = (a) => (a.length ? a[Math.floor(a.length / 2)] : null);
  if (!순위.length) {
    return { 결, 쓸만한가: false, 말: `${결} 에 믿을 만한 관측이 아직 없다 — 표본이 쌓이기 전엔 감이 낫다`, BPM: null, 밝기: null };
  }
  return {
    결, 쓸만한가: true, BPM: 중앙(값('BPM')), 밝기: 중앙(값('밝기')),
    말: `${결} 상위 ${좋은것.length}곡의 눈금 — BPM ${중앙(값('BPM')) ?? '?'} · 밝기 ${중앙(값('밝기')) ?? '?'}`
      + (바닥 ? ` (그 시간대 바닥 이탈률 ${(바닥.평균 * 100).toFixed(0)}%)` : ''),
  };
}

/** 축 전체가 지금 «살아 있나» — 학생 0명 동안 0인 것이 정상이고, 그것을 정직하게 말한다. */
function 축상태(관측들) {
  const 전부 = Array.isArray(관측들) ? 관측들 : [];
  const 쓸것 = 전부.filter((o) => 이탈률(o) !== null);
  return {
    관측: 전부.length,
    쓸수있는것: 쓸것.length,
    버린것: 전부.length - 쓸것.length,      // 0명 구간 등 — 「모르면 안 센다」
    믿을만한곡: new Set(쓸것.map((o) => o.곡id)).size,
    말: 전부.length === 0
      ? '관측 0 — 방송 전이라 정상이다(그릇은 서 있다)'
      : `관측 ${전부.length} = 쓸 것 ${쓸것.length} + 버린 것 ${전부.length - 쓸것.length}`,
  };
}

module.exports = { 최소표본, 이탈률, 결바닥, 곡성적, 결순위, 다음곡힌트, 축상태 };
