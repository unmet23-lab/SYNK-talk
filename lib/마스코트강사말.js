/** 강사판 ㉮ 순간 — 닫힌 목록 (말할순간 §2 A층에서 신호가 실재하는 것 + T10). */
const 강사순간 = Object.freeze(['T1', 'T2', 'T3', 'T4', 'T5', 'T10']);

/** 1~10을 세는 말로. 범위 밖은 숫자 그대로(지어내지 않는다). */
function 세는말(n) {
  const 말 = ['영', '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉', '열'];
  return Number.isInteger(n) && n >= 0 && n < 말.length ? 말[n] : String(n);
}

/**
 * 순간 → 문구 후보 풀. 고르는 것은 화면 몫(무작위 1개), 짓는 것은 여기뿐이다.
 * @param {string} 순간 강사순간 의 값
 * @param {{남음:number, 판정됨:number, 막힘:number, 전체:number}} 셈 강사화면 `진행()` 결과
 * @returns {readonly string[]} 빈 배열 = 그 순간에 낼 문구가 없다(침묵)
 */
function 강사문구(순간, 셈) {
  const { 남음 = 0, 판정됨 = 0, 막힘 = 0, 전체 = 0 } = 셈 || {};
  if (순간 === 'T1') {
    return Object.freeze([
      `이번 주 ${세는말(전체)} 건이 왔어요`,
      `이번 주 것들이 도착했어요 — ${세는말(전체)} 건이에요`,
    ]);
  }
  if (순간 === 'T2') {
    return Object.freeze([
      `${세는말(남음)} 건만 더 하면 이번 주 끝이에요`,
      `벌써 ${세는말(판정됨)} 건 하셨어요 — ${세는말(남음)} 건이면 끝나요`,
    ]);
  }
  if (순간 === 'T3') {
    return Object.freeze([
      '이번 주 끝! 고생하셨어요',
      '이번 주 것 전부 끝났어요 — 고생하셨어요',
    ]);
  }
  if (순간 === 'T4') {
    return Object.freeze([
      '이번 주 것들이 기다려요 — 5분이면 돼요',
      '이번 주 것, 한 건만 먼저 볼까요?',
    ]);
  }
  if (순간 === 'T5') {
    return Object.freeze([
      막힘 === 1
        ? '한 건은 막혀 있어요 — 그대로 두면 돼요'
        : `${세는말(막힘)} 건은 막혀 있어요 — 그대로 두면 돼요`,
    ]);
  }
  if (순간 === 'T10') {
    return Object.freeze([
      '처음 오셨네요! 한 건씩 판정하면 위의 숫자가 줄어요',
    ]);
  }
  return Object.freeze([]);
}

/**
 * 지금 말할 순간 하나를 고른다 — **한 방문에 최대 한 마디**(절제가 케어의 전제 · §1 원칙 7).
 *
 * @param {'열림'|'완료'} 계기 큐를 다 읽은 순간 | 마지막 판정이 저장된 순간
 * @param {{셈:object, 주:string, 요일:number, 오늘:string, 막힌카드:string[]}} 신호
 *   요일 = ISO(월1~일7) · 오늘 = 'YYYY-MM-DD' · 막힌카드 = blocked correction_id 목록
 * @param {Record<string,string>} 말한기록 키 → 말한 날짜 (src/저장.js 마스코트기록)
 * @returns {{순간:string, 키:string, 풀:readonly string[]}|null} null = 침묵
 */
function 강사순간고르기(계기, 신호, 말한기록) {
  const { 셈, 주 = '', 요일 = 0, 오늘 = '', 막힌카드 = [] } = 신호 || {};
  const s = 셈 || { 남음: 0, 판정됨: 0, 막힘: 0, 전체: 0 };
  const 기록 = 말한기록 || {};
  const 안한 = (키) => !(키 in 기록);
  const 내기 = (순간, 키) => {
    const 풀 = 강사문구(순간, s);
    return 풀.length ? { 순간, 키, 풀 } : null;
  };

  if (계기 === '완료') {
    // T3 — 「전부 완료한 순간」에만. 다시 연 화면은 이미 「이번 주 끝」 카드가 말하고 있다.
    if (s.남음 === 0 && s.판정됨 > 0 && 주 && 안한(`T3:${주}`)) return 내기('T3', `T3:${주}`);
    return null;
  }

  // T10 — 이 기기의 첫 방문. 안내 한 줄만 하고 그 방문은 끝(다른 줄과 겹쳐 서지 않는다).
  if (안한('T10')) return 내기('T10', 'T10');

  if (!주 || s.전체 === 0) return null; // 표본이 없는 주 — 말할 사실이 없다(빈 카드가 말한다)

  // T1 — 이번 주를 처음 만난 방문(아직 한 건도 판정 전).
  if (s.판정됨 === 0 && s.남음 > 0 && 안한(`T1:${주}`)) return 내기('T1', `T1:${주}`);

  // T2 — 하다 만 채로 재접속. 하루 1회.
  if (s.판정됨 > 0 && s.남음 > 0 && 오늘 && 안한(`T2:${오늘}`)) return 내기('T2', `T2:${오늘}`);

  // T4 — 주 후반(목요일부터)인데 판정 0건. T1 이 이미 나간 주에만(같은 방문에 둘은 잔소리다).
  if (s.판정됨 === 0 && s.남음 > 0 && 요일 >= 4 && 안한(`T4:${주}`)) return 내기('T4', `T4:${주}`);

  // T5 — 막힌 카드. 카드당 1회(키 = 첫 미발화 카드) · 다른 줄이 다 조용할 때만.
  const 새막힘 = 막힌카드.find((id) => 안한(`T5:${id}`));
  if (s.막힘 > 0 && 새막힘) return 내기('T5', `T5:${새막힘}`);

  return null;
}

module.exports = { 강사순간, 강사문구, 강사순간고르기, 세는말 };
