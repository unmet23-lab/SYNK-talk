/** `.env` 한 벌. 없으면 빈 객체 — 판단은 부르는 쪽이 한다. */
function 파일읽기(p = ENV파일) {
  if (!fs.existsSync(p)) return {};
  const out = {};
  for (const 줄 of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = 줄.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m) out[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return out;
}

/* 오늘은 UTC 로 뽑는다 — CI 와 로컬이 다른 날을 보면 「내 기계에서만 빨갛다」가 된다.
 * (repo 밖 환경에 기대는 검사는 CI 에서 깨진다 · CLAUDE.md 신뢰성) */
const 오늘UTC = () => new Date().toISOString().slice(0, 10);

/**
 * 만료 판정 — **순수 함수**라 회귀가 시계 없이 선다.
 * @returns {{상태:'ok'|'없음'|'모양이상'|'지남', 만료:string|null}}
 */
function 만료판정(env, 오늘 = 오늘UTC()) {
  const v = String((env && env[만료칸]) || '').trim();
  if (!v) return { 상태: '없음', 만료: null };
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) return { 상태: '모양이상', 만료: v };
  // 문자열 비교로 충분하다(YYYY-MM-DD 는 사전순 = 시간순). Date 파싱은 시간대를 끌어들인다.
  return { 상태: v < 오늘 ? '지남' : 'ok', 만료: v };
}

