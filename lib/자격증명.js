/* 자격증명 — `.env` + 환경변수를 읽는 **공용 통로**, 그리고 토큰을 시간으로 가두는 자리.
 *
 * ■ 왜 공용인가
 *   같은 `env읽기()` 가 도구 **6곳**에 복사돼 있었다(2026-08-06 실측: 원격SQL·원격배포·왕복시험
 *   ·업로드왕복시험·스토리지키_설정·로그인코드발급). 그러면 규칙을 하나 더할 때 6곳을 고쳐야 하고,
 *   **빠뜨린 곳은 「통과」로 보인다.** 호출부마다 고치는 대신 잘못 쓸 수 없는 통로를 하나 만든다.
 *
 * ■ 왜 만료인가
 *   Supabase 개인 액세스 토큰은 **스코프가 없다** — 계정 전체(프로젝트 전부·삭제 포함)에 닿는다.
 *   권한으로 못 좁히니 **시간으로 가둔다.** 그런데 「작업이 끝나면 폐기해 주십시오」는 지금까지
 *   **안내문 속 문장**이었고, 문장은 스스로 발화하지 않는다 — 그래서 08-06 현재까지 열려 있었다.
 *   여기서 그 문장이 기계가 된다.
 *
 * ■ 정책(유호님 확정 2026-08-06): 폐기 시점은 날짜가 아니라 **사건**이다 —
 *   「실학생 데이터가 DB 에 처음 들어가기 전」. 날짜는 그 사건을 잊지 않게 하는 **알람**이지
 *   정책 자체가 아니다. 그래서 만료가 지나도 하는 일은 「멈추고 다시 정하게 하기」다.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ENV파일 = path.join(__dirname, '..', '.env');
/* 🔑 이름은 **ASCII 여야 한다.** 처음에 `SUPABASE_TOKEN_만료` 로 썼다가 실측에서 깨졌다 —
 *   셸이 비ASCII 환경변수 이름을 못 세운다(`command not found`). `.env` 파일만 볼 때는 멀쩡해
 *   보이지만, 환경변수로 덮어쓰는 길(CI·일회성 실행·회귀)이 통째로 막힌다.
 *   저장소가 한국어여도 **OS 와 맞닿는 이름은 OS 의 표기를 따른다.** */
const 만료칸 = 'SUPABASE_TOKEN_EXPIRES';

/** `.env` 한 벌. 없으면 빈 객체 — 판단은 부르는 쪽이 한다. */
function 파일읽기(p = ENV파일) {
  if (!fs.existsSync(p)) return {};
  const out = {};
  for (const 줄 of fs.readFileSync(p, 'utf8').split(/\r?\n/)) {
    const m = 줄.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m) out[m[1]] = m[2].trim().replace(/^["']|["']$/g, '');
  }
  return out;
}

/* 오늘은 UTC 로 뽑는다 — CI 와 로컬이 다른 날을 보면 「내 기계에서만 빨갛다」가 된다.
 * (repo 밖 환경에 기대는 검사는 CI 에서 깨진다 · CLAUDE.md 신뢰성) */
const 오늘UTC = () => new Date().toISOString().slice(0, 10);

/**
 * 만료 판정 — **순수 함수**라 회귀가 시계 없이 선다.
 * @returns {{상태:'ok'|'없음'|'모양이상'|'지남', 만료:string|null}}
 */
function 만료판정(env, 오늘 = 오늘UTC()) {
  const v = String((env && env[만료칸]) || '').trim();
  if (!v) return { 상태: '없음', 만료: null };
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v)) return { 상태: '모양이상', 만료: v };
  // 문자열 비교로 충분하다(YYYY-MM-DD 는 사전순 = 시간순). Date 파싱은 시간대를 끌어들인다.
  return { 상태: v < 오늘 ? '지남' : 'ok', 만료: v };
}

function 폐기안내(도구, 만료) {
  console.error(`[${도구}] 액세스 토큰이 만료일(${만료})을 지났습니다 — 여기서 멈춥니다.

이 토큰은 **계정 전체**에 닿습니다(프로젝트 전부·삭제 포함). 좁힐 수단이 없어 시간으로 가둡니다.

유호님 손 (약 2분):
  1. https://supabase.com/dashboard/account/tokens 를 엽니다
  2. 쓰던 토큰 줄의 [Revoke] 를 누릅니다  ← 먼저 폐기합니다
  3. 아직 작업이 남았으면 [Generate new token] 으로 새로 만들어
     ${ENV파일} 의 SUPABASE_ACCESS_TOKEN 을 새 값으로 바꿉니다
  4. 같은 파일의 ${만료칸} 를 새 날짜로 바꿉니다 (예: ${새날짜(30)})

작업이 끝났다면 2번까지만 하시면 됩니다 — 이 도구들은 안 망가지고,
다음에 필요할 때 새로 발급하면 그대로 돕니다.`);
  process.exit(2);
}

/** 오늘 + n일 (YYYY-MM-DD) — 안내문이 **바로 붙여넣을 수 있는 값**을 주게 한다. */
function 새날짜(n) {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

/**
 * 도구가 부르는 유일한 통로 — `{...env읽기(), ...process.env}` 를 대신한다.
 * 🔑 **자격증명이 없을 때의 안내는 여기서 안 한다.** 도구마다 필요한 값도 다음 절차도 달라서,
 *   여기로 합치면 「어느 도구를 부르든 같은 문장」이 되고 그건 따라갈 수 없는 처방이 된다.
 *   이 통로가 지는 것은 **갈라지면 안 되는 것 하나 — 만료**뿐이다.
 * @param {string} 도구  안내문에 쓸 이름
 * @param {{오늘?: string}} [opt]  회귀가 시계 없이 서게 하는 구멍
 */
function 읽기(도구, opt) {
  const env = { ...파일읽기(), ...process.env };
  const 만료 = 만료판정(env, opt && opt.오늘);

  if (만료.상태 === '지남') 폐기안내(도구, 만료.만료);
  if (만료.상태 === '모양이상') {
    console.error(`[${도구}] ⚠ ${만료칸} 가 YYYY-MM-DD 가 아닙니다(${만료.만료}) — 만료를 재지 못합니다.`);
  }
  /* 🔑 **없으면 조용히 넘어가지 않는다.** 통과와 미실행이 같은 모양이면 이 장치는 있으나 마나다 —
   *   한 줄이라도 남겨서 「지금 안 재고 있다」가 보이게 한다. */
  if (만료.상태 === '없음') {
    console.error(`[${도구}] ⚠ ${만료칸} 가 없어 토큰 만료를 재지 않습니다 — .env 에 한 줄: ${만료칸}=${새날짜(30)}`);
  }
  return env;
}

module.exports = { 읽기, 만료판정, 파일읽기, 새날짜, 만료칸, ENV파일 };
