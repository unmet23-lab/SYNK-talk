/**
 * 과녁 판정 — 대상이 **운영**이면 손을 하나 더(`--운영`) 요구한다. **순수 함수**다.
 *
 * 🔴 왜 알림으로는 안 됐나 (2026-08-07 실측). `.env` 한 파일 안에서 **두 변수 가족이 서로 다른
 *   프로젝트를 가리키고 있었다** — `EXPO_PUBLIC_SUPABASE_URL`=리허설(앱·왕복시험이 붙는 곳) /
 *   `SUPABASE_PROJECT_REF`=운영(이 도구들이 쏘는 곳). 그래서 **왕복은 리허설에서 초록인데
 *   `--적용` 은 운영에 떨어진다.** 실제로 Edge Function 4개가 그렇게 운영에 섰고(08-07 07:50 KST)
 *   그 사실을 적은 커밋도 보드 줄도 없다 — 운영 데이터가 0행이라 무해했을 뿐이다.
 *   `원격SQL.js` 는 **쏘기 직전에 대상을 소리 내어 읽고 있었다**(`대상알림`). 그런데 스스로
 *   「알림이지 가드가 아니다」라고 적어 둔 그대로, 알림은 멈추지 않는다.
 *
 * 🔑 읽기까지 막는다. 한 번 더 치는 값이 한 플래그인데 잘못 쏜 쓰기는 되돌릴 수 없고,
 *   읽기·쓰기를 여기서 가르려면 호출부 10곳이 자기가 쓰는지를 선언해야 한다 —
 *   그러면 빠뜨린 곳이 생기고 **빠뜨린 곳은 「통과」로 보인다**(이 파일 머리말 그대로).
 *
 * @returns {{상태:'통과'|'막음', ref:string}}
 */
function 과녁판정(env, args) {
  const ref = String((env && env.SUPABASE_PROJECT_REF) || '');
  if (ref !== 운영REF) return { 상태: '통과', ref };
  if ((args || []).includes('--운영')) return { 상태: '통과', ref };
  return { 상태: '막음', ref };
}

function 과녁차단(도구, ref) {
  const 인자 = process.argv.slice(2).join(' ');
  console.error(`[${도구}] ⛔ 대상이 **운영**(Synk Core · ${ref})이다 — 여기서 멈춥니다.

실학생이 들어올 프로젝트입니다. \`.env\` 의 SUPABASE_PROJECT_REF 하나로 과녁이 조용히 바뀌고,
앱·왕복시험은 그 사이에도 리허설에 붙어 있어 **초록인데 운영에 떨어지는** 상태가 됩니다.

리허설에서 하려면 (거의 항상 이쪽입니다):
  Bash        SUPABASE_PROJECT_REF=${리허설REF} node tools/... ${인자}
  PowerShell  $env:SUPABASE_PROJECT_REF='${리허설REF}'; node tools/... ${인자}

정말 운영이어야 하면 — **유호님 명시 승인 뒤에** 두 번째 키를 붙입니다:
  node tools/... ${인자} --운영`);
  process.exit(2);
}

/** 오늘 + n일 (YYYY-MM-DD) — 안내문이 **바로 붙여넣을 수 있는 값**을 주게 한다. */
function 새날짜(n) {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

/**
 * 도구가 부르는 유일한 통로 — `{...env읽기(), ...process.env}` 를 대신한다.
 * 🔑 **자격증명이 없을 때의 안내는 여기서 안 한다.** 도구마다 필요한 값도 다음 절차도 달라서,
 *   여기로 합치면 「어느 도구를 부르든 같은 문장」이 되고 그건 따라갈 수 없는 처방이 된다.
 *   이 통로가 지는 것은 **갈라지면 안 되는 것 하나 — 만료**뿐이다.
 * @param {string} 도구  안내문에 쓸 이름
 * @param {{오늘?: string}} [opt]  회귀가 시계 없이 서게 하는 구멍
 */
function 읽기(도구, opt) {
  const env = { ...파일읽기(), ...process.env };
  const 만료 = 만료판정(env, opt && opt.오늘);

  if (만료.상태 === '지남') 폐기안내(도구, 만료.만료);
  if (만료.상태 === '모양이상') {
    console.error(`[${도구}] ⚠ ${만료칸} 가 YYYY-MM-DD 가 아닙니다(${만료.만료}) — 만료를 재지 못합니다.`);
  }
  /* 🔑 **없으면 조용히 넘어가지 않는다.** 통과와 미실행이 같은 모양이면 이 장치는 있으나 마나다 —
   *   한 줄이라도 남겨서 「지금 안 재고 있다」가 보이게 한다. */
  if (만료.상태 === '없음') {
    console.error(`[${도구}] ⚠ ${만료칸} 가 없어 토큰 만료를 재지 않습니다 — .env 에 한 줄: ${만료칸}=${새날짜(30)}`);
  }

  const 과녁 = 과녁판정(env, (opt && opt.args) || process.argv.slice(2));
  if (과녁.상태 === '막음') 과녁차단(도구, 과녁.ref);

  return env;
}

