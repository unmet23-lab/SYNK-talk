/* 소리게이트 — 앱 전체 소리·햅틱의 **단일 판정 자리** (게임층 설계 §3-1 🔴 · §3-2 ⓔ · 유호 확정 08-11).
 *
 * ■ 왜 게이트가 한 곳인가 — 「녹음 구간 소리·햅틱 전면 0」은 데이터 요건이다(내장 마이크 되먹임이
 *   전사와 `stt_segments` 를 오염 · 이어폰 없는 학생이 기본값). 화면마다 각자 지키게 두면
 *   프로즈로만 남는다 — 재생 요청이 전부 이 판정을 지나면 어길 수 있는 자리가 없다.
 *
 * ■ 판정 규칙 (전부 정본 승계):
 *   · 녹음 중: 효과음 0 · 햅틱 0 · BGM 음소거(§3-1 🔴 · §3-2 ⓔ) — 녹음 끝에 BGM 만 복원.
 *   · 효과음 이름 = 킷 3종 + 가이드 목소리 18종 화이트리스트만. 리프레이밍은 무음(§3-3 7번),
 *     실패음은 존재하지 않는다(규칙 ②) — 둘 다 「이름이 없어서」 원리상 못 지나간다.
 *   · 볼륨 재조정 없음 — 게이트는 허용/거부/음소거만 안다(밸런스는 파일에 있다 · 사운드킷 규칙).
 *
 * ■ 순수 모듈 — expo 0 · 시간 0 · I/O 0. 실행은 src/소리.js(어댑터)가 조치 목록을 받아 한다.
 */
'use strict';

/* 킷 3종 + 가이드 목소리 18종(몽글 12 · 까몽 3 · 마린 3). 목소리는 상황마다 다른 소리라
   이름이 여럿이다(몽글 유호 확정 08-25 · 까몽·마린 08-28 · 배치 정본 = lib/가이드목소리.js).
   화이트리스트인 이유는 그대로다 — 킷 밖 소리는 원리상 못 지난다.
   🔑 이름이 곧 파일이다(`synk-voice-<이름>.wav`) — 까몽·마린은 캐릭터 접두를 이름에 달고 있어
      몽글의 짧은 이름(mu·ppuu…)과 한 통에 섞여도 어느 캐릭터 것인지 읽힌다. */
const 목소리이름 = Object.freeze([
  'mu', 'ppuu', 'myang', 'miyu', 'ppoo', 'ppong', 'mii', 'miyuu', 'uung', 'muum', 'moong', 'muu',
  'kkamong-bee', 'kkamong-hiik', 'kkamong-nyamnyam',
  'marine-gidong', 'marine-wansu', 'marine-mollae',
]);
const 효과음이름 = Object.freeze(['earn', 'achieve', 'notify', ...목소리이름]);

function 만들기() {
  let 녹음중 = false;
  let bgm켜짐 = false;   // 어댑터가 재생을 시작했다고 알린 상태(복원 판단 재료)

  return {
    /** 녹음이 시작된다 — 실행할 조치 목록을 돌려준다(어댑터가 순서대로 실행). */
    녹음시작() {
      녹음중 = true;
      return bgm켜짐 ? [{ 할일: 'bgm음소거' }] : [];
    },
    /** 녹음이 끝났다 — BGM 만 복원한다(놓친 효과음·햅틱을 몰아 쏘지 않는다 — 상태 전이는 지나갔다). */
    녹음끝() {
      녹음중 = false;
      return bgm켜짐 ? [{ 할일: 'bgm복원' }] : [];
    },
    bgm상태(켜짐) { bgm켜짐 = !!켜짐; },

    /** 재생 요청 판정 — 종류: 'sfx' | 'haptic' | 'bgm시작'. */
    판정(종류, 이름) {
      if (종류 === 'sfx') {
        if (!효과음이름.includes(이름)) return { 허용: false, 사유: `킷 밖 소리(${이름}) — 통로는 토큰→사운드킷빌드→유호 시청뿐` };
        if (녹음중) return { 허용: false, 사유: '녹음중' };
        return { 허용: true };
      }
      if (종류 === 'haptic') {
        return 녹음중 ? { 허용: false, 사유: '녹음중' } : { 허용: true };
      }
      if (종류 === 'bgm시작') {
        // 녹음 중 시작 요청은 「음소거 상태로 시작」 — 거부하면 녹음 끝의 복원 대상이 사라진다.
        return 녹음중 ? { 허용: true, 조치: '음소거로시작' } : { 허용: true };
      }
      return { 허용: false, 사유: `모르는 종류(${종류})` };
    },

    지금녹음중() { return 녹음중; },
  };
}

module.exports = { 만들기, 효과음이름, 목소리이름 };
