'use strict';
/* 문장 끊기 — ②따라 말하기를 **한 문장씩**으로 되돌린다 (유호 확정 2026-08-23).
 *
 * ■ 왜 필요한가 — 계약이 넓어진 그날 화면이 좁아지지 않았다
 *   08-23 에 생성 산출 계약이 「한 문장 60자」에서 **1~3문장 8~120자**로 완화됐다(유호 확정 ·
 *   근거 = 첫 사람 채점 79건에서 한 문장 제한이 자연스러움과 정면 충돌). 그 확정 줄이 같은 자리에
 *   「따라 말하기 호흡은 앱이 **문장 단위로 끊어 처리**(어댑터 몫)」를 못박았는데, 화면은
 *   여태 `편지.핵심문장` 을 **통으로** 한 카드에 세우고 통으로 녹음받고 있었다.
 *   🔴 실측(08-26 · 3회전 결과 80행): **2문장 71 · 3문장 9 · 1문장 0** — 한 문장짜리가 하나도
 *   없다. 즉 이건 드문 갈래가 아니라 **생성이 켜지는 날의 기본값**이다.
 *
 * ■ 「한 호흡」 원칙의 새 형태
 *   ②의 값은 «의도를 100% 아는 발화»다(설계 §6 — 목표 문장이 정해져 있어 발음·억양 오류의
 *   정답 라벨이 공짜). 세 문장을 통으로 읽히면 학생은 외우다 지치고, 우리는 «어느 문장에서
 *   무너졌는지»를 못 본다. 문장마다 끊으면 둘 다 산다.
 *
 * ■ 🔴 이 파일은 **자르기만** 한다 — 걸음 이름은 `lib/걸음.js`, 화면 흐름은 `src/말하기화면.js`.
 *   판정이 셋으로 흩어지지 않게 각자 하나씩만 진다.
 */

/**
 * 한 ②호흡이 가질 수 있는 문장 수의 상한 — **계약 그대로**다(유호 확정 08-23 「1~3문장」).
 *
 * ⚠ 이 수를 «검문»이 재지는 않는다(실측 08-26): `lib/과제검문.js` 는 문장 «글자수» 8~120 만
 *   기계로 걸고, 1~3문장은 프롬프트 지시로만 산다. 그래서 여기 상한은 **막는 자**가 아니라
 *   화면이 무너지지 않게 하는 **받침**이다 — 넘치면 던지지 않고 마지막 조각에 남긴다(아래).
 */
const 상한 = 3;

/* 문장을 끝내는 글자. 반복(`?!`·`...`)은 아래에서 한 덩어리로 삼킨다. */
const 종결자 = new Set(['.', '!', '?', '…', '。', '！', '？']);

/* 종결자 «뒤»에 붙어도 여전히 그 문장인 것 — 닫는 따옴표·괄호. */
const 뒤따르는것 = new Set(['"', "'", '”', '’', '」', '』', ')', ']', '》', '〉']);

/* 여는 짝 → 닫는 짝. 🔴 ASCII `"` `'` 는 **일부러 뺐다** — 여는 것과 닫는 것이 같은 글자라
 * 짝을 셀 수가 없고, 잘못 세면 뒤 문장이 통째로 안 갈린다(조용한 실패). 못 세는 것을 세는
 * 척하지 않는다. */
const 여는것 = new Map([
  ['「', '」'], ['『', '』'], ['“', '”'], ['‘', '’'],
  ['(', ')'], ['[', ']'], ['《', '》'], ['〈', '〉'],
]);

const 숫자인가 = (c) => c != null && c >= '0' && c <= '9';

/**
 * 글 하나를 문장 배열로 가른다. **원문 글자를 지우거나 바꾸지 않는다**(앞뒤 공백만 턴다).
 *
 * ■ 안 자르는 자리 셋 — 자를 곳을 못 찾으면 **안 자르는 쪽**으로 넘어진다
 *   ⓐ 따옴표·괄호 «안»의 종결자 — 「같이 가자.」라고 했어요 는 한 문장이다.
 *   ⓑ 숫자 사이의 마침표 — `3.5`·`2026.08` 은 소수점이지 문장 끝이 아니다.
 *   ⓒ 짝이 안 맞는 여는 따옴표가 있으면 그 뒤로는 안 자른다 — 틀리게 자르느니 통으로 둔다.
 *      (통으로 두면 학생이 오늘까지 하던 그대로다 = 손해가 «없음»이지 «새 손해»가 아니다.)
 *
 * ■ 🔴 상한을 넘겨도 **버리지 않는다**
 *   `상한` 번째 조각부터는 자르기를 멈추고 남은 글을 **통째로** 마지막 조각에 담는다.
 *   조각을 다시 이어 붙이지 않는 이유는 그 순간 원문 공백이 우리 손에 재조립되기 때문이다 —
 *   학생이 따라 말할 글자는 서버가 낸 그 글자여야 한다.
 *
 * @param {string} 글
 * @returns {string[]} 빈 글이면 `[]` · 못 자르면 `[글]`
 */
function 문장들(글) {
  const 글자 = Array.from(String(글 == null ? '' : 글));
  const 조각들 = [];
  const 열림 = [];
  let 시작 = 0;

  for (let i = 0; i < 글자.length; i++) {
    const c = 글자[i];
    if (열림.length && c === 열림[열림.length - 1]) { 열림.pop(); continue; }
    if (여는것.has(c)) { 열림.push(여는것.get(c)); continue; }
    if (열림.length) continue;                 // ⓐ 따옴표 안
    if (!종결자.has(c)) continue;
    if (c === '.' && 숫자인가(글자[i - 1]) && 숫자인가(글자[i + 1])) continue;   // ⓑ 소수점
    if (조각들.length >= 상한 - 1) break;      // 🔴 상한 — 남은 것은 통째로 마지막 조각

    let j = i + 1;
    while (j < 글자.length && (종결자.has(글자[j]) || 뒤따르는것.has(글자[j]))) j++;
    /* 뒤에 글자가 없으면 자를 이유가 없다 — 자르면 빈 조각이 하나 생긴다. */
    if (!글자.slice(j).join('').trim()) break;

    const 조각 = 글자.slice(시작, j).join('').trim();
    if (조각) 조각들.push(조각);
    시작 = j;
    i = j - 1;
  }

  const 끝 = 글자.slice(시작).join('').trim();
  if (끝) 조각들.push(끝);
  return 조각들;
}

module.exports = { 문장들, 상한 };
