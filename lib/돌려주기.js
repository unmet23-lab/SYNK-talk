'use strict';
/**
 * 돌려주기 — 미니게임이 끝나는 자리에서 학생에게 **관찰 한 줄**을 돌려주는 조립기. 순수 함수만.
 *
 * 정본 = appsscript `docs/SYNK_철학.md` **Ⅱ-8 「알아낸 것은 학생에게 돌려준다」**(v1.4 신설) 셋째 실물:
 *   *「미니게임이 끝날 때 관찰 한 줄. 점수 대신 『너는 소리가 나올 때 더 빨라진다』. 수집한 것을
 *   **그 자리에서** 돌려주니, 수집이 가져가는 일이 아니라 주는 일이 된다.」*
 *   같은 조항이 형태도 못박았다 — **새 화면을 늘려서 풀지 않는다. 학생이 이미 보는 자리에 얹는다.**
 *   그래서 이 파일의 소비자는 `src/교수멘탈화면.js` 의 **이미 있는 「보냈어요」 카드** 하나다.
 *
 * ■ 🔴 재료를 새로 모으지 않는다 — 이미 기기에 있는 것만 읽는다
 *   `lib/게임로그.js` 항목은 보낸 사건을 **통째로** 들고 있어서(그 파일 머리말 「`사건` 을 통째로
 *   들고 있는다」) 지난 앉음의 `payload.compose_meta`·`payload.selected_option` 이 그대로 남아
 *   있다. 새 저장·새 사건·새 조회가 **0**인 이유다 — **읽기는 사건을 만들지 않는다**
 *   (`src/어제의나.js` 와 같은 판정: 열람 기록이 필요해지면 그때 계약 개정이고, 미리 보내면
 *   계약에 없는 행이 append-only 로 남아 못 지운다).
 *
 * ■ 🔴 문턱을 만들지 않는다 — 실학생이 **0명**이라 「오래」의 눈금을 못 잰다
 *   시간 축(`first_keystroke_ms`·`total_compose_ms`)은 문턱이 있어야 말이 된다. 그 문턱을 댈
 *   표본이 0인데 지금 정하면 **잡음이 관찰의 얼굴을 하고 나간다**. 그래서 이 파일은 **정수 축만**
 *   쓴다 — `revision_count`(되돌림 «구간» 수)와 `selected_option`(고른 전략)은 1 차이가 실제
 *   차이라 문턱 없이 대조된다. 시간 축은 표본이 오는 날 따로 판정한다.
 *   🚫 「일단 3초쯤으로 두고 나중에 튜닝」 — `lib/검수확정.js` 가 문턱 튜닝으로 30초 해상도
 *      문제를 못 푼 그 자리와 같은 병이다.
 *
 * ■ 🔴 `input_burst_max` 는 학생에게 **안 돌려준다**
 *   그 값은 「한 번에 들어온 덩어리」 휴리스틱이고 자동완성·키보드 예측·받아쓰기도 덩어리로
 *   들어온다(`lib/작성과정.js` 천장 절). 학생에게 돌려주면 관찰이 아니라 **의심**으로 읽힌다 —
 *   「검수 우선순위 신호 전용」이라는 그 파일의 판정을 화면이 뒤집지 않는다.
 *
 * ■ 🔴 비교 대상은 «지난번의 나» 하나뿐 (철학 Ⅰ 하지 않는 것 ㉢ · 브랜드 규칙 S1)
 *   남·평균·등수는 **입력에 들어오지도 않는다**(이 함수가 받는 것은 이 기기의 로그뿐이다).
 *   그래서 「비교하지 않는다」가 문구 검사가 아니라 **재료의 성질**로 지켜진다.
 *
 * ■ 🔴 화면에 숫자를 쓰지 않는다 (발주_게임모듈 G1 §6 «숨은 시계»)
 *   G1 은 화면에 시계·초·숫자·퍼센트가 0인 것이 규격이다. 관찰 한 줄도 그 규격 안이라
 *   문구에 수를 넣지 않는다 — 회귀가 `문구` 표를 통째로 훑어 못박는다.
 *
 * ■ 🔑 같은 줄을 연속으로 내지 않는다 — ① 세 조건의 «신선한가»가 깨지는 자리
 *   매번 전략을 바꾸는 학생은 매번 같은 줄을 본다. 그래서 앉음을 **처음부터 굴려** 직전에 낸
 *   종류를 알고, 같으면 다음 후보로 내린다. 저장 0 · 결정론 — 같은 로그면 언제 불러도 같은 줄이라
 *   화면이 리렌더될 때마다 말이 바뀌지 않는다.
 *
 * ■ 🔴 할 말이 없으면 **안 그린다**
 *   빈 자리를 남기면 「관찰이 없다」와 「관찰을 못 잰다」가 같은 모양이 된다(이 저장소가 반복해
 *   막아 온 형태). 첫 앉음에 되돌림이 0이 아니면 견줄 것이 없으므로 **아무 줄도 없다.**
 */

/** 후보 종류 — **이 배열의 순서가 곧 우선순위**다(앞이 먼저 뽑힌다). */
const 종류들 = Object.freeze(['전략바뀜', '안고침', '덜고침', '더고침']);

/**
 * 문구 — 학생이 읽는 글이라 브랜드 규칙(`.claude/skills/synk-brand`)을 지난다.
 * · 금칙어 0 · 숫자 0 · 남과의 비교 0 · 평가어(잘·못) 0 — 관찰이지 채점이 아니다.
 * · 「손실을 셀지 얻은 것을 셀지」 — 되돌림이 늘어난 날도 결핍이 아니라 **다듬은 과정**으로 센다.
 */
const 문구 = Object.freeze({
  전략바뀜: '지난번과 다른 방법을 골랐어요.',
  안고침: '한 번도 지우지 않고 끝까지 썼어요.',
  덜고침: '지난번보다 덜 고치고 썼어요.',
  더고침: '이번엔 여러 번 고쳐 가며 썼어요.',
});

/**
 * 로그에서 **제출된 앉음**만, 관찰이 쓰는 두 칸으로 줄여 시간순으로 낸다.
 *
 * 🔑 순서는 배열 순서를 그대로 믿는다 — `게임로그.항목추가` 가 `concat` 으로만 늘리므로
 *   담긴 순서가 곧 시간순이다(기기 시계를 다시 파싱하지 않는다 · 벽시계 금지와 같은 축).
 * 🔴 `되돌림` 은 **정수일 때만** 값이다. `compose_meta` 가 없는 제출(음성 등)·반쪽 객체는
 *   `null` 이고, `null` 은 「0회」가 아니라 「안 쟀다」다 — 대조에서 통째로 빠진다.
 *
 * @param {object[]} 로그 `lib/게임로그.js` 큐 항목 배열
 * @returns {{correlation_id: string, 되돌림: number|null, 전략: string|null}[]}
 */
function 앉음들(로그) {
  if (!Array.isArray(로그)) return [];

  /* 고름은 제출과 **다른 항목**이라 먼저 앉음별로 모은다(같은 correlation_id 로 이어진다). */
  const 전략 = new Map();
  for (const e of 로그) {
    if (!e || e.event_type !== 'choice.selected') continue;
    const 사건 = e.사건;
    const cid = 사건 && 사건.correlation_id;
    const 고른 = 사건 && 사건.payload && 사건.payload.selected_option;
    /* `selected_option` 은 계약상 택1이라 건너뜀·전량거절이면 `null` 이다 — 그 앉음은 전략이
     * 없는 것이지 「같은 전략」이 아니다(없는 것끼리는 대조하지 않는다 · 아래 `성립하는것`). */
    if (cid && 고른 != null && 고른 !== '') 전략.set(String(cid), String(고른));
  }

  const 결과 = [];
  for (const e of 로그) {
    if (!e || e.event_type !== 'submission.created') continue;
    const 사건 = e.사건;
    const cid = 사건 && 사건.correlation_id;
    if (!cid) continue;
    const m = 사건.payload && 사건.payload.compose_meta;
    결과.push({
      correlation_id: String(cid),
      되돌림: m && Number.isInteger(m.revision_count) ? m.revision_count : null,
      전략: 전략.has(String(cid)) ? 전략.get(String(cid)) : null,
    });
  }
  return 결과;
}

/**
 * 이 앉음에서 **성립하는** 후보들 — 우선순위 순서로.
 * 🔴 지난 앉음이 없거나 한쪽이 `null` 이면 그 대조는 성립하지 않는다(지어내지 않는다).
 */
function 성립하는것(이번, 지난) {
  const 성립 = new Set();
  if (지난 && 이번.전략 && 지난.전략 && 이번.전략 !== 지난.전략) 성립.add('전략바뀜');
  if (이번.되돌림 === 0) 성립.add('안고침');
  if (지난 && Number.isInteger(이번.되돌림) && Number.isInteger(지난.되돌림)) {
    if (이번.되돌림 < 지난.되돌림) 성립.add('덜고침');
    else if (이번.되돌림 > 지난.되돌림) 성립.add('더고침');
  }
  return 종류들.filter((k) => 성립.has(k));
}

/**
 * 앉음마다 «그때 낼 줄»을 처음부터 굴린다 — **직전에 낸 종류는 피한다**.
 *
 * 🔑 「직전에 낸 것」은 «직전 앉음»이 아니라 «마지막으로 실제로 낸 줄»이다. 줄이 안 나간 앉음은
 *   학생이 아무것도 못 봤으므로 그 사이를 건너뛰어도 같은 말이 두 번 보이지 않는다.
 *
 * @returns {Map<string, {종류: string, 글: string}>} 앉음 → 그 앉음에서 그릴 줄(없으면 키 없음)
 */
function 줄들(로그) {
  const 목록 = 앉음들(로그);
  const 결과 = new Map();
  let 마지막낸것 = null;
  let 지난 = null;
  for (const 이번 of 목록) {
    const 고른 = 성립하는것(이번, 지난).find((k) => k !== 마지막낸것) || null;
    if (고른) {
      결과.set(이번.correlation_id, { 종류: 고른, 글: 문구[고른] });
      마지막낸것 = 고른;
    }
    지난 = 이번;
  }
  return 결과;
}

/**
 * 화면이 부르는 자리 — 이 앉음에서 그릴 한 줄. **없으면 `null` 이고, `null` 이면 안 그린다.**
 *
 * @param {object[]} 로그 게임 로그 전량(이 기기의 것뿐)
 * @param {string|null} correlation_id **제출 사건의** 앉음 키 — 다시 열어 대기 화면으로 점프한
 *   날의 마운트 키가 아니다(그날은 새 `흐름id` 라 아무것도 안 맞는다).
 */
function 관찰한줄(로그, correlation_id) {
  if (correlation_id == null || correlation_id === '') return null;
  return 줄들(로그).get(String(correlation_id)) || null;
}

module.exports = { 종류들, 문구, 앉음들, 성립하는것, 줄들, 관찰한줄 };
