'use strict';
/* 캐시성적 — 벤더 `usage` 로 프롬프트 캐싱이 **실제로 걸렸는지**를 재는 눈금의 한 원천(2026-09-02).
 *
 * ■ 왜 제 파일인가 — `교정엔진.js` 에서 태어났고(08-09 「캐싱+배치」) 읽는 곳이 교정 통로뿐이었다.
 *   생성 통로(deliver-one)가 캐싱을 켜며(트랙 §1 캐싱) 같은 자가 둘째로 필요해졌다 — 자를 두 파일에
 *   적으면 갈린다. `벤더사유` 가 `교정엔진` 에서 나와 제 파일로 간 것과 같은 자리고, `교정엔진` 은
 *   **재수출만** 한다(호출부 `correct/index.ts`·`tools/eval-run.js` 는 한 글자도 안 고쳤다).
 * ⚠ 재수출이라도 **동봉은 따로 실린다** — `교정엔진.mjs` 를 든 함수는 `캐시성적.mjs` 도 같이 올려야
 *   한다. 안 올리면 `원격배포` 가 배포 전에 던진다(`tests/동봉신호.test.js` 「표가 닫혀 있다」).
 *
 * ■ 🔴 «0» 의 세 얼굴을 섞지 않는다 — 캐시는 안 걸려도 오류가 없고(접두가 문턱 미만이면 조용히 통과),
 *   usage 가 빠져도 200 이다. 그래서 읽음 0 은 세 뜻일 수 있다: ① 벤더를 안 불렀다 ② 200 인데 usage 가
 *   없다(자가 눈이 먼 것 — 0 이 아니라 「모름」) ③ 정말로 안 걸렸다. 셋이 같은 모양이면 「걸렸다」의
 *   반대말이 없다. `캐시장부` 가 호출·무계측을 따로 세어 셋을 가른다(appsscript `엔진_콘텐츠AI.js`
 *   `AI사용_기록_` 의 무계측 무늬 그대로).
 */

/**
 * 응답 하나의 캐시 눈금 — «값»만 낸다. usage 가 없으면 0 으로 접히므로 «없음»을 세는 자리는
 * 이 함수가 아니라 `캐시기록`(무계측)이다. 읽음이 계속 0이면 접두가 문턱 아래이거나 매번 바뀌는 것이다.
 */
function 캐시성적(usage) {
  const u = usage || {};
  return {
    입력: Number(u.input_tokens || 0),
    캐시생성: Number(u.cache_creation_input_tokens || 0),
    캐시읽음: Number(u.cache_read_input_tokens || 0),
  };
}

/** 성적 여럿을 한 칸으로. 배치 한 벌이 캐시를 몇 번 읽었는지가 그대로 절감액이다. */
function 성적합(성적들) {
  return (성적들 || []).reduce((a, b) => ({
    입력: a.입력 + b.입력,
    캐시생성: a.캐시생성 + b.캐시생성,
    캐시읽음: a.캐시읽음 + b.캐시읽음,
  }), { 입력: 0, 캐시생성: 0, 캐시읽음: 0 });
}

/** 빈 장부 — 분모 둘(호출·무계측) + 성적 세 칸. 호출 0 = 「벤더를 안 불렀다」의 얼굴. */
function 캐시장부() {
  return { 호출: 0, 무계측: 0, 입력: 0, 캐시생성: 0, 캐시읽음: 0 };
}

/** 응답 하나의 «얼굴» — 성적 객체 또는 `'무계측'`(usage 가 객체가 아니다). 「0」과 「모름」을 값으로 가른다. */
function 캐시얼굴(usage) {
  return usage && typeof usage === 'object' ? 캐시성적(usage) : '무계측';
}

/**
 * 200 응답 하나를 장부에 더하고 그 얼굴을 돌려준다. 무계측은 호출·무계측만 올리고 성적 칸은 안 건드린다
 * (0 을 더하면 ③ 「안 걸렸다」와 같은 얼굴이 된다). usage 값으로는 던지지 않는다 — 계측이 워커를 죽이면 안 된다.
 * @param {{호출:number,무계측:number,입력:number,캐시생성:number,캐시읽음:number}} 장부  `캐시장부()` 산출(제자리 갱신)
 * @param {unknown} usage  벤더 봉투의 usage
 * @returns {{입력:number,캐시생성:number,캐시읽음:number}|'무계측'}
 */
function 캐시기록(장부, usage) {
  if (!장부 || typeof 장부 !== 'object') throw new TypeError('캐시기록: 장부가 필요하다 — 캐시장부() 로 만든다');
  장부.호출 += 1;
  const 얼굴 = 캐시얼굴(usage);
  if (얼굴 === '무계측') { 장부.무계측 += 1; return 얼굴; }
  장부.입력 += 얼굴.입력;
  장부.캐시생성 += 얼굴.캐시생성;
  장부.캐시읽음 += 얼굴.캐시읽음;
  return 얼굴;
}

/** 로그 한 줄 — 세 얼굴이 글자로 갈린다: 「호출 0」 / 「무계측 n」 / 「읽음 0」. */
function 캐시줄(장부) {
  const t = 장부 && typeof 장부 === 'object' ? 장부 : 캐시장부();
  if (!t.호출) return '호출 0(벤더 응답 없음)';
  return `호출 ${t.호출} · 무계측 ${t.무계측} · 읽음 ${t.캐시읽음} · 생성 ${t.캐시생성} · 입력 ${t.입력}`;
}

module.exports = { 캐시성적, 성적합, 캐시장부, 캐시얼굴, 캐시기록, 캐시줄 };
