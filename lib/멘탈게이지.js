/** '-아/어서' 꼴이 아닌 「○서」 — 자리(에서·께서), 동시(-면서), 지시(여기서·거기서·어디서),
 *  순차(-고서). 이유 연결어미와 글자만 같은 이웃들이다. */
const 이유아닌앞글자 = new Set(['에', '께', '면', '기', '디', '고']);

/** 이유 칸 — 연결어미 꼴로 잰다: -기 때문에 · -느라 · -는 바람에 · -아/어서. */
function 이유있다(글) {
  if (/때문에|때문입니다|느라|는 바람에/.test(글)) return true;
  const 아어서 = /([가-힣])서(?=[\s,.!?…)]|$)/g;
  let 짝;
  while ((짝 = 아어서.exec(글))) {
    if (!이유아닌앞글자.has(짝[1])) return true;
  }
  return false;
}

/** 맺음 칸 — **글의 끝자리**(마지막 15자)에서만 잰다: 본문 중간의 감사 인사는 맺음이 아니다.
 *  창을 넓히면 끝 문장 하나 앞의 감사까지 맺음으로 오탐한다(회귀 픽스처가 재는 그 자리).
 *  ⚠ 「-주시면 감사하겠습니다」로 끝난 글은 요청이지 맺음이 아니다 — 「감사하겠」은 안 걸린다. */
function 맺음있다(글) {
  const 끝창 = Array.from(글.trim()).slice(-15).join('');
  return /감사합니다|감사드립니다|올림|드림|안녕히 계/.test(끝창);
}

/**
 * 칸별 판정기 — 키가 곧 칸 이름이고, 팩 `요구문형` 의 키와 1:1 이어야 한다(회귀가 잡는다).
 * 패턴은 판정이지 모범답안이 아니다 — 화면에 노출하지 않는다.
 */
const 판정기 = Object.freeze({
  인사: (글) => /안녕하(?:십니까|세요)|인사드립니다|처음 뵙겠습니다/.test(글),
  사과: (글) => /죄송|사과드리|미안/.test(글),
  이유: 이유있다,
  요청: (글) => /주시면|주시겠|주실 수|주시기|부탁드리|부탁합니다|주세요|고자 합니다/.test(글),
  맺음: 맺음있다,
});

/**
 * 5칸을 판정한다 — 게이지·빠진 칸 안내가 쓰는 유일한 입구.
 *
 * @param {string} 글       본문 전체(RN `onChangeText` 가 주는 모양 그대로)
 * @param {object} 요구문형 `펴기(prompt_seed).요구문형` — 칸 이름·순서의 정본
 * @returns {{칸별:Object<string,boolean>, 채움수:number, 전체수:number, 빠진칸:string[]}|null}
 *          재료가 아니거나 판정기 없는 칸이 있으면 `null` — 반쪽 판정을 내지 않는다.
 */
function 판정(글, 요구문형) {
  if (typeof 글 !== 'string') return null;
  if (!요구문형 || typeof 요구문형 !== 'object' || Array.isArray(요구문형)) return null;
  const 칸이름들 = Object.keys(요구문형);
  if (칸이름들.length === 0) return null;
  const 칸별 = {};
  for (const 이름 of 칸이름들) {
    if (typeof 판정기[이름] !== 'function') return null;
    칸별[이름] = 판정기[이름](글);
  }
  const 빠진칸 = 칸이름들.filter((이름) => !칸별[이름]);
  return Object.freeze({
    칸별: Object.freeze(칸별),
    채움수: 칸이름들.length - 빠진칸.length,
    전체수: 칸이름들.length,
    빠진칸: Object.freeze(빠진칸),
  });
}

/**
 * 두 판정이 같은가 — 화면은 이것이 false 일 때만 리렌더를 건다(한글 조합 보호).
 */
function 같은판정(앞, 뒤) {
  if (앞 === 뒤) return true;
  if (!앞 || !뒤) return false;
  if (앞.채움수 !== 뒤.채움수 || 앞.전체수 !== 뒤.전체수) return false;
  const 이름들 = Object.keys(앞.칸별);
  if (이름들.length !== Object.keys(뒤.칸별).length) return false;
  return 이름들.every((이름) => 앞.칸별[이름] === 뒤.칸별[이름]);
}

module.exports = { 판정기, 판정, 같은판정 };
