/* ── 명부 표 읽기 ─────────────────────────────────────────────────────────────
 * 시트에서 **내려받은 그 파일**(CSV/TSV)이든 시트에서 **그대로 긁은 칸들**(스윕)이든
 * 같은 해석을 지난다. 사람이 형식을 맞추게 하면 그 변환이 새 오류원이 된다
 * (옮겨 적다 틀린 전화 = 조용한 잠금).
 */

/** CSV/TSV 한 판 → 칸들의 행. 따옴표 안의 구분자·줄바꿈·이스케이프(`""`)를 지킨다. */
function 표파싱(텍스트, 구분자) {
  const 행들 = [];
  let 칸 = '';
  let 행 = [];
  let 따옴표안 = false;
  for (let i = 0; i < 텍스트.length; i += 1) {
    const c = 텍스트[i];
    if (따옴표안) {
      if (c !== '"') { 칸 += c; continue; }
      if (텍스트[i + 1] === '"') { 칸 += '"'; i += 1; continue; }   // `""` = 따옴표 한 개
      따옴표안 = false;
      continue;
    }
    if (c === '"' && 칸 === '') { 따옴표안 = true; continue; }
    if (c === 구분자) { 행.push(칸); 칸 = ''; continue; }
    if (c === '\r') continue;
    if (c === '\n') { 행.push(칸); 행들.push(행); 행 = []; 칸 = ''; continue; }
    칸 += c;
  }
  if (칸 !== '' || 행.length) { 행.push(칸); 행들.push(행); }
  return 행들;
}

/** 탭이 한 개라도 있으면 TSV — 시트에서 **복사해 붙인** 판이 그 모양이다. */
function 구분자추측(텍스트) {
  return (텍스트.split('\n', 1)[0] || '').includes('\t') ? '\t' : ',';
}

/** U+FEFF(BOM). 🔴 소스에 **눈에 안 보이는 글자**를 박지 않는다 — 다음 사람이 지우고도 모른다. */
const BOM = String.fromCharCode(0xFEFF);

/** 머리글 대조용 접기 — 사람이 실제로 쓰는 표기 차이(공백·밑줄·괄호·대소문자)만 민다.
 *  ⚠ `\s` 는 U+FEFF 도 포함한다(ECMAScript WhiteSpace) — 그래서 BOM 이 붙은 머리글도 여기서 접힌다. */
const 열키 = (s) => String(s == null ? '' : s).replace(/[\s_()[\]]/g, '').toLowerCase();

/* 🔴 **정본은 운영 시트다.** `profiles` 열 지도 = appsscript `Code.js:955-957`
 *   (`1 user_id · 2 이름 · 3 이름_몽골 · 4 role · 5 class_name · … · 8 연락처`).
 *   첫 판은 `user_id` 를 빠뜨려 **유호님이 시트를 그대로 내려받는 그 경로**에서 파일이 통째로
 *   거절됐다(08-09 실측 — `연락처` 는 맞아서 「번호 ✗ · 전화 ✓」로 떴다). 사람이 실제로 쓰는
 *   표기로 검사하지 않으면 이 자리는 영원히 초록이다. */
const 열별칭 = {
  번호: ['학생번호', '학생ID', 'student_code', 'user_id', '학번', '번호', 'code'],
  전화: ['전화', '전화번호', '연락처', '휴대폰', '핸드폰', 'contact', 'phone'],
  이름: ['이름', '성명', '학생이름', 'name', 'display_name'],
  역할: ['role', '역할', '구분'],
};

/** 이 줄이 학생인가 — 시트 `role` 값은 `student`·`teacher`·`parent` 가 섞인다. */
const 학생인가 = (값) => ['student', '학생'].includes(열키(값));

/** 머리글 행 → 열 자리. 못 찾으면 -1 (선택 열인 `이름`만 -1 로 살아남는다). */
function 헤더찾기(칸들) {
  /* 🔴 자리 목록을 여기 손으로 적지 않는다 — `열별칭` 에 `역할` 을 더했는데 이 초기값에만
   *   안 적혀 `자리.역할` 이 `undefined` 였고, `=== -1` 검사가 통째로 빗나가 **필터가 아예
   *   안 돌았다**(08-09 실측 — 강사가 그대로 통과했다). 같은 판정은 한 곳에서 파생시킨다. */
  const 자리 = {};
  for (const 키 of Object.keys(열별칭)) 자리[키] = -1;
  (칸들 || []).forEach((c, i) => {
    const k = 열키(c);
    for (const [키, 별칭들] of Object.entries(열별칭)) {
      if (자리[키] === -1 && 별칭들.some((a) => 열키(a) === k)) 자리[키] = i;
    }
  });
  return 자리;
}

/**
 * 표에서 머리글을 세운다 → `{첫줄, 자리, 오류}`. 오류가 있으면 표 전체가 **읽기 불가**다 —
 * 행 하나의 문제가 아니라서(위치로 짐작하면 이름을 전화로 읽는다) 스윕도 여기서는 멈춘다.
 */
function 머리글자리(표) {
  const 첫줄 = (표 || []).find((r) => r.some((v) => String(v == null ? '' : v).trim() !== ''));
  if (!첫줄) return { 첫줄: null, 자리: null, 오류: ['파일이 비어 있다'] };
  const 자리 = 헤더찾기(첫줄);
  if (자리.번호 === -1 || 자리.전화 === -1) {
    const 없는것 = [자리.번호 === -1 ? '학생번호' : null, 자리.전화 === -1 ? '전화' : null].filter(Boolean);
    return {
      첫줄,
      자리,
      오류: [`첫 줄이 **머리글**이어야 하는데 ${없는것.join('·')} 열을 못 찾았다.`,
        `  받은 첫 줄: ${첫줄.join(' | ')}`,
        `  쓸 수 있는 이름 — 학생번호: ${열별칭.번호.join(' · ')}`,
        `                  전화: ${열별칭.전화.join(' · ')}`,
        `                  이름(선택): ${열별칭.이름.join(' · ')}`],
    };
  }
  return { 첫줄, 자리, 오류: [] };
}

/**
 * 칸들의 표 한 판 → `{행들, 대상아닌행, 오류}`. 순수 함수라 파일 없이 검사할 수 있다.
 *
 * 🔴 **머리글을 요구한다.** 「첫 줄은 학생번호, 둘째 칸은 전화」로 위치를 가정하면 열 순서가
 *   다른 시트에서 **이름을 전화로** 읽고, 그 학생은 명부에 서지만 게이트가 영원히 안 맞는다.
 *   증상이 F269 와 같은 「앱에서 안 된다」라서, 애매하면 읽지 않는 쪽으로 간다.
 *
 * 🔴 **`profiles` 는 학생 전용 표가 아니다** — `role` 에 `student`·`teacher`·`parent` 가 섞인다
 *   (appsscript `Code.js:3727`·`3873` 이 그 열로 강사를 가른다). 안 보면 두 갈래로 터진다:
 *   ①강사 번호가 `SYNK-NNN` 이면 **강사가 학생 명부에 서고 그 계정으로 첫 등록이 열린다**
 *   ②아니면 거절 목록에 떠서 화면이 「파일을 고쳐 다시 돌려라」로 시키므로, 운영자가
 *     **강사에게 SYNK 번호를 붙이는 것**이 처방을 따르는 행동이 된다(F103 — 따를 수 없는
 *     처방은 우회를 정상 통로로 만든다). 둘 다 08-09 에 실측으로 재현했다.
 *   → 강사·학부모는 **고칠 대상이 아니라 대상이 아닌 행**이라 거절이 아니라 **건너뛴다.**
 *   ⚠ 단 열이 있는데 **전량 비어 있으면 그 열을 무시한다** — 안 그러면 전원 건너뜀이라
 *     도구가 통째로 무용지물이 된다(막는 방향이 늘 안전한 것은 아니다).
 *   ⚠ 열을 쓰는데 **그 줄만 비었으면 거절**한다 — 학생인지 아닌지 모르는 채 넘기면
 *     조용히 빠지고, 그 학생은 개원 첫날에야 드러난다. 「애매하면 안 나간다」.
 */
function 표읽기(표) {
  const 머리 = 머리글자리(표);
  if (머리.오류.length) return { 행들: [], 오류: 머리.오류 };
  const { 첫줄, 자리 } = 머리;

  const 머리줄 = 표.indexOf(첫줄);
  const 읽은것 = [];
  for (let i = 머리줄 + 1; i < 표.length; i += 1) {
    const 칸 = 표[i];
    const 값 = (j) => (j === -1 ? '' : String(칸[j] == null ? '' : 칸[j]).trim());
    const 번호 = 값(자리.번호);
    const 전화 = 값(자리.전화);
    const 이름 = 값(자리.이름);
    const 역할 = 값(자리.역할);
    if (번호 === '' && 전화 === '' && 이름 === '' && 역할 === '') continue;   // 시트 아래쪽 빈 줄
    읽은것.push({ 번호, 전화, 이름, 역할, 줄: i + 1 });
  }

  /* 역할 열이 **실제로 쓰이고 있을 때만** 거른다(위 ⚠ 둘). */
  const 역할씀 = 자리.역할 !== -1 && 읽은것.some((r) => r.역할 !== '');
  if (!역할씀) return { 행들: 읽은것, 대상아닌행: [], 오류: [] };

  const 행들 = [];
  const 대상아닌행 = [];
  const 오류 = [];
  for (const r of 읽은것) {
    if (r.역할 === '') {
      오류.push(`${r.줄}번째 줄 ${r.번호 || '(번호 없음)'} — 역할 칸이 비어 있다`
        + '\n      다른 줄엔 role 이 적혀 있어 이 열을 쓰는 파일로 봤다. 학생인지 아닌지 모르는 채'
        + '\n      넘기면 그 학생이 조용히 빠지고, 개원 첫날에야 드러난다.');
    } else if (학생인가(r.역할)) {
      행들.push(r);
    } else {
      대상아닌행.push(r);
    }
  }
  return { 행들, 대상아닌행, 오류 };
}

/**
 * 텍스트 한 판(내려받은 CSV/TSV) → 표읽기. BOM 을 벗기는 것까지가 텍스트 층의 일이다.
 * 🔴 시트에서 내려받은 CSV 는 **BOM 으로 시작한다** — 안 벗기면 첫 머리글이 `<BOM>학생번호` 가
 *   되어 어느 별칭과도 안 맞고, 화면엔 눈에 안 보이는 한 글자 때문에 「머리글이 없다」로 뜬다.
 */
function 명부읽기(텍스트) {
  const 받은것 = String(텍스트 == null ? '' : 텍스트);
  const 원문 = 받은것.startsWith(BOM) ? 받은것.slice(1) : 받은것;
  return 표읽기(표파싱(원문, 구분자추측(원문)));
}

/* ── 검증 — 붓기 전에 **전부** 본다 ──────────────────────────────────────────
 * 🔴 한 줄이라도 규격 밖이면 CLI 는 **아무것도 넣지 않는다**(전량 거절 — 사람이 그 자리에서
 *   고칠 수 있는 문이라서다). 스윕은 같은 판정을 **행별로** 받아 문제 행을 소리 내어 알리고
 *   멀쩡한 행은 흘린다 — 무인 문에서 전량 거절은 남의 오타 하나가 신입 전원을 영원히 막는
 *   모양이 된다(F103). **판정은 하나, 문마다 다른 것은 거절의 단위뿐이다.**
 */

/** 행마다 판정 하나 — `{행, 오류}` (오류 null = 규격 안). `검증`·`행별가르기` 둘 다 여기서 파생한다. */
function 행검사들(행들) {
  const 결과 = [];
  const 본것 = new Map();
  for (const r of 행들) {
    if (!학생번호맞나(r.번호)) {
      결과.push({
        행: r,
        오류: `${r.줄}번째 줄 — 학생번호 형식이 아니다: ${r.번호 || '(비어 있다)'}`
          + '\n      발급기가 내는 형태여야 한다(SYNK-001 · SYNK-1000). 자릿수는 접지 않는다 — SYNK-42 ≠ SYNK-042.',
      });
      continue;
    }
    /* 게이트와 **같은 함수**로 잰다 — 여기서 따로 세면 그 순간 둘이 갈라진다. */
    if (뒤4자리(r.전화) === null) {
      결과.push({
        행: r,
        오류: `${r.줄}번째 줄 ${학생번호표기(r.번호)} — 전화가 없다(숫자 4개 이상 필요${r.전화 ? `, 받은 값: ${r.전화}` : ''})`
          + '\n      뒤 4자리가 첫 등록 게이트의 **유일한 대조값**이다(§4-1-1). 비면 그 학생은'
          + '\n      「대조 불가로 잠금」이라 스스로 등록을 못 하고, 증상은 「앱에서 안 된다」뿐이다.',
      });
      continue;
    }
    /* 🔴 파일 안 중복 — 앱과 같은 방식으로 접어서 본다. `SYNK042` 와 `SYNK-042` 는 한 학생이다. */
    const 키 = 정규형(r.번호);
    if (본것.has(키)) {
      결과.push({
        행: r,
        오류: `${r.줄}번째 줄 ${학생번호표기(r.번호)} — ${본것.get(키)}번째 줄과 **같은 학생**이다`
          + '\n      한 학생이 두 행이 되면 첫 등록이 둘 다 집어 어느 쪽이 그 학생인지 알 수 없게 된다.',
      });
    } else {
      본것.set(키, r.줄);
      결과.push({ 행: r, 오류: null });
    }
  }
  return 결과;
}

/** CLI 의 얼굴 — 오류 문구만 모아 준다(전량 거절의 재료). 문구·순서는 종전과 같다. */
function 검증(행들) {
  return 행검사들(행들).map((x) => x.오류).filter(Boolean);
}

/** 스윕의 얼굴 — 같은 판정을 행별로 가른다. `문제들` 은 알림에 실을 수 있게 줄·번호를 든다. */
function 행별가르기(행들) {
  const 결과 = 행검사들(행들);
  return {
    정상: 결과.filter((x) => !x.오류).map((x) => x.행),
    문제들: 결과.filter((x) => x.오류).map((x) => ({ 줄: x.행.줄, 번호: x.행.번호 || '', 사유: x.오류 })),
  };
}

/**
 * 이미 명부에 있는 학생 한 명을 어떻게 다룰까 — `'건너뜀'` 이냐 `'막힘'` 이냐.
 *
 * 🔑 **게이트가 재는 것과 같은 것을 잰다.** 전체 문자열로 비교하면 `9911-2233` 과 `99112233`
 *   이 「다르다」로 나와, 아무 문제도 없는 명부가 매번 거절당한다 — 그러면 원장은 이 도구를
 *   안 쓰고 한 명씩으로 돌아간다. 첫 등록이 실제로 대조하는 값은 **뒤 4자리 하나**다(§4-1-1).
 *
 * 순수 함수인 이유: 여기가 이 통로에서 **조용히 틀릴 수 있는 유일한 자리**다(막아야 할 것을
 * 건너뛰면 그 학생이 개원 첫날 잠기고, 건너뛸 것을 막으면 동기화가 영영 안 돈다).
 * ⛔ 어느 문도 여기서 연락처를 **덮지 않는다** — `contact` 를 갈면 그 학생의 첫 등록
 *   대조값이 조용히 바뀐다. 어느 쪽이 맞는 번호인지는 사람이 안다.
 */
function 대조판정(기존, 행) {
  const 명부뒷자리 = 뒤4자리(기존.contact);
  if (명부뒷자리 === null) {
    return {
      종류: '막힘',
      번호: 기존.student_code,
      사유: '명부의 연락처가 비어 있다 — 그 학생은 지금 첫 등록이 잠겨 있다(이 도구는 덮지 않는다)',
    };
  }
  if (명부뒷자리 !== 뒤4자리(행.전화)) {
    return {
      종류: '막힘',
      번호: 기존.student_code,
      사유: `연락처가 다르다 — 명부 …${명부뒷자리} · 파일 …${뒤4자리(행.전화)}`,
    };
  }
  return { 종류: '건너뜀', 번호: 기존.student_code, 계정있음: !!기존.auth_user_id };
}

/**
 * 명부 행들 + DB 에 이미 있는 행들 → **무엇을 넣고 무엇을 건너뛰고 무엇이 막혔나**.
 * 순수 함수다 — 호출자 안에 두면 DB 없이는 한 줄도 검사할 수 없다.
 */
function 계획(행들, 있는행들) {
  const 기존맵 = new Map((있는행들 || []).map((row) => [정규형(row.student_code), row]));
  const 넣을것 = [];
  const 건너뛴것 = [];
  const 막힌것 = [];
  for (const r of 행들) {
    const 기존 = 기존맵.get(정규형(r.번호));
    if (!기존) { 넣을것.push(r); continue; }
    const 판정 = 대조판정(기존, r);
    (판정.종류 === '막힘' ? 막힌것 : 건너뛴것).push(판정);
  }
  return { 넣을것, 건너뛴것, 막힌것 };
}

/**
 * CLI 가 다음에 할 일. `main()` 은 이 답을 **집행만** 한다.
 * 🔴 순서가 곧 안전이다 — 막힌 것이 하나라도 있으면 `--적용` 이라도 붓지 않는다.
 *   「되는 것만 넣기」는 원장 화면에 「완료」를 띄우고 빠진 학생을 개원 첫날까지 감춘다.
 *   (스윕의 거절 단위는 위 검증 절 머리말 — 행별 + 소리 내는 알림.)
 */
function 행동정하기({ 막힌것, 넣을것 }, 적용) {
  if (막힌것.length) return '거절';
  if (!적용) return '미리보기';
  if (!넣을것.length) return '넣을것없음';
  return '붓기';
}

