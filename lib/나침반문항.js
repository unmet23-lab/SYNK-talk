'use strict';
/**
 * 나침반 문항 — 시즌 회고가 병치할 **왼쪽**의 정본
 * (정본 = appsscript `docs/시즌회고_설계.md` v3 §3-1·§9-2 · 유호님 확정 08-12).
 *
 * ■ 왜 지금 짓나 — 이것만 **소급이 원리상 불가능**하다 (설계 §2)
 *   회고는 「그때 이 학생이 스스로 뭐라고 말했나」와 「그 뒤 실기록」을 나란히 놓는 일이다.
 *   오른쪽(8축·집계)은 사건이 쌓이면 언제든 다시 계산되지만, **왼쪽은 그날 안 물으면 영원히
 *   빈칸**이다. 나중에 다시 물어도 나오는 것은 오늘의 답이지 그때의 답이 아니다 —
 *   `learners.goal_track` 이 이미 그 병으로 죽어 있다(설계 §2 · L0 §850 `goal_snapshot`).
 *   🔴 2026-08-12 두 저장소 전수 검색: `나침반`·`compass`·`season` 구현 **0건**. 살아 있는 것은
 *      상담AI FAQ Q11(`확정: true`)의 **대외 약속**뿐이다 — 「입학할 때, 그리고 시즌마다」.
 *      그래서 시한은 개원일이 아니라 **첫 학생의 «입학일»** 이다(설계 §8 ①).
 *
 * ■ 값은 문항키(ASCII 코드값), 화면 글자는 라벨 — `lib/가입문항.js` 규약 승계
 *   라벨은 몽골어 병기·눈높이 조정으로 계속 바뀐다. 그때마다 쌓인 답이 흔들리지 않도록
 *   행에 들어가는 키는 코드다(설계 §9-2 ㉢ — 「문구는 싸고 개수·키는 비싸다」).
 *
 * ■ 🔴 몽골어 라벨을 **지어 넣지 않는다** (설계 §9-2 ㉦-2)
 *   나침반은 급수 1 학생도 지나고 강사가 몽골어로 촉진한다. 검수자는 1인이고 그 검수는
 *   결정큐의 기존 항목이다 — 미검수 번역을 화면에 올리면 그것이 사실상 정본이 된다.
 *   🔑 문항키가 코드값이라 **검수 전에도 통로는 지을 수 있다**(막히는 것은 화면 문구뿐).
 *   그래서 `라벨_mn` 은 `null` 로 **자리만** 두고, 화면은 없으면 한국어를 그린다.
 *
 * ■ 문항 넷 — 셋은 «장기», 넷째가 «이번 시즌» (설계 §9-2 ㉡·㉤)
 *   ①`why_learning` ②`self_in_5y` ③`topik_use` 는 입학 1회. ④`season_goal` 은 시즌마다.
 *   ④가 없으면 **2달 회고가 원리상 판정을 못 한다** — 과녁이 5년짜리뿐이면 강사가 매번
 *   「제자리」를 눌러 라벨이 전부 같은 값이 되고, 그건 엔진 학습 0이다(설계 §9-2 ㉣).
 *
 * 🚫 문항을 여기서 늘리지 않는다 — 첫 행이 쌓인 뒤에 늘리면 시즌 1과 시즌 2의 답 개수가 달라
 *   **병치표가 갈린다**(가입문항의 「1회 문항」과 같은 병). 개수 변경은 계약 개정 자리다.
 * 🚫 `topik_use` 를 목적별 문항으로 쪼개기 — 키는 하나, **문구만** 목적별로 가른다(㉦-1).
 * 🚫 `season_goal` 을 지표·마감·달성기준으로 쪼개기 — 학생 화면이 계획서가 되고 2달마다
 *   6번 쓰는 일이 된다(유호님 「간편하게·실용적으로」 위반 · 설계 §9-2 ㉤).
 * 🚫 답을 시스템이 자동 채점하기 — 「목표 런타임 자동 판정 🚫」 승계(설계 §10).
 */

/** 회차 종류 — 저장되는 값이 아니라 **어느 문항 묶음을 묻나**의 코드값. */
const 종류 = Object.freeze({ 입학: 'enrollment', 시즌: 'season' });

/* 서술 길이 상한 — 화면이 아니라 여기서 정한다(화면이 정하면 강사 화면·학생 화면이 갈린다).
 * 🔑 상한의 목적은 「짧게 쓰게 만들기」가 아니라 **한 칸이 문서가 되는 것을 막기**다.
 *   `season_goal` 이 더 짧은 것은 설계가 「한 줄」로 못박았기 때문이다(§9-2 ㉤). */
const 서술상한 = 500;
const 한줄상한 = 200;

/**
 * 문항 정본 넷.
 * - `키`      = 행에 앉는 코드값(영원히 안 바뀐다)
 * - `라벨`    = 화면 글자(한국어 · 언제든 다듬는다)
 * - `라벨_mn` = 몽골어 — **검수 전이라 전부 `null`**(위 머리말)
 * - `목적별`  = 목적(`goal_track`)에 따라 문구만 갈리는 자리. 없으면 `라벨` 하나로 끝난다.
 * - `회차`    = 어느 묶음에 드나
 */
const 문항 = Object.freeze([
  Object.freeze({
    키: 'why_learning',
    회차: 종류.입학,
    라벨: '왜 한국어를 배우나요?',
    라벨_mn: null,
    상한: 서술상한,
    // 회고에서 끈기·리듬 축과 병치된다 — 「그 이유가 실제로 버티게 했는가」(설계 §9-2 ㉡ ①)
  }),
  Object.freeze({
    키: 'self_in_5y',
    회차: 종류.입학,
    라벨: '5년 뒤의 나는 어떤 모습인가요?',
    라벨_mn: null,
    상한: 서술상한,
    // 시즌마다 «지난 답 그대로 보여주고» [그대로]/[바꿀래] — `redirected` 판정의 유일한 근거
  }),
  Object.freeze({
    키: 'topik_use',
    회차: 종류.입학,
    라벨: 'TOPIK을 언제, 어디에 쓸 건가요?',
    라벨_mn: null,
    상한: 서술상한,
    /* 🔑 `culture` 목적 학생에게 TOPIK 문구는 안 맞는 질문이다(설계 §9-2 ㉦-1).
     *   키는 하나로 두고 **문구만** 가른다 — 키를 가르면 병치표가 목적별로 갈린다. */
    목적별: Object.freeze({
      culture: '배운 한국어를 어디에 쓰고 싶은가요?',
    }),
  }),
  Object.freeze({
    키: 'season_goal',
    회차: 종류.시즌,
    라벨: '이번 교재에서 하고 싶은 것 한 가지는?',
    라벨_mn: null,
    상한: 한줄상한,
    /* 🔑 단위가 «교재 1권»인 것은 유호님 확정이다(설계 §9-0) — 「2달」은 근사값이고
     *   정본은 교재다. 그래서 문구도 「이번 시즌」이 아니라 「이번 교재」다. */
  }),
]);

/** 입학 회차에 묻는 것 = 넷 전부(장기 3 + 이번 시즌 1). 설계 §3-1 「입학 시즌 행 = 넷」. */
const 입학키 = Object.freeze(문항.map((q) => q.키));

/** 이후 시즌에 묻는 것 = 둘. 설계 §3-1 「이후 시즌 행 = `self_in_5y`·`season_goal`」.
 *  🔑 `self_in_5y` 는 [그대로]를 눌러도 **값을 복사해 담는다** — 행마다 자족해야
 *  병치 쿼리가 단순해지고, 「안 바꿨다」를 값 비교로 추측하지 않게 된다(설계 §3-1). */
const 시즌키 = Object.freeze(['self_in_5y', 'season_goal']);

const 키목록 = (회차) => (회차 === 종류.입학 ? 입학키 : 시즌키);
const 문항찾기 = (키) => 문항.find((q) => q.키 === 키) || null;

/**
 * 그 학생에게 실제로 보일 문항 목록(문구까지 확정된 것).
 *
 * @param {string} 회차 `종류.입학` · `종류.시즌`
 * @param {string|null} 목적 `learners.goal_track` 3값(`study`·`work`·`culture`)
 * @returns {{키: string, 라벨: string, 라벨_mn: string|null, 상한: number}[]}
 */
function 물을것(회차, 목적) {
  return 키목록(회차).map((키) => {
    const q = 문항찾기(키);
    const 갈래 = q.목적별 && 목적 ? q.목적별[목적] : null;
    return Object.freeze({ 키, 라벨: 갈래 || q.라벨, 라벨_mn: q.라벨_mn, 상한: q.상한 });
  });
}

/**
 * 답이 그 회차의 규격에 맞나.
 *
 * 🔴 **비어 있는 것도 실패다** — 가입문항 `답검사` 와 같은 이유다. 「빈 값은 통과」로 두면
 *   그 학생의 왼쪽이 조용히 빈 채로 굳고, 그건 위 머리말이 말한 그 손실이라 못 고친다.
 * 🔴 **모르는 키가 섞이면 실패다.** 통과시키면 오타 키(`why_learn`)가 행에 그대로 앉고,
 *   병치 쿼리는 그 학생만 빈칸으로 그린다 — 실패가 「데이터가 없다」의 얼굴로 온다.
 * 🔑 어느 칸이 왜 틀렸는지 **말한다**. 여기서 감추면 앱 버그가 「저장이 안 된다」로만 보인다
 *   (첫 로그인 게이트의 「전부 같은 응답」은 학생번호의 존재를 감추려는 것이라 목적이 다르다).
 *
 * @param {string} 회차
 * @param {object} 답 문항키→서술
 * @param {boolean|null|undefined} 바꿨나 `self_in_5y_changed` — 시즌 회차에서만 뜻이 있다
 * @returns {{필드: string, 사유: string}|null} 통과면 `null`
 */
function 답검사(회차, 답, 바꿨나) {
  if (회차 !== 종류.입학 && 회차 !== 종류.시즌) {
    return { 필드: '회차', 사유: `회차는 ${종류.입학}·${종류.시즌} 중 하나여야 합니다` };
  }
  const a = 답 && typeof 답 === 'object' && !Array.isArray(답) ? 답 : {};
  const 기대 = 키목록(회차);

  for (const 키 of Object.keys(a)) {
    if (!기대.includes(키)) {
      return { 필드: 키, 사유: `이 회차(${회차})가 받는 문항이 아닙니다 — ${기대.join('·')}` };
    }
  }
  for (const 키 of 기대) {
    const v = a[키];
    if (typeof v !== 'string' || !v.trim()) {
      return { 필드: 키, 사유: '빈 답은 받지 않습니다(안 물어본 것과 구별이 안 됩니다)' };
    }
    const 상한 = 문항찾기(키).상한;
    if (v.length > 상한) {
      return { 필드: 키, 사유: `${상한}자를 넘습니다(${v.length}자)` };
    }
  }

  /* `self_in_5y_changed` — 시즌 회차의 **필수 칸**이다.
   * 🔑 이 칸이 있는 이유는 「값이 같으면 안 바꾼 것」이라는 추측을 없애기 위해서다(설계 §3-1).
   *   같은 문장을 다시 써서 제출한 학생과 [그대로]를 누른 학생은 다른 사건이고,
   *   `redirected` 판정의 근거는 **이 칸이 직접** 말한다.
   * 🔑 입학 회차에서는 `null` 이어야 한다 — 「안 물었다」다. `false` 로 적으면
   *   「물었고 안 바꿨다」가 되어 첫 행이 있지도 않은 지난 답을 가리킨다. */
  if (회차 === 종류.시즌) {
    if (typeof 바꿨나 !== 'boolean') {
      return { 필드: 'self_in_5y_changed', 사유: '시즌 회차에는 [그대로]/[바꿀래] 판정이 필요합니다' };
    }
  } else if (바꿨나 !== null && 바꿨나 !== undefined) {
    return { 필드: 'self_in_5y_changed', 사유: '입학 회차에는 지난 답이 없습니다 — null 이어야 합니다' };
  }
  return null;
}

module.exports = { 종류, 문항, 입학키, 시즌키, 물을것, 답검사, 서술상한, 한줄상한 };
