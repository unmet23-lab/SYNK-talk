/** 기본 캐릭터 — 부르는 쪽이 안 넘기면 여기로 떨어진다(개명 전과 100% 같은 동작). */
const 기본캐릭터 = '몽글';

const 상황들 = Object.freeze(Object.keys(배치[기본캐릭터]));

/** 미세 변주 폭 — ±3%. 0 이면 같은 소리가 매번 똑같이 난다(머리말 ③). */
const 흔들폭 = 0.03;

/** 겹침 최소 간격(ms) — 가장 긴 소리(마린 완수 680ms)보다 길어야 꼬리까지 안 포갠다. */
const 겹침막기ms = 700;

/**
 * 이 요청이 소리를 내도 되는가, 낸다면 어느 소리를 어느 속도로.
 *
 * @param {object} 인자
 * @param {string} [인자.캐릭터] '몽글'|'까몽'|'마린'. 안 넘기면 **몽글**(개명 전과 같은 동작).
 *   모르는 이름이면 몽글로 떨어진다 — 오타가 침묵을 정하지 않는다(아래 `상황`과 같은 규율).
 * @param {string} 인자.상황 `배치[캐릭터]` 의 키. 모르는 이름이면 **기본**으로 떨어진다(무음 아님 —
 *   화면이 오타를 내도 가이드는 말한다. 침묵은 게이트가 정하는 것이지 오타가 정하는 게 아니다).
 *   ⚠ **아는 이름인데 풀이 비었으면 조용히 «안 냄»**이다(정지선 ④) — 그 캐릭터에 그 소리가
 *   «없는» 것이라, 다른 소리로 메우면 배치가 거짓이 된다.
 * @param {number} 인자.지금 `Date.now()`
 * @param {number} [인자.마지막] 직전에 소리를 낸 시각
 * @param {string} [인자.직전소리] 직전에 난 소리 이름 — **연속으로 같은 소리를 피한다**(②의 실체).
 * @param {number} [인자.고르기] 0~1 난수(테스트가 고정값을 넣는다)
 * @param {number} [인자.흔들] 0~1 난수
 * @returns {{낼까: boolean, 소리?: string, 자산?: string, 속도?: number, 사유?: string}}
 */
function 목소리판정({ 캐릭터 = 기본캐릭터, 상황, 지금, 마지막 = 0, 직전소리 = null, 고르기 = 0, 흔들 = 0.5 }) {
  if (지금 - 마지막 < 겹침막기ms) {
    return { 낼까: false, 사유: `겹침(${지금 - 마지막}ms < ${겹침막기ms})` };
  }
  const 그캐릭터 = 배치[캐릭터] ? 캐릭터 : 기본캐릭터;
  const 줄 = 배치[그캐릭터];
  /* 아는 상황이면 그 풀(비었으면 빈 풀 그대로) · 모르는 상황이면 기본으로 — 둘을 가르는 것이
     이 줄이다. `줄[상황] || 줄.기본` 로 뭉치면 «빈 풀»이 «오타»와 같아져 안심 자리에
     기본 소리가 난다(정지선 ③④가 한꺼번에 깨진다). */
  const 후보 = Object.prototype.hasOwnProperty.call(줄, 상황) ? 줄[상황] : 줄.기본;
  if (!후보 || !후보.length) {
    return { 낼까: false, 사유: `빈 풀(${그캐릭터}·${상황}) — 이 캐릭터엔 그 자리의 소리가 없다` };
  }
  /* 같은 소리를 연달아 내지 않는다 — 후보가 둘 이상이면 직전 것을 뺀다.
     하나뿐인 상황(완료축하)은 그대로 낸다: 하루 한 번이라 반복이 안 생긴다. */
  const 고를것 = 후보.length > 1 && 직전소리 ? 후보.filter((s) => s !== 직전소리) : 후보;
  const 소리 = 고를것[Math.min(고를것.length - 1, Math.floor(고르기 * 고를것.length))];
  const 속도 = Math.round((1 + (흔들 * 2 - 1) * 흔들폭) * 1000) / 1000;
  return { 낼까: true, 소리, 자산: 소리들[그캐릭터][소리], 속도 };
}

