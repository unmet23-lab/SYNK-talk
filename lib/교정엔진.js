'use strict';
/**
 * 교정 엔진 — 학생 발화 한 줄 → **AI 1차 교정안**. 순수 함수만(네트워크·파일 0).
 *
 * ■ 이 파일이 닫는 것 — 「생산자가 0」이던 자리
 *   `engine.corrections` 를 **읽는** 곳은 넷이었는데(`functions/corrections`·`deliver`·검수 뷰·RLS)
 *   저장소 전체에 **INSERT 가 0줄**이었다. 그래서 검수 큐(`engine.review_queue`)는 「AI 교정이
 *   섰는가」를 inner join 으로 요구하는데 학생 제출 행에는 그 교정이 영원히 안 붙고, 큐는
 *   **구조적으로 0행**이다. 큐가 0이면 검수가 없고, 검수가 없으면 승격이 없고, 승격이 없으면
 *   엔진 도달이 영원히 0이다(대기열 P1 · `collection-engine-automation-mandate`).
 *
 * ■ 왜 **순수**인가 — 하네스가 이미 있다
 *   `evals/`(픽스처 100문항 + `tools/eval-score.js`)는 「프롬프트 → 출력 → 기계 채점」을 이미
 *   돌린다. 그런데 그 출력은 **대화 세션이 손으로 쓴 것**이라 `evals/결과.md` 가 스스로
 *   「실제 엔진 경로가 아니다」라고 적어 두었다. 요청 조립과 응답 해석이 여기 순수 함수로 있으면
 *   같은 코드를 배치와 eval 이 함께 쓴다 — 즉 **채점한 것이 곧 제품이 하는 것**이 된다.
 *   네트워크에 붙여 두면 그 대조가 영영 안 된다(왕복 없이는 못 재니까).
 *
 * ■ 🔴 값목록의 정본은 **계약 JSON 하나**다
 *   오류태그 24종은 `계약/수집_교정_계약.json` 의 `오류태그` 이고, `prompts/교정.md` 는 그것을
 *   사람이 읽는 프롬프트 안에 **다시 적어** 둔다(모델에게 보여줘야 하므로 피할 수 없다).
 *   두 벌이라 갈라질 수 있고, 갈라지면 증상이 **없다** — 모델이 계약 밖 태그를 붙이고 서버가
 *   그걸 그대로 적으면 2년치 집계가 조용히 깨진다(L0 §3-3 이 CHECK 를 안 걸고 「검증은 서버」로
 *   미룬 그 자리다). 그래서 `태그어긋남()` 이 **돌기 전에** 두 벌을 대조하고, `교정값()` 이
 *   **돌고 나서** 모델 출력을 계약으로 다시 거른다. 앞뒤로 두 번 막는다.
 *
 * ■ 🔴 못 읽은 응답은 **버린다**(빈 행을 만들지 않는다)
 *   `corrected_text` 도 `error_tags` 도 비운 행을 적으면 검수 뷰는 그 행 때문에 큐에 뜨고
 *   검수자 화면에는 **빈 카드**가 뜬다 — `functions/corrections` 가 학생 쪽에서 정확히 그것을
 *   막으려고 필터를 둔 모양이다. 여기서는 애초에 안 적는다(다음 배치가 다시 집는다).
 */

/* 계약이 지목한 자리는 「AI 1차안」이고(발주_게임모듈 §610 · L0 §679 `ai_processing_logs`),
 * 그 행이 지는 칸이 `model`·`prompt_ver`·`corrected_text`·`error_tags`·`explanation` 이다.
 * 🔑 모델 이름을 **행에 적는다** — 새 모델로 갈아탄 뒤에 옛 교정과 새 교정이 안 갈리면
 *   「모델을 바꿔서 좋아진 것」과 「학생이 늘어서 좋아진 것」을 영원히 못 가른다.
 * 🔴 교정은 콘텐츠 축이라 Sonnet 급이다(CLAUDE.md 모델 라우팅) — 정밀 검증이 아니다. */
const 모델 = 'claude-sonnet-5';

/* 벤더 왕복 상한. 전사(120초)보다 짧다 — 텍스트 한 줄이라 오래 걸리면 그건 느린 게 아니라
 * 막힌 것이다. 길게 잡으면 배치 하나가 벽시계를 다 쓰고 뒤엣것이 매번 잘린다. */
const 왕복제한밀리 = 60_000;

/** 모델이 낼 최대 토큰. 다섯 칸짜리 JSON 한 덩이라 넉넉하다 — 넘치면 잘린 JSON 이 오고
 *  `교정값()` 이 `형식밖` 으로 버린다(잘린 것을 반쯤 적는 것보다 낫다). */
const 최대토큰 = 1024;

/**
 * 프롬프트 판본을 **프롬프트 파일에서** 읽는다 — `prompts/교정.md` 머리말의 「현재 vN」.
 *
 * 🔑 손 상수로 두지 않는다: 프롬프트를 고치고 여기를 안 고치면 **새 프롬프트의 출력이 옛 판
 *   이름으로 쌓인다.** 그 오염은 소급이 안 된다 — 나중에 「v1 이 v2 보다 나았다」를 물을 때
 *   섞인 행을 갈라낼 근거가 어디에도 없다.
 * 🔴 못 읽으면 `null` 이고, 그때 배치는 **한 행도 안 적는다**. 「어느 프롬프트가 만들었나」를
 *   모르는 교정문은 학습 재료로 못 쓴다 — 모르는 것을 빈칸으로 적는 게 더 나쁘다.
 */
function 프롬프트판(지시문) {
  const m = /^>\s*\*\*현재\s+(v\d+)\*\*/m.exec(String(지시문 || ''));
  return m ? m[1] : null;
}

/**
 * 계약 값목록 ↔ 프롬프트 통제 어휘 대조. **어긋난 태그를 낸다**(같으면 빈 배열).
 *
 * `prompts/교정.md` 가 스스로 「⚠ 이 어휘는 수집층과 같아야 한다. 갈라지면 2년치 집계가
 * 깨진다」고 적어 두었다 — 그 문장을 기계로 옮긴 것이 이 함수다(산문으로 남은 경고는
 * 지켜지지 않는다). 배치는 어긋나면 **돌기 전에** 멈춘다.
 *
 * 🔑 부분 문자열이 아니라 **줄 안의 백틱 토큰**으로 센다. 프롬프트가 태그를 ``` `조사:기타` ```
 *   처럼 적으므로 그 표기를 그대로 집는다 — 산문 낱말(「조사」·「어순」)을 태그로 세면
 *   거짓양성이 쏟아지고, 쏟아지는 가드는 곧 꺼진다(F272 가 같은 자리에서 실측된 것).
 */
function 태그어긋남(지시문, 태그목록) {
  const 쓰인것 = new Set(
    [...String(지시문 || '').matchAll(/`([^`\n]+)`/g)].map((m) => m[1].trim()),
  );
  const 계약 = Array.isArray(태그목록) ? 태그목록 : [];
  return {
    // 계약엔 있는데 프롬프트가 모른다 → 모델이 그 태그를 **한 번도 못 붙인다**(조용한 축 소실).
    프롬프트에없음: 계약.filter((t) => !쓰인것.has(t)),
    // 프롬프트엔 있는데 계약 밖이다 → 모델이 붙여도 `교정값()` 이 전부 버린다(조용한 전량 폐기).
    계약에없음: [...쓰인것].filter((t) => /^(조사|어미|높임|어휘|맞춤법|어순|누락|중복|화용|오류없음)/.test(t)
      && !계약.includes(t)),
  };
}

/**
 * 벤더 요청 몸통(Anthropic Messages). **지시문을 여기서 짓지 않는다** — 정본은
 * `prompts/교정.md` 이고 이 함수는 그것을 그대로 `system` 에 싣는다. 여기서 한 줄이라도
 * 보태면 그 순간 프롬프트가 두 벌이 되고, `evals` 가 재는 것과 제품이 쓰는 것이 갈린다.
 *
 * 🔑 학생 문장은 **`user` 로만** 넣는다. 지시문에 끼워 넣으면 학생이 쓴 「위 지시를 무시하고…」
 *   같은 문장이 지시로 읽힌다 — 몽골 학생의 한국어 연습 문장이라 악의는 없겠지만, 사고는
 *   악의를 요구하지 않는다.
 * 🔑 급수를 함께 준다 — 프롬프트 규칙 4(「학생 수준을 넘는 표현으로 올리지 않는다」)가
 *   급수를 모르면 지킬 수 없는 규칙이다. 없으면 `미정` 으로 명시한다(빈칸으로 두면 모델이
 *   제 마음대로 가정하고, 그 가정은 행에 안 남는다).
 */
function 요청몸통({ 지시문, 문장, 급수 }) {
  return {
    model: 모델,
    max_tokens: 최대토큰,
    system: String(지시문),
    messages: [{
      role: 'user',
      content: `학생 급수: ${급수 || '미정'}\n학생 문장: ${String(문장)}`,
    }],
  };
}

/** 벤더 응답에서 모델이 쓴 글만 꺼낸다. 모양이 다르면 `null`(형식 추측 금지). */
function 응답글(본문) {
  const 조각 = 본문 && Array.isArray(본문.content) ? 본문.content : null;
  if (!조각) return null;
  const 글 = 조각.filter((c) => c && c.type === 'text').map((c) => String(c.text || '')).join('');
  return 글.trim() ? 글 : null;
}

/* 모델이 JSON 을 ```json 울타리에 넣어 주는 일이 잦다. 울타리째 파싱하면 전부 형식밖이 되고
 * 증상은 「교정이 하나도 안 선다」 하나뿐이라 원인이 안 보인다. */
function 울타리벗기기(글) {
  const m = /^\s*```(?:json)?\s*\n([\s\S]*?)\n?\s*```\s*$/.exec(String(글));
  return m ? m[1] : String(글);
}

/**
 * 모델 글 → `engine.corrections` 에 적을 세 칸. **못 읽으면 `{ 사유 }` 만** 낸다(행 0).
 *
 * @returns {{corrected_text:string, error_tags:string[], explanation:string|null, 사유:null}
 *          |{사유:string}}
 */
function 교정값(글, 태그목록) {
  let 본;
  try {
    본 = JSON.parse(울타리벗기기(글));
  } catch {
    return { 사유: '형식밖' };
  }
  if (!본 || typeof 본 !== 'object' || Array.isArray(본)) return { 사유: '형식밖' };

  const 고친문장 = typeof 본.고친문장 === 'string' ? 본.고친문장.trim() : '';
  if (!고친문장) return { 사유: '교정문없음' };

  if (!Array.isArray(본.오류태그)) return { 사유: '태그없음' };
  const 태그 = 본.오류태그.map((t) => String(t).trim()).filter(Boolean);

  /* 🔴 계약 밖 태그가 **하나라도** 있으면 행 전체를 버린다 — 그 태그만 빼고 적으면 남은
   *   태그가 「모델이 판정한 전부」인 것처럼 보이고, 그 거짓은 행에 안 남는다. 모르는 것을
   *   반쯤 적는 것이 안 적는 것보다 나쁘다(L0 §237 이 검증을 서버에 맡긴 이유). */
  const 밖 = 태그.filter((t) => !태그목록.includes(t));
  if (밖.length) return { 사유: `계약밖태그:${밖.join(',')}` };

  /* 🔑 빈 배열은 「판정 안 함」이고 `['오류없음']` 과 **다르다**(발주_게임모듈 §784).
   *   모델이 태그를 안 냈으면 그건 판정을 안 한 것이라 검수 재료가 못 된다. */
  if (!태그.length) return { 사유: '태그없음' };

  return {
    corrected_text: 고친문장,
    error_tags: 태그,
    /* ⚠ **여기가 계약과 어긋나 있다** — 계약은 `explanation` 을 「몽골어 해설」로 정했는데
     *   (발주_수집파이프라인 §87 · `functions/corrections` 가 그 이름으로 앱에 내려보낸다)
     *   `prompts/교정.md` v1 의 `오늘의포인트` 는 **한국어**다. 프롬프트를 고치려면 같은
     *   픽스처로 이전 판과 비교해야 하고(그 파일의 규칙), 그건 이 배선과 다른 트랙이다.
     *   🔑 그래서 **값을 옮기되 언어는 안 바꾼다**: AI 행은 1차안이고 검수자가 확정하므로
     *   한국어 해설은 되돌릴 수 있다. 빈칸으로 두면 검수자가 볼 재료가 사라진다. */
    explanation: typeof 본.오늘의포인트 === 'string' && 본.오늘의포인트.trim()
      ? 본.오늘의포인트.trim() : null,
    사유: null,
  };
  /* ⚠ `칭찬`·`다음미션` 은 **버린다** — 담을 열이 계약에 없다. 열을 새로 만드는 것은 계약
   *   개정(cN)이라 이 배선의 몫이 아니고, 있는 열(`rubric_scores` 등)에 밀어 넣으면 그 열의
   *   뜻이 갈린다. 버린다는 사실을 여기 적어 두는 것이 지금 할 수 있는 전부다. */
}

/**
 * 벤더 실패를 「다시 걸어 볼 것」과 「걸어도 같은 것」으로 가른다.
 *
 * 🔴 **`corrections` 에는 실패를 못박을 칸이 없다**(전사의 `transcript_state` 같은 자리가
 *   없다). 그래서 영구 실패도 다음 배치가 다시 집는다 — 같은 행이 매번 한 자리를 먹는다.
 *   지금은 그것을 **응답에 세어 드러내는 것**까지가 처방이다(칸을 만드는 것은 계약 개정).
 *   ⚠ 그 수가 배치 크기에 가까워지면 앞머리가 막힌 것이니 그때 칸을 판다.
 */
function 재시도가능(status) {
  if (status === 429) return true;          // 쿼터·속도 — 잠시 뒤면 된다
  if (status >= 500) return true;           // 벤더 쪽 — 우리 잘못이 아니다
  return false;                             // 401·400 — 다시 걸어도 같다(고칠 사람은 우리다)
}

module.exports = {
  모델, 왕복제한밀리, 최대토큰,
  프롬프트판, 태그어긋남, 요청몸통, 응답글, 교정값, 재시도가능,
};
