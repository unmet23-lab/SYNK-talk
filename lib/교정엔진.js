/** 벤더 응답에서 모델이 쓴 글만 꺼낸다. 모양이 다르면 `null`(형식 추측 금지). */
function 응답글(본문) {
  const 조각 = 본문 && Array.isArray(본문.content) ? 본문.content : null;
  if (!조각) return null;
  const 글 = 조각.filter((c) => c && c.type === 'text').map((c) => String(c.text || '')).join('');
  return 글.trim() ? 글 : null;
}

/* 문자열 리터럴 안의 중괄호는 안 센다 — `"고친문장": "{ 이런 문장 }"` 이 깊이를 어긋내면
 * 덩이가 엉뚱한 데서 닫힌다. 이스케이프(`\"`)도 같은 이유로 건너뛴다. */
function 중괄호덩이들(s) {
  const 덩이 = [];
  for (let i = 0; i < s.length; i++) {
    if (s[i] !== '{') continue;
    let 깊이 = 0, 따옴표 = false;
    for (let j = i; j < s.length; j++) {
      const c = s[j];
      if (따옴표) {
        if (c === '\\') j++;
        else if (c === '"') 따옴표 = false;
        continue;
      }
      if (c === '"') 따옴표 = true;
      else if (c === '{') 깊이++;
      else if (c === '}' && --깊이 === 0) { 덩이.push(s.slice(i, j + 1)); i = j; break; }
    }
  }
  return 덩이;
}

/**
 * 모델 글에서 **JSON 덩이 하나**를 꺼낸다. 못 꺼내면 원문 그대로(파싱이 `형식밖` 을 낸다).
 *
 * 🔴 **2026-08-12 실측 — 이 자리가 교정의 최대 손실원이었다.** 옛 판은 울타리가 글 «전체»일
 *   때만(`^…$`) 벗겼는데, 모델은 프롬프트가 「JSON만, 다른 말 금지」라고 못박아도 산문을
 *   두르는 일이 있다 — 머리말·꼬리 해설 사이에 ```json 울타리를 끼워 답한다. 그러면 정규식이
 *   안 걸려 **글 전체**가 파싱에 들어가고 전부 `형식밖` 으로 버려진다.
 *   첫 API 기준선 102문항 중 **8건(7.8%)**이 이 모양이었고, 꺼내 보니 **여덟 개 다 내용은
 *   정확한 답**이었다(E30 「선생님, 이거 뭐예요?」+높임:상대 — 픽스처 기대와 일치).
 *   즉 잃던 것은 모델 품질이 아니라 **파서**다. 프롬프트 문구를 세게 해도 0 은 못 된다
 *   (비결정적 — 같은 8건을 다시 돌리자 6건은 그냥 통과했다). 막는 자리는 여기다.
 *
 * 🔑 순서가 곧 안전장치다: ①울타리 안 → ②글 전체 → ③산문에 박힌 중괄호 덩이. 그리고 그중
 *   **`고친문장` 을 든 덩이를 먼저** 고른다 — 모델이 예시 JSON 을 먼저 적고 답을 뒤에 적어도
 *   답 쪽을 집는다. 아무것도 그 모양이 아니면 그때 「객체이기만 한」 첫 덩이로 물러선다.
 * ⚠ 느슨해진 만큼은 `교정값()` 이 그대로 진다 — 꺼낸 뒤에도 고친문장·태그·계약 어휘를 다시
 *   거르므로, 여기서 엉뚱한 덩이를 집어도 행이 서지 않는다(꺼내기는 판정이 아니다).
 */
function 응답덩이꺼내기(글) {
  const s = String(글 == null ? '' : 글);
  const 후보 = [];
  for (const m of s.matchAll(/```(?:json)?\s*\n([\s\S]*?)\n?\s*```/g)) 후보.push(m[1]);
  후보.push(s);
  후보.push(...중괄호덩이들(s));

  const 읽힌것 = [];
  for (const c of 후보) {
    let v;
    try { v = JSON.parse(c); } catch { continue; }
    if (!v || typeof v !== 'object' || Array.isArray(v)) continue;
    if (typeof v.고친문장 === 'string') return c;      // 답의 모양을 든 것이 최우선
    읽힌것.push(c);
  }
  return 읽힌것.length ? 읽힌것[0] : s;
}

/**
 * 모델 글 → `engine.corrections` 에 적을 세 칸. **못 읽으면 `{ 사유 }` 만** 낸다(행 0).
 *
 * @returns {{corrected_text:string, error_tags:string[], explanation:string|null, 사유:null}
 *          |{사유:string}}
 */
function 교정값(글, 태그목록) {
  let 본;
  try {
    본 = JSON.parse(응답덩이꺼내기(글));
  } catch {
    return { 사유: '형식밖' };
  }
  if (!본 || typeof 본 !== 'object' || Array.isArray(본)) return { 사유: '형식밖' };

  const 고친문장 = typeof 본.고친문장 === 'string' ? 본.고친문장.trim() : '';
  if (!고친문장) return { 사유: '교정문없음' };

  if (!Array.isArray(본.오류태그)) return { 사유: '태그없음' };
  const 태그 = 본.오류태그.map((t) => String(t).trim()).filter(Boolean);

  /* 🔴 계약 밖 태그가 **하나라도** 있으면 행 전체를 버린다 — 그 태그만 빼고 적으면 남은
   *   태그가 「모델이 판정한 전부」인 것처럼 보이고, 그 거짓은 행에 안 남는다. 모르는 것을
   *   반쯤 적는 것이 안 적는 것보다 나쁘다(L0 §237 이 검증을 서버에 맡긴 이유). */
  const 밖 = 태그.filter((t) => !태그목록.includes(t));
  if (밖.length) return { 사유: `계약밖태그:${밖.join(',')}` };

  /* 🔑 빈 배열은 「판정 안 함」이고 `['오류없음']` 과 **다르다**(발주_게임모듈 §784).
   *   모델이 태그를 안 냈으면 그건 판정을 안 한 것이라 검수 재료가 못 된다. */
  if (!태그.length) return { 사유: '태그없음' };

  return {
    corrected_text: 고친문장,
    error_tags: 태그,
    /* ⚠ **여기가 계약과 어긋나 있다** — 계약은 `explanation` 을 「몽골어 해설」로 정했는데
     *   (발주_수집파이프라인 §87 · `functions/corrections` 가 그 이름으로 앱에 내려보낸다)
     *   `prompts/교정.md` v1 의 `오늘의포인트` 는 **한국어**다. 프롬프트를 고치려면 같은
     *   픽스처로 이전 판과 비교해야 하고(그 파일의 규칙), 그건 이 배선과 다른 트랙이다.
     *   🔑 그래서 **값을 옮기되 언어는 안 바꾼다**: AI 행은 1차안이고 검수자가 확정하므로
     *   한국어 해설은 되돌릴 수 있다. 빈칸으로 두면 검수자가 볼 재료가 사라진다. */
    explanation: typeof 본.오늘의포인트 === 'string' && 본.오늘의포인트.trim()
      ? 본.오늘의포인트.trim() : null,
    사유: null,
  };
  /* ⚠ `칭찬`·`다음미션` 은 **버린다** — 담을 열이 계약에 없다. 열을 새로 만드는 것은 계약
   *   개정(cN)이라 이 배선의 몫이 아니고, 있는 열(`rubric_scores` 등)에 밀어 넣으면 그 열의
   *   뜻이 갈린다. 버린다는 사실을 여기 적어 두는 것이 지금 할 수 있는 전부다. */
}

/**
 * 벤더 실패를 「다시 걸어 볼 것」과 「걸어도 같은 것」으로 가른다.
 *
 * 🔴 **`corrections` 에는 실패를 못박을 칸이 없다**(전사의 `transcript_state` 같은 자리가
 *   없다). 그래서 영구 실패도 다음 배치가 다시 집는다 — 같은 행이 매번 한 자리를 먹는다.
 *   지금은 그것을 **응답에 세어 드러내는 것**까지가 처방이다(칸을 만드는 것은 계약 개정).
 *   ⚠ 그 수가 배치 크기에 가까워지면 앞머리가 막힌 것이니 그때 칸을 판다.
 */
function 재시도가능(status) {
  if (status === 429) return true;          // 쿼터·속도 — 잠시 뒤면 된다
  if (status >= 500) return true;           // 벤더 쪽 — 우리 잘못이 아니다
  return false;                             // 401·400 — 다시 걸어도 같다(고칠 사람은 우리다)
}

/* ── 배치(Message Batches) ─────────────────────────────────────────────────
 *
 * 왜 배치인가 (유호 승인 08-09 「캐싱 + 배치 부탁해」): 똑같은 요청이 **절반 값**이다.
 * 교정은 야간 cron 이 도는 일이라 실시간일 필요가 없어, 이 할인의 전제(최대 24시간)에
 * 구조가 그대로 맞는다. 캐싱과 곱해져 한 건 약 17원 → 약 5원이 된다.
 *
 * 🔑 **비동기라 왕복이 두 마디로 갈린다** — 제출과 회수. 그 사이 「무엇이 나가 있나」를 우리
 *   DB 에 적으려면 열이 필요하고, 열을 새로 파는 것은 계약 개정(cN)이라 이 배선의 몫이 아니다.
 *   그래서 **상태를 벤더가 지게 한다**: ①`custom_id` 가 「어느 제출행인가」를 나르고
 *   ②「지금 도는 배치가 있나」는 배치 목록에게 묻는다. 우리 쪽에 남는 상태가 0이라, 두 마디가
 *   순서를 잃거나 한쪽이 죽어도 복구 절차가 없다 — 다음 회차가 같은 질문을 다시 하면 된다.
 *   ⚠ 그 대가는 **이 키를 이 함수만 쓴다**는 전제다. 남이 같은 키로 배치를 돌리면 우리는
 *     「도는 게 있다」고 보고 그 회차를 쉰다 — 늦어질 뿐 두 번 청구되지는 않는다(안전한 방향).
 *
 * 🔴 `custom_id` 에 **프롬프트 판을 함께 싣는다.** 회수는 몇 시간~하루 뒤이고 그 사이 프롬프트가
 *   바뀌면, 회수 시점에 파일에서 읽은 판은 **그 출력을 만들지 않은 판**이다. 그렇게 적힌 행은
 *   나중에 갈라낼 근거가 없다(소급 불가). 모델 이름은 반대로 **안 싣는다** — 결과 줄이
 *   `message.model` 로 벤더가 실제로 태운 모델을 알려주므로 그쪽이 정본이고, 우리가 실은 값은
 *   기껏해야 「우리가 요청한 것」이다.
 */
const 키구분자 = '|';

/** `custom_id` 조립. 제출행 UUID 에는 구분자가 없으므로 뒤에 판을 붙여도 안 섞인다. */
function 배치키(submissionId, 판) {
  return `${String(submissionId)}${키구분자}${String(판)}`;
}

/** `custom_id` 해체. 모양이 다르면 `null` — 추측해서 절반만 적지 않는다. */
function 배치키풀기(customId) {
  const s = String(customId || '');
  const i = s.indexOf(키구분자);
  if (i <= 0 || i === s.length - 1) return null;
  return { submission_id: s.slice(0, i), 판: s.slice(i + 1) };
}

/**
 * 배치 생성 요청 몸통. 요청 하나하나는 **동기 왕복과 같은 `요청몸통()`** 을 쓴다 —
 * 두 통로가 서로 다른 프롬프트·모델·캐시 설정을 들면 「배치로 돌린 것」과 「즉시 돌린 것」의
 * 품질이 갈리고, 그 차이는 행에 안 남는다.
 */
function 배치몸통(행들, 지시문, 판) {
  return {
    requests: (Array.isArray(행들) ? 행들 : []).map((행) => ({
      custom_id: 배치키(행.submission_id, 판),
      params: 요청몸통({ 지시문, 문장: 행.문장, 급수: 행.급수 }),
    })),
  };
}

/**
 * 결과 파일(JSONL) 한 줄 → 적을 재료 또는 사유.
 *
 * 🔴 성공이 아닌 갈래(`errored`·`canceled`·`expired`)에서도 **행을 못박지 않는다.** 교정행이
 *   안 생기면 다음 회차의 대기 조회가 그 발화를 다시 집는다 — 자기치유가 기본값이고, 대신
 *   영구 실패는 같은 자리를 매번 먹는다. 그래서 **사유별로 세어 응답에 드러낸다**(그 수가
 *   배치 크기에 가까워지면 앞머리가 막힌 것이다 · `재시도가능` 머리말과 같은 축).
 * 🔴 모델 이름이 없으면 버린다. 「어느 모델이 만들었나」가 빈 행은 나중에 「모델을 바꿔서
 *   좋아진 것」과 「학생이 늘어서 좋아진 것」을 못 가르게 만든다 — 모르는 것을 적지 않는다.
 */
function 배치줄해석(줄) {
  let 본;
  try { 본 = JSON.parse(줄); } catch { return { 사유: '결과형식밖' }; }
  if (!본 || typeof 본 !== 'object') return { 사유: '결과형식밖' };

  const 키 = 배치키풀기(본.custom_id);
  if (!키) return { 사유: '키형식밖' };

  const r = 본.result || {};
  if (r.type !== 'succeeded') {
    const 갈래 = r.type === 'errored'
      ? `배치오류:${(r.error && r.error.type) || '알수없음'}`
      : `배치${r.type || '알수없음'}`;
    return { ...키, 사유: 갈래 };
  }

  const 글 = 응답글(r.message);
  if (!글) return { ...키, 사유: '응답형식밖' };
  const 모델이름 = r.message && typeof r.message.model === 'string' ? r.message.model : '';
  if (!모델이름) return { ...키, 사유: '모델없음' };

  return { ...키, 글, 모델: 모델이름, 사용량: (r.message && r.message.usage) || null, 사유: null };
}

/**
 * 캐싱이 **실제로 걸렸는지**를 재는 눈금. 캐시는 안 걸려도 오류를 내지 않으므로(접두가 최소
 * 길이 미만이면 조용히 통과) 이 숫자가 없으면 「걸렸다」와 「안 걸렸다」가 같은 모양이다.
 * 읽음이 계속 0이면 지시문이 문턱 아래이거나 접두가 매번 바뀌는 것이다.
 */
function 캐시성적(usage) {
  const u = usage || {};
  return {
    입력: Number(u.input_tokens || 0),
    캐시생성: Number(u.cache_creation_input_tokens || 0),
    캐시읽음: Number(u.cache_read_input_tokens || 0),
  };
}

/** 성적 여럿을 한 칸으로. 배치 한 벌이 캐시를 몇 번 읽었는지가 그대로 절감액이다. */
function 성적합(성적들) {
  return (성적들 || []).reduce((a, b) => ({
    입력: a.입력 + b.입력,
    캐시생성: a.캐시생성 + b.캐시생성,
    캐시읽음: a.캐시읽음 + b.캐시읽음,
  }), { 입력: 0, 캐시생성: 0, 캐시읽음: 0 });
}

