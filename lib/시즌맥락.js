const 목적말 = Object.freeze([
  ['why_learning', '왜 배우나'],
  ['topik_use', '토픽 쓸 곳'],
]);

/**
 * 입학 회차 답 → 맥락 줄들. 없는 것은 빼고, 둘 다 없으면 빈 배열.
 * @param {{why_learning?: string|null, topik_use?: string|null}} [답]
 * @returns {string[]}
 */
function 목적줄들(답) {
  const 안 = 답 && typeof 답 === 'object' ? 답 : {};
  const 줄들 = [];
  for (const [키, 말] of 목적말) {
    const 값 = String(안[키] == null ? '' : 안[키]).trim();
    if (값) 줄들.push(`${말}: ${값}`);
  }
  return 줄들;
}

