/** 나침반 답 하나 → `이번 시즌 목표: …` 한 줄. 없으면 null. */
function 시즌줄(season_goal) {
  const 값 = String(season_goal == null ? '' : season_goal).trim();
  return 값 ? `이번 시즌 목표: ${값}` : null;
}

module.exports = { 시즌줄 };
