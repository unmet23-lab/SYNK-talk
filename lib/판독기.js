/* 판독기 — `policy_ver`·`quality_ver` 지문을 «내는» 통로 (§16-1 선행 #5 · 2026-08-21)
 *   (정본 = appsscript docs/상태기반_과제선택_설계.md §5-1 재료 13 · §5-1-a · v5.9 원소 문자열 표
 *    · v5.10 자리수 12 · v5.7 D3 「산출 층 = 오케스트레이터 · ⓪ 시작 행에 굳힌다」).
 *
 * ■ 왜 있나 — 재료 13(파일 해시 7 · RPC 정의 · 폴백 순서 · 상수 · 회전식 · cron · 추정기)을
 *   모아 지문을 내는 함수가 저장소에 **0** 이었다(9회차 E7 실측). 규격이 코드에 없으면 구현자가
 *   짓고, 그 순간 첫 계보가 갈린다 — `learning_events` 는 append-only 라 소급 정정이 없다.
 *
 * ■ 순수 — 파일·DB 를 «읽지 않는다». 원소 문자열 13개는 호출자(오케스트레이터 — 저장소
 *   산출물을 들고 있는 유일한 층 · D3)가 조달한다. 그래서 이 모듈은 Node 회귀와 Edge 런타임
 *   양쪽에서 같은 값을 낸다(fs 의존이 있으면 Edge 에서 다른 통로가 생긴다 — 두 정본).
 *
 * ■ 산출 자리 = **배치 시작 1회** · ⓪`batch_run_start` 가 시작 행에 굳히고 이후 모든 RPC·구제가
 *   그 행에서 읽는다(§3-5-b — 학생마다 다시 계산하면 배치 도중 파일이 바뀔 때 한 날에 두 판이 섞인다).
 *
 * ■ 형식(v5.10 — 한 곳): `policy_ver` = `<접두>+<SHA-256 전문 hex 의 앞 12자>`.
 *   전환 판독은 접두로, 판지문 대조는 접미로(§5-4). 접두의 정본은 `lib/오늘과제.js` 의 `선택판`
 *   하나다 — 여기 리터럴을 적으면 판 올린 날 두 곳이 갈린다(가드 맹점 ④).
 *   🚫 16자·전문을 이 값에 되살리기(§13) — 기존 행동 지문의 「앞 16자」는 다른 대상의 옛 규격이다.
 *
 * ■ 재료가 하나라도 비면 **던진다** — 빠뜨림이 조용히 «다른 지문»이 되면, 같은 규칙이 두 판으로
 *   갈리고 그 갈림은 어디서도 안 빨개진다(「모르면 통과」는 이 장치의 존재 이유를 뒤집는다). */
'use strict';
const { hex } = require('./sha256.js');
const { 선택판 } = require('./오늘과제.js');

/** 재료 이름 — §5-1 표의 번호 순서 그대로. 순서가 곧 직렬화 순서라 여기 하나에서만 산다. */
const 재료이름 = Object.freeze([
  '요약조립',      // 1  lib/과제요약.js 파일 해시
  '검문',          // 2  lib/과제검문.js 파일 해시 (quality_ver 재료이기도 하다)
  '폴백순서',      // 3  단계 리터럴 배열 JSON.stringify — 값의 정본은 lib/오늘과제.js
  '타임아웃상수',  // 4  `생성타임아웃_MS=<값>` — 타임아웃만 바꿔도 성공/폴백 비율이 바뀐다
  '예산상수',      // 5  «이름=값» 을 이름 오름차순 \n 연결 — 워커학생상한·워커예산_MS·배달마감_시각
                   //    + 편입분(_lease_sec·실행리더여유_MS·적재예산_MS·폴백여유_MS): 「누가 마감에 걸리나」
  '회전식',        // 6  회전 seed SQL 표현식 전문 (공백 정규화 없이)
  '갈래판정',      // 7  lib/갈래판정.js 파일 해시
  '기술선택',      // 8  lib/기술선택.js 파일 해시
  'cron',          // 9  «이름=크론식» 을 이름 오름차순 \n 연결 (3잡)
  'rpc',           // 10 열 RPC 의 pg_get_functiondef 를 함수명 오름차순(collate "C") \n 연결 전문
  '오류분류',      // 11 lib/과제생성.js 파일 해시 (quality_ver 재료이기도 하다)
  '폴백조립',      // 12 lib/오늘과제.js 파일 해시
  '추정기',        // 13 lib/학습자상태.js 파일 해시
]);

/** 파일 재료의 원소 문자열(v5.9 표) — 원문의 UTF-8 SHA-256, 소문자 hex 전문. */
const 파일원소 = (원문) => hex(String(원문));

const 원소검사 = (재료) => {
  if (!재료 || typeof 재료 !== 'object') throw new TypeError('판독기: 재료 객체가 필요하다');
  const 빠짐 = 재료이름.filter((k) => typeof 재료[k] !== 'string' || 재료[k].length === 0);
  if (빠짐.length) {
    throw new TypeError(`판독기: 재료가 비었다 — ${빠짐.join('·')} (빠뜨림이 조용히 다른 지문이 되면 소급 분리가 안 된다)`);
  }
  const 밖 = Object.keys(재료).filter((k) => !재료이름.includes(k));
  if (밖.length) throw new TypeError(`판독기: 모르는 재료 — ${밖.join('·')} (재료 목록의 정본은 §5-1 표다)`);
};

/**
 * `policy_ver` 지문 — 재료 13 을 §5-1 순서로 정규 직렬화해 SHA-256, 접두+앞 12자.
 * @param {Record<string, string>} 재료  키 = `재료이름` 전량 · 값 = v5.9 표의 원소 문자열
 * @returns {string} 예: `오늘과제.v4+3f9a2c1b0d4e`
 */
function 정책지문(재료) {
  원소검사(재료);
  const 전문 = hex(JSON.stringify(재료이름.map((k) => 재료[k])));
  return `${선택판}+${전문.slice(0, 12)}`;
}

/**
 * `quality_ver` 지문 — 품질에 직접 닿는 «부분판»(§5-1-a · 재료 2 검문 + 재료 11 오류분류).
 * 쓰이는 곳은 §8-B 차단기 비교축 하나 — 사건 행·payload 에 싣지 않는다(계약 면적 불변).
 * @param {{검문: string, 오류분류: string}} 재료  각각 그 파일의 UTF-8 SHA-256 hex 전문
 * @returns {string} SHA-256 전문의 앞 12자 (접두 없음 — 행에 안 남는 평가 층의 값이다)
 */
function 품질지문(재료) {
  const { 검문, 오류분류 } = 재료 || {};
  for (const [k, v] of [['검문', 검문], ['오류분류', 오류분류]]) {
    if (typeof v !== 'string' || !v.length) throw new TypeError(`판독기: quality_ver 재료가 비었다 — ${k}`);
  }
  return hex(JSON.stringify([검문, 오류분류])).slice(0, 12);
}

module.exports = { 정책지문, 품질지문, 파일원소, 재료이름 };
