/**
 * 게임배정 — 「오늘 이 학생에게 게임(G1)을 낼 것인가」의 순수 판정 (배정 배선 ④ · 발주 §6-6 ⑩·⑪).
 *
 * ■ 자리 — `functions/deliver` 의 게임 갈래는 이 함수 하나를 부른다
 *   말하기의 `lib/오늘과제.오늘과제` 와 같은 이유로 떼어 놨다: 배치 본체는 DB 왕복이라 원격이
 *   필요하고, 「낼 것인가·무엇을」은 순수 판정이라 회귀가 DB 없이 행동으로 잰다(F287 — 함수
 *   본체에 인라인으로 적으면 글자로만 검사되고, 글자 검사는 조건을 통째로 죽여도 초록이다).
 *
 * ■ 판정 순서가 곧 우선순위다 — 갈래마다 어긋나면 잃는 것이 다르다
 *   ① `검수확정` 게이트(발주_게임콘텐츠팩 §3 · fail-closed): 몽골어 검수 전 판은 학생에게 안 연다.
 *      팩 export 를 직접 본다 — 호출자가 값을 넘기게 하면 참을 넘기는 실수가 게이트를 우회한다.
 *   ② 게임날이 아니면 게임이 없다(주 2회 상한 — G1 §3 ③ 검수 용량).
 *   ③ 첫날은 말하기 도입이 이긴다 — 첫 발화 기준선(§4-5)은 소급 불가다.
 *   ④ 🔴 미배달 말하기 교정문이 이긴다(적대 반박 C3): 게임 배정도 `task.assigned` 라 교정
 *      워터마크(「마지막 배정 뒤 확정분만」)를 밀고, 밀린 교정문은 **영구 증발**한다. 게임은
 *      다음 게임날로 미루면 그만이지만 교정문은 그날을 놓치면 되돌릴 수 없다.
 *   ⑤ 재제출(H3)이 새 문항보다 먼저다 — 설계 전체의 유일한 결과 변수(`retry_of_event_id`)를
 *      잇는 자리라, 새 문항이 끼어들면 그 고리가 밀린다.
 *      🔑 재제출은 초급 게이트를 **안 지난다**: 원 제출이 실재한다는 것이 「이 학생이 이 게임을
 *      해냈다」의 실측이고, 급수 추정(`초급인가` 의 「모르면 초급」)보다 강한 근거다.
 *   ⑥ 새 문항은 초급(1~2·미정)을 제외한다 — **판정안이다**(발주는 침묵 · 유호님 이의 자리).
 *      G1 은 격식 메일 «쓰기»라 말하기 자유발화와 같은 비대칭이 선다: 상급자가 게임을 안 받으면
 *      손해 0(말하기가 나간다), 초급자가 게임을 받으면 그날 산출이 통째로 사라진다.
 *
 * ■ 게임날 = 화·금 (판정안 — 발주는 「주 2회 상한」까지만 · 유호님 이의 자리)
 *   근거: 월요일은 한 주의 말하기 기준선을 지키고, 화 제출 → 수·목 검수 → 답장 열람 → 금
 *   재제출이 한 주 안에 닫히는 최단 리듬이다(검수가 밀리면 다음 화로 자연히 넘어간다 — H3 의
 *   닻은 요일이 아니라 「재배정 없음」이라 날을 놓쳐도 안 사라진다).
 *   요일은 `getUTCDay` 로 판다 — `YYYY-MM-DD` 는 몽골 달력 문자열이고 UTC 자정으로 파싱해야
 *   그 문자열의 요일이 나온다(`lib/골든표본.js` 선례 · 로컬 tz 로 읽으면 하루 밀린다).
 *
 * ■ 새 문항 시드는 **결정적**이다 — 같은 학생·같은 날 = 같은 시드
 *   배치 재실행이 같은 결정을 내야 멱등키의 `duplicate` 접힘과 아귀가 맞는다(다른 시드를 내면
 *   「접혔다」가 「다른 것을 내려다 접혔다」가 된다). 해시는 배분이지 비밀이 아니다(`게임제출.
 *   오늘추천` 과 같은 축). ⚠ 연속 게임날에 같은 상황틀이 다시 올 수 있다(45벌 중 무작위 배분) —
 *   팩 §2 가 「상황 재방문은 변주만 다름 · 집계가 안다」로 이미 안고 있는 성질이다.
 *
 * ■ 이 판정이 **안** 하는 것
 *   · `task.assigned`·`submissions` INSERT — 배치 몫(행 규격은 반환값이 전부 든다).
 *   · `intervention.delivered` — G1 은 개입 행이 없다(발주 §8 · 답장이 대본이라 학습 신호 0).
 *   · 같은 `task_ref` 재배정 방지의 물리층 — 멱등키(`task:{learner}:{날짜}`)와 날짜 스코프
 *     `task_ref` 가 진다(⑩ 확정 1 · 이 함수는 `task_ref` 를 **날짜에서만** 판다).
 *
 * ■ 🔴 이 파일은 CJS 다 — 동봉 기전이 CJS 전용이다(`tests/동봉CJS.test.js` · 적대 반박 C2).
 */
'use strict';

const { 검수확정, 문항들, 시드만들기, 모듈상수 } = require('../contents/교수멘탈문항.js');
const {
  검수확정: G2검수확정, 급수대풀: G2급수대풀, 앉음편성: G2앉음편성,
  모듈상수: G2모듈상수, 문항목록: G2문항목록,
} = require('../contents/보고서교정문항.js');
const {
  G1스냅샷, 스냅샷모양판, 과제유형, G2스냅샷, G2스냅샷모양판, G2과제유형,
} = require('./게임스냅샷.js');
const { 초급인가 } = require('./오늘과제.js');

/* 초급이 받는 급수대 — G2 §3-① 태그 배분의 「Lv1~2 = 조사·맞춤법」 칸이다. `초급인가` 의 문턱
 * (2급 이하·모름)과 **같은 뜻을 두 곳에 적은 것**이라, 문턱을 옮기는 날 이 줄도 같이 옮긴다.
 * 🔑 이름으로 묶어 두는 이유: 팩의 급수대 키는 `'Lv1~2'` 라는 «표기»고, 여기 리터럴이 흩어지면
 *   팩이 키를 갈아치운 날 배정이 조용히 빈 풀을 받아 게임이 0건이 된다(회귀가 결속을 잡는다). */
const 초급급수대 = 'Lv1~2';

/* 게임 요일 — ISO 아닌 JS `getUTCDay` 눈금(일=0)이다. 화=2 · 금=5. 바꾸는 날은 이 줄 하나와
 * 발주 §6-6 ⑪ 을 같이 고친다(문서에만 있으면 어긋나도 저장 시점에 신호가 없다 — §6-8 규칙 5). */
const 게임요일들 = Object.freeze([2, 5]);

const 날짜꼴 = /^\d{4}-\d{2}-\d{2}$/;

/** 그 날짜(몽골 달력 `YYYY-MM-DD`)가 게임날인가. */
function 게임날인가(날짜) {
  if (!날짜꼴.test(String(날짜))) throw new TypeError('게임날인가: 날짜는 YYYY-MM-DD 여야 한다');
  return 게임요일들.includes(new Date(`${날짜}T00:00:00Z`).getUTCDay());
}

/* 시드 공간 전체 — 팩 목록 하나에서 판다(여기 수를 다시 적으면 팩 개정과 갈라진다).
 * `시드만들기` 가 범위를 스스로 검증하므로 여기서 나온 시드는 전부 펴진다. */
const 시드전부 = Object.freeze((() => {
  const out = [];
  for (const 문항 of 문항들) {
    for (let s = 0; s < 문항.사유.length; s += 1) {
      for (let d = 0; d < 문항.세부.length; d += 1) {
        const 시드 = 시드만들기(문항.문항id, s, d);
        if (시드) out.push(시드);
      }
    }
  }
  return out;
})());

/** 새 문항 시드를 결정적으로 고른다 — 같은 (학생, 날짜) = 같은 시드. */
function 시드고르기(learner_id, 날짜) {
  return 시드전부[흩기(`${learner_id}:${날짜}`) % 시드전부.length];
}

/** 결정적 해시 — 배분이지 비밀이 아니다(`게임제출.오늘추천` 과 같은 축). */
function 흩기(글) {
  let 합 = 0;
  for (const ch of String(글)) 합 = (합 * 31 + ch.codePointAt(0)) % 9973;
  return 합;
}

/* G2 앵커 후보 — 초급 급수대의 **오류** 문항만이다(대조 문항이 앵커면 앉음편성이 못 선다).
 * 팩 목록 하나에서 판다 — 여기 id 를 적으면 팩 개정과 갈라지고, 갈라진 쪽은 조용히 0건이다. */
const G2앵커전부 = Object.freeze(G2급수대풀(초급급수대).오류.filter((id) => G2앉음편성(id)));

/**
 * 초급 학생의 G2 앵커를 결정적으로 고른다 — 같은 (학생, 날짜) = 같은 앵커 = 같은 3문항.
 * 🔑 G1 의 `시드고르기` 와 **같은 규율, 다른 소금**(`g2:` 접두) — 같은 글자를 두 모듈에 그대로
 *   쓰면 같은 학생이 같은 날 두 모듈에서 나란한 자리를 받는다(우연이지만 재현되는 우연이다).
 */
function G2앵커고르기(learner_id, 날짜) {
  if (G2앵커전부.length === 0) return null; // 팩이 그 급수대를 못 채운다 — 지어내지 않는다
  return G2앵커전부[흩기(`g2:${learner_id}:${날짜}`) % G2앵커전부.length];
}

/* 「고쳐서 다시 보낼래요」의 계약 값 — H3 재제출 조인(`functions/deliver`)의 술어가 이 값을
 * 지목한다. 값목록 정본은 계약 JSON `learner_response` 이고 회귀가 소속을 기계로 묶는다
 * (`src/교정API.학생응답값` 과 같은 규약 — 갈라지면 재제출 조인이 조용히 0건이 된다). */
const 재제출의사 = '수정';

/* deliver 의 H3 조인이 원 제출을 게임으로 한정하는 축 — 값 사본이 아니라 팩 정본의 지목이다. */
const 게임챌린지 = 모듈상수.challenge_id;
const G2챌린지 = G2모듈상수.challenge_id;

/* H3 조인이 걷어도 되는 원 제출의 문항 — 「⑤가 실제로 재배정을 세울 수 있는 것」만이다.
 * 🔴 왜 SQL 이 거르나: 조인은 `limit 1`(최신 «수정» 하나)이라, ⑤가 영원히 접기만 하는 원 제출
 *   (G2 대조 문항 — 과잉 교정에 대한 교정, 앉음이 원리상 못 선다 / 팩 개정으로 사라진 시드)이
 *   최신이면 그 닻이 **걷힐 수 있는 다른 재제출까지 그늘로 가리고**, ⑤는 null 이라 그 학생의
 *   게임이 통째로 서지 않는다. 증상은 「말하기만 나온다」 하나뿐이다.
 * 🔑 목록은 팩에서 파생한다(여기 id 를 적으면 팩 개정과 갈라진다) — G1 은 `시드전부`(아래 —
 *   전부 펴진다), G2 는 앉음이 서는 앵커 전부(전 급수대 · `앉음편성` 이 대조·풀 부족을 거른다).
 *   ⑤의 재검(`앉음편성`·스냅샷 null)은 이 필터의 이중 방어다 — 판정 정본은 lib 다. */
const G2재제출앵커들 = Object.freeze(G2문항목록().filter((id) => G2앉음편성(id)));

/**
 * 오늘 이 학생에게 게임을 낼 것인가 — 낸다면 배정 행의 규격 전부를 돌려준다.
 *
 * @param {object} 재료
 * @param {string} 재료.learner_id   새 문항 배분 축(재제출만 있으면 없어도 된다)
 * @param {string} 재료.날짜          몽골 기준 `YYYY-MM-DD`(배정 대상일)
 * @param {boolean} [재료.첫날]       배정 이력이 없다
 * @param {string|null} [재료.교정문]  미배달 말하기 교정문(있으면 게임을 미룬다 — C3)
 * @param {string|null} [재료.급수]    `level_current` 그대로(판정은 `초급인가`)
 * @param {{원사건:string, 원시드:string|null, 원챌린지?:string|null}|null} [재료.재제출]
 *        H3 — 「수정」이 눌렸는데 재배정이 아직 없는 게임 원 제출(deliver 조인이 걷는다 ·
 *        `원챌린지` = 그 제출 스냅샷의 challenge_id — 없으면 G1)
 * @returns {Readonly<{task_ref:string, task_type:string, task_snapshot:object,
 *   task_schema_ver:string, retry_of_event_id:string|null, degraded:boolean, 출처:string}>|null}
 *   `null` = 게임 없음 — 배치는 말하기 경로로 내려간다(그날 학생이 빈손이 되는 갈래는 없다).
 */
function 게임배정(재료) {
  const { learner_id = null, 날짜, 첫날 = false, 교정문 = null, 급수 = null, 재제출 = null } = 재료 || {};
  /* 🔴 게이트는 **모듈마다** 본다 — 예전엔 여기 G1 팩 하나가 서서 「미검수」가 곧 「게임 없음」
   *   이었다. 모듈이 둘이 된 지금 그 줄을 그대로 두면 G2 팩이 확정되는 날에도 초급 학생은
   *   영원히 게임을 못 받는다(증상은 오류가 아니라 조용한 말하기 폴백이라 아무 데도 안 남는다). */
  if (!게임날인가(날짜)) return null;
  if (첫날) return null;
  if (교정문 != null) return null;

  /* ⑤ 재제출이 새 문항보다 먼저다 — 초급 게이트를 안 지난다(머리말 ⑤).
   * 모듈은 **원 제출의 챌린지**가 가른다(H3 조인이 스냅샷에서 함께 걷어 온 값) — 지금 급수가
   * 아니라 원 제출 실재가 근거이므로, 그새 승급한 학생의 G2 재제출도 G2 로 돌아간다.
   * `원챌린지` 가 없으면 G1 이다 — 넓히기 전의 조인은 G1 만 걷었으므로 옛 호출자와 같은 뜻. */
  if (재제출 && 재제출.원사건) {
    if (재제출.원챌린지 === G2챌린지) {
      if (G2검수확정 !== true) return null;
      const 앵커 = String(재제출.원시드 || '');
      /* 대조 문항·팩에서 사라진 문항은 앉음이 못 선다 — SQL 필터(`G2재제출앵커들`)가 먼저
       * 거르지만 판정 정본은 여기다: 지어내지 않고 접는다(닻은 남는다 · 말하기 폴백). */
      if (!G2앉음편성(앵커)) return null;
      const task_snapshot = G2스냅샷(앵커);
      if (!task_snapshot) return null;
      return 배정행(날짜, task_snapshot, G2과제유형.짚음, G2스냅샷모양판, String(재제출.원사건), '게임G2재제출');
    }
    if (검수확정 !== true) return null;
    const 시드 = String(재제출.원시드 || '');
    const task_snapshot = G1스냅샷(시드);
    if (!task_snapshot) return null;
    return 배정행(날짜, task_snapshot, 과제유형, 스냅샷모양판, String(재제출.원사건), '게임재제출');
  }

  if (!learner_id) return null; // 배분 축이 없으면 지어내지 않는다 — 말하기가 나간다

  /* ⑥ 새 문항은 **모듈을 가른다** — 초급(1~2·미정)은 G2, 그 위는 G1.
   *   초급을 G1 에서 뺀 근거(격식 메일 쓰기는 초급이 받으면 그날 산출이 통째로 사라진다)는
   *   그대로다. 바뀐 것은 그 다음이다: 예전엔 거기서 **말하기로 내려갔고**, 그 대가로 초급
   *   학생의 ㉡ 재료(무엇을 오류로 보는가)가 영원히 0이었다 — 대장이 가장 비었다고 지목한
   *   바로 그 칸이 초급에서만 안 찼다. G2 는 그 비대칭이 없다: 어절 «하나»를 탭해 그 어절만
   *   고치므로 산출 하한이 「어절 1개」고, 초급이 받아도 그날 산출이 0 이 되지 않는다.
   *   🔑 `초급인가` 는 살려 둔다 — 뜻이 「제외」에서 「G2 로 보낸다」로 바뀔 뿐이다(모르면
   *   초급 = 안전 방향도 그대로: 모르는 학생은 산출 하한이 낮은 쪽을 받는다). */
  if (초급인가(급수)) {
    if (G2검수확정 !== true) return null;
    const 앵커 = G2앵커고르기(String(learner_id), 날짜);
    if (!앵커) return null;
    /* 🔑 배정 행에 실리는 것은 **앵커 하나**다. 나머지 둘은 앱이 같은 팩에서 결정적으로 편다
     *   (`contents/보고서교정문항.앉음편성`) — 배정 통로(멱등키·`task_ref`·`tasks` 응답 모양)를
     *   한 줄도 안 고치려는 판정이고, 근거는 그 함수 머리말에 한 벌로 적혀 있다. */
    const task_snapshot = G2스냅샷(앵커);
    if (!task_snapshot) return null;
    return 배정행(날짜, task_snapshot, G2과제유형.짚음, G2스냅샷모양판, null, '게임G2');
  }

  if (검수확정 !== true) return null;
  const 시드 = 시드고르기(String(learner_id), 날짜);

  const task_snapshot = G1스냅샷(시드);
  if (!task_snapshot) return null;
  return 배정행(날짜, task_snapshot, 과제유형, 스냅샷모양판, null, '게임');
}

/** 배정 행의 규격 한 벌 — 갈래마다 손으로 적으면 한쪽이 조용히 갈린다(판정 한 곳).
 *  🔑 `task_ref` 는 **날짜에서만** 판다(⑩ 확정 1) — 챌린지 식별은 스냅샷 `challenge_id` 다. */
function 배정행(날짜, task_snapshot, task_type, task_schema_ver, retry_of_event_id, 출처) {
  return Object.freeze({
    task_ref: `task-${날짜}`,
    task_type,
    task_snapshot,
    task_schema_ver,
    retry_of_event_id,
    degraded: false,
    출처,
  });
}

