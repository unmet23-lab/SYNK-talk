/* 🔴 `node:crypto` 가 아니라 순수 구현이다 — 이 파일은 `src/말하기화면.js` 까지 끌려가고
 *   (말하기화면 → 라디오낭독 → 여기), Metro 에는 Node 내장 모듈이 없어 **release 번들이
 *   통째로 안 만들어졌다**(실측 2026-08-16 · `Unable to resolve module node:crypto`).
 *   값은 그대로다 — `tests/sha256.test.js` 가 node:crypto 와 바이트로 대조해 못박는다. */
const { hex: sha256hex, 앞정수BE: sha256앞정수BE } = require('./sha256.js');
const { 추첨가중 } = require('./라디오편성.js');
/* 🔴 최상위 require 여야 한다 — 동봉 변환기(`원격배포.require풀기`)가 이 줄을 **최상위
 *   `import`** 로 바꾼다. 함수 안에 두면 배포본에서 함수 몸통 안의 import = SyntaxError 이고,
 *   배포는 성공하고 첫 호출에서 죽는다(2026-08-06 실측 계열). */
const { 검수판정 } = require('./토픽퀴즈검수.js');

const 생성판 = 'radio-round.v1';

/** 씨앗 → [0,1). sha256 앞 48비트 — 정수 안전 범위 안이고 후보 수천 개를 가르기 충분하다. */
function 눈금(씨앗) {
  if (typeof 씨앗 !== 'string' && typeof 씨앗 !== 'number') {
    throw new TypeError('라운드선정: 씨앗이 있어야 한다 — 없으면 매 라운드가 같은 문항을 뽑는다');
  }
  const s = String(씨앗);
  if (!s) throw new TypeError('라운드선정: 씨앗이 빈 문자열이다');
  return sha256앞정수BE(s, 6) / 2 ** 48;
}

/**
 * 라운드 문항 하나를 결정적으로 고른다.
 *
 * 재료 = {
 *   문항들: [{문항id, skill_ids}],        // 문항 팩
 *   노출수: {문항id: n},                  // 미노출 우선 회전(재고 축)의 재료
 *   승격요약: {skill: {응답, 오답}},       // `라디오편성.승격요약(...).요약`
 *   씨앗: string|number,                  // 라운드마다 다른 값 — 결정성의 축
 *   제외: [문항id],                       // 재도전 짝의 「다른 문항」 절반
 *   축한정: [skill_id] | null,            // 재도전 짝의 「같은 skill」 절반
 * }
 * 반환 = { 문항id, 가중, 후보수, 총가중, 생성판 } · 고를 것이 없으면 **null**
 *   — 없는 것을 지어내지 않는다. 부르는 쪽이 「팩이 말랐다」를 보고 사유를 남긴다.
 */
function 라운드선정(재료) {
  const { 문항들 = [], 노출수 = {}, 승격요약 = {}, 씨앗, 제외 = [], 축한정 = null } = 재료 || {};
  /* 씨앗 검사가 **맨 앞**이다 — 후보 추리기 뒤에 두면 팩이 마른 날에만 조용히 통과하는
   * 인자가 되고, 그것을 빠뜨린 부르는 쪽은 팩이 찰 때까지 안 드러난다. */
  const r = 눈금(씨앗);

  const 막힘 = new Set(Array.isArray(제외) ? 제외 : []);
  const 축 = Array.isArray(축한정) && 축한정.length ? new Set(축한정) : null;

  const 남은 = (Array.isArray(문항들) ? 문항들 : []).filter((q) => {
    if (!q || q.문항id == null || 막힘.has(q.문항id)) return false;
    if (!축) return true;
    const ids = Array.isArray(q.skill_ids) ? q.skill_ids : [];
    return ids.some((id) => 축.has(id)); // 재도전은 «같은 skill 다른 문항»이다(스키마 retry_of_round_id)
  });
  if (!남은.length) return null;

  const 후보들 = 추첨가중({ 문항들: 남은, 노출수, 승격요약 })
    .filter((x) => x.후보 && x.가중 > 0)
    .sort((a, b) => String(a.문항id).localeCompare(String(b.문항id)));
  if (!후보들.length) return null;

  const 총가중 = 후보들.reduce((s, x) => s + x.가중, 0);
  let 누적 = 0;
  for (const x of 후보들) {
    누적 += x.가중;
    if (r * 총가중 < 누적) {
      return { 문항id: x.문항id, 가중: x.가중, 후보수: 후보들.length, 총가중, 생성판 };
    }
  }
  /* 부동소수 잔차로 여기 오면 마지막 후보다 — null 로 떨어뜨리면 「팩이 말랐다」와 구분이
   * 안 되고, 그 오보가 곧 사유 없는 결번이 된다. */
  const 끝 = 후보들[후보들.length - 1];
  return { 문항id: 끝.문항id, 가중: 끝.가중, 후보수: 후보들.length, 총가중, 생성판 };
}

/* ══ 제안 ↔ 노출 두 문 — `radio-round` Fn 의 판정층 ═══════════════════════════════════
 *
 * 여기서 지는 것(전부 회귀가 닿는 순수 함수):
 *   ㉠ 검수 게이트 — `검수확정` 안 된 문항은 후보에서 아예 뺀다(팩 상수가 아니라 **문항별
 *      장부** 가 정본 · `lib/토픽퀴즈검수.검수판정` 을 그대로 부른다 — 규칙 사본 금지).
 *   ㉡ 화면 payload 조립 — 정답·해설은 **애초에 안 싣는다**(전광판판정의 `라운드금칙` 은
 *      마지막 그물이지 이 문의 변명이 아니다).
 *   ㉢ ack 해석 — 제안표를 풀고, 내용은 **팩에서 다시 조립**하고, 지문이 어긋나면 거절한다.
 */

/** 제안표·조립의 판. 스냅샷 «모양»의 판은 `생성판`(승격기가 `task_schema_ver` 로 쓴다). */
const 제안판 = 'radio-round-offer.v1';

/** v1 라운드 창(초) — 설계 §2-J. 전광판판정도 같은 값으로 접는다(둘 다 60). */
const 마감초기본 = 60;

/** 제안 → 노출 ack 사이 허용 창(초). 넘은 ack 는 거절한다 — 늦게 온 ack 를 그대로 적으면
 *  「몇 시간 전에 뽑은 문항」이 지금 화면에 있었다고 원장에 남는다. */
const 제안유효초 = 600;

/** 시계 어긋남 관용(초) — 봇 호스트와 DB 의 시계는 정확히 같지 않다. */
const 시계관용초 = 120;

const 제안구분 = '#';
const 부모없음 = '-';

/** 내용 지문 — 스냅샷의 «내용» 부분만 문다(제안id 자신은 뺀다: 순환이 된다). */
function 내용지문(내용) {
  return sha256hex(JSON.stringify(내용)).slice(0, 6);
}

/**
 * 팩 문항 하나 → 원장에 앉을 스냅샷의 «내용» 부분.
 * 소비자는 `lib/라디오승격.js`(`스냅.보기`·`스냅.skill_ids`·`스냅.스킬판`)와
 * `라디오편성.승격요약`(`task_snapshot.정답`)이다 — 키 이름은 그 두 곳이 정본이다.
 */
function 스냅샷내용(문항, 판) {
  const { 문항판 = null, 스킬판 = null } = 판 || {};
  return {
    문항판,
    스킬판,
    지시문: String(문항.지시문 ?? ''),
    질문: String(문항.질문 ?? ''),
    보기: (Array.isArray(문항.보기) ? 문항.보기 : []).map((o) => ({
      option_id: String(o.option_id), label: String(o.label),
    })),
    /* 🔴 정답은 **원장까지만** — 승격 스냅샷을 타고 learning_events 로 가지만, 화면 payload
     *   에는 안 실린다(팩 머리말 · C0 🚫is_correct — 정오는 파생값이다). */
    정답: String(문항.정답 ?? ''),
    skill_ids: (Array.isArray(문항.skill_ids) ? 문항.skill_ids : []).map(String),
  };
}

/** 제안표 만들기 — `<문항id>#<발급36>#<부모36|->#<지문6>`. 전광판 `round_id` 칸(32자)에 든다. */
function 제안id만들기(재료) {
  const { 문항id, 발급ms, 부모round_id = null, 지문 } = 재료 || {};
  const 초 = Math.floor(Number(발급ms) / 1000);
  if (!Number.isFinite(초) || 초 <= 0) throw new TypeError('제안id만들기: 발급ms 가 필요하다');
  const 부모 = 부모round_id == null || 부모round_id === '' ? 부모없음 : Number(부모round_id).toString(36);
  const 표 = [String(문항id), 초.toString(36), 부모, String(지문)].join(제안구분);
  /* 32자를 넘으면 전광판이 **조용히 자른다**(`String(round_id).slice(0,32)`) — 잘린 표는 ack 에서
   * 지문 불일치로만 드러나서, 원인이 「팩 id 가 길어졌다」인 것을 아무도 못 읽는다. 여기서 문다. */
  if (표.length > 32) throw new RangeError(`제안id만들기: 제안표가 32자를 넘었다(${표.length}) — 전광판이 자른다`);
  return 표;
}

/** 제안표 읽기 — 모양이 아니면 null(지어내지 않는다). */
function 제안id읽기(값) {
  if (typeof 값 !== 'string' || !값) return null;
  const 조각 = 값.split(제안구분);
  if (조각.length !== 4) return null;
  const [문항id, 발급36, 부모36, 지문] = 조각;
  if (!문항id || !발급36 || !부모36 || !지문) return null;
  const 초 = parseInt(발급36, 36);
  if (!Number.isFinite(초) || 초 <= 0) return null;
  let 부모round_id = null;
  if (부모36 !== 부모없음) {
    const n = parseInt(부모36, 36);
    if (!Number.isInteger(n) || n <= 0) return null;
    부모round_id = n;
  }
  return { 문항id, 발급ms: 초 * 1000, 부모round_id, 지문 };
}

/** 검수 게이트를 지난 문항만 — 규칙은 `토픽퀴즈검수` 하나가 진다(여기 사본을 안 만든다). */
function 송출가능문항(문항들, 장부) {
  const 판정 = 검수판정({ 문항들, 장부 });
  const 통과 = new Set(판정.송출가능);
  return { 문항들: (문항들 || []).filter((q) => q && 통과.has(q.문항id)), 분모: 판정.분모 };
}

/** 화면에 낼 것 — 마스코트가 아는 칸만. 정답·해설은 **여기 없다**(있으면 그게 유출이다).
 *  ⚠ v2 부터 전광판은 이걸 **안 그린다**(라운드 카드가 채팅으로 내려갔다 · 라디오24 §8-2-1).
 *  남긴 이유는 하나 — 같은 사건이 마스코트의 «놀람» 반응을 깨우고, 데모 계기판이 봇의 말을 센다.
 *  즉 이제 이것은 «화면 문안»이 아니라 **신호**다. 문안의 정본은 아래 `채팅조립`이다. */
function 화면조립(문항, 제안id, 마감초) {
  const 머리 = String(문항.지시문 ?? '').trim();
  const 몸 = String(문항.질문 ?? '').trim();
  const 한줄 = [머리, 몸].filter(Boolean).join(' ');
  return {
    종류: '라운드',
    round_id: 제안id,
    /* 120 은 전광판판정 `다듬기(원본.지시문, 120)` 의 상한이다 — 저쪽이 자르기 전에 여기서
     * 자른다. 저쪽에 맡기면 «무엇이 잘렸나»가 방송 화면에서만 드러난다. */
    지시문: 한줄.length > 120 ? `${한줄.slice(0, 119)}…` : 한줄,
    보기들: (Array.isArray(문항.보기) ? 문항.보기 : []).map((o) => ({
      option_id: String(o.option_id), label: String(o.label),
    })),
    마감초,
  };
}

/* ══ 채팅 3줄 — v2 의 «출제 통로» ═══════════════════════════════════════════════════
 *
 * 유호 확정 08-25 ①: 「미니퀴즈를 방송 화면에서 채팅으로 내린다 — 공부하려고 켠 학생에게
 * 정각마다 문제를 들이대면 배경음악이 아니라 수업이 된다.」 그래서 문항은 이제 봇이
 * `liveChatMessages.insert` 로 채팅에 «쓴다» — 라운드당 세 줄(출제·마감·정답).
 *
 * 🔴 급소는 **200자**다 — 유튜브 라이브 채팅 한 줄의 상한이다(실측 09-01).
 *   ⇒ 출제줄은 «보기부터» 채우고 남는 자리에 지시문을 넣는다. 순서가 뒤집히면(지시문 먼저)
 *     보기가 잘려 **답을 고를 수 없는 문제**가 방송에 나간다 — 지시문이 잘리는 것은 견딜 수 있고
 *     보기가 잘리는 것은 못 견딘다. 그 우선순위를 코드가 진다.
 *   ⇒ 보기·안내만으로 이미 200 을 넘는 문항은 **채팅 출제 불가**다(`null`). 조용히 자르지 않는다 —
 *     그런 문항은 팩 쪽에서 고칠 일이지 방송에서 뭉갤 일이 아니다.
 * 🔑 몽골어는 **비워 둔다** — 검수 전까지 한국어만(전광판판정 문안표와 같은 규칙).
 */

/** 유튜브 라이브 채팅 한 줄 상한(실측 09-01). 넘으면 API 가 거절한다. */
const 채팅상한 = 200;

/** 학생이 보는 문안. 몽골어는 검수 전까지 `null` — 지어내지 않는다. */
const 채팅문안 = {
  답안내: { ko: '채팅에 「!답 번호」 로 답해 주세요', mn: null },
  남은시간: { ko: '초 동안 받아요', mn: null },
  마감: { ko: '답 받는 시간이 끝났어요. 곧 정답을 알려 드릴게요', mn: null },
  정답머리: { ko: '정답은', mn: null },
  함께: { ko: '함께 푼 사람', mn: null },
  재도전: { ko: '60초 뒤에 같은 유형으로 한 번 더 갈게요', mn: null },
  /* 아무도 안 답한 라운드 — 「0명」이라고 쓰지 않는다(세어서 알려 줄 값이 아니라 그냥 조용했던 것이다).
     「오늘은」이 아니라 「이번엔」인 이유: 하루가 아니라 그 라운드 하나를 가리킨다. */
  혼자여도: { ko: '이번엔 조용했어요. 다음 문제도 곧 올게요', mn: null },
};

/** 한 줄 문안 — 몽골어가 비면 한국어만(빈 괄호·기계번역 금지). */
function 채팅말(키) {
  const t = 채팅문안[키];
  if (!t) return '';
  return t.mn ? `${t.ko} · ${t.mn}` : t.ko;
}

/** 보기 → 「1) 을  2) 에」. 번호는 학생이 `!답 2` 로 칠 **1-based 자리**다(option_id 가 아니다). */
function 보기줄(보기들) {
  return (Array.isArray(보기들) ? 보기들 : [])
    .map((o, i) => `${i + 1}) ${String(o.label ?? '').trim()}`)
    .join('  ');
}

/**
 * 출제줄 — 200자 안에서 «보기 먼저». 못 맞추면 `null`(방송에 안 낸다).
 * @returns {string|null}
 */
function 출제줄(문항, 마감초 = 마감초기본) {
  const 보기 = 보기줄(문항 && 문항.보기);
  if (!보기) return null;
  const 꼬리 = `${보기}  ·  ${채팅말('답안내')}  ·  ${마감초}${채팅말('남은시간')}`;
  if (꼬리.length >= 채팅상한) return null;   // 보기·안내만으로 이미 넘는다 — 팩이 고칠 일이다

  const 머리 = String((문항 && 문항.지시문) ?? '').trim();
  const 몸 = String((문항 && 문항.질문) ?? '').trim();
  const 물음 = [머리, 몸].filter(Boolean).join(' ');
  const 남는자리 = 채팅상한 - 꼬리.length - 2;  // 2 = 물음과 꼬리 사이 공백
  if (남는자리 < 1) return null;
  const 자른물음 = 물음.length > 남는자리
    ? `${물음.slice(0, Math.max(0, 남는자리 - 1))}…`
    : 물음;
  return `${자른물음}  ${꼬리}`.trim();
}

/** 마감줄 — 짧다. 여기엔 정답이 없다(공개는 다음 줄이다). */
function 마감줄() {
  return 채팅말('마감');
}

/**
 * 정답줄 — 정답 «자리»와 라벨을 함께 말한다(자리만 말하면 나중에 로그로 못 읽는다).
 * 응답수는 **집단 합산만**이다(§8 개인 성적 영구 금지). 0 명이면 숫자를 안 쓴다.
 * @returns {string|null} 정답이 보기에 없으면 null — 틀린 정답을 방송에 쓰지 않는다.
 */
function 정답줄(문항, 응답수 = null) {
  const 보기들 = Array.isArray(문항 && 문항.보기) ? 문항.보기 : [];
  const 자리 = 보기들.findIndex((o) => String(o.option_id) === String(문항 && 문항.정답));
  if (자리 < 0) return null;
  const 라벨 = String(보기들[자리].label ?? '').trim();
  const 앞 = `${채팅말('정답머리')} ${자리 + 1}번 「${라벨}」`;
  const n = Number(응답수);
  const 가운데 = Number.isInteger(n) && n > 0
    ? `  ·  ${채팅말('함께')} ${n}`
    : `  ·  ${채팅말('혼자여도')}`;
  const 한줄 = `${앞}${가운데}  ·  ${채팅말('재도전')}`;
  /* 자를 자리가 없다 — 넘으면 재도전 안내부터 뗀다(정답·집단수가 먼저다). */
  if (한줄.length <= 채팅상한) return 한줄;
  const 짧게 = `${앞}${가운데}`;
  return 짧게.length <= 채팅상한 ? 짧게 : 앞.slice(0, 채팅상한);
}

/**
 * 라운드 하나가 채팅에 쓸 세 줄. 봇은 이 순서로 `insert` 한다.
 * 🔑 `출제` 가 `null` 이면 **그 라운드를 열지 않는다** — 부르는 쪽이 다른 문항을 뽑아야 한다.
 * @returns {{출제:string|null, 마감:string, 정답:string|null}}
 */
function 채팅조립(문항, 마감초 = 마감초기본, 응답수 = null) {
  return { 출제: 출제줄(문항, 마감초), 마감: 마감줄(), 정답: 정답줄(문항, 응답수) };
}

/**
 * 라운드 하나를 «제안»한다 — **DB 를 안 만진다.**
 *
 * 재료 = {
 *   문항들, 판: {문항판, 스킬판},   // 팩
 *   장부,                          // 문항별 검수 장부
 *   노출수, 승격요약, 씨앗,          // 회전·되돌림 재료(라운드선정 그대로)
 *   제외, 축한정, 부모round_id,      // 재도전 짝(같은 skill 다른 문항)
 *   지금(ms), 마감초,
 * }
 * 반환 = { 제안: {제안id, task_ref, 화면, 스냅샷, 가중, 후보수, 총가중} | null, 분모 }
 *   — 고를 것이 없으면 `제안: null` 이고 **분모가 왜인지 말한다**(F207 — 조용한 0 금지).
 */
function 제안조립(재료) {
  const {
    문항들 = [], 판 = {}, 장부 = {}, 노출수 = {}, 승격요약 = {}, 씨앗,
    제외 = [], 축한정 = null, 부모round_id = null, 지금, 마감초 = 마감초기본,
  } = 재료 || {};
  if (!Number.isFinite(Number(지금))) throw new TypeError('제안조립: 지금(ms)은 부르는 쪽이 준다');

  const { 문항들: 검수통과, 분모: 검수분모 } = 송출가능문항(문항들, 장부);
  /* 🔴 v2 — 채팅 200자에 못 드는 문항은 후보에서 «먼저» 뺀다.
   *   뽑은 뒤에 걸러내면 「뽑혔는데 못 쓴다」가 되어 그 라운드가 통째로 빈다. 여기서 빼면
   *   추첨이 남은 것들 사이에서 정상으로 돈다. 뺀 수는 분모가 말한다(F207 — 조용한 0 금지). */
  const 통과 = 검수통과.filter((q) => 출제줄(q, 마감초) !== null);
  const 분모 = {
    검수: 검수분모,
    채팅넘침: 검수통과.length - 통과.length,
    제외: (제외 || []).length,
    축한정: 축한정 ? 축한정.length : 0,
  };

  /* 씨앗 검사는 `라운드선정` 이 맨 앞에서 한다 — 팩이 마른 날에도 던지도록 거기 둔 것이라
   * 여기서 미리 접지 않는다(접으면 그 설계가 무력해진다). */
  const 뽑힘 = 라운드선정({ 문항들: 통과, 노출수, 승격요약, 씨앗, 제외, 축한정 });
  if (!뽑힘) return { 제안: null, 분모: { ...분모, 사유: 통과.length ? '후보0' : '검수확정0' } };

  const 문항 = 통과.find((q) => q.문항id === 뽑힘.문항id);
  const 내용 = 스냅샷내용(문항, 판);
  const 제안id = 제안id만들기({ 문항id: 문항.문항id, 발급ms: Number(지금), 부모round_id, 지문: 내용지문(내용) });

  return {
    제안: {
      제안id,
      task_ref: 문항.문항id,           // 🔴 접두 변형 금지(§10 기각 4) — 앱과 같은 id 다
      부모round_id,
      화면: 화면조립(문항, 제안id, 마감초),   // 마스코트 반응 신호(문안 아님 — v2)
      채팅: 채팅조립(문항, 마감초),            // 🔴 봇이 실제로 쓰는 세 줄(문안 정본)
      스냅샷: { ...내용, 제안id, 제안판 },
      가중: 뽑힘.가중, 후보수: 뽑힘.후보수, 총가중: 뽑힘.총가중, 생성판: 뽑힘.생성판,
    },
    분모,
  };
}

/**
 * 전광판 ack 를 원장 행으로 번역한다 — **내용은 팩에서 다시 조립한다**(부르는 쪽 문안 무시).
 *
 * 재료 = { 제안id, at(ISO 문자열 — 화면이 그린 시각), 문항들, 판, 장부, 지금(ms), 유효초? }
 * 반환 = { ok:true, task_ref, 부모round_id, 스냅샷, shown_at } | { ok:false, 사유 }
 */
function 노출해석(재료) {
  const { 제안id, at, 문항들 = [], 판 = {}, 장부 = {}, 지금, 유효초 = 제안유효초 } = 재료 || {};
  if (!Number.isFinite(Number(지금))) throw new TypeError('노출해석: 지금(ms)은 부르는 쪽이 준다');
  const 이제 = Number(지금);

  const 표 = 제안id읽기(제안id);
  if (!표) return { ok: false, 사유: '제안표불량' };

  /* 신선도가 **내용 대조보다 먼저**다 — 오래된 표는 팩이 그 사이 바뀌었을 수 있어서, 지문
   * 불일치로 떨어뜨리면 사유가 「내용이 다르다」로 잘못 보인다. */
  if (표.발급ms > 이제 + 시계관용초 * 1000) return { ok: false, 사유: '발급미래' };
  if (이제 - 표.발급ms > 유효초 * 1000) return { ok: false, 사유: '제안만료' };

  const { 문항들: 통과 } = 송출가능문항(문항들, 장부);
  const 문항 = 통과.find((q) => q && q.문항id === 표.문항id);
  /* 팩에 없는 것과 검수 안 된 것을 **가르지 않는다** — 둘 다 「원장에 앉으면 안 되는 문항」이고,
   * 가르면 이 응답이 «검수 상태 조회기»가 된다(누가 뭘 물어보는지로 장부를 훑을 수 있다). */
  if (!문항) return { ok: false, 사유: '문항없음또는미검수' };

  const 내용 = 스냅샷내용(문항, 판);
  if (내용지문(내용) !== 표.지문) return { ok: false, 사유: '내용어긋남' };

  const t = Date.parse(at);
  if (!Number.isFinite(t)) return { ok: false, 사유: '노출시각불량' };
  if (t > 이제 + 시계관용초 * 1000) return { ok: false, 사유: '노출시각미래' };
  /* 그린 시각이 뽑은 시각보다 앞설 수는 없다(관용 안에서만 봐준다) — 앞서면 그 ack 는 이
   * 제안의 것이 아니다. */
  if (t < 표.발급ms - 시계관용초 * 1000) return { ok: false, 사유: '노출시각역전' };

  return {
    ok: true,
    task_ref: 문항.문항id,
    부모round_id: 표.부모round_id,
    스냅샷: { ...내용, 제안id: String(제안id), 제안판 },
    shown_at: new Date(t).toISOString(),
  };
}

