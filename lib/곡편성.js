'use strict';
/**
 * 곡편성 — SYNK **Reed** 의 심장. 「지금 무엇을 트나」를 **규칙으로** 답한다.
 * (설계 정본 = appsscript `docs/Reed_설계_v0.1.md` §3 · 유호 확정 08-25)
 *
 * ■ 🔴 왜 «편성표»가 아니라 «규칙»인가
 *   날짜별 편성표를 만들면 **그 표를 사람이 관리하게 된다** — 100곡이면 매일 배열하는 일이
 *   일의 전부가 되고, 곡을 하나 더할 때마다 표를 다시 짠다. 규칙으로 두면 **곡을 하나 더하면
 *   편성이 저절로 넓어진다.** 곡이 200이 돼도 사람 손은 0이다.
 *
 * ■ 🔴 순수 함수다 — 시계도 난수도 파일도 없다
 *   `지금시각` 을 **인자로 받는다**(몽골 기준 0~24 실수). 안에서 `new Date()` 를 부르면
 *   회귀가 원리상 못 문다 — 「새벽 3시의 편성」을 시험하려고 새벽 3시를 기다릴 수는 없다.
 *   ⚠ 날짜·시간대의 정본은 이 파일이 아니다(`lib/오늘과제.js` 계열). 여기는 «몇 시인가»만 받는다.
 *   난수도 안 쓴다 — 같은 상태에서 같은 답이 나와야 「왜 이 곡이 나왔나」를 물을 수 있다.
 *
 * ■ 랜덤 재생과 방송을 가르는 규칙 셋 (설계 §3)
 *   ① 결이 갑자기 안 바뀐다 — 결 사이는 곡 두세 개에 걸쳐 넘어간다(BPM·밝기가 계단으로)
 *   ② 최장 미노출 우선 — 「같은 곡 하루 1회」는 §3-B 산수상 **불가능**하니 약속하지 않는다.
 *      대신 «최소 간격»을 둔다: 그 안에는 어떤 이유로도 다시 안 나온다.
 *   ③ DJ 교대는 결이 바뀌는 자리에서만 — 곡 사이마다 바뀌면 존재가 싸구려가 된다(유호 08-25)
 */

const { 채택된것 } = require('./곡장부.js');

/**
 * 하루의 결 다섯. `시작` 은 몽골 기준 시각(0~24) · 반열림 구간 [시작, 다음 시작).
 * 🔑 `BPM`·`밝기` 는 그 결의 **중심**이다 — 전환 구간에서 두 결 사이를 «계단»으로 잇는 재료다.
 *    밝기는 0(어둡다)~1(밝다) 눈금이고 곡의 `밝기` 칸과 같은 자.
 */
const 결표 = Object.freeze([
  { 이름: '새벽', 시작: 0, DJ: '몽글', 장르: ['자연'], BPM: 56, 밝기: 0.12 },
  { 이름: '아침', 시작: 6, DJ: '까몽', 장르: ['시티팝'], BPM: 100, 밝기: 0.72 },
  { 이름: '낮', 시작: 9, DJ: '새친구', 장르: ['전자', '시티팝'], BPM: 108, 밝기: 0.80 },
  { 이름: '저녁', 시작: 17, DJ: '까몽', 장르: ['시티팝'], BPM: 98, 밝기: 0.55 },
  { 이름: '밤', 시작: 21, DJ: '몽글', 장르: ['자연', '전자'], BPM: 66, 밝기: 0.22 },
]);

/** 결이 바뀌기 «전» 이만큼은 다음 결로 건너가는 계단이다(분). 곡 두세 개 분량. */
const 전환분 = 24;

/** 이 안에는 같은 곡이 다시 안 나온다(분). §3-B 산수상 하루 1회는 불가능하니 이것으로 약속한다. */
const 최소간격분 = 90;

const 시각정리 = (h) => ((Number(h) % 24) + 24) % 24;

/** 지금 어느 결인가. */
function 지금결(지금시각) {
  const h = 시각정리(지금시각);
  let 결 = 결표[결표.length - 1];
  for (const r of 결표) if (h >= r.시작) 결 = r;
  return 결;
}

/** 다음 결과, 거기까지 몇 분 남았나. */
function 다음결까지(지금시각) {
  const h = 시각정리(지금시각);
  const 이번 = 지금결(h);
  const i = 결표.findIndex((r) => r.이름 === 이번.이름);
  const 다음 = 결표[(i + 1) % 결표.length];
  const 경계 = 다음.시작 === 0 ? 24 : 다음.시작;
  return { 다음, 남은분: Math.round((경계 - h) * 60) };
}

/**
 * 지금 겨눌 «과녁» — 결 하나이거나, 경계 앞이면 두 결 사이의 계단이다.
 * 🔑 이것이 규칙 ①의 전부다. 과녁이 계단으로 움직이면 고르는 곡도 계단으로 움직인다.
 * @returns {{결: string, 다음결: string|null, 진행: number, BPM: number, 밝기: number, 장르: string[], DJ: string}}
 */
function 과녁(지금시각) {
  const 이번 = 지금결(지금시각);
  const { 다음, 남은분 } = 다음결까지(지금시각);
  if (남은분 > 전환분) {
    return { 결: 이번.이름, 다음결: null, 진행: 0, BPM: 이번.BPM, 밝기: 이번.밝기, 장르: [...이번.장르], DJ: 이번.DJ };
  }
  const 진행 = Math.min(1, Math.max(0, (전환분 - 남은분) / 전환분));   // 0 → 1 로 다음 결에 다가간다
  return {
    결: 이번.이름,
    다음결: 다음.이름,
    진행,
    BPM: 이번.BPM + (다음.BPM - 이번.BPM) * 진행,
    밝기: 이번.밝기 + (다음.밝기 - 이번.밝기) * 진행,
    /* 🔑 전환 구간에서는 **두 결의 장르를 함께** 받는다 — 안 그러면 경계에서 소리가 «툭» 갈린다. */
    장르: [...new Set([...이번.장르, ...다음.장르])],
    /* 🔴 DJ 는 «아직» 안 바꾼다(규칙 ③) — 교대는 경계를 «넘은 뒤» 한 번이다. */
    DJ: 이번.DJ,
  };
}

/** DJ 가 지금 바뀌는가 — 결이 실제로 넘어간 그 자리에서만 참이다. */
function DJ교대인가(앞시각, 지금시각) {
  const a = 지금결(앞시각), b = 지금결(지금시각);
  return a.이름 !== b.이름 && a.DJ !== b.DJ;
}

/**
 * 곡 하나를 고른다 — **가장 오래 안 나온 곡부터, 과녁에 가까운 순으로**.
 *
 * 점수 = 미노출 시간(클수록 좋다) − 과녁에서 벗어난 만큼(BPM·밝기).
 * 🔑 «미노출»을 먼저 두는 이유: 취향에 맞추려 들면 같은 몇 곡만 계속 돌고, 100곡을 만든 값이
 *   사라진다. 과녁은 «어울리지 않는 곡을 밀어내는» 몫이지 «최고를 고르는» 몫이 아니다.
 *
 * @param {object[]} 장부
 * @param {number} 지금시각  몽골 기준 0~24
 * @param {Array<{id: string, 언제분: number}>} 이력  언제분 = 지금으로부터 «몇 분 전에» 나갔나
 * @returns {{곡: object|null, 왜: string, 과녁: object, 후보수: number}}
 */
function 다음곡(장부, 지금시각, 이력 = []) {
  const 겨눔 = 과녁(지금시각);
  const 풀 = 채택된것(장부).filter((c) => 겨눔.장르.includes(c.장르));
  const 마지막 = new Map();
  for (const h of Array.isArray(이력) ? 이력 : []) {
    if (!h || !h.id) continue;
    const 분 = Number(h.언제분);
    if (!Number.isFinite(분)) continue;
    if (!마지막.has(h.id) || 분 < 마지막.get(h.id)) 마지막.set(h.id, 분);
  }
  /* 규칙 ② — 최소 간격 안에는 어떤 이유로도 안 나온다. */
  const 걸수있는것 = 풀.filter((c) => !(마지막.has(c.id) && 마지막.get(c.id) < 최소간격분));
  if (!걸수있는것.length) {
    /* 🔴 여기서 «아무거나»로 접지 않는다 — 빈 방송보다 나쁜 것은 «왜 이게 나왔는지 모르는 방송»이다.
     *   못 고른 사유를 그대로 말하고, 부르는 쪽이 처분한다(간격을 줄이든 곡을 늘리든). */
    return {
      곡: null, 과녁: 겨눔, 후보수: 풀.length,
      왜: 풀.length
        ? `${겨눔.결} 풀 ${풀.length}곡이 전부 최근 ${최소간격분}분 안에 나갔다 — 곡이 모자라다`
        : `${겨눔.결} 에 걸 수 있는 채택곡이 0이다(장르 ${겨눔.장르.join('·')})`,
    };
  }
  const 점수 = (c) => {
    const 미노출 = 마지막.has(c.id) ? 마지막.get(c.id) : 24 * 60;       // 안 나온 곡은 하루로 친다
    const bpm벌 = Number.isFinite(Number(c.BPM)) ? Math.abs(Number(c.BPM) - 겨눔.BPM) : 0;
    const 밝기벌 = Number.isFinite(Number(c.밝기)) ? Math.abs(Number(c.밝기) - 겨눔.밝기) * 100 : 0;
    return 미노출 - (bpm벌 * 1.5 + 밝기벌 * 1.5);
  };
  /* 동점이면 id 순 — 같은 상태에서 같은 답이 나와야 「왜 이 곡인가」를 물을 수 있다(난수 0). */
  const 골라진것 = [...걸수있는것].sort((a, b) => (점수(b) - 점수(a)) || String(a.id).localeCompare(String(b.id)))[0];
  const 미노출 = 마지막.has(골라진것.id) ? `${마지막.get(골라진것.id)}분 전에 나갔다` : '아직 안 나갔다';
  return {
    곡: 골라진것, 과녁: 겨눔, 후보수: 걸수있는것.length,
    왜: `${겨눔.결}${겨눔.다음결 ? `→${겨눔.다음결} 계단(${Math.round(겨눔.진행 * 100)}%)` : ''} · ${미노출} · 과녁 ${Math.round(겨눔.BPM)}BPM`,
  };
}

/**
 * 앞으로 몇 곡을 미리 세워 본다 — «편성이 도는지»를 사람이 눈으로 보는 자리.
 * 🔑 방송을 안 켜고도 하루를 돌려볼 수 있어야 한다(학생 0명 · 방송 0일에도 잴 수 있는 유일한 층).
 */
function 미리보기(장부, 시작시각, 곡수 = 10) {
  const 줄 = [];
  const 이력 = [];
  let 시각 = 시각정리(시작시각);
  for (let i = 0; i < 곡수; i++) {
    const r = 다음곡(장부, 시각, 이력);
    줄.push({ 시각, ...r });
    if (!r.곡) break;
    const 분 = (Number(r.곡.길이초) || 360) / 60;
    for (const h of 이력) h.언제분 += 분;
    이력.unshift({ id: r.곡.id, 언제분: 0 });
    시각 = 시각정리(시각 + 분 / 60);
  }
  return 줄;
}

/**
 * 🔑 **최소 간격이 «풀의 최소 크기»를 정한다** — 회귀가 잡아낸 파생 규칙(08-26).
 *   같은 곡이 90분 안에 안 나오려면, 그 90분을 채울 만큼의 곡이 풀에 있어야 한다.
 *   6분 곡이면 90/6 = **15곡**이 바닥이고, 그 아래면 편성이 「곡이 모자라다」로 멈춘다.
 *   ⚠ 멈추는 것이 결함이 아니라 **정직한 신호**다 — 조용히 같은 곡을 다시 트는 쪽이 나쁘다.
 *   (유호 계획 = 장르당 20~30곡 · 6분 판이면 여유가 있다)
 * @param {number} 곡길이초 그 풀의 «대표» 길이
 * @returns {number} 이 풀에 최소 몇 곡이 있어야 안 멈추나
 */
function 풀최소크기(곡길이초) {
  const 초 = Number(곡길이초) > 0 ? Number(곡길이초) : 360;
  return Math.ceil((최소간격분 * 60) / 초) + 1;
}

module.exports = { 결표, 전환분, 최소간격분, 지금결, 다음결까지, 과녁, DJ교대인가, 다음곡, 미리보기, 풀최소크기 };
