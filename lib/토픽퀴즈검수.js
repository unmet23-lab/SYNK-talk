/* TOPIK 퀴즈 팩 «문항별» 검수 장부 — 판정층 (발전 트랙 ① · 유호 확정 08-14)
 *
 * ■ 무엇을 바꾸나
 *   팩(`contents/토픽퀴즈문항.js`)의 `검수확정` 은 **팩 전체에 걸린 상수 하나**다. 그래서
 *   100문항 중 3문항이 검수에서 걸리면 나머지 97문항까지 송출이 막힌다 — 실제로 열리는
 *   날은 「전부 통과한 날」뿐이고, 그런 날은 오지 않는다(첫 검수에서 치명 3이 나왔다).
 *   이 장부는 확정을 **문항 단위**로 내려, 통과한 것부터 라운드에 서게 한다.
 *
 * ■ 해설을 «자유 문장»으로 안 두는 이유 (팩 머리말 「🚫 해설」과의 충돌을 이렇게 푼다)
 *   팩은 해설을 일부러 뺐고 사유가 둘이다 — ①문안은 렌더 층(오버레이·봇) 몫 ②몽골어
 *   검수 의존을 팩에 들이지 않는다. 둘 다 유효하다. 그래서 여기서 확정하는 것은 문장이
 *   아니라 **「이 문항의 오답이 죽는 이유」 범주 하나**다:
 *     · 범주는 팩 머리말이 이미 저작 원칙으로 쓴 넷(음운·형태·호응·의미) 그대로다 — 새 축을
 *       발명하지 않는다.
 *     · 화면에 나가는 문구는 범주당 **한 벌**이라 몽골어 검수 발주가 100줄이 아니라 4줄이다
 *       (자유 해설이면 문항마다 번역·검수가 붙어 ②가 현실이 된다).
 *     · 그리고 이 범주는 표시용이 아니다 — 오답 «유형»이라 ㉠실력 이해 축의 재료가 된다
 *       (`error_tags` 와 같은 계열 · 승격 규격은 그 트랙 몫이고 여기서 만들지 않는다).
 *   자유 근거 문장(`근거_ko`)은 **선택**이다 — 강사가 남기고 싶을 때만. 화면에는 안 나간다
 *   (나가는 순간 ②가 되살아난다). 남는 자리는 다음 저작·재검수의 메모다.
 *
 * ■ 검수는 «그때 그 문항»에만 걸린다 — 낡으면 스스로 무효가 된다
 *   문항 문구를 고치면 그 문항의 검수는 자동으로 `낡음` 이 된다(확정 당시 지문과 대조).
 *   이게 없으면 「검수 완료」 표식이 고쳐진 문항 위에 그대로 앉아 **맞는 얼굴로 틀린 값**을
 *   낸다 — 장치가 안 도는 쪽보다 이쪽으로 더 자주 샌다(지침 v9.2 맹점 ④).
 *
 * ■ 경계
 *   · 파일·DB·시계를 안 읽는다 — 장부·팩·시각 전부 인자다(도구 `tools/문항검수.js` 가 읽고 쓴다).
 *   · 이 파일은 «누가 검수했나»를 신원으로 안 받는다 — 학생 식별자가 들어올 자리가 없다.
 *
 * ■ 틀릴 때의 모습 · 대가
 *   장부가 비어 있으면 `송출가능` 이 빈 배열이다 — 「전부 통과」와 「한 번도 안 열었다」가
 *   같은 모양이 되지 않게 `분모` 를 함께 낸다(F207). 닫는 것: 팩 상수 `검수확정` 은 그대로
 *   둔다(팩 전체를 한 번에 여는 축은 남긴다) — 다만 **라운드 통로는 이 장부를 본다**.
 */
'use strict';

const crypto = require('node:crypto');

const 검수판 = 'quiz-review.v1';

/* 오답이 죽는 이유 — 팩 머리말의 저작 원칙 넷 그대로(새 축 발명 금지).
 * `문구_ko` 가 정답 공개 화면에 나가는 «한 벌» 문구다. `문구_mn` 은 검수 발주 대상 4줄이고,
 * 비어 있으면 오버레이가 한국어만 낸다(지어낸 번역을 내보내지 않는다). */
const 범주표 = Object.freeze([
  Object.freeze({ 범주: '음운', 문구_ko: '앞말의 받침에 따라 꼴이 갈립니다', 문구_mn: '' }),
  Object.freeze({ 범주: '형태', 문구_ko: '활용(꼴 바꾸기)에서 갈립니다', 문구_mn: '' }),
  Object.freeze({ 범주: '호응', 문구_ko: '앞뒤가 서로 맞아야 합니다', 문구_mn: '' }),
  Object.freeze({ 범주: '의미', 문구_ko: '문맥에서 뜻이 맞아야 합니다', 문구_mn: '' }),
]);
const 범주이름들 = Object.freeze(범주표.map((c) => c.범주));

/** 문항 지문 — 확정 당시의 «그 문항»을 못박는다(문구가 바뀌면 검수가 낡는다). */
function 지문(문항) {
  if (!문항 || typeof 문항 !== 'object') throw new TypeError('지문: 문항 객체가 필요하다');
  const 재료 = JSON.stringify([
    문항.문항id, 문항.지시문, 문항.질문,
    (문항.보기 || []).map((b) => [b.option_id, b.label]),
    문항.정답,
  ]);
  return crypto.createHash('sha256').update(재료).digest('hex').slice(0, 16);
}

/**
 * 범주 «초안» — 사람이 고르는 칸을 미리 채운다(사람이 누르는 칸은 확정 하나여야 한다).
 * skill_id 축으로만 정한다. 초안이지 판정이 아니다 — 검수자가 화면에서 바꿀 수 있고,
 * 바꾼 값이 장부에 남는다. 모르는 축은 **지어내지 않고** null(화면이 「고르세요」로 낸다).
 */
function 범주초안(skill_ids) {
  const ids = Array.isArray(skill_ids) ? skill_ids : [];
  if (!ids.length) return null;
  const id = ids[0];
  if (/-particle-/.test(id)) return '음운';        // 조사는 받침에 따라 꼴이 갈리는 자리가 급소
  if (/-vocab-adverb/.test(id)) return '호응';      // 부사 호응(별로+긍정 류)
  if (/-vocab-/.test(id)) return '의미';
  if (/-grammar-|-expression-/.test(id)) return '형태'; // 어미·시제·높임·부정·표현 = 활용
  return null;
}

/**
 * 장부 한 칸 검사 — 통과면 null, 아니면 사유 문자열.
 * 「모양이 이상한 칸」을 통과로 세지 않는다(통과는 언제나 새는 방향이다).
 */
function 칸사유(칸, 문항) {
  if (!칸 || typeof 칸 !== 'object') return '칸없음';
  if (칸.확정 !== true) return '미확정';
  if (!범주이름들.includes(칸.범주)) return '범주불량';
  if (typeof 칸.지문 !== 'string' || !칸.지문) return '지문없음';
  if (칸.지문 !== 지문(문항)) return '낡음';
  return null;
}

/**
 * 장부 × 팩 → 지금 송출에 쓸 수 있는 문항.
 * 재료 = { 문항들: 팩.문항들, 장부: {문항id: 칸} }
 * 반환 = { 송출가능: [문항id], 막힘: {문항id: 사유}, 분모: { 팩: n, 송출가능: n, 사유별: {사유: n} } }
 *   — 「0」이 좋은 0인지 안 연 것인지를 분모가 가른다(F207).
 */
function 검수판정(재료) {
  const { 문항들 = [], 장부 = {} } = 재료 || {};
  const 송출가능 = [];
  const 막힘 = {};
  const 사유별 = {};
  for (const 문항 of Array.isArray(문항들) ? 문항들 : []) {
    if (!문항 || !문항.문항id) continue;
    const 사유 = 칸사유(장부[문항.문항id], 문항);
    if (사유 === null) { 송출가능.push(문항.문항id); continue; }
    막힘[문항.문항id] = 사유;
    사유별[사유] = (사유별[사유] || 0) + 1;
  }
  return {
    검수판,
    송출가능,
    막힘,
    분모: { 팩: (문항들 || []).length, 송출가능: 송출가능.length, 사유별 },
  };
}

/**
 * 확정 한 건을 장부에 얹는다 — **새 객체를 돌려준다**(제자리 수정 금지: 부르는 쪽이
 * 실패한 저장 뒤에도 옛 장부를 그대로 들고 있어야 한다).
 * 재료 = { 장부, 문항, 범주, 근거_ko?, 검수자?, 지금 }
 */
function 확정얹기(재료) {
  const { 장부 = {}, 문항, 범주, 근거_ko = '', 검수자 = '', 지금 } = 재료 || {};
  if (!문항 || !문항.문항id) throw new TypeError('확정얹기: 문항이 필요하다');
  if (!범주이름들.includes(범주)) throw new TypeError(`확정얹기: 범주는 ${범주이름들.join('·')} 중 하나여야 한다`);
  if (typeof 지금 !== 'string' || !지금) throw new TypeError('확정얹기: 지금(ISO 시각)은 부르는 쪽이 준다');
  if (typeof 근거_ko !== 'string') throw new TypeError('확정얹기: 근거_ko 는 문자열이다');
  return {
    ...장부,
    [문항.문항id]: {
      확정: true,
      범주,
      /* 근거는 화면에 안 나간다(몽골어 검수 의존을 안 만든다) — 다음 저작·재검수의 메모다. */
      근거_ko: 근거_ko.slice(0, 200),
      지문: 지문(문항),
      확정시각: 지금,
      검수자: String(검수자).slice(0, 40),
    },
  };
}

/** 반려 — 확정을 «지우는» 것이 아니라 사유를 남긴다(장부는 무슨 일이 있었는지도 든다). */
function 반려얹기(재료) {
  const { 장부 = {}, 문항, 사유 = '', 검수자 = '', 지금 } = 재료 || {};
  if (!문항 || !문항.문항id) throw new TypeError('반려얹기: 문항이 필요하다');
  if (typeof 지금 !== 'string' || !지금) throw new TypeError('반려얹기: 지금(ISO 시각)은 부르는 쪽이 준다');
  return {
    ...장부,
    [문항.문항id]: {
      확정: false,
      반려사유: String(사유).slice(0, 200),
      지문: 지문(문항),
      확정시각: 지금,
      검수자: String(검수자).slice(0, 40),
    },
  };
}

/** 화면에 낼 «한 벌» 문구 — 없는 범주는 null(지어내지 않는다). */
function 범주문구(범주) {
  return 범주표.find((c) => c.범주 === 범주) ?? null;
}

module.exports = {
  검수판, 범주표, 범주이름들, 지문, 범주초안, 칸사유, 검수판정, 확정얹기, 반려얹기, 범주문구,
};
