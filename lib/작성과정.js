/**
 * 작성과정 — 쓰기 3종(G1·G2·G4)이 낼 `payload.compose_meta` 의 **조립기**. 순수 함수만.
 *
 * ⚠ 이름은 `de44763a` 가 보드에 먼저 선언한 것을 따랐다(`lib/{작성과정,멘탈게이지,게임스냅샷}.js`).
 *   같은 것을 두 이름으로 부르면 계약이 계약을 못 한다 — 남은 두 벌은 그 트랙 몫이다.
 *
 * ■ 무엇을 재나 (`발주_게임모듈.md` G1 §153 · §6-6 ⑨)
 *   학생이 «무엇을 썼나»는 `body_original` 이 든다. 이 파일이 드는 것은 «어떻게 썼나»다 —
 *   시작하기까지 얼마나 미뤘나 · 얼마나 오래 붙들었나 · 몇 번 지웠다 다시 썼나 · 한 번에
 *   덩어리로 들어온 것이 있나. 게이트 ②(성향 파악) 자동층의 본체이고, **막힘 지점**과
 *   **완벽주의로 못 내는 학생**을 가리는 유일한 재료다.
 *
 * ■ 🔴 소급이 없다 — 그래서 첫 제출 전에 선다
 *   쓰기에는 재계산의 원천이 없다(키스트로크 로그를 남기지 않는다 — 용량·프라이버시).
 *   집계값이 곧 원본이라 나중에 붙이면 **그 사이 제출은 영원히 과정이 없다.**
 *
 * ■ 🔴 네 칸은 **한 벌로만** 나간다 (§6-6 ⑨ 처분 규칙 1)
 *   `compose_meta` 는 c9 ①로 계약에 올라갔다가 되돌려진 자리다. 되돌림 사유는 「한쪽만 보내면
 *   «측정 안 함»과 «0회»가 행에서 안 갈린다」였는데, **계약은 그것을 못 막는다** — 검증기·서버에
 *   실제로 태우니 반쪽 객체가 그대로 통과했다(⑨ 실측 3번). 막는 자리는 여기 하나뿐이다.
 *   그래서 `계측payload` 는 한 칸이라도 못 재면 **객체를 통째로 안 만든다**(`null`).
 *   🚫 못 잰 칸을 `0`·`null` 로 채워 내보내지 않는다 — 「안 쟀다」가 「0회였다」로 적힌다
 *   (G1 §190 이 `task_snapshot` 에서 금지한 형태를 payload 에 재현하는 것이다).
 *
 * ■ 🔴 못 재는 모듈은 이 파일을 **부르지 않는다** (처분 규칙 2)
 *   G3(음성)에는 타건이 없다 — 키를 아예 만들지 않는다. ⑤가 「한쪽만 보낸다」고 걱정한 상황은
 *   쓰기 3종이 **같은 조립기**를 쓰면 성립하지 않는다(G1·G2·G4 는 넷을 다 잰다).
 *
 * ■ 🔴 자리는 `payload` 안이다 (처분 규칙 3)
 *   봉투 최상위에 실어도 검증기는 통과시킨다(⑨ 실측 5번 — ⑥ 이 `task_format` 에서 낸 것과 같은
 *   구멍). 검증기가 못 거는 자리라 **회귀가 자리를 못박는다.**
 *
 * ■ 🔴 시계는 **경과 시계**다(`performance.now` 류) — 벽시계 금지
 *   `lib/선택로그.걸린시간` 과 같은 축이다. 벽시계 두 시점의 차는 시각 동기화·타임존 변경에서
 *   음수나 몇 시간짜리를 만들고, 그 행은 오류가 아니라 «아주 오래 붙든 학생»으로 읽힌다.
 *   음수가 나오면 접지 않고 **한 벌 전체를 버린다**(위 규칙 1).
 *
 * ■ 천장 — `input_burst_max` 는 라벨이 아니다 (§7 · §6-6 ⑤)
 *   RN `TextInput` 에 표준 paste 이벤트가 없어 「한 번에 들어온 덩어리 크기」로 재는
 *   **휴리스틱**이다. 자동완성·키보드 예측·받아쓰기도 덩어리로 들어온다. 그래서 불리언
 *   (`paste_used`)이 아니라 **정수**로 싣는다 — 임계값을 코드에 숨기면 나중에 임계를 바꿔도
 *   과거 데이터가 새 기준으로 재판정되지 않는다. 정수면 판정이 조회 시점에 있어 과거분이 산다.
 *   🚫 이 값으로 「번역기를 썼다」를 단정하지 않는다 — **검수 우선순위 신호 전용**이다.
 *
 * ⚠ 이 파일은 **아직 생산자가 아니다.** 사건을 실제로 내는 것은 G1 메일 쓰기 화면이고 그 화면은
 *   아직 없다(`lib/선택로그.js` 가 밟은 순서와 같다 — 조립기·회귀가 1단계, 화면·소비자가 2단계).
 *   화면이 서는 커밋에서 **엔진 도달을 같은 커밋에** 낸다.
 */

/** 이 객체가 드는 네 칸 — **하나라도 못 재면 객체가 없다.** 회귀가 이 목록으로 한 벌을 검사한다. */
const 칸들 = Object.freeze(['first_keystroke_ms', 'total_compose_ms', 'revision_count', 'input_burst_max']);

/**
 * 코드포인트 길이. `String.length` 는 이모지를 둘로 세서 「한 글자 지웠는데 2 줄었다」가 된다.
 * ⚠ 한글 조합 중에는 길이가 안 변하는 전이가 있다(「아」→「안」은 1→1) — 그 구간은 **일부러**
 *   안 센다. 조합 내 수정은 「지웠다 다시 썼다」가 아니라 한 글자를 완성해 가는 과정이다.
 */
function 글자수(s) {
  return typeof s === 'string' ? Array.from(s).length : 0;
}

/**
 * 계측을 시작한다 — 화면이 **입력 가능해진 순간**에 부른다(카드를 읽는 시간은 안 센다).
 * @param {number} 연시각 경과 시계 값
 */
function 계측시작(연시각) {
  return Object.freeze({
    연시각: Number.isFinite(연시각) ? 연시각 : null,
    첫타건: null,
    길이: 0,
    줄던중: false,
    되돌림: 0,
    최대덩어리: 0,
  });
}

/**
 * 입력 한 번을 먹인다 — RN `onChangeText` 마다 부른다(순수: 새 상태를 돌려준다).
 *
 * 🔑 **리렌더를 걸지 않는 자리다.** 반환값은 `ref` 에 담는다 — 값을 매 글자 state 로 되돌려
 *   넣으면 controlled TextInput 이 되어 한글 조합이 깨진다(「안녕」이 「ㅇㅏㄴㄴㅕㅇ」으로 흩어진다 ·
 *   G1 §124 ⚙). 게이지는 이 상태가 아니라 5칸 판정 결과에만 반응시킨다.
 *
 * @param {object} 상태 `계측시작`·`타건` 의 반환값
 * @param {string} 글   그 순간의 **전체** 텍스트(RN 이 주는 모양)
 * @param {number} 지금 경과 시계 값
 */
function 타건(상태, 글, 지금) {
  if (!상태) return 상태;
  const 새길이 = 글자수(글);
  const 늘어남 = 새길이 - 상태.길이;
  const 줄었다 = 늘어남 < 0;
  /* 길이가 **실제로 변했을 때만** 첫 타건으로 친다 — 화면이 초기화하며 빈 문자열로 한 번
   * 부르는 일이 흔하고, 그것을 첫 타건으로 잡으면 「바로 시작했다」가 공짜로 만들어진다. */
  const 변했다 = 늘어남 !== 0;
  return Object.freeze({
    연시각: 상태.연시각,
    첫타건: 상태.첫타건 === null && 변했다 && Number.isFinite(지금) ? 지금 : 상태.첫타건,
    길이: 새길이,
    줄던중: 줄었다,
    /* 🔑 **횟수가 아니라 «구간» 수**다 — 한 번 지우기 시작해 열 글자를 지운 것은 되돌림 1이다.
     *   글자마다 세면 「길게 지운 사람」과 「자주 고친 사람」이 같은 수가 되고, 성향 축에서
     *   그 둘은 다른 신호다(막힘 vs 다듬기). 줄다가 다시 늘면 그 구간이 닫힌다. */
    되돌림: 줄었다 && !상태.줄던중 ? 상태.되돌림 + 1 : 상태.되돌림,
    최대덩어리: 늘어남 > 상태.최대덩어리 ? 늘어남 : 상태.최대덩어리,
  });
}

/**
 * `payload.compose_meta` 를 조립한다.
 *
 * @param {object} 상태     `타건` 이 굴린 마지막 상태
 * @param {number} 제출시각 보내기를 누른 순간(경과 시계)
 * @returns {{first_keystroke_ms:number,total_compose_ms:number,revision_count:number,input_burst_max:number}|null}
 *          한 칸이라도 못 재면 `null` — 그러면 화면은 이 키를 **아예 안 싣는다**.
 */
function 계측payload(상태, 제출시각) {
  if (!상태) return null;
  const { 연시각, 첫타건 } = 상태;
  /* 한 벌 판정 — 셋 중 하나라도 없으면 넷이 다 없다. 한 칸만 비워 보내는 것이
   * 이 파일이 막으려는 바로 그 형태다(§6-6 ⑨ 규칙 1). */
  if (!Number.isFinite(연시각) || !Number.isFinite(첫타건) || !Number.isFinite(제출시각)) return null;

  const 미룬시간 = 첫타건 - 연시각;
  const 붙든시간 = 제출시각 - 첫타건;
  /* 🔴 음수는 「빨랐다」가 아니라 「시계가 뒤로 갔다」다. 0 으로 접으면 그 행이 «즉답»으로
   *   읽혀 회피 지연 축이 조용히 거짓이 된다(`선택로그.걸린시간` 과 같은 판정). */
  if (미룬시간 < 0 || 붙든시간 < 0) return null;

  return {
    /* 과제를 본 순간부터 **시작하기까지** = 회피 지연. ⚠ `latency_ms` 로 흡수하지 않는다 —
     * 그 이름은 선택로그 축(고르기까지)이고, 합치면 한 칸이 세 뜻을 갖는다(§6-6 ⑤ ②). */
    first_keystroke_ms: Math.round(미룬시간),
    /* 첫 타건부터 제출까지 — **위 값과 겹치지 않는다.** 둘을 더하면 화면에 머문 전체가 된다.
     * 겹치게 정의하면 「오래 붙들었다」가 「오래 미뤘다」를 포함해 두 신호가 한 수로 뭉갠다. */
    total_compose_ms: Math.round(붙든시간),
    revision_count: 상태.되돌림,
    input_burst_max: 상태.최대덩어리,
  };
}

module.exports = { 칸들, 계측시작, 타건, 계측payload, 글자수 };
