'use strict';
/* 저작 신뢰 — 「이 산출이 **그 학생의 산출 능력**을 말해 주는가」 (철학 Ⅱ-9 의 엔진 쪽 문).
 *
 * ■ 무엇을 막으려고 이 파일이 있나
 *   철학 Ⅱ-9 가 스스로 지목한 **단 하나의 내부 붕괴 경로**다:
 *   「들어온 답이 AI 것이면 엔진 눈에 그 학생은 완벽해서, 더 어려운 과제를 주고, 학생은 더 못
 *    따라가고, 더 AI를 쓴다 — 「선생님의 뇌」가 남의 뇌로 채워진다.」
 *   Core 의 출처 등급(`lib/사건출처.js`)은 «어떻게 알게 됐나»를 가르지 **«이 사람이 정말 썼나»를
 *   안 가른다** — `submission.created` 는 무엇이 들어오든 `observed` 다. 그 빈칸이 이 파일이다.
 *
 * ■ 🚫 이 파일이 **하지 않는 것** — 이게 규격의 절반이다
 *   ⓐ **학생을 판정하지 않는다.** 「AI 를 썼다」·「베꼈다」를 말하지 않는다. 신호의 원인은
 *      붙여넣기일 수도, 받아쓰기·자동완성·키보드 예측일 수도 있다(`lib/작성과정.js` 머리말이
 *      이미 못박은 자리 — 그래서 그 파일은 불리언이 아니라 **정수**를 싣는다).
 *   ⓑ **차단·처벌하지 않는다.** 철학의 처방은 금지가 아니라 판단이다(Ⅱ-9 — 「학생이 스스로
 *      가리게 만든다」). 제출은 그대로 서고, 검수도 그대로 확정된다.
 *   ⓒ **학생 상태로 저장하지 않는다.** 코어엔진 §원칙1 「낙인 금지」 — 값은 **그 행**에 붙지
 *      사람에 안 붙는다. 이 파일이 순수 함수인 이유이기도 하다: 저장할 상태가 없다.
 *   ⇒ 그래서 이름이 「부정 탐지」가 아니라 **「저작 신뢰」**다. 재는 것은 사람이 아니라 **재료**다.
 *
 * ■ 🔴 판정은 **조회 시점**에 있다 — 값에 임계를 굽지 않는다
 *   `compose_meta` 네 칸은 정수로 행에 남는다(`lib/작성과정.js` §7). 그래서 임계값을 나중에
 *   고쳐도 **과거 행이 새 기준으로 다시 판정된다**. 반대로 「의심」 불리언을 행에 구우면 그날의
 *   임계가 2년 뒤에도 사실 행세를 한다. 이 파일은 그 규율을 잇는다 — 읽는 자리에서 잰다.
 *
 * ■ 🔴 임계 둘은 **아직 실측이 없다**(2026-08-26 · 실학생 0명)
 *   아래 두 상수는 첫 코호트 전까지 «추정»이고, 그 사실을 숨기지 않는다. 그런데도 지금 세우는
 *   까닭은 **비대칭** 하나다: 승격 보류는 되돌릴 수 있고(그 행은 언제든 다시 판정한다),
 *   훈련 데이터 오염은 **못 되돌린다**(모델에 들어간 문장은 못 뺀다). 되돌릴 수 없는 쪽에서
 *   보수적으로 선다. ⚠ 첫 실데이터가 쌓이는 날 이 둘을 **다시 잰다**(설계 §5).
 *
 * 정본 = `docs/저작신뢰_설계_v1.md`
 */

const { 칸들: 작성칸들 } = require('./작성과정.js');

/**
 * 한 덩어리가 이만큼은 돼야 «사람 타건으로 설명 안 되는 크기»로 본다(코드포인트).
 * 🔑 한 어절(3~5자)·자동완성 한 낱말은 이 아래다. 한 문장(8자 이상 — `과제검문.문장길이.하한`)
 *   을 통째로 넘는 자리부터 잰다는 뜻이고, 넉넉히 잡았다(거짓 양성이 검수 손을 늘리므로).
 */
const 덩어리하한 = 20;

/**
 * 그 덩어리가 산출의 이만큼을 차지하면 «지배한다»로 본다.
 * 🔑 0.6 = 「반 넘게 한 번에 들어왔다」에 여유 한 자락. 긴 글에 한 문장을 받아쓰기로 넣은 학생은
 *   비율이 낮아 안 걸리고, 통째로 한 번에 들어온 글만 걸린다.
 */
const 지배비율 = 0.6;

/** 등급 셋 — **원인을 말하지 않는다.** 사실만 말한다(위 🚫 ⓐ). */
const 등급들 = Object.freeze({
  못잼: '못잼',       // 잴 재료가 없다 — 음성 제출·옛 행. 「깨끗하다」가 **아니다**.
  손으로: '손으로',   // 잰 것이 있고, 타건 흔적이 산출을 설명한다
  덩어리: '덩어리',   // 잰 것이 있고, 한 덩어리가 산출을 지배한다
});

const 온전한가 = (m) =>
  !!m && typeof m === 'object' && !Array.isArray(m) && 작성칸들.every((k) => Number.isInteger(m[k]));

/**
 * 저작 신뢰 판정 — 순수 함수.
 *
 * 🔴 `못잼` 을 «통과»로 접지 않는다. 음성 제출은 잴 것이 없어서 못 잰 것이고, 그건
 *   「손으로 썼다」와 다른 사실이다. 접으면 「안 쟀다」가 「깨끗하다」로 조용히 뜻을 갈아탄다
 *   (`lib/작성과정.js` 가 «0회»와 «측정 안 함»을 가른 것과 같은 축).
 *
 * @param {{compose_meta?: unknown, 본문길이?: number}} 재료
 * @returns {{등급: string, 잰것: object|null, 덩어리비율: number|null}}
 */
function 저작판정(재료) {
  const m = 재료 && 재료.compose_meta;
  const 길이 = Number(재료 && 재료.본문길이);
  if (!온전한가(m)) return { 등급: 등급들.못잼, 잰것: null, 덩어리비율: null };
  /* 🔑 길이를 못 읽으면 비율을 지어내지 않는다 — 못 잰 것은 `못잼` 이지 `손으로` 가 아니다.
   *   (0 으로 접으면 나눗셈이 Infinity 가 되어 **모든 행이 덩어리**가 된다.) */
  if (!Number.isFinite(길이) || 길이 <= 0) return { 등급: 등급들.못잼, 잰것: m, 덩어리비율: null };

  const 덩어리 = m.input_burst_max;
  /* 🔑 비율은 1 을 넘을 수 있다 — 썼다 지웠다 하면 최대 덩어리가 최종 길이보다 클 수 있다.
   *   자르지 않는다: 자르면 「많이 지운 학생」과 「통째로 넣은 학생」이 같은 1.0 이 된다. */
  const 비율 = 덩어리 / 길이;
  const 등급 = 덩어리 >= 덩어리하한 && 비율 >= 지배비율 ? 등급들.덩어리 : 등급들.손으로;
  return { 등급, 잰것: m, 덩어리비율: Math.round(비율 * 100) / 100 };
}

/**
 * **훈련 승격**(Core §6 경로 B · `corrections.promotion_intent`)을 보류할 자리인가.
 *
 * 🔴 보류하는 것은 **훈련 승격 하나**다 — 교정 확정도, 학생 화면도, 개인화도 그대로 돈다.
 *   여기서 더 넓히면(예: 성향 축에서 제외) 그 순간 「낙인」이 되고, 그건 Ⅱ-9 가 「막는 것은
 *   우리 방식도 아니다」로 이미 닫은 문이다.
 * 🔑 `못잼` 은 보류하지 않는다 — 음성 제출이 전부 여기 걸려 승격 통로가 통째로 죽는다.
 *   막는 자리는 **잰 것이 있고 그것이 덩어리인** 행 하나다(구멍이 실제로 있는 그 자리).
 */
const 승격보류인가 = (판정) => !!판정 && 판정.등급 === 등급들.덩어리;

/** 검수자에게 보일 한 줄 — 원인을 말하지 않고 **사실과 다음 행동**만 말한다. */
const 보류문구 = '이 항목은 훈련 승격만 보류했어요 — 글이 한 번에 들어온 자국이 있어요. 검수 확정은 그대로예요.';

module.exports = { 저작판정, 승격보류인가, 등급들, 덩어리하한, 지배비율, 보류문구 };
