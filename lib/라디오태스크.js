'use strict';
/* 라디오 승격이 만드는 task_type 의 **정본 목록** — 통로 축(c11)의 기계 실체.
 *
 * ■ 왜 따로 사나 (반박 c757278 치명 ①)
 *   c11 이 라디오 task_type 셋을 앱 어휘와 **일부러** 갈랐는데(「앱 퀴즈·앱 출석과 섞이면
 *   영영 못 가른다」), 그 축을 **보는 소비자가 한 곳도 없었다** — 리듬·끈기축이 라디오
 *   `submission.created` 를 앱 제출로 세어, 앱을 한 번도 안 연 학생이 「숙제를 12시간 여유
 *   두고 냈다」가 됐다(재현 실측). 개입 행 스탬프라 소급 불가.
 *
 * ■ 소비자
 *   · `lib/라디오승격.js` — 회귀가 「계획 행의 task_type ⊂ 이 목록」을 기계로 묶는다
 *     (새 라디오 task_type 을 여기 없이 내면 그 자리에서 빨개진다 — 새는 방향 차단).
 *   · `lib/학습자상태.js` — 리듬·끈기축 입력에서 이 목록을 **뺀다**(앱 통로만 센다).
 *   ⚠ 두 파일이 각자 목록을 적으면 라디오 명령을 늘린 날 조용히 갈라진다 — 그래서 한 파일이다.
 *   Edge 동봉: deliver·radio-promote 둘 다 `동봉.json` 에 `라디오태스크.mjs` 로 실린다. */
const 라디오태스크종 = Object.freeze(['라디오퀴즈', '목표선언', '자습체크인']);

/* 라디오 통로의 **두 번째 축** — 판(`task_schema_ver`) 접두 (발전 트랙 ④ 낭독 · 2026-08-14).
 *
 * ■ 왜 task_type 하나로 안 끝나나
 *   ⓖ 낭독은 라디오가 낸 과제인데 **학생이 앱에서 녹음한다** — 그래서 설계 §2-2 가 앱 어휘
 *   (`task_type='발화녹음'`)를 그대로 쓰기로 했다(계약 개정 0). 위 세 종과 모양이 다르다:
 *   저것들은 채팅에서 나서 승격기가 적는 행이고, 이건 앱에서 나서 앱이 보내는 행이다.
 *   그래서 `task_type` 만 보는 필터는 낭독을 **못 잡는다** — 그런데 리듬축에는 잡혀야 한다
 *   (배정과 짝지을 수 없는 과제인 것은 위 셋과 똑같기 때문이다).
 *
 * ■ 🔴 안 가르면 새는 방향은 「숙제를 냈다」다
 *   리듬축은 배정 구간 안의 **첫 제출**을 그 배정의 것으로 읽는다(`lib/학습자상태.리듬축`).
 *   낭독 한 번이 그 자리에 들어가면 숙제를 안 낸 날이 낸 날로 뒤집히고, 증상은 없다 —
 *   반박 c757278 치명 ① 이 잡은 역오염과 같은 모양이다. ⓖ 는 그 반박(08-12)보다 먼저 쓰인
 *   설계라 이 구멍을 아직 안 봤다.
 *
 * ■ 왜 `task_ref` 접두가 아니라 판인가
 *   `task_ref` 접두로 출처를 가르는 것은 설계 §10 기각 4 다(같은 문항이 앱·라디오로 나가면
 *   문항 정체성이 갈라진다). 판은 「이 과제를 **어느 통로가** 어느 모양으로 만들었나」라
 *   출처를 적기에 맞는 칸이고, 승격기가 자막 카드에 이미 `radio-card.v1` 을 쓴다.
 *
 * ⚠ 이 판별은 **행이 그 칸을 들고 있을 때만** 작동한다 — 질의가 `task_schema_ver` 를 안 실으면
 *   조용히 「앱 행」으로 읽힌다(새는 방향은 통과다). 그래서 원신호를 짓는 질의 둘
 *   (`functions/deliver`·`functions/teach`)이 이 칸을 함께 싣고, 회귀가 그것을 묶는다. */
const 라디오판접두 = 'radio-';

/**
 * 이 행이 **라디오 통로**에서 온 것인가 — 두 축(통로 어휘·판)을 한 자리에서 본다.
 *
 * 🔑 판정이 한 파일인 이유는 위 머리말 그대로다 — 소비자가 각자 축을 적으면 라디오 통로를
 *   하나 늘린 날 한쪽만 따라오고, 그 갈라짐은 「값이 조금 높다」로만 보인다.
 * 🔑 `task_type`·`task_schema_ver` 가 **없는 옛 행은 앱 행이다** — 라디오 행은 처음부터
 *   둘 중 하나를 들고 나왔으므로, 빈 칸을 라디오로 읽으면 옛 앱 제출이 통째로 사라진다.
 */
function 라디오통로인가(행) {
  if (!행 || typeof 행 !== 'object') return false;
  if (라디오태스크종.includes(행.task_type)) return true;
  return typeof 행.task_schema_ver === 'string' && 행.task_schema_ver.startsWith(라디오판접두);
}

module.exports = { 라디오태스크종, 라디오판접두, 라디오통로인가 };
