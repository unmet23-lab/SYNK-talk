/* 청취 계측 — 검수자가 **오디오의 어디를** 실제로 들었는지 재는 순수 계산.
 *
 * ■ 왜 화면이 아니라 여기 사나
 *   이 값(`review_listened_ms`)은 승인 게이트 ①의 입력이다(발주 §3 · 검수_내부계약 §5-1).
 *   화면 안에 두면 회귀가 못 닿고, 못 닿는 채로 새면 **새는 방향은 「통과」**다 —
 *   0초 승인이 3초로 적히는 것을 아무도 못 본다. `lib/검수확정.js` 가 서버 쪽 문턱을
 *   순수 모듈로 든 것과 같은 축이고, 이 파일은 그 문턱에 **넣을 값**을 든다.
 *
 * ■ 벽시계가 아니라 **오디오 위치의 합집합**이다
 *   같은 3초를 세 번 되들으면 벽시계는 9초라 문턱을 통과하지만 들은 구간은 3초다.
 *   문턱의 뜻이 「저신뢰 구간 길이의 합」인 이상(그건 오디오 위의 길이다) 재는 쪽도
 *   오디오 위의 길이여야 한다 — 아니면 「같은 자리 반복」이 게이트를 여는 값싼 우회가 된다.
 *   🔑 되듣기를 **막지는 않는다.** 합집합이라 겹친 만큼만 안 세일 뿐이다.
 *
 * ■ 이어 붙일지 끊을지는 **위치 델타와 시각 델타를 견줘** 정한다
 *   표본은 재생기 상태 갱신마다 온다(간격이 판마다 다르다). 위치만 보면 갱신 간격이
 *   허용치보다 큰 기기에서 정상 재생이 통째로 「점프」가 되어 **들은 것이 0으로 접힌다**.
 *   그래서 「오디오가 흐른 만큼 시간도 흘렀나」를 본다 — 1배속 재생이면 둘이 같고,
 *   구간 점프(seek)면 위치만 뛰며, 앱이 뒤로 물러나 있었으면 시각만 뛴다. 셋이 갈린다.
 *   ⚠ 배속 재생을 넣는 날 이 판정이 먼저 깨진다(2배속이면 위치가 시각의 두 배다).
 *     그때 고칠 자리는 여기 한 곳이고, `허용오차ms` 가 아니라 **배속을 인자로 받는** 쪽이다.
 */
'use strict';

/* 위치 델타와 시각 델타가 이만큼까지 어긋나는 것은 같은 재생으로 본다.
 * 표본 간격 흔들림·디코더 지터가 이 안에 든다. 크게 잡으면 짧은 점프가 「들은 것」이 되고,
 * 작게 잡으면 정상 재생이 잘게 끊긴다 — 끊겨도 **합집합이라 총량은 안 줄어든다**(끊김은
 * 사이에 구멍이 생길 때만 손해다). 그래서 애매하면 작은 쪽으로 둔다. */
const 허용오차ms = 500;

/** 빈 계측. 항목(제출물)마다 하나씩 — 항목을 넘기면 새로 만든다. */
function 새계측() {
  return { 구간: [], 진행: null, 마지막: null };
}

const 수인가 = (v) => Number.isFinite(Number(v));

/**
 * 표본 하나를 반영한 **새 계측**을 낸다(원본을 안 고친다 — React 상태로 그대로 쓴다).
 *
 * @param {object} 계측 `새계측()` 또는 직전 반환값
 * @param {{재생중: boolean, 위치ms: number, 시각ms: number}} 표본
 *   `위치ms` = 오디오 안의 현재 위치 · `시각ms` = 그 표본을 뜬 벽시계
 * @returns {object} 새 계측
 */
function 재기(계측, 표본) {
  const c = 계측 && typeof 계측 === 'object' ? 계측 : 새계측();
  if (!표본 || typeof 표본 !== 'object') return c;
  if (!수인가(표본.위치ms) || !수인가(표본.시각ms)) return c;

  const 위치 = Number(표본.위치ms);
  const 시각 = Number(표본.시각ms);

  /* 멈췄으면 진행 중인 구간을 닫는다. 🔴 「마지막」도 지운다 — 안 지우면 멈춘 동안 흐른
     시각이 다음 재생의 시각 델타에 얹혀 정상 재생이 점프로 판정된다. */
  if (!표본.재생중) {
    return { 구간: 닫기(c), 진행: null, 마지막: null };
  }

  if (!c.진행 || !c.마지막) {
    return { 구간: c.구간.slice(), 진행: { 시작: 위치, 끝: 위치 }, 마지막: { 위치, 시각 } };
  }

  const 위치델타 = 위치 - c.마지막.위치;
  const 시각델타 = 시각 - c.마지막.시각;
  /* 이어 붙이는 조건 둘 — ①오디오가 앞으로 갔다 ②그 만큼 시각도 흘렀다.
     ②가 없으면 seek 이 「들은 것」이 되고, ①이 없으면 되감기가 구간을 뒤로 늘린다. */
  const 이어짐 = 위치델타 >= 0 && Math.abs(위치델타 - 시각델타) <= 허용오차ms;

  if (이어짐) {
    return {
      구간: c.구간.slice(),
      진행: { 시작: c.진행.시작, 끝: 위치 },
      마지막: { 위치, 시각 },
    };
  }
  return { 구간: 닫기(c), 진행: { 시작: 위치, 끝: 위치 }, 마지막: { 위치, 시각 } };
}

/** 진행 중인 구간을 목록에 넣은 사본. 길이 0 구간은 버린다(합집합에 기여가 없다). */
function 닫기(계측) {
  const 목록 = 계측.구간.slice();
  if (계측.진행 && 계측.진행.끝 > 계측.진행.시작) 목록.push(계측.진행);
  return 목록;
}

/**
 * 들은 **총 길이(ms)** — 구간들의 합집합. 겹친 만큼은 한 번만 센다.
 * @returns {number} 정수 ms
 */
function 들은ms(계측) {
  const c = 계측 && typeof 계측 === 'object' ? 계측 : 새계측();
  const 목록 = 닫기(c).slice().sort((a, b) => a.시작 - b.시작);
  let 합 = 0;
  let 열린시작 = null;
  let 열린끝 = null;
  for (const 구간 of 목록) {
    if (열린시작 === null) {
      열린시작 = 구간.시작;
      열린끝 = 구간.끝;
      continue;
    }
    if (구간.시작 <= 열린끝) {
      /* 겹치거나 맞닿는다 — 늘리기만 한다. `Math.max` 가 없으면 **품은 구간**(앞 구간이
         뒤 구간을 통째로 포함)이 끝을 뒤로 당겨 총량이 줄어든다. */
      열린끝 = Math.max(열린끝, 구간.끝);
      continue;
    }
    합 += 열린끝 - 열린시작;
    열린시작 = 구간.시작;
    열린끝 = 구간.끝;
  }
  if (열린시작 !== null) 합 += 열린끝 - 열린시작;
  return Math.round(합);
}

module.exports = { 새계측, 재기, 들은ms, 허용오차ms };
