const 분 = 60 * 1000;

/** ISO 문자열·Date → 밀리초. 못 읽으면 `null`(0 으로 접으면 1970년이 근거가 된다). */
function 때(v) {
  if (v == null) return null;
  const ms = v instanceof Date ? v.getTime() : Date.parse(String(v));
  return Number.isFinite(ms) ? ms : null;
}

/** 소수 자리 고정. 🔑 `0.6666666666666666` 을 그대로 적으면 없는 정밀도를 주장하게 된다. */
const 자리 = (n, 몇 = 2) => (n == null ? null : Math.round(n * 10 ** 몇) / 10 ** 몇);

/** 비율. **분모 0 은 `null`** — 0/0 을 0 으로 접으면 「한 적이 없다」가 「못 한다」가 된다. */
const 비율 = (분자, 분모) => (분모 > 0 ? 자리(분자 / 분모) : null);

/** 중앙값. 평균이 아닌 이유 = 하루 몰아치기 한 건이 평균을 통째로 끌고 간다. */
function 중앙값(arr) {
  if (!arr.length) return null;
  const s = [...arr].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}

/**
 * 그 시점의 학습자 상태.
 *
 * @param {Array<object>} 사건들 원신호 행. 한 건 = `{event_id, event_type, occurred_at,
 *   retry_of_event_id?, correction_id?, due_at?, payload?}`. 순서는 안 가린다(여기서 정렬한다).
 * @param {{as_of: string|Date, ingested_as_of?: string|Date, 창?: number, 시간대?: string}} 옵션
 *   `as_of` **필수** — 이 시각 «이후» 사건은 전부 버린다(미래정보 누출 차단).
 *   `ingested_as_of` = 늦적재 경계(v11 · §11-4 ㉤) — 주면 `ingested_at` 도 같이 자른다.
 *   이 모드에서 `ingested_at` 없는 사건은 버린다(조회층이 칸을 안 실은 배선 누락을 조용히
 *   통과시키지 않는다) · 미전달 = v10 과 행동 동일.
 *   `시간대` = IANA 이름. **집중띠 축에서만** 쓴다(나머지 축은 시간대를 안 쓴다 — ① 머리말).
 *   🔴 안 주면 그 축만 `null` 이다 — UTC 로 접지 않는다. 접으면 몽골 저녁(=UTC 오전)이 「오전」
 *   띠로 들어가 축이 **조용히 거짓**이 된다. 이름을 여기 기본값으로 적는 것도 금지다(사본이
 *   되는 순간 날짜 경계가 두 곳에 산다 · `functions/deliver/index.ts` 머리) — 부르는 쪽이
 *   `lib/오늘과제.js` 의 `시간대` 를 그대로 넘긴다.
 * @returns {{estimator_version: string, estimator_confidence: number,
 *   evidence_refs: object, 축: object}}
 */
function 학습자상태(사건들, 옵션) {
  const 기준 = 때(옵션 && 옵션.as_of);
  if (기준 == null) {
    /* 🔴 던진다 — 기본값으로 「지금」을 쓰면 과거 개입을 평가하는 자리에서 미래가 섞이고,
     *   그 오염은 값만 보고는 알 수 없다(설계 §3 이 v1 에서 잡은 P0). */
    throw new Error('학습자상태: as_of 가 필요하다 — 시점 절단 없이 계산하면 미래정보가 섞인다');
  }
  const 창 = Number.isFinite(옵션 && 옵션.창) ? 옵션.창 : 창일수;
  const 시작 = 기준 - 창 * 24 * 60 * 분;
  /* 늦적재 경계(설계 §11-4 ㉤·C4 — v11) — `occurred_at <= as_of` 만으로는 스냅샷이 안 보장된다:
   * as_of «뒤»에 적재됐지만 발생 시각이 이른 사건은 읽는 순간에 따라 포함돼, 같은 as_of·같은
   * 판에서도 입력이 달라진다. 둘 다 걸어야 「같은 as_of = 같은 표본」이 성립한다.
   * · 미전달 = 현행과 완전 동일(기존 호출자 무영향 · v5.2) — 생성·스탬프 경로만 넘긴다.
   * · 🔴 이 모드에서 `ingested_at` 이 «없는» 사건은 **버린다** — 「모르면 포함」은 늦적재가
   *   새는 방향 그 자체이고, 조회층이 칸을 안 실어 준 배선 누락이 조용히 통과하는 길이다
   *   (C4 실측: 하류 필터는 검사할 값이 없어 항상 통과했다). 버리면 상태가 비어 시끄럽다. */
  const 적재기준 = 때(옵션 && 옵션.ingested_as_of);
  const 적재안 = (e) => {
    if (적재기준 == null) return true;
    const t = 때(e && e.ingested_at);
    return t != null && t <= 적재기준;
  };

  /* ① 시점 절단 + 창. 여기 한 곳에서만 자른다 — 축마다 자르면 축끼리 다른 기간을 보게 된다. */
  const 창안 = (Array.isArray(사건들) ? 사건들 : [])
    .map((e) => ({ ...e, _때: 때(e && e.occurred_at) }))
    .filter((e) => e._때 != null && e._때 <= 기준 && e._때 >= 시작 && 적재안(e))
    .sort((a, b) => a._때 - b._때);

  const 골라 = (t) => 창안.filter((e) => e.event_type === t);
  const 근거 = [];
  const 담아 = (행들) => { for (const e of 행들) if (e.event_id) 근거.push(String(e.event_id)); };

  /* 리듬·끈기는 **앱 통로 행만** 센다(v6 · 반박 ①) — 라디오 승격 제출(`목표선언`·`자습체크인`)
   * 은 배정과 짝지을 수 없는 다른 표면이다. 라디오 행 자체는 자기 축(선호·정서·자기인식)으로
   * 이미 닿고 있으므로 잃는 신호가 없다. task_type 이 없는 옛 행은 앱 행이라 그대로 남는다.
   *
   * 🔴 v10(2026-08-14 · 발전 트랙 ④ 낭독) — 판별을 `라디오통로인가` 로 옮기고 **이탈에도 건다.**
   *   ㉠ ⓖ 낭독은 앱 어휘(`발화녹음`)를 쓰는 라디오 과제라 `task_type` 목록에 안 걸린다.
   *      판(`task_schema_ver='radio-*'`)이 그 축이고, 정본은 `lib/라디오태스크.js` 하나다.
   *   ㉡ **이탈을 안 빼면 완주율이 반대로 기운다** — 제출만 빼고 `session.abandoned` 를 그대로
   *      두면 라디오 낭독을 중간에 그만둔 행은 분모에 남고 완주한 행만 사라져, 완주율이
   *      «조용히 낮아진다». 지금까지 안 드러난 이유는 라디오 승격 행이 이탈을 안 만들었기
   *      때문이고(채팅 명령엔 「그만둠」이 없다), 낭독은 앱에서 녹음하므로 **둘 다 만든다.**
   *      한쪽만 거는 필터는 안 거는 것보다 나쁘다 — 편향에는 증상이 없다. */
  const 앱통로만 = (행들) => 행들.filter((e) => !라디오통로인가(e));
  const 앱제출만 = 앱통로만; // 옛 이름 — 아래 축들이 부르던 그대로(뜻이 넓어졌을 뿐이다)

  const 축 = {
    리듬: 리듬축(골라('task.assigned'), 앱통로만(골라('submission.created')), 담아),
    끈기: 끈기축(앱통로만(골라('submission.created')), 앱통로만(골라('session.abandoned')), 담아),
    피드백수용: 피드백수용축(골라('correction.viewed'), 골라('correction.responded'), 담아),
    관심: 관심축(골라('choice.selected'), 담아),
    작성과정: 작성과정축(골라('submission.created'), 담아),
    /* v12 — 퀴즈 + G2 짚음 제출(확신도 기호식이 있는 두 통로 — Ⅲ⑦). G4 빈칸은 quiz.answered
     * 라 첫 인자에 이미 든다. 다른 제출(발화·변환 등)은 표기 자리가 없어 분모에 안 넣는다.
     * 짚음을 «갈라» 받는 이유 = 그 행은 끈기축이 이미 표본으로 센다(표본n 참조). */
    자기인식: 자기인식축(골라('quiz.answered'),
      골라('submission.created').filter((e) => e.task_type === '숙제제출'), 담아),
    /* v8 — G2 지목. 두 갈래(`짚음`=제출 · `무산출`=퀴즈응답)를 **한 축**으로 센다. 라디오 행은
     * `options_shown` 을 안 실어 표식에서 저절로 빠지지만, 제출 쪽은 `앱제출만` 도 함께 건다 —
     * 표식 하나에만 기대면 라디오가 그 필드를 싣는 날 조용히 섞인다(새는 방향은 언제나 통과). */
    탐지: 탐지축(앱제출만(골라('submission.created')), 골라('quiz.answered'), 담아),
    /* v9 — G4 지목. 세 갈래(빈칸·모름=퀴즈응답 · 변환=제출)를 **한 축**으로 센다. 라디오 행은
     * `submission.task_snapshot` 을 안 실어 표식에서 저절로 빠지지만, 제출 쪽은 `앱제출만` 도
     * 함께 건다 — 표식 하나에만 기대면 라디오가 그 칸을 싣는 날 조용히 섞인다(탐지축과 한 축). */
    강제산출: 강제산출축(앱제출만(골라('submission.created')), 골라('quiz.answered'), 담아),
    선호: 선호축(골라('preference.stated'), 담아),
    정서: 정서축(골라('affect.reported'), 담아),
    /* 끈기축과 **같은 두 사건**을 띠로 갈라 다시 읽는다(그래서 `표본제외`). 앱 통로만 세는 것도
     * 끈기축과 같다 — 라디오 승격 행은 학생이 앉은 시각이 아니라 승격기가 돈 시각이다.
     * 🔴 이탈에도 같이 건다(v10) — 끈기축과 재료가 같아야 「같은 것을 띠로 갈랐다」가 참이다. */
    집중띠: 집중띠축(앱통로만(골라('submission.created')), 앱통로만(골라('session.abandoned')),
      옵션 && 옵션.시간대, 담아),
  };

  /* 🔴 이미 센 사건을 다시 읽는 축은 표본에 안 더한다 — 더하면 같은 제출이 「몇 건 위에
   * 세웠나」에 두 번 세어져 신뢰도가 공짜로 오른다(표본은 사건이지 축-사건 쌍이 아니다).
   * 목록 정본 = 위 `표본제외`(여기 이름을 직접 적으면 축을 늘린 날 갈라진다).
   * v12 — 축이 `표본n` 을 갈라 실으면 그것을 읽는다: 자기인식축의 분모(n)에 G2 짚음 제출이
   * 합류했는데 그 행은 끈기축이 이미 표본으로 센다 — 축 분모와 표본 몫은 다른 질문이다. */
  const 표본 = Object.entries(축).reduce(
    (s, [이름, a]) => s + (표본제외.includes(이름) || !a ? 0 : (a.표본n ?? a.n)), 0);
  const 사건 = [...new Set(근거)];

  return {
    estimator_version: 추정판,
    estimator_confidence: 표본 ? 자리(표본 / (표본 + 완충)) : 0,
    /* 재현에 필요한 전부를 한 칸에 담는다 — ID 만 담으면 「어느 시점 기준이었나」가 빠져
     * 같은 근거로도 다른 값이 나오고, 그러면 재계산 대조가 아무것도 증명하지 못한다. */
    evidence_refs: {
      as_of: new Date(기준).toISOString(),
      /* 늦적재 경계를 «썼다»는 사실도 재현 재료다 — 없으면 같은 as_of 로 두 모드가 한 이름이 된다. */
      ...(적재기준 != null ? { ingested_as_of: new Date(적재기준).toISOString() } : {}),
      창일수: 창,
      사건: 사건.slice(0, 근거상한),
      ...(사건.length > 근거상한 ? { 잘림: 사건.length } : {}),
    },
    축,
  };
}

/* ── ① 리듬 — 제출 시각·간격·**마감 대비 여유**(코어엔진 성향 5축 ①)
 *
 * 🔑 「몇 시에 냈나」가 아니라 «마감까지 몇 분 남기고 냈나»다. 앞엣것은 수업표가 바뀌면
 *   뜻이 변하고 뒤엣것은 안 변한다 — c10 이 `due_at` 을 배정 순간에 박은 이유가 그것이다.
 * 🔴 배정↔제출은 **구간**으로 잇는다: 어떤 배정 뒤·다음 배정 앞에 온 제출이 그 배정의 것이다.
 *   `intervention_id` 로 잇고 싶지만 앱 제출 행이 그 값을 들지 않는다(들었다면 그게 정답이다).
 *   날짜로 잇는 것은 시간대 경계에서 갈리고, 이 구간 규칙은 시간대를 안 쓴다. */
function 리듬축(배정들, 제출들, 담아) {
  if (!배정들.length) return null;
  const 여유들 = [];
  let 제출된 = 0;
  배정들.forEach((배정, i) => {
    const 다음 = i + 1 < 배정들.length ? 배정들[i + 1]._때 : Infinity;
    const 낸것 = 제출들.find((s) => s._때 >= 배정._때 && s._때 < 다음);
    if (!낸것) return;
    제출된 += 1;
    const 마감 = 때(배정.due_at);
    /* 마감이 없는 배정은 **여유 계산에서만** 빠진다(c10 이전 행). 제출률에는 그대로 센다 —
     * 두 값의 분모가 다른 것이 정상이고, 그래서 각각 자기 n 을 들고 다닌다. */
    if (마감 != null) 여유들.push((마감 - 낸것._때) / 분);
  });
  담아(배정들); 담아(제출들);
  return {
    제출률: 비율(제출된, 배정들.length),
    마감여유분_중앙: 자리(중앙값(여유들), 0),
    /* 🔴 음수 = 마감을 넘겨 냈다. **버리지 않는다** — 늦게라도 낸 것과 안 낸 것은 다른 신호다. */
    지각: 여유들.filter((v) => v < 0).length,
    n: 배정들.length,
    여유n: 여유들.length,
  };
}

/* ── ② 끈기 — 틀린 뒤 재시도하나 넘어가나 · 어려운 것에서 이탈하나(코어엔진 축 ②)
 *
 * 🔑 `session.abandoned` 가 이 축의 유일한 「그만뒀다」 신호고, `retry_of_event_id` 가 유일한
 *   「교정을 받고 다시 냈다」 신호다(L0 §9-2 · 결과 변수). 둘 다 소급 불가라 지금 세는 것이 맞다.
 * ⚠ 완주율의 분모는 «시도»(제출+이탈)다. 배정을 분모로 쓰면 리듬축(안 낸 날)과 같은 것을
 *   두 번 세게 되고, 두 축이 같은 움직임을 보이면 축을 나눈 의미가 없어진다. */
function 끈기축(제출들, 이탈들, 담아) {
  const 시도 = 제출들.length + 이탈들.length;
  if (!시도) return null;
  담아(제출들); 담아(이탈들);
  return {
    완주율: 비율(제출들.length, 시도),
    재시도: 제출들.filter((e) => e.retry_of_event_id).length,
    이탈: 이탈들.length,
    n: 시도,
  };
}

/* ── ⑨ 집중띠 — «언제» 집중이 오르는가 (철학 v1.4 ㉡ 사람 이해 · 2026-08-12 신설)
 *
 * 🔑 **「몇 시에 냈나」를 성향으로 읽지 않는다.** 계약 c10 이 그것을 명시적으로 기각했고(같은
 *   21시 제출이라도 마감이 22시면 벼락치기고 다음날 정오면 여유다) 리듬축이 그래서 마감 대비
 *   여유를 쓴다. 이 축이 재는 것은 **그 띠에 앉았을 때 «끝까지 갔는가»** 다. 수업표가 시각을
 *   정해도 그 시각의 완주율은 그 학생의 것이라, c10 의 기각 사유가 이 축에는 안 걸린다.
 * 🔑 재료는 **이미 세는 두 사건뿐**(제출·이탈 · 끈기축과 동일). 새 열·새 사건·새 필드 0 —
 *   `hesitation_ms`·`duration_ms`·`capture_meta` 는 기각분이라 파생만 한다.
 *
 * 🔴 **문턱을 안 만들었다.** 실학생 0이라 「몇 건이면 믿을 만한가」를 못 잰다(`lib/돌려주기.js`
 *   가 같은 이유로 정수 축만 냈다). 그래서 「으뜸 띠」 같은 **판정을 여기서 안 낸다** — 띠별
 *   원값과 `띠수` 만 내고 판정은 소비자 몫이다. 🚫 문턱을 일단 정하고 나중에 튜닝하기.
 * 🔴 **`띠수 <= 1` 은 성향이 아니라 수업표다.** 학원이 시각을 한 칸으로 몰면 이 축은 아무것도
 *   못 말한다. 그 구분이 값에 안 보이면 소비자가 시간표를 성향으로 읽는다 — 그래서 `띠수` 가
 *   장식이 아니라 **읽기 전에 보는 칸**이다.
 * ⚠ 이 축만 시간대를 쓴다. 없으면 `null`(못 쟀다)이지 UTC 로 접지 않는다 — 위 JSDoc.
 */
function 집중띠축(제출들, 이탈들, 시간대, 담아) {
  /* 🔴 「못 쟀다」와 「띠가 하나다」는 다른 사실이라 둘 다 `null` 로 접지 않는다 —
   *   여기서 나가는 `null` 은 오직 「시간대를 못 받았다 / 재료가 0이다」뿐이다. */
  if (!시간대) return null;
  const 시도 = [
    ...제출들.map((e) => ({ e, 완주: true })),
    ...이탈들.map((e) => ({ e, 완주: false })),
  ];
  if (!시도.length) return null;

  /* 형식기는 **한 번만** 세운다(시도마다 세우면 같은 값에 비용만 는다). `hourCycle:'h23'` 을
   * 박는 이유 = `hour12:false` 는 ICU 판에 따라 자정을 「24」로 내고, 그러면 그 사건이 띠 밖으로
   * 떨어져 조용히 안 세어진다. 오프셋 상수는 안 적는다 — 규칙은 tzdata 가 진다. */
  const 형식 = new Intl.DateTimeFormat('en-GB', { timeZone: 시간대, hour: '2-digit', hourCycle: 'h23' });
  const 통 = new Map();
  let 못읽음 = 0;
  for (const { e, 완주 } of 시도) {
    const 시 = Number(형식.format(new Date(e._때)));
    /* 🔴 **버린 것을 세어 낸다.** 조용히 넘기면 그 행은 `n` 에서 사라지고, 남는 증상은
     *   「완주율이 좀 다르다」뿐이라 아무도 원인을 못 찾는다(`근거상한` 이 잘림을 적는 것과 같은 축).
     * ⚠ 이 자리는 **런타임이 갈리는 곳**이다 — 이 코드는 Deno(Edge)에서 돌고 회귀는 Node 에서
     *   돈다. ICU 판이 다르면 자정을 「24」로 내는 판이 있고, 그 판에서만 이 칸이 0 이 아니게 된다.
     *   즉 이 칸은 회귀가 못 재는 축을 **라이브에서** 재는 눈이다. 🚫 0 이라고 「안전하다」로 읽기. */
    if (!Number.isInteger(시) || 시 < 0 || 시 > 23) { 못읽음 += 1; continue; }
    const 이름 = 띠이름[Math.floor(시 / (24 / 띠이름.length))];
    if (!통.has(이름)) 통.set(이름, { 완주: 0, n: 0 });
    const t = 통.get(이름);
    t.n += 1;
    if (완주) t.완주 += 1;
  }
  if (!통.size) return null;
  담아(제출들); 담아(이탈들);

  const 띠 = {};
  let 센것 = 0;
  /* 띠는 **하루 순서대로** 낸다 — Map 삽입 순서로 내면 사건이 도착한 순서가 값에 새고,
   * 같은 학생의 같은 창을 다시 계산했을 때 키 순서가 달라진다(재현 대조가 무의미해진다). */
  for (const 이름 of 띠이름) {
    if (!통.has(이름)) continue;
    const t = 통.get(이름);
    띠[이름] = { 완주율: 비율(t.완주, t.n), n: t.n };
    센것 += t.n;
  }
  /* 🔑 `n` 은 **띠에 실제로 들어간 수**다(시도 수가 아니다) — 시각을 못 읽은 행이 있으면
   *   두 값이 갈리고, 분모를 시도 수로 쓰면 그 손실이 「완주율이 낮다」로 둔갑한다.
   *   `못읽음` 이 그 차이를 들고 있어 `n + 못읽음 === 시도` 가 항상 성립한다. */
  return { 띠, 띠수: Object.keys(띠).length, n: 센것, 못읽음 };
}

/* ── ④ 피드백 수용 — AI·강사 교정을 채택·무시·수정했나(코어엔진 축 ④ · 「최대 빈 곳」)
 *
 * 🔑 **교정 단위로 잇는다** — `correction.viewed` 도 `correction.responded` 도 `correction_id`
 *   를 필수로 들기 때문이다(c8). 사건 수를 따로 세면 「본 것」과 「답한 것」의 분모가 갈려
 *   응답률이 1 을 넘는 날이 생기고, 그때 값이 틀렸다는 것을 알 방법이 없다.
 * ⚠ 여기서 못 재는 것 — 「**보지도 않은** 교정」. 그러려면 배달된 교정의 목록이 필요한데
 *   `intervention.delivered` 의 payload 에 「이게 교정문이었나」가 없다. 그래서 이 축이 재는
 *   것은 «닿은 교정 안에서의» 반응뿐이고, 그 한계를 값 이름(`응답률`)이 아니라 여기 적어 둔다. */
function 피드백수용축(열람들, 응답들, 담아) {
  /* 🔴 `learner_response` 의 **값목록을 여기 베끼지 않는다.** 정본은 계약 JSON 하나고, 베낀
   *   목록은 계약이 값을 늘린 날 조용히 갈라진다(F272 · `lib/교정엔진.js` 가 태그 목록을
   *   인자로 받는 것과 같은 이유). 계약 밖 값을 막는 것은 **입구**(`lib/이벤트검증.js` 가
   *   c8 로 `payload.learner_response` 를 필수로 건다)의 일이라 여기서 다시 판정하면 같은
   *   판정이 두 곳에 살고 갈라진 쪽이 조용히 통과한다. 여기서는 **온 값 그대로** 센다.
   * ⚠ 아래 `채택` 한 낱말은 목록 복사가 아니라 **한 값의 지목**이다 — 「수용했나」를 재려면
   *   어느 값이 수용인지는 알아야 한다. 계약이 그 이름을 바꾸면 이 축은 0 이 되고, 그때
   *   분포에 낯선 키가 남아 있어 이유가 보인다(값을 통째로 버리지 않는 이유다). */
  const 수용값 = '채택';
  const 교정 = new Map();
  const 넣기 = (행, 칸) => {
    const id = 행.correction_id;
    if (!id) return;                                  // 대상 없는 행은 c8 위반 — 셈에서 뺀다
    const 칸값 = 교정.get(String(id)) || { 열람: false, 응답: null };
    if (칸 === '열람') 칸값.열람 = true;
    else {
      const v = 행.payload && 행.payload.learner_response;
      // 시간순이라 뒤엣것이 최신이다 — 같은 교정에 두 번 답하면 마지막 답이 그 학생의 답이다.
      if (v != null && v !== '') 칸값.응답 = String(v);
    }
    교정.set(String(id), 칸값);
  };
  열람들.forEach((e) => 넣기(e, '열람'));
  응답들.forEach((e) => 넣기(e, '응답'));
  if (!교정.size) return null;

  const 답한것 = [...교정.values()].filter((v) => v.응답);
  const 분포 = {};
  for (const v of 답한것) 분포[v.응답] = (분포[v.응답] || 0) + 1;

  담아(열람들); 담아(응답들);
  return {
    응답률: 비율(답한것.length, 교정.size),
    채택률: 비율(분포[수용값] || 0, 답한것.length),
    분포,
    n: 교정.size,
  };
}

/* ── ⑤ 관심·목표 — 무엇에 끌리나 · 우리가 민 것을 따르나(코어엔진 성향 5축 ⑤)
 *
 * 🔑 **이 축의 본체는 점수가 아니라 분포다.** 「관심이 높다/낮다」는 뜻이 없는 문장이고, 뜻이
 *   있는 것은 «무엇을» 고르느냐다(`고른것`). 그래서 하나의 수로 접지 않는다 — 접는 순간
 *   2년차 개인화 추천이 쓸 재료가 통째로 사라진다.
 *
 * 🔴 **`추천따름률` 이 이 축의 급소다.** 「좋아서 골랐다」와 「우리가 밀어서 골랐다」를 가르는
 *   유일한 값이고, 그것을 가르려고 계약이 `recommended_option` 을 필수로 걸었다. 오늘은 이
 *   값이 늘 `null` 이다 — S1-5 의 고정 선택지 2개는 아무것도 밀지 않아 분모가 0이기 때문이다.
 *   그게 정상이고, 배달층이 추천을 정하기 시작하면 **코드 변경 없이** 값이 찬다.
 *
 * 🔴 **`자리별` 은 판정하지 않고 분포만 낸다.** 표시 순서는 매번 섞이므로(`lib/선택로그.js`)
 *   자리가 한쪽으로 쏠렸다면 그건 「1번을 누르는 손버릇」의 증거지만, n 이 작을 때 그 쏠림은
 *   그냥 우연이다. 문턱을 여기서 정하면 근거 없는 상수가 하나 늘고 검증할 방법이 없다 —
 *   분포를 그대로 남기면 나중에 표본이 쌓인 뒤 누구든 다시 잴 수 있다.
 *
 * 🔴 **`안고름` 이 열렸다 — 그리고 한 수로 세면 그 값은 아무것도 안 가리킨다**(2026-08-10).
 *   그전까지 「아무것도 안 골랐다」(`skipped`·`rejected_all`)는 계약이 `payload.position` 을 값으로
 *   요구해 **도착 자체를 못 했다**. 이제 온다 — 그래서 이 자리에서 갈라야 한다: `skipped` 는
 *   **무관심**(보기를 봤는데 그냥 지나갔다)이고 `rejected_all` 은 **뚜렷한 거절**(둘 다 아니라고
 *   답했다)이다. 성향 축에서 **정반대 신호**인데 한 칸에 담으면 그 둘은 영원히 같은 모양이 된다 —
 *   계약이 택1로 두 이름을 가른 이유가 정확히 그것이다.
 * 🔑 `안고름` 은 **합으로 남긴다**(무관심+거절) — 호출부 호환이고, 「분모를 정직하게」의 자리다.
 * ⚠ 오늘 `거절` 의 생산자는 0이다 — S1-5 화면엔 「둘 다 아니에요」 버튼이 없다(G2 가 낸다 ·
 *   `발주_게임모듈.md` §6-6 ①). 🚫 그 0 을 「거절한 학생이 없다」로 읽지 않는다. */
function 관심축(선택들, 담아) {
  if (!선택들.length) return null;
  담아(선택들);

  /* 🔴 **차원이 다른 선택을 한 분포에 세면 그 수는 아무것도 안 가리킨다.**
   *   S1-5 만으로도 이미 축이 둘이다 — 「오늘 하루 어땠어요」(매일)와 「6개월 뒤의 나」(평생 1회).
   *   섞으면 `망설임_중앙` 은 매일 쪽 표본에 압도돼 「목표를 고를 때 오래 망설였다」가 사라지고,
   *   `고른것` 은 서로 비교할 수 없는 id 들의 한 자루가 된다. 미니게임 4모듈이 각자 보기를 내면
   *   그날 이 자루는 통째로 못 쓰게 된다(`발주_게임모듈.md` §6-0).
   * 🔑 **최상위 값은 그대로 둔다** — 호출부 호환이자 「몇 번 골랐나」처럼 축과 무관한 값의 자리다.
   *   ⚠ 다만 최상위 `고른것`·`망설임_중앙` 은 축이 섞인 값이라 **판정에 쓰지 않는다**: 그 판정은
   *   `차원별` 에서 한다. 🚫 최상위를 지워 「깨끗하게」 만들지 않는다(소비자가 조용히 죽는다).
   * 🔑 차원이 `null` 인 행은 **`미상` 으로 따로 센다** — 옛 배정 행에는 이 칸이 없고 스냅샷은
   *   불변이라 되짚을 길이 없다(`lib/오늘과제.답하기차원`). 아무 차원에 얹으면 그 분포가 거짓이 된다. */
  const 묶음 = new Map();
  for (const e of 선택들) {
    const d = (e && e.payload && e.payload.choice_dimension) || null;
    const 키 = typeof d === 'string' && d !== '' ? d : 미상차원;
    if (!묶음.has(키)) 묶음.set(키, []);
    묶음.get(키).push(e);
  }
  const 차원별 = {};
  for (const [키, 행들] of 묶음) 차원별[키] = 선택집계(행들);

  return { ...선택집계(선택들), 차원별 };
}

/** 차원이 없던 행들의 자리 — 「모른다」를 어느 축에도 얹지 않는다. */
const 미상차원 = '미상';

/* ── 작성과정 — 쓰기 과제를 «어떻게» 썼나 (게이트 ② 자동층 · 발주_게임모듈 §6-6 ⑨)
 *
 * 🔑 재료는 `submission.created` 의 `payload.compose_meta` 4칸이고, **칸 목록은 조립기에서
 *   파생한다**(`lib/작성과정.칸들` — 목록을 다시 적으면 조립기가 칸을 늘린 날 조용히 갈라진다).
 * 🔴 분모 = **4칸이 온전한 행**만이다. compose_meta 가 없는 행은 「안 잰 것」이 아니라
 *   대부분 **음성 제출**(잴 타건이 없다)이라, 그 행을 미측정으로 세면 수가 거짓이 된다.
 * 🔴 `불완전` 은 따로 센다 — 키는 있는데 4칸이 한 벌이 아닌 행은 조립기 규율(⑨ 규칙 1)이
 *   막았어야 하는 형태다. 계약·검증기는 그 반쪽을 원리상 못 막으므로(⑨ 실측) 여기 숫자가
 *   그 결함이 새어 들어왔음을 보는 유일한 눈이다. 0 이 정상이다.
 * 🔑 `최대덩어리` 는 중앙값이 아니라 **최대**다 — 검수 우선순위 신호(붙여넣기 의심)라
 *   「가장 큰 한 번」이 뜻이고, 라벨이 아니다(⑤ 천장 그대로 — 번역기 단정 금지). */
function 작성과정축(제출들, 담아) {
  const 온전 = (m) => !!m && typeof m === 'object' && 작성칸들.every((k) => Number.isInteger(m[k]));
  const 잰것 = [];
  const 불완전행 = [];
  for (const e of 제출들) {
    const m = e && e.payload && e.payload.compose_meta;
    if (m === undefined || m === null) continue; // 키 없음 = 잴 것이 없던 제출(음성 등)
    if (온전(m)) 잰것.push(e);
    else 불완전행.push(e);
  }
  const 불완전 = 불완전행.length;
  if (!잰것.length && !불완전) return null;
  담아(잰것);
  /* 불완전 행도 근거에 담는다(M2) — 이 축이 쓴 근거는 이 축이 담는다. ⚠ 같은 event_id 가
   * 끈기축을 거쳐 이미 근거에 있을 수 있지만(제출 행이므로) 그건 **우연의 겹침**이다 —
   * 끈기축이 분모를 바꾸는 날 이 축의 주소가 조용히 사라지면 안 된다. */
  담아(불완전행);
  const 값 = (k) => 잰것.map((e) => e.payload.compose_meta[k]);
  return {
    미룸_중앙: 자리(중앙값(값('first_keystroke_ms')), 0),
    붙듦_중앙: 자리(중앙값(값('total_compose_ms')), 0),
    되돌림_중앙: 자리(중앙값(값('revision_count')), 0),
    최대덩어리_최대: 잰것.length ? Math.max(...값('input_burst_max')) : null,
    불완전,
    /* 🔴 어느 행이 반쪽인지의 **주소**(M2) — 수만 있으면 결함 행을 찾으러 전 행을 다시 뒤진다.
     * evidence_refs 는 축 구분 없는 한 자루라 이 축이 직접 든다(조립기 규율이 새는 날의 유일한 눈). */
    불완전사건: 불완전행.map((e) => String(e.event_id || '')).filter(Boolean),
    n: 잰것.length,
  };
}

/** 한 묶음의 선택 집계. `관심축` 이 전체에 한 번, 차원마다 한 번씩 부른다. */
function 선택집계(선택들) {
  const 고른것 = {};
  const 자리별 = {};
  const 지연 = [];
  let 추천있음 = 0;
  let 추천따름 = 0;
  let 바꿈 = 0;
  let 무관심 = 0;
  let 거절 = 0;

  for (const e of 선택들) {
    const p = (e && e.payload) || {};
    const 고름 = p.selected_option == null || p.selected_option === '' ? null : String(p.selected_option);
    if (고름) {
      고른것[고름] = (고른것[고름] || 0) + 1;
      /* `position` 은 **1부터** 센다(L0 §140 정본 예시). 0 이나 음수가 오면 남의 판이거나
       * 지어낸 값이라 자리 분포에서 뺀다 — 세면 「첫째를 골랐다」가 한 칸 늘어난다. */
      if (Number.isInteger(p.position) && p.position >= 1) {
        자리별[p.position] = (자리별[p.position] || 0) + 1;
      }
    } else if (p.rejected_all === true) {
      /* 🔴 **`true` 로만 센다.** `있음(false)` 이 참이라 「실려 있나」로 재면 `rejected_all:false` 인
       *   평범한 무관심 행이 전부 거절로 넘어간다 — 검증기 택1이 같은 함정에 빠져 있던 자리다. */
      거절 += 1;
    } else {
      /* `skipped` 를 안 보고 else 로 받는 것이 정본이다 — 택1이 셋 중 하나를 보장하므로
       * 「고르지도 거절하지도 않았다」는 무관심 하나뿐이다. 키를 빠뜨린 옛 행도 여기 든다. */
      무관심 += 1;
    }
    /* 밀지 않은 날은 분모에도 안 넣는다 — 넣으면 「밀었는데 안 따랐다」와 「애초에 안 밀었다」가
     * 같은 모양이 되고, 그 둘은 이 축에서 정반대 뜻이다. */
    if (p.recommended_option != null && p.recommended_option !== '') {
      추천있음 += 1;
      if (고름 && 고름 === String(p.recommended_option)) 추천따름 += 1;
    }
    // 못 쟀으면 `null` 이라 여기서 빠진다(0 으로 접으면 «즉답»이 되어 분포가 왼쪽으로 쏠린다).
    if (Number.isFinite(p.latency_ms) && p.latency_ms >= 0) 지연.push(p.latency_ms);
    if (p.changed_selection) 바꿈 += 1;
  }

  return {
    고른것,
    자리별,
    추천따름률: 비율(추천따름, 추천있음),
    망설임_중앙: 자리(중앙값(지연), 0),
    바꿈률: 비율(바꿈, 선택들.length),
    안고름: 무관심 + 거절,
    무관심,
    거절,
    n: 선택들.length,
  };
}

/* ── 탐지 — G2 「보고서 교정」이 낸 지목을 읽는다 (발주_게임모듈.md G2 §5 A행 · §9-②·③)
 *
 * 🔑 **왜 `관심축`에 안 얹는가.** 모양이 같다(둘 다 선택로그 필드다). 뜻이 다르다 — 관심축의
 *   `selected_option` 은 「무엇에 끌리는가」(⑤관심·목표)고, G2 의 그것은 **「무엇을 오류로
 *   보는가」**다. 한 자루에 담으면 취향 분포에 오탐이 섞여 두 축이 같이 죽는다. v6 이 잡은
 *   결함(라디오 제출을 리듬축이 「숙제 제출」로 읽음)과 **같은 계열**이고, 그때 배운 것이
 *   「event_type 이 같다고 같은 사건이 아니다」였다.
 *
 * 🔴 **정오를 안 센다** — 짚은 자리가 «맞았나»의 정답은 `task_snapshot` 에 있다. 그 칸은 08-20 부터
 *   deliver 원신호에 실리지만(옛 「이 층에 안 온다」 벽은 무너짐), 대조·채점 없이 지어 붙이면
 *   축이 거짓이 된다. 그래서 이 v1 이 내는 것은
 *   **성향**뿐이다: 얼마나 자주 짚나 · 어디를 짚나 · 얼마나 빨리 · 얼마나 자주 「없음」이라 하나.
 *   §9-③ 의 조기 경보(대조 문항 정답률 ↔ 심은 문항 정답률의 벌어짐)는 그 조인이 서는 판에서
 *   열고 `추정판` 을 올린다 — 지금 절반을 「정답률」이라 이름 붙이면 그 이름이 거짓말을 한다.
 *
 * 🔑 G2 행을 가르는 표식 = **`options_shown` 배열 + `rejected_all` 불리언이 한 벌로 있는 행**.
 *   그 쌍을 내는 생산자는 `lib/보고서교정제출.js` 하나다(라디오 승격기는 `stated_option` 을
 *   쓰고 `options_shown` 을 «일부러 안 싣는다» — `lib/이벤트검증.js` 이벤트별필수 c11 주석).
 *   ⚠ 챌린지로는 아직 안 가른다 — v8 판정 때는 `task_snapshot` 이 이 층에 안 왔다(옛 벽 · 08-20
 *   deliver 원신호가 실어 무너짐). 표식을 챌린지로 좁히는 것은 축 행동 변경이라 별도 판정 몫이다. 모듈이 셋째로
 *   늘어 같은 쌍을 내는 날 이 표식은 좁혀야 한다 — 그날 이 주석이 그 자리를 가리킨다. */
function G2지목행인가(e) {
  const p = (e && e.payload) || {};
  return Array.isArray(p.options_shown) && typeof p.rejected_all === 'boolean';
}

/**
 * 탐지축 v1 — 성향만. `짚음`(submission.created) + `무산출`(quiz.answered) 두 갈래를 한 축으로 센다.
 * 🔴 두 갈래를 **합쳐서** 재는 것이 설계다 — 분모가 「그날 받은 문장 수」여야 「얼마나 자주
 *   짚나」가 뜻을 갖는다. 갈래별로 따로 세면 각자 분모가 자기 갈래라 비율이 항상 1 에 붙는다.
 */
function 탐지축(짚음들, 무산출들, 담아) {
  const 행들 = [...짚음들, ...무산출들].filter(G2지목행인가);
  if (행들.length === 0) return null; // 재료 없는 축은 `null` 이다 — 0 으로 채우면 「못한다」로 읽힌다
  담아(행들);

  const 자리별 = {};
  const 사유별 = {};
  const 지연 = [];
  let 짚음 = 0;
  let 거절 = 0;
  let 건너뜀 = 0;

  for (const e of 행들) {
    const p = e.payload;
    const 고름 = p.selected_option == null || p.selected_option === '' ? null : String(p.selected_option);
    if (고름) {
      짚음 += 1;
      /* 자리는 **1부터**다(L0 §140) — 0·음수는 남의 판이거나 지어낸 값이라 분포에서 뺀다.
       * 🔑 이 분포가 「1번을 습관적으로 누르는 손버릇」과 「그 자리를 의심함」을 가른다. */
      if (Number.isInteger(p.position) && p.position >= 1) {
        자리별[p.position] = (자리별[p.position] || 0) + 1;
      }
    } else if (p.rejected_all === true) {
      /* 🔴 `true` 로만 센다 — 「실려 있나」로 재면 `rejected_all:false` 인 짚음 행이 전부 거절로
       *   넘어간다(선택집계가 같은 함정을 명시적으로 피한 자리). */
      거절 += 1;
    } else if (p.skipped === true) {
      /* 🔴 거절과 **다른 사건**이다(c4 판정) — 합치면 「우리 문항이 다 틀렸다」와 「관심 없었다」를
       *   엔진이 같은 신호로 배운다. 그래서 `선택집계` 와 달리 여기는 else 로 안 받는다. */
      건너뜀 += 1;
    }
    // 못 쟀으면 빠진다 — 0 으로 접으면 「즉시 알아챘다」가 되어 분포가 왼쪽으로 쏠린다.
    if (Number.isFinite(p.latency_ms) && p.latency_ms >= 0) 지연.push(p.latency_ms);
    if (typeof p.selection_reason === 'string' && p.selection_reason !== '') {
      사유별[p.selection_reason] = (사유별[p.selection_reason] || 0) + 1;
    }
  }

  return {
    /* 「없음」이라 판정한 비율 — **과잉 교정 성향의 유일한 계기판**(§5 A②). 낮을수록 아무거나
     * 짚는 쪽이다. ⚠ 정밀도가 아니다: 대조 문항이 몇 장 섞였는지를 이 층은 모른다(머리말). */
    없음률: 비율(거절, 행들.length),
    짚음률: 비율(짚음, 행들.length),
    건너뜀률: 비율(건너뜀, 행들.length),
    자리별,
    사유별,
    /* 탐지 지연 — 확신도의 암묵 대리(§5 A행). 짧은 지연 + 오탐 = 화석화된 오개념. 그 결합은
     * 정오가 서는 판에서 계산한다(지금은 지연 분포만 남긴다). */
    탐지지연_중앙: 자리(중앙값(지연), 0),
    n: 행들.length,
  };
}

/* ── 강제산출 — G4 「서류 관문」이 낸 강제 산출을 읽는다 (발주_게임모듈.md G4 §2 ㉡ · §5 · v9)
 *
 * 🔑 표식 = **`submission.task_snapshot.challenge_id`** — 서류관문 팩 `모듈상수` 지목(값 사본 0).
 *   G2 표식(`options_shown`+`rejected_all` 쌍)과 다른 축인 이유: G4 payload 에는 선택로그가
 *   없다(보기 선택형 아님 — G4 §8 확정 기각). 챌린지로 가르는 것은 탐지축이 「`task_snapshot`
 *   이 이 층에 안 온다」고 접었던 자리다 — G4 는 그 칸을 **행이 실을 때만** 세겠다는 판정이고,
 *   deliver 원신호 질의가 그 칸을 `submission.task_snapshot` 으로 중첩해 싣는다(238bf21 ·
 *   08-20 — 그 전까지 이 축은 서버에서 항상 null 이었다). 행이 그 칸을 안 실은 날의 null 은
 *   「재료 없음」이지 거짓이 아니다 — 지어내지 않는다.
 *
 * 🔴 **정오를 안 센다** — 정답집합 대조는 서버 재채점(`lib/서류관문.채점`) 몫이고 그 산출은
 *   `corrections` 행이다(자기인식·탐지 v1 과 같은 벽). 이 v1 이 내는 것은 **성향**뿐이다:
 *   얼마나 자주 「모르겠어요」로 넘기나 · 얼마나 다시 도전하나 · 빈칸 앞에 얼마나 머무나.
 *
 * 🔴 G3(알바 변명) 소비자는 **여기 없다** — G3 행은 `발화녹음` 제출이라 끈기·리듬·집중띠축이
 *   이미 세고, G3 고유 신호(회피 지연·머뭇거림)는 서버 STT 파생이라 이 층의 재료가 아니다. */
function G4행인가(e) {
  const snap = e && e.submission && e.submission.task_snapshot;
  return !!snap && typeof snap === 'object' && !Array.isArray(snap)
    && snap.challenge_id === 서류관문상수.challenge_id;
}

/**
 * 강제산출축 v1 — 성향만. 빈칸·모름(`quiz.answered`)과 변환(`submission.created`)을 한 축으로
 * 센다. 🔴 분모는 「그날 지난 턴 수」다 — 갈래별로 따로 세면 모름넘김률의 분모가 자기 갈래라
 * 비율이 항상 1 에 붙는다(탐지축과 같은 판정).
 */
function 강제산출축(제출들, 퀴즈들, 담아) {
  const 행들 = [...제출들, ...퀴즈들].filter(G4행인가);
  if (행들.length === 0) return null; // 재료 없는 축은 `null` 이다 — 0 으로 채우면 「못한다」로 읽힌다
  담아(행들);

  const 지연 = [];
  let 모름 = 0;
  let 재도전 = 0;
  for (const e of 행들) {
    const p = e.payload || {};
    /* 🔴 `true` 로만 센다 — 「실려 있나」로 재면 값이 다른 행까지 넘어간다(탐지축 rejected_all
     *   과 같은 함정). 모름은 산출 강제를 «회피»한 유일한 정직 통로라 이 비율이 축의 핵심이다. */
    if (p.skipped === true) 모름 += 1;
    /* 재시도 후 자기수정 — 「유일한 결과 변수」의 앞면(G4 §5). attempt_no 없는 행은 못 잰
     *   행이지 첫 시도가 아니다 — 분자에서만 빠진다(0 으로 접지 않는다). */
    if (Number.isInteger(p.attempt_no) && p.attempt_no > 1) 재도전 += 1;
    // 못 쟀으면 빠진다 — 0 으로 접으면 「즉시 답했다」가 되어 분포가 왼쪽으로 쏠린다.
    if (Number.isFinite(p.latency_ms) && p.latency_ms >= 0) 지연.push(p.latency_ms);
  }

  return {
    /* 「모르겠어요」 비율 — 회피 성향의 계기판(G4 §5 「포기·회피 행동」). 감추지 않는 것이
     * 설계라(§4-2), 이 값이 높은 것은 결함이 아니라 신호다. */
    모름넘김률: 비율(모름, 행들.length),
    재도전률: 비율(재도전, 행들.length),
    /* 빈칸 체류 — 확신도의 암묵 대리(G4 §5 「실전 어휘·읽기 이해」). 변환 턴은 latency 를 안
     * 실으므로(payload 규격) 저절로 이 분모 밖이다 — 잰 행만 남는다. */
    빈칸체류_중앙: 자리(중앙값(지연), 0),
    n: 행들.length,
  };
}

/* ③자기인식 — c11 에서 열렸다(라디오 승격기 = `quiz.answered` 첫 생산자). v1 이 재는 것은
 * 「스스로 모른다고 아는가」의 **표기 축**뿐이다: `?`(low)·`??`(guess)를 얼마나 쓰는가.
 * v12 — 입력이 퀴즈 + G2 짚음 제출이다(호출부 참조). ⚠ 분모는 «표기 기회»가 아니라 «행 수»다 —
 * 토글 없던 시절 행·기회 없는 행(G2 무산출)이 분모에 들어 표기율은 방향만 본다(v1 머리말의
 * 「정밀도가 아니다」 그대로 — 기회 유무는 행에 안 남아 원리상 못 가른다).
 * 🔴 정오 결합(확신-정답 보정)은 여기서 안 한다 — 정답은 `task_snapshot`(submissions)에 있고
 * 그 칸은 08-20 부터 deliver 원신호에 실린다(옛 벽 무너짐). 그래도 대조·채점 없이 지어 붙이면
 * 축이 거짓이 된다 — 여는 판에서 `추정판`을 올린다(위 v5 주석). 표기 없음(null)은 「안 물렸다」지 「확신했다」가 아니다 —
 * 그래서 확신율이 아니라 표기율을 낸다. */
function 자기인식축(퀴즈들, 짚음들, 담아) {
  const 행들 = [...퀴즈들, ...짚음들];
  if (!행들.length) return null;
  담아(행들);
  const 값 = (e) => (e.payload && e.payload.confidence) ?? null;
  const 표기 = 행들.filter((e) => 값(e) != null);
  return {
    표기율: 비율(표기.length, 행들.length),
    저확신: 표기.filter((e) => 값(e) === 'low').length,
    찍음: 표기.filter((e) => 값(e) === 'guess').length,
    n: 행들.length,
    /* estimator_confidence 표본에 드는 몫 — 퀴즈 행만. 짚음 제출 행은 끈기축이 이미 표본으로
     * 세므로(회귀 ⑩ 「신뢰도가 공짜로 안 오른다」의 그 규율) 여기서 또 세면 이중이다. */
    표본n: 퀴즈들.length,
  };
}

/* 선호 — `preference.stated`(c11 ⓐⓑ · 첫 생산자 = 라디오 명령). 차원별 마지막 선언과 바꿈.
 * ⑤관심축(행동 관측 `choice.selected`)과 축을 가르는 이유 = **출처가 다르다**(explicit vs
 * observed · `lib/사건출처.js`) — 섞으면 개인화가 자기 추측을 학생의 말로 착각한다. */
function 선호축(선언들, 담아) {
  if (!선언들.length) return null;
  담아(선언들);
  const 차원별 = {};
  let 이유수 = 0;
  for (const e of 선언들) {
    const p = e.payload || {};
    if (p.selection_reason) 이유수 += 1;
    if (!p.preference_dimension) continue;
    if (!차원별[p.preference_dimension]) 차원별[p.preference_dimension] = { 마지막: null, 선언: 0, 바꿈: 0 };
    const d = 차원별[p.preference_dimension];
    d.선언 += 1;
    if (d.마지막 != null && p.stated_option != null && d.마지막 !== p.stated_option) d.바꿈 += 1;
    if (p.stated_option != null) d.마지막 = p.stated_option;
  }
  return { 차원별, 이유율: 비율(이유수, 선언들.length), n: 선언들.length };
}

/* 정서 — `affect.reported`(c11 ⓔ · `!슬럼프`). 신고 «빈도»가 재료의 전부다 — 점수로 접지
 * 않는다(「몇 번 말했나」까지가 사실이고 해석은 소비자 몫). 정의적 여과막 화면이 합류하는
 * 날 `stated_via` 가 표면을 가른다(그때도 이 축의 식은 안 바뀐다 — 재료만 는다). */
function 정서축(신고들, 담아) {
  if (!신고들.length) return null;
  담아(신고들);
  const 종류별 = {};
  for (const e of 신고들) {
    const k = (e.payload && e.payload.affect_kind) || '미상';
    종류별[k] = (종류별[k] || 0) + 1;
  }
  return { 종류별, 최근: 신고들[신고들.length - 1].occurred_at ?? null, n: 신고들.length };
}

