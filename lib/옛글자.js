/* 형제 `.claude/hooks/lib/옛글자.js` 와 **같은 클래스** — 한자+가나.
 * [vNEXT] 리뷰 P2-① 확장: 호환한자(F900–FAFF)·반각 가나(FF66–FF9F)·astral(가나 보충 1AFF0–1B16F ·
 * 2·3면 한자 20000–3FFFF)이 구판에서 «통과»로 샜다. 범위 산정 근거는 형제 정본 머리말에.
 * 갈라지면 `tests/옛글자.test.js` 의 「형제와 같은 클래스」가 빨개진다. */
const 클래스 = '[\\u3040-\\u30FF\\u3400-\\u4DBF\\u4E00-\\u9FFF\\uF900-\\uFAFF\\uFF66-\\uFF9F\\u{1AFF0}-\\u{1B16F}\\u{20000}-\\u{3FFFF}]';

/* 🔴 **내보내는 것은 전역이 아닌 쪽이다.** 전역 정규식의 `.test()`·`.exec()` 는 `lastIndex` 를
 *   들고 다녀 **같은 입력에 번갈아 참·거짓**을 낸다 — 부르는 쪽이 한 줄을 두 번 물으면 둘째가
 *   거짓이고, 새는 방향은 여기서도 「통과」다. 회귀를 처음 돌린 자리에서 실제로 걸렸다.
 *   전역은 `match` 용으로 **이 파일 안에서만** 쓴다. 클래스 문자열이 한 벌이라 단일 출처는
 *   그대로 지켜지고, `source` 도 같아서 형제 대조가 그대로 선다. */
const 옛글자 = new RegExp(클래스, 'u');
const 훑기 = new RegExp(클래스, 'gu');

/** 글에 든 옛 글자의 **코드포인트 집합**을 돌려준다(글자 자체는 담지 않는다). */
function 찾기(글) {
  const 본 = new Set();
  for (const m of String(글 == null ? '' : 글).match(훑기) || []) 본.add(m.codePointAt(0));
  return [...본];
}

/** 코드포인트들을 사람이 읽을 표기로 — `U+683C` 형태. 글자는 절대 넣지 않는다. */
function 짚기(코드들) {
  return 코드들.map((c) => 'U+' + c.toString(16).toUpperCase().padStart(4, '0')).join(' · ');
}

/**
 * 학생에게 나갈 칸들 중 **처음 걸린 칸 하나**를 돌려준다 — `{ 칸, 짚음 }` · 깨끗하면 `null`.
 *
 * 🔑 왜 「전부」가 아니라 「처음 하나」인가: 부르는 쪽은 행을 버릴지 말지만 정하면 되고, 사유는
 *   한 줄이라야 그 행의 실패 이유가 한눈에 읽힌다. 전수가 필요한 자리(채점·감사)는 `찾기` 를
 *   칸마다 부르면 된다 — 두 쓰임을 한 함수에 겹치면 반환 모양이 갈린다.
 * ⚠ 값이 문자열이 아닌 칸은 **건너뛰지 않고 문자열로 본다** — `null`·숫자는 어차피 안 걸리고,
 *   건너뛰기를 넣으면 「안 잰 칸」과 「깨끗한 칸」이 같은 모양이 된다(F207).
 */
function 첫걸림(칸들) {
  for (const [칸, 값] of Object.entries(칸들 || {})) {
    const 코드 = 찾기(값);
    if (코드.length) return { 칸, 짚음: 짚기(코드) };
  }
  return null;
}

module.exports = { 옛글자, 찾기, 짚기, 첫걸림 };
