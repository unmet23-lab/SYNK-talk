/* 라디오 출제 리듬 — 「지금 라운드를 열까 · 지금 무엇을 칠 차례인가」의 판정층.
 * (라디오24_설계 §2-J 운영 규칙 · §8-2-1 채팅 출제 · 2026-09-01 신설)
 *
 * ■ 왜 봇이 아니라 여기인가
 *   `bots/라디오수집봇.js` 는 VPS 에서 24/7 돈다 — 거기 있는 코드는 회귀가 원리상 못 닿는다.
 *   「언제 여는가」가 틀리면 그 사실이 드러나는 자리는 **송출 첫날 새벽**뿐이고, 그때 드러나는
 *   모양은 «문항 재고가 하루 만에 말랐다» 또는 «쿼터를 넘겨 수집이 조용히 0» 이다. 둘 다
 *   소급이 안 된다. 그래서 판정을 전부 여기로 내리고 봇은 이 표를 읽어 왕복만 한다
 *   (`lib/라디오수집.js` 가 «읽기 리듬»에 대해 하는 일과 같은 축 — 이 파일은 «쓰기 리듬»이다).
 *
 * ■ 이 파일이 지는 것
 *   ㉠ `열까` — 여는 조건 넷(시청자·하루 상한·쿼터 상한·간격). **사유를 늘 낸다**(조용한 0 금지).
 *   ㉡ `다음동작` — 출제 뒤 상태 기계: 대기 → 마감 → 정답 → 재도전 → 끝.
 *
 * ■ 🚫 여기 없는 것
 *   · 어느 문항인가 — `라디오라운드.제안조립`(가중·회전·검수 게이트)이 진다.
 *   · 문안 — 같은 파일의 `채팅조립`이 진다(200자 규율 포함).
 *   · 시계·난수 — 시각은 전부 인자다(안에서 읽으면 회귀가 돌린 날에 따라 갈린다).
 */
'use strict';

/** 하루에 여는 라운드 수의 위쪽 — 설계 §2-J 「참여 시간대 하루 4~6회」. */
const 하루상한기본 = 6;

/** 라운드 사이 최소 간격. 🔑 **정각마다 열지 않는다** — 유호 확정 08-25 ①의 실체다:
 *  「공부하려고 켠 학생에게 정각마다 문제를 들이대면 배경음악이 아니라 수업이 된다.」
 *  45분이면 하루 6회가 참여 시간대(≈5시간)에 흩어진다. */
const 라운드간최소밀리 = 45 * 60 * 1000;

/** 마감줄 뒤 정답줄까지의 틈(초) — 학생이 「마감」을 읽을 틈. 0 이면 두 줄이 붙어 지나간다. */
const 공개지연초 = 3;

/** 정답 공개 뒤 재도전까지(초) — 설계 §0-5 「60초 재도전 쌍」이 `retry_of_event_id` 를 만든다. */
const 재도전지연초 = 60;

/** 재도전은 **한 번만**. 재도전 라운드의 자식은 없다(사슬이 길어지면 그날 재고가 마른다). */
const 재도전깊이상한 = 1;

/* 🔴 `Number(null) === 0` · `Number('') === 0` · `Number(false) === 0` 이다.
 *   그래서 `Number.isFinite(Number(v))` 만 보면 **「모름」이 「0」으로 접힌다** — 이 파일에서는
 *   그 접힘이 「시청자 수를 못 읽었다」를 「아무도 없다」로, 「쿼터를 못 쟀다」를 「한 칸도 없다」로
 *   바꿔서 «사유»가 통째로 거짓이 된다(신설 당일 회귀가 잡았다).
 *   전광판판정 `합산수` 와 같은 형태로 막는다 — 빈 값은 숫자가 아니다. */
const 수 = (v) => {
  if (v === null || v === undefined || v === '' || typeof v === 'boolean') return null;
  const n = Number(v);
  return Number.isFinite(n) ? n : null;
};

/**
 * 지금 라운드를 열까.
 *
 * 재료 = {
 *   동시시청,            // ingest_heartbeat 와 같은 값. null 이면 «모름»이라 안 연다
 *   오늘연수,            // 오늘 이미 연 라운드 수(재도전 포함 — 같은 3줄이 나갔다)
 *   마지막출제ms,        // 없으면 null
 *   지금ms,
 *   하루상한 = 6,
 *   쿼터상한,            // `라디오수집.라운드상한(간격)` 의 값. null 이면 «못 쟀다»라 안 연다
 * }
 * @returns {{열다:boolean, 사유:string, 남은칸:number|null}}
 */
function 열까(재료) {
  const {
    동시시청, 오늘연수 = 0, 마지막출제ms = null, 지금ms,
    하루상한 = 하루상한기본, 쿼터상한,
  } = 재료 || {};
  const 이제 = 수(지금ms);
  if (이제 == null) throw new TypeError('열까: 지금ms 는 부르는 쪽이 준다');

  /* 🔴 「모름」은 「0명」이 아니다 — 시청자 수를 못 읽은 회차에 라운드를 열면 허수 분모가 된다.
   *   그리고 못 읽는 것은 흔하다(맥박이 null 을 그대로 남기는 것과 같은 사정). */
  const 본수 = 수(동시시청);
  if (본수 == null) return { 열다: false, 사유: '시청자수모름', 남은칸: null };

  /* 설계 §2-J — 동시 시청자 0 이면 열지 않는다. 아무도 없는데 문항을 태우면 재고가
   * 소진되고(quiz 100행 기준), 그 라운드는 분모가 0 인 «허수»로 원장에 남는다. */
  if (본수 <= 0) return { 열다: false, 사유: '시청자0', 남은칸: null };

  const 쿼터 = 수(쿼터상한);
  if (쿼터 == null) return { 열다: false, 사유: '쿼터상한모름', 남은칸: null };

  /* 🔑 두 상한 중 **작은 쪽**이 진짜 상한이다. 쿼터가 모자라면 출제부터 줄인다 —
   *   수집이 죽으면 그날 원장이 통째로 비고 그건 소급이 안 된다(`라디오수집` 출제 몫 머리말). */
  const 상한 = Math.min(수(하루상한) ?? 하루상한기본, 쿼터);
  const 연수 = Math.max(0, Math.floor(수(오늘연수) ?? 0));
  const 남은칸 = Math.max(0, 상한 - 연수);
  if (남은칸 <= 0) return { 열다: false, 사유: '하루상한', 남은칸: 0 };

  const 마지막 = 수(마지막출제ms);
  if (마지막 != null && 이제 - 마지막 < 라운드간최소밀리) {
    return { 열다: false, 사유: '간격부족', 남은칸 };
  }

  return { 열다: true, 사유: '열림', 남은칸 };
}

/**
 * 진행 중인 라운드에서 지금 무엇을 칠 차례인가.
 *
 * 진행 = {
 *   출제ms,                       // 출제줄이 채팅에 오른 시각(= shown_at)
 *   마감초,
 *   마감침 = false, 정답침 = false, 재도전냄 = false,
 *   깊이 = 0,                     // 0 = 첫 라운드 · 1 = 재도전 라운드
 *   지금ms,
 * }
 * @returns {{동작:'대기'|'마감'|'정답'|'재도전'|'끝', 남은초:number}}
 *   남은초 = 그 동작까지 남은 시간(음수 아님). '대기' 가 아니면 0 이다.
 */
function 다음동작(진행) {
  const {
    출제ms, 마감초 = 60, 마감침 = false, 정답침 = false, 재도전냄 = false,
    깊이 = 0, 지금ms,
  } = 진행 || {};
  const 이제 = 수(지금ms);
  const 시작 = 수(출제ms);
  if (이제 == null || 시작 == null) throw new TypeError('다음동작: 지금ms·출제ms 는 부르는 쪽이 준다');

  const 남음 = (때ms) => Math.max(0, Math.ceil((때ms - 이제) / 1000));

  const 마감때 = 시작 + (수(마감초) ?? 60) * 1000;
  if (!마감침) {
    return 이제 >= 마감때 ? { 동작: '마감', 남은초: 0 } : { 동작: '대기', 남은초: 남음(마감때) };
  }

  const 정답때 = 마감때 + 공개지연초 * 1000;
  if (!정답침) {
    return 이제 >= 정답때 ? { 동작: '정답', 남은초: 0 } : { 동작: '대기', 남은초: 남음(정답때) };
  }

  /* 재도전은 깊이 상한까지만 — 넘으면 이 라운드는 끝이다. */
  if (깊이 >= 재도전깊이상한 || 재도전냄) return { 동작: '끝', 남은초: 0 };

  const 재도전때 = 정답때 + 재도전지연초 * 1000;
  return 이제 >= 재도전때 ? { 동작: '재도전', 남은초: 0 } : { 동작: '대기', 남은초: 남음(재도전때) };
}

module.exports = {
  하루상한기본, 라운드간최소밀리, 공개지연초, 재도전지연초, 재도전깊이상한,
  열까, 다음동작,
};
