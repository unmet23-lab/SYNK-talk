'use strict';
/**
 * 몽글 목소리 — **표정 어휘와 그 판정** (유호 확정 2026-08-25).
 *
 * ■ 왜 표정인가 — 같은 소리를 반복하면 그게 곧 기계다
 *   유호님 지시는 「최대한 많이 넣되 우겨넣지 말고 적재적소에」였다. 소리를 여러 자리에
 *   넣을수록 «같은 파일이 또 났다»가 도드라지므로, 많이 넣는 것과 살아있게 들리는 것은
 *   **변주 없이는 정반대로 간다.** 그래서 파일은 하나(`synk-sound-mongle.wav` = 「무?」)로 두고
 *   **재생 속도로 표정을 만든다** — 빠르면 높고 밝게, 느리면 낮고 나른하게 들린다.
 *   🔑 피치 보정을 **꺼야** 한다(`shouldCorrectPitch=false`) — 보정이 켜지면 속도만 변하고
 *      음높이가 그대로라 «표정»이 아니라 «빨리 감기»가 된다.
 *
 * ■ 🔑 미세 변주(±3%)가 「기계 아님」의 핵심이다
 *   사람은 같은 말을 매번 같은 높이로 하지 않는다. 표정이 같아도 매 재생마다 속도를 조금씩
 *   흔든다 — 이 3%가 없으면 표정을 다섯으로 늘려도 각 표정 안에서 다시 기계가 된다.
 *
 * ■ 🚫 우겨넣지 않기 위한 정지선 셋 (이 파일이 지는 것은 ①뿐 — 나머지는 화면·게이트 몫)
 *   ① **연달아 나지 않는다** — `겹침막기ms` 안의 두 번째 요청은 버린다.
 *   ② 녹음 중엔 전부 침묵(`lib/소리게이트.js` — 마이크 되먹임은 데이터 요건이다).
 *   ③ 오류 순간에 밝은 소리를 두지 않는다 — 「안심」(0.92)만 쓴다. 기죽는 반응 금지 확정의
 *      소리판이다(하강 버저 부재와 같은 결).
 *
 * 순수 모듈 — expo 0 · 시간은 인자로 받는다(테스트가 시계를 쥔다).
 */

/** 표정 = 재생 속도. 값의 근거는 위 머리말 · 정본 메모는 as 디자인_토큰 「몽글」. */
const 표정속도 = Object.freeze({
  기쁨: 1.12,   // 무오류 첫 열람 · 완료축하 · 재도전 — 높고 밝게
  물음: 1.05,   // 질문 대사 · 말 건네기 — 살짝 들뜬
  기본: 1.0,    // 탭 · 평상시 혼잣말
  안심: 0.92,   // 오류가 남은 답장 — 낮고 느리게(밝은 소리를 이 자리에 두지 않는다)
  잠결: 0.85,   // 방치·밤에 졸림으로 넘어갈 때
});

const 표정들 = Object.freeze(Object.keys(표정속도));

/** 미세 변주 폭 — ±3%. 0 으로 두면 표정 안에서 다시 기계가 된다(머리말). */
const 흔들폭 = 0.03;

/** 같은 소리가 겹쳐 웅얼거리지 않게 하는 최소 간격(ms). 소리 자체가 297ms 다. */
const 겹침막기ms = 400;

/**
 * 이 요청이 소리를 내도 되는가, 낸다면 어느 속도인가.
 *
 * @param {object} 인자
 * @param {string} 인자.표정 `표정속도` 의 키. 모르는 이름이면 **기본**으로 떨어진다(무음 아님 —
 *   화면이 오타를 내도 몽글은 말한다. 침묵은 게이트가 정하는 것이지 오타가 정하는 게 아니다).
 * @param {number} 인자.지금 `Date.now()`
 * @param {number} 인자.마지막 직전에 소리를 낸 시각(없으면 0)
 * @param {number} [인자.흔들] 0~1 난수(테스트가 고정값을 넣는다). 없으면 0.5 = 흔들림 0
 * @returns {{낼까: boolean, 속도?: number, 사유?: string}}
 */
function 목소리판정({ 표정, 지금, 마지막 = 0, 흔들 = 0.5 }) {
  if (지금 - 마지막 < 겹침막기ms) {
    return { 낼까: false, 사유: `겹침(${지금 - 마지막}ms < ${겹침막기ms})` };
  }
  const 바탕 = 표정속도[표정] || 표정속도.기본;
  /* 흔들 0~1 을 -1~+1 로 펴서 ±흔들폭 을 곱한다. 소수 셋째 자리에서 끊는다 —
     그 아래는 귀가 못 듣고 값만 지저분해진다(로그·테스트가 읽기 어려워진다). */
  const 속도 = Math.round(바탕 * (1 + (흔들 * 2 - 1) * 흔들폭) * 1000) / 1000;
  return { 낼까: true, 속도 };
}

module.exports = { 표정속도, 표정들, 흔들폭, 겹침막기ms, 목소리판정 };
