'use strict';
/**
 * 몽글 목소리 — **상황별 소리 배치와 그 판정** (유호 확정 2026-08-25).
 *
 * ■ 왜 «상황마다 다른 소리»인가 — 하나를 속도로만 바꾸면 단조롭다
 *   앞선 판은 「무?」 하나에 재생속도 다섯(기쁨 1.12 … 잠결 0.85)을 걸어 표정을 만들었다.
 *   유호님 판정: **「너무 단조로운데?」** — 맞는 지적이다. 그건 같은 말을 빠르게/느리게 한
 *   것이라, 소리를 여러 자리에 넣을수록 「또 그 소리」가 도드라진다. 12종은 각자 «다른 말»이고
 *   (「먀앙~」과 「우웅~」은 성격이 다르다), 그래서 많이 넣을수록 살아난다.
 *
 * ■ 다양함이 세 겹으로 쌓인다 — 셋 다 있어야 「기계 아님」이 성립한다
 *   ① **상황마다 다른 소리** (아래 `배치`)
 *   ② **같은 상황에서도 둘 중 랜덤** — 한 상황에 후보를 둘 두어 연속 반복을 깬다
 *   ③ **매 재생 ±3% 속도 미세 변주** — 사람은 같은 말을 매번 같은 높이로 하지 않는다
 *   🔑 ②가 빠지면 상황 안에서 다시 기계가 되고, ③이 빠지면 「둘이 번갈아 나는 기계」가 된다.
 *
 * ■ 🚫 우겨넣지 않기 — 정지선 셋
 *   ① **연달아 나지 않는다**(`겹침막기ms`) — 가장 긴 소리(669ms)보다 길게 잡는다.
 *   ② 녹음 중엔 전부 침묵(`lib/소리게이트.js` — 마이크 되먹임은 데이터 요건이다).
 *   ③ **오류 자리엔 내려앉는 소리만** — 「안심」은 미이·미유우 둘 다 하강형이다.
 *      밝은 소리를 오답 옆에 두지 않는다(기죽는 반응 금지 확정의 소리판 · 하강 버저 부재와 같은 결).
 *
 * ■ 🔑 이름은 «소리 자체»다(무·먀앙·우웅), 상황이 아니다 — 배치가 바뀌어도 이름이 안 거짓말한다.
 *   소리의 정본은 as `docs/디자인_토큰.json` 「몽글_*」이고 파일은 `assets/sfx/synk-voice-*.wav`.
 *
 * 순수 모듈 — expo 0 · 시간·난수는 인자로 받는다(테스트가 시계와 주사위를 쥔다).
 */

/** 소리 이름 → 자산 키. 화면·어댑터가 이 키로 파일을 찾는다. */
const 소리들 = Object.freeze({
  무: 'mu', 뿌우: 'ppuu',
  먀앙: 'myang', 미유: 'miyu',
  뽀오: 'ppoo', 뽀옹: 'ppong',
  미이: 'mii', 미유우: 'miyuu',
  우웅: 'uung', 무우움: 'muum',
  모오옹: 'moong',
  무우: 'muu', // 예비 — 새 상황이 생기면 이 자리(지금 어떤 배치에도 안 쓴다)
});

/**
 * 상황 → 그 자리에서 날 수 있는 소리들. 유호님이 귀로 확정한 배치(08-25).
 * 🔴 「안심」 줄에 오름형(먀앙·미유·뽀옹…)을 넣지 않는다 — 위 정지선 ③.
 */
const 배치 = Object.freeze({
  기본: ['무', '뿌우'],        // 탭 · 평상 혼잣말 — 하루 수십 번이라 가장 짧은 둘
  기쁨: ['먀앙', '미유'],      // 무오류 첫 열람 · 재도전 — 표정이 큰 쪽
  물음: ['뽀오', '뽀옹'],      // 말 건네기 · 질문 대사 — 끝이 떠오른다
  안심: ['미이', '미유우'],    // 오류 남은 답장 — 내려앉는 둘뿐
  잠결: ['우웅', '무우움'],    // 방치 · 밤
  완료축하: ['모오옹'],        // 하루 한 번뿐 — 가장 길고 특별(이름 부르듯)
});

const 상황들 = Object.freeze(Object.keys(배치));

/** 미세 변주 폭 — ±3%. 0 이면 같은 소리가 매번 똑같이 난다(머리말 ③). */
const 흔들폭 = 0.03;

/** 겹침 최소 간격(ms) — 가장 긴 소리(모오옹 669ms)보다 길어야 꼬리까지 안 포갠다. */
const 겹침막기ms = 700;

/**
 * 이 요청이 소리를 내도 되는가, 낸다면 어느 소리를 어느 속도로.
 *
 * @param {object} 인자
 * @param {string} 인자.상황 `배치` 의 키. 모르는 이름이면 **기본**으로 떨어진다(무음 아님 —
 *   화면이 오타를 내도 몽글은 말한다. 침묵은 게이트가 정하는 것이지 오타가 정하는 게 아니다).
 * @param {number} 인자.지금 `Date.now()`
 * @param {number} [인자.마지막] 직전에 소리를 낸 시각
 * @param {string} [인자.직전소리] 직전에 난 소리 이름 — **연속으로 같은 소리를 피한다**(②의 실체).
 * @param {number} [인자.고르기] 0~1 난수(테스트가 고정값을 넣는다)
 * @param {number} [인자.흔들] 0~1 난수
 * @returns {{낼까: boolean, 소리?: string, 자산?: string, 속도?: number, 사유?: string}}
 */
function 목소리판정({ 상황, 지금, 마지막 = 0, 직전소리 = null, 고르기 = 0, 흔들 = 0.5 }) {
  if (지금 - 마지막 < 겹침막기ms) {
    return { 낼까: false, 사유: `겹침(${지금 - 마지막}ms < ${겹침막기ms})` };
  }
  const 후보 = 배치[상황] || 배치.기본;
  /* 같은 소리를 연달아 내지 않는다 — 후보가 둘 이상이면 직전 것을 뺀다.
     하나뿐인 상황(완료축하)은 그대로 낸다: 하루 한 번이라 반복이 안 생긴다. */
  const 고를것 = 후보.length > 1 && 직전소리 ? 후보.filter((s) => s !== 직전소리) : 후보;
  const 소리 = 고를것[Math.min(고를것.length - 1, Math.floor(고르기 * 고를것.length))];
  const 속도 = Math.round((1 + (흔들 * 2 - 1) * 흔들폭) * 1000) / 1000;
  return { 낼까: true, 소리, 자산: 소리들[소리], 속도 };
}

module.exports = { 소리들, 배치, 상황들, 흔들폭, 겹침막기ms, 목소리판정 };
