'use strict';
/**
 * 계약판 — 「이 DB 는 몇 판인가」를 정하는 **한 통로**. 순수 함수만(SQL·네트워크 0).
 *
 * ■ 왜 제 파일인가 (대기열 P3 #Q68 · 2026-08-12 재측정 → 2026-08-14 착지)
 *   `engine.schema_migrations` 의 최신 조각 이름에서 판을 읽는 **같은 판정**이 Edge Fn 12자리에
 *   **세 모양**으로 갈라져 있었다. 셋은 SQL 이 아니라 «행 → 판» 변환에서 갈렸다:
 *     ㉠ `계약판.exec(String(행?.최신조각 ?? '').match(/_(c\d+)\.sql$/)?.[1] ?? '')`  — 7자리
 *     ㉡ `판행.length ? String(판행[0].최신조각 ?? '').match(…)?.[1] : undefined`      — 3자리
 *     ㉢ `const [판] = …; String(판?.name ?? '').match(…)?.[1] ?? ''`                  — 2자리
 *   곁들여 `const 계약판 = /^c(\d+)$/` 손사본 **8벌**, 조각꼴 `_(c\d+)\.sql$` 는 **12자리 전부**에
 *   손으로 박혀 있었다. 같은 판정이 12벌이면 고칠 때 12벌을 다 찾아야 하고, 못 찾은 쪽의 증상은
 *   언제나 「통과」다 — CLAUDE.md 신뢰성: **3번째부터는 원인을 쓸 수 없게 만든다.**
 *
 * ■ 🔑 통로의 규격은 「SQL 통일」이 **아니다** — «행 → 판» 변환만 통일한다
 *   ㉠ 7자리는 학생·직원 확정 쿼리에 판을 **서브쿼리로 번들**해 왕복 1회를 벌고 있다. 공용
 *   read 함수(=여기서 sql 을 쥐는 안)로 바꾸면 **왕복이 7번 는다** — 통로를 세우려고 성능을
 *   깎는 셈이다. 그래서 SQL 은 자리에 남기고, 이 파일은 **아무것도 읽지 않는다**.
 *   👉 이 파일에 `sql`·`postgres`·`fetch` 가 들어오면 그 순간 규격이 깨진 것이다.
 *
 * ■ ⚠ 대가 (새 장치엔 틀릴 때의 모습을 함께 적는다 · CLAUDE.md 가드 맹점 ④)
 *   ① **틀리는 방향 = 시끄러운 쪽**으로 놓았다. `앞선판인가` 는 읽을 수 없는 값을 `true`(=거절)로
 *      접는다 — 조용히 통과시키면 DB 가 모르는 값을 보내는 앱이 그대로 들어온다(원 게이트가
 *      막으려던 바로 그것). 거절로 접으면 앱 전체가 426 으로 즉시 시끄럽다.
 *   ② 이 통로는 **「무엇을 읽나」까지만** 진다. 읽은 판으로 무엇을 할지(426·503·봉투 표기)는
 *      자리마다 다르고 여기로 접으면 안 된다 — 접는 순간 `auth`(게이트 아님)와 `radio-promote`
 *      (c11 미만 503)가 같은 규칙을 쓰게 된다.
 *   ③ 닫은 것 = 손사본 8벌 + 조각꼴 12벌. **안 닫은 것**: 판 «비교»를 `Number(…)` 로 직접
 *      하는 자리를 기계가 금지하지는 않는다(숫자 비교 전부를 금지할 수는 없다) —
 *      그건 `tests/계약판.test.js` 의 「손사본 0」 검사가 정규식 쪽에서만 진다.
 */

/** 계약판 표기 그 자체 — `c11`. 앱이 보내는 `X-Contract-Ver` 도 이 꼴이어야 한다. */
const 판꼴 = /^c(\d+)$/;

/** 마이그레이션 조각 파일명의 꼬리 — `20260812120000_engine_c11.sql` → `c11`. */
const 조각꼴 = /_(c\d+)\.sql$/;

/**
 * 판 표기 → 번호. 규격 밖이면 `null`(= 형식 검사를 겸한다).
 * @param {unknown} 판 @returns {number|null}
 */
function 판번호(판) {
  const m = 판꼴.exec(String(판 ?? ''));
  return m ? Number(m[1]) : null;
}

/**
 * 마이그레이션 조각 이름 → 판 표기. 규격 밖·빈 값이면 `null`.
 * 🔑 **`''` 를 돌려주지 않는다** — 옛 ㉢ 자리가 그랬고, 그러면 「못 읽었다」가 봉투에
 *   `contract_ver: ''` 로 실려 나가 «판이 없는 응답»과 «판을 못 읽은 응답»이 같은 모양이 됐다.
 * @param {unknown} 조각이름 @returns {string|null}
 */
function 조각에서판(조각이름) {
  const m = 조각꼴.exec(String(조각이름 ?? ''));
  return m ? m[1] : null;
}

/**
 * 질의 결과 → 판 표기. **세 모양을 한 자리에서 받는다** — 그게 이 파일의 존재 이유다.
 *   · 행 배열(`await sql\`…\``) · 이미 구조분해한 행 하나 · 0행(`[]`)·`null`·`undefined`
 *   · 별칭 `최신조각`(㉠㉡ 표기)과 `name`(㉢ 표기) **둘 다** 받는다
 * 🔴 0행에서 던지지 않는다 — 빈 이력에서 죽으면 500 의 이유가 로그에 안 남는다(반박 ⑮).
 *   못 읽은 것은 `null` 로 **말한다**. 부르는 쪽이 그 자리의 규칙대로 500·503 을 고른다.
 * @param {unknown} 행들 @returns {string|null}
 */
function 행들에서판(행들) {
  const 행 = Array.isArray(행들) ? 행들[0] : 행들;
  if (행 == null || typeof 행 !== 'object') return null;
  return 조각에서판(칸(행, '최신조각') ?? 칸(행, 'name'));
}

/** 자기 칸만 읽는다 — `행.name` 을 그대로 쓰면 행이 아닌 것(함수·클래스)을 넘긴 실수가
 *  내장 `name` 을 집어 조용히 「판을 읽었다」가 된다. 새는 방향을 통과에 두지 않는다. */
function 칸(행, 이름) {
  return Object.prototype.hasOwnProperty.call(행, 이름) ? 행[이름] : undefined;
}

/**
 * `앞` 이 `뒤` 보다 **뒤의(=새) 판인가**. 앱 선언판 > DB 판 게이트가 이것 하나로 선다.
 * 🔴 **읽을 수 없는 값은 `true`(거절)로 접는다.** 새는 방향을 「통과」에 두지 않는다 —
 *   통과로 접으면 DB 가 모르는 값을 보내는 앱이 그대로 들어오고, 그 증상은 한참 뒤
 *   CHECK 위반으로 나타난다. 거절로 접으면 426 으로 즉시 시끄럽다.
 * @param {unknown} 앞 @param {unknown} 뒤 @returns {boolean}
 */
function 앞선판인가(앞, 뒤) {
  const a = 판번호(앞);
  const b = 판번호(뒤);
  if (a === null || b === null) return true;
  return a > b;
}

module.exports = { 판꼴, 조각꼴, 판번호, 조각에서판, 행들에서판, 앞선판인가 };
