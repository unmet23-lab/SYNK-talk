'use strict';
/**
 * 교정 사건 로그 — 순수 함수만. 파일을 읽고 쓰는 것은 저장 어댑터(src/저장.js)의 일이다.
 *
 * ■ 이 파일이 닫는 것 — `src/교정API.js` 가 스스로 적어 둔 천장
 *   그 파일은 「사건은 화면이 한 번 만들어 쥐고, 재전송은 그 객체를 그대로」라는 규약을 세우고
 *   **「⚠ 천장: 이 사건은 아직 디스크에 안 남는다」** 고 적었다. 남지 않으면 규약이 앱을 껐다
 *   켠 순간 깨진다 — 같은 교정의 열람 사건이 **새 `idempotency_key` 로 다시 만들어져**
 *   서버에 두 벌 쌓이고, 그러면 「한 번에 세 장을 봤다」와 「사흘에 한 장씩」이 구별되지 않는다
 *   (그 구별이 `correlation_id` 를 둔 이유다 · P0 §3-1 ④). 결과축을 세우는 자리에서 결과축을
 *   오염시키는 셈이라, 화면보다 이 로그가 먼저다.
 *
 * ■ 🔑 큐를 새로 짓지 않는다 — `lib/제출로그.js` 의 **일반적인 세 칸**을 그대로 쓴다
 *   `전송기록`·`밀린것`·`직렬화`·`역직렬화` 는 항목의 `id`·`event_id`·`send_error`·`send_final`
 *   만 본다(제출 고유의 것은 `항목추가`·`다음시도번호`·`배달상태` 쪽이다). 그래서 그 넷을
 *   여기서 다시 내보내 **화면이 한 곳에서만 가져간다** — 두 벌로 적으면 「아직 안 보냄」과
 *   「거절당함」을 가르는 판정이 갈라지고, 갈라진 쪽은 조용히 영원히 재시도한다.
 *   🚫 제출 로그(`talk_log.jsonl`)에 섞어 넣지 않는다 — `학습출석`·`배달상태` 가 그 파일의
 *   모든 항목을 발화로 세므로, 교정 열람 한 건이 **제출 수를 늘린다**.
 *
 * 항목 모양:
 *   { id, correction_id, event_type, 사건, event_id: string|null,
 *     send_error: string|null, send_final: boolean }
 *
 * `사건` 을 통째로 들고 있는 것이 이 로그의 존재 이유다 — 다시 보낼 때 **그 객체 그대로**
 * 보내야 `idempotency_key` 가 같고, 같아야 서버가 `duplicate` 로 접는다(C0 §4-1).
 */
const { 전송기록, 밀린것, 직렬화, 역직렬화 } = require('./제출로그.js');

/**
 * 항목 id — **결정론**이다. 「어느 교정의 어느 사건」 한 쌍에 항목 하나.
 *
 * 🔴 `correction_id` 를 빼고 `event_type` 만으로 짓지 않는다 — 그러면 둘째 교정의 열람이
 *   첫째의 항목으로 접혀, 학생이 본 교정 중 **하나만** 서버에 남는다(그 손실은 「봤는지」와
 *   같이 소급이 없다). 반대로 시각·난수를 섞으면 껐다 켤 때마다 새 항목이 서서 위 천장이
 *   그대로 돌아온다.
 * 🔑 `idempotency_key` 와는 다른 축이다: 이건 **기기 안에서 같은 것을 두 번 만들지 않기**
 *   위한 키고, 그건 **서버가 같은 것을 두 번 저장하지 않기** 위한 키다.
 */
function 항목id(사건) {
  return `${사건.event_type}:${사건.correction_id}`;
}

/**
 * 사건을 항목으로 붙인 **새 배열**을 돌려준다. 원본은 건드리지 않는다.
 *
 * 🔑 **이미 있으면 아무것도 하지 않는다**(같은 항목을 그대로 돌려준다) — 화면이 열릴 때마다
 *   무조건 부르게 두고 여기서 접는 것이, 호출부마다 「이미 봤나」를 묻게 하는 것보다 안전하다
 *   (묻는 곳이 둘이 되면 한 곳이 잊고, 잊은 쪽은 조용히 사건을 늘린다).
 *
 * @param {object[]} 로그
 * @param {object|null} 사건 `교정API.열람사건`·`응답사건` 의 결과. `null` 이면 **로그를 안 바꾼다**
 *   (재료가 없어 만들지 못한 것이지, 빈 사건을 남길 자리가 아니다).
 * @returns {{로그: object[], 항목: object|null, 새것: boolean}}
 */
function 항목추가(로그, 사건) {
  if (!사건 || !사건.event_type || !사건.correction_id) return { 로그, 항목: null, 새것: false };
  const id = 항목id(사건);
  const 이미 = 로그.find((e) => e.id === id);
  if (이미) return { 로그, 항목: 이미, 새것: false };
  const 항목 = {
    id,
    correction_id: 사건.correction_id,
    event_type: 사건.event_type,
    사건,
    event_id: null,
    send_error: null,
    send_final: false,
  };
  return { 로그: 로그.concat([항목]), 항목, 새것: true };
}

/**
 * 이 교정에 학생이 이미 답한 값(`채택`·`수정`) — 없으면 `null`.
 * 화면이 버튼을 잠그는 근거다. **한 교정에 한 답**이고, 답은 사건이라 고쳐지지 않는다
 * (L0 §3-4 「현재 상태가 필요하면 이벤트에서 파생」 — 여기가 그 파생이다).
 */
function 응답값(로그, correction_id) {
  const e = 로그.find(
    (x) => x.correction_id === correction_id && x.event_type === 'correction.responded',
  );
  return (e && e.사건 && e.사건.payload && e.사건.payload.learner_response) || null;
}

/* 🚫 「이 교정을 봤나」를 묻는 함수를 두지 않는다 — `항목추가` 가 이미 접고 있어서, 두면
 *   같은 판정이 두 곳에 적히고 갈라진 쪽이 조용히 통과한다. 실제로 그 함수를 두고 변이 시험을
 *   돌렸더니 **아무 검사도 그것을 밟지 않았다**(호출부가 0이라 검사가 자기 주장을 못 쟀다). */
module.exports = { 항목id, 항목추가, 응답값, 전송기록, 밀린것, 직렬화, 역직렬화 };
