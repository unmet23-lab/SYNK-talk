'use strict';
/**
 * 몽글물음 — 강사가 몽글에게 묻는 자리의 **순수 판정**. (Vellum 1단계 · 앱 입구의 두뇌)
 *
 * ■ 왜 순수 층이 따로 있나
 *   화면(`src/강사화면.js`)은 RN 이라 회귀가 못 문다. 그런데 이 자리의 규칙은 «틀리면 조용한»
 *   것들이다 — 상한을 화면이 자기 숫자로 적으면 서버 상한이 바뀌는 날 화면만 옛 숫자를 말하고,
 *   그 거짓말은 아무 데서도 안 빨개진다(`강사API` 머리말의 `sample_size` 와 같은 축).
 *   그래서 «무엇을 보낼 수 있나 · 받은 것을 어떻게 읽나»만 여기 모으고 회귀가 여기를 문다.
 *
 * ■ 🔴 이 파일의 급소 = **인계를 «실패»로 그리지 않는 것**
 *   companion 의 기본값은 답이 아니라 **인계**다(그 문 머리말 §「지어내지 않는 것이 기능이다」).
 *   즉 `handoff: true` 는 오류가 아니라 **설계대로 동작한 것**이다. 화면이 이걸 빨갛게 그리면
 *   강사는 「고장났다」로 읽고 다시 묻는다 — 그러면 빈칸 로그에 같은 질문이 두 번 쌓여
 *   «문서에 없는 것» 목록의 분모가 조용히 부풀어 오른다.
 *   ⇒ 인계는 «몽글이 원장님께 넘겼다»는 **정상 결과**로 그린다.
 *
 * ■ 🚫 여기 두지 않는 것
 *   · 주소·키·fetch — 통로는 `src/사건통로.js` 하나다(`src/몽글API.js` 가 그 문을 지난다)
 *   · 문서 이름 목록 — 서버가 `cited_refs` 를 이미 화이트리스트로 걸러 준다. 앱이 사본을
 *     들면 목록이 자라는 날 갈리고, 갈린 쪽은 «멀쩡한 출처를 숨긴다»(새는 방향이 조용하다).
 */

/** 서버 상한 정본 = `functions/companion` 의 `질문상한`. 여기 값은 **그 사본**이고
 *  `tests/몽글물음.test.js` 가 서버 소스와 기계로 묶는다 — 갈리면 CI 가 빨개진다. */
const 질문상한 = 2000;

/** 화면 맥락 상한. 같은 규칙(서버 `화면상한` 과 묶인다). */
const 화면상한 = 100;

/**
 * 보낼 수 있는 질문인가. **자르지 않고 거절한다** — 자르면 강사는 자기가 물은 것과
 * 다른 질문의 답을 받고, 그게 틀린 답보다 나쁘다(서버가 같은 이유로 거절한다).
 * @param {string} 글
 * @returns {{보낼수있나: boolean, 사유: string, 글자수: number, 남은수: number}}
 */
function 질문판정(글) {
  const s = String(글 ?? '').trim();
  const n = [...s].length;                       // 🔑 코드포인트로 센다(서버와 같은 셈 · 이모지 1자)
  if (!n) return { 보낼수있나: false, 사유: '', 글자수: 0, 남은수: 질문상한 };
  if (n > 질문상한) {
    return { 보낼수있나: false, 사유: `${질문상한}자까지 물을 수 있어요`, 글자수: n, 남은수: 질문상한 - n };
  }
  return { 보낼수있나: true, 사유: '', 글자수: n, 남은수: 질문상한 - n };
}

/** 화면 맥락은 «있는데 이상한 것»만 막는다 — 없으면 그냥 안 보낸다(서버가 선택으로 받는다). */
function 화면정리(이름) {
  const s = String(이름 ?? '').trim();
  if (!s || [...s].length > 화면상한) return null;
  return s;
}

/** 보낼 몸 — 서버 칸 이름(`question`·`screen`)은 여기 한 곳에서만 쓴다. */
function 보낼것({ 질문, 화면 }) {
  const 몸 = { question: String(질문 ?? '').trim() };
  const 화 = 화면정리(화면);
  if (화) 몸.screen = 화;
  return 몸;
}

/**
 * 받은 답을 «화면이 그릴 모양»으로. 세 갈래뿐이다 — 답함 · 넘김 · 못 받음.
 *
 * 🔑 **«넘김»은 실패가 아니다**(위 급소). 그리고 «출처 0 으로 답함»도 정상 갈래가 아니라
 *   **빈칸 신호**다 — 문서에 없는 것을 몽글이 일반 지식으로 답한 자리라, 화면이 그 사실을
 *   조용히 삼키면 원장이 「무엇을 문서에 더해야 하는지」를 영영 못 본다.
 * @param {object|null} 답
 * @returns {{갈래: '답함'|'넘김'|'못받음', 글: string, 출처: string[], 사유: string, 근거없음: boolean, qa_id: string}}
 */
function 답읽기(답) {
  const a = 답 && typeof 답 === 'object' ? 답 : {};
  const 글 = String(a.reply ?? '').trim();
  const 출처 = Array.isArray(a.cited_refs) ? a.cited_refs.map(String).filter(Boolean) : [];
  const 사유 = String(a.handoff_reason ?? '').trim();
  const qa_id = String(a.qa_id ?? '');
  if (a.handoff) return { 갈래: '넘김', 글: '', 출처: [], 사유: 사유 || '원장님께 넘겼어요', 근거없음: false, qa_id };
  if (!글) return { 갈래: '못받음', 글: '', 출처: [], 사유: '답을 못 받았어요', 근거없음: false, qa_id };
  return { 갈래: '답함', 글, 출처, 사유: '', 근거없음: 출처.length === 0, qa_id };
}

module.exports = { 질문상한, 화면상한, 질문판정, 화면정리, 보낼것, 답읽기 };
