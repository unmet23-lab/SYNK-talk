'use strict';
/**
 * 곡장부 — SYNK **Reed** 의 첫 기둥. 「곡 하나가 자기에 대해 답하는 칸」과 그 **판정**.
 * (설계 정본 = appsscript `docs/Reed_설계_v0.1.md` §2-① · 유호 확정 08-25 «Reed» · 08-26 셋째 줄)
 *
 * ■ 왜 장부가 필요한가 — 곡 다섯이면 기억으로 되고, **곡 100이면 곡마다 손이 다시 든다**
 *   어느 자리 규칙인가 · 어느 판이 정본인가 · 다시 구우면 같은 소리가 나오나 · 어느 결에 걸리나 ·
 *   방송에 실제로 나갔나. 하나하나는 사소하고 100번 반복되면 그게 일의 전부가 된다.
 *
 * ■ 🔴 이 파일의 급소 = **`재현` 칸**
 *   재현이 안 되는 곡은 **영영 그 파일 하나**다 — 밝기 하나 못 바꾼다. 그리고 재현되는지는
 *   «만든 그 순간»에만 알 수 있다(나중에 물으면 아무도 모른다). 그래서 이 칸은 선택이 아니라
 *   필수이고, 「모른다」를 값으로 받지 않는다 — `없음` 이라고 **명시**해야 통과한다.
 *
 * ■ 🔴 채택 문턱의 순서 = **유호님 귀가 먼저, 규격은 그 뒤**
 *   규격을 통과해도 «좋은 곡»이 아니고, 규격을 못 넘으면 «방송에 못 거는 곡»이다. 그래서
 *   `채택판정` 은 「이 곡이 좋은가」를 묻지 않는다 — 「이미 고른 곡이 한 방송 안에 설 수 있나」만 본다.
 *
 * ■ 🚫 여기 두지 않는 것
 *   · 파일 읽기·쓰기 — 순수 판정만(장부의 «저장»은 부르는 쪽 몫)
 *   · 곡을 «만드는» 것 — 도구가 한다(합성 통로는 08-26 하차 · 곡은 AI 로)
 *   · 편성 — `lib/곡편성.js` 가 진다(장부는 «무엇이 있나», 편성은 «지금 무엇을 트나»)
 */

/** 결 다섯 — 하루가 한 결일 수 없다(24시간이라). 편성도 이 이름을 쓴다. */
const 결들 = Object.freeze(['새벽', '아침', '낮', '저녁', '밤']);

/** 장르 셋 (유호 확정 08-25). DJ 셋과 1:1 로 붙는다. */
const 장르들 = Object.freeze(['시티팝', '전자', '자연']);

/** 상태 셋 — 「후보」는 아직 안 들은 것, 「채택」은 방송에 서는 것, 「은퇴」는 뺀 것. */
const 상태들 = Object.freeze(['후보', '채택', '은퇴']);

/** 상태 전이 — **되돌릴 수 있게** 둔다(은퇴한 곡을 다시 채택하는 일은 실제로 생긴다). */
const 갈수있는곳 = Object.freeze({
  후보: Object.freeze(['채택', '은퇴']),
  채택: Object.freeze(['은퇴']),
  은퇴: Object.freeze(['채택']),
});

/**
 * 방송 규격 — **눈금 한 자**(설계 §4). 이 값들이 「100곡이 한 방송으로 들리는가」를 진다.
 * 🔑 유호님이 조정하실 자리라 한 곳에 모은다. 화면·도구가 자기 숫자를 적지 않는다.
 */
const 규격 = Object.freeze({
  /* §3-B 산수: 3분이면 밤 3시간 자습에서 풀 전체가 두 번씩 돌고, 6분이면 겹침 0.
   * 곡 수를 늘리는 것보다 길게 만드는 것이 압도적으로 싸다. */
  최소길이초: 360,
  /* 스트리밍 표준 눈금. 곡마다 다르면 학생이 볼륨 손잡이를 계속 만지고, 그 순간 배경이 아니게 된다. */
  라우드니스LUFS: -14,
  라우드니스허용: 1.0,
  /* 트루피크 여유 — 인코딩 뒤 넘치지 않게. */
  최대피크dBTP: -1.0,
  /* 루프 이음새는 «곡 안 최대 점프»보다 작아야 한다(절대값이 아니라 그 곡 자신과 견준다 —
   * 조용한 곡과 빽빽한 곡에 같은 절대 문턱을 걸면 한쪽은 늘 통과하고 한쪽은 늘 떨어진다). */
  이음새는곡내최대점프이하: true,
});

/** 곡 하나가 반드시 답해야 하는 칸. 빠지면 장부에 못 들어간다. */
const 필수칸 = Object.freeze(['id', '제목', '장르', '결', 'DJ', '판', '재현', '길이초', '상태']);

const 있나 = (v) => v !== undefined && v !== null && String(v).trim() !== '';

/**
 * 장부에 들어갈 수 있는 곡인가. **흠 목록을 돌려준다**(빈 배열 = 통과).
 * 🔑 첫 흠에서 멈추지 않는다 — 100곡을 들일 때 한 번에 한 흠씩 고치게 하면 100번을 100번 돈다.
 * @param {object} 곡
 * @returns {string[]} 흠 목록
 */
function 곡검증(곡) {
  const c = 곡 && typeof 곡 === 'object' ? 곡 : {};
  const 흠 = [];
  for (const 칸 of 필수칸) if (!있나(c[칸])) 흠.push(`${칸} 칸이 비었다`);
  if (있나(c.장르) && !장르들.includes(c.장르)) 흠.push(`장르가 목록 밖이다: ${c.장르}`);
  if (있나(c.결) && !결들.includes(c.결)) 흠.push(`결이 목록 밖이다: ${c.결}`);
  if (있나(c.상태) && !상태들.includes(c.상태)) 흠.push(`상태가 목록 밖이다: ${c.상태}`);
  if (있나(c.길이초) && !(Number(c.길이초) > 0)) 흠.push('길이초가 양수가 아니다');
  /* 🔴 재현 칸은 «비어 있음»과 «없음»을 가른다 — 「모른다」를 값으로 받으면 100곡 중 몇 개가
   *   못 고치는 곡인지 영영 모른다. 없으면 «없음» 이라고 명시해야 통과한다. */
  if (있나(c.재현) && c.재현 !== '없음' && String(c.재현).trim().length < 3) {
    흠.push('재현 칸이 명령도 「없음」도 아니다');
  }
  return 흠;
}

/** 이 곡을 고칠 수 있나 — 재현 명령이 있어야 밝기 하나라도 바꾼다. */
function 고칠수있나(곡) {
  return 있나(곡 && 곡.재현) && 곡.재현 !== '없음';
}

/**
 * 방송에 걸 수 있는가 — **규격 문턱**(설계 §4). 「좋은 곡인가」는 묻지 않는다.
 * @param {object} 곡  `측정` 칸에 {라우드니스LUFS, 피크dBTP, 이음새, 곡내최대점프} 가 있어야 한다
 * @returns {{선다: boolean, 흠: string[], 못잰것: string[]}}
 */
function 채택판정(곡, 눈금 = 규격) {
  const c = 곡 && typeof 곡 === 'object' ? 곡 : {};
  const m = c.측정 && typeof c.측정 === 'object' ? c.측정 : {};
  const 흠 = [];
  const 못잰것 = [];

  if (!(Number(c.길이초) >= 눈금.최소길이초)) {
    흠.push(`길이 ${Math.round(Number(c.길이초) || 0)}초 — 방송 판은 ${눈금.최소길이초}초 이상이다`);
  }
  /* 🔴 «못 잰 것»을 «통과»로 접지 않는다 — 새는 방향이 언제나 「통과」다.
   *   그래서 갈래를 따로 낸다: 흠이 0이어도 못 잰 것이 있으면 «선다»가 아니다. */
  if (!Number.isFinite(m.라우드니스LUFS)) 못잰것.push('라우드니스');
  else if (Math.abs(m.라우드니스LUFS - 눈금.라우드니스LUFS) > 눈금.라우드니스허용) {
    흠.push(`라우드니스 ${m.라우드니스LUFS.toFixed(1)} LUFS — 목표 ${눈금.라우드니스LUFS}±${눈금.라우드니스허용}`);
  }
  if (!Number.isFinite(m.피크dBTP)) 못잰것.push('피크');
  else if (m.피크dBTP > 눈금.최대피크dBTP) {
    흠.push(`피크 ${m.피크dBTP.toFixed(1)} dBTP — ${눈금.최대피크dBTP} 이하여야 한다`);
  }
  if (!Number.isFinite(m.이음새) || !Number.isFinite(m.곡내최대점프)) 못잰것.push('이음새');
  else if (눈금.이음새는곡내최대점프이하 && m.이음새 > m.곡내최대점프) {
    흠.push(`루프 이음새 ${m.이음새.toFixed(4)} > 곡내 최대 점프 ${m.곡내최대점프.toFixed(4)} — 감길 때 턱이 난다`);
  }
  return { 선다: 흠.length === 0 && 못잰것.length === 0, 흠, 못잰것 };
}

/**
 * 상태를 바꾼다. **허용된 전이만** — 아니면 사유를 돌려준다(던지지 않는다).
 * 🔴 «채택»으로 가는 문에는 규격 문턱이 걸린다(설계 §4 「규격을 통과해야 채택이 된다」).
 * @returns {{됐나: boolean, 곡: object, 사유: string}}
 */
function 상태바꾸기(곡, 새상태, 눈금 = 규격) {
  const c = 곡 && typeof 곡 === 'object' ? 곡 : {};
  if (!상태들.includes(새상태)) return { 됐나: false, 곡: c, 사유: `상태가 목록 밖이다: ${새상태}` };
  const 지금 = c.상태;
  if (지금 === 새상태) return { 됐나: false, 곡: c, 사유: `이미 ${새상태}다` };
  const 갈곳 = 갈수있는곳[지금];
  if (!갈곳) return { 됐나: false, 곡: c, 사유: `지금 상태를 모른다: ${지금}` };
  if (!갈곳.includes(새상태)) return { 됐나: false, 곡: c, 사유: `${지금} → ${새상태} 는 없는 길이다` };
  if (새상태 === '채택') {
    const p = 채택판정(c, 눈금);
    if (!p.선다) {
      const 말 = [...p.흠, ...p.못잰것.map((x) => `${x} 를 안 쟀다`)].join(' · ');
      return { 됐나: false, 곡: c, 사유: `규격 문턱을 못 넘었다 — ${말}` };
    }
  }
  return { 됐나: true, 곡: { ...c, 상태: 새상태 }, 사유: '' };
}

/** 지금 방송에 설 수 있는 곡들 — 편성이 고르는 «풀»이 이것이다. */
function 채택된것(장부) {
  return (Array.isArray(장부) ? 장부 : []).filter((c) => c && c.상태 === '채택');
}

/**
 * 장부 한 장 요약 — **«합계 = 갈래 + 갈래»로 낸다**(유호 확정 08-14 · 좋은 0과 「안 재봤다」를 가른다).
 * 곁들여 **못 고치는 곡 수**를 따로 센다 — 이 수가 늘면 장부가 굳어 가는 것이다.
 */
function 요약(장부) {
  const 목록 = Array.isArray(장부) ? 장부 : [];
  const 갈래 = { 후보: 0, 채택: 0, 은퇴: 0, 모름: 0 };
  const 장르별 = {};
  let 못고침 = 0;
  for (const c of 목록) {
    const s = c && 상태들.includes(c.상태) ? c.상태 : '모름';
    갈래[s] += 1;
    if (c && c.상태 === '채택') {
      const g = 장르들.includes(c.장르) ? c.장르 : '모름';
      장르별[g] = (장르별[g] || 0) + 1;
    }
    if (c && !고칠수있나(c)) 못고침 += 1;
  }
  return { 전체: 목록.length, ...갈래, 장르별, 못고침 };
}

module.exports = {
  결들, 장르들, 상태들, 갈수있는곳, 규격, 필수칸,
  곡검증, 고칠수있나, 채택판정, 상태바꾸기, 채택된것, 요약,
};
