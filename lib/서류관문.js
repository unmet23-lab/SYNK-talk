'use strict';
/**
 * 서류 관문(G4) 채점기 — 순수 함수만 (발주_게임모듈.md §G4 · §6-2 ⓑ · §9-1 ⓐ).
 *
 * ■ 자리 — 빈칸 스테이지의 «3갈래» 판정 하나뿐이다
 *   맞음(정답집합 안) · 축오답(오답집합 안 — 그 빈칸의 `재는축` 이 곧 태그다) · 모름(둘 다 밖 —
 *   태그 0 · 감사 레인 §6-6 ③ⓒ). 모르는 것을 「틀렸다」로 적지 않는다 — 정답집합 밖을 곧
 *   오답으로 접으면 살아있는 이형태(g4t04 b3 「하고」류 — 격이 다른 산 형태)가 오답 라벨로
 *   굳어 엔진이 거짓을 배운다(§9-1 이 이 팩의 최대 책임 자리로 못박은 그 사고).
 *   변환 스테이지는 열린 산출이라 여기 오지 않는다(검수 큐 몫 · §6-1).
 *
 * ■ 🔴 부분일치 채점 금지 — 집합 완전일치만 있다(`tests/멘탈게이지.test.js` 가 소스 전문을
 *   기계로 검사한다). 느슨하게 만들면 안 고친 답이 통과해 이 게임이 재려던 것이 안 재진다
 *   (G2 `정규화` 머리말과 같은 근거).
 *
 * ■ 정규화 — **정확히 넷만** 한다: NFC · 앞뒤 공백 제거 · 연속 공백 1칸 · 끝부호 제거.
 *   🔴 조사·활용·띄어쓰기는 그대로 둔다 — 그 셋이 이 모듈이 «재는» 축이다(§3-① 빈칸 1개 =
 *   문법 축 1개). 지우면 「에」와 「에서」가, 「올게요」와 「오겠습니다」가 같은 답이 되어
 *   측정 자체가 죽는다. 내부 공백도 홑칸으로만 접지 없애지 않는다(띄어쓰기 오류는 산 신호다).
 *   - NFC: 모바일 IME·iOS 가 자모 분해형(NFD)을 낼 수 있다 — 같은 글자가 바이트만 달라
 *     「모름」으로 새는 것을 막는다.
 *   - 끝부호: 문장 끝 마침류(`.` `。` `．` `!` `！` `?` `？` `…`)만 뗀다 — 빈칸 답은 조사·어미라
 *     끝부호가 뜻을 가르지 않는다(G2 가 `?`·`!` 를 남긴 것과 갈리는 근거: 저쪽은 문장 전문
 *     대조라 물음표가 뜻을 바꾼다).
 *
 * ■ 판정 재현 — `채점기판본` 이 스냅샷에 실린다(§6-8 모듈층 · «재계산 가능한 파생»이라는
 *   `is_correct` 금지 논거의 담보 — 발주 G4 §9 위험 6). 이 파일의 규칙(정규화·갈래)이 바뀌는
 *   날 판본이 함께 오른다 — 안 올리면 「그날 학생에게 보인 판정」을 재현할 수 없게 된다.
 *
 * ■ 앱 즉시 표시 = 연출 · 저장 판정 = 서버 재채점(§6-0-4) — 두 자리가 이 «같은» 순수 함수를
 *   쓰라고 CJS 로 둔다(동봉 기전은 CJS 전용 · `tests/동봉CJS.test.js`).
 */

/** 채점 규칙의 판 — 정규화·갈래가 바뀌는 커밋에서만 오른다(위 머리말). */
const 채점기판본 = 'g4채점.v1';

/**
 * 정규화 — 머리말의 넷만. 그 이상도 이하도 하지 않는다.
 * ⚠ 끝부호를 뗀 뒤 trim 을 한 번 더 한다 — 「에서 .」처럼 부호 앞 공백이 남는 모양을 접는다.
 * @returns {string|null} 재료가 아니면 null(지어내지 않는다).
 */
function 정규화(글) {
  if (typeof 글 !== 'string') return null;
  return 글.normalize('NFC').trim().replace(/\s+/g, ' ').replace(/[.。．!！?？…]+$/, '').trim();
}

/* 집합 재료 검사 — 비배열·빈 배열·비문자열 원소는 전부 «못 쓸 재료»다(반쪽 판정 금지). */
function 집합인가(값) {
  if (!Array.isArray(값) || 값.length === 0) return false;
  for (const 원소 of 값) {
    if (typeof 원소 !== 'string' || 원소.trim() === '') return false;
  }
  return true;
}

/**
 * 3갈래 채점 — 스냅샷에 실린 그 턴의 `빈칸` 원소와 학생 원문으로 판정한다.
 *
 * @param {object} 빈칸 `task_snapshot.빈칸`(§6-8 모듈층 — 그 턴의 원소 1개).
 *        정답집합·오답집합·재는축이 이 안에 있다 — 행만으로 재채점이 서는 근거(§6-2 ⓑ).
 * @param {string} 원문 학생이 그 칸에 실제로 친 문자열(`body_original` 그대로 — 저장 전
 *        가공 금지는 저장층 규칙이고, 여기는 «대조 시점»이라 정규화를 지난다).
 * @returns {Readonly<{판정:'맞음'|'축오답'|'모름', 오류태그?:string}>|null}
 *        맞음 = `오류태그: '오류없음'`(계약 24종의 그 값) · 축오답 = 그 빈칸의 `재는축` ·
 *        모름 = **`오류태그` 키 자체가 없다**(§6-8 규칙 1 — 태그 0 은 빈 문자열이 아니라 부재다).
 *        못 쓸 재료면 null — 반쪽 판정을 지어내지 않는다.
 *
 * 갈래(순서가 뜻이다 — 정답 우선):
 *   ⓐ 정규화 후 정답집합 안 → 맞음. 허용 이형태 전부가 집합에 있는 것이 팩의 책임이다(§9-1).
 *   ⓑ 오답집합 안 → 축오답. 같은 축의 알려진 오답만 담겨 있어 태그가 정직하다.
 *   ⓒ 둘 다 밖 → 모름. 빈 입력도 여기다(닫힌 두 집합 밖) — 「모르겠어요」 버튼(skipped)은
 *      화면 몫의 별개 통로라 이 함수에 오지 않는다.
 */
function 채점(빈칸, 원문) {
  if (!빈칸 || typeof 빈칸 !== 'object' || Array.isArray(빈칸)) return null;
  if (typeof 빈칸.재는축 !== 'string' || 빈칸.재는축.trim() === '') return null;
  if (!집합인가(빈칸.정답집합) || !집합인가(빈칸.오답집합)) return null;
  const 답 = 정규화(원문);
  if (답 === null) return null;

  const 정답셋 = new Set();
  for (const 값 of 빈칸.정답집합) 정답셋.add(정규화(값));
  const 오답셋 = new Set();
  for (const 값 of 빈칸.오답집합) 오답셋.add(정규화(값));

  if (정답셋.has(답)) return Object.freeze({ 판정: '맞음', 오류태그: '오류없음' });
  if (오답셋.has(답)) return Object.freeze({ 판정: '축오답', 오류태그: 빈칸.재는축 });
  return Object.freeze({ 판정: '모름' });
}

module.exports = { 채점기판본, 정규화, 채점 };
