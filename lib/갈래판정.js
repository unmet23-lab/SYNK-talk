/* 갈래판정 — 「오늘 어느 갈래인가」의 우선순위 판정 «만» (순수 · 콘텐츠 0)
 *   (정본 = appsscript docs/상태기반_과제선택_설계.md §3-3 · 반환 모양도 그 절 그대로).
 *
 * ■ 왜 제 파일인가 — `policy_ver` 재료 7 이 **이 파일의 해시**다(§5-1 v5.3 V6-16: 「무엇을
 *   고를지 가르는 그 함수」가 재료에 없었다). 조립(`lib/오늘과제.js` — 재료 12)과 판이 갈려
 *   있어야 「판정 규칙만 고친 날」과 「학생이 받는 것(문장·스냅샷)만 고친 날」이 행에서 갈린다.
 * ■ 문장이 반환에 없는 이유 — 판정과 조립은 층이 다르다. 선판정(오케스트레이터)은 «갈래»만
 *   필요하고(③생성대상인가 · §3-4), 갈래→문장 매핑은 조립기(`오늘과제()`)가 콘텐츠 정본
 *   (`도입`)과 함께 진다. 문장을 여기 두면 콘텐츠 의존이 생겨 판정 파일 해시가 문구 수정에도
 *   오른다 — 갈래가 곧 문장을 결정하므로 정보 손실은 0 이다.
 * ■ 순서가 곧 우선순위다(§6-1 세 갈래 + §6-4 두 단계). `첫날` 이 교정문보다 앞이다 —
 *   배정 이력이 없는데 교정이 있는 상태는 데이터가 어긋난 것이고, 그때 「어제 교정문」을 내면
 *   그 학생의 첫 발화 기준선(§4-5 · 소급 불가)을 잃는다.
 *
 * ■ 🔴 2026-08-26 — 「예비」 갈래 신설 + 「전날」에 조건 (유호 지시 「혹시나 버그나 오류 때문에
 *   개인화 숙제를 못 받으면 예비용 과제라도 지급해야 한다」). 실측한 구멍 둘:
 *   ⓐ 사다리의 마지막 칸이 **1일차 자기소개 문장 하나**였다 —
 *      「안녕하세요. 저는 (이름)입니다. 몽골에서 왔습니다.」. 6개월 차 Lv6 학생도 그것을 받는다.
 *   ⓑ **「전날」이 어제도 강등이었는지를 안 봤다.** 그래서 장애가 사흘이면 **같은 문장이 사흘**
 *      나갔다 — 강등이 «반복»으로 수렴하는 자리였고, 어느 검사도 그것을 안 봤다.
 *   ⇒ 「전날」은 어제가 **진짜 과제**였을 때만 쓴다(생것 = 생성·교정문). 그 밖은 「예비」다.
 *      「예비」 풀은 유호님이 §8-B 채점에서 일곱 축 전부에 O 를 준 산출이다(`contents/예비과제.js`).
 *
 * ■ 🔑 `예비있음` 은 «불리언»으로 받는다 — 이 파일은 콘텐츠를 모른다(머리말 규율).
 *   부르는 쪽이 `lib/예비과제.있나(급수)` 로 계산해 넘긴다. 초급(Lv1~2)·미정은 검증된 문장이
 *   0벌이라 false 가 오고, 그때는 예전처럼 도입 폴백이다(없는 것을 지어내지 않는다).
 * ■ ⚠ 안전한 방향 — `전날출처` 를 못 받거나 모르는 값이면 «전날»이 아니라 **예비**로 간다.
 *   미지를 「전날」로 접으면 구멍 ⓑ 가 조용히 남는다(새는 방향이 언제나 통과인 자리).
 *
 * @param {object} 재료 { 첫날?, 교정문?, 전날문장?, 전날출처?, 예비있음? } — `오늘과제()` 와 같은 칸
 * @returns {{갈래: '첫날'|'교정문'|'전날'|'예비'|'도입폴백', 출처: string, degraded: boolean}}
 */
'use strict';

/* 「어제 그 문장이 «진짜 오늘의 과제»였나」 — 이 둘만 복습할 값이 있다(생성 = AI 산출 ·
 * 교정문 = 그 학생 자기 문장). '전날'·'예비'·'도입' 은 그 자체가 강등이라 되풀이하면 안 된다. */
const 생것출처 = Object.freeze(['생성', '교정문']);

function 갈래판정(재료) {
  const { 첫날 = false, 교정문 = null, 전날문장 = null, 전날출처 = null, 예비있음 = false } = 재료 || {};
  if (첫날) return { 갈래: '첫날', 출처: '도입', degraded: false };
  if (교정문) return { 갈래: '교정문', 출처: '교정문', degraded: false };
  if (전날문장 && 생것출처.includes(String(전날출처))) return { 갈래: '전날', 출처: '전날', degraded: true };
  if (예비있음) return { 갈래: '예비', 출처: '예비', degraded: true };
  return { 갈래: '도입폴백', 출처: '도입', degraded: true };
}

/* 우선순위 «순서»의 리터럴 배열 — `policy_ver` 재료 3(폴백 순서 · §5-1 v5.9: 단계 리터럴
 * 배열의 JSON.stringify 가 지문 원소다). 위 갈래의 순서와 같은 하나여야 하고, 그 동치는
 * `tests/오늘과제.test.js` 행동 지문이 문다(순서가 바뀌면 행동이 바뀐다). */
const 갈래순서 = Object.freeze(['첫날', '교정문', '전날', '예비', '도입폴백']);

module.exports = { 갈래판정, 갈래순서, 생것출처 };
