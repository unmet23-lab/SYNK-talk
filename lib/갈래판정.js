/* 갈래판정 — 「오늘 어느 갈래인가」의 우선순위 판정 «만» (순수 · 콘텐츠 0)
 *   (정본 = appsscript docs/상태기반_과제선택_설계.md §3-3 · 반환 모양도 그 절 그대로).
 *
 * ■ 왜 제 파일인가 — `policy_ver` 재료 7 이 **이 파일의 해시**다(§5-1 v5.3 V6-16: 「무엇을
 *   고를지 가르는 그 함수」가 재료에 없었다). 조립(`lib/오늘과제.js` — 재료 12)과 판이 갈려
 *   있어야 「판정 규칙만 고친 날」과 「학생이 받는 것(문장·스냅샷)만 고친 날」이 행에서 갈린다.
 * ■ 문장이 반환에 없는 이유 — 판정과 조립은 층이 다르다. 선판정(오케스트레이터)은 «갈래»만
 *   필요하고(③생성대상인가 · §3-4), 갈래→문장 매핑은 조립기(`오늘과제()`)가 콘텐츠 정본
 *   (`도입`)과 함께 진다. 문장을 여기 두면 콘텐츠 의존이 생겨 판정 파일 해시가 문구 수정에도
 *   오른다 — 갈래가 곧 문장을 결정하므로 정보 손실은 0 이다.
 * ■ 순서가 곧 우선순위다(§6-1 세 갈래 + §6-4 두 단계). `첫날` 이 교정문보다 앞이다 —
 *   배정 이력이 없는데 교정이 있는 상태는 데이터가 어긋난 것이고, 그때 「어제 교정문」을 내면
 *   그 학생의 첫 발화 기준선(§4-5 · 소급 불가)을 잃는다.
 * ■ 행동은 #2 리팩터(161ac67) 그대로다 — `tests/오늘과제.test.js` 행동 지문(판 v3)이 증인.
 *
 * @param {object} 재료 { 첫날?, 교정문?, 전날문장? } — `오늘과제()` 와 같은 칸을 읽는다
 * @returns {{갈래: '첫날'|'교정문'|'전날'|'도입폴백', 출처: string, degraded: boolean}}
 */
'use strict';

function 갈래판정(재료) {
  const { 첫날 = false, 교정문 = null, 전날문장 = null } = 재료 || {};
  return 첫날 ? { 갈래: '첫날', 출처: '도입', degraded: false }
    : 교정문 ? { 갈래: '교정문', 출처: '교정문', degraded: false }
    : 전날문장 ? { 갈래: '전날', 출처: '전날', degraded: true }
    : { 갈래: '도입폴백', 출처: '도입', degraded: true };
}

module.exports = { 갈래판정 };
