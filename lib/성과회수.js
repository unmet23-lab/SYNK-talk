'use strict';
/**
 * 성과 회수 — 개입 하나 → **닿았나 · 그 뒤에 무엇이 달라졌나**. 순수 함수만(DB·네트워크 0).
 *
 * ■ 이 파일이 닫는 것 — 사슬 ⑦의 «남은 절반»
 *   `lib/학습자상태.js` 가 다섯 사건을 경로 A 로 닿게 하면서 래칫이 13→8·7→2 로 내려갔고,
 *   남은 둘이 `intervention.delivered`·`content.viewed` 다. 그 둘은 스탬프를 **받기만** 하는
 *   행이었다 — 그 행을 **읽는 코드가 저장소에 0줄**이라 「무엇이 통했는지」가 계산되지 않았다.
 *   엔진도달_설계 §5 가 도달의 정의를 «읽힌 것»으로 못박았으므로, 받는 것만으로는 도달이 아니다.
 *
 * ■ 왜 이 짝이 최상위인가 (제품방향 불변식 6 · 유호님 채택 2026-08-08)
 *   코어엔진 §10: *"학생 상태 → AI가 고른 지도 방식 → 학생 반응 → 즉시 성과 → 1·7·30일 뒤
 *   유지 성과."* 오류 데이터는 남들도 모으지만 **개입-효과 데이터는 개입을 실제로 한 곳만**
 *   가진다. 이것이 쌓이면 엔진이 「한국어」가 아니라 **「가르치는 법」**을 배운다.
 *
 * ■ 🔴 표도 뷰도 만들지 않는다 — `학습자상태.js` 와 **같은 판정**
 *   코어엔진 §10 이 *"C(학습자 상태)·D(개입·성과 집계)는 테이블조차 지금 만들지 않는다"* 를
 *   유호님 확정으로 걸어 두었다. 그래서 여기서도 계산만 하고 **아무것도 저장하지 않는다**.
 *   잃는 것이 없다 — 원신호가 남아 있으므로 성과는 언제든 다시 계산된다. 저장하면 반대로
 *   「이 개입은 효과 없음」이라는 **틀린 낙인이 굳는다**(코어엔진 §원칙1).
 *
 * ■ 🔴 「아직 안 왔다」와 「효과가 0이다」는 다른 값이다
 *   개입 이틀 뒤에 7일 창을 물으면 답은 0 이 아니라 **`미도래`** 다. 0 으로 접으면 개원 첫 달의
 *   모든 개입이 「30일 효과 없음」으로 쌓이고, 그 오독은 소급으로 못 고친다 — 값만 보고는
 *   재료가 없었던 것인지 효과가 없었던 것인지 갈 수 없기 때문이다. 표본이 0인 창(`표본0`)도
 *   같은 이유로 `null` 이고, **사유를 함께 낸다**(학습자상태의 「분모 0 은 null」과 같은 축).
 *
 * ■ 🔴 `이전`과 `이후`를 **빼지 않는다** — 증감 칸이 일부러 없다
 *   `이전` 은 개입 «전» 30일 추세이고 `이후` 는 개입 «뒤» N일만 본다. 창 길이가 다르니
 *   두 값의 뺄셈은 산술적으로 뜻이 없다 — 그런데 `증감` 이라는 칸을 하나 내면 읽는 쪽은
 *   반드시 뺀다. 그래서 두 값을 **나란히** 내고 창 길이를 각각 적는다(비교지 계산이 아니다).
 *   ⚠ 같은 창으로 양쪽을 재는 안은 기각했다: 30일 추세는 하루치 새 데이터로 거의 안 움직여
 *   「1일 성과」가 **구조적으로 0** 이 된다(민감도가 원리상 없다). 재는 층을 바꾼 것이지
 *   눈금을 느슨하게 한 것이 아니다.
 *
 * ■ 🔑 관측 짝의 고리는 `intervention_id` 가 **아니라** `parent_event_id` 다
 *   계약 c9 원문: *"대상은 이미 있는 이름으로 가리킨다(`parent_event_id` = 무엇을 봤나)"*.
 *   `intervention_id` 는 개입 행 «자신»의 출처 칸이라 관측 행에는 안 실린다. 여기를 헷갈리면
 *   관측이 영원히 0건이고 증상은 「아무도 안 본다」 하나뿐이다.
 */

const { 학습자상태, 쓰는사건: 상태가쓰는사건 } = require('./학습자상태.js');

/* 회수 알고리즘의 판. 🔴 `학습자상태.추정판` 과 **따로** 둔다 — 창 정의·관측 규칙은 여기서
 * 바뀌고 축 정의는 저기서 바뀌므로, 한 이름에 묶으면 어느 쪽이 바뀌어 값이 달라졌는지
 * 영원히 못 가른다. 창·관측·미도래 규칙 중 하나라도 고치면 이 판을 올린다. */
const 회수판 = '성과회수.v1';

/* 이 파일이 닿는 엔진 코어 부품(4부품 중 ④). 개입을 «고르는» 것이 게이트웨이이고
 * 이 파일은 그 선택을 평가해 되먹인다 — 엔진도달_설계 §2 표 ④행.
 * 🔑 주석이 아니라 **상수**인 이유는 `lib/이벤트검증.js 낡은도달` 이 이 파일 원문에서 이
 *   낱말을 찾기 때문이다. 주석에 두면 줄바꿈 하나로 조용히 깨진다(학습자상태.js 가 실제로 겪었다). */
const 부품 = 'AI 게이트웨이';

/* 되돌아보는 기준선 창(일). `학습자상태.창일수` 와 같은 눈금을 **일부러** 쓴다 —
 * 기준선은 「평소의 그 학생」이고, 그 정의가 두 파일에서 갈리면 같은 학생이 두 값을 갖는다. */
const 기준선창 = 30;

/* 회수의 **닻**이 되는 사건. 🔑 부르는 쪽이 여기서 파생시킨다 — 질의·필터에 이 문자열을 다시
 * 적으면 이름이 바뀐 날 필터는 0건을 고르고 증상은 「개입이 없다」 하나뿐이다(아래 `쓰는사건`
 * 과 같은 이유 · `학습자상태.쓰는사건` 이 세운 규칙 그대로). */
const 닻사건 = 'intervention.delivered';

/* 회수 창(일). 코어엔진 §10 의 「즉시·1·7·30일」 그대로다. 🔴 늘리거나 줄이면 `회수판` 을
 * 올린다 — 창이 다른 값들이 같은 이름표를 달고 섞이면 대조가 아무것도 증명하지 못한다. */
const 회수창 = Object.freeze([1, 7, 30]);

/* 이 모듈이 실제로 읽는 `event_type`. **부르는 쪽이 여기서 파생시킨다** — 질의에 목록을 다시
 * 적으면 창을 하나 늘린 날 코드는 세려는데 질의가 안 실어 주고, 증상은 「효과 없음」뿐이다. */
const 쓰는사건 = Object.freeze([
  닻사건,                   // 처치 — 회수의 닻(개입 ID·시각)
  'content.viewed',         // 관측 짝 — 실제로 눈이 닿았나
  ...상태가쓰는사건,        // 이후 상태를 계산할 재료(축 셋)
]);

const 일 = 24 * 60 * 60 * 1000;

/** ISO·Date → 밀리초. 못 읽으면 `null`(0 으로 접으면 1970년이 근거가 된다). */
function 때(v) {
  if (v == null) return null;
  const ms = v instanceof Date ? v.getTime() : Date.parse(String(v));
  return Number.isFinite(ms) ? ms : null;
}

/** 소수 자리 고정 — 없는 정밀도를 주장하지 않는다. */
const 자리 = (n, 몇 = 2) => (n == null ? null : Math.round(n * 10 ** 몇) / 10 ** 몇);

/**
 * 개입 하나의 성과 회수.
 *
 * @param {object} 개입 `intervention.delivered` 행 —
 *   `{event_id, event_type, occurred_at, learner_id?, intervention_id?, policy_ver?, estimator_version?}`.
 * @param {Array<object>} 사건들 그 학습자의 원신호 행(개입 전후 모두). 순서는 안 가린다.
 * @param {{기준시각: string|Date}} 옵션 `기준시각` **필수** — 「지금 어디까지 아는가」.
 *   🔴 기본값을 안 준다: 기본값이 있으면 과거를 재계산할 때 미도래 판정이 조용히 어긋나고,
 *   그 오염은 값만 보고는 알 수 없다(`학습자상태.as_of` 와 같은 이유 · 설계 §3 의 P0).
 * @returns {{intervention_id, event_id, 회수판, 관측, 성과, evidence_refs}}
 */
function 성과회수(개입, 사건들, 옵션) {
  if (!개입 || 개입.event_type !== 닻사건) {
    /* 🔴 던진다 — 다른 사건을 닻으로 받으면 「효과 0」이 조용히 쌓인다. 개입이 아닌 행에는
     *   붙일 성과가 없다는 것과, 성과가 없다는 것은 다른 사실이다. */
    throw new Error('성과회수: 닻은 intervention.delivered 행이어야 한다');
  }
  const 개입때 = 때(개입.occurred_at);
  if (개입때 == null) throw new Error('성과회수: 개입의 occurred_at 을 못 읽었다');

  const 기준 = 때(옵션 && 옵션.기준시각);
  if (기준 == null) {
    throw new Error('성과회수: 기준시각이 필요하다 — 없으면 「아직 안 왔다」를 「효과 0」과 못 가른다');
  }

  const 행들 = (Array.isArray(사건들) ? 사건들 : [])
    .map((e) => ({ ...e, _때: 때(e && e.occurred_at) }))
    .filter((e) => e._때 != null);

  return {
    /* 개입 ID 는 코어엔진 §10 이 「소급 불가」로 지목한 유일한 고리다 — 없으면 나중에
     * 성과를 이어붙일 수 없다. 값이 비어 있으면 그 사실을 그대로 낸다(지어내지 않는다). */
    intervention_id: 개입.intervention_id != null ? String(개입.intervention_id) : null,
    event_id: 개입.event_id != null ? String(개입.event_id) : null,
    회수판,
    관측: 관측짝(개입, 행들, 개입때),
    성과: 창별성과(행들, 개입때, 기준),
    evidence_refs: {
      개입시각: new Date(개입때).toISOString(),
      기준시각: new Date(기준).toISOString(),
      기준선창,
      회수창: [...회수창],
      /* 개입을 «고른» 규칙을 그대로 실어 둔다 — 성과를 규칙별로 갈라 보려면 이 짝이 필요하고,
       * 개입 행에 없으면 `null` 이다(정책 판의 생산자는 아직 0이다 · 대기열 P1). */
      policy_ver: 개입.policy_ver != null ? String(개입.policy_ver) : null,
      estimator_version: 개입.estimator_version != null ? String(개입.estimator_version) : null,
    },
  };
}

/* ── 즉시 — 「닿았나」. 추정(배달했다)을 관측(눈이 닿았다)으로 확인하는 칸이다.
 *
 * 🔴 이 칸이 없으면 **네트워크 실패가 「전달 완료」로 학습된다**(계약 c9 원문). 배달은
 *   전날 밤 배치의 추정이고(`lib/사건출처.js` 가 `inferred` 로 박는 자리), 관측 짝만이
 *   그것을 사실로 바꾼다.
 * 🔑 고리는 `parent_event_id` — 계약 c9 가 「무엇을 봤나」로 정의한 이름이다. */
function 관측짝(개입, 행들, 개입때) {
  const 닻 = 개입.event_id != null ? String(개입.event_id) : null;
  if (닻 == null) {
    return { 닿음: null, 사유: '개입 행에 event_id 가 없다 — 관측을 이을 고리가 없다' };
  }

  const 본것 = 행들
    .filter((e) => e.event_type === 'content.viewed'
      && e.parent_event_id != null && String(e.parent_event_id) === 닻)
    /* 개입 «이전»의 관측은 이 개입의 것이 아니다 — 같은 행이 다른 개입의 짝일 수 있다. */
    .filter((e) => e._때 >= 개입때)
    .sort((a, b) => a._때 - b._때);

  if (!본것.length) {
    /* ⚠ `닿음:false` 는 「안 봤다」가 아니라 「봤다는 기록이 없다」다. 관측 생산자가 아직
     *   한 화면뿐이라(`lib/오늘과제.js`) 화면을 안 거친 배달은 원리상 관측이 0건이다.
     *   그 구분을 사유로 남긴다 — 안 남기면 미구현이 「학생이 무시했다」로 읽힌다. */
    return { 닿음: false, 사유: '관측 행 없음(미열람 xor 관측 생산자 미배선)' };
  }

  const 첫 = 본것[0];
  return {
    닿음: true,
    관측_event_id: 첫.event_id != null ? String(첫.event_id) : null,
    /* 배달→열람 지연. 「얼마나 빨리 반응했나」가 즉시 성과의 실체다. */
    지연분: 자리((첫._때 - 개입때) / (60 * 1000), 1),
    관측수: 본것.length,
  };
}

/* ── 1·7·30일 — 「그 뒤에 무엇이 달라졌나」.
 *
 * 각 창은 `{이전, 이후}` 한 쌍이다. `이전` = 개입 직전 기준선(30일 추세 · `as_of ≤ 개입시각`
 * 이라 미래정보가 원리상 안 섞인다) · `이후` = 개입 뒤 N일 **만** 본 상태.
 * 🔴 뺄셈 칸은 일부러 없다(머리말 참조). */
function 창별성과(행들, 개입때, 기준) {
  /* 기준선은 창마다 다시 계산하지 않는다 — 같은 시점·같은 규칙이라 값이 같고,
   * 다시 계산하면 세 번 도는 동안 하나만 달라져도 아무도 못 알아챈다. */
  const 이전 = 학습자상태(행들, { as_of: new Date(개입때), 창: 기준선창 });

  const 성과 = {};
  for (const 일수 of 회수창) {
    const 끝 = 개입때 + 일수 * 일;
    if (기준 < 끝) {
      /* 🔴 미도래 — 0 이 아니다. 언제 다시 물으면 되는지까지 낸다(다시 물을 시각을 모르면
       *   호출부는 매번 전량을 되돌린다). */
      성과[`${일수}일`] = { 상태: '미도래', 잴수있는때: new Date(끝).toISOString() };
      continue;
    }
    const 이후 = 학습자상태(행들, { as_of: new Date(끝), 창: 일수 });
    성과[`${일수}일`] = {
      상태: 이후.estimator_confidence > 0 ? '측정' : '표본0',
      이전: { 창일수: 기준선창, 축: 이전.축, 표본충분도: 이전.estimator_confidence },
      이후: { 창일수: 일수, 축: 이후.축, 표본충분도: 이후.estimator_confidence },
    };
  }
  return 성과;
}

module.exports = { 성과회수, 회수판, 부품, 기준선창, 회수창, 쓰는사건, 닻사건 };
