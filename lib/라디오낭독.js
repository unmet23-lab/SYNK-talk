'use strict';
/**
 * 라디오 「오늘의 표현」 낭독 통로 — 판정층 (라디오24 발전 트랙 ④ · 설계 §2-2 ⓖ · §7-2 ㉢).
 *
 * ■ 이 통로가 닫는 것 — 라디오의 **음성 축은 0이었다**
 *   설계 §2-1 실측: 14 기능 중 음성 기여 0. `!말하기` 는 앱 딥링크뿐이라 **라디오가 유도한
 *   발화와 그냥 앱에서 한 발화를 가르는 고리가 없었고**, 그래서 「라디오가 말하기를 늘렸나」를
 *   영원히 못 물었다(§7-2 ㉢). ⓖ 낭독이 그 고리다: 카드 `content_ref` 를 발화 `task_ref` 로
 *   그대로 들면 **「방송에서 본 표현 → 그날 그 표현의 발화」** 쌍이 선다.
 *
 * ■ 🔴 그 쌍은 **송출이 있어야만** 선다 — 그래서 출처를 행에 적는다
 *   지금 송출은 0 이고(P1 ⏳ — **채널은 09-01 에 섰다**: SYNK LAB `@synkkorean`.
 *   남은 것은 라이브 액세스(09-02 22:21 해제)와 VPS 뿐이다), `radio.subtitle_card_log` 는 빈다. 그런데 통로를
 *   그때까지 안 세우면 음성 축은 계속 0 이고, 수집은 소급이 안 된다.
 *   그래서 **두 출처를 다 받되 한 칸으로 가른다**:
 *     · 방송 유래 = 그날 실제로 화면에 떠 있던 카드   → 판 `radio-card.v1`(승격기와 같은 이름)
 *     · 팩 회전   = 방송 전, 날짜 씨앗으로 고른 카드   → 판 `radio-pack.v1`
 *   🔑 **가르지 않고 합치면 그게 곧 날조다** — 송출 전에 읽은 것을 「방송에서 봤다」로 세면
 *   §2-B 가 못 하던 「누가 봤나」를 발화가 대신 증명한다는 이 트랙의 근거 자체가 거짓이 된다.
 *   🔑 반대로 팩 유래를 **안 만드는** 것도 답이 아니다: 그러면 낭독 통로는 첫 송출이 나갈
 *   때까지 「부르는 곳 없는 소비자」로 남고, 그동안 음성 축은 0 인 채로 지나간다.
 *
 * ■ 🔴 이 판이 리듬·끈기축을 **오염시킬 수 있다** — 판 축이 그 자물쇠다
 *   낭독은 앱 어휘(`task_type='발화녹음'`)를 그대로 쓴다(설계 ⓖ · 계약 개정 0). 그런데
 *   `lib/학습자상태.js` 의 리듬축은 **배정 구간 안의 첫 제출**을 그 배정의 것으로 읽으므로,
 *   표식이 없으면 「숙제를 안 낸 날」이 낭독 한 번으로 **「냈다」로 뒤집힌다** — 반박 c757278
 *   치명 ① 이 목표선언·자습체크인에서 잡았던 바로 그 역오염이고, ⓖ 는 그 반박(08-12)보다
 *   먼저 쓰인 설계라 이 구멍을 아직 안 봤다.
 *   🔑 그래서 모든 낭독 행은 **첫 행부터** 판을 들고 나간다. 판별 정본은
 *   `lib/라디오태스크.js` 하나이고(두 곳에 적으면 갈라진다), 읽는 쪽은 거기서 판정을 받는다.
 *   ⚠ 판을 지금 안 실으면 나중에 못 고친다 — 행은 불변이라 「이건 라디오였다」를 소급해서
 *   못 적는다. 읽는 쪽 필터는 나중에도 고칠 수 있지만, **행에 없는 사실은 영영 없다.**
 *
 * ■ 기준시각·시간대는 **인자다** — 여기서 시계를 읽지 않는다
 *   안에서 `new Date()` 를 부르면 회귀가 돌린 날에 따라 답이 갈리고, 시간대를 기본값으로
 *   적으면 날짜 경계가 두 곳에 산다(`lib/학습자상태.js` ①머리말과 같은 규칙).
 *
 * ■ 이 파일이 **안** 하는 것
 *   · 원장에 쓰지 않는다 — `subtitle_card_log` 는 「화면에 떴다」의 기록이라, 송출 없이 적으면
 *     안 보여준 것을 보여줬다고 적는 행이 된다(P3 라운드 생성기가 ⛔선행인 것과 같은 이유).
 *   · 사건을 조립하지 않는다 — 봉투는 `lib/오늘과제.제출사건` 하나가 만든다. 여기서 또 만들면
 *     같은 어휘를 아는 곳이 둘이 되고, 갈라지는 날 증상은 「거절」이 아니라 **엉뚱한 형식으로
 *     저장되는 것**이다(오늘과제.js:616 이 이미 못박은 자리).
 */

const { 몽골날짜 } = require('./몽골날짜.js');
const { 눈금 } = require('./라디오라운드.js');
const 팩 = require('../contents/자막카드.js');
const 걸음이름 = require('./걸음.js');

/** 방송 유래 — 승격기(`lib/라디오승격.js`)가 자막 카드에 쓰는 그 이름. 같은 뜻이면 같은 이름. */
const 방송판 = 'radio-card.v1';
/** 팩 회전 유래 — 「방송에서 본 것이 아니다」의 정직 표기. 접두 `radio-` 가 판별의 열쇠다. */
const 팩판 = 'radio-pack.v1';

/** 제출 로그 항목의 `step`. 그날 배정의 «호흡»이 아니라 자기 통로라 이름이 따로다.
 * 🔴 **이름의 정본은 `lib/걸음.js`** — 여기서 문자열을 다시 적었더니 문지기(`제출로그.항목추가`)가
 *   모르는 이름이 되어 낭독 제출이 08-14 부터 전건 던지고 있었다(08-26 실측·수리). */
const 낭독걸음 = 걸음이름.라디오낭독;

/**
 * ISO·Date·밀리초 → 밀리초. 못 읽으면 null(0 으로 접으면 1970년이 근거가 된다 · 학습자상태와 같은 규칙).
 *
 * 🔴 **숫자 갈래가 따로 있는 이유**(회귀가 잡은 실제 버그 · 2026-08-14): 이 함수가 숫자를
 *   `String()` 으로 돌리면 `Date.parse('1755165600000')` 이 **NaN** 이다. 그러면 한 번 파싱해
 *   둔 시각을 다시 넘기는 자리에서 전 후보가 걸러지고, 증상은 예외가 아니라 **「방송 카드가
 *   하나도 없다」로 조용히 팩 경로로 내려가는 것**이다 — 송출이 켜진 날에야, 그것도 「팩이
 *   도는데 왜 방송 카드가 안 잡히지」로만 보인다.
 */
function 때(v) {
  if (v == null) return null;
  if (typeof v === 'number') return Number.isFinite(v) ? v : null;
  const ms = v instanceof Date ? v.getTime() : Date.parse(String(v));
  return Number.isFinite(ms) ? ms : null;
}

/**
 * 그 시각에 **화면에 떠 있던** 카드 — 원장 행에서 고른다.
 *
 * 🔑 규칙은 `lib/라디오승격.카드찾기` 와 **같아야 한다**(반박 ⑤): 겹치는 표시 창이면 가장
 *   최근에 뜬 것이 그때 화면에 있던 것이고, 동률은 `content_ref` 로 끊는다. 두 곳이 다른
 *   규칙을 쓰면 같은 순간에 대해 승격기와 앱이 **다른 카드**를 가리키고, 그 어긋남은 행이
 *   쌓인 뒤에야 보인다.
 * 🚫 `localeCompare` 금지(재반박 ⑨) — 로케일·정규화에 따라 0 을 돌려주면 입력 순서로 되돌아간다.
 */
function 방송카드(원장카드들, 기준시각) {
  const 시각 = 때(기준시각);
  if (시각 == null) return null;
  const 후보 = (Array.isArray(원장카드들) ? 원장카드들 : [])
    .filter((c) => c && 때(c.shown_from) != null && 때(c.shown_from) <= 시각
      && (c.shown_to == null || 시각 < 때(c.shown_to)))
    .sort((a, b) => (때(b.shown_from) - 때(a.shown_from))
      || (String(b.content_ref) < String(a.content_ref) ? -1 : 1));
  return 후보.length ? 후보[0] : null;
}

/**
 * 팩 회전 — 그날의 카드를 **날짜 씨앗**으로 고른다(송출 전 경로).
 *
 * 🔑 난수가 아니라 씨앗인 이유는 `lib/라디오라운드.js` 와 같다 — 회귀가 분포가 아니라 **값**으로
 *   잰다. 분포 검사는 플레이크고, 플레이크 검사는 결국 아무도 안 본다.
 * 🔑 **정렬 후 고른다** — 팩 순서에 기대면 카드를 하나 끼워 넣은 날 «그 뒤 전부»가 다른 날짜로
 *   밀리는데 증상이 없다(반박 ⑤ 「정렬 없는 누적」과 같은 축).
 * 🔑 하루 = 한 장이다. 같은 날 다시 열어도 같은 카드가 나와야 「오늘의 표현」이 성립한다.
 */
function 팩카드(날짜, 카드들 = 팩.카드들) {
  const d = String(날짜 ?? '');
  if (!d) return null;
  /* 🔑 `카드들` 이 인자인 이유는 **정렬이 실제로 일하는지 잴 수 있게** 하기 위해서다.
   *   팩이 이미 id 순으로 적혀 있어서, 이 정렬을 지워도 회귀는 초록이다 — 「뒤집어도 우연히
   *   같은 것이 걸리는」 시험이 되는 자리다(`lib/라디오라운드.js` 가 변이 시험에서 놓쳤던 그 모양).
   *   섞인 팩을 먹여 같은 답이 나오는지 보면 그 우연이 걷힌다. */
  const 후보 = [...카드들].sort((a, b) => (a.카드id < b.카드id ? -1 : a.카드id > b.카드id ? 1 : 0));
  if (!후보.length) return null;
  /* 씨앗에 팩 이름을 섞는다 — 같은 날짜로 다른 팩(퀴즈 라운드)을 뽑는 자리와 값이 겹치면
   * 두 팩이 늘 같은 자리를 고른다(상관이 생기고, 그 상관은 우연처럼 보인다). */
  const i = Math.floor(눈금(`자막카드:${d}`) * 후보.length);
  return 후보[Math.min(i, 후보.length - 1)];
}

/**
 * 오늘의 낭독 과업 한 벌.
 *
 * @param {object} 재료
 *   `기준시각`   {string|Date|number} **필수** — 이 시각으로 방송 카드를 고른다.
 *   `날짜`       {string} `YYYY-MM-DD`(몽골 기준). 주면 **팩 회전은 이 날짜로** 돈다.
 *     🔑 있는 이유 = **기기 시계를 안 믿는다**(C0 §3). 앱은 서버가 준 날짜를 들고 있는데,
 *       그것을 안 쓰고 기기 시각으로 접으면 자정 언저리에 서버와 앱이 «다른 오늘»을 고르고,
 *       그날 학생은 어제 표현을 「오늘의 표현」으로 읽는다. 안 주면 기준시각으로 접는다.
 *     ⚠ 방송 카드 고르기는 이 값을 안 쓴다 — 거긴 「그 순간 화면에 떠 있었나」라 날짜가 아니라
 *       시각의 문제다(창이 자정을 넘길 수 있다).
 *   `원장카드들` {Array}  `radio.subtitle_card_log` 행들(없으면 팩 회전으로 내려간다).
 *   `level_snapshot`·`goal_snapshot` 그때 화면이 알던 값 — 항목이 들고 가야 사흘 밀려도 그날 값이다.
 * @returns {{content_ref: string, 카드: object|null, 판: string, 출처: '방송'|'팩',
 *   task_meta: object}|null} 팩이 비었고 방송 카드도 없으면 `null` — **지어내지 않는다.**
 */
function 오늘의낭독(재료) {
  const { 기준시각, 날짜 = null, 원장카드들 = [],
    level_snapshot = null, goal_snapshot = null } = 재료 || {};
  const 시각 = 때(기준시각);
  /* 🔴 던진다 — 기본값으로 「지금」을 쓰면 회귀가 돌린 날에 따라 답이 갈리고, 그 갈림은
   *   값만 보고는 알 수 없다(`학습자상태` 의 `as_of` 와 같은 판정). */
  if (시각 == null) throw new TypeError('오늘의낭독: 기준시각이 필요하다 — 여기서 시계를 읽지 않는다');

  const 방송 = 방송카드(원장카드들, 시각);
  if (방송) {
    /* 원장 행의 스냅샷을 **그대로** 싣는다 — 그때 화면에 뜬 문안이 곧 그때 학생이 본 것이다.
     * 팩에서 다시 조립하면 그 사이 문안을 고친 날 「본 것」과 「적힌 것」이 갈린다(불변 위반). */
    return {
      content_ref: String(방송.content_ref),
      카드: 팩.참조로찾기(방송.content_ref), // 팩에 없어도 된다(옛 카드) — 스냅샷이 정본이라 null 이 정상
      판: 방송판,
      출처: '방송',
      task_meta: 과업(String(방송.content_ref), 방송.content_snapshot, 방송판, level_snapshot, goal_snapshot),
    };
  }

  const 카드 = 팩카드(날짜 || 몽골날짜(new Date(시각)));
  if (!카드) return null; // 팩이 비었다 — 없는 과업을 지어내지 않는다
  return {
    content_ref: 팩.카드참조(카드.카드id),
    카드,
    판: 팩판,
    출처: '팩',
    task_meta: 과업(팩.카드참조(카드.카드id), 팩.카드스냅샷(카드), 팩판, level_snapshot, goal_snapshot),
  };
}

/**
 * `task_meta` — `lib/오늘과제.제출사건` 이 읽는 모양 **그대로**다.
 * (`lib/알바변명제출.제출재료` 와 같은 규약 — 봉투를 만드는 곳은 끝까지 한 곳이다.)
 */
function 과업(task_ref, task_snapshot, 판, level_snapshot, goal_snapshot) {
  return {
    task_ref,
    task_snapshot,
    /* 🔴 이 한 칸이 리듬·끈기축의 자물쇠다(위 머리말) — 빠지면 낭독이 숙제 제출로 세어진다. */
    task_schema_ver: 판,
    /* 형식은 걸음별 표다 — `제출사건` 이 `재료.형식[항목.step]` 으로 읽는다. 낭독 하나뿐이라도
     * 표로 두는 이유는 그 규약이 갈라지지 않게 하기 위해서다(모양이 다르면 읽는 쪽이 분기한다). */
    형식: { [낭독걸음]: '낭독' },
    level_snapshot,
    goal_snapshot,
  };
}

module.exports = { 방송판, 팩판, 낭독걸음, 방송카드, 팩카드, 오늘의낭독 };
