/* 생성상수 — 상태기반 과제 생성의 실행 상수 «한 원천»
 *   (정본 = appsscript docs/상태기반_과제선택_설계.md §3-2 상수 표 · §3-2-a cron 표 · 2026-08-21).
 *
 * ■ 전부 `policy_ver` 재료다(재료 4·5·9 — §5-1) — 값을 바꾸면 판이 오른다. 초기값은 측정 전
 *   «안전선»이지 최적값이 아니다(P0-L — 첫 리허설 실측이 서면 갱신하고 판을 올린다).
 * ■ SQL 층의 사본 둘과 기계로 붙는다(두 곳에 적힌 판정은 갈라진다 — 대조는 tests 몫):
 *   · 배달마감 = engine.gen_deadline(마이그 20260821120000) — 다음날 06:00(몽골 시간대)
 *   · 리더 여유 = engine.gen_leader_grace() — 900000ms
 *   · 회전식 = jobs_claim 의 그 SQL 표현식 전문(아래 리터럴 ↔ 마이그 원문 부분일치 대조)
 * ■ cron 표는 «활성 조각»의 등록 SQL 과 §12-21 이 대조할 값이다 — 여기가 코드 쪽 정본이고,
 *   활성 전에는 어떤 잡도 이 표를 안 읽는다(§3-2-a C5). */
'use strict';
const { 시간대 } = require('./몽골날짜.js');   // 시간대 손기입 금지 — 한 원천(그 파일 규율)

const 생성타임아웃_MS = 20000;   // 학생 1명당 벤더 대기 상한 — 넘으면 그 학생만 2단 폴백
const 워커예산_MS = 100000;      // 한 워커 호출의 자기 예산 — 소진되면 남은 학생은 큐에 그대로
const 적재예산_MS = 100000;      // 오케스트레이터 자기 예산 — 소진되면 ㉠ 를 «안 부르고» 끝낸다
const 실행리더여유_MS = 900000;  // 미완 배치 실행을 「살아 있다」로 보는 창(15분 · ⓪·②-b 공용)
const 배치실행상한_일 = 6;       // 한 날짜의 배치 실행 행 상한(ⓒ-12 — 그날 자동 복구의 포기 선)
const 임대_초 = 1800;            // jobs_claim 의 _lease_sec 초기값(㉥ — 워커 예산의 넉넉한 배수)
const 배달마감_시각 = `06:00 ${시간대}`;   // 배정일 «다음날» — SQL 정본 = gen_deadline
const 중복창_일 = 14;            // §8 중복 검사의 창 — lib/과제검문.js 와 같은 값(그쪽이 검문 정본)

/* 워커학생상한 — 손으로 적지 않는다(§3-2 ⚠): 150초 응답 상한에서 폴백 여유를 빼고
 * 타임아웃으로 나눈 내림. 타임아웃을 올리면 이 값이 «같이» 내려간다 — 한쪽만 바뀐 날
 * 조용히 깨지고 증상은 「가끔 504」다. 지금 값 = (150000−20000−100000? 아니다) —
 * 계산식의 정본은 표다: 플랫폼 150초 중 폴백 여유 ≥20초 · 미측정 항은 보수적으로 —
 * ⌊(150000 − 폴백여유_MS) / 생성타임아웃_MS⌋ 를 상한으로 두되 워커예산 안에서 3 이 초기값. */
const 폴백여유_MS = 40000;
const 워커학생상한 = Math.min(
  Math.floor((150000 - 폴백여유_MS) / 생성타임아웃_MS),
  Math.floor(워커예산_MS / 생성타임아웃_MS),
  3,   // P0-L 보수 초기값 — §12-20 실측이 서면 이 줄을 걷고 위 둘이 정본이 된다
);

/* ㉡ 회전식 — SQL «표현식 전문»(재료 6). 정본은 마이그 20260821120000 의 jobs_claim 본문이고
 * 이 리터럴은 그 사본이다 — tests/판재료.test.js 가 부분일치로 대조한다(공백 정규화 없이). */
const 회전식 = "mod(('x'||substr(md5(_assign_date::text),1,8))::bit(32)::int::bigint\n                  + 2147483648, 총수)";

/* §3-5-b RPC 열 — 판독기 재료 10 의 «어느 함수들인가»(pg_get_functiondef 대상). 실물의 정본은
 * 마이그 20260821120000 이고 이 목록은 그 이름 사본이다 — tests/판재료.test.js 가 마이그의
 * `create or replace function engine.<이름>` 전량과 대조한다(하나 늘고 여기 안 늘면 판이 안 오른다). */
const RPC열 = Object.freeze([
  'attempt_close', 'attempt_open', 'batch_run_start', 'jobs_claim', 'jobs_finalize',
  'jobs_finalize_due', 'jobs_load', 'jobs_load_one', 'jobs_reclaim', 'jobs_release',
]);

/* §3-2-a cron 표 — 이름 = 크론식(UTC). 활성 조각의 등록 SQL 과 §12-21 이 대조한다. */
const 크론표 = Object.freeze({
  'deliver-daily': '5 16 * * *',        // 00:05 UB — 오케스트레이터(기존 잡 재사용)
  'deliver-check': '5 22 * * *',        // 06:05 UB — 감시(마감 «뒤» 기준 · v5.5 B2)
  'generate-worker': '*/10 16-21 * * *',   // 00:00~05:50 UB 10분마다 — 워커 재진입(B3)
  'generate-deadline': '0 22 * * *',    // 06:00 UB — 마감 스윕(SQL 직접)
});

/** 판독기 재료 4·5·9 의 원소 문자열(§5-1 v5.9 표 — «이름=값» 이름 오름차순 \n 연결). */
const 타임아웃상수원소 = () => `생성타임아웃_MS=${생성타임아웃_MS}`;
const 예산상수원소 = () => {
  const 항 = {
    배달마감_시각, 배치실행상한_일, 실행리더여유_MS, 워커예산_MS, 워커학생상한,
    임대_초, 적재예산_MS, 폴백여유_MS,
  };
  return Object.keys(항).sort().map((k) => `${k}=${항[k]}`).join('\n');
};
const cron원소 = () =>
  Object.keys(크론표).sort().map((k) => `${k}=${크론표[k]}`).join('\n');

module.exports = {
  생성타임아웃_MS, 워커예산_MS, 적재예산_MS, 실행리더여유_MS, 배치실행상한_일,
  임대_초, 배달마감_시각, 중복창_일, 폴백여유_MS, 워커학생상한,
  회전식, 크론표, RPC열, 타임아웃상수원소, 예산상수원소, cron원소,
};
