/* 라디오 첫 2주 실측 계기 — 편성·수집 공백·팩 소진을 «데이터가 판정하게» (발전 트랙 ⑬ · 유호 확정 08-14)
 *
 * ■ 무엇을 여나 (설계 §5-P6 의 그 판정들)
 *   설계가 미룬 판정 셋이 전부 「첫 2주 실측 뒤」로 적혀 있는데, 재는 도구가 없었다:
 *     ㉠ 라운드를 하루 몇 시에 여나(§2-J 「참여 시간대 하루 4~6회」 — 지금은 사람 감)
 *     ㉡ 「새벽 자습 수요」 가정이 맞나(§6-7 — 관측 이력 0)
 *     ㉢ 봇이 죽은 구간이 있었나(§6-3 — 표가 선 것 ≠ 누가 본다 · 08-11 제안의 그 구멍)
 *   이 파일은 그 셋을 계산으로 낸다. **부를 때만 도는 계산기지 상시 계기가 아니다** —
 *   상주하는 계기판을 새로 만들지 않는다(그건 따로 기각된 축이다).
 *
 * ■ 경계
 *   · DB·시계·파일을 안 읽는다 — 행과 기준시각 전부 인자다(회귀가 값으로 잰다).
 *   · 개인 축이 없다. 채팅 행에서 읽는 것은 «시각·명령 종류»뿐이고 `channel_id`·표시명은
 *     쳐다보지 않는다 — 시간대 집계에 사람을 넣으면 그 순간 개인 활동 로그가 된다(§3·§8).
 *   · 알림·채널·비용이 붙는 층은 여기 없다(텔레그램 경보 배선은 유호님 몫으로 남은 자리).
 *
 * ■ 틀릴 때의 모습 · 대가
 *   표본이 적은 시간대가 우연히 1등이 되면 편성이 통째로 기운다 — 그래서 권고는 **표본
 *   하한을 넘긴 시간대에서만** 나오고, 못 낸 이유를 `보류사유` 로 돌려준다. 「권고 0」과
 *   「아직 못 잰다」가 같은 모양이 되지 않게 분모를 함께 낸다(F207).
 *   닫는 것: 없음 — 신설 계산기다(기존에 이 판정을 내는 자리가 0이었다).
 */
'use strict';

const 계기판 = 'radio-gauge.v1';

/** 울란바토르 = UTC+8 (몽골은 2017년부터 서머타임 없음 — 그래도 오프셋은 인자로 받는다). */
const 기본오프셋시 = 8;

/** 그 시간대를 편성 후보로 믿기 위한 최소 표본(맥박 샘플 수). P6 실측 뒤 재조정 자리. */
const 표본하한 = 20;

const 시간 = 3600000;

function 시각ms(v) {
  const t = Date.parse(v);
  return Number.isFinite(t) ? t : null;
}

/** UTC 시각 → 현지 «시»(0~23). 오프셋만 더해 읽는다(시간대 DB 의존을 안 만든다). */
function 현지시(ms, 오프셋시) {
  const d = new Date(ms + 오프셋시 * 시간);
  return d.getUTCHours();
}

/**
 * 시간대별 집계 — 24칸.
 * 재료 = { 맥박행들: [{polled_at, concurrent_viewers, messages_seen}],
 *          채팅행들: [{sent_at, command_kind}], 오프셋시? }
 * 반환 = { 시간대: [{시, 표본, 시청자합, 시청자평균, 명령수, 채팅수}], 분모: {...} }
 *   시청자평균은 표본이 0이면 **null** 이다(0 이 아니다 — 「아무도 안 봤다」와 「안 쟀다」는 다르다).
 */
function 시간대집계(재료) {
  const { 맥박행들 = [], 채팅행들 = [], 오프셋시 = 기본오프셋시 } = 재료 || {};
  const 칸 = Array.from({ length: 24 }, (_, 시) => ({
    시, 표본: 0, 시청자합: 0, 시청자표본: 0, 시청자평균: null, 명령수: 0, 채팅수: 0,
  }));
  const 뺀 = {};
  const 빼기 = (사유) => { 뺀[사유] = (뺀[사유] || 0) + 1; };

  for (const 행 of Array.isArray(맥박행들) ? 맥박행들 : []) {
    const t = 시각ms(행 && 행.polled_at);
    if (t == null) { 빼기('맥박_시각불량'); continue; }
    const c = 칸[현지시(t, 오프셋시)];
    c.표본 += 1;
    /* `concurrent_viewers` 는 API 가 안 줄 때가 있다(null) — 그걸 0 으로 접으면 평균이
     * 조용히 내려가 「새벽엔 아무도 없다」가 관측이 아니라 결손에서 나온다.
     * ⚠ `Number(null)` 은 0 이고 `Number('')` 도 0 이라 Number 로 먼저 접으면 결손이
     *   «관측된 0» 으로 둔갑한다 — 회귀가 이 자리를 실제로 잡았다(08-14). 원값부터 가른다. */
    const 원 = 행.concurrent_viewers;
    const v = typeof 원 === 'number' ? 원 : (typeof 원 === 'string' && 원.trim() !== '' ? Number(원) : NaN);
    if (Number.isFinite(v) && v >= 0) { c.시청자합 += v; c.시청자표본 += 1; }
  }
  for (const 행 of Array.isArray(채팅행들) ? 채팅행들 : []) {
    const t = 시각ms(행 && 행.sent_at);
    if (t == null) { 빼기('채팅_시각불량'); continue; }
    const c = 칸[현지시(t, 오프셋시)];
    c.채팅수 += 1;
    if (행.command_kind) c.명령수 += 1;
  }
  for (const c of 칸) if (c.시청자표본 > 0) c.시청자평균 = c.시청자합 / c.시청자표본;

  return {
    계기판,
    시간대: 칸,
    분모: {
      맥박: (맥박행들 || []).length,
      채팅: (채팅행들 || []).length,
      뺀,
      표본있는시간대: 칸.filter((c) => c.표본 > 0).length,
    },
  };
}

/**
 * 라운드 편성 권고 — 「참여가 실제로 있는 시간대」 상위 N(설계 §2-J).
 * 재료 = { 집계: 시간대집계(...), 회수 = 5, 표본하한 = 표본하한 }
 * 반환 = { 권고: [시], 보류사유: string|null, 근거: [{시, 시청자평균, 명령수, 표본}] }
 *   — 표본이 하한 미만인 시간대는 후보에서 뺀다. 후보가 없으면 권고 대신 **보류사유**를 낸다
 *     (없는 것을 지어내면 그 편성이 첫 2주를 통째로 잘못 쓴다).
 */
function 편성권고(재료) {
  const { 집계, 회수 = 5, 표본하한: 하한 = 표본하한 } = 재료 || {};
  if (!집계 || !Array.isArray(집계.시간대)) throw new TypeError('편성권고: 집계가 필요하다');
  const n = Number(회수);
  if (!Number.isInteger(n) || n < 1) throw new TypeError('편성권고: 회수는 1 이상 정수여야 한다');

  const 후보 = 집계.시간대.filter((c) => c.표본 >= 하한 && c.시청자표본 > 0 && c.시청자평균 > 0);
  if (!후보.length) {
    const 이유 = 집계.분모.맥박 === 0
      ? '맥박 0 — 아직 안 쟀다(송출 전이거나 수집이 안 돌았다)'
      : `표본 하한(${하한}) 넘긴 시간대 0 — 더 모아야 한다`;
    return { 권고: [], 보류사유: 이유, 근거: [] };
  }
  /* 참여(명령 수)를 1차, 시청자 평균을 2차로 본다 — 보기만 하는 시간대보다 «치는» 시간대가
   * 라운드의 자리다(라운드는 응답이 있어야 수집이 된다). 동률은 시 순서로 못박는다. */
  const 순 = [...후보].sort((a, b) => (b.명령수 - a.명령수) || (b.시청자평균 - a.시청자평균) || (a.시 - b.시));
  const 뽑은 = 순.slice(0, n);
  return {
    권고: 뽑은.map((c) => c.시).sort((a, b) => a - b),
    보류사유: null,
    근거: 뽑은.map((c) => ({ 시: c.시, 시청자평균: c.시청자평균, 명령수: c.명령수, 표본: c.표본 })),
  };
}

/**
 * 「새벽 자습 수요」 가정 판정 재료(§6-7) — 새벽대(기본 00~06시)와 그 밖을 갈라 낸다.
 * 판정 자체는 사람이 한다 — 이 함수는 «숫자»만 내고 결론 문자열을 만들지 않는다.
 */
function 새벽대조(재료) {
  const { 집계, 새벽시간 = [0, 1, 2, 3, 4, 5] } = 재료 || {};
  if (!집계 || !Array.isArray(집계.시간대)) throw new TypeError('새벽대조: 집계가 필요하다');
  const 새벽셋 = new Set(새벽시간);
  const 모으기 = (칸들) => {
    const 표본 = 칸들.reduce((s, c) => s + c.표본, 0);
    const 시청자표본 = 칸들.reduce((s, c) => s + c.시청자표본, 0);
    const 시청자합 = 칸들.reduce((s, c) => s + c.시청자합, 0);
    return {
      표본, 명령수: 칸들.reduce((s, c) => s + c.명령수, 0),
      시청자평균: 시청자표본 > 0 ? 시청자합 / 시청자표본 : null,
    };
  };
  return {
    새벽: 모으기(집계.시간대.filter((c) => 새벽셋.has(c.시))),
    그밖: 모으기(집계.시간대.filter((c) => !새벽셋.has(c.시))),
  };
}

/**
 * 수집 맥박 공백 — 봇이 죽어 있던 구간(§6-3 · OAuth 7일 만료가 첫 몇 주에 가장 잘 난다).
 * 재료 = { 맥박행들, 기대간격초 = 60, 배수 = 3, 창시작?, 창끝? }
 * 반환 = { 공백: [{시작, 끝, 길이초}], 분모: { 샘플, 최대공백초, 기준초 } }
 *   창시작/창끝을 주면 **양 끝의 공백도 잡는다** — 안 주면 「첫 폴링 전에 죽어 있던 구간」이
 *   영원히 안 보인다(끝에서 새는 것이 가장 흔한 형태다).
 */
function 맥박공백(재료) {
  const { 맥박행들 = [], 기대간격초 = 60, 배수 = 3, 창시작 = null, 창끝 = null } = 재료 || {};
  const 기준초 = Number(기대간격초) * Number(배수);
  if (!Number.isFinite(기준초) || 기준초 <= 0) throw new TypeError('맥박공백: 기대간격초·배수는 양수여야 한다');

  const 때들 = (Array.isArray(맥박행들) ? 맥박행들 : [])
    .map((행) => 시각ms(행 && 행.polled_at))
    .filter((t) => t != null)
    .sort((a, b) => a - b);

  const 시작ms = 시각ms(창시작);
  const 끝ms = 시각ms(창끝);
  const 점들 = [];
  if (시작ms != null) 점들.push(시작ms);
  점들.push(...때들);
  if (끝ms != null) 점들.push(끝ms);

  const 공백 = [];
  let 최대 = 0;
  for (let i = 1; i < 점들.length; i += 1) {
    const 초 = (점들[i] - 점들[i - 1]) / 1000;
    if (초 > 최대) 최대 = 초;
    if (초 > 기준초) {
      공백.push({ 시작: new Date(점들[i - 1]).toISOString(), 끝: new Date(점들[i]).toISOString(), 길이초: Math.round(초) });
    }
  }
  return { 계기판, 공백, 분모: { 샘플: 때들.length, 최대공백초: Math.round(최대), 기준초 } };
}

/**
 * 팩 소진 — 한 바퀴를 돌면 같은 문항이 다시 나오기 시작한다(암기 신호로 죽는 자리 · §2-J).
 * 재료 = { 노출수: {문항id: n}, 문항ids: [id] }
 * 반환 = { 미노출: [id], 최소노출, 한바퀴, 경보: 'none'|'임박'|'소진', 분모: {...} }
 *   경보는 문자열 셋뿐이고 알림을 «보내지 않는다» — 보내는 층은 이 파일 밖이다.
 */
function 팩소진(재료) {
  const { 노출수 = {}, 문항ids = [] } = 재료 || {};
  const ids = Array.isArray(문항ids) ? 문항ids.filter((v) => v != null) : [];
  if (!ids.length) throw new TypeError('팩소진: 문항ids 가 비었다 — 분모 없는 경보를 만들지 않는다');
  const n = (id) => {
    const v = Number(노출수[id]);
    return Number.isFinite(v) && v > 0 ? v : 0;
  };
  const 미노출 = ids.filter((id) => n(id) === 0);
  const 최소노출 = Math.min(...ids.map(n));
  const 남은비 = 미노출.length / ids.length;
  const 경보 = 미노출.length === 0 ? '소진' : (남은비 <= 0.1 ? '임박' : 'none');
  return {
    계기판, 미노출, 최소노출, 한바퀴: 미노출.length === 0, 경보,
    분모: { 팩: ids.length, 미노출: 미노출.length, 노출된: ids.length - 미노출.length },
  };
}

module.exports = { 계기판, 기본오프셋시, 표본하한, 시간대집계, 편성권고, 새벽대조, 맥박공백, 팩소진 };
