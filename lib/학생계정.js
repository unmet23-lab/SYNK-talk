'use strict';
/**
 * 학생 계정 — 학생번호 ↔ 합성 이메일, 첫 로그인 게이트의 전화 뒷자리 대조 (L0 §4-1·§4-2)
 *
 * 왜 lib 인가 — §4-2 가 못박은 그대로다: **앱과 서버가 같은 함수 하나를 공유한다.**
 *   두 곳에 적으면 갈라지고, 갈라졌을 때 증상은 「로그인이 안 된다」뿐이라 원인이 안 보인다.
 *
 * 도메인·정규형 규칙은 `로그인코드.js` 에서 가져온다 — 합성 이메일을 만드는 규칙이
 *   두 파일에 각자 적히면 그 순간 갈라진다(같은 판정은 한 곳에서 파생시킨다).
 *
 * ⛔ 여기에 난수는 없다(임시번호 생성은 원장 도구 몫). 순수 문자열 함수뿐이라 RN·Node 양쪽에서 돈다.
 * 🔴 비밀번호는 이 파일을 지나가지 않는다 — 학생이 친 값을 우리가 고치면(대소문자·공백)
 *   학생이 정한 것과 달라져 「분명히 맞게 쳤는데 안 된다」가 된다.
 */

const { 정규형, 도메인 } = require('./로그인코드.js');

/**
 * 발급기 정본 = `'SYNK-' + String(n).padStart(3,'0')` (appsscript `학생ID_포맷_`). 1000번부터 4자리.
 *
 * 🔴 **정규형(하이픈 제거)을 거친 뒤 검사하면 안 된다** — `SYNK-042-1` 이 `SYNK0421` 로 접혀
 *   **다른 학생의 계정을 조용히 가리킨다.** 코드 방식(8자 고정)에는 없던 함정이고, 학생번호는
 *   길이가 가변이라 생긴다. 그래서 **사람이 실제로 치는 형태**를 직접 본다: 구분자는 최대 1개.
 */
const 학생번호입력 = /^\s*synk[-\s]?\d{3,}\s*$/i;

/** 첫 로그인 게이트가 잠기는 실패 횟수 (L0 §4-1-1 ①). */
const 시도상한 = 5;

/**
 * 규격에 맞나 — 정규형이 `SYNK` + 숫자 3자리 이상. **애매하면 false**(막히는 방향이 안전하다).
 * ⚠ 자릿수를 접지 않는다: `SYNK-42` 는 발급된 적이 없는 문자열이므로 통과시키지 않는다.
 */
function 학생번호맞나(입력) {
  return 학생번호입력.test(String(입력 == null ? '' : 입력));
}

/**
 * 학생번호 → 합성 이메일. **소문자**다 — Supabase 가 이메일을 소문자로 저장한다.
 * 규격 밖 입력은 던진다(조용히 엉뚱한 계정을 가리키는 것보다 낫다).
 */
function 이메일(학생번호) {
  if (!학생번호맞나(학생번호)) throw new Error(`학생번호 형식이 아니다: ${학생번호}`);
  return 정규형(학생번호).toLowerCase() + 도메인;
}

/**
 * 학생번호 → **발급기 표기형**(`SYNK-042`). 화면·인쇄물에 내는 형태다.
 * 🔴 학생이 친 그대로(`synk 42`·`SYNK042`) 보여주면 안 된다 — 이 값의 용도는 **선생님이
 *   명단에서 찾는 것**이고(막힘 안내 `보여줄값`), 명단에 적힌 모양과 다르면 검색이 빗나간다.
 * ⚠ 규격 검사가 아니다 — 형식은 `학생번호맞나` 가 이미 본다. 여기서 던지면 「보여만 주는」
 *   자리가 화면을 죽인다.
 */
function 학생번호표기(입력) {
  return 정규형(입력).replace(/^SYNK/, 'SYNK-');
}

/**
 * 전화번호에서 **숫자만** 남긴 뒤 4자리. `+976`·공백·하이픈이 섞여 들어오므로 양쪽을 같은 규칙으로 민다.
 * 숫자가 4개 미만이면 `null` — 대조할 수 없다는 뜻이고, 호출부는 그것을 **통과가 아니라 잠금**으로 다룬다.
 */
function 뒤4자리(전화번호) {
  const 숫자 = String(전화번호 == null ? '' : 전화번호).replace(/\D/g, '');
  return 숫자.length < 4 ? null : 숫자.slice(-4);
}

/**
 * 첫 로그인 게이트의 뒷자리 대조 (L0 §4-1-1).
 * 🔴 **빈 값·짧은 값은 false 다** — 명단의 `contact` 가 비어 있으면 그 학생은 아무나 가져간다.
 */
function 뒷자리맞나(명단연락처, 입력) {
  const 기준 = 뒤4자리(명단연락처);
  const 받은 = 뒤4자리(입력);
  return 기준 !== null && 받은 !== null && 기준 === 받은;
}

module.exports = { 학생번호입력, 시도상한, 학생번호맞나, 이메일, 학생번호표기, 뒤4자리, 뒷자리맞나 };
