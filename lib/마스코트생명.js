/** 마스코트기록 지도 안에서 만남이 사는 키. 강사말 키(T1·T2…)와 안 겹치게 `_` 로 연다. */
const 만남키 = '_만남';

/**
 * 기기 시계의 «오늘» — UTC 가 아니라 현지 날짜다(몽골 UTC+8 · `toISOString` 은 하루가 밀린다).
 * 🔑 09-02 에 `src/강사화면.js` 의 지역 함수를 여기로 올렸다 — 같은 기록 지도(`마스코트기록`)에
 *   날짜를 쓰는 곳이 둘이 되었기 때문이다. 두 곳이 «오늘»을 따로 지으면 하루가 어긋나는 날이
 *   생기고, 그날 재회 눈금과 강사말 상한이 서로 다른 날을 본다.
 * @param {Date} d
 */
function 오늘줄(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

/** 'YYYY-MM-DD' 둘의 일수 차. 못 재면 null (`오랜만복귀인가` 와 같은 파싱). */
function 날수차(이른, 늦은) {
  if (typeof 이른 !== 'string' || typeof 늦은 !== 'string') return null;
  const 차 = (Date.parse(늦은) - Date.parse(이른)) / 86400000;
  return Number.isFinite(차) ? Math.round(차) : null;
}

/**
 * 며칠 만인가 → 어느 재회 자리인가.
 *
 * 🔑 **하루 만에 온 것에는 반응하지 않는다.** 매일 오는 것이 기본이라, 매일 「반가워!」를 하면
 *   그 말이 값을 잃는다(별눈의 「특별함은 흔해지는 순간 소진된다」와 같은 규율).
 * ⚠ 눈금(2·4·14)은 **초기값**이다 — 학생 0명이라 못 재고, 부트캠프에서 다시 잰다
 *   (idle·방치 눈금과 같은 태도).
 *
 * @param {string|null} 마지막 마지막으로 만난 날 'YYYY-MM-DD' (없으면 첫 만남)
 * @param {string} 오늘 'YYYY-MM-DD'
 * @returns {'재회잠깐'|'재회오랜만'|'재회한참'|null}
 */
function 재회눈금(마지막, 오늘) {
  const 차 = 날수차(마지막, 오늘);
  if (차 === null || 차 < 2) return null;   // 첫 만남·오늘·어제는 조용하다
  if (차 <= 3) return '재회잠깐';
  if (차 <= 13) return '재회오랜만';
  return '재회한참';
}

