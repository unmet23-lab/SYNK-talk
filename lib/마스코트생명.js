/** 길이 갈래(§5-2). 활성은 «짧»뿐 — 「긴」은 홈·대기 화면이 서는 날 열린다. */
const 혼잣말갈래들 = Object.freeze(['짧', '긴']);
const 활성갈래 = '짧';

/* 색인 — {캐릭터: {자리: {갈래: [문구…]}}}. 모듈 로드 때 한 번 접는다(idle 타이머가 13초·78초
   마다 478벌을 훑지 않게). 정본에 있어도 «활성 자리 밖»이면 색인에 안 들어온다 — 코드가
   못 고르는 것이 데이터로 새지 않게 하는 것이 이 게이트의 전부다. */
const 혼잣말색인 = (() => {
  const 통 = {};
  for (const c of 혼잣말캐릭터들) {
    통[c] = {};
    for (const z of 혼잣말자리들) {
      통[c][z] = {};
      for (const g of 혼잣말갈래들) 통[c][z][g] = [];
    }
  }
  for (const 줄 of 혼잣말원본) {
    const 칸 = 통[줄.캐릭터] && 통[줄.캐릭터][줄.자리];
    if (!칸 || !칸[줄.갈래]) continue;   // 활성 밖(차강사르 등) — 데이터엔 있고 코드는 안 본다
    칸[줄.갈래].push(줄.문구);
  }
  for (const c of 혼잣말캐릭터들) {
    for (const z of 혼잣말자리들) {
      for (const g of 혼잣말갈래들) 통[c][z][g] = Object.freeze(통[c][z][g]);
      통[c][z] = Object.freeze(통[c][z]);
    }
    통[c] = Object.freeze(통[c]);
  }
  return Object.freeze(통);
})();

const 빈풀 = Object.freeze([]);

/**
 * 혼잣말 풀 — 순수 필터. 없는 조합은 **빈 배열**이다(화면은 빈 풀에 조용히 아무 말도 안 한다).
 *
 * @param {string} [캐릭터] '몽글'|'까몽'|'마린' — 안 넘기면 몽글(반입 전과 같은 동작)
 * @param {string} [자리] `혼잣말자리들` 의 값. 목록 밖이면 빈 배열(차강사르·오류남은답장 포함)
 * @param {string} [갈래] '짧'(기본 · 활성) | '긴'(데이터만 · 홈·대기 화면 자리가 서는 날)
 * @returns {ReadonlyArray<string>}
 */
function 혼잣말(캐릭터 = '몽글', 자리 = 'idle', 갈래 = 활성갈래) {
  const 줄 = 혼잣말색인[캐릭터];
  if (!줄) return 빈풀;
  const 칸 = 줄[자리];
  if (!칸) return 빈풀;
  return 칸[갈래] || 빈풀;
}

/* ── 시각·월 게이트 — 새 자리 넷(아침·밤·겨울·여름)을 깨우는 신호 ──────────────
 * 🔑 전부 **주입식 순수 함수**다(인자로 받은 Date 만 본다) — `목소리판정()` 과 같은 패턴이라
 *   회귀가 시계를 쥔다. 화면이 `new Date()` 를 만들어 넘기는 자리는 딱 두 곳이다.
 * 🔑 `밤인가` 는 **여기가 정본**이다(08-28 이전엔 src/마스코트.js 에 살았다) — 졸림 판정과
 *   밤 혼잣말이 같은 자를 써야 한다. 두 곳에 적으면 「밤인데 밤말을 안 한다」가 난다.
 * ⚠ 아침 창(06~10시)은 **초기값**이다 — 학생 0명이라 못 재고, 부트캠프에서 다시 잰다
 *   (`src/마스코트.js` 의 idle·방치 눈금과 같은 태도). 밤 창은 08-13 판을 그대로 승계했다. */
const 밤인가 = (시각) => { const h = 시각.getHours(); return h >= 22 || h < 6; };

/**
 * 이 캐릭터가 «지금 자야 하는» 시각인가 — 밤 졸림의 캐릭터판 (순수 함수 · 시각 주입).
 * 까몽은 밤에 안 졸린다 — 「지금부터가 내 시간이지!」·「졸린 게 아니라 반짝이는 거야」
 * (contents/혼잣말.json kkamong-020·023)가 데이터로 이미 그렇게 말한다. 코드가 밤마다
 * 재우면 문구와 정면 모순이다. 몽글·마린은 밤인가 그대로다(방치 낮잠 축은 캐릭터 공통 —
 * 그건 시각이 아니라 «한동안 안 만짐»이라 여기 없다).
 * @param {string} 캐릭터
 * @param {Date} 시각
 */
const 잘시간인가 = (캐릭터, 시각) => (캐릭터 === '까몽' ? false : 밤인가(시각));

const 아침인가 = (시각) => { const h = 시각.getHours(); return h >= 6 && h < 10; };
const 겨울인가 = (시각) => { const m = 시각.getMonth() + 1; return m === 12 || m <= 2; };
const 여름인가 = (시각) => { const m = 시각.getMonth() + 1; return m >= 6 && m <= 8; };

/**
 * 지금은 어느 자리인가 — 평상(idle) 혼잣말이 고를 자리 하나.
 * 우선순위 = **시각이 계절을 이긴다**(아침 창은 4시간, 계절은 석 달 — 좁은 쪽이 더 «지금»이다).
 * 겨울·여름이 아닌 달(3~5·9~11월)은 그냥 idle 이다 — 봄·가을 풀은 정본에 없다.
 * @param {Date} 시각
 * @returns {'밤'|'아침'|'겨울'|'여름'|'idle'}
 */
function 자리고르기(시각) {
  if (밤인가(시각)) return '밤';
  if (아침인가(시각)) return '아침';
  if (겨울인가(시각)) return '겨울';
  if (여름인가(시각)) return '여름';
  return 'idle';
}

/**
 * 평상 혼잣말 풀 — 시각 창(밤·아침)은 그 자리 풀로 갈아타고, **계절(겨울·여름)은 1/3 가중**이다.
 * 판정 ㉮(09-01 · 유호 위임): 계절 석 달 내내 좁은 풀(캐릭터당 짧 2~3벌)로 갈아타면 가짓수가
 * 확 줄어 「가짓수가 많아야 «가끔»이 산다」(정본 §5-1)와 부딪힌다 — 계절감은 가끔 스치는 쪽이
 * 산다. 밤·아침 창은 2~4시간이라 가짓수 급감 문제가 없고, 밤 풀은 까몽 각성 축이 쓰는 자리라
 * 현행 갈아타기를 유지한다. 계절 풀이 비면 언제나 idle 이다.
 * @param {string} 캐릭터
 * @param {Date} 시각
 * @param {() => number} [골라잡기] 0~1 난수 — 회귀가 주사위를 쥐게 주입식(목소리판정 무늬)
 */
function 평상혼잣말(캐릭터, 시각, 골라잡기 = Math.random) {
  const 자리 = 자리고르기(시각);
  if (자리 === '겨울' || 자리 === '여름') {
    const 계절풀 = 혼잣말(캐릭터, 자리);
    if (계절풀.length && 골라잡기() < 1 / 3) return 계절풀;
    return 혼잣말(캐릭터, 'idle');
  }
  const 풀 = 혼잣말(캐릭터, 자리);
  return 풀.length ? 풀 : 혼잣말(캐릭터, 'idle');
}

