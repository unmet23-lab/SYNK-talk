/**
 * 별눈 판정 — 허용 사건 + 하루 1회 상한.
 * @param {string} 사건 별눈허용사건 의 값
 * @param {string|null} 오늘 'YYYY-MM-DD' — 상한 대조용
 * @param {string|null} 마지막별눈날 이 기기에서 마지막으로 별눈이 뜬 날 (없으면 null)
 * @returns {{허용: boolean, 사유: string|null}} 사유 = '목록밖' | '하루1회' | null
 */
function 별눈판정(사건, 오늘, 마지막별눈날) {
  if (!별눈허용사건.includes(사건)) return { 허용: false, 사유: '목록밖' };
  // 첫 경험이 겹치는 첫날에도 한 번만 — 「특별함은 흔해지는 순간 소진된다」(README ⛔)
  if (오늘 != null && 마지막별눈날 === 오늘) return { 허용: false, 사유: '하루1회' };
  return { 허용: true, 사유: null };
}

