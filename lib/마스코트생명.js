const 연출대본메모 = {};

/**
 * 캐릭터판 연출 대본 — 걸음 골격은 공유하고 **말 필드만** 캐릭터 것으로 치환한 동결 배열.
 * 몽글(기본값)·말 표가 없는 대본은 기존 `연출대본` 그 객체를 그대로 돌려준다(소비자·회귀 무영향).
 * @param {string} 이름 연출대본 의 키
 * @param {string} [캐릭터] '몽글'|'까몽'|'마린'
 */
function 연출대본가져오기(이름, 캐릭터 = '몽글') {
  const 골격 = 연출대본[이름];
  if (!골격 || 캐릭터 === '몽글') return 골격;
  const 말들 = 대본말[이름] && 대본말[이름][캐릭터];
  if (!말들) return 골격;
  const 키 = `${이름}|${캐릭터}`;
  if (!연출대본메모[키]) {
    let i = 0;
    연출대본메모[키] = Object.freeze(골격.map((걸음) => {
      if (걸음.말 === undefined) return 걸음;
      const 말 = 말들[i];
      i += 1;
      return 말 === undefined ? 걸음 : Object.freeze({ ...걸음, 말 });
    }));
  }
  return 연출대본메모[키];
}

/**
 * 오랜만에 돌아왔나 — 복귀 인트로(말하기인트로복귀)의 판정 하나 (순수 함수 · D4-8).
 * 🔑 로그 0줄(생애 첫 만남)은 false — 첫편지는 복귀가 아니다.
 * @param {object[]} 로그 제출 로그(항목의 date = 'YYYY-MM-DD')
 * @param {string} 오늘 'YYYY-MM-DD'
 * @param {number} [문턱일] 이 일수 «이상» 비었으면 오랜만이다
 */
function 오랜만복귀인가(로그, 오늘, 문턱일 = 3) {
  if (!Array.isArray(로그) || 로그.length === 0 || !오늘) return false;
  let 마지막 = null;
  for (const e of 로그) {
    if (e && typeof e.date === 'string' && (마지막 === null || e.date > 마지막)) 마지막 = e.date;
  }
  if (!마지막) return false;
  const 차 = (Date.parse(오늘) - Date.parse(마지막)) / 86400000;
  return Number.isFinite(차) && 차 >= 문턱일;
}

