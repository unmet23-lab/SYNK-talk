/* 레벨(Lv1~6) → 그 레벨이 다루는 TOPIK 급 밴드. 계약 `레벨밴드` 의 사본.
 * 🚫 Lv3=2~3급·Lv5=3~4급의 겹침은 오기가 아니라 설계다(커리큘럼 정본 ⓪표 · 「정리하자」 금지). */
const 레벨밴드 = Object.freeze({ 1: [1], 2: [2], 3: [2, 3], 4: [3], 5: [3, 4], 6: [4, 5] });

const 색인 = new Map(급수표.map(([id, 도입, 재출현]) => [id, Object.freeze({ 도입, 재출현 })]));

/**
 * 문법 하나의 급수. 모르는 ID 는 **null** — 0 이나 빈 객체로 접으면 「뱅크 밖 문법」과
 * 「급수가 안 붙은 문법」이 같은 모양이 된다(엔진 `grammarGrade_` 와 같은 규약).
 * @returns {Readonly<{도입:number, 재출현:number|null}>|null}
 */
function 급수(gid) {
  return 색인.get(String(gid ?? '').trim()) ?? null;
}

/** 그 레벨이 다루는 급 배열. 모르는 레벨은 빈 배열(예외 아님 — 배정이 통째로 죽지 않게). */
function 밴드(lv) {
  return 레벨밴드[Number(lv)] || [];
}

/** 문항이 딛는 문법 ID 전부(스킬 순서 · 중복 제거 · 결정적). */
function 문항문법(문항) {
  const out = [];
  for (const s of (문항 && 문항.skill_ids) || []) {
    for (const gid of 문법대응[s] || []) if (!out.includes(gid)) out.push(gid);
  }
  return out;
}

/**
 * 문항의 요구 급수 — 딛는 문법들의 **도입급 최댓값**. 대응이 하나도 없으면 `null`(미상).
 * 재출현급은 안 본다: 「언제 다시 만나나」는 복습 설계 축이고, 여기 물음은 「낼 수 있나」다.
 */
function 문항급수(문항) {
  let 최대 = null;
  for (const gid of 문항문법(문항)) {
    const g = 급수(gid);
    if (!g) continue;                    // 계약에 없는 ID — 회귀가 별도로 잡는다(여기서 삼키지 않게 세지는 않는다)
    if (최대 == null || g.도입 > 최대) 최대 = g.도입;
  }
  return 최대;
}

/**
 * 그 레벨에게 이 팩이 무엇을 낼 수 있나 — **세 칸으로 갈라** 돌려준다(머리말 🔴).
 * @param {number|string} lv 레벨(1~6). 모르면 밴드가 비어 전부 `밴드밖`+`미상` 으로 갈린다.
 * @param {readonly object[]} [대상] 기본 = 팩 전량.
 * @returns {Readonly<{밴드안:string[], 밴드밖:string[], 미상:string[]}>} 문항id 목록(팩 순서).
 */
function 밴드나누기(lv, 대상) {
  const 안 = [], 밖 = [], 미상 = [];
  const b = 밴드(lv);
  for (const 문항 of 대상 || 문항들) {
    const g = 문항급수(문항);
    if (g == null) 미상.push(문항.문항id);
    else if (b.indexOf(g) >= 0) 안.push(문항.문항id);
    else 밖.push(문항.문항id);
  }
  return Object.freeze({ 밴드안: 안, 밴드밖: 밖, 미상 });
}

/** 급수별 문항 수 — 「이 팩이 몇 급을 몇 개 갖고 있나」의 분모. 키 `미상` 은 대응 0인 문항. */
function 급수분포(대상) {
  const c = {};
  for (const 문항 of 대상 || 문항들) {
    const k = 문항급수(문항) ?? '미상';
    c[k] = (c[k] || 0) + 1;
  }
  return c;
}

