'use strict';
/**
 * 시즌 회고 — 판정 어휘 + 구간 가르기 + **굳히기**.
 * 정본 = appsscript `docs/시즌회고_설계.md` v3 §3-2·§4·§5·§6(유호님 확정 6건 · 2026-08-12).
 *
 * ■ 이 파일이 있는 이유 = **판정과 근거가 갈리지 않게 하기** (설계 §4)
 *   `학습자상태.v6` 은 **창 30일**이고 시즌은 **2달**이다. 회고 시점에 그냥 조회하면 8축이
 *   덮는 것은 시즌의 **뒤 절반**뿐이고, 한 달 뒤 같은 학생을 다시 조회하면 창이 밀려
 *   **다른 숫자**가 나온다. 「가까워졌다」고 적힌 행 옆에 나중에 조회한 숫자를 붙이면
 *   그 숫자는 **그 판정을 낸 사람이 본 적 없는 숫자**다.
 *   → 그래서 회고를 여는 그 순간의 오른쪽 전부를 **한 덩어리로 굳힌다**(`record_snapshot`).
 *     새 발명이 아니라 `task_snapshot` 이 이미 쓰는 논리 그대로다.
 *
 * ■ 🔑 창을 «늘리지» 않고 **구간을 달리해 두 번 부른다** (설계 §4-2 · 유호님 물음에 답한 판정)
 *   창 60일 한 번은 이 문제를 **못 푼다** — 평균으로 접히기 때문이다. 「초반에 잘하다 말았다」와
 *   「초반에 못하다 살아났다」가 60일 평균으로는 **똑같이** 나오는데, 회고가 판정해야 하는 것이
 *   정확히 그 **방향**이다. 그리고 창 30일의 소비자는 회고 하나가 아니다(과제 배정·답장 맥락이
 *   매일 쓴다 · 거기선 최근성이 값이다).
 *   비용은 0에 가깝다 — `학습자상태` 가 `{as_of, 창}` 을 **이미 인자로 받고** 순수 함수라,
 *   같은 사건 배열을 재사용해 인자만 바꿔 부른다(조회도 한 번이다).
 *   🚫 두 층 평균 내기 · 🚫 `학습자상태` 의 기본 `창일수 = 30` 바꾸기(다른 소비자가 갈린다) ·
 *   🚫 회고 전용 축 함수 신설(같은 판정이 두 곳에 살면 갈라진다 — **인자만** 다르게 쓴다).
 *
 * ■ 🔑 두 번 부르는 자리가 **여기 하나**다
 *   호출부(Edge Function)가 직접 두 번 부르면 「어디를 반으로 가르나」가 통로마다 갈리고,
 *   갈린 쪽은 조용히 틀린다(가드 맹점 ④ — 목록은 하나에서 파생시킨다). 그래서 구간 계산과
 *   두 번 호출을 이 파일이 **함께** 진다.
 *
 * ■ 판정이 «3갈래»인 이유 (설계 §5) — 2갈래면 엔진이 목적 변경을 **실패로 배운다**
 *   `redirected`(방향을 바꿨다)를 빼면 목적 변경이 「멀어짐」으로 접히고, 엔진은
 *   「학생이 목적을 바꾸는 것 = 나쁜 신호」를 배운다 — 철학 Ⅱ-4(목적 변경은 정상 경로)를
 *   정면으로 뒤집는 학습이 **조용히** 일어난다.
 *
 * 🚫 재제안 금지
 *   · 판정 눈금 5단계·점수화 — 강사마다 다른 자를 쓰게 되고 라벨이 잡음이 된다(설계 §10).
 *   · 답·판정 자동 채점 — 「목표 런타임 자동 판정 🚫」 유호님 확정 승계.
 *   · `record_snapshot` 을 호출부가 조립해 넘기기 — 앱이 보낸 근거는 근거가 아니다.
 */

const { 학습자상태, 추정판 } = require('./학습자상태.js');

/** 굳힌 것의 판. 축 정의(`추정판`)와 **다른 축**이다 — 여기가 바뀌는 것은 「무엇을 굳히나」가
 *  바뀔 때이고, 그건 옛 회고 행과 새 회고 행의 «모양»이 갈리는 순간이다. */
const 굳힌판 = '회고스냅샷.v1';

/**
 * 판정 3갈래 — **코드값**이다(화면 글자는 라벨이라 언제든 다듬는다).
 * 🔴 이 세 값이 DB CHECK(`season_review_verdict_c11`)와 **글자까지 같아야 한다.**
 *   두 층이 같은 파일을 못 쓰므로(하나는 JS·하나는 DDL) 사본을 피할 수 없고,
 *   없앨 수 없는 사본은 기계에 물린다 — `tests/회고.test.js` 가 그 둘을 대조한다.
 */
const 판정종류 = Object.freeze({
  가까워짐: 'closer',
  그대로: 'same',
  방향바꿈: 'redirected',
});
const 판정목록 = Object.freeze(Object.values(판정종류));

/** 한 줄 사유의 상한. 목적은 「짧게 쓰게 하기」가 아니라 **한 칸이 문서가 되는 것을 막기**다
 *  (`lib/나침반문항.js` 의 `한줄상한` 과 같은 사유 · 값이 같아도 축이 달라 각자 정한다). */
const 사유상한 = 200;

/**
 * 화면에 보일 3갈래 — **문구는 여기 하나에서 나간다**(화면은 코드값도 글자도 모른다).
 *
 * 🔑 라벨이 **둘**인 이유: 같은 코드값을 강사와 학생이 각자 누르는데, 강사에게는 「이 학생이」이고
 *   학생에게는 「내가」다. 한 문장으로 쓰면 한쪽은 반드시 어색해지고, 어색한 버튼은 대충 눌린다
 *   (그리고 대충 눌린 라벨은 엔진 재료로 못 쓴다).
 * 🔴 `redirected` 문구에 **부정적인 낱말을 쓰지 않는다** — 목적 변경은 정상 경로다(철학 Ⅱ-4).
 *   여기서 「못 갔다」로 적으면 코드값이 3갈래여도 사람 머릿속에서 다시 2갈래가 된다.
 * ⚠ 몽골어는 전부 `null` 이다 — 검수자 1인이 아직 안 봤다(나침반 문항과 같은 규칙).
 *   **비면 화면이 한국어를 그린다**(지어 넣지 않는다 · 검수가 끝나면 여기만 고친다).
 *   🔴 학생이 «직접 누르는» 칸이라 이 검수는 나침반 문항보다 **먼저** 끝나야 한다.
 *   🔑 몽골어 칸도 **둘**이다(`라벨_mn`·`라벨_mn_학생`) — 지금 하나만 두면 검수가 오는 날
 *     화면이 「강사 문구를 학생에게」 그리게 되고, 그건 화면을 고쳐야 낫는 병이다.
 *     지금 비어 있는 칸을 두는 값이 그것이다(자리를 미리 파는 것과 축이 다르다).
 */
const 판정보기 = Object.freeze([
  Object.freeze({
    코드: 판정종류.가까워짐, 라벨_mn: null, 라벨_mn_학생: null,
    라벨: '목표에 가까워졌다', 라벨_학생: '나는 목표에 가까워졌다',
  }),
  Object.freeze({
    코드: 판정종류.그대로, 라벨_mn: null, 라벨_mn_학생: null,
    라벨: '거의 그대로다', 라벨_학생: '거의 그대로다',
  }),
  Object.freeze({
    코드: 판정종류.방향바꿈, 라벨_mn: null, 라벨_mn_학생: null,
    라벨: '가고 싶은 방향이 바뀌었다', 라벨_학생: '가고 싶은 방향이 바뀌었다',
  }),
]);

const 하루 = 24 * 60 * 60 * 1000;
const 자리 = (n, 몇 = 2) => (n == null ? null : Math.round(n * 10 ** 몇) / 10 ** 몇);
const 비율 = (분자, 분모) => (분모 > 0 ? 자리(분자 / 분모) : null);

function 때(v) {
  if (v == null) return null;
  const t = v instanceof Date ? v.getTime() : Date.parse(String(v));
  return Number.isFinite(t) ? t : null;
}

/**
 * 강사 판정 검사 — **판정 하나 + 한 줄 사유**.
 *
 * 🔴 사유를 선택으로 두지 않는다. 빈 사유가 통과하면 라벨은 남고 「왜」는 사라지는데,
 *   나중에 그 라벨이 이상해 보일 때 되짚을 것이 아무것도 없다(그리고 되짚을 수 없는 라벨은
 *   엔진 재료로도 못 쓴다 — 오염을 가려낼 방법이 없다).
 *
 * @param {unknown} 판정 3갈래 코드값
 * @param {unknown} 사유 한 줄
 * @returns {{필드: string, 사유: string}|null} 통과면 `null`
 */
function 판정검사(판정, 사유) {
  if (typeof 판정 !== 'string' || !판정목록.includes(판정)) {
    return { 필드: 'verdict', 사유: `판정은 ${판정목록.join('·')} 중 하나여야 합니다` };
  }
  if (typeof 사유 !== 'string' || !사유.trim()) {
    return { 필드: 'note', 사유: '한 줄 사유가 필요합니다(왜 그렇게 봤는지가 라벨의 절반입니다)' };
  }
  if (사유.length > 사유상한) {
    return { 필드: 'note', 사유: `${사유상한}자를 넘습니다(${사유.length}자)` };
  }
  return null;
}

/**
 * 학생 자기 판정 검사 — **판정 하나뿐**(사유 없음 · 클릭 1).
 *
 * 🔑 `null`(안 눌렀다)은 이 함수를 **안 부르는 것**으로 표현한다. 여기서 `null` 을 통과시키면
 *   「안 눌렀다」와 「눌렀는데 값이 없다」가 같은 모양이 되고, 그 둘이 섞이는 순간
 *   대조군의 **분모가 거짓**이 된다(설계 §6 ⚠).
 */
function 자기판정검사(판정) {
  if (typeof 판정 !== 'string' || !판정목록.includes(판정)) {
    return { 필드: 'verdict_by_self', 사유: `판정은 ${판정목록.join('·')} 중 하나여야 합니다` };
  }
  return null;
}

/**
 * 시즌을 **전·후반으로 가른다**.
 *
 * ⚠ 시즌 2달이 정확히 60일이 아니다(달마다 28~31일 · 게다가 정본 단위는 달력이 아니라
 *   **교재 1권**이다 · 설계 §9-0). 그래서 창을 30 으로 고정해 넘기지 않고 **`season` 행의
 *   날짜에서 계산**한다 — 고정하면 시즌 경계와 어긋난 구간을 재게 된다.
 * 🔑 `ends_on` 이 `null`(교재를 아직 안 뗐다)이면 끝은 **`지금`** 이다. 미래를 끝으로 잡으면
 *   후반 창이 아직 오지 않은 날들을 포함해 분모가 조용히 부풀고, 그러면 「후반에 뜸했다」가
 *   달력 때문에 생긴다.
 * ⚠ 경계(`중간`)에 정확히 걸친 사건은 양쪽에 다 든다 — 두 층은 **대조용**이지 합산용이
 *   아니므로(합치지 않는다 · 🚫두 층 평균) 이 중복은 값을 깨뜨리지 않는다.
 *
 * @param {{starts_on: string|Date, ends_on: string|Date|null}} 시즌
 * @param {string|Date} 지금
 * @returns {{시작: number, 중간: number, 끝: number, 전반창: number, 후반창: number,
 *   전체일수: number, 진행중: boolean}}
 */
function 구간나누기(시즌, 지금) {
  const 기준 = 때(지금);
  if (기준 == null) throw new Error('회고 구간: 지금 이 필요하다');
  const 시작 = 때(시즌 && 시즌.starts_on);
  if (시작 == null) throw new Error('회고 구간: season.starts_on 을 못 읽었다');

  const 끝날 = 때(시즌 && 시즌.ends_on);
  /* 끝난 시즌이라도 `지금` 보다 뒤일 수는 없다 — 미래 구간을 재면 창만 넓어지고 사건은 0이다. */
  const 끝 = 끝날 == null ? 기준 : Math.min(끝날 + 하루 - 1, 기준);
  if (끝 < 시작) throw new Error('회고 구간: 시즌이 아직 시작되지 않았다');

  const 길이 = 끝 - 시작;
  const 중간 = 시작 + 길이 / 2;
  return {
    시작, 중간, 끝,
    /* 창은 **일 단위**다(`학습자상태` 가 `창 * 24 * 60 * 분` 으로 되돌린다) — 소수도 받는다. */
    전반창: (중간 - 시작) / 하루,
    후반창: (끝 - 중간) / 하루,
    전체일수: 자리(길이 / 하루, 1),
    진행중: 끝날 == null,
  };
}

/**
 * **굳히기** — 회고를 연 그 순간의 오른쪽 전부를 한 덩어리로.
 *
 * 🔑 `추정판`을 같이 굳히는 것이 핵심이다(설계 §4). 축 정의가 v7 로 바뀐 날, 옛 회고 행이
 *   **어떤 정의 위에서** 판정된 것인지 모르면 종단 대조가 통째로 죽는다.
 * 🔑 `evidence_refs` 도 그대로 담는다 — 같은 근거로 다시 계산해 대조할 수 있어야
 *   「그때 그 숫자였다」가 검증 가능한 주장이 된다(ID 만 담으면 시점이 빠져 재현이 안 된다).
 *
 * @param {Array<object>} 사건들 그 학생의 원신호(시즌 구간을 덮는 것 · 목록·상한은 호출부)
 * @param {{season_id?: string, code?: string, textbook?: string,
 *   starts_on: string|Date, ends_on: string|Date|null}} 시즌
 * @param {object} 집계 시즌 구간 전체 집계(SQL 이 낸 것 · 아래 `집계정리` 로 다듬어 넘긴다)
 * @param {string|Date} 지금
 * @returns {object} `season_review.record_snapshot` 에 그대로 들어갈 값
 */
function 굳히기(사건들, 시즌, 집계, 지금) {
  const 구간 = 구간나누기(시즌, 지금);
  const 행들 = Array.isArray(사건들) ? 사건들 : [];

  const 전반 = 학습자상태(행들, { as_of: new Date(구간.중간), 창: 구간.전반창 });
  const 후반 = 학습자상태(행들, { as_of: new Date(구간.끝), 창: 구간.후반창 });

  const 층 = (r, 창) => ({
    창일수: 자리(창, 2),
    as_of: r.evidence_refs.as_of,
    표본충분도: r.estimator_confidence,
    축: r.축,
    evidence_refs: r.evidence_refs,
  });

  return {
    굳힌판,
    /* 🔴 축 정의의 판은 **lib 에서 가져온다**(손 사본 0) — 여기에 문자열로 적으면
     *   `학습자상태` 가 v7 로 오른 날 굳힌 값만 v6 이라고 거짓말한다. */
    추정판,
    굳힌시각: new Date(때(지금)).toISOString(),
    구간: {
      season_id: 시즌 && 시즌.season_id ? String(시즌.season_id) : null,
      code: (시즌 && 시즌.code) || null,
      textbook: (시즌 && 시즌.textbook) || null,
      시작: new Date(구간.시작).toISOString(),
      중간: new Date(구간.중간).toISOString(),
      끝: new Date(구간.끝).toISOString(),
      전체일수: 구간.전체일수,
      /* ⚠ 「교재를 아직 안 뗐다」를 **숨기지 않는다** — 진행 중에 연 회고는 끝이 오늘이라
       *   나중에 같은 시즌을 다시 재면 다른 값이 나온다. 그 사실이 행에 적혀 있어야 한다. */
      시즌_진행중: 구간.진행중,
    },
    axes_전반: 층(전반, 구간.전반창),
    axes_후반: 층(후반, 구간.후반창),
    season_totals: 집계 && typeof 집계 === 'object' ? 집계 : {},
  };
}

/**
 * SQL 이 낸 시즌 집계 한 줄을 **굳힐 모양**으로 다듬는다(설계 §4 「시즌 구간 집계」).
 *
 * ⚠ `교정열람률` 의 분모는 **그 시즌에 난 교정**이라, 시즌 끝자락에 난 교정을 학생이 다음
 *   시즌에 보면 이 비율은 실제보다 낮게 나온다. 감추지 않고 분자·분모를 **둘 다** 담아
 *   나중에 다시 잴 수 있게 둔다(비율만 담으면 그 왜곡이 영영 안 보인다).
 */
function 집계정리(행) {
  const n = (v) => (v == null ? 0 : Number(v));
  const 교정수 = n(행 && 행.교정수);
  const 열람수 = n(행 && 행.열람수);
  return {
    제출수: n(행 && 행.제출수),
    배정수: n(행 && 행.배정수),
    교정수,
    열람수,
    교정열람률: 비율(열람수, 교정수),
    급수_시작: (행 && 행.급수_시작) || null,
    급수_끝: (행 && 행.급수_끝) || null,
    시험_최신: (행 && 행.시험_최신) || null,
  };
}

module.exports = {
  판정종류, 판정목록, 판정보기, 사유상한, 굳힌판,
  판정검사, 자기판정검사, 구간나누기, 굳히기, 집계정리,
};
