'use strict';
/**
 * 게임큐 — 게임 로그의 **모든 읽기·쓰기가 지나는 단일 직렬 통로**(팩토리 · IO 주입).
 *
 * ■ 왜 있나 (적대 리뷰 B3 · 실사고 계열 = `src/말하기화면.js` 「순차로 묶으면 경쟁이 원리상 없다」)
 *   read-modify-write 를 병렬로 두면 늦게 끝난 쪽이 **호출 시점에 캡처한 배열**로 파일을 통째로
 *   덮는다 — 고름을 담는 중에 이탈 cleanup 이 겹치면 한쪽 사건이 파일에서 사라지고, 그 소실은
 *   오류 없이 「성공」의 모양이다. 그래서 이 파일이 두 가지를 한 번에 강제한다:
 *   ① **직렬화** — 모든 작업이 promise 사슬 하나를 지난다(동시에 두 쓰기가 원리상 없다).
 *   ② **매 작업이 read-modify-write** — 캡처한 배열이 아니라 그 순간의 파일에서 시작한다
 *      (앞 작업이 남긴 결과 위에 병합되지 다시 덮지 않는다).
 *
 * ■ IO 를 주입받는 이유
 *   실제 읽기·쓰기(`src/저장.js`)는 react-native 사슬이라 node 회귀가 못 연다. 판정(직렬·병합)을
 *   여기 순수 팩토리로 떼면 회귀가 **가짜 IO 로 경쟁을 실제로 만들어** 잰다(`tests/게임큐.test.js`).
 *   실 배선은 `src/게임큐.js` 하나다 — 화면이 저장을 직접 부르면 이 통로가 장식이 된다(그 금지는
 *   회귀가 소스로 잰다).
 */
const { 항목추가, 전송기록, 보낼것, 죽은배정들 } = require('./게임로그.js');

/**
 * @param {object} io { 읽기: () => Promise<{로그, 깨진줄}>, 쓰기: (로그) => Promise,
 *                     보내기: (토큰, 사건) => Promise<{event_id?, 오류?, 끝?}> }
 */
function 게임큐만들기({ 읽기, 쓰기, 보내기 }) {
  if (typeof 읽기 !== 'function' || typeof 쓰기 !== 'function' || typeof 보내기 !== 'function') {
    throw new TypeError('게임큐만들기: 읽기·쓰기·보내기가 전부 필요하다');
  }

  /* 사슬 하나 — 앞 작업의 실패가 뒤를 막지 않는다(끝을 늘 성공으로 접어 둔다).
   * 호출자는 자기 작업의 실패를 그대로 받는다(`다음`은 안 접는다). */
  let 줄 = Promise.resolve();
  const 직렬로 = (작업) => {
    const 다음 = 줄.then(작업, 작업);
    줄 = 다음.then(() => {}, () => {});
    return 다음;
  };

  return {
    /** 그 순간의 로그 — 읽기도 사슬을 지난다(쓰기 도중의 중간 상태를 안 본다). */
    읽기: () => 직렬로(읽기),

    /**
     * 사건 하나를 담는다 — 그 순간의 파일에서 시작해 병합한다(id 결정론이 중복을 접는다).
     * `task_meta` = 고름 항목의 로컬 닻(`게임로그.항목추가` 머리말 — 수거의 재료).
     * @returns {Promise<{로그, 항목, 새것}>}
     */
    담기: (사건, task_meta = null) => 직렬로(async () => {
      const { 로그 } = await 읽기();
      const r = 항목추가(로그, 사건, task_meta);
      if (r.새것) await 쓰기(r.로그);
      return r;
    }),

    /**
     * 죽은 배정 수거(H2 「다음 마운트 발견」) — 고름만 남고 그날이 지난 배정을 이탈 항목으로
     * 세운다. 전송은 안 한다(다음 밀기가 진다 — 막힘 판정도 밀기 것을 그대로 승계).
     * `조립` 은 실 조립기(`게임제출.이탈사건`)를 실배선(`src/게임큐.js`)이 주입한다 — 이 lib 는
     * CJS 라 ESM 조립기를 require 못 하고, IO 주입과 같은 무늬가 판정과 배선을 가른다.
     * 두 번 걷어도 항목 id(`abandon:{앉음}`)와 `죽은배정들` 의 끝난-배정 제외가 접는다.
     * @returns {Promise<{로그, 수거수}>}
     */
    수거: (오늘task_ref, 조립) => 직렬로(async () => {
      let { 로그 } = await 읽기();
      let 수거수 = 0;
      for (const 죽은 of 죽은배정들(로그, 오늘task_ref)) {
        const 사건 = typeof 조립 === 'function' ? 조립(죽은) : null;
        if (!사건) continue; // 조립이 계약을 못 지키면 안 세운다 — 지어내지 않는다
        const r = 항목추가(로그, 사건);
        if (r.새것) { 로그 = r.로그; 수거수 += 1; }
      }
      if (수거수 > 0) await 쓰기(로그);
      return { 로그, 수거수 };
    }),

    /**
     * 아직 안 닿은 것을 순서대로 민다. 결과는 **항목마다 즉시** 파일에 적는다 — 도중에 죽어도
     * 닿은 것이 다시 안 나간다(멱등키가 접긴 하지만 왕복 자체가 낭비이자 회선 점유다).
     * @returns {Promise<object[]>} 민 뒤의 로그(화면 표시용)
     */
    밀기: (토큰, 막힘) => 직렬로(async () => {
      let { 로그 } = await 읽기();
      for (const e of 보낼것(로그, 막힘)) {
        let 결과;
        try {
          결과 = await 보내기(토큰, e.사건);
        } catch (err) {
          결과 = { 오류: String((err && err.message) || err), 끝: false };
        }
        로그 = 전송기록(로그, e.id, 결과);
        await 쓰기(로그);
      }
      return 로그;
    }),
  };
}

module.exports = { 게임큐만들기 };
