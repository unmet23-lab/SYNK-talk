'use strict';
/* 걸음 이름 — **녹음이 있는 걸음**의 정본은 여기 하나다.
 *
 * ■ 왜 파일이 따로 섰나 (2026-08-26)
 *   이름을 «쓰는 곳»은 셋인데(`src/말하기화면.js` 호흡 카드 · `lib/라디오낭독.js` 자기 통로 ·
 *   `lib/제출로그.js` 문지기) 목록을 **문지기가 혼자 들고 있었다.** 그래서 08-14 에 라디오
 *   낭독이 자기 걸음 이름(`라디오낭독`)을 세울 때 문지기는 안 따라왔고, 그날부터
 *   `항목추가` 가 낭독 제출을 **전건 던졌다** — 화면에는 오류 한 줄도 안 뜨고
 *   「제출」을 눌러도 아무 일이 안 일어나는 모양이다(실측 08-26 · 아래 회귀가 그 자리를 잰다).
 *   👉 이름을 늘리는 자리와 이름을 «아는» 자리가 갈라지면 반드시 이 병이 난다. 그래서 한 곳이다.
 *
 * ■ 🔴 이름 «변경·삭제»는 금지다 — 늘리는 것만 안전하다
 *   `step` 은 제출 로그 항목의 `id`(`{날짜}-{걸음}-{시도}`)와 음성 파일 이름에 그대로 박히고,
 *   그 로그는 기기에 남는 오프라인 큐다. 이름을 바꾸면 **아직 안 올라간 옛 항목이 문지기에
 *   걸려 통째로 죽는다.** (수집층 규약 승계 — `lib/제출로그.js` 머리말과 같은 규칙.)
 */

/** ②따라 말하기 — 하루 한 흐름의 둘째 호흡(설계 §6). */
const 따라 = '따라';
/** ③답하기 — 셋째 호흡. */
const 답하기 = '답하기';
/** 라디오 「오늘의 표현」 낭독 — 그날 배정의 «호흡»이 아니라 자기 통로다(발전 트랙 ④). */
const 라디오낭독 = '라디오낭독';

/**
 * `따라2` → 2. 따라 걸음이 아니면 `null`.
 *
 * 🔴 **`따라` 자체는 `null` 이다** — 「문장이 하나라 안 갈랐다」와 「첫 문장이다」는 다른 사실이고,
 *   여기서 1 로 접으면 로그만 보고는 그 둘을 영영 못 가른다(갈랐는지 여부가 소급 불가다).
 * 🔑 `0` 과 앞자리 0(`따라01`)은 안 받는다 — 차례는 1부터고, 같은 문장이 두 이름을 갖게 되면
 *   `다음시도번호` 가 그 둘을 다른 걸음으로 세어 재시도가 조용히 갈린다.
 */
function 따라차례(step) {
  const m = /^따라([1-9]\d*)$/.exec(String(step == null ? '' : step));
  return m ? Number(m[1]) : null;
}

/**
 * 문장 `차례`(1부터)와 그날 문장 `총`개수 → 로그에 적을 걸음 이름.
 *
 * 🔴 **총이 1이면 `따라` 그대로다 — 행동 불변.** 안 가른 날의 항목 `id`·음성 파일 이름·
 *   `다음시도번호` 가 08-23 이전과 한 글자도 안 달라진다. 「고쳤는데 옛 날이 갈렸다」가 없어야
 *   기기에 밀려 있는 항목과 새 항목이 한 자리에서 산다.
 */
function 따라걸음(차례, 총) {
  return Number(총) <= 1 ? 따라 : `${따라}${차례}`;
}

/**
 * 녹음이 있는 걸음인가 — `lib/제출로그.항목추가` 의 문지기가 묻는 그 질문.
 *
 * 🔑 문지기를 없애지 않는 이유: 오타 걸음(`따라 `·`답하기2`)은 **화면에서는 멀쩡히 녹음되고**
 *   서버에서만 조용히 사라진다(`제출사건` 이 형식을 못 찾아 `null` 을 낸다). 여기서 던지면
 *   그 실수는 개발 중에 죽는다.
 */
function 녹음걸음인가(step) {
  return step === 따라 || step === 답하기 || step === 라디오낭독 || 따라차례(step) != null;
}

module.exports = { 따라, 답하기, 라디오낭독, 따라차례, 따라걸음, 녹음걸음인가 };
