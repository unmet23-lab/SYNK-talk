'use strict';
/**
 * 목표 왕복 문구 — 아침 서클에서 말한 목표를 그날 밤에 되묻는 한 줄과, 답에 대한 즉시 반응
 * (교실 수집 ② · 유호 확정 08-31 「웅 그대로 가」 · 정본 = appsscript docs/교실수집_목표왕복_설계_v1.md).
 * 정본은 여기, 화면·서버는 배치만 한다(문구_성향확인.js 와 같은 규율).
 *
 * ■ 말의 규율 (성향확인 상시 축 그대로)
 *   · 아침의 그 순간을 가리킨다 — 목표 «내용»은 v1 에 안 실린다(인쇄 과녁이 저장되지 않는 실측 ·
 *     설계 §2). 학생은 자기가 말한 것을 기억하고, 문장은 그 기억을 가리키기만 한다.
 *   · 「아직」에도 감사로 받는다 — 정직한 자기 신고가 제일 비싼 데이터다(설계 §1 · ㉢ 벌 0).
 *   · 수치 0 · 물음으로 끝난다 · 시스템 말투 상시 규칙(synk-brand).
 * ■ 카피 확정 = 유호님 08-31 「이대로 확정」 — 다섯 줄(라벨·물음·단추 둘·반응 둘)을 화면 그대로
 *   보여 드리고 받은 확정이다. 몽골어는 비워 둔다(검수 선행 · 지어낸 번역 금지 — 문구_성향확인.js 와 같은 줄).
 */

const { 문구 } = require('./문구_동의.js');   // 「빈 mn 은 조용히 건너뛴다」 — 한 함수

/** 카피 확정 표식 — 유호님 확정 08-31. 임시로 되돌아오면 카피가 낡은 것이다. */
const 카피확정 = true;

/** 되묻는 한 줄 — 서클이 있던 평일 밤에만 뜬다(게이트는 lib/목표확인.js 가 진다). */
const 목표문구 = {
  오늘목표: { ko: '오늘 아침에 말한 목표, 해냈어요?', mn: '' },
};

/** 답 단추 라벨 — 값(해냈다|아직)은 계약 「목표응답」이고, 라벨은 학생 존댓말이다. */
const 답라벨 = Object.freeze({ 해냈다: '해냈어요', 아직: '아직이에요' });

/** 답에 대한 즉시 반응 — 반영이 «보이는» 자리. 「아직」이 벌이 아니라는 것이 문장에 있어야 한다. */
const 반응문구 = {
  해냈다: { ko: '멋져요! 아침의 그 말이 하루를 끌고 왔네요.', mn: '' },
  아직: { ko: '말해 줘서 고마워요. 내일 그 자리부터 같이 봐요.', mn: '' },
};

/** 카드 재료 — 모르는 키는 null(카드 자체를 접는다 · 확인안내와 같은 갈래). */
function 목표안내() {
  const 안 = 목표문구.오늘목표;
  if (!안) return null;
  return { 키: '오늘목표', 문장: 문구(안), 답라벨 };
}

/** 답 → 즉시 반응 문장 배열(빈 mn 건너뛰기 포함). 모르는 답은 빈 배열. */
function 목표반응(응답) {
  const 안 = 반응문구[응답];
  return 안 ? 문구(안) : [];
}

module.exports = { 카피확정, 목표문구, 답라벨, 반응문구, 목표안내, 목표반응 };
