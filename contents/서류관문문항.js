/**
 * 한 관문의 턴 시드를 **화면에 뜰 순서 그대로** 낸다 — 빈칸 순서대로, 변환이 마지막(발주 G4 §4).
 * G2 `앉음편성` 과 같은 자리다: 편성이 화면과 배정에서 갈리면 「그날 학생이 본 순서」가 행과
 * 달라진다. 못 펴는 관문은 null.
 * @returns {readonly string[]|null}
 */
function 관문편성(관문id) {
  const 관문 = 색인.get(String(관문id || ''));
  if (!관문) return null;
  const 시드들 = 관문.빈칸.map((_, i) => `${관문.관문id}.b${i + 1}`);
  시드들.push(`${관문.관문id}.t1`);
  return Object.freeze(시드들);
}

/**
 * 시드를 편다 — 같은 시드는 언제나 같은 산출(결정적 · 깊은 동결).
 *
 * 빈칸 턴: { 관문id, 이름, 종류:'빈칸', 지시문(공통 한 벌), 질문(지문 = 안내문 원문), 문항판,
 *           빈칸(그 턴의 원소 하나) } — 턴 1개 = 이벤트 1건이라 그 턴의 채점 근거만 든다.
 * 변환 턴: { 관문id, 이름, 종류:'변환', 지시문(변환 지시문), 질문(제시문), 문항판, 형식 } —
 *           열린 산출이라 정답·채점 근거가 없다.
 * @returns {Readonly<object>|null} 못 펴는 시드는 null.
 */
function 펴기(prompt_seed) {
  const 짝 = 시드꼴.exec(String(prompt_seed || ''));
  if (!짝) return null;
  const 관문 = 색인.get(짝[1]);
  if (!관문) return null;
  const 번호 = Number(짝[3]);
  if (짝[2] === 'b') {
    const 빈칸 = 관문.빈칸[번호 - 1];
    if (번호 < 1 || 빈칸 === undefined) return null;
    return 깊이얼리기({
      관문id: 관문.관문id,
      이름: 관문.이름,
      종류: '빈칸',
      지시문: 빈칸지시문,
      질문: 관문.지문,
      문항판,
      빈칸,
    });
  }
  if (번호 !== 1) return null; // 변환은 관문당 하나다(발주 G4 §4)
  return 깊이얼리기({
    관문id: 관문.관문id,
    이름: 관문.이름,
    종류: '변환',
    지시문: 관문.변환.지시문,
    질문: 관문.변환.제시문,
    문항판,
    형식: 관문.변환.형식,
  });
}

module.exports = { 모듈상수, 문항판, 검수확정, 빈칸지시문, 문항들, 관문편성, 펴기 };
