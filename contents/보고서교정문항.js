/**
 * 문항 id 목록 — 배정 통로가 회전(미노출 우선)을 얹을 재료. 팩 순서 그대로.
 * @returns {readonly string[]}
 */
function 문항목록() {
  return 깊이얼리기(문항들.map((문항) => 문항.문항id));
}

/**
 * 이 문항이 대조 문항인가 — 판정 근거는 **`교정문` 유무 하나**다.
 * 🔴 id 접두·별도 플래그로 가르지 않는다: 그러면 「대조인가」의 정본이 둘이 되고, 갈라지는 날
 *    과잉 교정률의 분모(§6-6 ① 집계)가 조용히 틀린다. 조인 키가 「`정답` 유무」인 것과 같은 축.
 * @returns {boolean|null} 모르는 문항은 `null` — 지어내지 않는다.
 */
function 대조문항인가(문항id) {
  const 문항 = 색인.get(String(문항id || ''));
  if (!문항) return null;
  return !('교정문' in 문항);
}

/**
 * 문항 한 벌을 편다 — 같은 문항id 는 언제나 같은 산출(결정적). 반환값은 얼려 나간다.
 *
 * 산출은 §6-8 값 «재료»다: `지시문`·`질문`(= 오류문·대조문)·`문항판` 은 공통층 값이고,
 * `교정문`·`오류태그` 는 조립기가 `정답` 을 세울 재료다. **대조 문항엔 그 두 키가 없다**
 * (규칙 1 — 조립기가 `정답` 키 자체를 안 만드는 근거가 이 부재다).
 *
 * @returns {Readonly<{문항id:string, 지시문:string, 질문:string, 문항판:string, 급수대:string,
 *            교정문?:string, 오류태그?:string}>|null} 모르는 문항은 null.
 */
function 펴기(문항id) {
  const 문항 = 색인.get(String(문항id || ''));
  if (!문항) return null;
  const 펴진 = {
    문항id: 문항.문항id,
    지시문,
    질문: 문항.오류문,
    문항판,
    급수대: 문항.급수대,
  };
  /* 값이 있을 때만 키를 만든다(§6-8 규칙 1) — 대조 문항에 `교정문: null` 을 두지 않는다. */
  if ('교정문' in 문항) 펴진.교정문 = 문항.교정문;
  if ('오류태그' in 문항) 펴진.오류태그 = 문항.오류태그;
  return 깊이얼리기(펴진);
}

