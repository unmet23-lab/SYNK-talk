/** 재귀 동결 — 배열·중첩 객체까지. 얕은 freeze 는 결정성을 못 지킨다(G1 팩 반박 C1 실측).
 *  ⚠ G1 팩의 같은 이름 함수와 «값»을 공유하지 않는다 — 도메인 값이 아니라 6줄 유틸이고,
 *  팩끼리 import 로 얽으면 한 팩의 개정이 남의 팩 동봉을 끌고 다닌다. */
function 깊이얼리기(값) {
  if (값 && typeof 값 === 'object' && !Object.isFrozen(값)) {
    Object.freeze(값);
    for (const 속 of Object.values(값)) 깊이얼리기(속);
  }
  return 값;
}

