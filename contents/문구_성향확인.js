'use strict';
/**
 * 성향 확인 문구 — 봇이 관찰로 추정한 성향을 학생에게 확인받는 한 줄과, 답에 대한 즉시 반응
 * (Ⅲ⑥ · 유호 확정 08-22 「리듬부터 · 이 설계로 진행」 · 정본 = appsscript docs/코어엔진_설계.md §10).
 * 정본은 여기, 화면·서버는 배치만 한다(`문구_생성.js` 와 같은 규율 — 서버(progress)가 shown_text 를
 * 이 파일로 조립하고, 그날 학생이 본 문장은 사건 행에 그대로 남는다).
 *
 * ■ 말의 규율
 *   · 근거가 문장에 들어 있다 — 「리듬이 좋으시네요」(빈 응원)가 아니라 관찰 서술. 단 **수치 0**
 *     (화면에 숫자를 쓰지 않는다 — 돌려주기·G1 «숨은 시계» 규격 그대로).
 *   · 물음으로 끝난다 — 확인받는 자리다. 단정하면 「맞아요/아니에요」 단추가 설 자리가 없다.
 *   · 시스템 말투 상시 규칙(synk-brand) — 긍정·명랑 · 「아니에요」 답에도 감사로 받는다(학생이
 *     틀린 게 아니라 우리가 배운 것이다).
 * ■ 카피 확정 전 임시 표식 — 유호님이 확정하시는 날 `카피확정=true`(생성 문구 2벌과 같은 길).
 * ■ 몽골어는 비워 둔다(검수 선행 · 지어낸 번역 금지).
 */

const { 문구 } = require('./문구_동의.js');   // 「빈 mn 은 조용히 건너뛴다」 — 한 함수

/** 카피 확정 표식 — 임시 문구다(카피 확정은 유호님 몫). */
const 카피확정 = false;

/** 추정 키 → 확인 문장. 키의 정본은 `lib/성향확인.js`(판정이 내는 값) — 여기 없는 키는 안 그린다. */
const 확인문구 = {
  /* 리듬축 — 마감보다 미리 내는 경향(중앙값이 마감 전 · 복수 표본). */
  여유제출: { ko: '요즘 과제를 마감보다 미리 내고 계시던데요 — 미리 계획해 두는 편이에요?', mn: '' },
  /* 리듬축 — 창 안의 과제를 빠짐없이 냄(등식 · 복수 표본). */
  반복제출: { ko: '요즘 과제를 빠짐없이 하고 계시던데요 — 공부가 습관으로 자리 잡았어요?', mn: '' },
};

/** 답 단추 라벨 — 값(맞다|아니다)은 계약 「확인응답」이고, 라벨은 학생 존댓말이다. */
const 답라벨 = Object.freeze({ 맞다: '맞아요', 아니다: '아니에요' });

/** 답에 대한 즉시 반응 — 답이 반영되는 것이 «보이는» 자리(설계 요소 ② · 반영 없으면 설문이다). */
const 반응문구 = {
  맞다: { ko: '맞았네요! 앞으로 더 잘 맞춰 볼게요.', mn: '' },
  아니다: { ko: '알려주셔서 고마워요! 다시 살펴볼게요.', mn: '' },
};

/**
 * 확인 키 → 화면 재료. 모르는 키는 null(안 그린다 — 서버가 새 키를 내면 화면이 빈 칸 대신
 * 조용히 카드 자체를 접는다: 확인 카드는 «없어도 되는» 꼬리라 생성카드의 모름 처리와 갈래가 다르다).
 */
function 확인안내(키) {
  const 안 = 확인문구[키];
  if (!안) return null;
  return { 키, 문장: 문구(안), 답라벨 };
}

/** 답 값 → 반응 한 줄. 모르는 값은 null. */
function 반응안내(답) {
  const 안 = 반응문구[답];
  return 안 ? 문구(안) : null;
}

module.exports = { 카피확정, 확인문구, 답라벨, 반응문구, 확인안내, 반응안내 };
