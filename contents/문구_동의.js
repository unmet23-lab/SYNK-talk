'use strict';
/**
 * 막힘 문구 — 학생이 읽는 글의 정본.
 *
 * ■ 왜 콘텐츠 파일인가
 *   화면 코드 안에 문장을 박으면 몽골어가 붙는 날 화면 파일을 다시 열어야 하고, 그때 번역이
 *   화면마다 흩어진다. 문장은 여기, 화면은 배치만 한다(CLAUDE.md 파일 차선: 콘텐츠 = contents_*).
 *
 * ■ 🔴 몽골어는 **비워 둔다** — 지어낸 번역을 학생에게 뿌리지 않는다
 *   `P0 §185·§191`: 동의·안내 문구의 **몽골어 병기는 검수 완료가 선행**이다. 게다가 이 앱에는
 *   지금 **키릴 글리프를 가진 폰트가 없다** — `App.js` 가 싣는 것은 SUIT 4종 + DM Mono 뿐이고
 *   둘 다 키릴이 없어(`DESIGN.md §3`: `ө`·`ү`·키릴은 **Inter Tight만**) 몽골어를 넣으면 시스템
 *   폴백으로 떨어진다. 즉 **브랜드 밖 글자**가 된다.
 *   → 그래서 `mn` 은 빈 문자열이고, `문구()` 는 **빈 값을 조용히 건너뛴다**(빈 줄이 안 생긴다).
 *     번역과 폰트가 오는 날 이 파일의 `mn` 만 채우면 화면은 그대로 병기로 선다.
 *   🚫 여기에 임시 번역·기계 번역을 넣지 않는다. 학생이 읽는 글이고, 틀린 몽골어는 없는 것보다 나쁘다.
 *
 * ■ 말투 (`synk-brand`)
 *   존댓말 · 짧게 · **학생을 탓하지 않는다** · 다음 한 걸음을 준다 · 이모지 0
 *   (`DESIGN.md §1` 이모지 과다 금지 — 위계는 킷이 진다).
 */

/** 서버가 주는 막힘 코드 → 학생이 읽는 글. 코드는 `lib/동의게이트.js 거절몸통.code` 와 같은 값이다. */
const 막힘문구 = {
  CONSENT_MISSING: {
    제목: { ko: '아직 시작 준비가 하나 남았어요', mn: '' },
    본문: {
      ko: '개인정보 동의 확인이 아직 등록되지 않았어요.\n선생님께 학생번호를 보여 주시면 바로 열려요.',
      mn: '',
    },
    /* 🔑 학생이 **할 수 있는 일**을 준다 — 막다른 화면을 만들지 않는다.
     *   그 일이 「선생님께 보여 주기」라서 화면은 학생번호를 크게 낸다(아래 `보여줄값`). */
    보여줄값: '학생번호',
    /* ⚠ S1 에서는 앱이 동의를 **받지 않는다**(P0 §239 — 상담 대면 동의를 운영자가 옮겨 적는다).
     *   파일럿(2027-02)에는 앱 내 동의가 유일한 근거가 되므로(P0 §240) 이 자리에 「동의하기」
     *   버튼이 붙는다. 그 단계의 선행 조건 **둘**: 몽골어 검수 · Inter Tight cyrillic-ext 탑재.
     *   (문안은 ✅ 종결 — 유호님 D6 `docs/동의_문구_v1.md`. A-10 이 셋째였다.)
     *   지금 버튼을 두면 근거 없는 동의가 쌓인다. */
    단계: 'S1-확인만',
  },
};

/**
 * 한 줄 뽑기 — 몽골어가 비어 있으면 한국어만 낸다.
 * 🔑 「비었다」를 빈 줄로 렌더하지 않는다: 화면에 이유 없는 공백이 생기면 그건 버그처럼 보인다.
 * @param {{ko: string, mn: string}} 짝
 * @returns {string[]} 렌더할 줄들(1개 또는 2개)
 */
function 문구(짝) {
  if (!짝) return [];
  return [짝.ko,짝.mn].map((s) => (s || '').trim()).filter(Boolean);
}

/**
 * 막힘 코드를 화면이 쓸 모양으로.
 * 🔴 **모르는 코드를 「괜찮다」로 접지 않는다** — 서버가 새 코드를 내는 날 화면이 조용히
 *   빈 상태로 돌아가면, 학생은 또 이유 없이 막힌다(F176 이 정확히 그 모양이었다).
 * @param {{code: string}|null|undefined} 막힘  `GET /v1/tasks` 의 `blocked`
 * @returns {{코드: string, 제목: string[], 본문: string[], 보여줄값: string|null, 아는코드: boolean}|null}
 */
function 막힘안내(막힘) {
  const code = 막힘 && 막힘.code;
  if (!code) return null;
  const 안 = 막힘문구[code];
  if (!안) {
    return {
      코드: code,
      제목: ['지금은 시작할 수 없어요'],
      본문: ['선생님께 이 화면을 보여 주세요.'],
      보여줄값: '학생번호',
      아는코드: false,
    };
  }
  return {
    코드: code,
    제목: 문구(안.제목),
    본문: 문구(안.본문),
    보여줄값: 안.보여줄값 || null,
    아는코드: true,
  };
}

module.exports = { 막힘문구, 문구, 막힘안내 };
