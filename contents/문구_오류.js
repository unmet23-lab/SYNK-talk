/**
 * 한 줄 뽑기 — 몽골어가 비어 있으면 한국어만 낸다.
 * 🔑 「비었다」를 빈 줄로 렌더하지 않는다: 이유 없는 공백은 버그처럼 보인다(`문구_동의.js` 와 같은 규율).
 *
 * @param {string} id  이 표의 키(= l10n string_id)
 * @param {{채움?: Record<string, string|number>}} [opt]  `{n}` 같은 칸을 메운다
 * @returns {string} 렌더할 글(한 줄 또는 두 줄) — 모르는 id 면 빈 문자열
 */
function 말(id, opt) {
  const 짝 = 문구[id];
  if (!짝) return '';
  const 채움 = (opt && opt.채움) || null;
  const 메우기 = (s) => (채움
    ? String(s).replace(/\{([\w가-힣]+)\}/g, (전체, k) => (k in 채움 ? String(채움[k]) : 전체))
    : String(s));
  return [짝.ko, 짝.mn].map((s) => 메우기(s || '').trim()).filter(Boolean).join('\n');
}

/**
 * 병기 렌더의 «가르는 자» 정본 — `말()` 이 합쳐 낸 `ko\nmn` 을 화면이 줄배열로 그릴 때 여기서만 가른다.
 * 🔑 수송은 문자열 그대로다(오류 배관 전체 — `인증API` 의 `super(message)`·`사건통로` 의 문자열 연결 —
 *   가 문자열을 흐른다) — 가르기는 그리는 순간, 이 함수 하나로 한다(화면마다 split 을 적으면 갈라진다).
 * ⚠ 알려진 꼬리: `src/사건통로.js` 의 괄호 메타(`(계약 위반: …)`)는 mn 이 채워지는 날 mn 줄 꼬리에 붙는다.
 */
const 줄들 = (글) => String(글 || '').split('\n').map((s) => s.trim()).filter(Boolean);

/**
 * 서버가 준 것으로 학생이 읽을 글을 만든다.
 *
 * 🔴 **모르는 코드에서 서버 말을 버리지 않는다.** 우리 표로 덮으면 새 코드가 생기는 날
 *   학생도 우리도 무엇이 막았는지 모른 채 일반 문구만 본다(F176).
 * 🔑 코드가 아예 없는 갈래(게이트웨이 401 등)도 여기로 온다 — 그때도 서버 말이 이긴다.
 *
 * @param {string|null|undefined} code     서버 봉투의 `error.code`
 * @param {string|null|undefined} 서버말   서버 봉투의 `error.message`
 * @param {{채움?: object, 기본?: string}} [opt]
 * @returns {string}
 */
function 코드로말(code, 서버말, opt) {
  const id = code && 코드별[code];
  const 우리말 = id ? 말(id, opt) : '';
  if (우리말) return 우리말;
  const 남은것 = String(서버말 || '').trim();
  if (남은것) return 남은것;
  return (opt && opt.기본) || 말('err.try_again');
}

/** 이 표가 아는 코드인가 — 화면이 「우리가 쥔 말인지」를 물어야 할 때. */
const 아는코드 = (code) => Boolean(code && 코드별[code]);

module.exports = { 문구, 코드별, 말, 줄들, 코드로말, 아는코드 };
