'use strict';
/**
 * AI 네 낱말 — 숙제 화면 한 줄. 숙제 종류마다 네 낱말(맡기기·부탁하기·가려보기·책임지기) 중
 * «그 숙제의 것 하나»만 붙인다 — 넷 다 나열하면 아무도 안 읽는다(가이드 §B 확정 설계).
 *
 * ■ 정본 계보 — appsscript `docs/AI활용_가이드_v2.md` §B(✅유호 카피확정 2026-08-24 밤 · 결정.md 등재).
 *   몽골어 = `docs/AI활용문안_몽골어_검수표.md` §5 — AI 초안 + 기계 대조(문법 정상)까지 끝났고
 *   **사람 검수 대기**다. 검수 확정이 오면 아래 mn 빈칸에 그 문장이 앉는다.
 * ■ 규율(`문구_생성.js` 와 같은 층) — 문장의 정본은 여기, 화면(`src/`)은 배치만 ·
 *   mn 은 검수 확정 전 빈칸(지어낸 번역 금지 — 빈 mn 은 `문구_동의.문구()` 가 조용히 건너뛴다) ·
 *   `{이름}` 치환은 이 파일 «하나»가 진다. 이름을 모르면 이름없음 판 — 지금 로그인 세션에는
 *   이름이 안 실리므로(생성카드 실측) 당분간 이름없음 판이 사실상 기본이다.
 * ■ 이름없음 판(말하기)은 확정문의 최소 변형으로 세션이 지었다(08-24 · {이름}님→내/나) —
 *   카피 확정 «원문»은 `글.ko` 그대로다. 유호님이 다르게 정하시면 이 판만 간다.
 * ■ 화면 배치 현황(08-24) — 실물 화면이 있는 「말하기」만 배선(src/말하기화면.js 첫 카드).
 *   문장만들기·단어찾기·고쳐쓰기 화면은 아직 없다 — 그 화면이 서는 날 `AI한줄(종류)` 를 부른다.
 */

const { 문구 } = require('./문구_동의.js');   // [ko, mn] 중 빈 것을 거른 배열 — 한 함수만 쓴다

/** 카피 확정 표식 — 유호님 2026-08-24 밤 「앱 문구도 전부 카피확정할게」. */
const 카피확정 = true;

const AI네낱말문구 = {
  말하기: {
    낱말: '맡기기',
    글: { ko: '오늘은 {이름}님 목소리가 주인공이에요 — 이 문장은 세상에서 {이름}님만 말할 수 있어요!', mn: '' },
    글_이름없음: { ko: '오늘은 내 목소리가 주인공이에요 — 이 문장은 나만 말할 수 있어요!', mn: '' },
  },
  문장만들기: {
    낱말: '맡기기',
    글: { ko: 'AI에게 물어보기 전에, 먼저 한 문장만 써 볼까요?', mn: '' },
  },
  단어찾기: {
    낱말: '부탁하기',
    글: { ko: '모르는 단어는 물어봐도 좋아요 — 예문까지 같이 달라고 해 보세요!', mn: '' },
  },
  고쳐쓰기: {
    낱말: '가려보기',
    글: { ko: 'AI 답이 이상하면 교재를 한 번 더 봐 주세요 — AI도 틀려요!', mn: '' },
  },
};

/** {이름} 자리 치환 — 자리가 없으면 그대로, 자리가 있는데 이름이 없으면 null(이름없음 판으로). */
function 이름채움(글, 이름) {
  if (!/\{이름\}/.test(글)) return 글;
  const 값 = String(이름 == null ? '' : 이름).trim();
  return 값 ? 글.replaceAll('{이름}', 값) : null;
}

/** 숙제 종류 → 화면이 그릴 한 줄 `{ 낱말, 글: [줄…] }`. 모르는 종류·판 없음은 null — 안 그린다
 *  (문구를 지어내지 않는다 · 없는 화면은 없는 대로 둔다). */
function AI한줄(종류, 이름) {
  const 안 = AI네낱말문구[종류];
  if (!안) return null;
  const ko = 이름채움(안.글.ko, 이름);
  const 판 = ko !== null ? { ko, mn: 안.글.mn } : 안.글_이름없음;
  if (!판) return null;
  const 줄들 = 문구(판);
  return 줄들.length ? { 낱말: 안.낱말, 글: 줄들 } : null;
}

module.exports = { 카피확정, AI네낱말문구, AI한줄 };
