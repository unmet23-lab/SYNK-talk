/* 내부 색인 — 목록 하나에서 파생한다(두 곳에 적으면 갈라진다). */
const 색인 = new Map(문항들.map((문항) => [문항.문항id, 문항]));

/** 시드 꼴의 정본 — 생성기·해석기가 같은 이 한 곳을 쓴다(G1 반박 W1 승계). */
const 시드꼴 = /^(g3t\d{2})\.s(\d+)d(\d+)$/;

/**
 * 시드를 만든다 — 배정하는 쪽(서버 배치)이 부른다.
 * @returns {string|null} `g3t01.s0d1` 꼴. 문항·변주가 없으면 null(지어내지 않는다).
 */
function 시드만들기(문항id, 사유번호, 세부번호) {
  const 문항 = 색인.get(문항id);
  if (!문항) return null;
  if (!Number.isInteger(사유번호) || 사유번호 < 0 || 사유번호 >= 문항.사유.length) return null;
  if (!Number.isInteger(세부번호) || 세부번호 < 0 || 세부번호 >= 문항.세부.length) return null;
  const 시드 = `${문항id}.s${사유번호}d${세부번호}`;
  return 시드꼴.test(시드) ? 시드 : null; // 자기 산출을 같은 꼴로 검증 — 못 펼 시드를 내지 않는다
}

/**
 * 시드를 편다 — 같은 시드는 언제나 같은 산출(결정적). 화면·조립기·조회가 같은 것을 본다.
 *
 * 산출의 「지시문·질문·문항판」은 §6-8 스냅샷 공통층의 값 재료다. `질문` 은 상황문과 사장님
 * 대사의 **결정적 합**이고(머리말), `상황문`·`사장님대사` 는 화면 연출(카드·TTS)용으로 따로
 * 낸다 — 정본은 어디까지나 `질문` 이다(행에 남는 것).
 *
 * @returns {Readonly<{문항id:string, 이름:string, 지시문:string, 질문:string, 상황문:string,
 *            사장님대사:string, 문항판:string}>|null} 못 펴는 시드는 null.
 */
function 펴기(prompt_seed) {
  const 짝 = 시드꼴.exec(String(prompt_seed || ''));
  if (!짝) return null;
  const 문항 = 색인.get(짝[1]);
  if (!문항) return null;
  const 사유 = 문항.사유[Number(짝[2])];
  const 세부 = 문항.세부[Number(짝[3])];
  if (사유 === undefined || 세부 === undefined) return null;
  const 채우기 = (틀) => 틀.replace('{사유}', 사유).replace('{세부}', 세부);
  const 상황문 = 채우기(문항.상황틀);
  return 깊이얼리기({
    문항id: 문항.문항id,
    이름: 문항.이름,
    지시문: 채우기(문항.지시문틀),
    질문: `${상황문} 사장님: 「${문항.사장님대사}」`,
    상황문,
    사장님대사: 문항.사장님대사,
    문항판,
  });
}

