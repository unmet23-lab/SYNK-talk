'use strict';
/**
 * 생성 상태 문구 — `GET /v1/tasks` 의 `assignment_status`(있음|없음|생성중|오류 · 상태기반 설계 §3-1 v5.6)를
 * 학생이 읽는 글로. 정본은 여기, 화면(`src/생성카드.js`)은 배치만 한다(`contents/문구_동의.js` 와 같은 규율).
 *
 * ■ 무엇을 가르나 — 빈 배정은 두 사실을 한 모양으로 뭉갠다(§3-1 v5.4 C3): 「오늘 낼 것이 없다」와
 *   「지금 짓는 중이라 곧 생긴다」. 같은 화면을 그리면 학생은 「오늘은 없구나」로 읽고 닫는데 실제로는
 *   온다. `있음`·`없음`·칸 없음(구앱 규칙 — 서버가 안 실음)은 이 카드가 **아무것도 안 그린다**.
 *
 * ■ 🔴 말투 정본 = 시스템 말투 상시 규칙(유호 확정 08-22 · synk-brand §「시스템 말투」):
 *   **귀책·결핍으로 말하지 않는다 — 귀책이더라도 긍정적·명랑하게(진행형 · 느낌표 허용).**
 *   `오류` 도 「못 했어요」가 아니라 「학생을 위해 더 맞추는 중」으로 재프레임한다 — 사고 사실은
 *   봉투(`assignment_status`)와 서버 로그가 지고, 학생 화면은 다음 걸음(선생님께 보여 주기)만 준다.
 * ■ 🔴 이름 자리 `{이름}` — `오류` 제목은 학생 이름이 있으면 「{이름}님답게」 판을, 없으면 이름 없는
 *   판(`제목_이름없음`)을 쓴다. 치환은 이 파일 «하나»가 진다(화면이 치환하면 규칙이 두 곳에 산다).
 *   이름을 지어내지 않는다 — 모르는 화면(구앱 서버 폴백 포함)은 이름 없는 판이 정본이다.
 * ■ 카피 확정 = 유호님 08-22(「맞다 — 이대로 진행」). 몽골어는 비워 둔다(검수 선행 · 지어낸 번역 금지).
 */

const { 문구 } = require('./문구_동의.js');   // 「빈 mn 은 조용히 건너뛴다」 — 한 함수

/** 카피 확정 표식 — 유호님 확정 08-22(시스템 말투 상시 규칙과 한 벌). */
const 카피확정 = true;

/** 상태 값 → 학생이 읽는 글. 값은 서버 계약(c12 `assignment_status` 값목록 4)과 같은 한글이다. */
const 생성문구 = {
  생성중: {
    제목: { ko: '오늘 문장을 준비하고 있어요!', mn: '' },
    본문: { ko: '조금 뒤에 다시 열어 보세요.\n열면 오늘 과제가 와 있어요.', mn: '' },
    보여줄값: null,
  },
  오류: {
    제목: { ko: '오늘 과제는 {이름}님을 위해 더 {이름}님답게 만드는 중이에요!', mn: '' },
    제목_이름없음: { ko: '오늘 과제를 더 맞춤으로 만드는 중이에요!', mn: '' },
    본문: { ko: '선생님께 이 화면을 보여 주시면 바로 챙겨 드릴게요.', mn: '' },
    /* 학생이 **할 수 있는 일**을 준다 — 막힘카드와 같은 한 걸음(선생님이 명단에서 찾을 값). */
    보여줄값: '학생번호',
  },
};

/** 이 카드가 «그리지 않는» 값 — 기존 화면이 그대로 선다(있음 = 과제 카드 · 없음 = 폴백 · 칸 없음 = 구앱 규칙). */
const 안그림 = Object.freeze(['있음', '없음']);

/** `{이름}` 자리 치환 — 빈 이름이면 null(호출부가 이름 없는 판으로 간다). split·join = 구형 Hermes 호환. */
const 이름채움 = (글, 이름) => {
  const 값 = String(이름 == null ? '' : 이름).trim();
  return 값 ? 글.split('{이름}').join(값) : null;
};

/**
 * 상태 값을 화면이 쓸 모양으로.
 * 🔴 모르는 값을 「괜찮다」로 접지 않는다 — 서버가 값목록을 늘리는 날 화면이 조용히 빈 상태로 돌아가면
 *   학생은 또 이유 없이 기다린다(막힘안내와 같은 규율). 단 `null`·`있음`·`없음` 은 정상(안 그림)이다.
 * @param {string|null|undefined} 상태  `GET /v1/tasks` 의 `assignment_status`
 * @param {string|null} [이름]  학생 이름(`display_name`) — 없으면 이름 없는 판을 쓴다(지어내지 않는다)
 * @returns {{값: string, 제목: string[], 본문: string[], 보여줄값: string|null, 아는값: boolean}|null}
 */
function 생성안내(상태, 이름 = null) {
  if (상태 == null || 상태 === '' || 안그림.includes(상태)) return null;
  const 안 = 생성문구[상태];
  if (!안) {
    /* 모르는 값도 말투 규칙을 지킨다 — 「열 수 없어요」(결핍)가 아니라 진행형·다음 걸음. */
    return {
      값: String(상태),
      제목: ['오늘 과제를 준비하고 있어요!'],
      본문: ['선생님께 이 화면을 보여 주시면 바로 챙겨 드릴게요.'],
      보여줄값: '학생번호',
      아는값: false,
    };
  }
  const 제목판 = (() => {
    const 채움 = 이름채움(안.제목.ko, 이름);
    if (채움 !== null || !안.제목_이름없음) {
      /* 이름이 있거나, 이름 자리가 애초에 없는 문구(생성중) — 정본 판 그대로(치환만). */
      return 채움 !== null ? { ko: 채움, mn: 안.제목.mn } : 안.제목;
    }
    return 안.제목_이름없음;   // 이름 자리가 있는데 이름을 모른다 — 이름 없는 판
  })();
  return { 값: 상태, 제목: 문구(제목판), 본문: 문구(안.본문), 보여줄값: 안.보여줄값 || null, 아는값: true };
}

module.exports = { 카피확정, 생성문구, 안그림, 생성안내 };
