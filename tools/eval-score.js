#!/usr/bin/env node
'use strict';
/**
 * 교정 엔진 채점기.
 *
 * 왜 기계로 채점하는가: 모델이 자기 출력을 채점하면 후한 쪽으로 기운다.
 * 기대값(`evals/픽스처.json`)을 **먼저 고정**하고, 대조는 문자열 규칙으로만 한다.
 *
 * 사용: node tools/eval-score.js evals/출력_v0.json [--json]
 *
 * 채점 축 3개 — 셋을 **따로** 낸다. 합산 점수 하나로 뭉치면
 * 거짓양성(맞는 문장을 고침)이 탐지율에 묻힌다. 제품에서 더 나쁜 실패는 거짓양성 쪽이다.
 *   ① 거짓양성  — 정상 문장을 고쳤는가 (낮을수록 좋다)
 *   ② 교정 정확 — 오류 문장을 기대대로 고쳤는가
 *   ③ 태그 정확 — 오류 유형을 맞게 분류했는가 (집계의 근거라 교정과 별개로 잰다)
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const FIXTURE = path.join(ROOT, 'evals', '픽스처.json');

function load(p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

/** 공백 차이는 무시하지 않는다 — 띄어쓰기 자체가 채점 대상이다. 앞뒤 공백만 턴다. */
function norm(s) {
  return String(s == null ? '' : s).trim();
}

/* ── ④ 문자 축 — 학생이 읽을 글에 «옛 글자»(한자·가나)가 섞였는가 ────────────────
 * 왜 넷째 축인가: 유호님 확정(2026-08-07)은 「쓰는 문자는 한글·몽골어(키릴)·영어 셋뿐」인데,
 *   그 확정을 기계로 지키던 자리는 **저장소 텍스트 검사** 하나뿐이었다
 *   (SYNK-appsscript `tests/문서문자.test.js`). 그 검사가 겨눈 것은 «우리가 쓴 글»이라
 *   «모델이 낸 글»은 재는 층이 다르다 — 2026-08-12 에 eval 출력에 박힌 한자 1자가 그 검사를
 *   빨갛게 만들었는데, 고칠 자리는 출력 파일이 아니라 프롬프트였다. 검사가 못 고칠 자리를
 *   가리키면 처방을 따를 수 없고, 따를 수 없는 처방은 우회를 정상 통로로 만든다.
 * 🔑 이 축이 없는 동안 채점기는 교정률·태그만 셌다 — 학생이 읽을 해설에 한자가 나가도 **초록**이다.
 *   `evals/결과.md` 의 「오늘의포인트 몽골어 102/102」도 손으로 한 번 센 값이라 다음 판에서 낡는다.
 * ⚠ 한국어 «인용»은 결함이 아니다 — 학생이 찾을 글자를 몽골어 문장 «안에» 넣는 것이 설계다.
 *   그래서 한글은 안 잡고 한자·가나만 잡는다: 한국어 학습 문장에는 원래 안 나오고 TOPIK 에도 없다.
 * ⚠ 이 파일에도 그 글자를 **적지 않는다**(적으면 위 저장소 검사가 이 소스에 걸린다) — 코드포인트로 쓴다. */
const 옛글자 = new RegExp('[\\u3040-\\u30FF\\u3400-\\u4DBF\\u4E00-\\u9FFF]', 'u');

/* 검사 «밖»은 이 넷뿐이고 나머지 문자열 칸은 **전부** 잰다.
 * 🔴 허용목록으로 짜면 새 칸이 생길 때 기본값이 「안 잼」이 되고, 새는 방향은 언제나 「통과」다.
 *   여기서는 반대로 기본값이 「잼」이라, 프롬프트가 새 칸을 내면 그날 자동으로 검사 안에 든다. */
const 문자검사밖 = new Set([
  'id',        // 키다. 학생이 읽는 글이 아니다.
  '원문',      // 파싱 «전» 응답 원본(진단 보존용) — 파싱된 칸을 이미 재므로 같은 글자를 두 번 센다.
  '검증사유',  // 우리 하네스가 적는다(`형식밖`). 모델이 낸 글이 아니다.
  '사유',      // 위와 같은 자리의 옛 이름.
]);

/** 한 출력 행의 문자 판정 — `{ 걸림:[{필드,글자}], 잰칸:n }`. 걸림이 비면 깨끗하다.
 *  🔑 걸림과 분모(잰칸)를 **한 함수에서** 낸다 — 두 곳에 적으면 갈라지고, 갈라지면
 *     「0건」과 「아무 칸도 안 봤다」가 같은 모양이 된다(분모 없는 초록). */
function 문자판정(out) {
  if (!out || typeof out !== 'object') return { 걸림: [], 잰칸: 0 };
  const 걸림 = [];
  let 잰칸 = 0;
  for (const [k, v] of Object.entries(out)) {
    if (문자검사밖.has(k)) continue;
    const 값들 = typeof v === 'string' ? [v]
      : Array.isArray(v) ? v.filter((x) => typeof x === 'string') : [];
    if (!값들.length) continue;
    잰칸 += 1;
    // 대리쌍을 쪼개지 않게 코드포인트 단위로 훑는다(확장B 이상이 와도 U+FFFD 로 뭉개지 않는다).
    const 글자 = [...new Set([...값들.join('\n')].filter((c) => 옛글자.test(c)))];
    if (글자.length) {
      걸림.push({ 필드: k, 글자: 글자.map((c) => 'U+' + c.codePointAt(0).toString(16).toUpperCase()) });
    }
  }
  return { 걸림, 잰칸 };
}

const 문자문구 = (걸림) => 걸림.map(({ 필드, 글자 }) => `${필드} ${글자.join(' ')}`).join(' · ');

function scoreOne(fx, out) {
  const 고친 = norm(out && out.고친문장);
  const 태그 = Array.isArray(out && out.오류태그) ? out.오류태그.map(norm) : [];
  const r = { id: fx.id, 종류: fx.종류, 입력: fx.입력, 출력: 고친, 태그, 판정: {}, 메모: [] };

  /* 🔴 출력 «자체»가 없는 항목은 채점에서 뺀다 — 「안 돌았다」와 「틀렸다」는 다른 사건이다.
   *   이 분기가 없으면 무응답이 아래 정상 분기로 흘러 **「거짓양성 — 맞는 문장을 고쳤다」로 집계된다**.
   *   하필 거짓양성은 이 채점기가 가장 중요하게 보는 축이라(제품에서 더 나쁜 실패), 모델 선발 판정이
   *   그대로 뒤집힌다: 응답을 빠뜨린 모델이 「과교정이 심한 모델」로 보인다.
   *   2026-08-08 실측 — 픽스처를 26→100으로 늘리자 옛 출력에 없는 74건이 전부 거짓양성으로 찍혔다.
   *   ⚠빈 문자열(`고친문장: ''`)은 여기서 빼지 않는다 — 그건 모델이 실제로 낸 답이고 진짜 실패다. */
  if (out == null) {
    r.판정불가 = true;
    r.판정불가사유 = '출력없음';
    r.통과 = null;
    r.메모.push('판정불가 — 이 id의 출력이 없다(모델을 안 돌렸거나 응답이 누락됐다). 채점에서 뺀다.');
    return r;
  }

  /* 문자 축은 아래 갈래들보다 **먼저** 붙인다 — 무응답·정상(거짓양성)·근거없음 갈래가 각자
   * early return 을 하므로 뒤에 두면 그 갈래들이 조용히 빠진다. 학생에게는 어느 갈래든 그대로 나간다. */
  r.문자혼입 = 문자판정(out).걸림;
  if (r.문자혼입.length) {
    r.메모.push(`🔴 옛 글자 혼입 — ${문자문구(r.문자혼입)} (쓰는 문자는 한글·키릴·라틴 셋뿐 · 고칠 자리는 프롬프트다)`);
  }

  /* 🔴 제품 규칙이 **버린** 응답은 세 축(거짓양성·교정·태그) 어디에도 못 들어간다 — 채점할
   *   답이 아예 없다. 위 `out == null` 자물쇠는 「그 id 가 파일에 없다」만 잡는데,
   *   `tools/eval-run.js` 는 버린 응답도 **행으로 남긴다**(`{ id, 검증사유: '형식밖' }`).
   *   그 행은 null 이 아니라 아래 정상 분기로 흘렀고, 거기서 `고친문장` 이 undefined → ''
   *   이라 **「거짓양성 — 맞는 문장을 고쳤다」로 집계됐다.**
   *   2026-08-12 실측: 102문항 중 형식밖 6건(C16·C24·C30·C31·E30·M12)이 그렇게 흘러
   *   거짓양성이 **2/40 이 아니라 6/40** 으로 찍혔다 — 이 파일이 08-08 에 막았다고 적어 둔
   *   바로 그 오독(「응답을 빠뜨린 모델이 과교정 모델로 보인다」)이 **다른 문으로 다시 샜다.**
   *   ⚠ 그렇다고 판정불가로 빼지는 않는다 — 제품에서도 그 응답으로는 교정행이 **안 선다**.
   *     진짜 실패라서 전체통과 분모에는 실패로 남기고, 세 축의 분모에서만 뺀다.
   *   🔑 가르는 것은 사유 문자열이 아니라 **채점할 답이 있는가**다: `고친문장` 칸이 파싱돼
   *     들어왔으면 빈 문자열이어도 그건 모델이 «실제로 낸» 답이라, 08-08 판정 그대로
   *     진짜 실패로 센다(아래 정상·오류 분기). eval 실행기의 원문 보존 조건과 같은 술어다. */
  const 버린사유 = out.검증사유 || out.사유 || null;
  if (버린사유 && out.고친문장 === undefined) {
    r.무응답 = true;
    r.무응답사유 = String(버린사유);
    r.통과 = false;
    r.메모.push(
      `무응답 — 제품 규칙이 버린 응답(${버린사유})이라 교정행이 안 선다. ` +
      '세 축(거짓양성·교정·태그)의 분모 밖 · 전체통과 분모 안.'
    );
    return r;
  }

  // `종류: '정상'`도 거짓양성 검사다 — `불변` 하나에만 기대면 그 필드를 빠뜨린 픽스처가
  // **오류 항목으로 채점되고**, 오류 채점은 포함·불포함·기대태그가 모두 비면 무조건 통과라
  // 「멀쩡한 문장을 건드렸는가」가 자동 만점이 된다. 실제로 수집층이 08-04까지 `불변`을
  // 안 만들고 있었다(계약 c1 목록에 없어서 양쪽 회귀가 둘 다 못 봤다 → c2에서 추가).
  // 둘 중 하나만 맞아도 거짓양성 검사로 가는 편이, 놓치는 쪽보다 안전하다.
  if (fx.불변 || fx.종류 === '정상') {
    r.판정.불변 = 고친 === norm(fx.입력);
    r.판정.태그 = 태그.length === 1 && 태그[0] === '오류없음';
    if (!r.판정.불변) r.메모.push(`거짓양성 — 맞는 문장을 고쳤다: "${고친}"`);
    if (!r.판정.태그) r.메모.push(`태그가 '오류없음' 하나여야 하는데 [${태그.join(', ')}]`);
    r.통과 = r.판정.불변 && r.판정.태그;
    return r;
  }

  /* 🔴 대조할 근거가 하나도 없는 오류 항목은 **채점에서 뺀다**. 아래 검사들은 전부
   *   「기대한 것이 없으면 통과」 모양이라, 셋이 다 비면 무엇을 내놓든 통과가 된다
   *   (08-04 실측: 엔진이 「바나나」를 내놔도 통과였다). 픽스처 문서는 빈 배열을
   *   "그 검사를 건너뛴다"고 적어 두었는데, 건너뜀이 통과와 같은 모양이면 **점수를 부풀린다**.
   *   수집층은 전면 재작성이면 포함·불포함을 일부러 비우므로(추측을 확신처럼 적지 않는다),
   *   오류태그까지 비어 있는 행이 실제로 나온다. 통과도 실패도 아닌 제3의 상태로 세고 분모에서 뺀다. */
  const 근거수 = (fx.포함 || []).length + (fx.불포함 || []).length + (fx.기대태그 || []).length;
  if (근거수 === 0) {
    r.판정불가 = true;
    r.판정불가사유 = '근거없음';
    r.통과 = null;
    r.메모.push('판정불가 — 포함·불포함·기대태그가 모두 비어 대조할 근거가 없다. 채점에서 뺀다(강사 교정을 더 받아야 한다).');
    return r;
  }

  const 포함 = (fx.포함 || []).filter((s) => !고친.includes(s));
  const 불포함 = (fx.불포함 || []).filter((s) => 고친.includes(s));
  r.판정.교정 = 포함.length === 0 && 불포함.length === 0;
  if (포함.length) r.메모.push(`빠짐: ${포함.map((s) => `"${s}"`).join(', ')}`);
  if (불포함.length) r.메모.push(`남음: ${불포함.map((s) => `"${s}"`).join(', ')}`);

  // v1 방침(2026-08-03 유호님 결정: 틀린 것은 전부 고친다) 이후로는 기대 태그를
  // **전부** 요구한다. some() 이었다면 오류 3개 중 1개만 잡아도 통과해서,
  // 방침을 바꾼 것이 채점에 하나도 반영되지 않는다.
  const 기대 = fx.기대태그 || [];

  /* 🔴 `오류없음` 은 오류 문항에서 **절대 대안이 아니다** — 승인 목록에 적혀 있어도 안 된다.
   *   그건 「어휘 안에서 다른 칸을 골랐다」가 아니라 **「틀린 문장을 맞다고 했다」**이고,
   *   학생이 받는 피해가 태그 축 실패 중 가장 크다(자기가 뭘 틀렸는지 모른 채 넘어간다).
   *   2026-08-12 실측: 판 5벌에서 E46(선생님이…있어요)·E08(끝냈어서)이 5판 내내 이 모양이었다.
   *   한 숫자로 뭉치면 이 둘이 「연어냐 유의어혼동이냐」 같은 «말싸움»과 같은 칸에 들어간다. */
  r.미검출 = 태그.includes('오류없음');

  /* 대안 태그 — 통제 어휘에 겹치는 칸이 있어 «둘 다 성립»하는 자리가 있다
   *   (예: `키가 비싸요→커요` 를 어휘:유의어혼동으로 볼 것인가 어휘:연어로 볼 것인가).
   *   그런 자리를 전부-일치로만 채점하면 동전 던지기를 채점하는 것이 된다.
   * 🔑 **어느 태그가 옳은지는 교육 방침 판정이라 이 파일이 정하지 않는다** — 픽스처의
   *   `대안태그`(승인된 대안 세트들)에 적힌 것만 인정하고, 인정한 건수를 요약에 **따로** 낸다.
   *   숨기면 느슨해진 채점이 「좋아졌다」로 보인다. */
  const 전부있나 = (세트) => (세트 || []).every((t) => 태그.includes(t));
  const 기대충족 = 전부있나(기대);                       // 기대 [] 면 true — 종전과 같다
  const 맞은대안 = 기대충족 || r.미검출 ? null
    : (fx.대안태그 || []).find((세트) => 세트.length > 0 && 전부있나(세트)) || null;

  r.판정.태그 = 기대충족 || Boolean(맞은대안);
  r.대안통과 = Boolean(맞은대안);

  if (맞은대안) {
    r.메모.push(`대안 인정: [${맞은대안.join(', ')}] — 픽스처 기대 [${기대.join(', ')}] 와 다르지만 승인된 대안이다`);
  } else if (!r.판정.태그) {
    const 놓친 = 기대.filter((t) => !태그.includes(t));
    r.메모.push(`태그 놓침: ${놓친.join(', ')} / 실제 [${태그.join(', ')}]`);
    if (r.미검출) r.메모.push('🔴 미검출 — 오류 문장을 「오류없음」이라 했다(대안으로 인정될 수 없는 실패)');
  }

  const 초과 = 태그.filter((t) => !기대.includes(t));
  if (초과.length && !맞은대안) r.메모.push(`추가 태그(감점 아님): ${초과.join(', ')}`);

  r.통과 = r.판정.교정 && r.판정.태그;
  return r;
}

function main(argv) {
  /* 픽스처를 골라 쓴다 — 합성(evals/픽스처.json)과 실학생(수집층이 올리는 것)은 **다른 질문에 답한다**:
   * 합성은 「23개 오류 유형을 다 잡는가」(유형 커버리지), 실학생은 「우리 학생이 실제로 무너지는 곳을
   * 잡는가」(분포). 하나로 덮으면 덮인 쪽 질문을 영영 못 묻는다. 그래서 기본값은 합성 그대로 두고
   * 수집층은 다른 경로에 올린다. */
  const fi = argv.indexOf('--fixture');
  const fixturePath = fi !== -1 && argv[fi + 1] ? path.resolve(ROOT, argv[fi + 1]) : FIXTURE;
  // fi === -1 이면 fi+1 === 0 이라, 조건을 그냥 `i !== fi + 1`로 쓰면 **출력 경로 자신이 걸러진다**
  const outPath = argv.filter((a, i) => !a.startsWith('--') && !(fi !== -1 && i === fi + 1))[0];
  if (!outPath) {
    console.error('사용: node tools/eval-score.js evals/출력_v0.json [--json] [--fixture evals/픽스처_실학생.json]');
    return 2;
  }
  if (!fs.existsSync(fixturePath)) {
    console.error(`픽스처가 없다: ${path.relative(ROOT, fixturePath)}\n` +
      '  실학생 픽스처는 수집층(SYNK-appsscript) 시트 메뉴 「🚀 골든셋 → SYNK-talk 저장소로 바로 보내기」가 올린다.');
    return 2;
  }
  const fixture = load(fixturePath);
  const outputs = load(path.resolve(ROOT, outPath));
  const byId = new Map(outputs.항목.map((o) => [o.id, o]));

  const rows = fixture.항목.map((fx) => scoreOne(fx, byId.get(fx.id)));
  const 판정불가 = rows.filter((r) => r.판정불가);
  const 채점대상 = rows.filter((r) => !r.판정불가);
  /* 무응답은 **채점대상 안**이다(전체통과 분모에 실패로 남는다) — 세 축에서만 뺀다.
   * 판정불가로 옮기면 분모가 줄어 「교정행이 안 서는 응답」이 점수에서 통째로 사라진다. */
  const 무응답 = 채점대상.filter((r) => r.무응답);
  const 정상 = 채점대상.filter((r) => r.종류 === '정상' && !r.무응답);
  const 오류 = 채점대상.filter((r) => r.종류 === '오류' && !r.무응답);

  const 요약 = {
    항목수: 채점대상.length,
    // 판정불가는 **분모에서 빼고 따로 센다**. 0으로 감추면 「표본이 부족하다」가 「점수가 좋다」로 보인다.
    판정불가: 판정불가.length,
    // 🔑 사유를 가르는 이유는 **처방이 정반대**여서다: 출력없음 = 모델을 돌려라 / 근거없음 = 강사 교정을 받아라.
    //    한 숫자로 뭉치면 「74건 판정불가」를 보고 있지도 않은 강사 교정을 기다리게 된다.
    판정불가내역: {
      출력없음: 판정불가.filter((r) => r.판정불가사유 === '출력없음').length,
      근거없음: 판정불가.filter((r) => r.판정불가사유 === '근거없음').length,
    },
    /* 🔑 사유별로 센다 — 처방이 갈린다: `형식밖` = 응답이 JSON 이 아니다(잘렸는지 군말인지는
     *   원문을 봐야 안다 · eval 실행기가 남긴다) / `벤더:4xx`·`네트워크:*` = 통로 문제다. */
    무응답: {
      건수: 무응답.length,
      내역: 무응답.reduce((a, r) => {
        const k = String(r.무응답사유).split(':')[0];
        a[k] = (a[k] || 0) + 1;
        return a;
      }, {}),
    },
    거짓양성: {
      // 「고치지 말았어야 하는데 고친」 건수
      건수: 정상.filter((r) => !r.판정.불변).length,
      분모: 정상.length,
    },
    교정정확: { 건수: 오류.filter((r) => r.판정.교정).length, 분모: 오류.length },
    태그정확: {
      건수: 오류.filter((r) => r.판정.태그).length,
      분모: 오류.length,
      // 승인된 대안으로 통과한 몫 — 이 수를 안 내면 느슨해진 채점이 「좋아졌다」로 보인다.
      대안인정: 오류.filter((r) => r.대안통과).length,
      // 🔴 「틀린 문장을 맞다고 했다」 — 태그 축 실패 중 성질이 다르고 더 나쁘다.
      미검출: 오류.filter((r) => r.미검출).length,
    },
    전체통과: 채점대상.filter((r) => r.통과 === true).length,
    /* 🔑 문자 축의 분모만 **모델이 낸 행 전부**다(채점대상이 아니라). 픽스처에 없는 id 로 온 행도
     *   학생에게는 그대로 나가는데, 채점대상으로 재면 그 행들이 조용히 분모 밖으로 빠진다.
     *   0건이어도 줄을 낸다 — 「0건」과 「아무 행도 안 봤다」를 분모가 가른다(F207). */
    문자혼입: (() => {
      const 판정 = outputs.항목.map((o) => ({ id: o.id, ...문자판정(o) }));
      const 걸린 = 판정.filter((x) => x.걸림.length);
      return {
        건수: 걸린.length,
        분모: 판정.filter((x) => x.잰칸 > 0).length,
        자리: 걸린.map((x) => `${x.id}: ${문자문구(x.걸림)}`),
      };
    })(),
  };

  /* 종료코드 판정은 **한 자리**에서만 낸다 — 아래 두 return 이 각자 조건을 적고 있었고,
   * 축을 하나 더 달 때 한쪽만 고치면 `--json` 과 사람용 출력이 서로 다른 판정을 낸다. */
  const 초록 = 요약.거짓양성.건수 === 0
    && 요약.문자혼입.건수 === 0
    && 요약.전체통과 === 요약.항목수;

  if (argv.includes('--json')) {
    console.log(JSON.stringify({ 요약, 항목: rows }, null, 2));
    return 초록 ? 0 : 1;
  }

  const pct = (a, b) => (b === 0 ? '—' : `${Math.round((a / b) * 100)}%`);
  console.log(`\n교정 엔진 채점 — ${path.basename(outPath)}\n`);
  for (const r of rows) {
    console.log(`${r.판정불가 ? '—' : r.통과 ? '✔' : '✖'} ${r.id}  ${r.입력}`);
    if (!r.통과 || r.메모.length) {
      console.log(`    → ${r.출력}`);
      r.메모.forEach((m) => console.log(`    · ${m}`));
    }
  }
  console.log('\n── 요약 ─────────────────────────────');
  console.log(
    `거짓양성  ${요약.거짓양성.건수}/${요약.거짓양성.분모}  (맞는 문장을 고친 건수 — 0이어야 한다)`
  );
  console.log(
    `교정 정확  ${요약.교정정확.건수}/${요약.교정정확.분모}  ${pct(요약.교정정확.건수, 요약.교정정확.분모)}`
  );
  /* 대안으로 통과한 몫은 «괄호 안에 엄격 기준을 같이» 낸다 — 대안을 늘리면 태그 점수가
   * 올라가므로, 엄격 숫자를 못 보면 「채점을 느슨하게 한 것」과 「모델이 좋아진 것」이 같은
   * 모양이 된다(무응답 축과 같은 이유 · F207). */
  const 엄격 = 요약.태그정확.건수 - 요약.태그정확.대안인정;
  console.log(
    `태그 정확  ${요약.태그정확.건수}/${요약.태그정확.분모}  ${pct(요약.태그정확.건수, 요약.태그정확.분모)}` +
    (요약.태그정확.대안인정
      ? `  (대안 인정 ${요약.태그정확.대안인정} · 엄격 ${엄격}/${요약.태그정확.분모} ${pct(엄격, 요약.태그정확.분모)})`
      : '')
  );
  console.log(
    `🔴 미검출  ${요약.태그정확.미검출}건  — 오류 문장을 「오류없음」이라 했다` +
    ' (대안으로 인정될 수 없는 실패 — 학생이 틀린 줄 모른 채 넘어간다)'
  );
  /* 넷째 축 — 0이어도 «분모와 함께» 낸다. 이 줄이 없던 동안 한자 1자가 8벌 중 1벌에 박혀
   * 학생이 읽을 자리에 그대로 있었는데 채점은 내내 이 축을 한 번도 세지 않았다. */
  console.log(
    `옛글자 혼입 ${요약.문자혼입.건수}/${요약.문자혼입.분모}  — 한자·가나가 섞인 행 수(0이어야 한다 · 분모는 «모델이 글을 낸 행» 전부)`
  );
  요약.문자혼입.자리.forEach((s) => console.log(`   🔴 ${s}`));
  console.log(`전체 통과  ${요약.전체통과}/${요약.항목수}`);
  /* 위 세 축의 분모는 **답이 온 것**뿐이다 — 0이어도 한 줄은 낸다(F207: 분모 없이 읽은 초록).
   * 이 줄이 없으면 「거짓양성 2/36」이 「2/40」보다 좋아 보이는데, 줄어든 4는 좋아진 게 아니라
   * 아예 답이 없던 것이다. */
  console.log(
    `무응답    ${요약.무응답.건수}건  — ${Object.entries(요약.무응답.내역).map(([k, v]) => `${k} ${v}`).join(' · ') || '없음'}` +
    ' (교정행이 안 서는 응답 — 위 세 축의 분모 밖 · 전체통과 분모 안)'
  );
  // 침묵하면 「표본이 부족하다」가 「점수가 좋다」로 읽힌다 — 0이어도 한 줄은 낸다.
  console.log(
    `판정불가  ${요약.판정불가}건  — 출력없음 ${요약.판정불가내역.출력없음}(모델을 안 돌렸다) · ` +
    `근거없음 ${요약.판정불가내역.근거없음}(강사 교정을 더 받아야 한다)`
  );
  // 위 세 비율의 분모는 **채점한 것**뿐이다. 안 돌린 문항이 있는데 「전체 통과」만 읽으면 초록으로 오독한다.
  if (요약.판정불가내역.출력없음 > 0) {
    console.log(
      `⚠ 시험지 ${rows.length}문항 중 ${요약.판정불가내역.출력없음}문항은 출력이 없어 **안 재졌다** — 위 점수는 ${요약.항목수}문항짜리다.`
    );
  }
  if (요약.무응답.건수 > 0) {
    const 정상전체 = rows.filter((r) => !r.판정불가 && r.종류 === '정상').length;
    const 오류전체 = rows.filter((r) => !r.판정불가 && r.종류 === '오류').length;
    console.log(
      `⚠ 무응답 ${요약.무응답.건수}건이 세 축의 분모에서 빠졌다 — 거짓양성 ${요약.거짓양성.분모}/${정상전체} · ` +
      `교정·태그 ${요약.교정정확.분모}/${오류전체}. 줄어든 분모는 «좋아진 것»이 아니라 «답이 없던 것»이다.`
    );
  }
  console.log('');

  return 초록 ? 0 : 1;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
