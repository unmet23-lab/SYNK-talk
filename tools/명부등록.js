/** SQL 문자열 리터럴 — 작은따옴표를 겹쳐 막는다. 신뢰 경계라 검증과 이스케이프를 **둘 다** 한다. */
const 따옴표 = (s) => `'${String(s).replace(/'/g, "''")}'`;

async function sql(e, query) {
  const r = await fetch(`https://api.supabase.com/v1/projects/${e.SUPABASE_PROJECT_REF}/database/query`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${e.SUPABASE_ACCESS_TOKEN}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query }),
  });
  const t = await r.text();
  if (!r.ok) throw new Error(`SQL HTTP ${r.status} — ${t.slice(0, 400)}`);
  return JSON.parse(t);
}

async function main() {
  const args = process.argv.slice(2);
  const 적용 = args.includes('--적용');
  const 값 = (이름) => {
    const i = args.indexOf(이름);
    return i !== -1 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : null;
  };
  const 파일 = 값('--파일');
  const 이름 = 값('--이름');
  const 전화 = 값('--전화');
  const 붙은값 = ['--이름', '--전화', '--파일'];
  const student = args.find((a, i) => !a.startsWith('--') && !붙은값.includes(args[i - 1]));

  /* ① 입력을 **행들**로 접는다 — 여기서부터 아래는 1명이든 40명이든 같은 코드다. */
  let 행들;
  let 일괄;
  let 대상아닌행 = [];
  if (파일) {
    일괄 = true;
    if (student) die('--파일 과 학생번호를 같이 줄 수 없다 — 어느 쪽이 명부인지 갈린다.');
    if (전화 || 이름) die('--파일 을 줬으면 --전화·--이름 은 파일 안에 있다(인자로 준 값은 어느 줄에 붙는지 알 수 없다).');
    let 원문;
    try {
      원문 = fs.readFileSync(파일, 'utf8');
    } catch (err) {
      die(`파일을 못 읽었다: ${파일}\n     ${err.message}`);
    }
    const 읽음 = 명부읽기(원문);
    if (읽음.오류.length) die(읽음.오류.join('\n'));
    행들 = 읽음.행들;
    대상아닌행 = 읽음.대상아닌행 || [];
    if (!행들.length) {
      /* 🔴 「학생 0명」의 이유를 갈라 말한다 — `role` 로 전원이 빠진 것과 파일이 빈 것은
       *   화면이 같으면 원장이 「도구가 고장났다」로 읽고 열 이름을 고치기 시작한다. */
      die(대상아닌행.length
        ? `${파일} 에서 읽은 ${대상아닌행.length}행이 **전부 학생이 아니다**(${[...new Set(대상아닌행.map((r) => r.역할))].join('·')}).\n`
          + '     학생 명부라 학생 행만 올린다 — 시트에서 학생만 걸러 내려받거나 role 열을 확인한다.'
        : `${파일} 에 학생 줄이 0개다 — 머리글만 있는 파일로 보인다.`);
    }
  } else {
    일괄 = false;
    if (!student) die(사용법);
    행들 = [{ 번호: student, 전화: 전화 || '', 이름: 이름 || '', 줄: 1 }];
  }

  /* ② 규격 검사 — **전부 아니면 0**. 한 줄이라도 틀리면 붓지 않는다. */
  const 오류 = 검증(행들);
  if (오류.length) {
    die(일괄
      ? `${오류.length}건이 규격 밖이다 — **아무것도 넣지 않았다**(한 줄이라도 틀리면 전량 거절한다).\n`
        + 오류.map((s) => '  · ' + s).join('\n')
      : 오류[0]);
  }

  const e = 자격증명.읽기('명부등록');
  if (!e.SUPABASE_ACCESS_TOKEN || !e.SUPABASE_PROJECT_REF) {
    die('.env 에 SUPABASE_ACCESS_TOKEN·SUPABASE_PROJECT_REF 가 필요하다 (tools/원격SQL.js 안내 참조)');
  }

  /* 🔴 **어디에 붓는지부터 소리 내어 읽는다.** 과녁 게이트(`자격증명.읽기`)는 「운영이면 막는다」
   *   까지고, 리허설로 갈 때는 아무 말도 안 한다. 그런데 이 도구의 성공 화면은 「✅ 명부 등록 3명」
   *   하나뿐이라, **운영에 올렸어야 할 학생이 리허설에 올라가도 똑같이 초록으로 보인다** —
   *   실제로 리허설 156행 / 운영 0행이 그 모양으로 났다(08-09 실측).
   * 🔑 미리보기에서도 찍는다. 「무엇을 넣을지」만 알고 「어디에」를 모르면 미리보기가 반쪽이고,
   *   원장이 확인하는 자리가 바로 거기다. */
  await 자격증명.대상알림('명부등록', e, { 쓰기: 적용 });

  /* ③ 이미 있는지 먼저 본다 — **앱과 같은 방식으로 접어서** 본다(`upper(replace(...))`).
   *   exact 로 보면 `SYNK042` 가 있는데 `SYNK-042` 를 또 넣어 두 행이 서고, 첫 등록은 둘 다
   *   집어 어느 쪽이 그 학생인지 알 수 없게 된다(auth/index.ts 의 조회와 같은 규칙이다). */
  const 접힌번호 = 행들.map((r) => 정규형(r.번호));
  const 있는것 = await sql(e, 'select student_code, contact, auth_user_id from engine.learners'
    + ` where upper(replace(student_code, '-', '')) in (${접힌번호.map((c) => 따옴표(c)).join(', ')})`);
  const { 넣을것, 건너뛴것, 막힌것 } = 계획(행들, 있는것);

  /* ④ 무엇을 할지는 순수 함수가 정하고, 여기는 집행만 한다. */
  const 행동 = 행동정하기({ 넣을것, 건너뛴것, 막힌것 }, 적용);
  if (행동 === '거절') die(막힘글(막힌것));
  if (행동 === '미리보기') { console.log(미리보기글(넣을것, 건너뛴것, 대상아닌행)); return; }
  if (행동 === '넣을것없음') {
    console.log(`✅ 넣을 것이 없다 — 읽은 ${건너뛴것.length}명이 전부 이미 명부에 있고 연락처도 같다.`
      + 대상아님글(대상아닌행));
    return;
  }

  /* ⑤ 한 문장 = 한 트랜잭션이다. 여러 문장으로 쪼개면 중간에 끊겼을 때 **반쯤 등록된 명부**가
   *   남고, 그 상태는 「누가 들어갔나」를 다시 세야만 알 수 있다. */
  const 버전 = 계약버전();
  await sql(e, 'insert into engine.learners (student_code, contact, display_name, schema_ver) values '
    + `${넣을것.map((r) => `(${따옴표(학생번호표기(r.번호))}, ${따옴표(r.전화)}, `
      + `${r.이름 ? 따옴표(r.이름) : 'null'}, ${따옴표(버전)})`).join(', ')}`);

  console.log(`✅ 명부 등록 ${넣을것.length}명`
    + (건너뛴것.length ? ` (이미 있어 건너뛴 ${건너뛴것.length}명)` : '')
    + 대상아님글(대상아닌행)
    + '\n' + 넣을것.map((r) => `   + ${학생번호표기(r.번호)}${r.이름 ? ` (${r.이름})` : ''}`).join('\n')
    + 첫등록안내(학생번호표기(넣을것[0].번호), 뒤4자리(넣을것[0].전화))
    + (넣을것.length > 1 ? '\n     (나머지도 같다 — 학생번호와 뒤 4자리만 각자 것이다)' : '')
    + `\n   📌 감사 기록(누가·언제): ${new Date().toISOString()} · ${넣을것.length}명 명부 등록`
    + '\n      ⚠ 넣을 표가 아직 없어 화면에만 남는다 — 필요하면 지금 옮겨 적는다.');

  /* 🔴 다음 한 걸음 = 동의 (유호님 확정 2026-08-07: **등록 직후**).
   * 명부에 올라도 학생은 아무것도 못 한다 — `uploads` 는 403 CONSENT_MISSING 이고
   * `deliver` 는 「동의 없는 학생은 배정하지 않는다」(P0 §345)라 과제도 안 간다. 두 증상 다
   * 「앱이 비어 있다」로만 보여서, 올리고 잊으면 그 학생은 **조용히** 멈춘 채로 남는다.
   * ⛔ 여기서 대신 넣지 않는다 — 동의는 별개의 법적 행위다. 받은 사실이 없는데 도구가
   *    만들면 그건 편의가 아니라 위조다. 이 자리가 하는 일은 **안 잊게 하는 것**까지다.
   * 유효성 판정은 여기서 안 한다(그 정본은 동의 게이트 하나여야 한다) — 있나 없나만 센다. */
  const 넣은번호 = 넣을것.map((r) => 정규형(r.번호));
  const 동의수 = await sql(e, 'select l.student_code, count(c.learner_id)::int n from engine.learners l'
    + ' left join engine.consents c on c.learner_id = l.learner_id'
    + ` where upper(replace(l.student_code, '-', '')) in (${넣은번호.map((c) => 따옴표(c)).join(', ')})`
    + ' group by 1');
  const 센것 = new Map(동의수.map((row) => [정규형(row.student_code), row.n]));
  const 무동의 = 넣을것.map((r) => 학생번호표기(r.번호)).filter((번호) => !(센것.get(정규형(번호)) > 0));
  console.log(일괄동의안내(무동의));
}

