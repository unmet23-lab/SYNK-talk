/**
 * 등록 직후 화면이 들고 있는 **다음 한 걸음**. 순수 함수라 검사할 수 있다.
 * 유호님 확정(2026-08-07): 동의는 **등록 직후** 옮겨 적는다.
 */
function 다음걸음(student, 동의수) {
  return 동의수 > 0
    ? `\n   동의 이력 ${동의수}건 — 지금 유효한지: node tools/동의발급.js --현황 --학생 ${student}`
    : `\n   🔴 이 학생은 **아직 아무것도 못 한다** — 동의 행이 0건이라 업로드는 403 이고`
      + `\n      오늘의 과제 배정에서도 빠진다. 상담에서 받은 동의를 지금 옮겨 적는다:`
      + `\n      node tools/동의발급.js ${student} --판 v18.9 --확정자 "이름" --적용`;
}

/**
 * 여럿일 때의 같은 한 걸음. 1명이면 `다음걸음` 을 그대로 쓴다 — 문구가 둘이 되면 갈라진다.
 * 🔴 **0건인 학생을 이름으로 다 부른다.** 숫자만 세면(「3명이 동의 없음」) 원장이 누구인지
 *   찾으러 다시 DB 를 열어야 하고, 그 왕복이 곧 「나중에」가 된다.
 */
function 일괄동의안내(무동의) {
  if (!무동의.length) return '\n   동의 이력 — 넣은 학생 전원이 1건 이상이다.';
  if (무동의.length === 1) return 다음걸음(무동의[0], 0);
  return `\n   🔴 **동의 0건 ${무동의.length}명** — 이들은 아직 아무것도 못 한다(업로드 403 · 배정 제외):`
    + `\n      ${무동의.join(' · ')}`
    + '\n      상담에서 받은 동의를 지금 옮겨 적는다(한 명씩):'
    + '\n      node tools/동의발급.js <학생번호> --판 v18.9 --확정자 "이름" --적용';
}

/**
 * 학생이 화면에서 볼 **첫 등록 안내**. 전달물은 여전히 0이다 — 학생번호는 이미 학생 것이고
 * 뒤 4자리는 자기 전화다. 비밀번호는 우리가 만들지 않는다(§4-1).
 */
function 첫등록안내(번호, 뒷자리) {
  return `\n   학생에게 줄 것은 **학생번호 하나**다 — 비밀번호는 학생이 직접 정한다(전달물 0).`
    + `\n     ① 앱 첫 화면에 학생번호 ${번호}`
    + `\n     ② 본인 전화 **뒤 4자리 ${뒷자리}** — 상담 때 받은 그 번호다(다른 번호로 5번 틀리면 잠긴다)`
    + `\n     ③ 쓸 비밀번호를 학생이 직접 정한다(6자 이상)`;
}

/**
 * 🔴 이미 명부에 있는데 **연락처가 어긋난** 학생들. 이 자리가 이 도구의 급소다.
 *
 * 조용히 건너뛰면 원장 화면엔 「동기화 완료」가 뜨는데 그 학생의 게이트 값은 **옛 번호**로
 * 남는다 — 증상은 개원 첫날 그 학생만 못 들어오는 것뿐이라 원인이 명부에 있는 줄 모른다.
 * 그래서 **전량 거절**하고, 고치는 명령을 함께 준다(F103 — 막으려면 처방을 같이 낸다).
 *
 * ⛔ 여기서 대신 덮지 않는다 — `contact` 를 갈면 그 학생의 게이트 값이 조용히 바뀐다.
 *    어느 쪽이 맞는 번호인지는 사람이 안다.
 */
function 막힘글(막힌것) {
  return `${막힌것.length}명이 이미 명부에 있는데 **연락처가 맞지 않는다** — 아무것도 넣지 않았다.\n`
    + 막힌것.map((m) => `  · ${m.번호} — ${m.사유}`).join('\n')
    + '\n\n     덮어쓰지 않았다 — 연락처를 갈면 그 학생의 첫 등록 대조값이 조용히 바뀐다.'
    + '\n     어느 쪽이 맞는 번호인지 확인한 뒤 그 한 행만 고친다:'
    + '\n       node tools/원격SQL.js <파일.sql> --적용'
    + "\n       update engine.learners set contact = '<맞는 번호>' where student_code = '<학생번호>';"
    + '\n     파일 쪽이 틀린 것이면 파일을 고쳐 다시 돌린다.';
}

/**
 * 학생이 아니라 **대상이 아니어서** 뺀 행들. 조용히 빼면 원장은 시트 40줄을 넣었는데
 * 화면의 33명이 맞는 수인지 알 방법이 없다 — 「0건 처리」와 「안 읽었다」가 같은 모양이다(F207).
 */
function 대상아님글(대상아닌행) {
  if (!대상아닌행.length) return '';
  const 종류 = new Map();
  for (const r of 대상아닌행) 종류.set(r.역할, (종류.get(r.역할) || 0) + 1);
  return `\n  대상 아님    : ${대상아닌행.length}행 건너뜀 — `
    + [...종류].map(([역할, n]) => `${역할} ${n}`).join(' · ')
    + '\n                (학생 명부라 학생 행만 올린다 — 고칠 것이 아니라 대상이 아닌 행이다)';
}

/** 미리보기 화면. 무엇이 나가고 무엇이 안 나가는지를 **세어서** 보여준다(F207 — 분모부터). */
function 미리보기글(넣을것, 건너뛴것, 대상아닌행) {
  const 뺀것 = 대상아닌행 || [];
  const 줄 = [`[미리보기] 아무것도 만들지 않았다. 실제로 올리려면 --적용 을 붙인다.`,
    `  읽은 줄     : ${넣을것.length + 건너뛴것.length + 뺀것.length}줄`
      + (뺀것.length ? ` (학생 ${넣을것.length + 건너뛴것.length}명 + 대상 아님 ${뺀것.length}행)` : ''),
    `  새로 넣을 것 : ${넣을것.length}명`,
    `  건너뛸 것   : ${건너뛴것.length}명 (이미 명부에 있고 연락처도 같다)`,
    '  계정        : 만들지 않는다 — 학생이 앱에서 첫 등록을 할 때 선다(§4-1).'];
  if (뺀것.length) 줄.push(대상아님글(뺀것).replace(/^\n/, ''));
  for (const r of 넣을것) {
    줄.push(`    + ${학생번호표기(r.번호)}${r.이름 ? ` (${r.이름})` : ' (이름 없음 — 명부에서 사람이 못 알아본다)'}`
      + `  전화 ${r.전화} → 대조할 뒤 4자리 ${뒤4자리(r.전화)}`);
  }
  for (const s of 건너뛴것) 줄.push(`    = ${s.번호}${s.계정있음 ? ' (첫 등록 완료)' : ' (계정은 아직)'}`);
  return 줄.join('\n');
}

const 자격증명 = require('../lib/자격증명.js');   // .env 읽기 + 토큰 만료 + 과녁 게이트 + 대상 알림(공용 통로)

