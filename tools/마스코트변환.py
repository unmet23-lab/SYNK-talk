# 실행:  python tools/마스코트변환.py [캐릭터]   (talk 저장소 루트 어디서든 · 캐릭터를 주면 그 벌만)
# 산출:  assets/마스코트/<컷>.webp + 캐릭터별 눈검수 시트(마스코트_시트*.png) + 실측 로그
import os
import sys
import numpy as np
from PIL import Image

_정본뿌리 = r"C:\Users\q1212\Documents\SYNK-appsscript\docs\캐릭터"
_정본 = os.path.join(_정본뿌리, "정본_4K")   # 셋이 한 폴더 · 전부 투명(09-05 판올림)
SRC = {"몽글": _정본, "까몽": _정본, "마린": _정본}
DST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "마스코트")

# 앱이 쓰는 컷 = lib/마스코트생명.표정컷 값과 1:1 (tests/마스코트자산.test.js 가 파생 대조)
컷들 = {
    "몽글": ["몽글_본체", "몽글_놀람", "몽글_눈웃음", "몽글_눈감음"],
    "까몽": ["까몽_본체", "까몽_놀람", "까몽_눈웃음", "까몽_눈감음",
           "까몽_윙크", "까몽_졸림", "까몽_으쓱", "까몽_민망"],
    # 마린 — 09-05 반입. 정본 11컷 중 «앱 어휘가 부르는» 8컷만 가져온다.
    #   안 가져오는 셋: 좌34·우34(앱은 정면만 쓴다) · 감탄(별눈 자리인데 발동 신호가 아직 0).
    #   🔑 마린은 눈이 «렌즈»라 표정을 빛과 모양으로 낸다 — 그래서 이름이 몽글·까몽과 다르다:
    #     «몰래기쁨»(한 단 밝아진 렌즈) = 기쁨 전용판. 셋 중 마린만 제 기쁨 컷을 갖는다.
    #     «집중»(가늘어진 렌즈) = 브리핑 성격의 뒤 박자. 윙크·으쓱은 렌즈라 원리상 없다.
    "마린": ["마린_본체", "마린_놀람", "마린_눈웃음", "마린_눈감음",
           "마린_졸림", "마린_민망", "마린_몰래기쁨", "마린_집중"],
}
크기 = 336  # 표시 84pt × @4x — 09-05 부터 정본이 4096 이라 12배 축소다(밀도가 남는다)


def 시트경로(캐릭터):
    # 몽글 시트는 08-23 부터 이 이름으로 살았다 — 개명하면 옛 시트가 낡은 채 남는다.
    return os.path.join(DST, "마스코트_시트.png" if 캐릭터 == "몽글" else f"마스코트_시트_{캐릭터}.png")


def 변환(캐릭터):
    낱장들 = []
    for 이름 in 컷들[캐릭터]:
        원본 = Image.open(os.path.join(SRC[캐릭터], f"{이름}.png")).convert("RGBA")
        assert 원본.size == (4096, 4096), f"{이름}: 정본 크기가 아니다 {원본.size}"
        작게 = 원본.resize((크기, 크기), Image.LANCZOS)
        나갈길 = os.path.join(DST, f"{이름}.webp")
        작게.save(나갈길, "WEBP", quality=92, method=6)

        # 실측 — 모서리는 뚫려 있고(α=0) 중심은 차 있다(불투명). 조용한 흰 판 반입을 막는다.
        a = np.asarray(작게)[:, :, 3]
        모서리 = int(a[0, 0]) + int(a[0, -1]) + int(a[-1, 0]) + int(a[-1, -1])
        중심 = int(a[크기 // 2, 크기 // 2])
        assert 모서리 == 0, f"{이름}: 모서리 α {모서리} — 누끼가 아니다"
        assert 중심 > 200, f"{이름}: 중심 α {중심} — 몸이 비었다"
        kb = os.path.getsize(나갈길) / 1024
        print(f"  · {이름}.webp  {크기}px · {kb:.0f}KB · 모서리α 0 · 중심α {중심}")
        낱장들.append(작게)

    # 눈검수 시트 — 어두운 지면(앱 바탕 #080605)에 나란히. 라이트에 얹으면 알파 구멍이 안 보인다
    # (누끼 README 「구슬 하이라이트 114px 구멍」이 정확히 그렇게 숨었다).
    판 = Image.new("RGBA", (크기 * len(낱장들) + 40, 크기 + 40), (8, 6, 5, 255))
    for i, im in enumerate(낱장들):
        판.paste(im, (20 + i * 크기, 20), im)
    판.convert("RGB").save(시트경로(캐릭터), "PNG")
    print(f"  · 시트 → {os.path.relpath(시트경로(캐릭터), os.path.join(DST, '..', '..'))}")


if __name__ == "__main__":
    대상 = sys.argv[1:] or list(컷들)
    for 캐릭터 in 대상:
        assert 캐릭터 in 컷들, f"모르는 캐릭터 {캐릭터} — 어휘 = {list(컷들)}"
        print(f"[마스코트변환] {캐릭터} · 정본 {SRC[캐릭터]}")
        변환(캐릭터)
        print(f"[마스코트변환] {캐릭터} {len(컷들[캐릭터])}벌 완료 → {os.path.relpath(DST)}")
