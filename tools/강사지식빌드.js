'use strict';
/**
 * 강사지식빌드 — 매니페스트(`contents/강사지식_목록.json`)를 읽어 `contents/강사지식.js` 를 굽는다.
 *
 * ■ 자리 (정본 = `docs/컴패니언_내부계약.md` §3)
 *   companion Fn 이 강사 질문에 답할 때 프롬프트에 싣는 지식이다. 실시간 repo 읽기는 없다 —
 *   Fn 은 배포 시점에 구워진 이 파일만 본다(`동봉.json` · teach 의 `contents/서류관문문항.js` 선례).
 *
 * ■ 🔴 **화이트리스트지 필터가 아니다** (appsscript `엔진_두뇌.js:18-19` 원칙 ⑤ 승계)
 *   「이건 빼자」가 아니라 「이것만 싣는다」다. 목록에 없는 문서는 **구조적으로 못 실린다** —
 *   빼는 쪽을 세면 새 문서가 생길 때마다 사람이 기억해야 하고, 잊은 방향은 언제나 「노출」이다.
 *
 * ■ 🔴 경로 가드 — 이 도구가 **기계로** 지는 몫 (4칸 중 「_ops 닫힘·원장만」)
 *   매니페스트에 `_ops`·`_archive`·보안·급여·재무 경로 조각이 오면 **빌드가 죽는다**.
 *   프로즈로 「넣지 마세요」라고 적는 대신 기계에 물리는 이유는 CLAUDE.md 신뢰성 절 그대로다 —
 *   여기서 안 막으면 막는 자리가 사람의 기억뿐이고, 그 기억이 틀린 날은 알 방법이 없다.
 *   ⚠ 이 가드가 틀릴 때의 모습 = **거짓양성**이다(맹점 ④). 멀쩡한 문서 경로에 `재무` 같은
 *     낱말이 우연히 들어가면 빌드가 죽고 사람은 이유를 모른다 — 그래서 죽을 때 **어느 조각이
 *     걸렸는지**를 그대로 찍고, 탐지력은 픽스처(`tests/강사지식.test.js`)가 진다.
 *
 * ■ 생성물에 **원본 경로 + 원본 커밋 해시**를 함께 굽는다
 *   구운 뒤 원본이 바뀌면 생성물은 조용히 낡는다. 해시가 있으면 낡음을 잴 수 있다 —
 *   재는 것은 `tests/강사지식.test.js` 몫이고, 형제 저장소(appsscript)가 없는 CI 에서는
 *   **skip 으로 드러낸다**(F296 · 없는 것을 fail 로 적으면 남의 배포가 막힌다).
 *
 * ■ 쓰는 법
 *   node tools/강사지식빌드.js            # 굽는다
 *   node tools/강사지식빌드.js --확인      # 굽지 않고 «지금 구우면 달라지나»만 본다(0=같다)
 */

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { 공용플래그, 인자게이트 } = require('../lib/플래그.js');   // 모르는 낱말 거절(공용 판정 · F435)

/* 이 도구가 아는 낱말 — `공용플래그` 를 펴 넣는다(빠뜨리면 되던 명령이 죽는다 · F103). */
const 아는플래그 = [...공용플래그, '--확인'];

const 뿌리 = path.resolve(__dirname, '..');
const 매니페스트경로 = path.join(뿌리, 'contents', '강사지식_목록.json');
const 생성물경로 = path.join(뿌리, 'contents', '강사지식.js');

/** 형제 저장소 — `as:` 항목이 여기서 온다. 같은 부모 아래 나란히 있는 것이 이 기계의 전제다. */
const 저장소뿌리 = {
  talk: 뿌리,
  as: path.resolve(뿌리, '..', 'SYNK-appsscript'),
};

function die(줄) {
  console.error(`[강사지식빌드] ${줄}`);
  process.exit(1);
}

/* ── 경로 가드 ───────────────────────────────────────────────────────
 * 🔴 **금지 조각**은 소문자로 비교하지 않는다 — 전부 한글이거나 `_` 접두라 대소문자 축이 없고,
 *   낮춰 비교하면 영문 경로에서 엉뚱한 것이 걸린다. 사람이 실제로 쓰는 표기 그대로 센다(맹점 ①). */
const 금지조각 = [
  '_ops',        // 운영 장부·보드·인계문 — 원장만 본다
  '_archive',    // 걷어낸 옛판 — 실린 순간 낡은 것이 정본 얼굴을 한다
  '정본/SYNK 보안',
  '급여',
  '재무',
  '전략',
];

/** 경로 하나를 판정한다 — 걸린 조각을 돌려주고, 없으면 null. **순수 함수**라 픽스처가 문다(F296). */
function 막힌조각(경로) {
  const 정규 = String(경로).replace(/\\/g, '/');
  return 금지조각.find((조각) => 정규.includes(조각)) || null;
}

/* ── ⛔ 게이트 ───────────────────────────────────────────────────────
 * 자주묻는질문 정본은 **주제만** 싣는다(계약 §3 ⑧). ⛔ 는 「유호님 확정 전」이라 답이 아직
 * 없는 칸이고, 본문에는 그 자리에 «권고»·«범위»가 적혀 있다 — 그것이 강사 입을 통해 나가면
 * 확정 안 된 것이 확정된 얼굴로 학부모에게 닿는다. 그래서 제목(=주제)만 남기고 몸을 버린다.
 *
 * 🔑 버리는 것이지 «가리는» 것이 아니다 — 모델이 못 보면 지어낼 수도 없다.
 * 🔴 제목을 남기는 이유: 지우면 강사가 물었을 때 봇이 «그런 항목 자체가 없다»고 답한다.
 *   주제가 있으면 「그건 아직 확정 전이라 원장님께 넘긴다」가 된다 — 그게 인계의 정확도다.
 */
const 인계표시 = '  (⛔ 유호님 확정 전 — 답하지 않는다. 물으면 원장에게 넘긴다.)';

function 주제만걸기(글) {
  const 줄들 = String(글).split('\n');
  const 결과 = [];
  let 버리는중 = false;
  for (const 줄 of 줄들) {
    const 제목인가 = /^#{1,6}\s/.test(줄);
    if (제목인가) {
      /* 🔴 새 제목을 만나면 **무조건** 버리기를 끝낸다 — 끝내지 않으면 ⛔ 하나가
       *   그 뒤 문서 전체를 삼킨다(새는 방향이 「덜 실림」이라 조용하다). */
      버리는중 = 줄.includes('⛔');
      결과.push(줄);
      if (버리는중) 결과.push(인계표시);
      continue;
    }
    if (!버리는중) 결과.push(줄);
  }
  return 결과.join('\n');
}

/* 🔑 표의 **열쇠**가 매니페스트에 적히는 이름이다(`⛔주제만`) — 함수 이름은 `⛔` 를 못 쓴다
 *   (JS 식별자가 아니다). 사람이 읽는 쪽은 열쇠, 기계가 부르는 쪽은 함수 이름으로 갈라 둔다. */
const 게이트표 = { '⛔주제만': 주제만걸기 };

/* ── 굽기 ────────────────────────────────────────────────────────── */

/** 그 파일을 마지막으로 만진 커밋. 못 읽으면 `'(모름)'` — 없는 것을 지어내지 않는다. */
function 커밋해시(저장소, 상대경로) {
  try {
    const out = execFileSync('git', ['-C', 저장소, 'log', '-1', '--format=%H', '--', 상대경로], {
      encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'],
    });
    return out.trim() || '(미추적)';
  } catch (_) {
    return '(모름)';
  }
}

function 매니페스트읽기() {
  if (!fs.existsSync(매니페스트경로)) die(`매니페스트가 없다: ${path.relative(뿌리, 매니페스트경로)}`);
  let 표;
  try {
    표 = JSON.parse(fs.readFileSync(매니페스트경로, 'utf8'));
  } catch (e) {
    die(`매니페스트가 JSON 이 아니다 — ${e.message}`);
  }
  const 항목 = Array.isArray(표 && 표.항목) ? 표.항목 : null;
  if (!항목 || !항목.length) die('매니페스트에 `항목` 배열이 없거나 비었다 — 지식 0벌은 굽지 않는다.');

  const 이름들 = new Set();
  for (const it of 항목) {
    if (!it || !it.이름 || !it.경로 || !it.저장소) {
      die(`항목에 이름·저장소·경로 중 빠진 칸이 있다: ${JSON.stringify(it)}`);
    }
    if (!저장소뿌리[it.저장소]) die(`모르는 저장소 \`${it.저장소}\` — 아는 것은 ${Object.keys(저장소뿌리).join('·')} 뿐이다.`);
    /* 🔴 이름은 companion 의 cited_refs 화이트리스트 값이다 — 겹치면 어느 문서를 인용한 것인지
     *   원리상 못 가른다. 그 모호함은 «출처 있는 답»의 얼굴을 하고 남으므로 여기서 죽인다. */
    if (이름들.has(it.이름)) die(`이름이 겹친다: ${it.이름} — cited_refs 화이트리스트 값이라 유일해야 한다.`);
    이름들.add(it.이름);
    if (it.게이트 && !게이트표[it.게이트]) {
      die(`모르는 게이트 \`${it.게이트}\`(${it.이름}) — 아는 것은 ${Object.keys(게이트표).join('·')} 뿐이다.`);
    }
    const 걸림 = 막힌조각(it.경로);
    if (걸림) {
      die(`경로 가드: \`${it.이름}\` 의 경로에 금지 조각 «${걸림}» 이 있다 — ${it.경로}\n`
        + '       이 층은 강사에게 안 연다(계약 §3 · _ops 닫힘·원장만). 정말 열어야 하면 계약부터 고친다.');
    }
  }
  return 항목;
}

function 조립() {
  const 항목 = 매니페스트읽기();
  const 조각 = [];
  const 대장 = [];

  for (const it of 항목) {
    const 저장소 = 저장소뿌리[it.저장소];
    const 전체 = path.join(저장소, it.경로);
    if (!fs.existsSync(전체)) {
      die(`원본이 없다: ${it.저장소}:${it.경로}\n`
        + (it.저장소 === 'as'
          ? `       형제 저장소를 못 찾았을 수 있다 — 기대한 자리: ${저장소}`
          : '       매니페스트의 경로가 낡았다.'));
    }
    let 본문 = fs.readFileSync(전체, 'utf8');
    if (it.게이트) 본문 = 게이트표[it.게이트](본문);

    const 해시 = 커밋해시(저장소, it.경로);
    대장.push({ 이름: it.이름, 저장소: it.저장소, 경로: it.경로, 커밋: 해시, 게이트: it.게이트 || null, 글자: [...본문].length });
    조각.push(
      `━━━ ${it.이름} ━━━\n`
      + `(출처: ${it.저장소}:${it.경로}${it.게이트 ? ` · 게이트 ${it.게이트}` : ''})\n\n`
      + 본문.trim() + '\n',
    );
  }

  return { 대장, 지식: 조각.join('\n\n') };
}

function 파일글(대장, 지식) {
  const 표 = 대장.map((d) => `
 *   · ${d.이름} — ${d.저장소}:${d.경로}
 *     커밋 ${d.커밋}${d.게이트 ? ` · 게이트 ${d.게이트}` : ''} · ${d.글자.toLocaleString('en-US')}자`).join('');

  return `'use strict';
/**
 * 강사 지식 v0 — **생성물이다. 손으로 안 고친다.**
 *
 * 굽는 통로: \`node tools/강사지식빌드.js\` (매니페스트 = \`contents/강사지식_목록.json\`)
 * 정본 사슬: \`docs/컴패니언_내부계약.md\` §3
 *
 * ■ 실린 것 (원본 경로 + 그 파일의 마지막 커밋)${표}
 *
 * ⚠ 낡음은 \`tests/강사지식.test.js\` 가 잰다 — 형제 저장소(appsscript)가 없는 CI 에서는
 *   그 검사가 **skip** 으로 드러난다(F296). 초록을 분모 없이 읽지 않는다.
 */

/** companion 프롬프트에 통째로 실리는 지식. 문서 경계는 \`━━━ 이름 ━━━\` 줄이다. */
const 강사지식 = ${JSON.stringify(지식)};

/** cited_refs 화이트리스트 — 모델이 이 목록 밖 이름을 대면 companion 이 버린다. */
const 문서이름 = ${JSON.stringify(대장.map((d) => d.이름), null, 2).replace(/\n/g, '\n')};

/** 낡음 대조용 대장(경로·커밋). 프롬프트엔 안 실린다. */
const 출처대장 = ${JSON.stringify(대장.map((d) => ({ 이름: d.이름, 저장소: d.저장소, 경로: d.경로, 커밋: d.커밋, 게이트: d.게이트 })), null, 2)};

module.exports = { 강사지식, 문서이름, 출처대장 };
`;
}

function main() {
  const args = process.argv.slice(2);
  const 플래그오류 = 인자게이트('강사지식빌드', args, 아는플래그);   // 모르는 낱말은 여기서 죽는다(F435)
  if (플래그오류) die(플래그오류);

  const { 대장, 지식 } = 조립();
  const 새글 = 파일글(대장, 지식);

  if (args.includes('--확인')) {
    const 옛글 = fs.existsSync(생성물경로) ? fs.readFileSync(생성물경로, 'utf8') : '';
    if (옛글 === 새글) {
      console.log(`[강사지식빌드] 같다 — ${대장.length}벌 · ${[...지식].length.toLocaleString('en-US')}자`);
      process.exit(0);
    }
    console.error('[강사지식빌드] 다르다 — `node tools/강사지식빌드.js` 로 다시 구워야 한다.');
    process.exit(1);
  }

  fs.writeFileSync(생성물경로, 새글, 'utf8');
  console.log(`[강사지식빌드] 구웠다 — ${대장.length}벌 · ${[...지식].length.toLocaleString('en-US')}자 → ${path.relative(뿌리, 생성물경로)}`);
  for (const d of 대장) {
    console.log(`  · ${d.이름.padEnd(22)} ${String(d.글자).padStart(7)}자  ${d.커밋.slice(0, 8)}${d.게이트 ? `  [${d.게이트}]` : ''}`);
  }
}

if (require.main === module) main();

module.exports = { 막힌조각, 주제만걸기, 금지조각 };
