#!/usr/bin/env node
'use strict';
/* 동봉신호 — 방금 커밋한 파일이 Edge Function 으로 **나갈 것**이면 그 자리에서 알린다.
 *
 * ■ 왜 있나 (F313 · 2026-08-10 실측)
 *   `lib/검수확정.js` 의 **주석만** 고쳐 커밋했다. 내 커밋은 초록이고 회귀도 초록이었다.
 *   그런데 그 파일은 `supabase/functions/review/동봉.json` 이 실어 나르는 파일이라,
 *   `배포대조` 는 즉시 `review` 를 「다르다」로 잡았고 `왕복전게이트` 는 다름 1건에 exit 1 로
 *   차단한다 → 그 순간부터 talk 의 **모든 왕복시험이 살아있는 세션 전부에게** 막혔다.
 *
 *   🔑 급소는 크기가 아니라 **비대칭**이다. 편집한 쪽엔 증상이 0 이고, 빨개지는 건 남의 화면이다.
 *   그래서 「조심하자」로는 안 막힌다 — 신호가 편집한 사람에게 가야 한다.
 *
 * ■ 무엇을 안 하나 (설계 제약 · 대기열 P3)
 *   · **막지 않는다.** 배포는 라이브를 바꾸는 승인 자리다. 커밋을 막으면 우회가 정상 통로가
 *     된다(F103) — 따를 수 없는 처방은 규칙이 아니라 구멍이다. 그래서 `post-commit` 이다.
 *   · **네트워크 0.** `배포대조` 를 여기서 부르지 않는다 — 커밋 경로에 네트워크를 넣으면
 *     오프라인·자격증명 없는 세션에서 커밋마다 멈춰 선다. 여기서는 로컬 파일만 본다.
 *   · 표를 여기서 다시 읽지 않는다 — `원격배포.동봉목록` 하나에서 파생시킨다(갈라지면 조용하다).
 *
 * 사용:
 *   node tools/동봉신호.js            방금 커밋(HEAD)
 *   node tools/동봉신호.js <커밋>     아무 커밋이나
 */
const path = require('path');
const { execFileSync } = require('child_process');
const { 동봉목록 } = require('./원격배포.js');

const ROOT = path.join(__dirname, '..');

/* git 의 `-z` 출력(NUL 구분)을 경로 배열로.
 * 🔴 **`-z` 가 아니면 이 장치는 통째로 죽는다.** git 은 기본값에서 비ASCII 경로를 따옴표로 싸고
 *   바이트를 이스케이프해 내보낸다(`"lib/\355\206\240\355\201\260.js"`). 동봉 값은 **전부 한글**이라
 *   그 표기로는 어느 경로도 표에 안 맞는다 — 그리고 안 맞으면 하는 일이 「조용함」이라
 *   정상과 **같은 모양**이다. 재는 층이 값을 깨뜨리는 자리다(CLAUDE.md 판정·검증). */
function 경로들파싱(z출력) {
  return String(z출력).split('\0').filter(Boolean);
}

/** 커밋 하나가 바꾼 경로 전량(저장소 상대·`/` 표기). 병합 커밋은 빈 배열이다(편집이 아니다). */
function 커밋된경로들(root = ROOT, ref = 'HEAD') {
  const out = execFileSync(
    'git',
    ['diff-tree', '--no-commit-id', '--name-only', '-r', '-z', '--root', ref],
    { cwd: root, encoding: 'utf8' },
  );
  return 경로들파싱(out);
}

/** 커밋된 경로 × 동봉 목록 → 재배포까지가 한 벌인 함수들. **순수 함수** — 파일도 git 도 안 본다.
 *
 *  두 갈래를 나눠 담는다:
 *    · `동봉` — 함수 폴더 **밖**에 있는데 실려 나가는 파일(F313 의 그 자리 · 편집자에게 안 보인다)
 *    · `본체` — 함수 폴더 안의 파일(`index.ts`·`동봉.json` 포함). 여기도 안 밀면 같은 적색이 난다
 *      (본체는 바이트로 못 대조해 **시각 축**이 대신 잡는다 · `배포대조.시각뒤처짐`). */
function 영향받은함수(커밋된경로들목록, 목록) {
  const 커밋됨 = new Set(커밋된경로들목록);
  const out = [];
  for (const f of 목록) {
    const 동봉 = f.경로들.filter((p) => 커밋됨.has(p));
    const 본체 = 커밋된경로들목록.filter((p) => p.startsWith(`${f.디렉터리}/`));
    if (동봉.length || 본체.length) out.push({ slug: f.slug, 디렉터리: f.디렉터리, 동봉, 본체 });
  }
  return out;
}

/** 사람이 읽을 안내문. 순수 함수라 회귀가 문구까지 잰다.
 *
 *  @param 빚줄들 «지금까지 안 갚은 배포 빚» 요약 줄들(없으면 빈 배열). F455 가 연 칸이다 —
 *    이 신호는 **탐지는 정확했는데**(`49d4feb` 에서 다섯 함수를 이름까지 댔다) 그 말이
 *    그 순간의 stdout 에만 살아서, 그 자리에서 못 갚은 빚은 어디에도 안 남았다.
 *    그래서 이제 커밋마다 «방금 진 빚»과 «아직 안 갚은 빚»을 함께 낸다. */
function 안내문(영향, 빚줄들 = []) {
  const 줄 = [
    '',
    '[동봉신호] 방금 커밋이 Edge Function 으로 **나갈 파일**을 바꿨다 — 재배포까지가 한 벌이다.',
    '           안 밀면 `배포대조` 가 「다르다」로 잡고 `왕복전게이트` 가 다름 1건에 exit 1 로 막는다.',
    '           🔑 내 화면은 초록이라 증상이 0 이다 — 빨개지는 건 **남의 왕복시험**이다(F313).',
    '',
  ];
  for (const f of 영향) {
    const 사유 = [
      f.동봉.length ? `동봉 ${f.동봉.join(' · ')}` : '',
      f.본체.length ? `본체 ${f.본체.join(' · ')}` : '',
    ].filter(Boolean).join('  |  ');
    줄.push(`  · ${f.slug}  ←  ${사유}`);
    줄.push(`      node tools/원격배포.js ${f.디렉터리} --적용`);
  }
  if (빚줄들.length) {
    줄.push('');
    줄.push('  ── 아직 안 갚은 배포 빚 (이 커밋 것만이 아니다 · F455) ──');
    for (const b of 빚줄들) 줄.push(`  ${b}`);
  }
  줄.push('');
  줄.push('  ⚠ 배포는 라이브를 바꾼다 — 승인 자리다. 이 신호는 **알리기만 하고 아무것도 막지 않는다.**');
  줄.push('');
  return 줄.join('\n');
}

/** 판별 «남은 빚» 한 줄씩. 실패하면 **빈 배열** — 알림 하나가 못 서서 신호 전체가 죽으면 안 된다. */
function 빚요약() {
  try {
    const 배포빚 = require('./배포빚.js');
    const 장부 = 배포빚.장부읽기();
    return 배포빚.판들.map((판) => `${배포빚.요약문(판, 배포빚.판정하기(판, 장부))}`);
  } catch { return []; }
}

function main() {
  const ref = process.argv.slice(2).find((a) => !a.startsWith('--')) || 'HEAD';
  const 영향 = 영향받은함수(커밋된경로들(ROOT, ref), 동봉목록(ROOT));
  if (영향.length) console.log(안내문(영향, 빚요약()));
}

module.exports = { 경로들파싱, 커밋된경로들, 영향받은함수, 안내문, 빚요약 };

if (require.main === module) {
  /* 알림이지 가드가 아니다 — 어떤 실패도 커밋 뒤 흐름을 흔들지 않는다.
   * (post-commit 은 종료코드로 커밋을 되돌리지 못한다. 그래도 조용히 끝낸다.) */
  try { main(); } catch (_) { /* 무시 */ }
}
