/* ── 자연층 — 비·파도·바람 (장르 ③) ─────────────────────────────────────
 * 🔑 **합성으로 만든다**(유호 08-25 「직접 녹음은 비효율」 — 샘플을 사도 되지만 합성은 공짜에
 *   즉시고 무엇보다 **루프 안전**하다: 감길 때 이음새가 원리상 안 생긴다).
 *   나중에 실제 샘플을 얹고 싶으면 이 층 «위에» 더하면 된다 — 자리를 그렇게 비워 뒀다.
 * 🔑 흔들림 주기는 전부 루프의 «정수 분할»이다. 아니면 한 바퀴 돌 때마다 파도가 튄다.
 */
function 자연층(종류, N, rnd, 세기) {
  const L = new Float64Array(N), R = new Float64Array(N);
  const 대역 = (x, 저, 고) => { // 아주 단순한 2극 밴드패스 — 저역 뺀 뒤 고역을 깎는다
    let z1 = 0, z2 = 0;
    const a1 = Math.exp(-2 * Math.PI * 저 / SR), a2 = Math.exp(-2 * Math.PI * 고 / SR);
    for (let i = 0; i < x.length; i++) {
      z1 = (1 - a1) * x[i] + a1 * z1;
      const hp = x[i] - z1;
      z2 = (1 - a2) * hp + a2 * z2;
      x[i] = z2;
    }
    return x;
  };
  const 씨소리 = () => { const a = new Float64Array(N); for (let i = 0; i < N; i++) a[i] = rnd(); return a; };

  if (종류 === 'rain') {
    // 바탕 = 고역 쉿 + 그 위에 «방울» 임펄스. 방울이 없으면 비가 아니라 그냥 노이즈다.
    const bl = 대역(씨소리(), 900, 9000), br = 대역(씨소리(), 900, 9000);
    for (let i = 0; i < N; i++) { L[i] += bl[i] * 0.5; R[i] += br[i] * 0.5; }
    const 방울수 = Math.round(N / SR * 90);          // 초당 90방울
    for (let d = 0; d < 방울수; d++) {
      const 시작 = Math.floor(((rnd() + 1) / 2) * N);
      const 길이 = Math.round(SR * (0.004 + 0.012 * (rnd() + 1) / 2));
      const 팬 = rnd() * 0.8;
      const g = 0.9 + 0.6 * rnd();
      for (let k = 0; k < 길이; k++) {
        const n = (시작 + k) % N;
        const env = Math.exp(-k / (길이 * 0.3)) * g;
        const v = rnd() * env;
        L[n] += v * (1 - Math.max(0, 팬)) * 0.5;
        R[n] += v * (1 + Math.min(0, 팬)) * 0.5;
      }
    }
  } else if (종류 === 'waves') {
    // 파도 = 넓은 노이즈에 «숨»(느린 진폭)과 밝기 변화를 함께 건다. 주기 = 루프의 정수 분할.
    const bl = 대역(씨소리(), 180, 2600), br = 대역(씨소리(), 180, 2600);
    const 주기 = 2;                                   // 루프 한 바퀴에 파도 두 번
    for (let i = 0; i < N; i++) {
      const p = 0.5 - 0.5 * Math.cos(2 * Math.PI * 주기 * i / N);
      const env = Math.pow(p, 1.7);                   // 밀려왔다 천천히 빠진다
      L[i] += bl[i] * env; R[i] += br[i] * env;
    }
  } else { // 'wind' — 바람에 스치는 잎(자작나무)
    const bl = 대역(씨소리(), 400, 5200), br = 대역(씨소리(), 400, 5200);
    const 주기1 = 3, 주기2 = 5;                        // 두 주기를 겹쳐 «불규칙해 보이게»
    for (let i = 0; i < N; i++) {
      const g = 0.45 + 0.3 * Math.sin(2 * Math.PI * 주기1 * i / N)
                     + 0.25 * Math.sin(2 * Math.PI * 주기2 * i / N + 1.1);
      const env = Math.max(0, g);
      L[i] += bl[i] * env; R[i] += br[i] * env;
    }
  }
  // 정규화 뒤 세기 — 종류마다 크기가 제각각이라 여기서 한 자로 맞춘다
  let 피크 = 0;
  for (let i = 0; i < N; i++) 피크 = Math.max(피크, Math.abs(L[i]), Math.abs(R[i]));
  const k = 피크 ? 세기 / 피크 : 0;
  for (let i = 0; i < N; i++) { L[i] *= k; R[i] *= k; }
  return [L, R];
}

