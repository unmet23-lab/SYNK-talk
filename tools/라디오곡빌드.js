/* ── 효과층 — 「깨끗하지만 얇다」를 고치는 넷 (유호 확정 08-25 「음질 넷부터」) ────────
 *
 * 🔑 **전부 «루프 안전»해야 한다.** 이 곡들은 감겨 도는 루프라 꼬리가 끝에서 잘리면 매 바퀴
 *   «턱»이 든다. 그래서 규율 하나를 전 효과에 건다 — **입력을 두 바퀴 이어 붙여 처리하고
 *   «둘째 바퀴»만 취한다.** 첫 바퀴가 남긴 꼬리(잔향·지연)가 둘째 바퀴의 머리에 이미 실려
 *   있어 이음새가 연속이 된다. 재는 자 = 산출 뒤 이음새 대조(설계 §4).
 *
 * ⚠ 대가: 잔향이 표본을 두 배로 훑는다. 29초 곡에서 곡당 몇 초, **6분 곡이면 분 단위**다
 *   (설계 §3-B 가 방송 판을 6분으로 못박았으므로 이 비용은 곧 현실이 된다 — 그때는
 *   잔향을 한 번만 계산해 좌우로 나누거나, 굽기를 밤에 돌린다).
 */

/** 두 바퀴 처리 → 둘째 바퀴만. 꼬리 있는 효과는 전부 이 통로를 지난다. */
function 루프안전(x, 처리) {
  const N = x.length;
  const 두바퀴 = new Float64Array(N * 2);
  두바퀴.set(x, 0); 두바퀴.set(x, N);
  return 처리(두바퀴).subarray(N, N * 2);
}

/* ① 잔향 — 콤 8 + 올패스 4 (Schroeder 계열).
 *   왜 필요한가: 지금 소리에 «공간»이 0이라 악기가 전부 코앞에서 난다. 「얇다」의 절반이 이것이다. */
const 콤길이 = [1116, 1188, 1277, 1356, 1422, 1491, 1557, 1617];   // 44.1kHz 정본 튜닝
const 올패스길이 = [556, 441, 341, 225];
function 잔향(x, opt) {
  const { 방크기 = 0.84, 감쇠 = 0.28, 확산 = 23 } = opt || {};
  return 루프안전(x, function (입력) {
    const n = 입력.length;
    const out = new Float64Array(n);
    for (let c = 0; c < 콤길이.length; c++) {
      const d = 콤길이[c] + 확산;
      const buf = new Float64Array(d);
      let idx = 0, 저역 = 0;
      for (let i = 0; i < n; i++) {
        const y = buf[idx];
        out[i] += y;
        저역 = y * (1 - 감쇠) + 저역 * 감쇠;          // 콤 안 감쇠 = 잔향이 «어두워지며» 사라진다
        buf[idx] = 입력[i] + 저역 * 방크기;
        if (++idx >= d) idx = 0;
      }
    }
    for (let i = 0; i < n; i++) out[i] /= 콤길이.length;
    for (const L of 올패스길이) {                       // 올패스 = 메아리를 «뭉개» 자연스럽게
      const d = L + 확산;
      const buf = new Float64Array(d);
      let idx = 0;
      for (let i = 0; i < n; i++) {
        const y = buf[idx];
        const v = out[i] + y * 0.5;
        buf[idx] = v;
        out[i] = y - v * 0.5;
        if (++idx >= d) idx = 0;
      }
    }
    return out;
  });
}

/* ② 코러스 — 흔들리는 지연 셋.
 *   왜 필요한가: 첫 판 좌우상관이 0.97(거의 모노)이었다. 시티팝은 «넓이»가 정체다.
 *   🔑 루프 버퍼라 음수 인덱스가 «지난 바퀴»로 감긴다 — 지연선을 따로 안 들고도 루프 안전이다. */
function 코러스(xL, xR, opt) {
  const 세기 = (opt && opt.세기) != null ? opt.세기 : 0.5;
  const N = xL.length;
  const 성부 = [
    { 기준ms: 11, 폭ms: 3.4, Hz: 0.23, 왼쪽: true },
    { 기준ms: 17, 폭ms: 4.1, Hz: 0.31, 왼쪽: false },
    { 기준ms: 24, 폭ms: 2.6, Hz: 0.17, 왼쪽: true },
  ];
  const oL = new Float64Array(N), oR = new Float64Array(N);
  for (const v of 성부) {
    const 원 = v.왼쪽 ? xL : xR;
    /* 흔들림 주기를 루프의 «정수 분할»로 반올림한다 — 안 그러면 감길 때 위상이 튄다. */
    const 주기 = Math.max(1, Math.round(v.Hz * N / SR));
    for (let i = 0; i < N; i++) {
      const lfo = Math.sin(2 * Math.PI * 주기 * i / N);
      const d = (v.기준ms + v.폭ms * lfo) * SR / 1000;
      const i0 = Math.floor(d), frac = d - i0;
      const a = 원[((i - i0) % N + N) % N];
      const b = 원[((i - i0 - 1) % N + N) % N];
      const 값 = (a * (1 - frac) + b * frac) * 세기;
      oL[i] += 값 * (v.왼쪽 ? 1 : 0.35);
      oR[i] += 값 * (v.왼쪽 ? 0.35 : 1);
    }
  }
  return [oL, oR];
}

/* ③ 덕킹(사이드체인) — 킥이 칠 때 화성이 숨을 죽인다.
 *   없으면 킥과 화성이 같은 자리에서 부딪혀 저역이 뭉친다. 있으면 곡이 «맥동»한다 —
 *   Daft Punk 결(장르 ②)의 절반이 이 펌핑이다. */
function 덕킹곡선(N, 킥시각들, opt) {
  const { 깊이 = 0.4, 회복초 = 0.26 } = opt || {};
  const g = new Float64Array(N).fill(1);
  const 길이 = Math.max(1, Math.round(회복초 * SR));
  for (const t of 킥시각들) {
    const 시작 = Math.round(t * SR);
    for (let k = 0; k < 길이; k++) {
      const n = ((시작 + k) % N + N) % N;
      const 값 = 1 - 깊이 * Math.pow(1 - k / 길이, 2);   // 즉시 눌리고 제곱으로 되돌아온다
      if (값 < g[n]) g[n] = 값;
    }
  }
  return g;
}

