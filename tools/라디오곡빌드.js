/* ── 음정 — 12평균율 전부(라디오 자리에서만 넓힌다 · 위 표) ────────────── */
const 반음표 = { C: -9, 'C#': -8, D: -7, 'D#': -6, E: -5, F: -4, 'F#': -3, G: -2, 'G#': -1, A: 0, 'A#': 1, B: 2 };
function 주파수(이름) {
  const m = /^([A-G]#?)(\d)$/.exec(String(이름));
  if (!m) throw new Error(`음 이름이 아니다: ${이름}`);
  return 440 * Math.pow(2, (반음표[m[1]] + (Number(m[2]) - 4) * 12) / 12);
}

/* ── 씨 고정 난수 — 노이즈(하이햇·셰이커)의 유일한 원천.
 *   🔑 `Math.random` 을 쓰면 재렌더 대조(`--check`)가 **원리상 못 돈다** — 손 편집 탐지가 통째로
 *      죽는다. 그래서 LCG 하나를 곡마다 같은 씨로 돌린다(같은 곡 = 같은 노이즈). */
function 난수기(씨) {
  let s = 씨 >>> 0;
  return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296 * 2 - 1; };
}

/* ── 신디시스 ───────────────────────────────────────────────────────────
 * 모든 음색은 사인 부분음의 합이다(규칙 ③ 승계). 넓힌 것은 «어느 음정을 쓰나»와 «타악» 둘뿐.
 */
/**
 * 음 하나를 원형(loop-wrap)으로 쓴다 — 끝이 처음으로 감겨 이음새가 안 들린다.
 * @param opt.부분음   [[배수, 진폭], …]
 * @param opt.떨림     {세기, Hz} — 진폭 트레몰로(로즈 특유의 흔들림). 없으면 0
 * @param opt.음높이감쇠 세미톤 — 시작에서 이만큼 위로 떴다가 60ms 안에 제자리(킥의 「퉁」)
 */
function 음쓰기(L, R, N, opt) {
  const { 시작초, 길이초, 주파수: f, 부분음, 어택, 릴리즈, 세기, 팬 = 0, 디튠 = 0,
    떨림 = null, 음높이감쇠 = 0 } = opt;
  const 시작 = Math.round(시작초 * SR);
  const 전체 = Math.round((길이초 + 릴리즈) * SR);
  const gL = 세기 * Math.cos((팬 + 1) * Math.PI / 4);
  const gR = 세기 * Math.sin((팬 + 1) * Math.PI / 4);
  const f0 = f * Math.pow(2, 디튠 / 1200);
  let 위상 = 0;
  for (let i = 0; i < 전체; i++) {
    const t = i / SR;
    let env;
    if (t < 어택) env = 0.5 - 0.5 * Math.cos((t / 어택) * Math.PI);
    else if (t < 길이초) env = Math.exp(-1.2 * (t - 어택));      // 로즈·베이스의 자연 감쇠
    else env = Math.exp(-1.2 * (길이초 - 어택)) * Math.exp(-4 * (t - 길이초) / 릴리즈);
    if (env <= 1e-5) continue;
    if (떨림) env *= 1 - 떨림.세기 * (0.5 - 0.5 * Math.cos(2 * Math.PI * 떨림.Hz * t));
    const 지금f = 음높이감쇠 ? f0 * Math.pow(2, (음높이감쇠 * Math.exp(-t / 0.03)) / 12) : f0;
    위상 += 2 * Math.PI * 지금f / SR;
    let s = 0;
    for (const [배, 진폭] of 부분음) s += Math.sin(위상 * 배) * 진폭;
    const n = (시작 + i) % N;
    L[n] += s * env * gL;
    R[n] += s * env * gR;
  }
}

/** 노이즈 한 방(하이햇·셰이커). 1차 고역통과 뒤 지수 감쇠 — 「치」 소리만 남는다. */
function 노이즈쓰기(L, R, N, opt) {
  const { 시작초, 길이초, 세기, 팬 = 0, 고역 = 7000, rnd } = opt;
  const 시작 = Math.round(시작초 * SR);
  const 전체 = Math.round(길이초 * SR);
  const gL = 세기 * Math.cos((팬 + 1) * Math.PI / 4);
  const gR = 세기 * Math.sin((팬 + 1) * Math.PI / 4);
  const a = Math.exp(-2 * Math.PI * 고역 / SR);
  let z = 0;
  for (let i = 0; i < 전체; i++) {
    const x = rnd();
    z = (1 - a) * x + a * z;
    const hp = x - z;                                   // 고역통과 = 원신호 − 저역
    const env = Math.exp(-i / SR / (길이초 * 0.32));
    const n = (시작 + i) % N;
    L[n] += hp * env * gL;
    R[n] += hp * env * gR;
  }
}

