/* ── 씨 고정 난수 — 노이즈(하이햇·셰이커)의 유일한 원천.
 *   🔑 `Math.random` 을 쓰면 재렌더 대조(`--check`)가 **원리상 못 돈다** — 손 편집 탐지가 통째로
 *      죽는다. 그래서 LCG 하나를 곡마다 같은 씨로 돌린다(같은 곡 = 같은 노이즈). */
function 난수기(씨) {
  let s = 씨 >>> 0;
  return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296 * 2 - 1; };
}

