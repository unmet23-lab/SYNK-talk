/** 포먼트 봉우리로 부분음 진폭을 만든다 — 사람 목소리·보코더가 그렇게 생겼다(전자 결의 얼굴). */
function 포먼트부분음(기음, 봉우리 = [520, 1480, 2500], 폭 = 340, 개수 = 18) {
  const 표 = [];
  for (let k = 1; k <= 개수; k++) {
    const f = 기음 * k;
    let a = 0;
    for (const F of 봉우리) a = Math.max(a, Math.exp(-Math.pow((f - F) / 폭, 2)));
    a *= Math.pow(k, -0.55);                       // 위로 갈수록 얇게 — 안 그러면 쇳소리가 난다
    if (a > 0.008) 표.push([k, a]);
  }
  return 표.length ? 표 : [[1, 1]];
}

