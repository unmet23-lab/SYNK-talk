'use strict';
/**
 * 녹음띠 — 말하기의 «한 땀»을 펠트로 보여주는 세 상태 (Loom 굽기 08-25 · 앱 반입 08-28).
 *
 * ■ 이 그림이 왜 있나
 *   appsscript `세트굽기.js` 의 구조2 세트 주석이 자기 존재 이유를 이렇게 적어 뒀다 —
 *   「🔴 녹음 — 이 공방의 가장 큰 구멍이었다. … 우리는 «말하기» 학원이고 학생이 가장 여러 번
 *   누르는 단추다. 상태 셋을 «따로» 굽는다 — 한 판에 늘어놓으면 유채가 둘이 되어 신호 1점이 깨진다.」
 *   08-25 에 구웠는데 **08-28 까지 앱에 한 장도 안 들어와 있었다**(받침이 켜진 채로 구워져
 *   알파가 프레임을 꽉 채웠고, 알파 크롭이 원리상 아무것도 못 잘랐다 — NPC 배지와 같은 병).
 *
 * ■ 세 상태가 말하는 것 — 이건 장식이 아니라 «문장»이다
 *   대기   = 실이 아직 안 꿰어짐 (바늘이 놓여 있다 · **코랄이 없다**)
 *   말하는중 = 꿰는 중 (바늘이 서고 코랄 땀이 따라온다)
 *   맺음   = 다 꿰었다 (땀이 끝까지 가고 매듭이 진다)
 *
 * ■ ✅ 이것이 **녹음 단추**다 (유호 확정 08-28 「녹음띠는 ㉮로 가자」 · 검수문 ⑦ 세 안 중 ㉮)
 *   말하기 화면과 알바변명 화면(녹음카드 공유)의 단추가 이 띠다. 코랄 원은 걷었다.
 *   🔴 **알고 고른 대가**: 대기 판에는 유채가 없어 **녹음 «전» 화면의 신호가 0점**이 된다
 *   (테마 R1 신호자리 = 녹음버튼). 그 대가를 검수문 ⑦ 에 적어 드린 뒤의 픽이므로
 *   **결함이 아니라 확정이다** — 「신호가 없다」를 고치겠다고 코랄 원을 되살리지 않는다.
 *   신호는 없는 것이 아니라 녹음이 시작되면 코랄 땀으로 «늦게 온다».
 *
 * ■ 실기기 확인(08-28 · 에뮬레이터 pixel · 대기→녹음중 전환까지)
 *   ⚠ 스크린샷으로 검수할 때 **찍는 시점을 조심한다**: 안드로이드 Image 는 기본 페이드인이 있어
 *   탭 «직후»에 찍으면 띠가 없거나 반투명하게 나온다. 나는 그것을 「안 그려진다」로 한 번 오독했다.
 *   화면이 «가라앉을 때까지»(연속 두 장이 같아질 때까지) 기다렸다가 찍는다.
 *   단 녹음 «중»에는 맥박이 계속 뛰어 영영 안 가라앉으니, 그때는 여러 장 찍어 고른다.
 *   (08-31 fadeDuration 0 으로 껐다 — 이 함정은 다른 Image 자리에만 남는다)
 */
import { Image, StyleSheet, View } from 'react-native';

/* 굽기 산출 → `tools/부품변환.py` → 여기. 셋은 **한 자로 잘려** 같은 틀(1024×563)이다 —
 * 각자 제 알파로 자르면 높이가 444·482·363 으로 갈려 상태가 바뀔 때마다 띠가 커졌다 작아졌다 한다
 * (08-28 실측 · 그래서 변환기가 «묶음은 한 자로» 자른다). */
const 그림 = {
  대기: require('../assets/부품/구조2/녹음_대기.webp'),
  말하는중: require('../assets/부품/구조2/녹음_말하는중.webp'),
  맺음: require('../assets/부품/구조2/녹음_맺음.webp'),
};

export const 상태들 = ['대기', '말하는중', '맺음'];

/* 🔑 가로세로비를 **손으로 안 적는다** — «자른 이»가 적은 장부를 읽는다.
 *   08-28 에 변환기를 「긴 변 기준·확대 금지」로 고치자 1024×563 이 **1022×563** 이 됐다.
 *   여기 `563/1024` 를 박아 뒀더라면 그 순간 조용히 틀린 수가 됐을 것이다(눈에 안 띄는 0.2% 다).
 *   ⚠ `Image.resolveAssetSource` 로 묻는 길도 해 봤는데 **회귀에서 못 쓴다** — 테스트가 자산을
 *     파일 이름 문자열로 세우므로 그 함수가 없다(08-28 실측 · 화면 셋이 통째로 빨개졌다).
 *   ⇒ `tools/부품변환.py` 가 자를 때 `assets/부품/치수.json` 에 적는다. 값의 주인이 하나다.
 *   셋은 «한 자»로 잘려 크기가 같으므로 대표 한 장을 본다. */
const 치수 = require('../assets/부품/치수.json');
const _대표 = 치수['구조2/녹음_대기'];
if (!_대표) throw new Error('🔴 치수장부에 구조2/녹음_대기 가 없다 — python tools/부품변환.py 를 돌려라');
export const 가로세로비 = _대표[1] / _대표[0];

/**
 * @param {'대기'|'말하는중'|'맺음'} 상태
 * @param {number} 폭   띠의 가로 px. 세로는 비율이 정한다.
 */
export default function 녹음띠({ 상태 = '대기', 폭 = 240, 스타일 }) {
  const 그것 = 그림[상태] || 그림.대기;
  return (
    <View style={[{ width: 폭, height: Math.round(폭 * 가로세로비) }, 스타일]}>
      <Image source={그것} style={s.그림} resizeMode="contain" accessibilityIgnoresInvertColors fadeDuration={0} />
    </View>
  );
}

const s = StyleSheet.create({
  그림: { width: '100%', height: '100%' },
});
