'use strict';
/**
 * 게임큐 실배선 — 앱 전역 **하나뿐인** 게임 로그 통로(판정은 `lib/게임큐.js`).
 *
 * ■ 쓰는 쪽 계약
 *   · 게임 로그를 읽고 쓰는 화면은 **이 모듈만** 부른다 — `저장.게임로그읽기/쓰기` 를 직접
 *     잡으면 직렬 통로 밖의 쓰기가 생기고, 그 쓰기가 파일을 덮어 남의 사건을 지운다(B3 —
 *     그 금지는 `tests/게임큐.test.js` 가 소스로 잰다). 예외는 `기기비우기`(저장 안 · 로그아웃)뿐.
 *   · 큐 밀기 자리는 둘이다 — 게임 화면(자기 사건 직후) · **말하기 화면의 마운트·복귀**(B2 —
 *     G1 이 안 나오는 날에도 밀린 게임 사건이 나가는 유일한 배출구 · 되듣기 큐와 같은 선례).
 *
 * ■ 모듈 싱글턴인 이유
 *   직렬 사슬은 프로세스에 하나여야 한다 — 화면마다 저마다의 사슬을 만들면 사슬끼리 다시
 *   경쟁한다. 이 파일의 인스턴스 하나가 그 전부다.
 */
import { 게임큐만들기 } from '../lib/게임큐.js';
import { 게임로그읽기, 게임로그쓰기 } from './저장.js';
import { 사건보내기 } from './사건통로.js';
/* 수거의 실 조립 — 죽은 앉음의 이탈은 화면 cleanup 과 **같은 조립기**를 지난다(계약 밖 이탈이
 * 큐에 서는 길을 조립기 하나가 막는다). 키는 담는 순간 판다 — 중복은 항목 id 가 접는다. */
import { 이탈사건 } from '../lib/게임제출.js';
import { 흐름id } from '../lib/제출로그.js';
import { 압축 } from '../lib/게임로그.js';
import { 몽골날짜 } from '../lib/몽골날짜.js';

/* 압축은 **읽기 안**에서 돈다(G2-9) — 읽기·담기·수거·밀기가 전부 이 함수를 직렬 사슬 «안에서»
 * 부르므로, 읽고 나서 사슬 밖에서 되쓰면 그 틈의 담기를 덮는다(직렬 통로가 막는 바로 그 사고).
 * 걷을 것이 없으면 `압축` 이 원본 참조를 그대로 내 쓰기 0회다 — 쓰는 날은 날이 넘어간 첫 열림뿐. */
const 압축읽기 = async () => {
  const r = await 게임로그읽기();
  const 줄인 = 압축(r.로그, 몽골날짜());
  if (줄인 === r.로그) return r;
  await 게임로그쓰기(줄인);
  return { ...r, 로그: 줄인 };
};

const 큐 = 게임큐만들기({ 읽기: 압축읽기, 쓰기: 게임로그쓰기, 보내기: 사건보내기 });

export const 게임큐읽기 = 큐.읽기;
/* 상시 압축 자리(말하기화면 마운트) — 실체는 직렬 사슬을 지나는 읽기 한 번이다(위 머리말). */
export const 압축돌리기 = () => 큐.읽기();
export const 게임사건담기 = 큐.담기;
export const 게임큐밀기 = 큐.밀기;
/* H2 「다음 마운트 발견」 — 오늘 배정의 서버 task_ref 를 모르면 걷지 않는다(오귀속보다 0건). */
export const 게임이탈수거 = (오늘task_ref) => 큐.수거(오늘task_ref, (죽은) =>
  이탈사건(죽은.task_meta, { correlation_id: 죽은.correlation_id, idempotency_key: 흐름id() }));
