'use strict';
/**
 * 교실 관찰 API — 강사 통로(`teach`)의 `observe/*` 세 경로를 앱에서 부르는 자리.
 * 정본 = appsscript `docs/관찰태그_자동화_설계.md` v1.1 §4 · 계약 c14 `observation.noted`.
 *
 * ■ 이 파일이 닫는 것 — 앱이 **원리상 못 보는 것**의 유일한 통로
 *   발음·태도·듣기·위축은 앱 데이터에 흔적이 없다. 교실에서 사람이 본 것이 엔진에 닿는 길은
 *   이 셋뿐이고, 그전까지 교실 관찰은 라이브 구글 폼 → `student_errors` 로만 갔다 —
 *   그 행들은 그 시점의 동의판·급수 스냅샷을 영원히 못 갖는다(설계 §4 ③ · 소급 불가).
 *
 * ■ 검수·골든·반피드백과 **같은 문**을 지난다 (`src/사건통로.js`)
 *   봉투 해석·계약판 헤더·401 재갱신·네트워크 구분이 여기도 똑같이 필요하다. 🔑 그래서 이
 *   파일에는 주소도 키도 없다.
 *
 * ■ 🔴 어휘 사본이 **0개**다
 *   영역 9종·오류태그 24종·상한·분모 규칙은 `lib/관찰초안.js` 가 정본이고 화면이 그것을
 *   **직접** 부른다(`강사화면` 이 `lib/검수확정.js` 를, `반피드백화면` 이 `lib/반피드백.js` 를
 *   직접 부르는 선례). 여기에 또 적으면 세 번째 사본이다.
 *
 * 🚫 재제안 금지
 *   · 초안을 화면이 «저장»하기 — 초안은 사건이 아니다(설계 §2). 확정 전에 이탈하면 아무것도
 *     안 남는 것이 규격이고, 관찰 원문은 강사가 재입력할 수 있는 것이라 그 소실은 감수한다.
 *   · `draft_modified` 를 앱이 계산해 보내기 — **서버가 정한다**(§2 ㉡). 앱이 불리언을 보내면
 *     `서버칸` 규약이 막으려던 자기신고가 이름만 바꿔 돌아온다.
 *   · 관찰 화면에 학생의 첨삭·퀴즈·급수를 그리기 — §2 ㉯ 기각의 화면 적용이다. 앱의 의심을
 *     먼저 보여주면 그 뒤 관찰은 앱 사전확률의 **확증 표본**이 되고, `teacher` 등급이 거짓이 된다.
 *   · 초안 실패를 오류로 그리기 — 빈 초안은 **정상 경로**다(§3 「못 뽑으면 비운 채 확정」).
 */
import { 부르기 } from './사건통로.js';
import { 흐름id } from '../lib/제출로그.js';

/**
 * `GET /v1/teach/observe/roster` — 관찰을 적을 학생 목록(내 담당 반 전원).
 *
 * 🔑 조회 1회 = **감사 1행**이다(`teach` 의 `teach.observe.roster`). 학생 이름을 여는 조회라
 *   직원 통로 규약상 한 벌이고, 되풀이 조회는 그 장부의 분모를 조용히 바꾼다 — 화면은 한 번만 읽는다.
 * ⚠ 빈 목록은 「내가 다 봤다」가 아니라 **담당 반이 아직 없다**는 뜻이다(서버가 403 대신 빈
 *   목록을 준다 — 「배정 전」과 「강사가 아님」은 다른 사실이라 코드로 안 접는다).
 */
export async function 로스터(토큰) {
  const 본문 = await 부르기('teach/observe/roster', 토큰);
  return (Array.isArray(본문.roster) ? 본문.roster : []).map((r) => ({
    학생id: String(r.learner_id),
    학번: r.student_code ?? '',
    이름: r.display_name ?? null,
    반열쇠: r.class_key ?? '',
    반이름: r.class_name ?? null,
    /* 🚫 화면이 안 그린다 — 앱 축 데이터다(§2 ㉯). 서버가 `level_snapshot` 을 박을 때 쓰는
     *   같은 값이라 목록에 실려 오지만, 여기서 그리면 관찰 «전»에 급수를 보여주는 것이 된다. */
  }));
}

/**
 * `POST /v1/teach/observe/draft` — 자유 한 줄 → 구조 초안.
 *
 * 🔴 이 왕복은 **DB 를 안 건드린다**(설계 §2 의 물리). 그래서 학생을 안 가리키고, 감사도 안 남고,
 *   여기서 이탈하면 아무 데도 안 남는다.
 * 🔑 초안이 비어 와도 **오류가 아니다** — `사유`(키없음·벤더:429·응답형식밖…)만 다르고 화면은
 *   그대로 확정으로 갈 수 있다. 「AI 가 막히면 교실 관찰도 막힌다」가 되면 이 통로는 벤더
 *   가동률만큼만 사는 통로가 된다.
 */
export async function 초안받기(토큰, 원문) {
  const 본문 = await 부르기('teach/observe/draft', 토큰, { note_text: String(원문 ?? '') });
  const d = (본문 && 본문.draft) || {};
  return {
    영역: d.area ?? null,
    태그: Array.isArray(d.tags) ? d.tags : [],
    확신도: typeof d.confidence === 'number' ? d.confidence : null,
    /* 되싣기의 재료 — 확정 요청이 이 값을 **그대로** 돌려보내야 서버가 `draft_modified` 를
     * 잰다(§2 ㉡). 화면이 사람이 고친 값으로 덮으면 그 수는 언제나 「안 고쳤다」가 된다. */
    판: d.draft_ver ?? null,
    사유: d.사유 ?? null,
  };
}

/**
 * `POST /v1/teach/observe/note` — 확정. **여기서만** 행이 남는다(§2 「확정만 적재」).
 *
 * @param {object} 확정
 * @param {string} 확정.학생id
 * @param {string} 확정.영역     계약 「관찰영역」 9종
 * @param {string[]} 확정.태그   오류태그 0~2 (안 실리는 영역이면 서버가 400)
 * @param {string} 확정.원문     강사가 적은 그 문장
 * @param {object|null} 확정.초안 `초안받기` 가 준 것 그대로. 없으면 「직접 썼다」이고
 *   `draft_modified` 는 **null**(분모 밖 — 「안 고쳤다」가 아니다).
 * @param {string} [확정.멱등키] 재전송용. 안 주면 새로 짓는다.
 *
 * 🔑 멱등키를 **앱이 만든다**(`functions/events` 와 같은 규약) — 관찰은 같은 학생에게 하루에도
 *   여러 번 정상으로 쌓이므로, 서버가 내용으로 키를 지으면 「같은 관찰을 두 번 본 날」이 하나로
 *   접힌다. 그래서 재전송 방어는 **같은 키를 다시 보내는 것**으로 선다 — 화면이 실패 뒤 다시
 *   누를 때 키를 새로 짓지 않도록, 키는 확정 시도 «전»에 한 번 지어 들고 있는다.
 */
export async function 관찰보내기(토큰, 확정) {
  const 요청 = {
    learner_id: String(확정.학생id ?? ''),
    area: 확정.영역 ?? null,
    tags: Array.isArray(확정.태그) ? 확정.태그 : [],
    note_text: String(확정.원문 ?? ''),
    idempotency_key: 확정.멱등키 || 흐름id(),
  };
  /* 초안을 **그대로** 되싣는다(§2 ㉡). 🚫 여기서 모양을 바꾸지 않는다 — 서버가 지문으로
   * 대조하므로 키 이름 하나만 달라도 대조가 「고쳤다」로 기운다. */
  if (확정.초안 && 확정.초안.판) {
    요청.draft = { area: 확정.초안.영역 ?? null, tags: 확정.초안.태그 ?? [], draft_ver: 확정.초안.판 };
  }

  const 본문 = await 부르기('teach/observe/note', 토큰, 요청);
  /* 🔴 `event_id` 는 **안 온다** — 서버가 일부러 벗긴다(`review` ③ 과 같은 축: 그 값은 서버 안의
   * 배선이라 브라우저로 안 나간다). 화면이 아는 것은 「실렸나」와 「무엇으로 실렸나」까지다. */
  return {
    실린때: 본문.occurred_at ?? null,
    영역: 본문.area ?? null,
    태그: Array.isArray(본문.tags) ? 본문.tags : [],
    /* 🔑 서버가 답한 것만 그린다 — 화면이 「고쳤다」를 스스로 판정하면 그게 자기신고다. */
    고쳤나: 본문.draft_modified === true ? true : (본문.draft_modified === false ? false : null),
    새로실림: 본문.새로실림 !== false,
    멱등키: 요청.idempotency_key,
  };
}

/** 확정 한 번에 쓸 멱등키 — 화면이 시도 «전»에 지어 들고 있는다(위 `관찰보내기` 머리말). */
export const 새멱등키 = () => 흐름id();
