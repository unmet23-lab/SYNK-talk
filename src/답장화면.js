/* 마스코트 — 이 화면이 «보는 화면»이라 캐릭터가 산다(생명감 설계 §5 배치 = 홈·답장 ·
   말하기(녹음) 화면은 08-12 판정으로 금지 — 배선 회귀 tests/마스코트배선.test.js).
   화면은 사건 이름만 넘기고 연출·문구는 전부 캐릭터 층(src/마스코트.js·lib/마스코트생명.js) 몫이다. */
import 마스코트 from './마스코트.js';

/** 누가 고쳤나 — `actor_kind` 그대로 말한다(계약이 이 칸을 준 이유다 · L0 §3-4). */
const 고친이 = { teacher: '선생님이 고쳐 줬어요', ai: 'AI 가 고쳐 줬어요' };

/** 버튼 문구 — 값은 계약 값목록(`학생응답값`)이고 문구는 이 화면 것이다. */
const 답문구 = { 채택: '알겠어요', 수정: '다시 말해 볼래요' };

/**
 * @param {object} props
 * @param {string} props.토큰
 * @param {object|null} props.교정 `GET /v1/corrections` 의 `data[0]`. 없으면 **화면 자체가 안 뜬다**
 *   (App.js 가 링크를 안 그린다 · C0 §4-3 ② 「빈 카드 금지」).
 * @param {{code: string}|null} props.막힘 같은 응답의 `blocked`. 있으면 **사건을 한 건도 안 보낸다**
 *   (아래 `흘려보내기` — C0 §7 왕복 5 와 같은 처방). 카드는 그대로 보여준다.
 * @param {string|null} [props.학생번호] 막힘 안내가 학생에게 주는 **다음 한 걸음**이다
 *   (「선생님께 보여 주시면 바로 열려요」) — 안 넘기면 `막힘카드` 가 그 칸을 안 그려
 *   같은 카드가 말하기 화면과 다르게 동작한다.
 * @param {() => void} props.돌아가기
 */
export default function 답장화면({ 토큰, 교정, 막힘, 학생번호 = null, 돌아가기 }) {
  const [로그, set로그] = useState([]);
  const [오류, set오류] = useState(null);
  const [도는중, set도는중] = useState(true);
  // 마스코트에 넘기는 최신 사건 1건 — 값은 이름뿐이고 연출은 캐릭터 층이 정한다(반응 지도 §2)
  const [캐릭터사건, set캐릭터사건] = useState(null);

  /* 🔑 **한 번 열린 것이 한 앉음**이다 — 사건마다 새로 지으면 「한 번에 다 봤다」와
     「나눠 봤다」가 같은 모양이 된다(`교정API.교정앉음` 머리말 · P0 §3-1 ④).
     `useRef` 로 두는 것은 리렌더에 값이 바뀌지 않게 하기 위해서다. */
  const 앉음 = useRef(교정앉음()).current;
  const id = 교정 && 교정.correction_id;

  /**
   * 아직 안 닿은 항목을 **만들어진 순서대로** 보내고, 결과를 그 항목에 적는다.
   * 🔑 열람과 응답이 같은 통로를 지난다 — 판정(계약 위반·`duplicate`)이 두 곳에 적히면
   *   갈라지고, 갈라진 쪽은 조용히 영원히 재시도한다(`src/사건통로.js`).
   *
   * 🔴 **막힌 학생의 것은 한 건도 안 나간다**(`보낼것` · C0 §7 왕복 5 와 **같은 처방**).
   *   보내면 서버가 `CONSENT_MISSING`(`retryable:false`)으로 접고 앱은 그것을 `send_final` 로
   *   적어 큐에서 영영 뺀다 — 동의가 다시 서는 날 나갈 수 있었던 답이 죽는다(append-only ·
   *   소급 0). **멈추는 것이지 기기에서 지우는 것이 아니다** — 항목은 그대로 남아 다음에 나간다.
   *   ⚠ 그 「다음」은 **이 화면을 다시 여는 날**이다. 교정 큐에는 말하기 화면의 `AppState` 복귀
   *     같은 상시 배출구가 없다(이 처방 이전에도 그랬다 — 새 천장이 아니라 원래 천장이다).
   *     답장 링크는 이미 읽은 교정에도 계속 서므로 닫히는 문은 아니지만, 보장도 아니다.
   * 🔑 전송 자리가 **여기 하나**라서 호출부(마운트·답하기)마다 막힘을 물을 필요가 없다.
   *   말하기 화면이 두 자리(마운트·`AppState` 복귀)를 각각 고쳐야 했던 것과 다른 점이다.
   */
  const 흘려보내기 = async (시작로그) => {
    let 다음 = 시작로그;
    for (const 항목 of 보낼것(시작로그, 막힘)) {
      const 결과 = await 교정사건보내기(토큰, 항목.사건);
      다음 = 전송기록(다음, 항목.id, 결과);
    }
    await 교정로그쓰기(다음).catch(() => {});
    set로그(다음);
    return 다음;
  };

  /* 화면에 카드가 **실제로 뜬 순간** 열람 사건 하나. 이미 만든 적이 있으면 `항목추가` 가
     접는다 — 그래서 여기서 「이미 봤나」를 따로 묻지 않는다(묻는 곳이 둘이면 한 곳이 잊는다). */
  useEffect(() => {
    let 살아있음 = true;
    (async () => {
      try {
        const { 로그: 저장된 } = await 교정로그읽기();
        const { 로그: 더한것, 새것 } = 항목추가(저장된, 열람사건({ correction_id: id, correlation_id: 앉음 }));
        await 교정로그쓰기(더한것).catch(() => {});
        if (!살아있음) return;
        set로그(더한것);
        /* 🔊 achieve — **무오류 답장을 처음 여는 순간** 한 번(유호 확정 2026-08-13 「웅 넣어 —
           빈도를 올려도 좋다, 학생이 케어받는 느낌을 받길 원해」 · 결과_성취감_설계 §6-1 승격).
           · 무오류에만 — **소리도 사실이다**: 「오늘 고칠 데가 없었다」가 참인 날만 울려야
             소리가 흔한 보상으로 인플레되지 않는다(오류 남은 날의 온기는 노력 줄 글이 진다).
           · 판정은 `lib/꼬리.js` 무오류인가 **하나**다 — 여기 다시 적으면 서버 꼬리와 갈라진다.
           · `새것`(이 기기에서 이 교정의 첫 열람)에만 — 화면을 오갈 때마다 울리면 벽지가 된다.
           · 게이트(`lib/소리게이트.js`)가 녹음 중이면 알아서 무음 — 여기서 더 묻지 않는다. */
        if (새것 && 무오류인가(교정)) {
          효과음('achieve');
          // 놀람→기쁨·큰 점프 — achieve 소리와 **같은 순간**(생명감 §2 · 판정은 위 무오류인가 하나)
          set캐릭터사건({ 이름: '무오류첫열람', 때: Date.now() });
        } else if (교정 && !무오류인가(교정) && (교정.error_tags || []).length) {
          // 오류 남은 답장 — 기쁨도 슬픔도 아니다: 카드 쪽으로 몸을 기울여 «같이 들여다본다»(§1-3)
          set캐릭터사건({ 이름: '오류남은답장', 때: Date.now() });
        }
        await 흘려보내기(더한것);
      } catch (e) {
        /* 🔴 읽기 실패를 빈 로그로 둔갑시키지 않는다 — 빈 로그로 이어 가면 이미 보낸 열람을
           「처음」으로 취급해 사건이 두 벌 나간다. 카드는 그대로 보여주고 기록만 멈춘다. */
        if (살아있음) set오류(String((e && e.message) || e));
      } finally {
        if (살아있음) set도는중(false);
      }
    })();
    return () => { 살아있음 = false; };
  }, [id]);

  const 답하기 = async (값) => {
    set도는중(true);
    // 「다시 말해 볼래요」를 고른 순간 = 재도전(반응 지도 §2) — 서버 왕복을 기다리지 않는다(3초 원칙)
    if (값 === '수정') set캐릭터사건({ 이름: '재도전', 때: Date.now() });
    try {
      const { 로그: 더한것 } = 항목추가(
        로그,
        응답사건({ correction_id: id, correlation_id: 앉음, 학생응답: 값 }),
      );
      await 교정로그쓰기(더한것).catch(() => {});
      set로그(더한것);
      await 흘려보내기(더한것);
    } catch (e) {
      set오류(String((e && e.message) || e));
    } finally {
      set도는중(false);
    }
  };

  const 답한값 = id ? 응답값(로그, id) : null;
  /* 🔴 「보냈다」고 말할 수 있는 것은 `event_id` 가 있을 때뿐이다(제출 완료 카드가 안 닿은
     목소리를 「도착」이라 부르던 자리와 같은 축). 여기서는 **영구 실패만** 글자로 세운다 —
     아직 밀린 것은 다음에 열 때 조용히 다시 나가므로 학생이 할 일이 없다. */
  const 못보낸답 = 로그.some(
    (e) => e.correction_id === id && e.event_type === 'correction.responded'
      && !e.event_id && e.send_final,
  );
  /* 무오류 표식(`오류없음`)은 «찾을 오류»가 아니다 — 이 화면의 코랄은 「학생이 찾아야 하는
     자리」의 신호인데, 성취의 날에 그 표식까지 코랄로 세우면 잘한 날이 경고의 옷을 입는다.
     그날의 말은 꼬리·소리가 진다(유호 확정 08-13 케어 방향). 판정값 자체는 그대로 온다 —
     거르는 것은 표시 한 줄뿐이다. */
  const 태그 = ((교정 && 교정.error_tags) || []).filter((t) => t !== 무오류표식);

  return (
    <View style={s.wrap}>
    <ScrollView style={s.흐름} contentContainerStyle={s.inner}>
      <Text style={s.머리}>답장</Text>

      {교정 ? (
        <View style={s.카드}>
          <Text style={s.고친이}>{고친이[교정.actor_kind] || '고쳐 줬어요'}</Text>

          {교정.corrected_text ? (
            <Text style={s.문장} selectable>{교정.corrected_text}</Text>
          ) : null}

          {/* 신호 1점 — 이 화면의 코랄은 여기뿐이다. 태그는 한글이라 모노를 쓰지 않는다
              (DM Mono 에 한글 글리프가 없다 · `테마.js`). */}
          {태그.length ? (
            <View style={s.태그줄}>
              {태그.map((t) => <Text key={t} style={s.태그}>{t}</Text>)}
            </View>
          ) : null}

          {/* 몽골어 해설 — 온 것만 그린다. 「왜 그것인가」 한 줄이라 고친 문장 **아래**다
              (발주_게임모듈 §138 의 배치). */}
          {교정.explanation ? (
            <Text style={s.해설} selectable>{교정.explanation}</Text>
          ) : null}

          {/* 🔴 꼬리 한 줄 — **서버가 지은 글을 그대로 그린다**(유호님 확정 2026-08-12).
              앱은 한 글자도 짓지 않는다: 지으려면 기기에 오류 이력을 쌓아야 하는데 이 앱은
              그걸 안 하고, 기기를 바꾸면 사라진다(판정 정본 = `lib/꼬리.js` · 서버가 부른다).
              🔑 `lang` 으로 **글꼴만** 고른다 — 몽골어면 킷 폰트에 키릴 자형이 없어 두부가 뜬다
                 (해설 칸이 이미 판 자리와 같은 근거). 검수 전이라 지금은 늘 `ko` 다.
              🔴 없으면 안 그린다 — 빈 자리를 남기면 「꼬리가 없다」와 「꼬리가 빈 값이다」가
                 같은 모양이 된다(해설 칸과 같은 규칙). */}
          {교정.growth_note && 교정.growth_note.text ? (
            <Text
              style={[s.꼬리, 교정.growth_note.lang === 'mn' ? s.꼬리_몽골어 : null]}
              selectable
            >
              {교정.growth_note.text}
            </Text>
          ) : null}

          <Text style={s.메모}>내일 따라 말하기는 이 문장이에요.</Text>
        </View>
      ) : null}

      {/* 🔴 막힘이 **버튼보다 앞선다** — 누를 수 있게 두면 답이 로그에만 남고 화면은
          「답했어요」라고 말한다. 그건 서버 도착을 함의하는 문구라 그 순간 거짓이 되고,
          위 `흘려보내기` 가 큐를 멈춘 뒤로는 `send_final` 도 안 붙어 **경고조차 안 뜬다**
          (F176 이 끝낸 「이유 없이 아무 일도 안 일어남」의 재발이다). 교정 카드 자체는
          위에 그대로 남는다 — 읽는 것을 막을 이유는 없다. */}
      {막힘 ? (
        <막힘카드 막힘={막힘} 학생번호={학생번호} />
      ) : 답한값 ? (
        <Text style={s.답한줄}>{답문구[답한값] || 답한값} — 답했어요</Text>
      ) : (
        <View style={s.버튼줄}>
          {학생응답값
            .filter((값) => 답문구[값])
            .map((값) => (
              <Pressable
                key={값}
                /* 손잡이는 **코드값**에서 짓는다 — `답문구[값]` 은 카피라 바뀌지만 `값` 은 계약이다. */
                testID={`답장-${값}`}
                disabled={도는중 || !id}
                onPress={() => 답하기(값)}
                style={({ pressed }) => [
                  s.버튼,
                  값 === '수정' && s.버튼_보조,
                  (도는중 || !id) && s.버튼_잠김,
                  pressed && s.버튼_눌림,
                ]}
              >
                <Text style={[s.버튼글, 값 === '수정' && s.버튼글_보조]}>{답문구[값]}</Text>
              </Pressable>
            ))}
        </View>
      )}

      {못보낸답 ? <Text style={s.알림}>답이 저장되지 않았어요. 선생님께 알려 주세요.</Text> : null}
      {오류 ? <Text style={s.알림}>{오류}</Text> : null}

      <Pressable onPress={돌아가기} style={({ pressed }) => [s.back, pressed && { opacity: 0.7 }]}>
        <Text style={s.backText}>← 말하기로 돌아가기</Text>
      </Pressable>
    </ScrollView>
      {/* 스크롤 밖(겉테 층) — 캐릭터는 화면에 «사는» 존재라 내용과 같이 흘러가지 않는다.
          🚫 코랄 0 · 면 0 — 이 화면의 신호 1점은 오류 태그 그대로다(`테마.신호자리`). */}
      <마스코트 사건={캐릭터사건} />
    </View>
  );
}

