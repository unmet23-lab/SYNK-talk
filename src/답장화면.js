'use strict';
/**
 * 「답장」 — 학생이 **받은 교정을 보고 답하는** 화면 (P0 §5 **S1-8** · C0 §4-3 ②).
 *
 * ■ 이 화면이 닫는 것 — 결과축 생산자가 런타임에 0이었다
 *   `src/교정API.js` 는 이름(c8)·물리·검증기·서버 INSERT·조회 통로까지 다 서 있는데
 *   **그 파일을 부르는 화면이 없었다.** 그래서 `correction.viewed`·`correction.responded` —
 *   P0 가 「**학습이 일어났다」의 유일한 직접 신호**로 지목한 두 사건 — 은 회귀와 왕복시험의
 *   합성 사건으로만 초록이었고 실제 행은 0이었다. 새는 방향은 언제나 「통과」다.
 *   🔴 손실 시계는 **학생이 교정을 처음 보는 날** 시작되고 그날 이후는 소급이 없다 —
 *   「봤는지」는 그때만 알 수 있는 값이다.
 *
 * ■ 🔑 목록이 아니라 **최신 1건**이다 (C0 §4-3 ② 「S1 사용」)
 *   계약이 그렇게 정했다. 지난 것을 스크롤하는 화면은 「어제 것을 오늘 봤다」와 「오늘 것을
 *   오늘 봤다」를 한 앉음에 섞고, 그 둘은 끈기 축에서 다른 신호다. 페이지 커서(`since`)는
 *   서버에 이미 있으니 회고 화면이 정해지는 날 그때 붙인다.
 *
 * ■ 🚫 「무시」 버튼을 두지 않는다 — 버튼은 둘이다 (발주_게임모듈 §153·§191)
 *   `무시` 는 앱이 보내지 않는다: 안 누른 것은 이미 **`viewed` 는 있고 `responded` 가 없는
 *   모양**으로 남아 그 자체가 관측이다. 버튼을 세 개로 늘리면 「접었다」와 「안 열었다」가
 *   한 값으로 섞인다(`src/교정API.js` 가 값목록을 지키며 화면에 넘긴 판정이 이 자리다).
 *
 * ■ 몽골어 해설 (`explanation` · 유호님 승인 2026-08-09 로 응답에 실렸다)
 *   발주_수집파이프라인 §87 이 「교정문은 한국어 1문장, **해설은 몽골어**」로, 발주_게임모듈
 *   §780 이 「화면에 그대로 나간다」로 정해 둔 칸이다. c6 부터 물리에 있었는데 응답 목록에만
 *   없어서 앱에 닿는 길이 0이었다 — 지금은 온다(C0 §4-3 ②).
 *   🔴 **없으면 그 자리를 안 그린다** — 쓰는 쪽 생산자가 아직 0이라(AI 파이프라인 미착수 ·
 *   검수 콘솔 편집분) 실데이터에서는 당분간 늘 `null` 이다. 빈 칸을 남기면 「해설이 안 왔다」와
 *   「해설이 빈 값이다」가 같은 모양이 된다.
 *   🔴 **키릴 자형이 킷 폰트에 없다** — 그래서 이 한 줄만 `테마.몽골어`(시스템 폰트)를 쓴다.
 *   SUIT 을 지정하면 두부(□□□)가 뜨고, 그 화면은 「글자가 안 온 것」과 구별이 안 된다.
 *
 * ■ 꼬리 한 줄 (`growth_note` · 유호님 확정 2026-08-12 「서버에서 짓자」)
 *   철학 Ⅱ-8 「알아낸 것은 학생에게 돌려준다」의 둘째 실물이다 — 같은 조항이 **새 화면을 늘려서
 *   풀지 말라**고 못박아, 이미 매일 보는 이 카드에 한 줄로 얹는다(새 화면·새 사건·새 저장 **0**).
 *   🔴 **앱은 한 글자도 짓지 않는다.** 판정도 문구도 서버(`lib/꼬리.js`)가 낸 것을 그대로 그린다 —
 *   앱이 지으려면 기기에 `error_tags` 이력을 쌓아야 하는데 이 앱은 그걸 안 하고(조회는 사건을
 *   만들지 않는다) 기기를 바꾸면 통째로 사라진다. 여기서 하는 판단은 **글꼴 하나**뿐이다.
 *   🔴 없으면 안 그린다 — 해설 칸과 같은 규칙이고, 실데이터에서는 당분간 자주 `null` 이다
 *   (성공을 «주장하는» 줄은 무오류일 때만 · 오류가 남은 날은 되말하기 노력 사실 줄 하나뿐
 *    — 유호 지시 08-13 · 판정 정본 `lib/꼬리.js`).
 *
 * ■ 디자인 (`테마.js` R1 · `신호자리`)
 *   신호 1점 = **오류 태그**(코랄 글자). 이 화면엔 녹음 버튼이 없어서 성립한다 —
 *   인증 화면이 오류 메시지로 같은 자리를 쓰는 것과 같은 근거다.
 *   🚫 코랄 **면**을 만들지 않는다(그 위에 얹을 수 있는 글자색이 킷에 없다).
 */
import { useEffect, useRef, useState } from 'react';
import { Pressable, ScrollView, StyleSheet, Text, View } from 'react-native';
import { 색, 폰트, 모노트래킹, 몽골어 } from './테마';
