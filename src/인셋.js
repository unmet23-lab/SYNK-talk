const { Platform, StatusBar } = require('react-native');

const 기준선 = 24; // 설계 y값들이 전제한 상태바 높이(dp)

const 상태바 =
  Platform.OS === 'android' && typeof StatusBar.currentHeight === 'number'
    ? StatusBar.currentHeight
    : 기준선;

const 상단밀림 = Math.max(0, 상태바 - 기준선);

module.exports = { 상단밀림 };
