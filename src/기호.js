'use strict';
/**
 * 기호 `<` — SYNK 브랜드 표식의 앱 판 (유호 확정 2026-08-24 «로고 승격» · appsscript 결정.md)
 *
 * ■ 왜 워드마크가 아니라 기호인가
 *   로고가 두 층으로 갈렸다: **이름 `synk`** 는 브랜드를 «보여주는» 순간(스플래시·스토어·간판),
 *   **기호 `<`** 는 이미 «안에 들어와 있는» 자리(상단바·진행 눈금·로딩·불릿).
 *   앱 안에서 이름을 매 화면 반복하면 촌스러워진다 — 여기서는 기호가 브랜드를 진다.
 *
 * ■ 🔴 색 — 이 앱에서 기호는 **코랄이 아니다**
 *   테마 R1 「신호 1점」이 화면마다 못박혀 있다(`신호자리` — 말하기=녹음버튼 …).
 *   기호를 코랄로 칠하면 그 화면의 신호가 둘이 되어 규율이 깨진다.
 *   ⇒ 기본 = `색.잉크`(Paper) + 투명도 0.62 — 즉 «잉크_메타와 같은 밝기»의 표식 층이되
 *     알파를 색이 아니라 컨테이너가 진다(아래 🔴 겹침 반점).
 *     진행 눈금의 «지난 칸»처럼 상태를 말해야 하는 자리는 호출부가 역할색(정답·성장 등)을 준다.
 *   코랄은 오직 그 화면의 신호자리에만 남는다. 이 규율을 어기려면 테마 정본을 먼저 고쳐야 한다.
 *
 * ■ 형태 — appsscript `tools/lib/로고정본.js` 의 자수판을 RN 으로 옮긴 것
 *   꼭짓점 (118, 66.35) · 팔 끝 (150, 48)/(150, 84.7) ⇒ 벌림 60°(v2 불변 · 유호 08-18).
 *   각 팔은 중심선에서 ±29.8° 이고, 획은 둥근 끝(자수판 = 둥근 몸 13 · 60°).
 *   ⚠ react-native-svg 를 **안 쓴다** — 이 앱에 그 의존성이 없고, 기호 하나 때문에 네이티브
 *     모듈을 들이면 빌드·EAS 표면이 넓어진다. 둥근 막대 둘을 회전해 붙이면 같은 그림이 나온다.
 *   ⚠ 실땀(자수 점선)은 **여기 없다** — 정본 규율이 「28px 이상에서만 실땀」이고 앱의 기호 자리는
 *     20~24px 이라 그 문턱 아래다(그 크기의 점선은 노이즈다 · 08-24 실측). 큰 판이 필요해지면
 *     그때 자산(WebP)으로 굽는다 — 마스코트와 같은 길.
 */
import { StyleSheet, View } from 'react-native';
import { 색 } from './테마.js';

/* 정본 좌표에서 유도한 값 — 눈대중 아님.
 *   팔 길이 = |(150,48) - (118,66.35)| = √(32² + 18.35²) = 36.89 (정본 단위)
 *   기울기  = atan2(18.35, 32) = 29.85°
 *   획 굵기 = 13 (정본 자수판)
 * 화면 px 로 옮길 때는 `크기`(= 기호의 전체 높이 36.7 단위)를 기준으로 비례한다. */
const 단위높이 = 36.7;      // (84.7 - 48) — 기호의 세로 폭
const 팔길이비 = 36.89 / 단위높이;
const 굵기비 = 13 / 단위높이;
const 기울기 = 29.85;

/**
 * @param {number} 크기      기호 높이(px). 기본 22 — 상단바 자리.
 * @param {string} 색값      **불투명 색만 준다**(아래 🔴). 기본 = 잉크(Paper).
 * @param {number} 투명도    옅게 쓰려면 이 값으로 — 색의 알파가 아니라 «컨테이너»가 진다.
 *
 * 🔴 **색값에 rgba 를 주지 마라.** 두 팔이 꼭짓점에서 겹치므로, 반투명 색이면 그 자리만
 *   알파가 겹쳐 밝은 반점이 생긴다(08-24 실측 — 56px 판에서 눈에 띄었다).
 *   그래서 «색은 불투명, 옅기는 컨테이너 opacity»로 가른다. 기본값도 그 규율을 따라
 *   `잉크_메타`(rgba) 가 아니라 `잉크`(#FBF7F0) + 투명도 0.62 로 둔다 — 결과 색은 같다.
 */
export default function 기호({ 크기 = 22, 색값 = 색.잉크, 투명도 = 0.62, 스타일 }) {
  const 팔 = 크기 * 팔길이비;
  const 굵기 = Math.max(1.5, 크기 * 굵기비);
  const 반경 = 굵기 / 2;
  /* 두 팔이 꼭짓점에서 만난다 — 컨테이너 왼쪽 가운데가 그 꼭짓점이다.
     각 팔은 왼쪽 끝을 축으로 ∓기울기 만큼 돌아 위·아래로 뻗는다. */
  const 팔공통 = {
    position: 'absolute', left: 0, height: 굵기, width: 팔,
    borderRadius: 반경, backgroundColor: 색값,
  };
  const 폭 = 팔 * Math.cos((기울기 * Math.PI) / 180) + 굵기 * 0.5;
  return (
    <View
      style={[{ width: 폭, height: 크기 + 굵기 * 0.5, opacity: 투명도 }, 스타일]}
      accessibilityRole="image"
      accessibilityLabel="SYNK"
    >
      <View style={[팔공통, {
        top: (크기 + 굵기 * 0.5) / 2 - 굵기 / 2,
        transform: [{ translateX: 0 }, { rotate: `-${기울기}deg` }],
        transformOrigin: 'left center',
      }]} />
      <View style={[팔공통, {
        top: (크기 + 굵기 * 0.5) / 2 - 굵기 / 2,
        transform: [{ translateX: 0 }, { rotate: `${기울기}deg` }],
        transformOrigin: 'left center',
      }]} />
    </View>
  );
}

/**
 * 진행 눈금 — 기호 여러 개가 단계가 된다(정본 「기호가 눈금이 된다」).
 * 지난 칸은 `성장`(Meadow Soft — 역할색이라 코랄 자리를 안 뺏는다), 남은 칸은 옅은 잉크.
 */
export function 진행눈금({ 전체, 지난, 크기 = 13, 스타일 }) {
  return (
    <View style={[눈금꼴.줄, 스타일]} accessibilityRole="progressbar"
      accessibilityValue={{ min: 0, max: 전체, now: 지난 }}>
      {Array.from({ length: 전체 }, (_, i) => (
        <기호 key={i} 크기={크기}
          색값={i < 지난 ? 색.성장 : 색.잉크_보조}
          투명도={i < 지난 ? 1 : 0.32} />
      ))}
    </View>
  );
}

const 눈금꼴 = StyleSheet.create({
  줄: { flexDirection: 'row', alignItems: 'center', gap: 5 },
});
