'use strict';
/**
 * 몽글 API — **강사가 몽글에게 묻는 문**을 앱에서 부르는 자리. (Vellum 1단계의 마지막 조각)
 *
 * ■ 이 파일이 닫는 것 — 서버가 여는 문 열하나 중 **이 하나만 부르는 데가 없었다**
 *   2026-08-25 실측: `companion/ask` 를 부르는 앱 코드가 저장소 전수 **0줄**. 나머지 열(compass·
 *   feedback·gold·retro)은 전부 호출처가 있었다. 서버·지식(12문서 17만자)·로그·실답 증명이
 *   다 서 있는데 **문고리가 없어서 아무도 못 쓰는** 상태였다.
 *   🔑 이건 이 저장소에서 **두 번째**다 — `src/강사API.js` 머리말이 같은 문장으로 시작한다
 *     (「서버는 다 섰는데 입구가 0줄이었다」). 서버 트랙이 끝나면 «끝났다»고 느껴져 앱 몫이
 *     트랙에서 사라지는 것이 이 병의 뿌리다. 세는 법은 위 실측 그대로다 —
 *     **경로표의 문 전수 ↔ `src/` 호출처 수**를 견준다.
 *
 * ■ 같은 문을 지난다 (`src/사건통로.js`)
 *   봉투 해석·계약판 헤더·401 재갱신·네트워크 구분이 여기도 똑같이 필요하다.
 *   🔑 **이 파일에는 주소도 키도 없다.**
 *
 * ■ 🚫 재제안 금지
 *   · 답을 앱에 캐시하기 — 같은 질문의 답이 문서 갱신 뒤에도 옛것으로 남는다. 이 문의 값어치가
 *     「지금 정본이 뭐라고 하나」인데 캐시가 그걸 정확히 깬다.
 *   · 인계(`handoff`)를 오류로 던지기 — 인계는 **설계된 정상 결과**다(`lib/몽글물음.js` 급소).
 *   · 질문을 잘라 보내기 — 서버가 거절로 답하도록 두고, 앱은 보내기 «전에» 막는다.
 */
import { 부르기 } from './사건통로.js';
import { 보낼것, 답읽기 } from '../lib/몽글물음.js';

/**
 * `POST /v1/companion/ask` — 강사 질문 1건.
 *
 * 🔑 **되풀이 호출을 하지 않는다** — 질문 하나에 `companion_qa` 1행 + 감사 1행이 남고,
 *   그 장부가 곧 «문서에 없는 것» 목록의 분모다. 화면이 재시도를 자동으로 걸면 분모가
 *   조용히 부푼다(서버가 로그 실패를 응답 실패로 접는 이유와 같은 축).
 *
 * @param {string} 토큰   강사·원장 토큰(서버가 role 로 가른다 — 학생 토큰이면 403)
 * @param {{질문: string, 화면?: string}} 물음
 * @returns {Promise<{갈래: '답함'|'넘김'|'못받음', 글: string, 출처: string[],
 *   사유: string, 근거없음: boolean, qa_id: string}>}
 */
export async function 물어보기(토큰, 물음) {
  const 본문 = await 부르기('companion/ask', 토큰, 보낼것(물음));
  return 답읽기(본문);
}
